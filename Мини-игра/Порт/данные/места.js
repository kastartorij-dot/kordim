// Реестр мест, куда можно зайти из города. Движок не знает имён: карта города и
// «войти» читают только этот файл. «модуль» — данные места (данные/места/*.js).
import { СИНИЙ_ЧАС } from './места/синий-час.js';

export const МЕСТА = [
  {
    id: 'синий-час',
    имя: 'Синий час',
    район: 'торговый',
    когда: ['вечер'],
    подпись: 'вход 20 гр.',
    модуль: СИНИЙ_ЧАС,
  },
];

export function место(id) {
  return МЕСТА.find(м => м.id === id) ?? null;
}

// Темы, что известны с начала игры всем (у места они помечены «всегда»).
export function всегдаТемы() {
  const т = [];
  for (const м of МЕСТА)
    for (const [id, тема] of Object.entries(м.модуль.ТЕМЫ))
      if (тема.всегда && !т.includes(id)) т.push(id);
  return т;
}
