// Ходит строго через доступныеДействия. Три стратегии × три начала × три зерна, по 30 дней.
import { новоеСостояние } from '../движок/состояние.js';
import { доступныеДействия } from '../движок/действия.js';
import { НАЧАЛА } from '../данные/герой.js';

const ЗЕРНА = [11, 222, 3333];
const ДНИ = 30;
const ОТМЕТКИ = [7, 14, 30];

const годные = (A, вид) => A.filter(а => а.вид === вид && а.можно);
const дешёвый = арр => [...арр].sort((а, б) => а.цена - б.цена)[0];
const по = (A, id) => A.find(а => а.id === id && а.можно);
const ждать = A => A.find(а => а.id === 'отрезок:здесь');

function ест(S, A) {
  if (S.герой.тело.сыт > 1) return null;
  return дешёвый(годные(A, 'еда')) ?? null;
}

const СТРАТЕГИИ = {
  работяга(S, A) {
    const { отрезок, район } = S.мир;
    const е = ест(S, A);
    if (е) return е;
    if (отрезок === 'ночь') {
      const сны = годные(A, 'сон');
      return дешёвый(сны.filter(с => с.отдых >= 2)) ?? дешёвый(сны);
    }
    if (отрезок === 'утро') { const р = по(A, 'работа:разгрузка'); if (р) return р; }
    if (отрезок === 'день') { const р = по(A, 'работа:разноска'); if (р) return р; }
    if (район !== 'доки') return по(A, 'переход:доки');
    return ждать(A);
  },
  дёшево(S, A) {
    if (S.герой.тело.сыт <= 1) { const х = по(A, 'еда:хлеб'); if (х) return х; }
    if (S.мир.отрезок === 'ночь') return по(A, 'сон:небо');
    return ждать(A);
  },
  ничего(S, A) {
    if (S.мир.отрезок === 'ночь') return по(A, 'сон:небо');
    return ждать(A);
  },
};

function прогон(имя, началоId, сид) {
  const S = новоеСостояние(началоId, сид);
  const р = { имя, началоId, сид, ошибки: [], доход: 0, еда: 0, сон: 0, кражи: 0, кошель: {}, сыт5: null, цел: 3 };
  let шаги = 0;
  try {
    while (S.мир.день <= ДНИ && шаги++ < 10000) {
      if (S.мир.день === 5 && S.мир.отрезок === 'утро' && р.сыт5 === null) р.сыт5 = S.герой.тело.сыт;
      const A = доступныеДействия(S);
      const а = СТРАТЕГИИ[имя](S, A);
      if (!а) throw new Error(`стратегия не выбрала действие: день ${S.мир.день} ${S.мир.отрезок}`);
      const до = S.герой.кошель;
      а.выполнить(S);
      const после = S.герой.кошель;
      if (а.вид === 'работа') р.доход += после - до;
      else if (а.вид === 'еда') р.еда += до - после;
      else if (а.вид === 'сон') { р.сон += а.цена; р.кражи += до - а.цена - после; }
      for (const [к, v] of Object.entries(S.герой.тело))
        if (!Number.isInteger(v) || v < 0 || v > 3) р.ошибки.push(`${к}=${v} на дне ${S.мир.день}`);
      if (S.герой.кошель < 0) р.ошибки.push(`кошель ${S.герой.кошель} на дне ${S.мир.день}`);
      if (S.мир.конецДня) {
        const д = S.мир.конецДня.день;
        if (ОТМЕТКИ.includes(д)) р.кошель[д] = S.герой.кошель;
        S.мир.конецДня = null; // «Начать день» на экране
      }
    }
  } catch (e) {
    р.ошибки.push(`упало: ${e.message}`);
  }
  if (S.мир.день !== ДНИ + 1) р.ошибки.push(`день в конце ${S.мир.день}, ожидалось ${ДНИ + 1}`);
  р.цел = S.герой.тело.цел;
  р.жив = S.герой.тело.цел >= 1;
  р.итог = S.герой.кошель;
  if (имя === 'работяга') {
    if (!р.жив) р.ошибки.push('работяга: цел 0 к 30 дню');
    if (р.итог >= 400) р.ошибки.push(`работяга: накопил ${р.итог} гр.`);
  }
  if (имя === 'ничего') {
    if (р.сыт5 !== 0) р.ошибки.push(`ничего: к 5 дню сыт ${р.сыт5}, ожидался 0`);
    if (р.цел >= 3) р.ошибки.push('ничего: цел не упал');
  }
  return р;
}

const все = [];
for (const имя of Object.keys(СТРАТЕГИИ))
  for (const н of НАЧАЛА)
    for (const сид of ЗЕРНА) все.push(прогон(имя, н.id, сид));

const ср = (арр, ф) => арр.reduce((с, x) => с + ф(x), 0) / арр.length;
const ф1 = n => n.toFixed(1);
console.log('| стратегия | начало | доход/день | еда/день | сон/день | кражи/день | кошель 7 | 14 | 30 | цел в конце |');
console.log('|---|---|---|---|---|---|---|---|---|---|');
for (const имя of Object.keys(СТРАТЕГИИ))
  for (const н of НАЧАЛА) {
    const g = все.filter(р => р.имя === имя && р.началоId === н.id);
    console.log(`| ${имя} | ${н.id} | ${ф1(ср(g, р => р.доход / ДНИ))} | ${ф1(ср(g, р => р.еда / ДНИ))} | ${ф1(ср(g, р => р.сон / ДНИ))} | ${ф1(ср(g, р => р.кражи / ДНИ))} | ${ОТМЕТКИ.map(д => ф1(ср(g, р => р.кошель[д] ?? 0))).join(' | ')} | ${ф1(ср(g, р => р.цел))} |`);
  }

const плохие = все.filter(р => р.ошибки.length);
if (плохие.length) {
  console.log('\nПРОВАЛЫ:');
  for (const р of плохие) console.log(`- ${р.имя}/${р.началоId}/${р.сид}: ${р.ошибки.slice(0, 3).join('; ')}`);
  process.exit(1);
}
console.log('\nВсе проверки пройдены.');
