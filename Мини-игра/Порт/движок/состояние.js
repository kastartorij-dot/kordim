// Состояние: три части (ГДД §21). В стадии «каркас» сцена и большая часть
// мира ещё не нужны — но схема сразу закладывается целиком, чтобы потом не
// резать S на части задним числом (Город_КОНЦЕПТ.md, «подводные камни», п.3).
import { новыйГерой, СТАРТ_РАЙОН, НАЧАЛА } from '../данные/герой.js';
import { всегдаТемы } from '../данные/места.js';
import { ОТРЕЗКИ } from './время.js';

export const ВЕРСИЯ = 5;
const КЛЮЧ = 'порт-теней';

// Темы, известные с начала игры: то, что все знают, плюс своё у каждого начала.
function началоТемы(началоId) {
  const н = НАЧАЛА.find(x => x.id === началоId) ?? НАЧАЛА[0];
  return [...всегдаТемы(), ...(н.темы ?? [])];
}

// сид — зерно случайности (движок/случай.js); в браузере берём от часов, бот задаёт своё.
export function новоеСостояние(началоId, сид = Date.now() >>> 0) {
  const S = {
    версия: ВЕРСИЯ,
    герой: новыйГерой(началоId),
    мир: {
      день: 1,
      отрезок: ОТРЕЗКИ[0],
      район: СТАРТ_РАЙОН,
      погода: 'ясно',
      фракции: { ножи: 0, картель: 0, братство: 0 },
      репутация: 0,
      тень: 0,
      места: {}, // память мест: { 'синий-час': { дом, долг, флаги, осмотрено, визитов } }
      люди: {}, // { id: { распол, спрошено, исчерпано } }
      темы: началоТемы(началоId), // общие для города (ГДД §11)
      знания: {}, // { тид: { день, верность: слышал | подтверждено | опровергнуто, от? } } — рядом с темами
      ушло: {}, // { тид: 'картель' | 'ножи' | 'картель ножи' } — куда ушло то, что было сказано или продано
      дела: [],
      флаги: [],
      долги: [],
      обещания: [],
      конецДня: null, // итог только что прошедшего дня, пока его экран не закрыт
      журналДня: [], // строки о сделанном за день, обнуляется с новым днём
      сид,
      отключкаДень: 0, // день, когда уже был «отключился на ходу» (цел −1 не чаще раза в день)
    },
    сцена: null, // визит в место: комната, собеседник, подход, ветка, реплика, часы… — только внутри визита
    история: [], // откат только внутри сцены (ГДД §21)
  };
  // Всё, что игрок знает с начала, — подтверждено.
  for (const т of S.мир.темы) S.мир.знания[т] = { день: 1, верность: 'подтверждено' };
  return S;
}

function слот(n) {
  return `${КЛЮЧ}-слот-${n}`;
}

export function сохранить(S, слотN) {
  const ключ = слотN === 'авто' ? `${КЛЮЧ}-авто` : слот(слотN);
  localStorage.setItem(ключ, JSON.stringify(S));
}

export function загрузить(слотN) {
  const ключ = слотN === 'авто' ? `${КЛЮЧ}-авто` : слот(слотN);
  const сырое = localStorage.getItem(ключ);
  if (!сырое) return null;
  const S = JSON.parse(сырое);
  return мигрировать(S);
}

export function списокСохранений() {
  const слоты = [1, 2, 3, 'авто'];
  return слоты.map(n => {
    const ключ = n === 'авто' ? `${КЛЮЧ}-авто` : слот(n);
    const сырое = localStorage.getItem(ключ);
    if (!сырое) return { слот: n, пусто: true };
    const S = JSON.parse(сырое);
    return { слот: n, пусто: false, день: S.мир?.день, герой: S.герой?.имя };
  });
}

// Мягкая миграция при несовпадении версии (ГДД §21, правило 4).
export function мигрировать(S) {
  if (S.версия === ВЕРСИЯ) return S;
  if (S.версия === 1) {
    S.мир.журналДня ??= [];
    S.мир.сид ??= Date.now() >>> 0;
    S.мир.отключкаДень ??= 0;
    if (S.мир.конецДня) {
      S.мир.конецДня.журнал ??= [];
      S.мир.конецДня.причины ??= [];
      S.мир.конецДня.предупреждение ??= false;
    }
    S.герой.серии ??= {};
    S.герой.холод1 ??= 0;
    S.герой.жильё ??= null;
    S.версия = 2;
  }
  if (S.версия === 2) {
    S.мир.места ??= {};
    S.мир.люди ??= {};
    if (!S.мир.темы || !S.мир.темы.length) S.мир.темы = началоТемы(S.герой.начало);
    S.сцена = null;
    S.история ??= [];
    S.версия = 3;
  }
  if (S.версия === 3) {
    // Вечер в месте считается ходами, а не часами (решение автора 18.09): 12 часов → 6 ходов.
    if (S.сцена && S.сцена.часы !== undefined) {
      S.сцена.ходы = Math.ceil(S.сцена.часы / 2);
      delete S.сцена.часы;
    }
    S.история = []; // старые снимки — в часах, откатываться в них нельзя
    S.версия = 4;
  }
  if (S.версия === 4) {
    // Знание темы получило верность: всё, что игрок уже знает, — подтверждено, день 1.
    S.мир.знания ??= {};
    for (const т of S.мир.темы) S.мир.знания[т] ??= { день: 1, верность: 'подтверждено' };
    S.мир.ушло ??= {};
    S.история = []; // старые снимки без знаний
    S.версия = 5;
    return S;
  }
  console.warn(`Сохранение версии ${S.версия}, ожидалась ${ВЕРСИЯ} — миграции нет.`);
  return S;
}
