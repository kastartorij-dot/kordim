// Тело в конце дня. ГДД §5, задание этапа 2, шаг 5. Без DOM. Ничего о конкретных местах:
// всё, что зависит от ночлега, приходит в «сон» из данных/жильё.js.
import { ХОЛОДА_С } from '../данные/жильё.js';

export const МАКС = 3;
const НАЗВАНИЕ = { сыт: 'Сыт', отдых: 'Отдых', тепло: 'Тепло', цел: 'Цел' };
const зажать = v => Math.max(0, Math.min(МАКС, v));
const зн = n => (n > 0 ? '+' : '−') + Math.abs(n);

// Меняет S.герой.тело, дописывает в итог.причины по строке на причину.
export function применитьТело(S, сон, итог) {
  const г = S.герой, т = г.тело, п = итог.причины;
  const менять = (к, d, почему) => {
    const было = т[к];
    т[к] = зажать(т[к] + d);
    if (т[к] !== было) п.push(`${НАЗВАНИЕ[к]} ${зн(т[к] - было)}: ${почему}`);
  };

  менять('сыт', -1, 'прошёл день');
  if (сон) {
    менять('отдых', сон.отдых, сон.имя);
    if (сон.тепло) менять('тепло', сон.тепло, сон.имя);
  } else {
    менять('отдых', -1, 'ночь без сна');
  }
  if (S.мир.день >= ХОЛОДА_С && !(сон && сон.укрыт)) менять('тепло', -1, 'осенние холода');

  if (т.тепло === 0) {
    менять('цел', -1, 'совсем нет тепла');
    г.холод1 = 0;
  } else if (т.тепло === 1) {
    г.холод1 += 1;
    if (г.холод1 >= 2) {
      // ВОПРОС: после штрафа за два дня подряд счётчик сбрасывается в 0 (следующий штраф — ещё через два дня)?
      менять('цел', -1, 'два дня подряд мало тепла');
      г.холод1 = 0;
    }
  } else {
    г.холод1 = 0;
  }

  if (сон && сон.поправка && т.сыт >= 2 && т.тепло >= 2) менять('цел', 1, 'ночь в покое, сыт и в тепле');

  // Тень спадает на 1 за три спокойных дня — без новых ушей (ГДД §8).
  const м = S.мир;
  if (м.тень > 0 && м.день - (м.теньДень ?? 0) >= 3) {
    м.тень -= 1;
    м.теньДень = м.день;
    п.push('Тень −1: три спокойных дня');
  }

  итог.предупреждение = т.цел === 0;
}
