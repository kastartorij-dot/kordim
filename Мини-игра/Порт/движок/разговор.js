const зажать = (от, до, v) => Math.max(от, Math.min(до, v));
const Д = S => место(S.сцена.место).модуль;
const М = S => S.мир.места[S.сцена.место];

function человек(S, id) {
  return (S.мир.люди[id] ??= { спрошено: [], исчерпано: [] });
}
const расп = (S, id) => S.мир.люди[id]?.распол ?? 0;
function добавитьРаспол(S, id, d) {
  const л = человек(S, id);
  л.распол = зажать(-2, 4, (л.распол || 0) + d);
}

function датьТему(S, т) {
  if (т && !S.мир.темы.includes(т)) S.мир.темы.push(т);
}
function есть(S, ф) {
  return S.сцена.флагиВечера.includes(ф) || М(S).флаги.includes(ф);
}
function флаг(S, ф) {
  const список = Д(S).флагиВечера.includes(ф) ? S.сцена.флагиВечера : М(S).флаги;
  if (!список.includes(ф)) список.push(ф);
}

// ── условия ─────────────────────────────────────────────────────────────
// ctx — для итога вечера: { причина, тепло }.
export function выполнено(S, у, ctx = {}) {
  if (!у) return true;
  const м = М(S);
  if (у.флаг && !есть(S, у.флаг)) return false;
  if (у.нетФлага && есть(S, у.нетФлага)) return false;
  if (у.домОт !== undefined && м.дом < у.домОт) return false;
  if (у.домДо !== undefined && м.дом >= у.домДо) return false;
  if (у.распол && расп(S, у.распол.кто) < у.распол.от) return false;
  for (const п of [].concat(у.предмет ?? [])) if (!S.герой.при_себе.includes(п)) return false;
  for (const п of [].concat(у.безПредмета ?? [])) if (S.герой.при_себе.includes(п)) return false;
  if (у.деньгиОт !== undefined && S.герой.кошель < у.деньгиОт) return false;
  if (у.вошёл !== undefined && S.сцена.вошёл !== у.вошёл) return false;
  if (у.тема && !S.мир.темы.includes(у.тема)) return false;
  // тема узнана именно в этот визит — чтобы утечка про неё не повторялась каждый вечер
  if (у.новаяТема && (!S.мир.темы.includes(у.новаяТема) || (S.сцена.темыНаВходе ?? []).includes(у.новаяТема))) return false;
  if (у.причина && ctx.причина !== у.причина) return false;
  if (у.теплоОт !== undefined && (ctx.тепло ?? 0) < у.теплоОт) return false;
  if (у.долг && !м.долг) return false;
  if (у.безДолга && м.долг) return false;
  return true;
}

// ── эффекты ─────────────────────────────────────────────────────────────
function применить(S, э) {
  if (!э) return;
  const с = S.сцена, м = М(S), т = S.герой.тело;
  if (э.гроши) S.герой.кошель += э.гроши;
  if (э.долг) м.долг += э.долг;
  if (э.погаситьДолг) { S.герой.кошель -= м.долг; м.долг = 0; }
  if (э.дом) м.дом = зажать(-3, 3, м.дом + э.дом);
  if (э.распол) for (const к in э.распол) добавитьРаспол(S, к, э.распол[к]);
  if (э.тема) датьТему(S, э.тема);
  if (э.флаг) флаг(S, э.флаг);
  if (э.сыт) т.сыт = зажать(0, МАКС, т.сыт + э.сыт);
  if (э.отдых) т.отдых = зажать(0, МАКС, т.отдых + э.отдых);
  if (э.вошёл) с.вошёл = true;
  if (э.реплика !== undefined) с.реплика = э.реплика;
  if (э.комната) с.комната = э.комната;
  if (э.час) времяИдёт(S, э.час);
  if (э.финал) финал(S, э.финал);
}

export function времяИдёт(S, n) {
  const с = S.сцена;
  с.часы += n;
  if (с.часы >= Д(S).часов && !с.конец) финал(S, 'время');
}

// ── откат: снимок — весь S без истории; живёт только внутри визита ─────────
function снимок(S) {
  const копия = { ...S };
  delete копия.история;
  S.история.push(JSON.stringify(копия));
  if (S.история.length > Д(S).откат) S.история.shift();
}

// Меняет S на месте: объект S держит index.html.
export function назад(S) {
  if (!S.сцена || !S.история.length) return false;
  const ист = S.история;
  const пред = JSON.parse(ист.pop());
  for (const к of Object.keys(S)) delete S[к];
  Object.assign(S, пред);
  S.история = ист;
  return true;
}

// ── вход и выход ────────────────────────────────────────────────────────
// Можно ли войти прямо сейчас (для кнопки на карте города).
export function можноВойти(S, местоId) {
  const м = место(местоId);
  if (!м.когда.includes(S.мир.отрезок)) return { можно: false, почему: м.закрыто };
  return { можно: true, почему: null };
}

export function войти(S, местоId) {
  const д = место(местоId).модуль;
  let п = S.мир.места[местоId];
  if (!п) {
    п = S.мир.места[местоId] = { дом: 0, долг: 0, флаги: [], осмотрено: [], визитов: 0 };
    const зн = НАЧАЛА.find(н => н.id === S.герой.начало)?.знакомства?.[местоId];
    if (зн?.дом) п.дом = зажать(-3, 3, зн.дом);
  }
  п.визитов += 1;
  следующийОтрезок(S); // вечерний отрезок списан при входе, один раз
  S.история = [];
  S.сцена = {
    место: местоId,
    комната: д.старт,
    собеседник: null,
    подход: д.ЭКРАН.подходСтарт,
    ветка: null,
    реплика: '',
    мояреплика: '',
    часы: 0,
    вошёл: false,
    кошелёкНаВходе: S.герой.кошель,
    темыНаВходе: S.мир.темы.slice(),
    флагиВечера: [], // флаги вечера сброшены на входе
    конец: null,
    итог: null,
    нужнаСцена: null,
  };
  return S;
}

export function вернутьсяВГород(S) {
  S.сцена = null;
  S.история = [];
  return S;
}

function финал(S, причина) {
  const с = S.сцена;
  с.конец = причина;
  с.итог = посчитатьИтог(S, причина);
}

function посчитатьИтог(S, причина) {
  const д = Д(S), м = М(S), Ч = д.СЧЁТ;
  const с = д.ЛЮДИ;
  const ключи = Object.keys(S.мир.люди).filter(к => typeof S.мир.люди[к].распол === 'number');
  const лучший = ключи.sort((a, b) => S.мир.люди[b].распол - S.мир.люди[a].распол)[0];
  const тепло = лучший ? S.мир.люди[лучший].распол : 0;
  const ctx = { причина, тепло };
  const и = д.ИТОГИ.find(x => выполнено(S, x.если, ctx));

  const потрачено = S.сцена.кошелёкНаВходе - S.герой.кошель;
  const строки = [[Ч.потрачено, потрачено + Ч.грошей]];
  if (м.долг) строки.push([Ч.долг, м.долг + Ч.грошей]);
  строки.push([Ч.тем, String(S.мир.темы.filter(т => !д.ТЕМЫ[т]?.всегда).length)]);
  строки.push([Ч.осмотрено, String(м.осмотрено.length)]);
  строки.push([Ч.домЧитает, Ч.домИмена[String(м.дом)]]);
  if (лучший && тепло > 0) строки.push([Ч.запомнила, с[лучший].имя + ' (' + тепло + ')']);

  const утечки = д.УТЕЧКИ.filter(у => выполнено(S, у.если)).map(у => у.текст);
  return { причина, заг: и.заг, текст: и.текст, строки, утечки, потрачено };
}

// ── подход и вопросы ────────────────────────────────────────────────────
export function выбратьПодход(S, п) {
  S.сцена.подход = п;
}

function фраза(д, тид, подход) {
  const т = д.ФРАЗЫ[тид];
  return (т && т[подход]) || (т && т['прямо']) || д.ТЕМЫ[тид].ярлык;
}

// Ответ человека на тему в текущем подходе: { узел, р, текст, эффект } или null, если ответа нет.
function ответ(S, кто, тид) {
  const с = S.сцена, д = Д(S);
  const узел = (д.Р[кто] || {})[тид];
  const р = узел ? узел[с.подход] || узел['любой'] || null : null;
  if (!р) return null;
  const овер = р.поПерсонажу && р.поПерсонажу[S.герой.начало];
  const текст = (typeof овер === 'string' ? овер : овер && овер.т) || р.т;
  const эффект = (овер && typeof овер === 'object' && овер.э) || р.э;
  return { узел, р, текст, эффект };
}

function спросить(S, тид) {
  const с = S.сцена, д = Д(S), кто = с.собеседник;
  const л = человек(S, кто);
  const о = ответ(S, кто, тид);
  const ключТон = тид + ':' + с.подход;
  const повтор = л.спрошено.includes(ключТон);

  с.мояреплика = фраза(д, тид, с.подход);

  if (!о) {
    с.реплика = д.ОТГОВОРКИ[кто];
    if (!повтор) {
      л.спрошено.push(ключТон);
      времяИдёт(S, 1);
    }
    return;
  }
  const { р, узел } = о;

  // Об одном и том же одним и тем же тоном второй раз — тот же ответ, но вечер на это не
  // тратится и расположение не копится (это и держит дом от фарма визитами). Кроме веток
  // с продолжением: их читают заново, чтобы дойти до конца.
  // ВОПРОС: как в старой игре, повтор показывает общий текст р.т, а не персональный (поПерсонажу).
  if (повтор && !р.дальше) {
    с.реплика = р.т;
    return;
  }
  if (!повтор) л.спрошено.push(ключТон);

  с.реплика = о.текст;
  // Недочитанную ветку можно начать заново, но расположение и дом за неё даются один раз —
  // иначе ветку, брошенную на середине, фармят визитами.
  if (о.эффект && !повтор) применить(S, о.эффект);
  if (р.тема) датьТему(S, р.тема);

  // подход против натуры: нажим стоит расположения (старое: без ограничения снизу)
  const ч = д.ЛЮДИ[кто];
  if (!повтор && ч.обижает && с.подход === ч.обижает && с.подход !== ч.любит && !узел['любой']) {
    л.распол = (л.распол || 0) - 1;
  }
  времяИдёт(S, 1);

  if (р.дальше && р.дальше.length) {
    // ВОПРОС: старая игра брала узел ветки по тону в момент «Продолжить»; ветка теперь помнит тон, с которого началась.
    с.ветка = { кто, тид, шаг: 0, подход: с.подход };
  }
}

function продолжитьВетку(S) {
  const с = S.сцена, д = Д(S), в = с.ветка;
  const узел = д.Р[в.кто][в.тид][в.подход] || д.Р[в.кто][в.тид]['любой'];
  const шаг = узел.дальше[в.шаг];
  const л = человек(S, в.кто);
  л.шаги ??= {}; // сколько шагов ветки уже прочитано — их эффекты второй раз не даются
  if (шаг.э && в.шаг >= (л.шаги[в.тид] ?? 0)) применить(S, шаг.э);
  л.шаги[в.тид] = Math.max(л.шаги[в.тид] ?? 0, в.шаг + 1);
  if (шаг.тема) датьТему(S, шаг.тема);
  с.реплика = шаг.т;
  с.мояреплика = '';
  в.шаг++;
  if (в.шаг >= узел.дальше.length) {
    человек(S, в.кто).исчерпано.push(в.тид);
    с.ветка = null;
  }
}

function ходИнтим(S, б, кто) {
  const с = S.сцена;
  for (const ф of б.флаги) флаг(S, ф);
  применить(S, { распол: { [кто]: б.распол } });
  с.реплика = '';
  с.мояреплика = '';
  с.нужнаСцена = б.сцена; // текст лежит файлом, его подгружает догрузитьСцену
  S.герой.напряжение = 0; // ГДД §9
}

// Подгружает текст сцены близости. читать(id) → Promise<string|null>: в браузере это fetch,
// в тесте — чтение файла. Нет файла — «Дальше — без слов.», как в старой игре.
export async function догрузитьСцену(S, читать) {
  const с = S.сцена;
  const id = с?.нужнаСцена;
  if (!id) return false;
  let текст = null;
  try { текст = await читать(id); } catch { текст = null; }
  if (S.сцена !== с || с.нужнаСцена !== id) return false;
  с.реплика = текст ? текст.replace(/\r\n/g, '\n') : Д(S).ЭКРАН.подпись.дальшеБезСлов;
  с.нужнаСцена = null;
  return true;
}

// ── список действий текущего экрана ─────────────────────────────────────
function послеСцены(S, К, кто) {
  return !!(К.хозяйка === кто && К.близость && есть(S, К.близость.флаги[1]));
}

export function действияСцены(S) {
  const с = S.сцена, д = Д(S), сл = д.ЭКРАН.слова, м = М(S);
  if (с.итог) return [];
  const А = [];
  const добавить = (а, шаг) => {
    А.push({ можно: true, почему: null, подпись: '', ...а, выполнить(S2) { снимок(S2); шаг(S2); return null; } });
  };
  const деньги = цена => S.герой.кошель >= цена;
  const К = д.КОМНАТЫ[с.комната];

  // действие из данных: { вид, текст, подпись, стоит, условие, эффект }
  const изДанных = (а, i, префикс) => {
    if (!выполнено(S, а.условие)) return;
    const мало = a => (a.стоит && !деньги(a.стоит)) || (a.эффект?.погаситьДолг && !деньги(м.долг));
    добавить({ id: `${префикс}:${i}`, вид: а.вид, текст: а.текст, подпись: а.эффект?.погаситьДолг ? м.долг + сл.гр.split('·')[0].trimEnd() : а.подпись, можно: !мало(а), почему: мало(а) ? сл.нетДенег : null },
      S2 => {
        if (а.стоит) S2.герой.кошель -= а.стоит;
        применить(S2, а.эффект);
      });
  };

  if (!с.собеседник) {
    if (К.вход && !с.вошёл) {
      К.вход.действия.forEach((а, i) => изДанных(а, i, 'вход'));
      return А;
    }
    for (const id of К.люди) {
      добавить({ id: `заговорить:${id}`, вид: 'заговорить', текст: сл.заговорить + д.ЛЮДИ[id].имя, подпись: '' },
        S2 => { S2.сцена.собеседник = id; S2.сцена.реплика = ''; S2.сцена.мояреплика = ''; });
    }
    for (const дт of К.детали) {
      const было = м.осмотрено.includes(с.комната + ':' + дт.id);
      добавить({ id: `рассмотреть:${дт.id}`, вид: 'рассмотреть', текст: (было ? сл.было : '') + сл.рассмотреть + дт.имя, подпись: сл.даром },
        S2 => {
          // Повторный осмотр не дописывается: в старой игре «Осмотрено» росло от повторов,
          // а с памятью между визитами это копилось бы бесконечно.
          const ключ = S2.сцена.комната + ':' + дт.id;
          if (!М(S2).осмотрено.includes(ключ)) М(S2).осмотрено.push(ключ);
          S2.сцена.реплика = дт.текст;
          датьТему(S2, дт.тема);
        });
    }
    const П = д.платнаяКомната;
    for (const id of К.соседи) {
      const Н = д.КОМНАТЫ[id];
      if (Н.цена) {
        const мало = !деньги(Н.цена);
        добавить({ id: `подняться:${id}`, вид: 'подняться', цель: id, текст: сл.подняться + Н.имя,
          подпись: Н.цена + сл.гр + Н.часы + сл.ч, цена: Н.цена, можно: !мало, почему: мало ? сл.нетДенег : null },
        S2 => {
          S2.герой.кошель -= Н.цена;
          S2.сцена.комната = id; S2.сцена.реплика = ''; флаг(S2, П.флаг);
          времяИдёт(S2, Н.часы);
        });
        if (мало) {
          добавить({ id: `вдолг:${id}`, вид: 'вдолг', цель: id, текст: сл.вДолг + Н.имя, подпись: сл.вДолгЦена + Н.цена + сл.грКонец },
            S2 => {
              const м2 = М(S2);
              м2.долг += Н.цена;
              м2.дом = зажать(-3, 3, м2.дом + П.вДолг.дом);
              флаг(S2, П.вДолг.флаг);
              S2.сцена.комната = id; S2.сцена.реплика = ''; флаг(S2, П.флаг);
              времяИдёт(S2, Н.часы);
            });
        }
      } else {
        добавить({ id: `пойти:${id}`, вид: 'пойти', цель: id, текст: сл.пойти + Н.имя, подпись: '' },
          S2 => { S2.сцена.комната = id; S2.сцена.реплика = ''; });
      }
    }
    (К.действия || []).forEach((а, i) => изДанных(а, i, 'действие'));
    return А;
  }

  // ── разговор
  const кто = с.собеседник;
  const л = S.мир.люди[кто] || { спрошено: [], исчерпано: [] };
  const отойти = () => добавить({ id: 'отойти', вид: 'отойти', текст: сл.отойти },
    S2 => { S2.сцена.собеседник = null; S2.сцена.реплика = ''; S2.сцена.мояреплика = ''; });

  if (послеСцены(S, К, кто)) {
    добавить({ id: 'спуститься', вид: 'спуститься', текст: сл.спуститься },
      S2 => { S2.сцена.комната = К.близость.после; S2.сцена.собеседник = null; S2.сцена.реплика = ''; S2.сцена.мояреплика = ''; });
    return А;
  }
  if (с.ветка && с.ветка.кто === кто) {
    добавить({ id: 'продолжить', вид: 'продолжить', текст: сл.продолжить }, продолжитьВетку);
    отойти();
    return А;
  }
  for (const тид of S.мир.темы) {
    const исчерпана = л.исчерпано.includes(тид);
    const было = л.спрошено.includes(тид + ':' + с.подход);
    // Подход «деньгами» списывает гроши: на пустой кошелёк такой вопрос не задать.
    // ВОПРОС: в старой игре такой проверки не было (кошелёк мог уйти в минус).
    const о = ответ(S, кто, тид);
    const трата = о?.эффект?.гроши < 0 && !(было && !о.р.дальше) ? -о.эффект.гроши : 0;
    const мало = трата > S.герой.кошель;
    добавить({ id: `тема:${тид}`, вид: 'тема', тема: тид, текст: (исчерпана || было ? сл.было : '') + сл.реплика + фраза(д, тид, с.подход),
      подпись: исчерпана ? сл.сказано : было ? сл.уже : сл.час, можно: !исчерпана && !мало,
      почему: исчерпана ? сл.сказано : мало ? сл.нетДенег : null },
    S2 => спросить(S2, тид));
  }
  if (К.хозяйка === кто && К.близость) {
    добавить({ id: 'остаться', вид: 'остаться', текст: сл.остаться }, S2 => ходИнтим(S2, К.близость, кто));
  }
  отойти();
  return А;
}

// ── что рисовать: модель экрана без единой строки вёрстки ───────────────────
function часСловами(S) {
  const ч = S.сцена.часы;
  for (const [до, т] of Д(S).ЭКРАН.часСловами) if (до === null || ч < до) return т;
  return '';
}

function тинт(S) {
  const д = S.сцена.часы / Д(S).часов;
  for (const т of Д(S).ЭКРАН.тинт) if (т.до === undefined || д < т.до) return т.фон;
  return '';
}

function тепло(S, кто) {
  const р = расп(S, кто);
  for (const т of Д(S).ЭКРАН.тепло) {
    if (т.от !== undefined && р >= т.от) return т.текст;
    if (т.до !== undefined && р <= т.до) return т.текст;
    if (т.от === undefined && т.до === undefined) return т.текст;
  }
  return '';
}

export function видСцены(S) {
  const с = S.сцена, д = Д(S), Э = д.ЭКРАН, м = М(S);
  const К = д.КОМНАТЫ[с.комната];
  const кто = с.собеседник;
  const ч = кто ? д.ЛЮДИ[кто] : null;

  let реплика;
  if (кто) {
    // ВОПРОС: у Ярны в старом коде нет «вступления» (старая игра показывала «undefined») — здесь пусто.
    реплика = с.реплика || (с.нужнаСцена ? '' : ч.вступление ?? '');
  } else if (К.вход && !с.вошёл && !с.реплика) {
    реплика = К.текст + К.вход.текст;
  } else {
    реплика = с.реплика || К.текст;
  }

  const любитИзвестно = кто && расп(S, кто) >= 1;
  return {
    пипсы: { всего: д.часов, прошло: с.часы },
    деньги: S.герой.кошель + ' гр.' + (м.долг ? ' (долг ' + м.долг + ')' : ''),
    дом: Э.домВШапке[String(м.дом)] || Э.домВШапкеИначе,
    можноНазад: S.история.length > 0,
    фон: { комната: с.комната, градиент: К.градиент, подпись: Э.подпись.фон + К.фон + ' ]' },
    тинт: тинт(S),
    темы: S.мир.темы.filter(т => !д.ТЕМЫ[т]?.всегда).map(т => д.ТЕМЫ[т].ярлык),
    заголовок: ч
      ? { имя: ч.имя.toUpperCase(), справа: ч.место + ' · ' + тепло(S, кто) }
      : { имя: К.имя.toUpperCase(), справа: часСловами(S) },
    реплика,
    моя: кто ? с.мояреплика : '',
    портрет: ч ? { имя: ч.имя, файл: ч.портрет } : null,
    подходы: кто ? Э.подходы.map(п => ({ id: п, активен: с.подход === п })) : null,
    любит: любитИзвестно ? (ч.она ? Э.подпись.ейЗаходит : Э.подпись.емуЗаходит) + ч.любит : null,
    загружается: !!с.нужнаСцена,
    итог: с.итог,
  };
}

export function видПлана(S) {
  const с = S.сцена, д = Д(S), П = д.ПЛАН, м = М(S);
  return {
    заг: П.заг,
    вступление: П.вступление,
    клетки: П.порядок.map(id => {
      const к = д.КОМНАТЫ[id];
      const тут = id === с.комната;
      const был = м.осмотрено.some(x => x.startsWith(id + ':')) || тут;
      return {
        класс: тут ? 'mroom here' : был ? 'mroom' : 'mroom dark',
        имя: был || тут ? к.имя : П.неизвестно,
        подпись: тут ? П.тут : к.цена ? к.цена + ' гр.' : был ? '' : П.незнакомо,
      };
    }),
    ключ: есть(S, 'была_у_ярны') ? П.кабинетОткрыт : П.кабинетЗакрыт,
    закрыть: П.закрыть,
  };
}

