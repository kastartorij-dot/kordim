// Меню (ГДД §18: три слота + автосейв, загрузка в любой момент) и «Как играть».
// Работает с DOM; решения о состоянии принимает index.html через колбэки.
import { списокСохранений } from './состояние.js';
import { НАЧАЛА } from '../данные/герой.js';
import { ВСТУПЛЕНИЕ } from '../данные/вступление.js';

const окно = html => {
  document.querySelectorAll('.ов.меню').forEach(o => o.remove());
  const ов = document.createElement('div');
  ов.className = 'ов меню';
  ов.innerHTML = `<div class="овбокс меню-бокс">${html}</div>`;
  document.body.appendChild(ов);
  return ов;
};
const закрыть = () => document.querySelectorAll('.ов.меню').forEach(o => o.remove());

function подпись(с) {
  if (с.пусто) return 'пусто';
  const н = НАЧАЛА.find(x => x.id === с.начало);
  return `день ${с.день}, ${с.отрезок}${н ? ' · ' + н.имя.toLowerCase() : ''}`;
}

// колбэки: { загрузить(слот), сохранитьВ(слот), заново(), помощь() }
export function рендерМеню(есть, к) {
  const список = списокСохранений();
  const строка = с => `
    <div class="слот">
      <div><b class="px">${с.слот === 'авто' ? 'Автосейв' : 'Слот ' + с.слот}</b><br><span class="mono">${подпись(с)}</span></div>
      <div class="слот-кнопки">
        ${с.слот !== 'авто' && есть ? `<button class="b" data-сохр="${с.слот}">Сохранить сюда</button>` : ''}
        <button class="b" data-загр="${с.слот}" ${с.пусто ? 'disabled' : ''}>Загрузить</button>
      </div>
    </div>`;
  const ов = окно(`
    <h2 class="px">Меню</h2>
    <p class="меню-мелко">Игра сама сохраняется в конце каждого дня (и на каждом шаге внутри места) — это автосейв. Слоты — чтобы отложить момент и вернуться к нему.</p>
    ${список.map(строка).join('')}
    <div class="меню-низ">
      <button class="b" id="меню-помощь">Как играть</button>
      <button class="b" id="меню-заново">Начать заново</button>
      <button class="b sin" id="меню-закрыть">Закрыть</button>
    </div>`);
  ов.querySelectorAll('[data-сохр]').forEach(b => b.onclick = () => {
    const n = Number(b.dataset.сохр);
    if (!список.find(с => с.слот === n).пусто && !confirm(`Перезаписать слот ${n}?`)) return;
    к.сохранитьВ(n);
    рендерМеню(есть, к);
  });
  ов.querySelectorAll('[data-загр]').forEach(b => b.onclick = () => {
    const n = b.dataset.загр === 'авто' ? 'авто' : Number(b.dataset.загр);
    if (есть && !confirm('Загрузить? Несохранённое с последнего автосейва пропадёт.')) return;
    закрыть();
    к.загрузить(n);
  });
  ов.querySelector('#меню-заново').onclick = () => {
    if (!confirm('Начать заново? Автосейв сотрётся, слоты 1–3 останутся.')) return;
    закрыть();
    к.заново();
  };
  ов.querySelector('#меню-помощь').onclick = () => { закрыть(); к.помощь(); };
  ов.querySelector('#меню-закрыть').onclick = закрыть;
}

