// Сцена прибытия после выбора начала.
export function рендерВступление(началоId, onДальше) {
  const В = ВСТУПЛЕНИЕ;
  const экр = т => String(т).replace(/&/g, '&amp;').replace(/</g, '&lt;');
  const ов = окно(`
    <h2 class="px">${экр(В.заголовок)}</h2>
    <p class="вступление">${экр(В.текст)}</p>
    <p class="вступление">${экр(В.поНачалу[началоId] ?? '')}</p>
    <button class="b sin" id="вступление-дальше">${экр(В.кнопка)}</button>`);
  ов.querySelector('#вступление-дальше').onclick = () => { закрыть(); onДальше(); };
}

// Предупреждение 18+ перед первым входом (решение автора 18.09, ГДД §24). Ответ помнит браузер.
const КЛЮЧ_18 = 'порт-теней-18';
export function подтверждено18() {
  try { return localStorage.getItem(КЛЮЧ_18) === 'да'; } catch { return false; }
}
export function рендерВзрослым(onДа) {
  const ов = окно(`
    <h2 class="px">Только для взрослых</h2>
    <div class="помощь">
      <p>В «Порте Теней» есть откровенные сцены и взрослые темы: дом Ярны, деньги за близость, зависимость, долги, насилие — за кадром, но всерьёз.</p>
      <p>Все персонажи — взрослые.</p>
      <p>Продолжая, ты подтверждаешь, что тебе есть 18 лет.</p>
    </div>
    <div class="меню-низ">
      <button class="b" id="взр-нет">Уйти</button>
      <button class="b sin" id="взр-да">Мне есть 18</button>
    </div>`);
  ов.querySelector('#взр-да').onclick = () => {
    try { localStorage.setItem(КЛЮЧ_18, 'да'); } catch {}
    закрыть();
    onДа();
  };
  ов.querySelector('#взр-нет').onclick = () => {
    ов.querySelector('.помощь').innerHTML = '<p>Хорошо. Эту вкладку можно просто закрыть.</p>';
    ов.querySelector('.меню-низ').remove();
  };
}
