// Экраны каркаса: карта, HUD, конец дня. Пиксельная рамка без картинок —
// подложки района необязательны (см. подложка(id) внизу), их подключение не
// требует правки этого файла (ГДД §21, правило 2).
import { РАЙОНЫ, район } from '../данные/районы.js';
import { переход, потратитьОтрезок } from './время.js';
import { сохранить } from './состояние.js';

const $ = id => document.getElementById(id);

// Путь разный у копии на сайте и у оригинала — тот же приём, что в «Синем часе».
const БАЗА_ПОДЛОЖЕК = location.pathname.includes('/game/')
  ? '../../img/port/районы/'
  : '../../wiki/img/port/районы/';

export function рендерHUD(S) {
  $('hud-день').textContent = `День ${S.мир.день}`;
  $('hud-отрезок').textContent = S.мир.отрезок;
  $('hud-кошель').textContent = `${S.герой.кошель} гр.`;
  const тело = S.герой.тело;
  $('hud-тело').innerHTML = ['сыт', 'отдых', 'тепло', 'цел']
    .map(к => `<span class="стат стат-${тело[к]}" title="${к}">${к[0].toUpperCase()}</span>`)
    .join('');
}

export function рендерКарту(S, onПереход) {
  const поле = $('экран');
  const текущий = район(S.мир.район);
  поле.innerHTML = `
    <div class="карта">
      <div class="карта-подложка" style="background-image:url('${подложка(текущий.id)}')"></div>
      <div class="карта-подпись px">${текущий.имя}</div>
      <p class="карта-описание">${текущий.описание}</p>
      <div class="карта-районы">
        ${РАЙОНЫ.map(р => `
          <button class="b район ${р.id === текущий.id ? 'здесь' : ''}" data-id="${р.id}">
            ${р.имя}<br><span class="mono">${р.id === текущий.id ? 'ты здесь' : '1 отрезок'}</span>
          </button>
        `).join('')}
      </div>
      <button class="b sin" id="ждать">Провести здесь отрезок</button>
    </div>
  `;
  поле.querySelectorAll('.район').forEach(btn => {
    btn.onclick = () => {
      if (btn.dataset.id === текущий.id) return;
      переход(S, btn.dataset.id);
      onПереход(S);
    };
  });
  $('ждать').onclick = () => {
    потратитьОтрезок(S);
    onПереход(S);
  };
}

export function рендерКонецДня(S, onДальше) {
  const поле = $('экран');
  поле.innerHTML = `
    <div class="ов">
      <div class="овбокс">
        <h2 class="px">Ночь. День ${S.мир.день} позади</h2>
        <p>Сыт: ${S.герой.тело.сыт} · Отдых: ${S.герой.тело.отдых} ·
           Тепло: ${S.герой.тело.тепло} · Цел: ${S.герой.тело.цел}</p>
        <p class="mono">Кошель: ${S.герой.кошель} гр.</p>
        <button class="b sin" id="дальше">Начать новый день</button>
      </div>
    </div>
  `;
  сохранить(S, 'авто');
  $('дальше').onclick = () => {
    потратитьОтрезок(S); // «ночь» последний отрезок — эта же функция откроет новый день (движок/время.js)
    onДальше(S);
  };
}

function подложка(районId) {
  const р = район(районId);
  return р?.подложка ? БАЗА_ПОДЛОЖЕК + р.подложка : '';
}
