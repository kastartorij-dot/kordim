// Верхний уровень времени: утро/день/вечер/ночь. ГДД §4.
// Ночь — полноценный отрезок: можно лечь спать, а можно потратить её на дела
// (ночная работа, слежка, ГДД §4 и §13) — тогда день кончается без сна.
export const ОТРЕЗКИ = ['утро', 'день', 'вечер', 'ночь'];

export function следующийОтрезок(S) {
  const i = ОТРЕЗКИ.indexOf(S.мир.отрезок);
  if (i < ОТРЕЗКИ.length - 1) {
    S.мир.отрезок = ОТРЕЗКИ[i + 1];
  } else {
    закончитьДень(S, false); // ночь ушла на дела, не на сон
  }
  return S;
}

export function лечьСпать(S) {
  закончитьДень(S, true);
  return S;
}

// Итог дня пишется в S.мир.конецДня — экран конца дня показывается, пока он
// не снят (так он переживает и перезагрузку страницы после автосейва).
function закончитьДень(S, выспался) {
  S.мир.конецДня = { день: S.мир.день, выспался };
  S.мир.день += 1;
  S.мир.отрезок = ОТРЕЗКИ[0];
  // Падения статов раз в сутки, ГДД §5. Сколько сон восстанавливает, зависит
  // от жилья — это стадия 2; пока только цена бессонной ночи.
  S.герой.тело.сыт = Math.max(0, S.герой.тело.сыт - 1);
  if (!выспался) S.герой.тело.отдых = Math.max(0, S.герой.тело.отдых - 1);
  return S;
}

// Тратит отрезок на действие внутри текущего района (работа, отдых, слежка —
// всё, что не переход и не заход в место).
export function потратитьОтрезок(S) {
  следующийОтрезок(S);
  return S;
}

export function переход(S, районId) {
  if (S.мир.район === районId) return S; // внутри района — бесплатно (§4)
  S.мир.район = районId;
  потратитьОтрезок(S);
  return S;
}
