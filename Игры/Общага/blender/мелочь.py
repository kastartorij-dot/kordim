# Мелочь, которая делает комнату жилой: бутылки, банки, коробки, пакеты, бокалы на полке над столом,
# вещи на шкафу, холодильнике, столе, подоконнике и тумбочке. Простые формы, правильные пропорции,
# цвета — с фото 1 и 2 (белые и голубые бутылки, голубая коробка, оранжево-чёрная упаковка, зелёные пачки).
# Раскладка случайная, но с постоянным зерном — от запуска к запуску одинаковая.
import bpy, math, random
from мебель import box, cyl, soft, flat_mat, glass_mat

_mats = {}
def mat(color, rough=0.4, kind="plastic"):
    key = (tuple(round(c, 3) for c in color), rough, kind)
    if key not in _mats:
        if kind == "glass":
            _mats[key] = glass_mat(f"стекло_{len(_mats)}", color, rough)
        else:
            _mats[key] = flat_mat(f"мелочь_{len(_mats)}", color, rough)
    return _mats[key]

PAL = {
    "белый": (0.88, 0.88, 0.86), "голубой": (0.35, 0.62, 0.85), "бирюза": (0.15, 0.6, 0.62),
    "оранж": (0.95, 0.42, 0.08), "чёрный": (0.03, 0.03, 0.035), "зелёный": (0.25, 0.5, 0.2),
    "красный": (0.75, 0.12, 0.1), "розовый": (0.9, 0.5, 0.6), "жёлтый": (0.92, 0.75, 0.15),
    "серый": (0.5, 0.5, 0.52), "синий": (0.1, 0.18, 0.5), "крафт": (0.62, 0.48, 0.32),
}

def cone(name, r1, r2, z1, z2, x, y, m, verts=24):
    bpy.ops.mesh.primitive_cone_add(vertices=verts, radius1=r1, radius2=r2, depth=z2 - z1, location=(x, y, (z1 + z2) / 2))
    ob = bpy.context.object; ob.name = name
    ob.data.materials.append(m)
    for p in ob.data.polygons: p.use_smooth = True
    return ob

def бутылка(x, y, z, h=0.24, r=0.035, тело="белый", крышка="синий", стекло=False):
    m = mat(PAL[тело] if not стекло else (0.75, 0.85, 0.7), 0.3 if not стекло else 0.05, "glass" if стекло else "plastic")
    hb = h * 0.62
    cyl("бутылка", r, z, z + hb, x, y, m, 24)
    cone("плечи", r, r * 0.38, z + hb, z + h * 0.82, x, y, m)
    cyl("горло", r * 0.38, z + h * 0.82, z + h * 0.94, x, y, m, 16)
    cyl("крышка", r * 0.42, z + h * 0.94, z + h, x, y, mat(PAL[крышка]), 16)
    return 2 * r

def спрей(x, y, z, h=0.22, r=0.032, тело="белый"):
    cyl("флакон", r, z, z + h * 0.7, x, y, mat(PAL[тело]), 24)
    cone("плечи", r, r * 0.5, z + h * 0.7, z + h * 0.8, x, y, mat(PAL[тело]))
    box("распылитель", x - 0.012, y - 0.03, z + h * 0.8, x + 0.012, y + 0.01, z + h, mat(PAL["зелёный"]), 0.003, None)
    return 2 * r

def банка(x, y, z, r=0.04, h=0.12, тело="красный", крышка="белый"):
    cyl("банка", r, z, z + h * 0.85, x, y, mat(PAL[тело]), 24)
    cyl("крышка", r * 1.02, z + h * 0.85, z + h, x, y, mat(PAL[крышка]), 24)
    return 2 * r

def пузырёк(x, y, z, r=0.018, h=0.07, тело="чёрный"):
    cyl("пузырёк", r, z, z + h * 0.75, x, y, mat(PAL[тело]), 16)
    cyl("крышка", r * 0.7, z + h * 0.75, z + h, x, y, mat(PAL["белый"]), 12)
    return 2 * r

def коробка(x, y, z, w=0.12, d=0.08, h=0.2, тело="голубой", полоса="белый", rot=0.0):
    b = box("коробка", x - w/2, y - d/2, z, x + w/2, y + d/2, z + h, mat(PAL[тело], 0.6), 0.003, None)
    s = box("этикетка", x - w/2 + 0.01, y + d/2, z + h * 0.35, x + w/2 - 0.01, y + d/2 + 0.001, z + h * 0.65, mat(PAL[полоса], 0.6), 0, None)
    # этикетка на лицевой стороне (+y) поворачивается вместе с коробкой вокруг её центра
    dy = d/2 + 0.0005
    b.rotation_euler = (0, 0, rot)
    s.rotation_euler = (0, 0, rot)
    s.location = (x - math.sin(rot) * dy, y + math.cos(rot) * dy, s.location.z)
    return w

def пакет(x, y, z, w=0.15, h=0.14, тело="зелёный", seed=0):
    rnd = random.Random(seed)
    b = box("пакет", x - w/2, y - 0.06, z, x + w/2, y + 0.06, z + h, mat(PAL[тело], 0.35), 0, None)
    b.scale = (1 + rnd.uniform(-0.1, 0.1), 1 + rnd.uniform(-0.15, 0.1), 1)
    b.rotation_euler = (rnd.uniform(-0.08, 0.08), rnd.uniform(-0.08, 0.08), rnd.uniform(-0.3, 0.3))
    soft(b, 2, 0.04)
    return w

def бокал(x, y, z, h=0.18):
    g = mat((0.95, 0.97, 0.96), 0.0, "glass")
    cyl("подставка", 0.035, z, z + 0.004, x, y, g, 24)
    cyl("ножка", 0.004, z + 0.004, z + h * 0.45, x, y, g, 12)
    cone("чаша", 0.012, 0.042, z + h * 0.45, z + h, x, y, g, 24)
    return 0.085

def стакан(x, y, z, r=0.035, h=0.11):
    cone("стакан", r * 0.85, r, z, z + h, x, y, mat((0.95, 0.97, 0.96), 0.0, "glass"), 24)
    return 2 * r

def кружка(x, y, z, тело="белый"):
    cyl("кружка", 0.042, z, z + 0.095, x, y, mat(PAL[тело], 0.25), 24)
    b = box("ручка", x + 0.04, y - 0.006, z + 0.02, x + 0.07, y + 0.006, z + 0.08, mat(PAL[тело], 0.25), 0.006, None)
    return 0.1

def стопка_бумаг(x, y, z, n=8):
    for i in range(n):
        p = box("лист", x - 0.105, y - 0.148, z + i * 0.0012, x + 0.105, y + 0.148, z + (i + 1) * 0.0012, mat((0.95, 0.95, 0.93), 0.8), 0, None)
        p.rotation_euler = (0, 0, random.uniform(-0.06, 0.06))
    return 0.21

# --- раскладка по отрезку: предметы встают в ряд с промежутками, пока есть место
ITEMS = [
    lambda x, y, z, r: бутылка(x, y, z, r.uniform(0.18, 0.28), r.uniform(0.028, 0.04), r.choice(["белый", "голубой", "бирюза", "белый"]), r.choice(["синий", "красный", "белый", "зелёный"])),
    lambda x, y, z, r: банка(x, y, z, r.uniform(0.03, 0.045), r.uniform(0.08, 0.14), r.choice(["красный", "жёлтый", "белый", "зелёный"]), r.choice(["белый", "чёрный", "красный"])),
    lambda x, y, z, r: пузырёк(x, y, z, r.uniform(0.014, 0.02), r.uniform(0.05, 0.09), r.choice(["чёрный", "серый", "белый"])),
    lambda x, y, z, r: коробка(x, y, z, r.uniform(0.08, 0.16), r.uniform(0.05, 0.09), r.uniform(0.1, 0.24), r.choice(["голубой", "оранж", "чёрный", "белый", "зелёный"]), r.choice(["белый", "оранж", "жёлтый"]), r.uniform(-0.15, 0.15)),
    lambda x, y, z, r: спрей(x, y, z, r.uniform(0.17, 0.24), 0.03, r.choice(["белый", "голубой", "розовый"])),
    lambda x, y, z, r: пакет(x, y, z, r.uniform(0.12, 0.18), r.uniform(0.1, 0.16), r.choice(["зелёный", "крафт", "розовый", "белый"]), r.randrange(99)),
]

def ряд(x1, x2, y, z, seed, плотность=0.75, hmax=0.28, weights=(5, 3, 3, 3, 2, 2)):
    """Заполняет отрезок по X предметами. Возвращает, сколько поставлено."""
    rnd = random.Random(seed)
    x = x1 + rnd.uniform(0.01, 0.04)
    n = 0
    while x < x2 - 0.05:
        if rnd.random() > плотность:
            x += rnd.uniform(0.05, 0.12); continue
        f = rnd.choices(ITEMS, weights)[0]
        w = 0.09
        # оцениваем ширину заранее: ставим, потом сдвигаем курсор
        xc = x + 0.05
        if xc > x2 - 0.04: break
        w = f(xc, y + rnd.uniform(-0.02, 0.02), z, rnd) or 0.09
        x = xc + w / 2 + rnd.uniform(0.01, 0.04) + 0.02
        n += 1
    return n

def наполнить(L=4.6, W=3.2):
    """Раскладка мелочи по комнате (оси комнаты — см. комната.py)."""
    # полка над столом: стол стоит в (1.875, 0), повёрнут на 180 — X полки идёт в обратную сторону.
    # Стойки на X 1.545 и 2.205; ярусы: 1.318, 1.633 и верх 1.948. Глубина полки 0.26 (Y 0..0.26).
    for i, z in enumerate((1.318, 1.633)):
        ряд(1.30, 1.53, 0.09, z, 10 + i, 0.8)
        ряд(1.565, 2.19, 0.12, z, 20 + i, 0.85)
        ряд(2.22, 2.45, 0.09, z, 30 + i, 0.8)
    # верх полки: бокалы, бутылки, стаканы — как на фото 1
    rnd = random.Random(40)
    x = 1.32
    while x < 2.43:
        k = rnd.random()
        if k < 0.35: w = бокал(x, 0.12, 1.948)
        elif k < 0.7: w = бутылка(x, 0.12, 1.948, rnd.uniform(0.22, 0.3), 0.035, rnd.choice(["белый", "бирюза", "голубой"]), "чёрный")
        else: w = стакан(x, 0.12, 1.948)
        x += w + rnd.uniform(0.02, 0.07)
    # шкаф сверху: сумка и коробка
    s = box("сумка", 0.08, 1.2, 2.35, 0.52, 1.75, 2.58, mat(PAL["чёрный"], 0.5), 0, None); soft(s, 2, 0.06)
    коробка(0.3, 2.2, 2.35, 0.4, 0.3, 0.2, "крафт", "крафт", 0.1)
    # стол 1: кружка, бумаги, зарядка
    кружка(1.45, 0.45, 0.75, "белый")
    стопка_бумаг(2.25, 0.4, 0.75)
    # столик у холодильника: кружка, тарелка, пакет
    кружка(0.75, W - 0.2, 0.75, "бирюза")
    cyl("тарелка", 0.1, 0.75, 0.765, 1.55, W - 0.25, mat(PAL["голубой"], 0.2), 32)
    пакет(1.6, W - 0.42, 0.75, 0.2, 0.12, "белый", 3)
    # подоконник: стакан и коробка
    стакан(L - 0.0, 1.2, 0.85)
    коробка(L + 0.02, 1.9, 0.85, 0.1, 0.1, 0.12, "жёлтый", "белый", 0.3)
    # тумбочка у окна: зелёная кружка, как на видео 4
    кружка(L - 0.33, 1.2, 0.6, "зелёный")
