def ph(id, x, y, z, rot=0.0, scale=1.0):
    """Скан с Poly Haven (CC0) из assets/polyhaven/<id>: ставится основанием на z."""
    before = set(bpy.data.objects)
    bpy.ops.import_scene.gltf(filepath=os.path.join(ASSETS, id, id + ".gltf"))
    new = [o for o in bpy.data.objects if o not in before]
    root = bpy.data.objects.new(id, None); bpy.context.collection.objects.link(root)
    for o in new:
        if o.parent is None: o.parent = root
    root.location = (x, y, z); root.rotation_euler = (0, 0, rot); root.scale = (scale,) * 3
    return root

