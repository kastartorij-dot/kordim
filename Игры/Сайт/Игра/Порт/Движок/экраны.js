const экр = т => String(т).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const список = строки => строки.length ? `<ul class="журнал mono">${строки.map(с => `<li>${экр(с)}</li>`).join('')}</ul>` : '';

// Состояние интерфейса города (в сохранение не входит): открыт ли экран района и какая карточка раскрыта.
export const ИНТ = { район: true, карточка: null, категория: 'места', момент: null };

// Есть ли картинка карты. Файла может не быть — тогда районы рисуются кнопками.
let картаЕсть; // undefined — ещё не проверяли
function проверитьКарту(готово) {
  if (картаЕсть !== undefined) return готово();
  const i = new Image();
  i.onload = () => { картаЕсть = true; готово(); };
  i.onerror = () => { картаЕсть = false; готово(); };
  i.src = БАЗА_КАРТЫ + КАРТА;
}

export function рендерHUD(S) {
  $('hud-день').textContent = 'День ' + S.мир.день;
  const м = S.сцена && МЕСТА.find(x => x.id === S.сцена.место);
  const отрезок = м ? S.сцена.отрезок ?? м.когда[0] : S.мир.отрезок;
  $('hud-отрезок').innerHTML = ['утро', 'день', 'вечер', 'ночь'].map(о => '<span class="отрезок' + (о === отрезок ? ' сейчас' : '') + '">' + экр(о) + '</span>').join('');
  $('hud-где').textContent = м ? м.имя : район(S.мир.район)?.имя ?? '';
  $('hud-погода').textContent = S.мир.погода ?? 'ясно';
  $('hud-кошель').textContent = S.герой.кошель + ' гр.';
}

const карточкаДействия = (д, S) => {
  const риск = предупреждениеДействия(д, S);
  return '<button class="b действие-карточка" data-id="' + экр(д.id) + '"' + (д.можно ? '' : ' disabled') + '><strong>' + экр(названиеДействия(д)) + '</strong><span class="действие-цена">' + экр(подписьДействия(д)) + '</span>'
    + (!д.можно && д.почему ? '<span class="действие-причина">' + экр(д.почему) + '</span>' : '')
    + (риск ? '<span class="действие-риск">' + экр(риск) + '</span>' : '') + '</button>';
};
const краткоеТело = S => '<div class="состояние-кратко" aria-label="Состояние героя">' + сводкаГероя(S).тело.map(т => '<span class="тело-' + т.значение + '" title="' + экр(т.строка) + '"><i aria-hidden="true"></i>' + экр(т.название) + ' · ' + т.значение + '/3</span>').join('') + '</div>';

// Город: карта или экран района.
export function рендерКарту(S, onПереход) {
  if (ИНТ.район) рендерРайон(S, onПереход);
  else рендерГород(S, onПереход);
}

// Смена блокирует город, пока игрок не выберет исход и не закроет карточку.
// Раньше её действия возвращались движком, но экран района их не рисовал.
export function рендерСмены(S, onПереход) {
  const поле = $('экран');
  const вид = видСмены(S);
  const действия = доступныеДействия(S).filter(д => д.группа === 'смена');
  const строки = вид.строки?.length
    ? `<ul class="смена-итог mono">${вид.строки.map(с => `<li>${экр(с)}</li>`).join('')}</ul>`
    : '';
  поле.innerHTML = `
    <div class="смена-экран">
      <section class="смена-карточка">
        <h1 class="px">${экр(вид.заголовок)}</h1>
        ${вид.текст ? `<p class="смена-текст">${экр(вид.текст)}</p>` : ''}
        ${строки}
        <div class="смена-кнопки">${действия.map(д => `
          <button class="b" data-id="${экр(д.id)}" ${д.можно ? '' : 'disabled'}>
            ${экр(д.текст)}${д.подпись ? `<br><span class="mono">${экр(д.можно ? д.подпись : д.почему)}</span>` : ''}
          </button>`).join('')}
        </div>
      </section>
    </div>`;
  поле.querySelectorAll('button[data-id]').forEach(btn => {
    btn.onclick = () => {
      const д = действия.find(x => x.id === btn.dataset.id);
      if (!д?.можно) return;
      д.выполнить(S);
      onПереход(S, true);
    };
  });
}

// Значки мест района, открытых сейчас.
// Все места района: открытые сейчас — ярко, закрытые — серым (иначе днём «Синего часа» на карте будто нет).
const местаРайона = (S, районId) => МЕСТА.filter(м => м.район === районId).map(м => ({ м, открыто: можноВойти(S, м.id).можно }));

function рендерГород(S, onПереход) {
  const поле = $('экран');
  const действия = доступныеДействия(S);
  const выбран = район(ИНТ.карточка ?? S.мир.район) ?? район(S.мир.район);
  const тут = выбран.id === S.мир.район;
  const ход = действия.find(д => д.id === 'переход:' + выбран.id);
  const метка = р => экр(р.имя) + (р.id === S.мир.район ? '<small>ты здесь</small>' : '');
  const места = местаРайона(S, выбран.id);
  const собрать = естьКартинка => {
    if (S.сцена || S.мир.смена || S.мир.конецДня || ИНТ.район) return;
    const зоны = РАЙОНЫ.map(р => '<button class="b карта-метка' + (р.id === выбран.id ? ' выбрана' : '') + '" data-р="' + р.id + '" style="--x:' + р.наКарте.x + '%;left:var(--x);top:' + р.наКарте.y + '%" aria-pressed="' + (р.id === выбран.id) + '">' + метка(р) + '</button>').join('');
    const html = '<div class="город"><section class="город-вид"><div class="надзаголовок">Порт Теней</div><h1>Город у воды</h1>'
      + (естьКартинка ? '<div class="город-полотно"><img class="город-картинка" width="1672" height="941" src="' + БАЗА_КАРТЫ + КАРТА + '" alt="Карта пяти районов Порта Теней">' + зоны + '</div>' : '<div class="город-кнопки">' + РАЙОНЫ.map(р => '<button class="b" data-р="' + р.id + '">' + метка(р) + '</button>').join('') + '</div>')
      + '</section><aside class="город-карточка"><div class="надзаголовок">Выбранный район</div><h2>' + экр(выбран.имя) + '</h2><p class="карта-описание">' + экр(выбран.описание) + '</p><p class="действие-цена">' + (тут ? 'Ты здесь · без затрат времени' : экр(ход?.подпись ?? '') + ' · 0 гр.') + '</p>'
      + '<button class="b sin" id="идти"' + (!тут && !ход?.можно ? ' disabled' : '') + '>' + (тут ? 'Открыть район' : 'Перейти в район') + '</button><div class="места-карты"><h3>Места</h3>'
      + места.map(({м, открыто}) => '<div><b>' + экр(м.имя) + '</b><small>' + (открыто ? 'Открыто сейчас' : экр(можноВойти(S, м.id).почему ?? 'Закрыто')) + '</small></div>').join('')
      + '</div><p class="подсказка">Выбор района на карте не расходует время.</p></aside></div>';
    if (поле.querySelector('.город')) {
      // Выбор меняет описание справа, а рисунок и метки остаются на месте.
      const шаблон = document.createElement('template'); шаблон.innerHTML = html;
      поле.querySelector('.город-карточка').replaceWith(шаблон.content.querySelector('.город-карточка'));
      поле.querySelectorAll('[data-р]').forEach(el => {
        const выбранная = el.dataset.р === выбран.id;
        el.classList.toggle('выбрана', выбранная);
        el.setAttribute('aria-pressed', String(выбранная));
      });
    } else поле.innerHTML = html;
    поле.querySelectorAll('[data-р]').forEach(el => {
      el.onclick = () => {
        ИНТ.карточка = el.dataset.р;
        рендерГород(S, onПереход);
        поле.querySelector('[data-р="' + el.dataset.р + '"]')?.focus({preventScroll: true});
      };
    });
    $('идти').onclick = () => {
      if (!тут) { if (!ход?.можно) return; ход.выполнить(S); }
      ИНТ.карточка = null; ИНТ.район = true;
      onПереход(S);
    };
  };
  if (картаЕсть === undefined) проверитьКарту(() => собрать(картаЕсть)); else собрать(картаЕсть);
}

function рендерРайон(S, onПереход) {
  const поле = $('экран');
  const текущий = район(S.мир.район);
  const момент = S.мир.день + ':' + S.мир.район + ':' + S.мир.отрезок;
  if (ИНТ.момент !== момент) {
    if (S.мир.отрезок === 'ночь') ИНТ.категория = 'быт';
    else if (ИНТ.момент?.endsWith(':ночь')) ИНТ.категория = 'места';
    ИНТ.момент = момент;
  }
  const действия = доступныеДействия(S).filter(д => д.вид !== 'переход');
  const прогулка = действия.find(д => д.id === 'отрезок:здесь');
  const остальные = действия.filter(д => д !== прогулка);
  const категории = КАТЕГОРИИ.filter(([id]) => остальные.some(д => категорияДействия(д) === id));
  if (!категории.some(([id]) => id === ИНТ.категория)) ИНТ.категория = категории[0]?.[0];
  const безопасные = S.мир.отрезок === 'ночь' ? ЖИЛЬЁ.filter(ж => ж.открыто && !ж.риск && ж.где && !ж.где.includes(S.мир.район)).map(ж => {
    const оплачено = S.герой.жильё?.id === ж.id && S.герой.жильё.оплачено_по >= S.мир.день;
    return ж.имя + ' — ' + (оплачено ? 'уже оплачено' : ж.цена + ' гр.' + (ж.ночей ? ' за ' + ж.ночей + ' ночей' : ''));
  }) : [];
  const выбранные = остальные.filter(д => категорияДействия(д) === ИНТ.категория);
  поле.innerHTML = '<div class="район-экран"><section class="район-вид"><div class="район-сцена" style="background-image:url(' + подложка(текущий.id) + ')"><div class="район-название"><div class="надзаголовок">Порт Теней / ' + экр(текущий.сторона) + '</div><h1>' + экр(текущий.имя) + '</h1></div></div>'
    + '<p class="карта-описание">' + экр(текущий.описание) + '</p>' + краткоеТело(S)
    + (прогулка ? карточкаДействия(прогулка, S) : '')
    + (S.мир.журналДня.length ? '<details class="события-дня"><summary>Сегодня · ' + S.мир.журналДня.length + '</summary>' + список(S.мир.журналДня) + '</details>' : '')
    + '</section><aside class="район-действия"><div class="надзаголовок">Ты здесь · ' + экр(S.мир.отрезок) + '</div><div class="район-шапка"><h2>Что можно сделать</h2><button class="b ссылка" id="на-карту">На карту</button></div>'
    + '<div class="вкладки-действий">' + категории.map(([id,имя]) => '<button class="b' + (id === ИНТ.категория ? ' on' : '') + '" data-категория="' + id + '" aria-pressed="' + (id === ИНТ.категория) + '">' + имя + '</button>').join('') + '</div>'
    + '<div class="список-действий">' + выбранные.map(д => карточкаДействия(д,S)).join('') + '</div>'
    + (ИНТ.категория === 'быт' && безопасные.length ? '<p class="подсказка">Защита кошеля во сне: ' + экр(безопасные.join('; ')) + '. Дорога занимает отрезок — жильё лучше выбирать заранее.</p>' : '')
    + (ИНТ.категория === 'места' ? '<p class="подсказка">Посещение места занимает один отрезок. Сон выбирается отдельно.</p>' : '') + '</aside></div>';
  $('на-карту').onclick = () => { ИНТ.район = false; ИНТ.карточка = null; onПереход(S); };
  поле.querySelectorAll('[data-категория]').forEach(btn => {
    btn.onclick = () => {
      const верх = поле.scrollTop;
      ИНТ.категория = btn.dataset.категория;
      рендерРайон(S, onПереход);
      поле.scrollTop = верх;
      поле.querySelector('[data-категория="' + ИНТ.категория + '"]')?.focus({preventScroll:true});
    };
  });
  поле.querySelectorAll('button[data-id]').forEach(btn => {
    btn.onclick = () => {
      const д = действия.find(x => x.id === btn.dataset.id);
      if (!д?.можно) return;
      д.выполнить(S); onПереход(S);
    };
  });
}

// Итог дня: день уже переключён (Движок/время.js), здесь только показать и
// снять S.мир.конецДня. Автосейв делает index.html.
