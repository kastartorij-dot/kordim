// Девять голосов героя (ПЛАН_ДОРАБОТКИ П05.5). Громкость нужд равна состоянию тела; ум и прошлое имеют ступень 0–3.
// Правила (концепт §3): не больше двух голосов на экран; строка не повторяется за сейв; голос молчит следующие два узла.
import { ГОЛОСА, ГОЛОСА_РЕМЕСЛА, СТУПЕНИ_РЕМЕСЛА, ЗАРУБКИ_ПОРОГИ, МОЛВА_ПОРОГИ, ГОЛОС_МОЛЧИТ_УЗЛОВ, ГОЛОСОВ_НА_УЗЕЛ } from '../Данные/голоса.js';
import { верностьТемы, ПОДТВЕРЖДЕНО } from './знание.js';
import { НАЧАЛА } from '../Данные/герой.js';

const по = (таблица, n) => таблица.find(([от]) => n >= от)[1];
const П = S => (S.мир.голоса ??= { показано: {}, молчит: {}, зарубки: {}, открыты: [] });

// Громкость нужды: сыт/отдых/тепло/цел 3–2 → молчит, 1 → говорит (2), 0 → перебивает (3).
const нужда = z => (z >= 2 ? 0 : z === 1 ? 2 : 3);

export function громкость(S, голос) {
  const т = S.герой.тело;
  if (голос === 'БРЮХО') return нужда(т.сыт);
  if (голос === 'КОСТИ') return нужда(Math.min(т.отдых, т.тепло, т.цел));
  if (голос === 'ХМЕЛЬ') return (S.герой.хмель ?? 0) >= 2 ? Math.min(3, S.герой.хмель) : 0;
  if (голос === 'ЖАР') return (S.герой.напряжение ?? 0) >= 2 ? Math.min(3, S.герой.напряжение) : 0;
  return 0;
}

// Ступень голоса ума и прошлого (0–3). У нужд ступени нет.
export function ступеньГолоса(S, голос) {
  const г = ГОЛОСА[голос];
  if (!г || г.группа === 'нужды') return 0;
  const П_ = П(S);
  const зарубки = П_.зарубки[голос] ?? 0;
  if (ГОЛОСА_РЕМЕСЛА.includes(голос)) {
    // Голос ремесла один из трёх (концепт §3): говорит тот, чьё ремесло было стартовым. Выученные позже ремёсла голоса не добавляют.
    if (НАЧАЛА.find(н => н.id === S.герой.начало)?.ремесло !== г.ремесло) return 0;
    return СТУПЕНИ_РЕМЕСЛА[S.герой.ремёсла?.[г.ремесло]?.ступень] ?? 0;
  }
  if (голос === 'МОЛВА') {
    const н = S.мир.темы.filter(т => верностьТемы(S, т) === ПОДТВЕРЖДЕНО).length;
    return Math.max(S.мир.темы.length ? 1 : 0, по(МОЛВА_ПОРОГИ, н));
  }
  if (голос === 'ЧУТЬЁ') return Math.max((S.мир.тень ?? 0) >= 1 ? 1 : 0, по(ЗАРУБКИ_ПОРОГИ, зарубки));
  // ОТЕЦ и ДЫМ просыпаются по очереди: пока не раскрыты, ступень 0
  return П_.открыты.includes(голос) ? Math.max(1, по(ЗАРУБКИ_ПОРОГИ, зарубки)) : 0;
}

export function слышен(S, голос) {
  const г = ГОЛОСА[голос];
  if (!г) return false;
  return г.группа === 'нужды' ? громкость(S, голос) > 0 : ступеньГолоса(S, голос) > 0;
}

export function открыть(S, голос) {
  const о = П(S).открыты;
  if (ГОЛОСА[голос] && !о.includes(голос)) о.push(голос);
}

// Зарубка: успех проверки по делу, не больше одной на сцену.
export function зарубка(S, голос) {
  const с = S.сцена;
  if (!с || с.зарубкаСцены) return false;
  с.зарубкаСцены = true;
  П(S).зарубки[голос] = (П(S).зарубки[голос] ?? 0) + 1;
  return true;
}

// Приоритет: пассивный успех 3 > нужда с громкостью 3 → 2 > нужда с громкостью 2 → 1 > остальные 0.
export const приоритет = (S, в, пассивныйУспех) => (пассивныйУспех ? 3 : ГОЛОСА[в.голос]?.группа === 'нужды' ? (громкость(S, в.голос) >= 3 ? 2 : 1) : 0);

// На входе в узел: голоса, что молчали, становятся ближе к речи.
export function тикУзла(S) {
  const м = П(S).молчит;
  for (const к of Object.keys(м)) if ((м[к] -= 1) <= 0) delete м[к];
}

// Выбор строк. кандидаты: [{ ид, голос, текст, приоритет }] — уже отфильтрованы по условиям и пассивным проверкам.
export function выбрать(S, кандидаты) {
  const Г = П(S);
  const доступные = кандидаты
    .filter(в => слышен(S, в.голос) || в.пассивныйУспех || в.первый)
    .filter(в => !Г.показано[в.ид] && !Г.молчит[в.голос])
    .sort((a, b) => b.приоритет - a.приоритет);
  const взято = [];
  for (const в of доступные) {
    if (взято.length >= ГОЛОСОВ_НА_УЗЕЛ) break;
    if (взято.some(x => x.голос === в.голос)) continue;
    взято.push(в);
  }
  for (const в of взято) { Г.показано[в.ид] = S.мир.день; Г.молчит[в.голос] = ГОЛОС_МОЛЧИТ_УЗЛОВ; }
  return взято;
}

// Показать заранее написанную строку голоса (итог проверки, явная реплика): она тоже запоминается.
export function записатьСтроку(S, ид, голос) {
  const Г = П(S);
  if (ид) Г.показано[ид] = S.мир.день;
  Г.молчит[голос] = ГОЛОС_МОЛЧИТ_УЗЛОВ;
}
