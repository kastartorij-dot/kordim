// Огонь маяка: читать с галереи вечером или ночью, купить у Гвоздя прогноз на завтра, сложить записи в код.
// Записи лежат в памяти места: S.мир.места.маяк.память.огонь[день] = { режим }. Без DOM; таблица и числа — в данные/огонь.js.
import { режимНочи, ТЕКСТ_ОГНЯ, ПРОГНОЗ, ЗАПИСЕЙ_ДЛЯ_КОДА } from '../Данные/огонь.js';
import { деньСцены } from './торг.js';
import { датьТему } from './знание.js';
import { бросок } from './случай.js';

const М = S => S.мир.места[S.сцена.место];
const память = S => (М(S).память ??= {});
export const записи = S => S.мир.места.маяк?.память?.огонь ?? {};
const видыРежимов = S => new Set(Object.values(записи(S)).map(з => з.режим));

export const запись = (S, день) => записи(S)[день] ?? null;
export const кодСложился = S => Object.keys(записи(S)).length >= ЗАПИСЕЙ_ДЛЯ_КОДА && видыРежимов(S).has('две вспышки') && видыРежимов(S).has('долгая тьма');

// С галереи видно, как горит огонь: режим записывается в память места и в журнал; сверяется с прогнозом Гвоздя.
export function читатьОгонь(S) {
  const день = деньСцены(S), режим = режимНочи(день), п = память(S);
  (п.огонь ??= {})[день] = { режим };
  датьТему(S, 'mayak_ogon', undefined, S.сцена.место);
  if (режим === 'две вспышки') датьТему(S, 'kladbishche_kitov', undefined, S.сцена.место);
  let текст = ТЕКСТ_ОГНЯ[режим];
  const прогноз = п.прогноз?.[день];
  if (прогноз) {
    const верно = прогноз === режим;
    текст += верно ? '\n\nГвоздь вчера сказал то же самое. На этот раз он не ошибся.' : `\n\nГвоздь вчера обещал «${прогноз}». Он ошибся.`;
    (п.сверка ??= []).push({ день, верно });
  }
  S.сцена.реплика = текст;
  S.мир.журналДня.push(`Записал огонь маяка: ${режим} (день ${день})`);
}

// Гвоздь продаёт режим на завтра; в четверти случаев называет не тот.
export function купитьПрогноз(S) {
  const день = деньСцены(S) + 1, настоящий = режимНочи(день);
  const другие = ['ровный', 'две вспышки', 'долгая тьма'].filter(р => р !== настоящий);
  const названный = бросок(S) < ПРОГНОЗ.ошибка ? другие[Math.floor(бросок(S) * другие.length)] : настоящий;
  (память(S).прогноз ??= {})[день] = названный;
  S.сцена.реплика = `Гвоздь оглядывается на лестницу и шепчет: «Завтра ночью — ${названный}. Это я слышал от тех, кто просит. Клянусь, почти наверняка».`;
  S.мир.журналДня.push(`Гвоздь сказал: завтра (день ${день}) — ${названный}`);
}

// Достаточно записей: из них складывается код огня.
export function сверитьЗаписи(S) {
  if (!кодСложился(S)) return;
  датьТему(S, 'ogon_kod', undefined, S.сцена.место);
  S.сцена.реплика = 'Ты раскладываешь записи по ночам. Две вспышки совпадают с судами без огней, долгая тьма с расчётными днями и стражей на берегу. Это не случайность и не прихоть смотрителя: огонь меняют по чьей-то просьбе.';
  S.мир.журналДня.push('Записи огня сложились в код');
}
