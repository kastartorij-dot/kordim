// Слухи об Одвине: обратное течение — то, что герой сделал, начинает опережать его самого.
// Переработка Порт-Слухи-о-герое.md под ПЛАН_ДОРАБОТКИ.md П08.3–4.
//
// Что изменено по сравнению со старым заданием (и почему):
//  • слух — запись с датой, статусом и «кто комментировал», а не голый id: нужны
//    источник, круг слышавших, срок, опровержение (П08.3);
//  • реакция только у тех, кто мог услышать: источник и круг из данных (П08.4);
//  • человек, о чьих делах слух («Сибилла» для «свой у Сибиллы»), не пересказывает его
//    как чужой: это были бы его слова о самом себе;
//  • лесенка тени: из группы живёт одна ступень, два резервных слуха одновременно
//    не появляются (П08.3: «один повод не порождает все резервные формулировки»);
//  • слух объявляется герою не при появлении, а когда до него дошёл (первая реакция
//    человека или подслушанное), иначе игрок знает то, чего герой знать не мог;
//  • выбор реакции — чистая функция (её зовёт видСцены), а отметка «показано» —
//    отдельная: вход сохраняет выбранный текст в сцене и отмечает показ, видСцены() читает его.

import { СЛУХИ, ГРУППЫ, СРОК_ПО_УМОЛЧАНИЮ } from '../Данные/слухи-о-герое.js';
import { НАСТРОЙКИ, деньИгры, журналДня, человекЗнаком } from './шаг7-адаптер.js';

export const списокСлухов = S => S.мир.слухиОГерое ?? [];
export const найтиСлух = (S, id) => списокСлухов(S).find(з => з.id === id) ?? null;

const новаяЗапись = (S, id, статус = 'ходит', день = деньИгры(S)) =>
  ({ id, день, статус, дошёл: null, комментировали: [] });

// ---------- кто что мог слышать ----------

export function людиИсточника(р) {
  const ист = р.источник ?? {};
  return [...(ист.человек ? [ист.человек] : []), ...(ист.группа ? (ГРУППЫ[ист.группа] ?? []) : [])];
}

export function людиКруга(р) {
  const к = р.круг ?? {};
  return new Set([
    ...(к.люди ?? []),
    ...(к.группы ?? []).flatMap(г => ГРУППЫ[г] ?? []),
    ...людиИсточника(р),
  ]);
}

export function слухАктуален(S, з) {
  const р = СЛУХИ[з.id];
  if (!р || з.статус !== 'ходит') return false;
  const д = деньИгры(S);
  return д >= з.день + (р.задержка ?? 1) && д <= з.день + (р.срок ?? СРОК_ПО_УМОЛЧАНИЮ);
}

export function могСлышать(S, з, idЧеловека) {
  const р = СЛУХИ[з.id];
  return Boolean(р) && людиКруга(р).has(idЧеловека);
}

// ---------- раз в день, в закончитьДень (порядок суток ПЛАН П02.5: после последствий и фактов) ----------

export function обновитьСлухи(S, итог) {
  const д = итог?.день ?? деньИгры(S);
  const список = (S.мир.слухиОГерое ??= []);

  // 1. опровержение и остывание
  for (const з of список) {
    const р = СЛУХИ[з.id];
    if (!р || з.статус !== 'ходит') continue;
    if (р.опровержение?.условие(S)) { з.статус = 'опровергнут'; з.деньКонца = д; continue; }
    if (д > з.день + (р.срок ?? СРОК_ПО_УМОЛЧАНИЮ)) { з.статус = 'остыл'; з.деньКонца = д; }
  }

  // 2. новые слухи: отдельные — как есть, лесенки — только высшая подошедшая ступень
  const подошли = Object.entries(СЛУХИ).filter(([id, р]) => !найтиСлух(S, id) && р.условие(S));
  const лесенки = new Map();
  for (const [id, р] of подошли) {
    if (!р.группа) { список.push(новаяЗапись(S, id, 'ходит', д)); continue; }
    if (!лесенки.has(р.группа)) лесенки.set(р.группа, []);
    лесенки.get(р.группа).push([id, р]);
  }
  for (const [группа, ступени] of лесенки) {
    ступени.sort((a, b) => b[1].ступень - a[1].ступень);
    const [верхний, ...нижние] = ступени;
    const уже = список.find(з => СЛУХИ[з.id]?.группа === группа && СЛУХИ[з.id].ступень > верхний[1].ступень);
    if (уже) {                                   // высшая ступень уже звучала — нижняя не возвращается
      for (const [id] of ступени) список.push(новаяЗапись(S, id, 'вытеснен', д));
      continue;
    }
    список.push(новаяЗапись(S, верхний[0], 'ходит', д));
    for (const [id] of нижние) список.push(новаяЗапись(S, id, 'вытеснен', д));
    for (const з of список) {                    // прежняя низшая ступень уступает место
      const р = СЛУХИ[з.id];
      if (з.статус === 'ходит' && р?.группа === группа && р.ступень < верхний[1].ступень) {
        з.статус = 'вытеснен'; з.деньКонца = д;
      }
    }
  }

  if (НАСТРОЙКИ.объявлятьСлухСразу && итог?.причины) {
    for (const з of список) {
      if (з.день === д && з.статус === 'ходит') {
        итог.причины.push(`По городу уже говорят: ${СЛУХИ[з.id].коротко}`);
      }
    }
  }
}

// ---------- где слух виден игроку ----------

function текстРеакции(S, р, id, впервые) {
  const поле = впервые ? (р.вступление ?? р.повтор) : р.повтор;
  if (!поле) return null;
  if (typeof поле === 'function') return поле(S, id) || null;
  if (typeof поле === 'string') return поле;
  return поле[id] ?? поле.по_умолчанию ?? null;
}

// Первая встреча: проверять до любого места, которое создаёт S.мир.люди[кто].
export const впервыеСЧеловеком = (S, id) => !человекЗнаком(S, id);

// Чистая функция: что человек скажет о герое. → { слухId, текст, вид } | null.
// вид: 'вступление' (первая встреча) или 'повтор' (повторный разговор).
// Каждый слух человек комментирует один раз.
export function реакцияНаСлух(S, idЧеловека, { впервые = впервыеСЧеловеком(S, idЧеловека) } = {}) {
  const кандидаты = списокСлухов(S)
    .filter(з => слухАктуален(S, з) && могСлышать(S, з, idЧеловека)
      && !з.комментировали.includes(idЧеловека))
    .map(з => ({ з, р: СЛУХИ[з.id] }))
    .filter(({ р }) => !(р.не_для ?? []).includes(idЧеловека))
    .map(({ з, р }) => ({ з, р, текст: текстРеакции(S, р, idЧеловека, впервые) }))
    .filter(x => x.текст);
  кандидаты.sort((a, b) => (b.р.приоритет ?? 0) - (a.р.приоритет ?? 0) || b.з.день - a.з.день);
  const x = кандидаты[0];
  return x ? { слухId: x.з.id, текст: x.текст, вид: впервые ? 'вступление' : 'повтор' } : null;
}

// Пометить слух услышанным героем. Зовётся при входе в сцену / показе реплики,
// не из видСцены(). idЧеловека — кто сказал; null — подслушано в месте.
export function отметитьСлухПоказанным(S, слухId, idЧеловека = null) {
  const з = найтиСлух(S, слухId);
  if (!з) return false;
  if (idЧеловека && !з.комментировали.includes(idЧеловека)) з.комментировали.push(idЧеловека);
  if (з.дошёл == null) {
    з.дошёл = деньИгры(S);
    журналДня(S, `До тебя дошёл слух: ${СЛУХИ[слухId].коротко}.`);
  }
  return true;
}

// «Сидеть и слушать» в месте. → [{ слухId, текст }] по убыванию приоритета.
export function слухиДляМеста(S, местоId) {
  return списокСлухов(S)
    .filter(з => з.дошёл == null && слухАктуален(S, з) && СЛУХИ[з.id].слушать
      && (СЛУХИ[з.id].круг?.места ?? []).includes(местоId))
    .sort((a, b) => (СЛУХИ[b.id].приоритет ?? 0) - (СЛУХИ[a.id].приоритет ?? 0) || b.день - a.день)
    .map(з => ({ слухId: з.id, текст: СЛУХИ[з.id].слушать }));
}

// Опровержение остаётся в истории (П08.4): слух не удаляется, только перестаёт звучать.
export function опровергнуть(S, слухId, причина = null) {
  const з = найтиСлух(S, слухId);
  if (!з || з.статус !== 'ходит') return false;
  з.статус = 'опровергнут'; з.деньКонца = деньИгры(S);
  if (причина) з.причина = причина;
  return true;
}

// Для раздела журнала: только то, что дошло до героя.
export function сводкаСлухов(S) {
  return списокСлухов(S)
    .filter(з => з.дошёл != null && СЛУХИ[з.id])
    .map(з => ({ id: з.id, текст: СЛУХИ[з.id].коротко, статус: з.статус, день: з.дошёл }));
}
