const СТАТУСЫ_ЗАКРЫТЫХ = ['готово', 'просрочено', 'провалено', 'отказано'];
export const СЛОВА_СТАТУСОВ = { предложено: 'предложено', активно: 'в работе', готово: 'выполнено', просрочено: 'просрочено', провалено: 'провалено', отказано: 'отказался' };

export const записи = S => (S.мир.дела ??= []);
export const запись = (S, id) => записи(S).find(р => р.id === id) ?? null;
export const делоАктивно = (S, id) => запись(S, id)?.статус === 'активно';
export const делоГотово = (S, id) => запись(S, id)?.статус === 'готово';

const журнал = (S, строка) => { S.мир.журналДня.push(строка); return строка; };

function имяЧеловека(id) {
  for (const м of МЕСТА) { const л = м.модуль.ЛЮДИ?.[id]; if (л) return л.имя; }
  return id;
}

// ── условия, зависящие от мира и сцены ────────────────────────────────────
export const ходовОсталось = S => (S.сцена ? место(S.сцена.место).модуль.ходов - S.сцена.ходы : 0);

function условие(S, у) {
  if (!у) return true;
  const м = S.мир;
  if (у.подтверждена && верностьТемы(S, у.подтверждена) !== ПОДТВЕРЖДЕНО) return false;
  if (у.тема && !м.темы.includes(у.тема)) return false;
  if (у.свидетельство && !(м.свидетельства ?? []).includes(у.свидетельство)) return false;
  if (у.распол && (м.люди[у.распол.кто]?.распол ?? 0) < у.распол.от) return false;
  if (у.деньОт !== undefined && м.день < у.деньОт) return false;
  if (у.деньДо !== undefined && м.день > у.деньДо) return false;
  if (у.чётный && м.день % 2 !== 0) return false;
  if (у.нечётный && м.день % 2 === 0) return false;
  if (у.флаг && !(м.флаги ?? []).includes(у.флаг)) return false;
  if (у.ходовОсталось !== undefined && ходовОсталось(S) < у.ходовОсталось) return false;
  if (у.делоГотово && !делоГотово(S, у.делоГотово)) return false;
  return true;
}

function подходитГде(ш, ctx) {
  const г = ш.где;
  if (г.район !== undefined) return ctx.вид === 'город' && г.район === ctx.район;
  if (г.кто) return ctx.вид === 'разговор' && г.место === ctx.место && г.кто === ctx.кто;
  return ctx.вид === 'комната' && г.место === ctx.место && г.комната === ctx.комната;
}

// ── вещи дела ──────────────────────────────────────────────────────────────
function выдатьВещь(S, р, в) {
  if (!положить(S, в.вещь, 1, { происхождение: 'дело', дело: р.id })) return false;
  const x = привестиВещи(S).filter(y => y.тип === в.вещь && y.дело === р.id).at(-1);
  р.вещь = x?.uid ?? null;
  р.вещьТип = в.вещь;
  return true;
}

// Что несёшь по этому делу. «Свежая» вещь (пирог) — купленная сегодня и не лежавшая в сумке к моменту, когда дело взято.
function найтиВещьДела(S, р, треб) {
  const сумка = привестиВещи(S);
  if (треб.свежая) {
    return сумка.find(x => x.тип === треб.вещь && x.создано === S.мир.день
      && ['рынок', 'прилавок: торговый'].includes(x.происхождение)
      && !(р.данные?.былоВСумке ?? []).includes(x.uid)) ?? null;
  }
  return сумка.find(x => x.тип === треб.вещь && x.дело === р.id) ?? null;
}

function убратьВещиДела(S, id) {
  const г = S.герой;
  привестиВещи(S);
  for (const список of [г.при_себе, г.хранилище.вдова, г.хранилище.угол]) {
    for (let i = список.length - 1; i >= 0; i--) if (список[i].дело === id) список.splice(i, 1);
  }
  if (г.рука && !г.при_себе.some(x => x.uid === г.рука)) г.рука = null;
}

// ok | нет (вещи нигде нет) | испорчено (вещь сменила вид: миска остыла)
function сверитьВещь(S, р) {
  if (!р.вещь) return 'ок';
  const г = S.герой;
  привестиВещи(S);
  const x = [...г.при_себе, ...г.хранилище.вдова, ...г.хранилище.угол].find(y => y.uid === р.вещь);
  if (!x) return 'нет';
  return x.тип === р.вещьТип ? 'ок' : 'испорчено';
}

// ── жизненный цикл ─────────────────────────────────────────────────────────
function создатьЗапись(S, id, статус) {
  const р = { id, тип: ДЕЛА[id].тип === 'помоги' ? 'помощь' : ДЕЛА[id].тип, статус, шаг: null, предложено: S.мир.день, принято: null, срок_до: null, закрыто: null, вещь: null, вещьТип: null, итог: null, данные: {} };
  записи(S).push(р);
  return р;
}

function принятьДело(S, р, д, выдача) {
  р.статус = 'активно';
  р.принято = S.мир.день;
  р.срок_до = д.срок === null || д.срок === undefined ? null : S.мир.день + д.срок;
  р.данные.былоВСумке = привестиВещи(S).map(x => x.uid);
  if (выдача) выдатьВещь(S, р, выдача);
  журнал(S, `Дело «${д.имя}»: взял${р.срок_до === null ? '' : `, срок — до конца дня ${р.срок_до}`}`);
}

function закрыть(S, р, статус, итог, выплата = 0) {
  р.статус = статус;
  р.закрыто = S.мир.день;
  р.шаг = null;
  р.итог = статус === 'готово' && р.тип === 'помощь' ? { выплата, выбор: выплата > 0 ? 'взял плату' : 'помог без платы', день: S.мир.день, описание: итог ?? статус } : (итог ?? статус);
  if (статус === 'готово' && р.тип === 'помощь' && выплата === 0) отметитьФакт(S, 'помог_без_платы', { дело: р.id });
}

// Эффект на языке Движок/эффекты.js; свидетельство — отдельная запись «что ты видел или слышал».
function применитьЭ(S, э) {
  if (!э) return [];
  const { свидетельство, ...остальное } = э;
  const строки = применитьЭффект(S, остальное, { источник: 'нить', откуда: 'дело' });
  if (свидетельство) {
    S.мир.свидетельства ??= [];
    if (!S.мир.свидетельства.includes(свидетельство)) S.мир.свидетельства.push(свидетельство);
  }
  return строки;
}
const сКвадратными = строки => (строки.length ? ` (${строки.join(', ')})` : '');

// Провал: срок вышел, вещь пропала или испортилась. Последствия — из данных дела; «шанс» бросает движок.
export function провалитьДело(S, р, причина, итог = null) {
  const д = ДЕЛА[р.id];
  const п = д.провал?.[причина === 'нет' ? 'потеря' : 'срок'] ?? д.провал?.срок ?? д.провал?.потеря ?? null;
  закрыть(S, р, причина === 'срок' || причина === 'испорчено' ? 'просрочено' : 'провалено', причина);
  убратьВещиДела(S, р.id);
  if (п?.эффект) применитьЭ(S, п.шанс === undefined ? п.эффект : { шанс: п.шанс, тогда: п.эффект, иначе: null });
  const строка = п?.строка ?? `Дело «${д.имя}» не выполнено`;
  if (итог) итог.причины.push(строка); else журнал(S, строка);
}

// Конец дня (Движок/время.js): потерянные и испорченные вещи, истёкшие сроки, повисшие предложения «на сегодня».
export function проверитьСроки(S, итог) {
  for (const р of [...записи(S)]) {
    const д = ДЕЛА[р.id];
    if (!д) continue;
    if (р.статус === 'предложено' && д.срок === 0) { записи(S).splice(записи(S).indexOf(р), 1); continue; } // просьба «на этот заход» не переживает день
    if (р.статус !== 'активно') continue;
    const вещь = сверитьВещь(S, р);
    if (вещь !== 'ок') { провалитьДело(S, р, вещь, итог); continue; }
    if (р.срок_до !== null && р.срок_до <= S.мир.день) провалитьДело(S, р, 'срок', итог);
  }
}

// ── кнопки ─────────────────────────────────────────────────────────────────
function причинаНельзя(S, р, ш, ctx) {
  if (ш.подход && ctx.подход !== ш.подход) return 'Не тот тон для такого разговора';
  if (ш.стоит && S.герой.кошель < ш.стоит) return 'Нет денег';
  for (const н of ш.нужно ?? []) if (!условие(S, н.у)) return н.почему;
  const выдача = ш.выдать ?? ш.принять?.выдать;
  if (выдача && !можноПоложить(S, выдача.вещь)) return 'Нет места в сумке';
  if (ш.требует && р && !найтиВещьДела(S, р, ш.требует)) {
    return ш.требует.свежая ? 'Нужен свежий пирог, купленный сегодня' : `Нет при себе: ${имяВещи(ш.требует.вещь)}`;
  }
  if (ctx.вид !== 'город' && ш.ход && ходовОсталось(S) < ш.ход) return 'Не хватит времени';
  return null;
}

const срокСловами = д => (д.срок === null || д.срок === undefined ? 'без срока' : д.срок === 0 ? 'на этот заход' : `срок: ${д.срок === 1 ? 'сегодня и завтра' : `${д.срок + 1} дн.`}`);

function кнопка(id, ш, ctx, поля) {
  return { вид: 'дело', ход: ш.ход ?? 0, отрезков: 0, группа: 'на ходу', ...поля, id };
}

// Выполнение шага: единое место, где платят, сдают вещь, получают награду и двигают дело дальше.
function выполнитьШаг(S, id, ш, ctx) {
  const д = ДЕЛА[id];
  let р = запись(S, id);
  if (ш.предложение ? !!р : р ? р.статус !== 'активно' || р.шаг !== ш.id : ш !== д.шаги[0]) return null;
  const можноСейчас = причинаНельзя(S, р, ш, ctx);
  if (можноСейчас) return null; // условие могло устареть между построением списка и кликом
  if (ш.стоит) S.герой.кошель -= ш.стоит;

  if (ш.предложение) {
    р = создатьЗапись(S, id, 'предложено');
    р.шаг = ш.следующий;
    return { текст: ш.текст, ход: ш.ход ?? 0 };
  }
  if (!р) {
    р = создатьЗапись(S, id, 'предложено');
    принятьДело(S, р, д, ш.выдать);
  } else if (ш.выдать && !выдатьВещь(S, р, ш.выдать)) {
    return null;
  }
  let текст = ш.текст, эффект = ш.эффект;
  if (ш.требует) {
    const x = найтиВещьДела(S, р, ш.требует);
    if (x.состояние?.вскрыто && ш.еслиВскрыто) { текст = ш.еслиВскрыто.текст ?? текст; эффект = ш.еслиВскрыто.эффект ?? эффект; }
    забрать(S, x.uid, 1);
    (S.мир.передано ??= []).push({ кому: ш.получатель ?? (ш.где.кто ? имяЧеловека(ш.где.кто) : д.кто), тип: x.тип, день: S.мир.день, дело: id });
    if (р.вещь === x.uid) р.вещь = null;
  }
  const строки = применитьЭ(S, эффект);
  if (ш.следующий) р.шаг = ш.следующий;
  else if (!ш.остаться) {
    закрыть(S, р, 'готово', 'выполнено', эффект?.гроши ?? 0);
    журнал(S, `Дело «${д.имя}»: выполнено${сКвадратными(строки)}`);
  }
  return { текст, ход: ш.ход ?? 0 };
}

// «Сведение»: тема должна быть подтверждена; что она стоит, решает то, куда она уже ушла.
function кнопкиСведения(S, id, д, р, ш, ctx) {
  const тема = ш.тема;
  const слух = верностьТемы(S, тема) !== ПОДТВЕРЖДЕНО;
  const уже = ушлоК(S, тема, ш.уходитК);
  const ножи = !уже && ушлоК(S, тема, 'ножи');
  const почемуНет = слух ? 'Пока только слух — нужно подтверждённое, а не чужие слова' : null;
  const безХода = ходовОсталось(S) < 1 ? 'Не хватит времени' : null;
  const годится = S2 => делоАктивно(S2, id) && запись(S2, id).шаг === ш.id && ходовОсталось(S2) >= 1 && верностьТемы(S2, тема) === ПОДТВЕРЖДЕНО;

  const завершить = (S2, текст, эффект) => {
    const строки = применитьЭ(S2, эффект);
    if (ш.тень) строки.push(...применитьЭ(S2, { тень: ш.тень }));
    закрыть(S2, запись(S2, id), 'готово', 'выполнено', эффект?.гроши ?? 0);
    журнал(S2, `Дело «${д.имя}»: выполнено${сКвадратными(строки)}`);
    return { текст, ход: 1 };
  };

  const деньги = кнопка(`дело:${id}:${ш.id}:деньги`, ш, ctx, {
    текст: ш.деньги.кнопка, подпись: ш.деньги.подпись, можно: !почемуНет && !безХода, почему: почемуНет ?? безХода,
    выполнить(S2) {
      if (!годится(S2)) return null;
      if (ушлоК(S2, тема, ш.уходитК)) { // прежняя продажа: ей это уже принесли — дело закрывается без награды и без новой утечки
        закрыть(S2, запись(S2, id), 'готово', 'уже знала');
        журнал(S2, `Дело «${д.имя}»: закрыто без награды — это уже продали ей раньше`);
        return { текст: ш.уже, ход: 1 };
      }
      const ножиУзнали = ушлоК(S2, тема, 'ножи'); // слив конкуренту: ножи узнали раньше — вдвое дешевле
      отметитьУшло(S2, тема, ш.уходитК);
      return завершить(S2, ножиУзнали ? ш.ножи.текст : ш.деньги.текст, ножиУзнали ? ш.ножи.эффект : ш.деньги.эффект);
    },
  });

  const причинаОбмена = почемуНет ?? (уже ? 'Это ей уже принесли' : ножи ? 'Ножи узнали раньше: менять не на что' : безХода);
  const обмен = кнопка(`дело:${id}:${ш.id}:обмен`, ш, ctx, {
    текст: ш.обмен.кнопка, подпись: ш.обмен.подпись, можно: !причинаОбмена, почему: причинаОбмена,
    выполнить(S2) {
      if (!годится(S2) || ушлоК(S2, тема, ш.уходитК) || ушлоК(S2, тема, 'ножи')) return null;
      const р2 = предложитьСведение(S2, место(ш.где.место).модуль.обмен, ш.где.место, тема);
      if (!р2.получена) return { текст: р2.реплика, ход: 1 }; // сделка не состоялась: дело остаётся открытым
      return завершить(S2, `${ш.обмен.текст}\n\n${р2.реплика}`, null);
    },
  });
  return [деньги, обмен];
}

// Все кнопки дел, живущие в этом контексте: ctx = { вид: 'разговор' | 'комната' | 'город', место, кто, комната, район, подход }.
export function действияДел(S, ctx) {
  const А = [];
  for (const [id, д] of Object.entries(ДЕЛА)) {
    if (д.ждёт) continue; // дела, которым ещё нужна точка на карте
    const р = запись(S, id);
    if (!р) {
      const ш = д.шаги[0];
      if (!подходитГде(ш, ctx) || !условие(S, ш.условие)) continue;
      А.push(...кнопкиШага(S, id, д, null, ш, ctx));
      continue;
    }
    if (р.статус === 'предложено') {
      const ш0 = д.шаги[0];
      if (!подходитГде(ш0, ctx)) continue;
      А.push(...кнопкиПредложения(S, id, д, р, ш0, ctx));
      continue;
    }
    if (р.статус !== 'активно') continue;
    const ш = д.шаги.find(x => x.id === р.шаг);
    if (!ш || !подходитГде(ш, ctx)) continue;
    А.push(...кнопкиШага(S, id, д, р, ш, ctx));
  }
  return А;
}

function кнопкиШага(S, id, д, р, ш, ctx) {
  if (ш.тип === 'сведение') return кнопкиСведения(S, id, д, р, ш, ctx);
  let шаг = ш;
  let суффикс = '';
  if (ш.варианты) {
    const в = ш.варианты[ctx.подход];
    if (!в) return [];
    шаг = { ...ш, ...в, подход: undefined };
    суффикс = `:${ctx.подход}`;
  }
  const почему = причинаНельзя(S, р, шаг, ctx);
  return [кнопка(`дело:${id}:${ш.id}${суффикс}`, шаг, ctx, {
    текст: шаг.кнопка, подпись: шаг.подпись ?? '', можно: !почему, почему,
    выполнить: S2 => выполнитьШаг(S2, id, шаг, ctx),
  })];
}

function кнопкиПредложения(S, id, д, р, ш0, ctx) {
  const выдача = ш0.принять?.выдать;
  const мало = выдача && !можноПоложить(S, выдача.вещь) ? 'Нет места в сумке' : null;
  return [
    кнопка(`дело:${id}:принять`, ш0, ctx, {
      текст: `Согласиться: ${д.имя}`, подпись: срокСловами(д), можно: !мало, почему: мало, ход: 0,
      выполнить(S2) {
        const р2 = запись(S2, id);
        if (!р2 || р2.статус !== 'предложено' || (выдача && !можноПоложить(S2, выдача.вещь))) return null;
        принятьДело(S2, р2, д, выдача);
        р2.шаг = ш0.следующий;
        return { текст: ш0.принять?.текст ?? '', ход: 0 };
      },
    }),
    кнопка(`дело:${id}:отказ`, ш0, ctx, {
      текст: 'Отказаться', подпись: '', можно: true, почему: null, ход: 0,
      выполнить(S2) {
        const р2 = запись(S2, id);
        if (!р2 || р2.статус !== 'предложено') return null;
        закрыть(S2, р2, 'отказано', 'отказ');
        применитьЭ(S2, д.отказ?.эффект);
        журнал(S2, `Дело «${д.имя}»: отказался`);
        return { текст: д.отказ?.строка ?? '', ход: 0 };
      },
    }),
  ];
}

// Бесплатные действия города: сдача вещи или сведения на месте.
export function действияДелВГороде(S) {
  if (S.сцена) return [];
  const ctx = { вид: 'город', район: S.мир.район };
  return действияДел(S, ctx).map(а => ({
    ...а,
    выполнить(S2) {
      const р = а.выполнить(S2);
      if (!р) return null;
      if (р.текст) журнал(S2, р.текст);
      return null;
    },
  }));
}

// ── журнал и миграция ──────────────────────────────────────────────────────
const ПОРЯДОК = { активно: 0, предложено: 1, готово: 2, просрочено: 2, провалено: 2, отказано: 2 };

export function сводкаДел(S) {
  const вых = [];
  for (const р of записи(S)) {
    const д = ДЕЛА[р.id];
    if (!д) continue;
    const ш = д.шаги.find(x => x.id === р.шаг);
    вых.push({
      id: р.id, имя: д.имя, тип: д.тип, статус: р.статус, слово: СЛОВА_СТАТУСОВ[р.статус], кто: д.кто, чего: д.чего,
      срок: р.статус === 'активно' ? (р.срок_до === null ? 'без срока' : `до конца дня ${р.срок_до}`) : null,
      следующий: р.статус === 'предложено' ? 'Решить: согласиться или отказаться' : р.статус === 'активно' ? (ш?.журнал ?? ш?.кнопка ?? '') : '',
      вещь: р.статус === 'активно' && р.вещьТип ? имяВещи(р.вещьТип) : null,
      день: р.закрыто ?? р.принято ?? р.предложено,
    });
  }
  return вых.sort((а, б) => ПОРЯДОК[а.статус] - ПОРЯДОК[б.статус] || б.день - а.день);
}

// Мягкая миграция: дела старых сохранений — пустой список; битые записи (неизвестный id) отбрасываются.
export function привестиДела(S) {
  const старые = S.мир.дела ?? [];
  S.мир.дела = (Array.isArray(старые) ? старые : Object.entries(старые).map(([id, запись]) => ({ id, ...запись }))).filter(р => р && typeof р.id === 'string');
  for (const р of S.мир.дела) if (ДЕЛА[р.id]) { р.тип ??= ДЕЛА[р.id].тип === 'помоги' ? 'помощь' : ДЕЛА[р.id].тип; р.данные ??= {}; р.вещь ??= null; р.вещьТип ??= null; р.срок_до ??= null; }
  return S.мир.дела;
}

