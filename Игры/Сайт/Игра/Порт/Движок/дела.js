// Статусы: предложено → активно → готово | просрочено | провалено; предложено → отказано. Закрытое дело не открывается снова.
// Три источника дел — доска, разговор и состояние мира — это разные шаги в данных; движок только предлагает кнопки там, где шаг «живёт».
