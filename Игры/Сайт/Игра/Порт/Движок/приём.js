// Приём у лекаря (карточка 5.7): осмотр → три вопроса → лечение. Состояние живёт в S.сцена.приём.
// Правда о теле берётся из состояния героя (данные/лекарь.js читает его, ничего не выдумывает). Лжи Ворн не замечает вслух,
// но лечит «не то, что было»: лечение слабее. Без DOM, имён нет — всё лежит в данные/лекарь.js.
import { ЦЕНА_ПО_ВИДУ, СКИДКА_ЗА_ОТВЕТЫ, ЛЕЧЕНИЕ, НАСТОЙКА, ФАКТЫ, ВОПРОСЫ, ПРОВЕРЯЕМЫЕ, ПЕРВЫЙ_ВОПРОС, СЛОВА } from '../Данные/лекарь.js';
import { бросок } from './случай.js';
import { МАКС } from './тело.js';
import { отметитьКризисТела } from './голос.js';
import { видОдежды } from './одежда.js';

const М = S => S.мир.места[S.сцена.место];
const тетрадь = S => ((М(S).память ??= {}).знает ??= []);
const счёт = S => (М(S).счётчики ??= {});

// Что про героя уже записано в тетради Ворна.
export const знаетЛекарь = S => S.мир.места.лекарь?.память?.знает ?? [];

function запомнить(S, id, текст) {
  const т = тетрадь(S);
  if (т.some(x => x.id === id)) return false;
  т.push({ id, текст });
  return true;
}

export const приёмИдёт = S => !!S.сцена?.приём;
export const этапПриёма = S => S.сцена?.приём?.этап ?? null;
export function вопросСейчас(S) {
  const п = S.сцена?.приём;
  if (!п || п.этап !== 'вопросы') return null;
  const id = п.вопросы[п.i];
  return id ? { id, ...ВОПРОСЫ[id] } : null;
}
export const естьЧтоЛечить = S => S.герой.тело.цел < МАКС || S.герой.рана > 0 || S.герой.боль > 0;

// Цена полного лечения: по «виду» одежды (бедному дешевле); за честные ответы — вполовину.
export function цены(S) {
  const вид = Math.max(0, Math.min(3, видОдежды(S)));
  const полная = ЦЕНА_ПО_ВИДУ[вид];
  return { полная, скидка: Math.max(1, Math.ceil(полная * СКИДКА_ЗА_ОТВЕТЫ)) };
}
export function ценаЛечения(S) {
  const ц = цены(S);
  return S.сцена?.приём?.режим === 'ответы' ? ц.скидка : ц.полная;
}

function выбрать(S, список, сколько) {
  const из = [...список], вышло = [];
  while (вышло.length < сколько && из.length) вышло.push(из.splice(Math.floor(бросок(S) * из.length), 1)[0]);
  return вышло;
}

export const строк = n => (n % 10 === 1 && n % 100 !== 11 ? 'строка' : [2, 3, 4].includes(n % 10) && ![12, 13, 14].includes(n % 100) ? 'строки' : 'строк');

// Осмотр: Ворн называет один–два факта о теле. Видимое он записывает в тетрадь сразу.
export function начатьПриём(S) {
  const названо = ФАКТЫ.filter(ф => ф.если(S)).slice(0, 2);
  const п = S.сцена.приём = { этап: 'режим', режим: null, факты: названо.map(ф => ф.id), вопросы: [ПЕРВЫЙ_ВОПРОС, ...выбрать(S, ПРОВЕРЯЕМЫЕ, 2)], i: 0, ложь: 0, правда: 0 };
  for (const ф of названо) запомнить(S, `видно:${ф.id}`, ф.текст);
  const ц = цены(S);
  S.сцена.комната = 'приём';
  S.сцена.реплика = `${СЛОВА.осмотр} «${названо.map(ф => ф.текст).join('. ')}.»\n\nДальше как хочешь: ответишь на мои вопросы — возьму ${ц.скидка} гр. вместо ${ц.полная}. Не ответишь — цена полная, лечу то, что видел.`;
  return п;
}

export function выбратьРежим(S, режим) {
  const п = S.сцена.приём;
  п.режим = режим;
  if (режим === 'молчать') {
    п.этап = 'исход';
    S.сцена.реплика = СЛОВА.молчать;
  } else {
    п.этап = 'вопросы';
    S.сцена.реплика = `${СЛОВА.вопросы}\n\n${вопросСейчас(S).текст}`;
  }
}

// Ответ на вопрос: проверяемый ответ либо правда (Ворн записывает факт), либо ложь (диагноз пойдёт мимо).
export function ответить(S, номер) {
  const п = S.сцена.приём, в = вопросСейчас(S);
  if (!в) return;
  const о = в.ответы[номер];
  if (!о) return;
  if (о.верно) {
    if (о.верно(S)) { п.правда += 1; запомнить(S, `ответ:${в.id}`, о.факт); }
    else { п.ложь += 1; счёт(S).лжи = (счёт(S).лжи ?? 0) + 1; }
  }
  п.i += 1;
  const следующий = вопросСейчас(S);
  const ответРеплика = о.реплика ?? 'Ворн записывает ответ, не поднимая глаз.';
  if (следующий) {
    S.сцена.реплика = `${ответРеплика}\n\n${следующий.текст}`;
  } else {
    п.этап = 'исход';
    S.сцена.реплика = `${ответРеплика}\n\n${СЛОВА.вопросыКонец}`;
  }
}

// Лечение. Диагноз верный (лжи нет): цел +2, рана и боль проходят. Соврал: цел +1, рана слабее, боль остаётся.
// Настойка Ворна одинакова для всех: цел +1 и боль проходит. «нет» — просто закончить приём.
export function лечить(S, как) {
  const п = S.сцена.приём, г = S.герой, т = г.тело;
  let текст = СЛОВА.ушёл;
  if (как === 'полное') {
    const точно = п.ложь === 0;
    т.цел = Math.min(МАКС, т.цел + (точно ? ЛЕЧЕНИЕ.цел : ЛЕЧЕНИЕ.послеЛжи));
    if (точно) { г.рана = 0; г.боль = 0; } else if (г.рана > 0) г.рана -= 1;
    текст = точно ? СЛОВА.точно : СЛОВА.мимо;
    счёт(S).лечений = (счёт(S).лечений ?? 0) + 1;
    if (!точно) счёт(S).мимо = (счёт(S).мимо ?? 0) + 1;
    S.мир.журналДня.push(точно ? 'Ворн вылечил точно: цел +2' : 'Ворн лечил не то, что было: цел +1');
  } else if (как === 'настойка') {
    т.цел = Math.min(МАКС, т.цел + НАСТОЙКА.цел);
    г.боль = 0;
    текст = СЛОВА.настойка;
    счёт(S).лечений = (счёт(S).лечений ?? 0) + 1;
    S.мир.журналДня.push('Настойка Ворна: цел +1');
  }
  if (как !== 'нет') отметитьКризисТела(S);
  const n = тетрадь(S).length;
  S.мир.журналДня.push(`В тетради Ворна про тебя ${n} ${строк(n)}`);
  S.сцена.приём = null;
  S.сцена.комната = 'кабинет-лекаря';
  S.сцена.реплика = `${текст}\n\nВ тетради про тебя теперь ${n} ${строк(n)}.`;
}
