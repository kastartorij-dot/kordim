// Только представление: стоимость и доступность приходят из движка.
import { ЖИЛЬЁ } from '../Данные/жильё.js';
export const КАТЕГОРИИ = [['места', 'Места'], ['работа', 'Работа'], ['быт', 'Еда и отдых'], ['товары', 'Товары'], ['дела', 'Дела']];
export function категорияДействия(д) {
  if (д.вид === 'место') return 'места';
  if (д.вид === 'работа') return 'работа';
  if (д.вид === 'дело' || д.вид === 'выдача' || д.вид === 'действие') return 'дела';
  if (д.группа === 'товары') return 'товары';
  if (д.группа === 'на ходу' || д.группа === 'услуги' || д.группа === 'ночлег' || д.вид === 'сон') return 'быт';
  return 'дела'; // новое действие не должно исчезнуть из интерфейса
}
// «N ход(а)» в подписях данных — деления той же шкалы дня (Р19): на экране ромбами, без слова.
export function ходыВРомбы(т) {
  return String(т ?? '')
    .replace(/(\d+) ход(?:а|ов)?(?![а-яё])/g, (_, n) => '◆'.repeat(Math.max(1, Math.min(+n, 6))))
    .replace(/не хватит ходов/g, 'не успеть до закрытия');
}
export const времяВПодписи = ч => /◆|^до (утра|дня|вечера|ночи)$|^кончится |без затрат|^ночь без сна$/.test(ч);
export function подписьДействия(д) {
  let подпись = ходыВРомбы(д.подпись ?? '');
  if (д.вид === 'место') {} // вход даром: время тратят вопросы и дела внутри (Р19)
  else if (д.id.startsWith('сон:')) подпись += ' · до утра';
  else if (!д.делений && !д.отрезков && !подпись.split(' · ').some(времяВПодписи)) подпись += ' · без затрат времени';
  return подпись.replace(/^ · /, '');
}
export function предупреждениеДействия(д, S) {
  if (д.id.startsWith('сон:')) {
    const сон = ЖИЛЬЁ.find(x => x.id === д.id.slice(4));
    if (сон?.риск) return 'Риск кражи: могут украсть половину кошеля.';
  }
  return '';
}
export function названиеДействия(д) {
  return д.id.startsWith('сон:') ? 'Спать: ' + д.текст : д.текст;
}
