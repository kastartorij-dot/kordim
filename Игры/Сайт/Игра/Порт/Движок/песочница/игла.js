function сгустить(сырые) {
  const точки = [сырые[0]];
  for (let k = 1; k < сырые.length; k++) {
    const a = сырые[k - 1];
    const b = сырые[k];
    const n = Math.max(1, Math.ceil(Math.hypot(b.x - a.x, b.y - a.y) / 4));
    for (let j = 1; j <= n; j++) точки.push({ x: a.x + (b.x - a.x) * j / n, y: a.y + (b.y - a.y) * j / n });
  }
  return точки;
}
