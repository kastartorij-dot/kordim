// Кости — с моряком. Как напёрстки: кость под кружкой, кружки тасуются, а рука моряка может
// тайком перекинуть кость под другую. Мухлюет он не в каждом коне, а руки то и дело поправляют
// кружки просто так. Поймай руку с бликом кости в момент подмены — или угадай кружку в конце.
// Обвинил честную руку — кон его. С каждой подменой он ловчее: блик короче, руки быстрее.
// Противник — вариант: обычный моряк, Горм (не мухлюет, но руки беспокойные), ловкач (редко и быстро),
// моряк под хмелем (часто, но неуклюже), хитрец (в пустых пальцах блестит медь — ловить надо белую кость).
import {
  ЦВЕТ, ШИР, ШРИФТ, звуки, ступеньНавыка, создатьПоле, картинка, фон, надпись, плашка, свет,
  портрет, ограничить, выбрать, звук,
} from './общее.js';

export const ОПИСЬ = { id: 'кости', имя: 'Кости', где: 'С моряком' };
export const СМЫСЛ = {
  плохо: 'Тебя обвели вокруг пальца — или ты зря обвинил честную руку. Кон за ним.',
  нормально: 'Ты не дал себя обыграть, но и верх не взял. Ничья по-честному.',
  отлично: 'Глаз не подвёл: ни одна кость не ушла от тебя. Кон твой.',
};

// мухлёж — в скольких конах из четырёх подмена (диапазон); темп — во сколько раз медленнее тасует;
// длит — длительность подмены; блик — с какой доли подмены блестит кость (меньше — дольше блестит);
// ловкость — с какой ловкости начинает; ныряний — сколько лишних обманок; медь — шанс, что в пустой руке блеснёт монета.
const НРАВ = {
  моряк: { мухлёж: [1, 3], темп: 1, длит: 1, блик: 0.25, ловкость: 0, ныряний: 0, медь: 0 },
  горм: { мухлёж: [0, 0], темп: 0.92, длит: 1, блик: 0.25, ловкость: 0, ныряний: 1, медь: 0 },
  ловкач: { мухлёж: [1, 1], темп: 0.86, длит: 0.85, блик: 0.32, ловкость: 2, ныряний: 1, медь: 0 },
  хмель: { мухлёж: [3, 3], темп: 1.18, длит: 1.3, блик: 0.18, ловкость: 0, ныряний: 0, медь: 0 },
  хитрец: { мухлёж: [1, 2], темп: 1, длит: 1, блик: 0.25, ловкость: 1, ныряний: 1, медь: 0.7 },
};
export const варианты = [
  { id: 'моряк', имя: 'Моряк с чужого корабля', кто: 'моряк', строка: 'Мухлюет не в каждом коне: руки то и дело поправляют кружки просто так, и только иногда пальцы уносят кость — тогда в них блестит.' },
  { id: 'горм', имя: 'Горм', кто: 'Горм', строка: 'Горм играет честно — но руки у него беспокойные, то и дело трогают кружки. Обвинишь зря — кон его. Следи за кружкой.' },
  { id: 'ловкач', имя: 'Ловкач', кто: 'ловкач', строка: 'Тасует быстро и мухлюет редко — может, раз за вечер. Блик короткий: моргнёшь — пропустишь.' },
  { id: 'хмель', имя: 'Моряк под хмелем', кто: 'моряк', строка: 'Выпил и мухлюет почти каждый кон, но неуклюже: кость в пальцах блестит долго. Не прозевай.' },
  { id: 'хитрец', имя: 'Хитрец', кто: 'хитрец', строка: 'В пустых пальцах у него блестит медный грош — на него и ловит. Хватай руку, только если блеснула белая кость.' },
];

const РАУНДОВ = 4;
const СЛОТЫ = [300, 480, 660];
const СТОЛ_У = 360;

let поКругу = 0;
export async function запустить(контейнер, { навык = 0, тихо = false, сигнал, вариант } = {}) {
  const н = ступеньНавыка(навык);
  звук.тихо = тихо;
  const вар = варианты.find(x => x.id === вариант) ?? варианты[поКругу++ % варианты.length];
  const нрав = НРАВ[вар.id];
  const поле = создатьПоле(контейнер, { подсказка: 'Следи за кружкой с костью. Блеснула кость в пальцах — кликни по руке. Зря обвинишь — кон его. В конце кликни по кружке с костью.', сигнал });
  const [зал, моряк] = await Promise.all([картинка('Ресурсы/Места/комната-с-общим-столом.png'), картинка('Ресурсы/Лица/port_moryak_pixel.png')]);

  const темп = (1 + 0.28 * н) * нрав.темп; // во сколько раз медленнее тасовка
  const подменаДлит = (0.4 + 0.18 * н) * нрав.длит;
  // В каких конах мухлюет: столько, сколько велит нрав, в случайных конах.
  const сколько = нрав.мухлёж[0] + Math.floor(Math.random() * (нрав.мухлёж[1] - нрав.мухлёж[0] + 1));
  const коны = [0, 1, 2, 3].sort(() => Math.random() - 0.5).slice(0, сколько);
  const мухлёж = Array.from({ length: РАУНДОВ }, (_, k) => коны.includes(k));
  let подмен = нрав.ловкость; // сколько раз уже мухлевал — с каждым разом ловчее

  let раунд = 0;
  let фаза = 'показ'; // показ | тасовка | выбор | ответ
  let вФазе = 0;
  let кружки = []; // { слот, x, y }
  let кость = 0; // индекс кружки, под которой кость
  let ходы = [];
  let ход = 0;
  let вХоде = 0;
  let поднято = 0;
  let наведено = -1;
  let ловля = 0; // >0 — рука показана, ловить можно
  let рука = null;
  const итоги = [];
  let реплика = '';
  let репликаЖизнь = 0;

  function сказать(s) {
    реплика = s;
    репликаЖизнь = 2.2;
  }

  function новыйРаунд() {
    кружки = СЛОТЫ.map((x, слот) => ({ слот, x, y: СТОЛ_У }));
    кость = Math.floor(Math.random() * 3);
    const обменов = 5 + раунд;
    const скорость = (0.62 - раунд * 0.08) * темп;
    ходы = [];
    // Рука ныряет к кружке несколько раз за кон: чаще впустую, в коне с мухлежом — один раз с костью.
    const ныряний = 1 + Math.floor(Math.random() * 2) + (раунд >= 2 ? 1 : 0) + нрав.ныряний;
    const места = new Set();
    while (места.size < ныряний) места.add(1 + Math.floor(Math.random() * (обменов - 1)));
    const настоящее = мухлёж[раунд] ? выбрать([...места]) : -1;
    const ловкость = Math.min(подмен, 3);
    for (let k = 0; k < обменов; k++) {
      const a = Math.floor(Math.random() * 3);
      const b = (a + 1 + Math.floor(Math.random() * 2)) % 3;
      ходы.push({ вид: 'обмен', a, b, длит: скорость });
      if (места.has(k)) {
        const длит = (подменаДлит + 0.25) * (1 - 0.1 * ловкость);
        const обман = k !== настоящее;
        ходы.push({ вид: 'подмена', обман, длит, блик: нрав.блик + 0.06 * ловкость, медь: обман && Math.random() < нрав.медь });
      }
    }
    ход = 0;
    вХоде = 0;
    фаза = 'показ';
    вФазе = 0;
    поднято = 1;
    рука = null;
    ловля = 0;
  }

  const слотX = слот => СЛОТЫ[слот];
  function кружкаНа(x, y) {
    return кружки.findIndex(к => Math.abs(x - к.x) < 62 && y > к.y - 120 * 1 && y < к.y + 20);
  }

  function кубик(ctx, x, y, s) {
    ctx.fillStyle = '#efe3c9';
    ctx.fillRect(x - s / 2, y - s, s, s);
    ctx.fillStyle = '#1a1309';
    for (const [dx, dy] of [[-0.25, -0.75], [0, -0.5], [0.25, -0.25]]) {
      ctx.beginPath();
      ctx.arc(x + dx * s, y + dy * s, s * 0.08, 0, Math.PI * 2);
      ctx.fill();
    }
  }

  function кружка(ctx, к, i, подъём) {
    const x = к.x;
    const y = к.y - подъём;
    const ярко = наведено === i && фаза === 'выбор';
    ctx.fillStyle = 'rgba(0,0,0,.35)';
    ctx.beginPath();
    ctx.ellipse(к.x, к.y + 4, 58 - подъём * 0.2, 12, 0, 0, Math.PI * 2);
    ctx.fill();
    const г = ctx.createLinearGradient(x - 50, 0, x + 50, 0);
    г.addColorStop(0, ярко ? '#8d8a80' : '#5d5b55');
    г.addColorStop(0.45, ярко ? '#d8d2c2' : '#a9a497');
    г.addColorStop(1, ярко ? '#77746b' : '#4a4843');
    ctx.fillStyle = г;
    ctx.beginPath();
    ctx.moveTo(x - 52, y);
    ctx.lineTo(x - 40, y - 104);
    ctx.lineTo(x + 40, y - 104);
    ctx.lineTo(x + 52, y);
    ctx.closePath();
    ctx.fill();
    ctx.fillStyle = ярко ? '#cfc8b6' : '#8f8a7e';
    ctx.fillRect(x - 54, y - 8, 108, 8);
    ctx.strokeStyle = ярко ? '#cfc8b6' : '#77736a';
    ctx.lineWidth = 7;
    ctx.beginPath();
    ctx.arc(x + 52, y - 56, 22, -Math.PI / 2, Math.PI / 2);
    ctx.stroke();
  }

  function кисть(ctx, x, y, наклон = 0) {
    ctx.save();
    ctx.translate(x, y);
    ctx.rotate(наклон);
    ctx.fillStyle = '#8a6448';
    ctx.fillRect(-16, -140, 32, 110);
    ctx.fillStyle = '#b08362';
    ctx.beginPath();
    ctx.ellipse(0, -18, 26, 22, 0, 0, Math.PI * 2);
    ctx.fill();
    for (let f = -2; f <= 1; f++) ctx.fillRect(f * 11 - 2, -6, 9, 22);
    ctx.restore();
  }

  function нарисовать(ctx, t) {
    фон(ctx, зал, 0.68);
    свет(ctx, 480, 260, 360, 0.18);
    // стол
    ctx.fillStyle = '#3a2817';
    ctx.beginPath();
    ctx.ellipse(480, 390, 420, 120, 0, 0, Math.PI * 2);
    ctx.fill();
    ctx.fillStyle = 'rgba(255,220,160,.05)';
    ctx.beginPath();
    ctx.ellipse(480, 380, 400, 100, 0, 0, Math.PI * 2);
    ctx.fill();
    // кость видна, когда кружки подняты
    const подъём = поднято * 90;
    if (поднято > 0.05) кубик(ctx, кружки[кость].x, кружки[кость].y - 2, 30);
    кружки.forEach((к, i) => кружка(ctx, к, i, подъём));
    // руки
    if (фаза === 'тасовка' && ходы[ход]) {
      const х = ходы[ход];
      if (х.вид === 'обмен') {
        кисть(ctx, кружки[х.a].x, кружки[х.a].y - 100, -0.15);
        кисть(ctx, кружки[х.b].x, кружки[х.b].y - 100, 0.15);
      } else if (рука) {
        // подмена: рука ныряет к краю кружки и уносит кость под другую
        const д = вХоде / х.длит;
        const из = кружки[рука.из];
        const в = кружки[рука.в];
        const x = из.x + (в.x - из.x) * ограничить((д - 0.25) / 0.5, 0, 1);
        const y = из.y - 20 - Math.sin(д * Math.PI) * 28;
        кисть(ctx, x, y + 18, (в.x === из.x ? рука.сторона : в.x > из.x ? 1 : -1) * 0.5);
        if (!х.обман && д > х.блик && д < 1 - х.блик) {
          // блик кости в пальцах — единственная примета
          ctx.fillStyle = `rgba(255,245,220,${0.5 + 0.5 * Math.sin(t * 40)})`;
          ctx.fillRect(x - 5, y + 10, 10, 10);
        } else if (х.медь && д > 0.3 && д < 0.7) {
          // у хитреца в пустой руке блестит медный грош — круглый и рыжий, не белый квадрат кости
          ctx.fillStyle = `rgba(214,140,70,${0.55 + 0.45 * Math.sin(t * 36)})`;
          ctx.beginPath();
          ctx.arc(x, y + 15, 6, 0, Math.PI * 2);
          ctx.fill();
        }
      }
    }
    // моряк
    const мх = ШИР - 175;
    ctx.fillStyle = 'rgba(8,12,14,.85)';
    ctx.fillRect(мх - 6, 12, 152, 172);
    if (вар.id === 'горм') {
      // портрета Горма нет — силуэт
      ctx.fillStyle = '#1a1714';
      ctx.beginPath();
      ctx.arc(мх + 70, 70, 34, 0, Math.PI * 2);
      ctx.fill();
      ctx.beginPath();
      ctx.roundRect(мх + 18, 104, 104, 56, 26);
      ctx.fill();
    } else портрет(ctx, моряк, мх, 18, 140, 140);
    надпись(ctx, вар.кто, мх + 70, 172, { р: 15, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.бумага2 });
    if (репликаЖизнь > 0) {
      ctx.globalAlpha = Math.min(1, репликаЖизнь);
      плашка(ctx, мх - 330, 60, 310, 40, { заливка: 'rgba(239,227,201,.92)', обвод: ЦВЕТ.чернила });
      надпись(ctx, `«${реплика}»`, мх - 175, 80, { р: 18, цвет: ЦВЕТ.чернила, тень: false });
      ctx.globalAlpha = 1;
    }
    // счёт
    плашка(ctx, 30, 24, 230, 60);
    надпись(ctx, `кон ${Math.min(раунд + 1, РАУНДОВ)} из ${РАУНДОВ}`, 46, 42, { р: 15, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.свеча, выр: 'left' });
    итоги.forEach((и, k) => {
      надпись(ctx, и.знак, 52 + k * 30, 66, { р: 20, цвет: и.цвет, вес: 700 });
    });
    const строка = { показ: 'Смотри, где кость…', тасовка: 'Следи за руками!', выбор: 'Где кость? Кликни по кружке.', ответ: '' }[фаза];
    if (строка) надпись(ctx, строка, 480, 120, { р: 30, шрифт: ШРИФТ.титул, вес: 700, цвет: фаза === 'выбор' ? ЦВЕТ.свеча : ЦВЕТ.бумага });
  }

  новыйРаунд();
  поле.кадр(нарисовать);
  await поле.старт({
    заголовок: `Кости · ${вар.имя}`,
    строка: `Кость под кружку — и тасовка, четыре кона. ${вар.строка} Увидел, как пальцы уносят кость, — кликни по руке. Иначе угадай кружку в конце.`,
  });

  function закрытьКон(очки, слово, цвет, знак) {
    итоги.push({ очки, цвет, знак });
    фаза = 'ответ';
    вФазе = 0;
    поле.слово(слово, 480, 200, цвет, 36);
  }

  поле.отладка = () => ({ вариант: вар.id, фаза, кость, кружки, рука, ход, ходы, итоги, мухлёж, раунд, руки: рукиСейчас() });

  // Где сейчас руки моряка — чтобы понять, по руке ли клик.
  function рукиСейчас() {
    const х = ходы[ход];
    if (фаза !== 'тасовка' || !х) return [];
    if (х.вид === 'обмен') return [кружки[х.a], кружки[х.b]].map(к => ({ x: к.x, y: к.y - 160 }));
    if (!рука) return [];
    const из = кружки[рука.из];
    const в = кружки[рука.в];
    return [{ x: из.x + (в.x - из.x) * ограничить((вХоде / х.длит - 0.25) / 0.5, 0, 1), y: из.y - 70 }];
  }

  return поле.играть({
    обновить(dt) {
      вФазе += dt;
      репликаЖизнь = Math.max(0, репликаЖизнь - dt);
      if (фаза === 'показ') {
        поднято = вФазе < 1.1 ? 1 : Math.max(0, 1 - (вФазе - 1.1) * 4);
        if (вФазе > 1.4) {
          фаза = 'тасовка';
          вФазе = 0;
          поднято = 0;
          звуки.стук();
        }
      } else if (фаза === 'тасовка') {
        const х = ходы[ход];
        вХоде += dt;
        const д = ограничить(вХоде / х.длит, 0, 1);
        if (х.вид === 'обмен') {
          const [a, b] = [кружки[х.a], кружки[х.b]];
          const ха = слотX(a.слот);
          const хб = слотX(b.слот);
          const с = (1 - Math.cos(д * Math.PI)) / 2;
          a.x = ха + (хб - ха) * с;
          b.x = хб + (ха - хб) * с;
          a.y = СТОЛ_У - Math.sin(д * Math.PI) * 26;
          b.y = СТОЛ_У + Math.sin(д * Math.PI) * 14;
        } else {
          if (!рука) {
            // обманка — рука поправляет случайную кружку и уходит; подмена — уносит кость
            const из = х.обман ? Math.floor(Math.random() * 3) : кость;
            const в = х.обман ? из : [0, 1, 2].filter(i => i !== кость)[Math.floor(Math.random() * 2)];
            рука = { из, в, сторона: Math.random() < 0.5 ? -1 : 1 };
            звуки.тик(0.12);
          }
          ловля = !х.обман && д > х.блик - 0.1 && д < 1.05 - х.блик ? 1 : 0;
        }
        if (вХоде >= х.длит) {
          if (х.вид === 'обмен') {
            const [a, b] = [кружки[х.a], кружки[х.b]];
            [a.слот, b.слот] = [b.слот, a.слот];
            a.x = слотX(a.слот);
            b.x = слотX(b.слот);
            a.y = b.y = СТОЛ_У;
            звуки.стук();
          } else {
            if (!х.обман) {
              кость = рука.в;
              подмен++;
            }
            рука = null;
            ловля = 0;
          }
          ход++;
          вХоде = 0;
          if (ход >= ходы.length) {
            фаза = 'выбор';
            вФазе = 0;
            сказать('Ну, где она?');
          }
        }
      } else if (фаза === 'ответ') {
        поднято = Math.min(1, вФазе * 4);
        if (вФазе > 1.5) {
          раунд++;
          if (раунд >= РАУНДОВ) поле.конец(итоги.reduce((с, и) => с + и.очки, 0) / РАУНДОВ);
          else новыйРаунд();
        }
      }
    },
    нарисовать,
    мышьДвиг(x, y) {
      наведено = кружкаНа(x, y);
    },
    мышьВниз(x, y) {
      if (фаза === 'тасовка') {
        const х = ходы[ход];
        const поРуке = рукиСейчас().some(р => Math.abs(x - р.x) < 70 && Math.abs(y - р.y) < 110);
        if (!поРуке) {
          поле.слово('кликай по руке', x, y - 30, ЦВЕТ.тихо, 18);
          return;
        }
        if (х.вид === 'подмена' && ловля && рука) {
          const из = кружки[рука.из];
          const в = кружки[рука.в];
          const рх = из.x + (в.x - из.x) * ограничить((вХоде / х.длит - 0.25) / 0.5, 0, 1);
          {
            кость = рука.из;
            рука = null;
            ход = ходы.length;
            звуки.ура();
            поле.вспышка(ЦВЕТ.свеча, 0.25);
            поле.дрожь(8);
            поле.искры(рх, СТОЛ_У - 40, ЦВЕТ.свеча, 24);
            сказать(вар.id === 'хитрец' ? 'Ишь. Медь не обманула.' : 'Ха! Глазастый.');
            закрытьКон(1, 'поймал за руку!', ЦВЕТ.свеча, '★');
            return;
          }
        }
        // та самая рука, но блик уже прошёл или ещё не начался — не поймал, но и не оклеветал
        if (х.вид === 'подмена' && !х.обман) {
          звуки.хлоп();
          поле.слово('не успел', x, y - 30, ЦВЕТ.тихо, 20);
          return;
        }
        // ложное обвинение: рука была чистая — моряк показывает пустые пальцы, кон его
        звуки.мимо();
        поле.дрожь(5);
        рука = null;
        ход = ходы.length;
        сказать(вар.id === 'горм' ? 'Пусто. Я не мухлюю.' : 'Пусто, видишь? Ставка моя.');
        закрытьКон(0, 'зря обвинил', ЦВЕТ.ржа, '!');
        return;
      }
      if (фаза !== 'выбор') return;
      const i = кружкаНа(x, y);
      if (i < 0) return;
      if (i === кость) {
        звуки.звон(1100);
        поле.кольцо(кружки[i].x, СТОЛ_У - 50, ЦВЕТ.трава, 90);
        сказать('Твоя взяла.');
        // Подмену проглядел, но кружку нашёл — меньше, чем поймать; честный кон угадан — полный.
        закрытьКон(мухлёж[раунд] ? 0.7 : 1, 'угадал', ЦВЕТ.трава, '✓');
      } else {
        звуки.мимо();
        поле.дрожь(5);
        сказать('Не та, приятель.');
        закрытьКон(0, 'не та', ЦВЕТ.ржа, '✗');
      }
    },
  }, [0.45, 0.8]);
}
