// Торг — у Пина. Пять ходов с откатом (клавиши 1–5 или клик по карточке): изъян, «дорого», похвалить,
// сделать вид, что уходишь, «по рукам». Довод работает, только когда Пин слушает, а внимание у него
// гуляет само и с разной скоростью. Давишь — портишь ему настрой; настрой низкий — он сам поднимает
// цену, высокий — сам уступает. Ниже своего предела Пин не пойдёт: вовремя сказать «по рукам» — тоже ход.
import {
  ЦВЕТ, ШИР, ШРИФТ, звуки, ступеньНавыка, создатьПоле, картинка, фон, надпись, плашка, полоса, свет,
  ограничить, случайно, выбрать, звук,
} from './общее.js';

export const ОПИСЬ = { id: 'торг', имя: 'Торг', где: 'У Пина' };
export const СМЫСЛ = {
  плохо: 'Пин обиделся или не уступил. Берёшь по его цене — или уходишь ни с чем.',
  нормально: 'Сторговались посередине. Пин ворчит, но торг ему понравился.',
  отлично: 'Цена твоя, и Пин не в обиде — он уважает тех, кто умеет торговаться.',
};

const ВРЕМЯ = 40;
const ПРОСИТ = 48;
const ХОЧЕШЬ = 30;

export async function запустить(контейнер, { навык = 0, тихо = false, сигнал } = {}) {
  const н = ступеньНавыка(навык);
  звук.тихо = тихо;
  const поле = создатьПоле(контейнер, { подсказка: 'Ходы — клавиши 1–5 или клик по карточке. Доводы действуют, когда Пин слушает. Вовремя скажи «по рукам».', сигнал });
  const лавка = await картинка('Ресурсы/Места/lavka.webp');

  const предел = 30 + Math.floor(Math.random() * 7); // ниже Пин не уступит, игрок не знает
  const порог = 0.6 - 0.07 * н; // выше — Пин слушает
  const откатК = 1 - 0.15 * н;
  const подсказкаПредела = н === 2 ? `Чутьё: ниже ${предел - 1}–${предел + 1} он не пойдёт.`
    : н === 1 ? `Чутьё: ниже ${предел - 3}–${предел + 3} он вряд ли пойдёт.` : '';

  let цена = ПРОСИТ;
  let настрой = 0.55;
  let внимание = 0.5;
  let фаза = Math.random() * 10;
  let темп = 1;
  let доТемпа = 3;
  let доХодаПина = случайно(5, 7);
  let изъянов = 3;
  let ушёл = false;
  let реплика = '';
  let репликаЖизнь = 0;
  let тепло = 0;
  let наведено = -1;
  let ходов = 0;

  const ХОДЫ = [
    { имя: 'Изъян', что: 'указать на брак', откат: 5 },
    { имя: '«Дорого»', что: 'давить ценой', откат: 2.5 },
    { имя: 'Похвалить', что: 'товар и лавку', откат: 6 },
    { имя: 'Уйти', что: 'сделать вид · раз', откат: 0 },
    { имя: 'По рукам', что: 'взять по этой цене', откат: 0 },
  ].map(х => ({ ...х, остыл: 0 }));
  const карта = k => ({ x: 70 + k * 168, y: 420, w: 150, h: 92 });

  const слушает = () => внимание > порог;
  function сказать(s) {
    реплика = s;
    репликаЖизнь = 2.6;
  }
  function сбавить(на, слово) {
    const было = цена;
    цена = Math.max(предел, цена - на);
    if (цена < было) {
      звуки.звон(980);
      поле.слово(`−${было - цена}`, 190, 104, ЦВЕТ.трава, 30);
      поле.кольцо(190, 104, ЦВЕТ.трава, 60);
      сказать(цена === предел ? 'Ниже — себе в убыток. Всё.' : слово);
    } else {
      настрой -= 0.15;
      поле.дрожь(4);
      звуки.мимо();
      сказать('Я же сказал: ниже не будет.');
    }
  }

  function нарисовать(ctx, t) {
    фон(ctx, лавка, 0.6);
    // Пин за прилавком: внимание — куда повёрнута голова, настрой — брови и рот
    const пх = 480;
    const пу = 196;
    const злость = ограничить(1 - настрой * 1.6, 0, 1);
    const поворот = (1 - ограничить(внимание / порог, 0, 1)) * 26;
    свет(ctx, пх, пу, 210, 0.1 + тепло * 0.18, злость > 0.6 ? '224,127,98' : '231,178,99');
    ctx.fillStyle = '#1a1714';
    ctx.beginPath();
    ctx.roundRect(пх - 110, пу + 44, 220, 140, 40);
    ctx.fill();
    ctx.beginPath();
    ctx.arc(пх + поворот, пу, 52, 0, Math.PI * 2);
    ctx.fill();
    ctx.strokeStyle = злость > 0.6 ? ЦВЕТ.ржа : ЦВЕТ.бумага2;
    ctx.lineWidth = 4;
    ctx.lineCap = 'round';
    const наклон = (злость - 0.3) * 14 - тепло * 6;
    const гх = пх + поворот * 1.5;
    ctx.beginPath();
    ctx.moveTo(гх - 28, пу - 14 - наклон);
    ctx.lineTo(гх - 8, пу - 14 + наклон);
    ctx.moveTo(гх + 28, пу - 14 - наклон);
    ctx.lineTo(гх + 8, пу - 14 + наклон);
    ctx.stroke();
    ctx.beginPath();
    const улыбка = (настрой - 0.45) * 22;
    ctx.moveTo(гх - 18, пу + 22);
    ctx.quadraticCurveTo(гх, пу + 22 + улыбка, гх + 18, пу + 22);
    ctx.stroke();
    ctx.fillStyle = '#2d2116';
    ctx.fillRect(0, 300, ШИР, 30);
    надпись(ctx, 'Пин', пх, 315, { р: 18, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.бумага2 });
    // внимание Пина
    const вx = 330;
    const вy = 348;
    const вw = 300;
    плашка(ctx, вx - 14, вy - 12, вw + 28, 50);
    ctx.fillStyle = 'rgba(255,236,200,.07)';
    ctx.fillRect(вx, вy, вw, 12);
    ctx.fillStyle = слушает() ? 'rgba(170,201,139,.55)' : 'rgba(170,201,139,.2)';
    ctx.fillRect(вx + порог * вw, вy, (1 - порог) * вw, 12);
    ctx.fillStyle = слушает() ? ЦВЕТ.трава : ЦВЕТ.бумага2;
    ctx.fillRect(вx + внимание * вw - 3, вy - 5, 6, 22);
    надпись(ctx, слушает() ? 'слушает' : 'отвлёкся', вx + вw / 2, вy + 28, { р: 15, шрифт: ШРИФТ.метка, цвет: слушает() ? ЦВЕТ.трава : ЦВЕТ.тихо });
    // цена
    плашка(ctx, 40, 30, 290, 150);
    надпись(ctx, 'Пин просит', 58, 52, { р: 15, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо, выр: 'left' });
    надпись(ctx, `${цена} гр.`, 58, 96, { р: 50, шрифт: ШРИФТ.титул, вес: 700, цвет: цена <= ХОЧЕШЬ + 2 ? ЦВЕТ.трава : ЦВЕТ.свеча, выр: 'left' });
    надпись(ctx, `ты хочешь ${ХОЧЕШЬ}`, 58, 136, { р: 16, цвет: ЦВЕТ.бумага2, выр: 'left' });
    if (подсказкаПредела) надпись(ctx, подсказкаПредела, 58, 162, { р: 14, цвет: ЦВЕТ.море, выр: 'left' });
    // настрой и время
    плашка(ctx, ШИР - 320, 30, 280, 96);
    надпись(ctx, 'настрой Пина', ШИР - 302, 52, { р: 15, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо, выр: 'left' });
    полоса(ctx, ШИР - 302, 64, 244, 12, настрой, настрой < 0.3 ? ЦВЕТ.ржа : настрой < 0.6 ? ЦВЕТ.свеча : ЦВЕТ.трава);
    надпись(ctx, 'время', ШИР - 302, 100, { р: 15, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо, выр: 'left' });
    полоса(ctx, ШИР - 236, 95, 178, 8, 1 - поле.t / ВРЕМЯ, ЦВЕТ.бумага2);
    // карточки ходов
    ХОДЫ.forEach((х, k) => {
      const к = карта(k);
      const нет = (k === 0 && изъянов <= 0) || (k === 3 && ушёл);
      const готов = х.остыл <= 0 && !нет;
      плашка(ctx, к.x, к.y, к.w, к.h, {
        заливка: наведено === k && готов ? 'rgba(231,178,99,.22)' : 'rgba(13,19,22,.88)',
        обвод: готов ? ЦВЕТ.свеча : ЦВЕТ.линия,
      });
      if (х.остыл > 0) {
        ctx.fillStyle = 'rgba(147,199,194,.16)';
        ctx.fillRect(к.x + 1, к.y + 1, (к.w - 2) * (х.остыл / (х.откат * откатК)), к.h - 2);
      }
      надпись(ctx, String(k + 1), к.x + 12, к.y + 18, { р: 15, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо, выр: 'left' });
      надпись(ctx, х.имя, к.x + к.w / 2, к.y + 42, { р: 22, шрифт: ШРИФТ.титул, вес: 700, цвет: готов ? ЦВЕТ.бумага : ЦВЕТ.тихо });
      const что = k === 0 ? `${х.что} · ${изъянов}` : х.что;
      надпись(ctx, что, к.x + к.w / 2, к.y + 70, { р: 14, цвет: готов ? ЦВЕТ.бумага2 : ЦВЕТ.тихо });
    });
    if (репликаЖизнь > 0) {
      ctx.globalAlpha = Math.min(1, репликаЖизнь);
      плашка(ctx, пх + 74, пу - 84, 330, 42, { заливка: 'rgba(239,227,201,.94)', обвод: ЦВЕТ.чернила });
      надпись(ctx, `«${реплика}»`, пх + 239, пу - 63, { р: 18, цвет: ЦВЕТ.чернила, тень: false });
      ctx.globalAlpha = 1;
    }
  }

  поле.кадр(нарисовать);
  await поле.старт({
    заголовок: 'Торг',
    строка: `Пин просит ${ПРОСИТ}, ты хочешь ${ХОЧЕШЬ}. Доводы доходят, когда он слушает — следи за его вниманием. Давишь — портится настрой, а злой Пин сам поднимает цену. Ниже своего предела он не пойдёт: вовремя скажи «по рукам».`,
  });

  function кончить(исход) {
    let о;
    if (исход === 'сошлись') {
      const доля = ограничить((ПРОСИТ - цена) / (ПРОСИТ - предел), 0, 1);
      о = 0.15 + 0.7 * доля + 0.15 * настрой;
    } else о = исход === 'обиделся' ? 0.1 : 0.15;
    поле.конец(о);
  }

  function ход(k) {
    if (поле.кончено) return;
    const х = ХОДЫ[k];
    if (!х || х.остыл > 0) return;
    if (k === 0 && изъянов <= 0) return поле.слово('изъянов больше не видно', 480, 400, ЦВЕТ.тихо, 18);
    if (k === 3 && ушёл) return;
    х.остыл = х.откат * откатК;
    ходов++;
    const к = карта(k);
    поле.кольцо(к.x + к.w / 2, к.y + к.h / 2, ЦВЕТ.свеча, 70);
    if (k === 0) {
      изъянов--;
      if (слушает()) {
        сбавить(3 + (Math.random() < 0.5 ? 1 : 0), выбрать(['Хм. Тут ты прав.', 'Ну, шов не лучший…', 'Ладно, вижу.']));
        настрой -= 0.04;
      } else {
        настрой -= 0.06;
        звуки.тик(0.2);
        поле.слово('мимо ушей', 480, 270, ЦВЕТ.тихо, 24);
        сказать('А? Что ты там бормочешь?');
      }
    } else if (k === 1) {
      настрой -= слушает() ? 0.13 : 0.24;
      поле.дрожь(3);
      сбавить(2, выбрать(['Грабишь…', 'Ну, ну. Ладно.', 'Режешь без ножа.']));
    } else if (k === 2) {
      настрой += слушает() ? 0.26 : 0.14;
      тепло = 1;
      звуки.звон(760);
      сказать(слушает() ? 'Глаз у тебя есть, это верно.' : 'Ну-ну.');
    } else if (k === 3) {
      ушёл = true;
      if (настрой >= 0.55) {
        звуки.ура();
        сбавить(5, 'Стой! Ладно, ладно…');
      } else {
        сказать('Ну и иди.');
        звуки.мимо();
        поле.слово('он не окликнул', 480, 270, ЦВЕТ.ржа, 30);
        кончить('ушёл');
      }
    } else if (k === 4) {
      сказать('По рукам.');
      звуки.ура();
      поле.вспышка(ЦВЕТ.трава, 0.18);
      кончить('сошлись');
    }
    настрой = ограничить(настрой, 0, 1);
  }

  поле.отладка = () => ({ цена, предел, настрой, внимание, порог, слушает: слушает(), изъянов, ушёл, ходы: ХОДЫ.map(х => х.остыл), карта: ХОДЫ.map((_, k) => карта(k)) });

  return поле.играть({
    обновить(dt, t) {
      // Пин сам меняет темп: то смотрит на тебя, то на улицу, то быстро, то медленно
      доТемпа -= dt;
      if (доТемпа <= 0) {
        темп = случайно(0.6, 1.9);
        доТемпа = случайно(2, 4.5);
      }
      фаза += dt * темп;
      внимание = ограничить(0.5 + Math.sin(фаза * 1.1) * 0.32 + Math.sin(фаза * 2.6 + 1) * 0.14 - (0.5 - настрой) * 0.25, 0, 1);
      for (const х of ХОДЫ) х.остыл = Math.max(0, х.остыл - dt);
      репликаЖизнь = Math.max(0, репликаЖизнь - dt);
      тепло = Math.max(0, тепло - dt * 0.8);
      // настрой понемногу возвращается к середине
      настрой += (0.5 - настрой) * dt * 0.03;
      // свой ход Пина: доволен — сам уступает, зол — поднимает цену
      доХодаПина -= dt;
      if (доХодаПина <= 0) {
        доХодаПина = случайно(5, 8);
        if (настрой > 0.68 && цена > предел) {
          сбавить(1, 'Ладно, для тебя…');
        } else if (настрой < 0.3 && цена < ПРОСИТ) {
          цена = Math.min(ПРОСИТ, цена + 2);
          звуки.ох();
          поле.слово('+2', 190, 104, ЦВЕТ.ржа, 30);
          сказать(`Что-то ты мне не нравишься. ${цена}.`);
        } else if (ходов === 0) {
          сказать('Ну? Берёшь или смотришь?');
        }
      }
      if (настрой <= 0) {
        сказать('Всё. Иди отсюда.');
        поле.дрожь(10);
        звуки.мимо();
        кончить('обиделся');
      } else if (t >= ВРЕМЯ) {
        if (настрой >= 0.25) {
          сказать(`Последнее слово — ${цена}.`);
          кончить('сошлись');
        } else {
          сказать('Хватит. Не продам.');
          кончить('время');
        }
      }
    },
    нарисовать,
    мышьДвиг(x, y) {
      наведено = ХОДЫ.findIndex((_, k) => {
        const к = карта(k);
        return x >= к.x && x <= к.x + к.w && y >= к.y && y <= к.y + к.h;
      });
    },
    мышьВниз(x, y) {
      const k = ХОДЫ.findIndex((_, k) => {
        const к = карта(k);
        return x >= к.x && x <= к.x + к.w && y >= к.y && y <= к.y + к.h;
      });
      if (k >= 0) ход(k);
    },
    клавиша(код) {
      const k = ['Digit1', 'Digit2', 'Digit3', 'Digit4', 'Digit5'].indexOf(код);
      if (k >= 0) ход(k);
    },
  }, [0.45, 0.8]);
}
