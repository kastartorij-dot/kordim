const ПК = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 };
const частота = m => 440 * Math.pow(2, (m - 69) / 12);
function нота(s) {
  const м = /^([A-G])(#|b)?(\d)$/.exec(s);
  if (!м) throw new Error('нота: ' + s);
  return 12 * (Number(м[3]) + 1) + ПК[м[1]] + (м[2] === '#' ? 1 : м[2] === 'b' ? -1 : 0);
}
// Аккорд: тоны лютни (около соль малой — фа-диез первой) и бас октавой ниже.
function аккорд(имя) {
  const м = /^([A-G])(#|b)?(m)?(7)?$/.exec(имя);
  let r = 48 + ПК[м[1]] + (м[2] === '#' ? 1 : м[2] === 'b' ? -1 : 0);
  if (r < 55) r += 12;
  const тоны = [r, r + (м[3] ? 3 : 4), r + 7];
  if (м[4]) тоны.push(r + 10);
  return { тоны, бас: r - 12, квинта: r - 5 };
}
// Ноты строки: [{ д (доля от начала строки), m, дл (в долях) }], паузы пропускаются.
function разобрать(s) {
  const out = [];
  let д = 0;
  for (const tok of s.trim().split(/\s+/)) {
    const [н, дл] = tok.split('/');
    const длит = Number(дл);
    if (н !== '-') out.push({ д, m: нота(н), дл: длит });
    д += длит;
  }
  return { ноты: out, долей: д };
}
// Высота дорожки — место ноты в строке: самая низкая — низко, самая высокая — высоко.
function дорожки(ноты) {
  const разные = [...new Set(ноты.map(н => н.m))].sort((a, b) => a - b);
  return ноты.map(н => (разные.length < 2 ? 1 : Math.round(2 * разные.indexOf(н.m) / (разные.length - 1))));
}

// Песня целиком: такты (аккорд, чей), строка Норы (зов) и ответ зала — время в секундах от первой доли.
function разложить(п) {
  const ДОЛЯ = 60 / п.темп;
  const такты = [];
  const зов = [];
  const ответ = [];
  let д0 = 0;
  const положить = (куда, строка, аккорды, чей, смещение = 0) => {
    const { ноты, долей } = строка;
    const тактов = Math.round(долей / п.вТакте);
    const h = дорожки(ноты);
    ноты.forEach((н, k) => куда.push({ t: (д0 + н.д) * ДОЛЯ, m: н.m + смещение, f: частота(н.m + смещение), длит: н.дл * ДОЛЯ * 0.92, h: h[k] }));
    for (let i = 0; i < тактов; i++) такты.push({ аккорд: аккорд([].concat(аккорды)[i] ?? [].concat(аккорды).at(-1)), чей });
    д0 += тактов * п.вТакте;
  };
  п.строки.forEach(([аккорды, s], k) => {
    const строка = разобрать(s);
    положить(зов, строка, аккорды, 'зов');
    if (п.ответ === 'припев') {
      const [ак, ps] = п.припевы[k % п.припевы.length];
      положить(ответ, разобрать(ps), ак, 'ответ', -12);
    } else if (п.ответ === 'назад') {
      const высоты = строка.ноты.map(н => н.m).reverse();
      положить(ответ, { ноты: строка.ноты.map((н, i) => ({ ...н, m: высоты[i] })), долей: строка.долей }, аккорды, 'ответ', -12);
    } else {
      положить(ответ, строка, аккорды, 'ответ', -12);
    }
  });
  return { ДОЛЯ, ТАКТ: ДОЛЯ * п.вТакте, такты, зов, ответ, финал: аккорд(п.финал) };
}

// ---------- инструменты ----------
const щипок = (m, через, громк = 0.14, длит = 0.7) => {
  тон(частота(m), { длит, тип: 'triangle', громк, через });
  тон(частота(m) * 2, { длит: длит * 0.35, тип: 'sine', громк: громк * 0.3, через });
};
const бас = (m, через, длит, громк = 0.45) => {
  тон(частота(m), { длит, тип: 'sine', громк, через });
  тон(частота(m) * 2, { длит: 0.22, тип: 'triangle', громк: громк * 0.16, через });
};
const бой = (ак, через, громк) => ак.тоны.forEach((m, k) => щипок(m, через + k * 0.016, громк, 0.55));

// Аккомпанемент одного такта. через — секунды до его первой доли; живо — 0…1, насколько зал подхватил.
function сыгратьТакт(п, Р, такт, через, живо, тихийЗал) {
  const Д = Р.ДОЛЯ;
  const а = такт.аккорд;
  const стук = (д, сила) => { if (!тихийЗал) звуки.удар(через + д * Д, сила * (0.45 + живо * 0.5)); };
  const хлоп = д => { if (!тихийЗал && живо > 0.25) звуки.хлоп(через + д * Д); };
  switch (п.аккомп) {
    case 'вальс':
      бас(а.бас, через, Д * 2.4, 0.42);
      щипок(а.тоны[1], через + Д, 0.1, 0.5); щипок(а.тоны[2], через + Д + 0.01, 0.08, 0.5);
      щипок(а.тоны[1], через + Д * 2, 0.08, 0.5); щипок(а.тоны[2], через + Д * 2 + 0.01, 0.06, 0.5);
      стук(0, 0.5);
      break;
    case 'рабочая':
      бас(а.бас, через, Д * 1.6, 0.5); бас(а.квинта, через + Д * 2, Д * 1.6, 0.38);
      бой(а, через, 0.12); бой(а, через + Д * 2, 0.09);
      стук(0, 1); стук(2, 0.75); хлоп(1); хлоп(3);
      break;
    case 'джига':
      бас(а.бас, через, Д * 2.5, 0.45); бас(а.квинта, через + Д * 3, Д * 2.5, 0.34);
      щипок(а.тоны[1], через + Д * 2, 0.09, 0.35); щипок(а.тоны[2], через + Д * 2 + 0.01, 0.07, 0.35);
      щипок(а.тоны[1], через + Д * 5, 0.09, 0.35); щипок(а.тоны[2], через + Д * 5 + 0.01, 0.07, 0.35);
      стук(0, 0.9); стук(3, 0.65); хлоп(2); хлоп(5);
      break;
    case 'плач':
      голос(частота(а.бас), { длит: Д * 4.1, через, громк: 0.07, яркость: 650, тип: 'sawtooth', вибрато: 0.002 });
      бас(а.бас, через, Д * 3, 0.3);
      [а.тоны[0], а.тоны[2], а.тоны[0] + 12, а.тоны[1]].forEach((m, k) => щипок(m, через + k * Д, 0.08, 1.1));
      break;
    default: // застольная
      бас(а.бас, через, Д * 1.6, 0.46); бас(а.квинта, через + Д * 2, Д * 1.6, 0.34);
      бой(а, через + Д, 0.08); бой(а, через + Д * 3, 0.08);
      стук(0, 0.8); стук(2, 0.55); хлоп(3); хлоп(3.5);
  }
}

// Метки игрока: при подпевании — ответ зала; при стуке — доли всех тактов.
function меткиИгры(п, Р, стук) {
  if (!стук) return Р.ответ.map(м => ({ ...м, струна: м.h, итог: null }));
  const [рано, позже] = СТУК[п.аккомп];
  const метки = [];
  Р.такты.forEach((_, т) => {
    for (const д of т < 4 ? рано : позже) метки.push({ t: (т * п.вТакте + д) * Р.ДОЛЯ, h: 1, струна: 0, f: 0, итог: null });
  });
  return метки;
}

