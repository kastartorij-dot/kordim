// ── сетка путей: где можно ходить и сколько идти до каждой двери ──────────────
function сетка(место) {
  const w = Math.ceil(ШИР / КЛ), h = Math.ceil(ВЫС / КЛ);
  const можно = new Uint8Array(w * h);
  for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) {
    const x = i * КЛ + КЛ / 2, y = j * КЛ + КЛ / 2;
    const внутри = место.дома.some(д => x > д.x - R + 2 && x < д.x + д.w + R - 2 && y > д.y - R + 2 && y < д.y + д.h + R - 2);
    можно[j * w + i] = !внутри && y > ВЕРХ + R - 4 && y < НИЗ - R + 4 ? 1 : 0;
  }
  // расстояние от точки до всех клеток (Дейкстра на 8 соседей)
  const поле = (x0, y0) => {
    const д = new Float32Array(w * h).fill(Infinity);
    const ci = ограничить(Math.floor(x0 / КЛ), 0, w - 1), cj = ограничить(Math.floor(y0 / КЛ), 0, h - 1);
    const старт = ближайшая(ci, cj);
    д[старт] = 0;
    const оч = [старт];
    while (оч.length) {
      let k = 0;
      for (let q = 1; q < оч.length; q++) if (д[оч[q]] < д[оч[k]]) k = q;
      const c = оч.splice(k, 1)[0];
      const i = c % w, j = (c - i) / w;
      for (let dj = -1; dj <= 1; dj++) for (let di = -1; di <= 1; di++) {
        if (!di && !dj) continue;
        const ni = i + di, nj = j + dj;
        if (ni < 0 || nj < 0 || ni >= w || nj >= h) continue;
        const n = nj * w + ni;
        if (!можно[n] || (di && dj && (!можно[j * w + ni] || !можно[nj * w + i]))) continue;
        const нд = д[c] + (di && dj ? 1.414 : 1) * КЛ;
        if (нд < д[n]) { if (д[n] === Infinity) оч.push(n); д[n] = нд; }
      }
    }
    return д;
  };
  function ближайшая(ci, cj) {
    let лучшая = cj * w + ci, мин = Infinity;
    for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) if (можно[j * w + i]) {
      const r = (i - ci) ** 2 + (j - cj) ** 2;
      if (r < мин) { мин = r; лучшая = j * w + i; }
    }
    return лучшая;
  }
  const клетка = (x, y) => ограничить(Math.floor(y / КЛ), 0, h - 1) * w + ограничить(Math.floor(x / КЛ), 0, w - 1);
  // Следующая точка по полю расстояний от (x, y) к цели — для бота и стрелки.
  const следующая = (д, x, y) => {
    const c = клетка(x, y), i = c % w, j = (c - i) / w;
    let лучшая = null, мин = д[c];
    for (let dj = -1; dj <= 1; dj++) for (let di = -1; di <= 1; di++) {
      const ni = i + di, nj = j + dj;
      if (ni < 0 || nj < 0 || ni >= w || nj >= h) continue;
      const n = nj * w + ni;
      if (д[n] < мин) { мин = д[n]; лучшая = { x: ni * КЛ + КЛ / 2, y: nj * КЛ + КЛ / 2 }; }
    }
    return лучшая;
  };
  return { поле, клетка, следующая };
}

