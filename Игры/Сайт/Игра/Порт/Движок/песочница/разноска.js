  function итог() {
    if (кончено) return;
    кончено = true;
    const q = свёртки.reduce((с, x) => с + (x.отдан ? x.q * (x.поздно ? 0.5 : 1) : 0), 0) / свёртки.length;
    const скор = ограничить(1 - Math.max(0, время - пар) / (1.3 * пар), 0, 1);
    поле.конец(0.6 * q + 0.4 * скор * (доставлено / свёртки.length) - Math.min(0.35, 0.05 * толчков) - 0.04 * задержан);
  }

  function двигать(dt) {
    герой.стоп = Math.max(0, герой.стоп - dt);
    герой.собирает = Math.max(0, герой.собирает - dt);
    const шагом = поле.клавиши.has('ShiftLeft') || поле.клавиши.has('ShiftRight');
    const тяжесть = вКорзине().some(с => с.тяжёлый) ? 0.7 + 0.06 * н : 1;
    const вЛуже = лужи.some(л => ((герой.x - л.x) / л.rx) ** 2 + ((герой.y - л.y) / л.ry) ** 2 < 1);
    const vmax = V * тяжесть * (шагом ? 0.5 : 1) * (вЛуже && !П.скользко ? 0.6 : 1);
    let жx = 0, жy = 0;
    if (клавишами) {
      const к = поле.клавиши;
      жx = (к.has('ArrowRight') || к.has('KeyD') ? 1 : 0) - (к.has('ArrowLeft') || к.has('KeyA') ? 1 : 0);
      жy = (к.has('ArrowDown') || к.has('KeyS') ? 1 : 0) - (к.has('ArrowUp') || к.has('KeyW') ? 1 : 0);
      const д = Math.hypot(жx, жy) || 1;
      жx = жx / д * vmax;
      жy = жy / д * vmax;
    } else if (поле.мышь.внутри) {
      const dx = поле.мышь.x - герой.x, dy = поле.мышь.y - герой.y;
      const д = Math.hypot(dx, dy);
      const с = Math.min(vmax, д * 4);
      if (д > 2) { жx = dx / д * с; жy = dy / д * с; }
    }
    const множ = герой.собирает > 0 ? 0 : герой.стоп > 0 ? 0.35 : 1;
    // скользко: разгон и торможение втрое слабее, в луже — ещё слабее
    const разгон = (П.скользко ? (вЛуже ? 160 : 300) : 900) * dt;
    герой.vx += ограничить(жx * множ - герой.vx, -разгон, разгон);
    герой.vy += ограничить(жy * множ - герой.vy, -разгон, разгон);
    // стены домов: по осям отдельно, чтобы скользить вдоль
    const nx = ограничить(герой.x + герой.vx * dt, R, ШИР - R);
    if (!внутриДома(nx, герой.y)) герой.x = nx; else герой.vx *= П.скользко ? -0.3 : 0;
    const ny = ограничить(герой.y + герой.vy * dt, ВЕРХ + R, НИЗ - R);
    if (!внутриДома(герой.x, ny)) герой.y = ny; else герой.vy *= П.скользко ? -0.3 : 0;
  }

  function шаг(dt) {
    время += dt;
    if (время >= конецДня) { поле.слово(квартал ? 'Лавки закрываются' : 'Рынок закрывается', ШИР / 2, ВЫС / 2, ЦВЕТ.ржа, 30); итог(); return; }
    if (волна) { волна.жизнь -= dt * 1.6; if (волна.жизнь <= 0) волна = null; }
    двигать(dt);
    // толпа
    for (const ч of люди) {
      ч.тол = Math.max(0, ч.тол - dt);
      if (ч.окрик > 0) {
        ч.окрик -= dt;
        const x = ч.x + ч.ox * 110 * dt, y = ч.y + ч.oy * 110 * dt;
        if (свободно(x, y, ч.r)) { ч.x = x; ч.y = y; }
      } else if (ч.пауза > 0) ч.пауза -= dt;
      else {
        const dx = ч.цх - ч.x, dy = ч.цу - ч.y;
        const д = Math.hypot(dx, dy);
        if (д < 8) { новаяЦель(ч); if (Math.random() < 0.4) ч.пауза = случайно(0.5, 2); }
        else {
          const x = ч.x + dx / д * ч.v * dt, y = ч.y + dy / д * ч.v * dt;
          if (свободно(x, y, ч.r)) { ч.x = x; ч.y = y; } else новаяЦель(ч);
        }
      }
    }
    for (const к of кучки) for (const ч of к.люди) ч.тол = Math.max(0, ч.тол - dt);
    for (const т of тележки) {
      т.тол = Math.max(0, т.тол - dt);
      т.x += т.dir * т.v * dt;
      if (т.x > ШИР - 60 || т.x < 100) т.dir *= -1;
    }
    const скорость = Math.hypot(герой.vx, герой.vy);
    // стража ходит по улице; бегущего мимо останавливает
    for (const с of стражи) {
      с.отдых = Math.max(0, с.отдых - dt);
      с.тол = Math.max(0, с.тол - dt);
      с.x += с.dir * 26 * dt;
      if (с.x > с.до || с.x < с.от) с.dir *= -1;
      const d = Math.hypot(герой.x - с.x, герой.y - с.y);
      if (d < 78 && скорость > 118 && с.отдых <= 0 && герой.собирает <= 0) {
        с.отдых = 5;
        задержан++;
        герой.стоп = 1.5;
        герой.vx *= 0.1; герой.vy *= 0.1;
        звуки.ох();
        поле.слово(выбрать(['Стой! Куда несёшься?', 'Не беги, разносчик!', 'А ну шагом!']), с.x, с.y - 30, ЦВЕТ.свеча, 20);
      }
    }
    // собака в переулке: подпускает близко — и кидается
    for (const с of собаки) {
      с.спит = Math.max(0, с.спит - dt);
      с.тол = Math.max(0, с.тол - dt);
      const dx = герой.x - с.x, dy = герой.y - с.y, d = Math.hypot(dx, dy);
      if (с.гонит > 0) {
        с.гонит -= dt;
        с.x += dx / (d || 1) * 190 * dt;
        с.y += dy / (d || 1) * 190 * dt;
        if (d < R + с.r && с.тол <= 0) {
          с.тол = 1; с.гонит = 0; с.спит = 6;
          укушен++;
          толкнул(с, true, ['гав!', 'р-р-р!']);
          герой.стоп = 0.9;
        }
      } else {
        const к = { x: с.дом.x - с.x, y: с.дом.y - с.y }, дк = Math.hypot(к.x, к.y);
        if (дк > 2) { с.x += к.x / дк * 60 * dt; с.y += к.y / дк * 60 * dt; }
        if (d < 78 - 8 * н && с.спит <= 0) { с.гонит = 1.3; с.спит = 6; звуки.стук(); поле.слово('гав!', с.x, с.y - 22, ЦВЕТ.ржа, 22); }
      }
    }
    // столкновения героя с людьми и телегами
    const все = [...люди, ...кучки.flatMap(к => к.люди), ...тележки, ...стражи];
    for (const ч of все) {
      const dx = герой.x - ч.x, dy = герой.y - ч.y;
      const д = Math.hypot(dx, dy) || 0.01;
      const мин = R + ч.r - 2 - н;
      if (д < мин) {
        const x = ч.x + dx / д * мин, y = ч.y + dy / д * мин;
        if (!внутриДома(x, y)) { герой.x = x; герой.y = y; }
        if (ч.тол <= 0 && скорость > 40) толкнул(ч, скорость > 120, undefined, скорость);
        герой.vx *= 0.3;
        герой.vy *= 0.3;
      }
    }
    // доставка: дошёл до двери с любым из свёртков
    if (герой.собирает <= 0) for (const с of вКорзине()) {
      if (Math.hypot(герой.x - с.точка.x, герой.y - с.точка.y) > 30) continue;
      с.отдан = true;
      с.поздно = с.срочно && время > срокСрочных;
      доставлено++;
      подряд = 0;
      const хорошо = с.q >= 0.85 && !с.поздно;
      звуки.звон(хорошо ? 1250 : 990);
      поле.кольцо(с.точка.x, с.точка.y, хорошо ? ЦВЕТ.трава : ЦВЕТ.свеча, 60);
      поле.слово(с.поздно ? 'поздно' : с.разбит ? 'битое' : хорошо ? 'держи!' : 'помятое', с.точка.x, с.точка.y + (с.точка.y < 200 ? 34 : -34), хорошо ? ЦВЕТ.трава : ЦВЕТ.свеча, 22);
      if (доставлено >= свёртки.length) { итог(); return; }
    }
  }

