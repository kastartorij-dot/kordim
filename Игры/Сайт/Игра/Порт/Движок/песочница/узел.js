// Узел — двор мастера. Мастер показывает, как ведёт конец каната: вверх, вбок, вниз — шаг за шагом.
// Потом твоя очередь: повтори те же движения по памяти — мазком мыши в нужную сторону или стрелками.
// Ошибся — канат соскользнул, шаг заново; задумался надолго — канат ослаб. Три узла, каждый длиннее.
import {
  ЦВЕТ, ШИР, ВЫС, ШРИФТ, звуки, ступеньНавыка, создатьПоле, картинка, фон, надпись, плашка, полоса,
  ограничить, выбрать, звук, тон,
} from './общее.js';

export const ОПИСЬ = { id: 'узел', имя: 'Узел', где: 'Двор мастера' };
export const СМЫСЛ = {
  плохо: 'Узлы расползлись под рукой мастера. Канат перевязывать ему самому.',
  нормально: 'Узлы держат, хоть мастер и поправил пару петель. За подсобку заплатят.',
  отлично: 'Все три узла — как у мастера, с первого раза. Он позовёт ещё.',
};
// Подсобка во дворе идёт без ремесла; навык живого слоя пока не растёт (решено за автора).
export const навык = () => 0;

const ХОДЫ = {
  верх: { dx: 0, dy: -1, знак: '↑', f: 660 },
  право: { dx: 1, dy: 0, знак: '→', f: 550 },
  низ: { dx: 0, dy: 1, знак: '↓', f: 330 },
  лево: { dx: -1, dy: 0, знак: '←', f: 440 },
};
const ОБРАТНО = { верх: 'низ', низ: 'верх', право: 'лево', лево: 'право' };
const КЛЕТКА = 58;
const ЦЕНТР = { x: 480, y: 300 };
const ДЛИНЫ = [4, 6, 8];
const МАЗОК = 34;
const КНОПКА = { x: 760, y: 470, w: 170, h: 50 };

function узор(длина) {
  for (;;) {
    const путь = [];
    let x = 0, y = 0;
    const было = new Set(['0,0']);
    let ок = true;
    for (let i = 0; i < длина && ок; i++) {
      const можно = Object.keys(ХОДЫ).filter(х => {
        if (путь.length && х === ОБРАТНО[путь[путь.length - 1]]) return false;
        const nx = x + ХОДЫ[х].dx, ny = y + ХОДЫ[х].dy;
        return Math.abs(nx) <= 4 && Math.abs(ny) <= 3 && !было.has(nx + ',' + ny);
      });
      if (!можно.length) { ок = false; break; }
      const х = выбрать(можно);
      путь.push(х);
      x += ХОДЫ[х].dx;
      y += ХОДЫ[х].dy;
      было.add(x + ',' + y);
    }
    if (ок) return путь;
  }
}

export async function запустить(контейнер, { навык = 0, тихо = false, сигнал } = {}) {
  const н = ступеньНавыка(навык);
  звук.тихо = тихо;
  const поле = создатьПоле(контейнер, { подсказка: 'Смотри, как мастер ведёт конец каната. Потом повтори: мазок мышью в нужную сторону или стрелки/WASD. H или кнопка — подсмотреть ещё раз.', сигнал });
  const двор = await картинка('Ресурсы/Места/порт-двор-складской.webp');

  const такт = [0.6, 0.7, 0.8][н];
  const ошибокМожно = [1, 1, 2][н];
  const ослаб = 3.5 + 0.5 * н;
  let подсмотров = [1, 2, 2][н];

  let k = 0;
  let путь = узор(ДЛИНЫ[0]);
  let фаза = 'показ';
  let т = -0.6; // время внутри фазы
  let сделано = 0;
  let ошибок = 0, подсмотрел = 0;
  let тишина = 0;
  let соскольз = 0;
  const итоги = [];
  let мазок = null;
  let над = false;

  const точки = (n) => {
    const p = [{ x: 0, y: 0 }];
    for (let i = 0; i < n; i++) p.push({ x: p[i].x + ХОДЫ[путь[i]].dx, y: p[i].y + ХОДЫ[путь[i]].dy });
    return p.map(q => ({ x: ЦЕНТР.x + q.x * КЛЕТКА, y: ЦЕНТР.y + q.y * КЛЕТКА }));
  };
  const внутри = (x, y, п) => x >= п.x && x <= п.x + п.w && y >= п.y && y <= п.y + п.h;

  function подсмотреть() {
    if (фаза !== 'повтор' || подсмотров <= 0) return;
    подсмотров--;
    подсмотрел++;
    фаза = 'показ';
    т = -0.3;
    поле.слово('ещё раз…', ЦЕНТР.x, 90, ЦВЕТ.бумага2, 22);
  }

  function закончитьУзел(вышел) {
    const о = вышел ? ограничить(1 - 0.15 * ошибок - 0.15 * подсмотрел, 0.3, 1) : 0.5 * сделано / путь.length;
    итоги.push(о);
    фаза = 'пауза';
    т = 0;
    if (вышел) {
      звуки.ура();
      поле.кольцо(ЦЕНТР.x, ЦЕНТР.y, ЦВЕТ.трава, 120);
      поле.слово(о >= 0.85 ? 'держит!' : 'держит, но мастер поправил', ЦЕНТР.x, 90, о >= 0.85 ? ЦВЕТ.трава : ЦВЕТ.свеча, 30);
    } else {
      звуки.мимо();
      поле.дрожь(6);
      поле.слово('распустился', ЦЕНТР.x, 90, ЦВЕТ.ржа, 30);
    }
  }

  function ход(х) {
    if (фаза !== 'повтор') return;
    тишина = 0;
    if (х === путь[сделано]) {
      сделано++;
      тон(ХОДЫ[х].f, { длит: 0.2, тип: 'triangle', громк: 0.4 });
      const p = точки(сделано)[сделано];
      поле.искры(p.x, p.y, ЦВЕТ.бумага2, 5);
      if (сделано >= путь.length) закончитьУзел(true);
    } else {
      ошибок++;
      соскольз = 0.4;
      звуки.мимо();
      поле.дрожь(5);
      поле.слово('соскользнул', ЦЕНТР.x, 90, ЦВЕТ.ржа, 24);
      if (ошибок > ошибокМожно) закончитьУзел(false);
    }
  }

  function шаг(dt) {
    т += dt;
    соскольз = Math.max(0, соскольз - dt);
    if (фаза === 'показ') {
      const i = Math.floor(т / такт);
      const шагПрежде = Math.floor((т - dt) / такт);
      if (т >= 0 && i !== шагПрежде && i < путь.length) тон(ХОДЫ[путь[i]].f, { длит: 0.22, тип: 'sine', громк: 0.35 });
      if (т >= путь.length * такт + 0.5) { фаза = 'повтор'; т = 0; тишина = 0; }
    } else if (фаза === 'повтор') {
      тишина += dt;
      if (тишина >= ослаб) {
        тишина = 0;
        ошибок++;
        поле.слово('канат ослаб', ЦЕНТР.x, 90, ЦВЕТ.свеча, 24);
        звуки.ох();
        if (ошибок > ошибокМожно) закончитьУзел(false);
      }
    } else if (фаза === 'пауза' && т >= 1.4) {
      k++;
      if (k >= ДЛИНЫ.length) { поле.конец(итоги.reduce((с, о) => с + о, 0) / ДЛИНЫ.length); return; }
      путь = узор(ДЛИНЫ[k]);
      фаза = 'показ';
      т = -0.6;
      сделано = 0;
      ошибок = 0;
      подсмотрел = 0;
    }
  }

  function канат(ctx, p, цвет, ширина, альфа = 1) {
    if (p.length < 2) return;
    ctx.globalAlpha = альфа;
    ctx.lineCap = 'round';
    ctx.lineJoin = 'round';
    for (const [ш, ц] of [[ширина + 4, 'rgba(10,8,5,.6)'], [ширина, цвет]]) {
      ctx.strokeStyle = ц;
      ctx.lineWidth = ш;
      ctx.beginPath();
      ctx.moveTo(p[0].x, p[0].y);
      for (let i = 1; i < p.length; i++) ctx.lineTo(p[i].x, p[i].y);
      ctx.stroke();
    }
    ctx.strokeStyle = 'rgba(40,28,14,.55)';
    ctx.lineWidth = 2;
    ctx.setLineDash([5, 6]);
    ctx.beginPath();
    ctx.moveTo(p[0].x, p[0].y);
    for (let i = 1; i < p.length; i++) ctx.lineTo(p[i].x, p[i].y);
    ctx.stroke();
    ctx.setLineDash([]);
    ctx.globalAlpha = 1;
  }

  function нарисовать(ctx, t) {
    фон(ctx, двор, 0.74);
    // доска с колышками
    плашка(ctx, ЦЕНТР.x - 4.6 * КЛЕТКА, ЦЕНТР.y - 3.6 * КЛЕТКА, 9.2 * КЛЕТКА, 7.2 * КЛЕТКА, { заливка: 'rgba(40,30,20,.75)', обвод: ЦВЕТ.линия });
    for (let x = -4; x <= 4; x++) for (let y = -3; y <= 3; y++) {
      ctx.fillStyle = 'rgba(226,198,146,.18)';
      ctx.beginPath();
      ctx.arc(ЦЕНТР.x + x * КЛЕТКА, ЦЕНТР.y + y * КЛЕТКА, 3, 0, Math.PI * 2);
      ctx.fill();
    }
    ctx.fillStyle = '#6b5233';
    ctx.beginPath();
    ctx.arc(ЦЕНТР.x, ЦЕНТР.y, 14, 0, Math.PI * 2);
    ctx.fill();
    // канат мастера (во время показа) и свой
    if (фаза === 'показ' && т >= 0) {
      const сколько = Math.min(путь.length, Math.floor(т / такт) + 1);
      const доля = Math.min(1, (т % такт) / (такт * 0.6));
      const p = точки(сколько);
      if (сколько <= путь.length && т < путь.length * такт) {
        const a = p[сколько - 1], b = p[сколько];
        p[сколько] = { x: a.x + (b.x - a.x) * доля, y: a.y + (b.y - a.y) * доля };
      }
      канат(ctx, p, '#e4d3a8', 12, 0.85);
      const конец = p[p.length - 1];
      if (т < путь.length * такт) {
        const х = путь[сколько - 1];
        надпись(ctx, ХОДЫ[х].знак, конец.x + ХОДЫ[х].dx * 34, конец.y + ХОДЫ[х].dy * 34, { р: 30, цвет: ЦВЕТ.свеча, вес: 700 });
      }
    } else {
      const p = точки(сделано);
      const дрож = соскольз > 0 ? Math.sin(t * 70) * 4 : 0;
      канат(ctx, p.map(q => ({ x: q.x + дрож, y: q.y })), '#c9a46a', 12);
      const конец = p[p.length - 1];
      if (фаза === 'повтор') {
        ctx.strokeStyle = `rgba(231,178,99,${0.5 + 0.3 * Math.sin(t * 6)})`;
        ctx.lineWidth = 2;
        ctx.beginPath();
        ctx.arc(конец.x, конец.y, 16, 0, Math.PI * 2);
        ctx.stroke();
      }
    }
    // табло
    плашка(ctx, 30, 24, 270, 84);
    надпись(ctx, `узел ${Math.min(k + 1, ДЛИНЫ.length)} из ${ДЛИНЫ.length}`, 46, 42, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.свеча, выр: 'left' });
    const словоФазы = фаза === 'показ' ? 'смотри, как ведёт мастер' : фаза === 'повтор' ? `твоя очередь · ${сделано} из ${путь.length}` : '';
    надпись(ctx, словоФазы, 46, 68, { р: 17, выр: 'left' });
    надпись(ctx, `ошибок ${ошибок} из ${ошибокМожно + 1}`, 46, 92, { р: 14, выр: 'left', цвет: ошибок ? ЦВЕТ.ржа : ЦВЕТ.тихо });
    if (фаза === 'повтор') полоса(ctx, 180, 88, 104, 6, тишина / ослаб, тишина / ослаб > 0.7 ? ЦВЕТ.ржа : ЦВЕТ.бумага2);
    итоги.forEach((о, i) => надпись(ctx, о >= 0.85 ? '●' : о >= 0.45 ? '◐' : '○', 46 + i * 24, 128, { р: 20, выр: 'left', цвет: о >= 0.85 ? ЦВЕТ.трава : о >= 0.45 ? ЦВЕТ.свеча : ЦВЕТ.ржа }));
    const можно = фаза === 'повтор' && подсмотров > 0;
    плашка(ctx, КНОПКА.x, КНОПКА.y, КНОПКА.w, КНОПКА.h, { заливка: можно && над ? 'rgba(231,178,99,.25)' : 'rgba(13,19,22,.75)', обвод: можно ? ЦВЕТ.свеча : ЦВЕТ.линия });
    надпись(ctx, `подсмотреть · ${подсмотров}`, КНОПКА.x + КНОПКА.w / 2, КНОПКА.y + 18, { р: 17, цвет: можно ? ЦВЕТ.свеча : ЦВЕТ.тихо });
    надпись(ctx, 'H', КНОПКА.x + КНОПКА.w / 2, КНОПКА.y + 37, { р: 12, цвет: ЦВЕТ.тихо });
  }

  поле.кадр(нарисовать);
  await поле.старт({
    заголовок: 'Узел',
    строка: 'Двор мастера: вяжут канат для рыбаков, лишние руки пригодятся. Мастер покажет каждый узел один раз — запомни, куда шёл конец, и повтори. Три узла, каждый длиннее прежнего.',
  });
  поле.отладка = () => ({ k, путь, фаза, сделано, ошибок, итоги, подсмотров });

  const КЛАВИШИ = { ArrowUp: 'верх', KeyW: 'верх', ArrowRight: 'право', KeyD: 'право', ArrowDown: 'низ', KeyS: 'низ', ArrowLeft: 'лево', KeyA: 'лево' };
  return поле.играть({
    обновить: шаг,
    нарисовать,
    мышьВниз(x, y) {
      if (внутри(x, y, КНОПКА)) { подсмотреть(); return; }
      мазок = { x, y };
    },
    мышьДвиг(x, y) {
      над = внутри(x, y, КНОПКА);
      if (!мазок || !поле.мышь.нажата) return;
      const dx = x - мазок.x, dy = y - мазок.y;
      if (Math.max(Math.abs(dx), Math.abs(dy)) < МАЗОК) return;
      ход(Math.abs(dx) > Math.abs(dy) ? (dx > 0 ? 'право' : 'лево') : (dy > 0 ? 'низ' : 'верх'));
      мазок = { x, y };
    },
    мышьВверх() { мазок = null; },
    клавиша(код) {
      if (КЛАВИШИ[код]) ход(КЛАВИШИ[код]);
      else if (код === 'KeyH') подсмотреть();
    },
  }, [0.45, 0.8]);
}
