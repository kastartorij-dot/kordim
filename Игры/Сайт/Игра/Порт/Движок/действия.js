const зажать = v => Math.max(0, Math.min(МАКС, v));
const запись = (S, строка) => { S.мир.журналДня.push(строка); return строка; };

// Подпись места: плата за вход меняется, если у места есть скидка (баня после дела «Присмотреть, пока ходит»).
function подписьМеста(S, м) {
  const в = м.модуль.вход;
  if (!в || typeof в !== 'object' || !в.скидка) return м.подпись;
  const плата = платаВхода(S, м.модуль);
  return плата === в.стоит ? м.подпись : м.подпись.replace(String(в.стоит), String(плата));
}

// Исход «слоняться»: 15% находка (+2 гр.), 15% невезение (тепло −1), иначе просто атмосфера.
// Доля мала и деньги малы нарочно — это должно быть хуже работы, а не бесплатной её заменой.
const НАХОДКА = 0.15, СЛУЧАЙ = 0.15;
function случайнаяСтрока(массив, S) {
  return массив[Math.floor(бросок(S) * массив.length)];
}
// Прогулка всегда что-то даёт (решение автора 12.11): кроме случая — что в квартале будет дальше сегодня.
const ПОРЯДОК = ['утро', 'день', 'вечер', 'ночь'];
const КОГДА_СЛОВОМ = { утро: 'утром', день: 'днём', вечер: 'с вечера', ночь: 'ночью' };
function дальшеВРайоне(S) {
  const i = ПОРЯДОК.indexOf(S.мир.отрезок), впереди = ПОРЯДОК.slice(i + 1), район = S.мир.район;
  const части = [];
  for (const м of МЕСТА) {
    if (м.район !== район || м.когда.includes(S.мир.отрезок)) continue;
    const о = впереди.find(x => м.когда.includes(x));
    if (о) части.push(`${м.имя} — ${КОГДА_СЛОВОМ[о]}`);
  }
  for (const р of РАБОТЫ) {
    if (!р.открыто || р.скрыто || !(Array.isArray(р.где) ? р.где : [р.где]).includes(район) || р.когда.includes(S.мир.отрезок)) continue;
    const о = впереди.find(x => р.когда.includes(x));
    if (о) части.push(`${р.имя.toLowerCase()} — ${КОГДА_СЛОВОМ[о]}`);
  }
  return части.length ? `Узнал, что дальше: ${части.slice(0, 3).join('; ')}.` : null;
}
function игратьСлоняться(S, сл) {
  if (!сл) return null;
  const строка = игратьСлонятьсяСлучай(S, сл), дальше = дальшеВРайоне(S);
  if (дальше) запись(S, дальше);
  return [строка, дальше].filter(Boolean).join(' ') || null;
}
function игратьСлонятьсяСлучай(S, сл) {
  const р = бросок(S);
  if (р < НАХОДКА && сл.находки?.length) {
    S.герой.кошель += 2;
    return запись(S, `${случайнаяСтрока(сл.находки, S)} (+2 гр.)`);
  }
  if (р < НАХОДКА + СЛУЧАЙ && сл.случаи?.length) {
    S.герой.тело.тепло = зажать(S.герой.тело.тепло - 1);
    return запись(S, `${случайнаяСтрока(сл.случаи, S)} (тепло −1)`);
  }
  return сл.варианты?.length ? запись(S, случайнаяСтрока(сл.варианты, S)) : null;
}

// Цена во времени на кнопке: ромбы делений; без сил день короче — это видно на шкале, а не в цене.
function подписьВремени(S, n) {
  return ценаВремени(S, n) + (устал(S) ? ' · без сил' : '');
}
const ПОСЛОНЯТЬСЯ = 2; // делений (решение автора 12.11)

export function доступныеДействия(S) {
  if(S.мир.кампанияЗавершена||S.мир.кварталы?.караул?.статус==='задержан'&&S.мир.день<S.мир.кварталы.караул.доДня)return [];
  // Пока смена не закрыта, город стоит: есть только кнопки карточки (Движок/смена.js).
  const карточка = действияСмены(S);
  if (карточка) return обернутьШаг(S, карточка);
  const А = [];
  const { район, отрезок } = S.мир;

  // Ночью дорога к своему оплаченному ночлегу — «домой и спать» (PR005-01). Вечером дорога остаётся дорогой,
  // а «Домой, спать» — отдельная кнопка: бодрый вечером может зайти в свой квартал и не лечь (Р19).
  const дом = отрезок === 'ночь' ? свойНочлег(S) : null;
  const свой = отрезок === 'вечер' ? свойНочлег(S) : null;
  if (свой) А.push({
    id: 'домой', вид: 'переход', группа: 'пойти', текст: 'Домой, спать', домой: true,
    подпись: подписьДомой(S), отрезков: 0, делений: дорога(район, районДома(свой) ?? район), можно: true, почему: null,
    выполнить(S) {
      if (S.сцена || S.мир.кампанияЗавершена) return null;
      return идтиДомой(S);
    },
  });
  for (const р of РАЙОНЫ) {
    if (р.id === район) continue;
    if (дом && районДома(дом) === р.id) {
      А.push({
        id: `переход:${р.id}`, вид: 'переход', группа: 'пойти', текст: р.имя, домой: true,
        подпись: подписьДомой(S), отрезков: 0, делений: дорога(район, р.id), можно: true, почему: null,
        выполнить(S) {
          if (S.сцена || S.мир.кампанияЗавершена) return null;
          return идтиДомой(S);
        },
      });
      continue;
    }
    const путь = дорога(район, р.id);
    А.push({
      id: `переход:${р.id}`, вид: 'переход', группа: 'пойти', текст: р.имя,
      подпись: подписьВремени(S, путь), отрезков: 0, делений: путь, можно: true, почему: null,
      выполнить(S) {
        if(S.сцена||S.мир.кампанияЗавершена||S.мир.кварталы?.караул?.статус==='задержан'&&S.мир.день<S.мир.кварталы.караул.доДня)return null;
        const с = запись(S, `Дорога в ${р.имя}`); // имена районов — неодушевлённые: «в Доки», «в Торговый квартал»
        const путь2 = дорога(S.мир.район, р.id);
        S.мир.район = р.id;
        потратить(S, путь2, { дорога: true });
        return с;
      },
    });
  }

  {
    const тек = РАЙОНЫ.find(р => р.id === район);
    const сл = тек?.слоняться;
    const следующий = { утро: 'дня', день: 'вечера', вечер: 'ночи', ночь: 'утра' }[отрезок];
    const ост = Math.max(1, осталось(S));
    А.push({
      id: 'отрезок:здесь', вид: 'ждать', группа: 'здесь',
      текст: отрезок === 'ночь' ? 'Не спать до утра' : `Подождать до ${следующий}`,
      подпись: отрезок === 'ночь' ? 'ночь без сна' : подписьВремени(S, ост), отрезков: 0, делений: ост, можно: true, почему: null,
      выполнить(S) {
        потратить(S, Math.max(1, осталось(S)), { улица: true });
        return null;
      },
    });
    if (сл && отрезок !== 'ночь') А.push({
      id: 'слоняться', вид: 'ждать', группа: 'здесь', текст: сл.кнопка ?? 'Пройти по району',
      подпись: подписьВремени(S, ПОСЛОНЯТЬСЯ), отрезков: 0, делений: ПОСЛОНЯТЬСЯ, можно: true, почему: null,
      выполнить(S) {
        // Изредка подворачивается пара грошей или не везёт с погодой (тепло −1); иначе — как живёт район.
        // Специально мало и ниже дохода от работы — иначе это была бы бесплатная работа без риска.
        const с = игратьСлоняться(S, сл);
        потратить(S, ПОСЛОНЯТЬСЯ, { улица: true });
        return с;
      },
    });
  }

  // Места города: видны в своём районе; открыты только в свои отрезки.
  for (const м of МЕСТА) {
    if (м.район !== район) continue;
    const { можно, почему } = можноВойти(S, м.id);
    А.push({
      id: `место:${м.id}`, вид: 'место', группа: 'места', текст: м.имя,
      подпись: `${подписьМеста(S, м)} · ${м.когда.join(', ')}`, отрезков: 0, делений: 0, можно, почему,
      выполнить(S) {
        if (!можноВойти(S, м.id).можно) return null; // условие могло устареть между построением списка и кликом
        const с = запись(S, КУДА[м.id] ? `Заходил ${КУДА[м.id]}` : `Заходил: ${м.имя}`);
        войти(S, м.id);
        return с;
      },
    });
  }

  А.push(...действияРаботы(S));
  А.push(...действияПоследствийРабот(S));

  for (const е of ЕДА) {
    if (!е.где.includes(район) || !е.когда.includes(отрезок)) continue;
    // Еда нужна, пока от неё есть толк: сытость или тепло (похлёбкой греются и сытые).
    const т = S.герой.тело;
    const сыт = т.сыт >= МАКС && !(е.тепло && т.тепло < МАКС);
    const цена = ценаУличнойПокупки(S, е.цена);
    const бедно = S.герой.кошель < цена;
    А.push({
      id: `еда:${е.id}`, вид: 'еда', группа: 'на ходу', текст: е.имя, цена,
      подпись: `${цена} гр. · сыт +${е.сыт}${е.тепло ? `, тепло +${е.тепло}` : ''}`,
      отрезков: 0, можно: !сыт && !бедно, почему: сыт ? 'сыт' : бедно ? 'нет денег' : null,
      выполнить(S) {
        const сытСейчас = S.герой.тело.сыт >= МАКС && !(е.тепло && S.герой.тело.тепло < МАКС);
        const стоимость = ценаУличнойПокупки(S, е.цена);
        if (сытСейчас || S.герой.кошель < стоимость) return null;
        S.герой.кошель -= стоимость;
        S.герой.тело.сыт = зажать(S.герой.тело.сыт + е.сыт);
        S.герой.тело.тепло = зажать(S.герой.тело.тепло + (е.тепло || 0));
        return запись(S, `${е.имя}: −${стоимость} гр., сыт +${е.сыт}${е.тепло ? `, тепло +${е.тепло}` : ''}`);
      },
    });
  }

  // Еда «с собой»: та же цена, не ест, а кладёт вещь в свободный слот (Данные/еда.js, поле «собой»).
  for (const е of ЕДА) {
    if (!е.собой || !е.где.includes(район) || !е.когда.includes(отрезок)) continue;
    const в = ВЕЩИ[е.собой];
    const некуда = !можноПоложить(S, в.id);
    const цена = ценаУличнойПокупки(S, е.цена);
    const бедно = S.герой.кошель < цена;
    А.push({
      id: `еда-собой:${е.id}`, вид: 'еда-собой', группа: 'на ходу', текст: в.подписьСобой, цена,
      подпись: `${цена} гр.`, отрезков: 0, можно: !некуда && !бедно,
      почему: некуда ? 'некуда положить' : бедно ? 'нет денег' : null,
      выполнить(S) {
        const стоимость = ценаУличнойПокупки(S, е.цена);
        if (!можноПоложить(S, в.id) || S.герой.кошель < стоимость) return null;
        if (!положить(S, в.id, 1, { происхождение: 'рынок' })) return null; // не влезло — денег не берём
        S.герой.кошель -= стоимость;
        return запись(S, `${в.имя}: −${стоимость} гр., с собой`);
      },
    });
  }

  А.push(...доступныеПокупки(S), ...доступныеУслуги(S));
  А.push(...действияДелВГороде(S));

  for (const x of S.мир.отложенныеВещи ?? []) А.push({
    id: `выдача:${x.номер}`, вид: 'выдача', группа: 'здесь',
    текст: `Забрать: ${имяВещи(x.тип)}`, подпись: 'даром', отрезков: 0,
    можно: можноПоложить(S, x.тип), почему: 'некуда положить',
    выполнить(S2) { return получитьОтложенное(S2, x.номер); },
  });

  if (отрезок === 'утро' && S.мир.ночьБезСна === S.мир.день) А.push({
    id: 'передышка:после-ночи', вид: 'сон', группа: 'здесь', текст: 'Передохнуть после ночной работы',
    подпись: `${подписьВремени(S, Math.max(1, осталось(S)))} · силы +1`, отрезков: 0, делений: Math.max(1, осталось(S)), можно: true, почему: null,
    выполнить(S2) {
      if (S2.мир.ночьБезСна !== S2.мир.день || S2.мир.отрезок !== 'утро') return null;
      S2.мир.ночьБезСна = null;
      S2.герой.тело.отдых = Math.min(МАКС, S2.герой.тело.отдых + 1);
      const строка = запись(S2, 'Передохнул после ночной работы: силы +1');
      следующийОтрезок(S2);
      return строка;
    },
  });

  // Лечь можно с вечера (Р19). Потрачено больше половины ночи — сон на 1 хуже (время.js, лечьСпать).
  if (можноЛечь(S)) {
    for (const ж of ЖИЛЬЁ) {
      if (!ж.открыто || (ж.где && !ж.где.includes(район)) || (ж.договор && !договорДействует(S))) continue;
      if (ж.id === 'часовня' && часовняЗакрыта(S)) continue; // Уна молчит после лжи
      const жильё = S.герой.жильё;
      const оплачено = ж.ночей && жильё && жильё.id === ж.id && жильё.оплачено_по >= S.мир.день;
      const платить = оплачено ? 0 : ж.цена;
      const бедно = S.герой.кошель < платить;
      const подпись = оплачено ? `оплачено до дня ${жильё.оплачено_по}`
        : ж.ночей ? `${ж.цена} гр. за ${ж.ночей} ночей` : ж.цена ? `${ж.цена} гр.` : 'даром';
      А.push({
        id: `сон:${ж.id}`, вид: 'сон', группа: 'ночлег', текст: ж.имя, цена: платить, отдых: ж.отдых,
        подпись: `${подпись} · силы +${ж.отдых}${ж.тепло ? `, тепло ${ж.тепло > 0 ? '+' : '−'}${Math.abs(ж.тепло)}` : ''}`,
        отрезков: 0, можно: !бедно, почему: бедно ? 'нет денег' : null,
        выполнить(S) {
          if (S.герой.кошель < платить) return null;
          if (платить) {
            S.герой.кошель -= платить;
            запись(S, `${ж.имя}: −${платить} гр.`);
          }
          if (ж.ночей && !оплачено) S.герой.жильё = { id: ж.id, оплачено_по: S.мир.день + ж.ночей - 1 };
          let итог = null;
          if (ж.риск && кражаСлучилась(S, ж.риск.шанс)) итог = украсть(S, ж.имя);
          if (ж.id === 'ночлежка') записатьНочь(S); // книга кроватей считает и ночи, что начались на карте
          лечьСпать(S, ж);
          return итог;
        },
      });
    }
  }
  return обернутьШаг(S, А);
}


