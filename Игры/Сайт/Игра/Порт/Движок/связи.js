// Личные линии (шаг 11): чистая логика без DOM. Состояние в S.мир.связи[кто] создаётся лениво (версию сохранения не трогаем).
// Данные и подписи — Данные/связи.js. Что здесь держится:
// - доверие (расположение из разговоров), влечение (личные моменты) и доступ (оплаченные вечера) раздельны;
// - деньги и подарки не двигают этап и не дают влечения;
// - её решение — запись, которую не переписывают числа; «нет» снимает только её же новое решение;
// - этапы идут по одному; поступки, обещания, отсутствие и примирение остаются в памяти линии.
import { ЭТАПЫ, ЛИНИИ, ПРАВИЛА, ПОДПИСИ_ЭТАПОВ, РЕШЕНИЯ, СТАТУСЫ, ТЕКСТЫ_СВЯЗЕЙ } from '../Данные/связи.js';

const новая = () => ({
  этап: 'нет',
  этапДень: null,       // день, когда начался текущий этап
  влечение: 0,
  доступ: 0,            // оплаченные вечера: коммерческий доступ, не близость
  дниВстреч: [],        // разные дни, когда герой с ней говорил
  последняяВстреча: null,
  поступки: [],         // [{ ид, день }] — одноразовые значимые поступки
  обещания: [],         // [{ ид, что, день, срок, статус: дано | сдержано | нарушено }]
  решение: null,        // { что: да | нет | дружба | позже, день }
  статус: 'нет',        // нет | вместе | дружба | отказ | пауза | расстались
  история: [],          // [{ день, что }] — смены этапов и статусов, для журнала и будущего сезона
});

export const линия = кто => ЛИНИИ[кто] ?? null;
export const естьЛиния = кто => !!ЛИНИИ[кто];

export function связь(S, кто) {
  const все = (S.мир.связи ??= {});
  const с = (все[кто] ??= новая());
  for (const [к, v] of Object.entries(новая())) с[к] ??= v;
  return с;
}
const читать = (S, кто) => S.мир.связи?.[кто] ?? новая();
const доверие = (S, кто) => S.мир.люди?.[кто]?.распол ?? 0;
const номер = этап => ЭТАПЫ.indexOf(этап);
const зажать = (от, до, v) => Math.max(от, Math.min(до, v));
const журнал = (S, т) => { S.мир.журналДня.push(т); return т; };
const записать = (S, с, что) => { с.история.push({ день: S.мир.день, что }); };

// ── этапы ───────────────────────────────────────────────────────────────
// Ранние этапы открываются сами: знакомство — первая встреча, встречи — несколько разных дней и доверие.
function проверитьРанние(S, кто) {
  const л = линия(кто), с = связь(S, кто);
  const нужно = л.встречи ?? {}, дов = л.доверие ?? {};
  for (const э of ['знакомство', 'встречи']) {
    if (номер(с.этап) >= номер(э)) continue;
    if (номер(с.этап) !== номер(э) - 1) break;
    if (с.дниВстреч.length < (нужно[э] ?? 1)) break;
    if (доверие(S, кто) < (дов[э] ?? 0)) break;
    с.этап = э; с.этапДень = S.мир.день;
    записать(S, с, `этап: ${э}`);
  }
}

// Следующий этап только по одному шагу; поздние этапы — эффектом графа, когда написан сам поворот.
export function сдвинутьЭтап(S, кто, этап) {
  if (!естьЛиния(кто) || !ЭТАПЫ.includes(этап)) return false;
  const с = связь(S, кто);
  проверитьРанние(S, кто);
  if (номер(этап) <= номер(с.этап)) return false;
  if (номер(этап) !== номер(с.этап) + 1) return false;
  с.этап = этап; с.этапДень = S.мир.день;
  записать(S, с, `этап: ${этап}`);
  return true;
}

// Встреча — разговор с человеком линии (вызывается из Движок/диалог.js при начале разговора).
export function отметитьВстречу(S, кто) {
  if (!естьЛиния(кто)) return;
  const с = связь(S, кто), день = S.мир.день;
  if (!с.дниВстреч.includes(день)) с.дниВстреч.push(день);
  с.последняяВстреча = день;
  проверитьРанние(S, кто);
}

// Оплаченный вечер: растёт только доступ. Ни доверия, ни влечения, ни этапа.
export function оплаченныйВечер(S, кто) {
  if (!естьЛиния(кто)) return;
  const с = связь(S, кто);
  с.доступ += 1;
  с.последняяВстреча = S.мир.день;
}

// ── её решение и статус ─────────────────────────────────────────────────
const СТАТУС_ПО_РЕШЕНИЮ = { да: 'вместе', нет: 'отказ', дружба: 'дружба', позже: 'нет' };
export function решить(S, кто, что) {
  if (!естьЛиния(кто) || !РЕШЕНИЯ[что]) return false;
  const с = связь(S, кто);
  с.решение = { что, день: S.мир.день };
  с.статус = СТАТУС_ПО_РЕШЕНИЮ[что];
  записать(S, с, `решение: ${что}`);
  return true;
}

export function расстаться(S, кто, причина = 'разговор') {
  const с = связь(S, кто);
  if (!['вместе', 'пауза', 'дружба'].includes(с.статус)) return false;
  с.статус = 'расстались';
  записать(S, с, `расстались: ${причина}`);
  return true;
}

// Примирение — только если линия его допускает и после паузы или расставания. Решение «нет» примирением не снимается.
export function примириться(S, кто) {
  const л = линия(кто), с = связь(S, кто);
  if (!л?.примирение || !['пауза', 'расстались'].includes(с.статус)) return false;
  if (с.решение?.что === 'нет') return false;
  с.статус = с.решение?.что === 'дружба' ? 'дружба' : 'вместе';
  с.последняяВстреча = S.мир.день;
  записать(S, с, 'примирение');
  return true;
}

// ── поступки и обещания ─────────────────────────────────────────────────
export function поступок(S, кто, ид, { доверие: д = 0 } = {}) {
  const с = связь(S, кто);
  if (с.поступки.some(п => п.ид === ид)) return false;
  с.поступки.push({ ид, день: S.мир.день });
  if (д) {
    const л = ((S.мир.люди ??= {})[кто] ??= { спрошено: [], исчерпано: [] });
    л.распол = зажать(-2, 4, (л.распол || 0) + д);
  }
  проверитьРанние(S, кто);
  return true;
}

export function пообещать(S, кто, { ид, что, дней = ПРАВИЛА.обещаниеДней }) {
  const с = связь(S, кто);
  if (с.обещания.some(о => о.ид === ид)) return false;
  с.обещания.push({ ид, что, день: S.мир.день, срок: S.мир.день + дней, статус: 'дано' });
  return true;
}

export function сдержать(S, кто, ид) {
  const с = связь(S, кто), о = с.обещания.find(x => x.ид === ид && x.статус === 'дано');
  if (!о) return false;
  о.статус = 'сдержано';
  журнал(S, ТЕКСТЫ_СВЯЗЕЙ.сдержано(линия(кто), о.что));
  return true;
}

// ── эффект и условие для графов ─────────────────────────────────────────
// э.связь: { кто?, этап, влечение, поступок, доверие, решение, обещание: { ид, что, дней }, сдержать, расстаться, примириться }
export function применитьСвязь(S, кто0, э) {
  const кто = э.кто ?? кто0;
  if (!естьЛиния(кто)) return;
  const с = связь(S, кто);
  if (э.поступок) поступок(S, кто, э.поступок, { доверие: э.доверие ?? 0 });
  if (э.влечение) с.влечение = зажать(...ПРАВИЛА.влечение, с.влечение + э.влечение);
  if (э.этап) сдвинутьЭтап(S, кто, э.этап);
  if (э.решение) решить(S, кто, э.решение);
  if (э.обещание) пообещать(S, кто, э.обещание);
  if (э.сдержать) сдержать(S, кто, э.сдержать);
  if (э.расстаться) расстаться(S, кто);
  if (э.примириться) примириться(S, кто);
}

// у.связь: { кто?, этапОт, этапДо, вЭтапеДнейОт, влечение, решение, статус, поступок, обещание, отсутствиеОт, другаяСвязь, доступОт }
export function условиеСвязи(S, кто0, у) {
  const кто = у.кто ?? кто0;
  const с = читать(S, кто);
  if (у.этапОт && номер(с.этап) < номер(у.этапОт)) return false;
  if (у.этапДо && номер(с.этап) >= номер(у.этапДо)) return false;
  if (у.вЭтапеДнейОт !== undefined && (с.этапДень === null || S.мир.день - с.этапДень < у.вЭтапеДнейОт)) return false;
  if (у.влечение !== undefined && с.влечение < у.влечение) return false;
  if (у.решение !== undefined && (с.решение?.что ?? null) !== у.решение) return false;
  if (у.статус && ![].concat(у.статус).includes(с.статус)) return false;
  if (у.поступок && !с.поступки.some(п => п.ид === у.поступок)) return false;
  if (у.обещание) {
    const [ид, статус = 'дано'] = [].concat(у.обещание);
    if (!с.обещания.some(о => о.ид === ид && о.статус === статус)) return false;
  }
  if (у.отсутствиеОт !== undefined && (с.последняяВстреча === null || S.мир.день - с.последняяВстреча < у.отсутствиеОт)) return false;
  if (у.доступОт !== undefined && с.доступ < у.доступОт) return false;
  if (у.другаяСвязь !== undefined && другиеСвязи(S, кто).length > 0 !== !!у.другаяСвязь) return false;
  return true;
}

// Другие линии, где герой сейчас «вместе»: для последовательных реакций, если связей несколько.
export function другиеСвязи(S, кто) {
  return Object.entries(S.мир.связи ?? {}).filter(([id, с]) => id !== кто && с.статус === 'вместе').map(([id]) => id);
}

// ── закрытие дня ────────────────────────────────────────────────────────
// Отсутствие героя: долгая пауза у связи «вместе» превращается в паузу, потом в расставание.
// Просроченное обещание — нарушено, стоит доверия. Вызывается из Движок/время.js до смены дня.
export function закрытьДеньСвязей(S) {
  const день = S.мир.день, о = ПРАВИЛА.отсутствие;
  for (const [кто, с] of Object.entries(S.мир.связи ?? {})) {
    const л = линия(кто);
    if (!л) continue;
    const нет = с.последняяВстреча === null ? 0 : день - с.последняяВстреча;
    if (с.статус === 'вместе' && нет >= о.пауза) {
      с.статус = 'пауза'; записать(S, с, 'пауза: отсутствие'); журнал(S, ТЕКСТЫ_СВЯЗЕЙ.пауза(л));
    } else if (с.статус === 'пауза' && нет >= о.расставание) {
      с.статус = 'расстались'; записать(S, с, 'расстались: отсутствие'); журнал(S, ТЕКСТЫ_СВЯЗЕЙ.расставание(л));
    }
    for (const об of с.обещания) {
      if (об.статус !== 'дано' || день < об.срок) continue;
      об.статус = 'нарушено';
      const ч = ((S.мир.люди ??= {})[кто] ??= { спрошено: [], исчерпано: [] });
      ч.распол = зажать(-2, 4, (ч.распол || 0) + ПРАВИЛА.нарушеноДоверие);
      журнал(S, ТЕКСТЫ_СВЯЗЕЙ.нарушено(л, об.что));
    }
  }
}

// ── итог сезона ─────────────────────────────────────────────────────────
// Одна строка на линию, где было больше знакомства: что решила она и чем это стало. Сохраняется для второго сезона.
const ИТОГ_СТАТУСА = {
  вместе: л => `${л.имя}: вы вместе — по её слову и на её условиях.`,
  дружба: л => `${л.имя}: дружба без близости; это её ответ, и он не меньше другого.`,
  отказ: л => `${л.имя} сказала «нет». Знакомство осталось, решение — её.`,
  пауза: л => `${л.имя}: вы давно не виделись, и то, что было, теперь надо возобновлять.`,
  расстались: л => `${л.имя}: вы расстались.`,
};
export function итогСвязей(S) {
  const строки = [];
  for (const [кто, с] of Object.entries(S.мир.связи ?? {})) {
    const л = линия(кто);
    if (!л || номер(с.этап) < номер('встречи')) continue;
    строки.push(ИТОГ_СТАТУСА[с.статус]?.(л) ?? `${л.имя}: ${ПОДПИСИ_ЭТАПОВ[с.этап]}, решения пока нет.`);
  }
  return строки;
}

// ── журнал ──────────────────────────────────────────────────────────────
// Строка для вкладки «Люди»: этап, её решение и статус, отдельно доверие, влечение и доступ.
export function сводкаСвязей(S) {
  return Object.entries(S.мир.связи ?? {}).filter(([кто, с]) => линия(кто) && с.этап !== 'нет').map(([кто, с]) => {
    const части = [ПОДПИСИ_ЭТАПОВ[с.этап]];
    if (с.решение) части.push(РЕШЕНИЯ[с.решение.что]);
    if (СТАТУСЫ[с.статус] && с.статус !== 'отказ') части.push(СТАТУСЫ[с.статус]);
    const числа = [`доверие ${доверие(S, кто)}`];
    if (с.влечение) числа.push(`влечение ${с.влечение}`);
    if (с.доступ) числа.push(`оплаченных вечеров ${с.доступ} — ${ТЕКСТЫ_СВЯЗЕЙ.доступ}`);
    const обещано = с.обещания.filter(о => о.статус === 'дано').map(о => `обещано: ${о.что}`);
    return { кто, имя: линия(кто).имя, этап: с.этап, текст: части.join(' · '), числа: числа.join(' · '), обещано };
  });
}
