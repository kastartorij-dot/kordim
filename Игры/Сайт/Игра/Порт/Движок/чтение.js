// Мини-игра «Чтение комнаты» (шаг 12): рынок, двор Горма, лекарь. Без DOM; данные — Данные/чтение.js.
// Игра места: начинает её действие комнаты (эффект `игра: { вид: 'чтение', чтение }`), ходы и вид отдаёт Движок/игры-места.js.
// Спокойный режим: два взгляда из четырёх мест, потом ответ — всё одним касанием, таймера нет.
// Исход считается уровнем (Движок/уровень.js) и применяется один раз в завершитьЧтение — туда же подключится живой слой.
// Состояние — S.сцена.игра: { вид: 'чтение', чтение, видел[], реплика }. Учёт — S.мир.мини.чтение.решены: одно чтение на место.
import { ЧТЕНИЯ, ВЗГЛЯДОВ, ПРАВИЛО_ЧТЕНИЯ, ИСХОДЫ_ЧТЕНИЯ } from '../Данные/чтение.js';
import { вход } from './стенд-вход.js';
import { уровеньИтога } from './уровень.js';

// Навык для живого слоя: своего ремесла у чтения нет — 0.
export const навык = () => 0;

export const учётЧтения = S => ((S.мир.мини ??= {}).чтение ??= { решены: [] });
// Чтение этой комнаты, если оно есть и ещё не сделано.
export function чтениеЗдесь(S) {
  const [id] = Object.entries(ЧТЕНИЯ).find(([, ч]) => ч.место === S.сцена?.место && ч.комната === S.сцена?.комната) ?? [];
  return id && !учётЧтения(S).решены.includes(id) ? id : null;
}

export function начатьЧтение(S, id) {
  const ч = ЧТЕНИЯ[id];
  if (!ч || учётЧтения(S).решены.includes(id)) return false;
  S.сцена.игра = { вид: 'чтение', чтение: id, видел: [], реплика: ч.начало };
  return true;
}

// Спокойный режим → уровень: неверно — плохо; верно и видел нужную примету — отлично; верно наугад — нормально.
export function уровеньЧтения(ч, видел, ответ) {
  if (ответ !== ч.верный) return 'плохо';
  return видел.some(x => ч.нужно.includes(x)) ? 'отлично' : 'нормально';
}

