// Свой оплаченный ночлег (PR005-01): комната у вдовы на оплаченные ночи или «Свой угол» по договору.
// С вечера «Домой» — дорога до него и сон одним нажатием (Р19: лечь можно с вечера).
import { ЖИЛЬЁ } from '../Данные/жильё.js';
import { РАЙОНЫ } from '../Данные/районы.js';
import { дорога } from '../Данные/дороги.js';
import { договорДействует } from './угол.js';
import { лечьСпать, потратить, можноЛечь, ценаВремени } from './время.js';

export function свойНочлег(S) {
  const ж = S.герой.жильё;
  if (договорДействует(S)) return ЖИЛЬЁ.find(x => x.id === 'угол') ?? null;
  if (ж && ж.оплачено_по >= S.мир.день) return ЖИЛЬЁ.find(x => x.id === ж.id && x.ночей) ?? null;
  return null;
}

export const районДома = ж => ж?.где?.[0] ?? null;
const имяРайона = id => РАЙОНЫ.find(р => р.id === id)?.имя ?? id;

// Совместимость: «дорога съест ночь» — теперь просто «уже можно лечь» (вечер или ночь).
export const дорогаСъестНочь = S => можноЛечь(S);

// Подпись «домой» для кнопок: куда и что будет, коротко — на узком окне длинная подпись обрезается.
const ГДЕ = { вдова: 'у вдовы', угол: 'в своём углу' };
export function подписьДомой(S) {
  const ж = свойНочлег(S);
  if (!ж) return '';
  const где = ГДЕ[ж.id] ?? ж.имя.toLowerCase();
  if (!можноЛечь(S)) return `ночлег ${где} — с вечера`;
  const путь = дорога(S.мир.район, районДома(ж) ?? S.мир.район);
  return `домой, сон ${где}${путь ? ' · ' + ценаВремени(S, путь) : ''}`;
}

// Дойти до своего ночлега и лечь. Возвращает строку журнала или null.
export function идтиДомой(S) {
  const ж = свойНочлег(S);
  if (!ж || !можноЛечь(S) || S.мир.конецДня || S.мир.кампанияЗавершена) return null;
  const район = районДома(ж);
  let строка = null;
  if (район && район !== S.мир.район) {
    строка = `${S.мир.отрезок === 'ночь' ? 'Ночью' : 'Вечером'} домой, в ${имяРайона(район)}`;
    S.мир.журналДня.push(строка);
    потратить(S, дорога(S.мир.район, район), { дорога: true, держатьРассвет: true });
    S.мир.район = район;
  }
  if (S.мир.конецДня) return строка;
  лечьСпать(S, ж);
  return строка ?? ж.имя;
}
