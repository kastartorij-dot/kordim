import { работа } from '../Данные/работы.js';
import { ЖИЛЬЁ } from '../Данные/жильё.js';
import { начатьСмену, доступность } from './смена.js';
import { потратитьОтрезок, лечьСпать } from './время.js';
import { привестиВещи, вещь, можноПоложить, положить } from './вещи.js';
import { купитьУслугу } from './хозяйство.js';
import { ДНИ_ОБОЗОВ, деньОбоза as поКалендарю } from '../Данные/календарь.js';

export { ДНИ_ОБОЗОВ };
export const деньОбоза = S => поКалендарю(S.мир.день);
export const заседание = S => (S.сцена?.вход?.день ?? S.мир.день) === 19 && (S.сцена?.отрезок ?? S.мир.отрезок) === 'день';
export const обычныйПриём = S => ['утро', 'день'].includes(S.сцена?.отрезок ?? S.мир.отрезок);

export function кварталы(S) {
  const к = S.мир.кварталы ??= {};
  к.обращения ??= [];
  к.документы ??= {};
  к.записиВорот ??= [];
  к.проверкиВорот ??= {};
  к.совет ??= {};
  к.копии ??= {};
  к.встречиВдовы ??= [];
  return к;
}

export function сказать(S, текст, вЖурнал = false) {
  if (S.сцена) S.сцена.реплика = текст;
  if (вЖурнал) S.мир.журналДня.push(текст);
  return текст;
}

export function входКвартала(S, первый, повторный) {
  const п = S.мир.места[S.сцена.место];
  сказать(S, п.визитов > 1 ? повторный : первый);
  if (S.сцена.место === 'дом-управы' && !обычныйПриём(S))
    сказать(S, 'Окно писаря и зал Совета закрыты до утра. В караульной горит свет; туда можно обратиться из города.');
  if (S.сцена.место === 'дом-вдовы' && !['утро', 'вечер'].includes(S.сцена.отрезок))
    сказать(S, S.герой.жильё?.оплачено_по >= S.мир.день || S.герой.жильё?.id === 'угол'
      ? 'Жилец проходит к своей двери. Хозяйка сегодня уже закончила приём; оплаченное жильё и сундук доступны.'
      : 'Хозяйка принимает утром и вечером. Двери жилых комнат заперты; осмотреть условия у лестницы можно сейчас.');
}

function свидетельство(S, id) {
  const с = S.мир.свидетельства ??= [];
  if (!с.includes(id)) с.push(id);
}

export function основаниеОбращения(S) {
  const день = S.мир.места.ночлежка?.дниДействий?.облава;
  // Разговор о слухе и простой визит не делают героя очевидцем.
  if (Number.isInteger(день) && день <= S.мир.день)
    return { id: 'облава-ночлежки', свидетель: 'Тон', факт: `ночной приход караула в ночлежку дня ${день}, при котором Одвин помог Тону; Тон может подтвердить книгу постояльцев` };
  return null;
}

export function податьОбращение(S) {
  if (!обычныйПриём(S)) return сказать(S, 'Писарь вернётся утром. Караул принимает только обращения о порядке и задержании.');
  const к = кварталы(S), о = основаниеОбращения(S);
  if (!о) {
    к.набросок = { день: S.мир.день, чегоНеХватает: 'свидетель или проверяемый документ к конкретному событию' };
    return сказать(S, '«Я не назову вас лжецом. Принесите имя свидетеля или вещь, которую можно сверить». Писарь оставляет набросок; решения, сбора и штрафа нет.', true);
  }
  const старое = к.обращения.find(x => x.основание === о.id);
  if (старое) return сказать(S, `Обращение №${старое.номер} уже в книге. Свидетель — ${старое.свидетель}; новой платы и второго дела нет.`);
  const номер = к.обращения.length + 1;
  к.обращения.push({ номер, день: S.мир.день, основание: о.id, факт: о.факт, свидетель: о.свидетель, статус: 'проверка', ответственный: 'писарь портового Совета' });
  свидетельство(S, `управа_обращение_${номер}`);
  return сказать(S, `Обращение №${номер}: ${о.факт}. Писарь записывает имя свидетеля и предлагает спросить ответ по этому номеру. Это запись обращения, а не доказательство вины.`, true);
}

export function получитьГородскуюКопию(S, тип) {
  if (!обычныйПриём(S)) return сказать(S, 'Копии выдаёт писарь утром и днём. Запись остаётся в книге.');
  const к = кварталы(S), о = к.обращения.at(-1);
  const ключ = тип === 'совет' ? 'решение-19' : о ? `обращение-${о.номер}` : null;
  if (!ключ || тип === 'совет' && !к.совет.прочитано) return сказать(S, 'Сначала нужно назвать свою запись или прочитать существующее решение. Пустой выписки не выдают.');
  if (к.копии[ключ]) return сказать(S, 'Копия уже получена; сама запись остаётся у писаря. Повторного экземпляра за тот же визит не выдают.');
  const содержание = тип === 'совет' ? к.совет.решение : `Обращение №${о.номер}: ${о.факт}. Свидетель: ${о.свидетель}. Статус — проверка; решение ещё не принято.`;
  const происхождение = `Управа: ${ключ}; ${содержание}`;
  if (!положить(S, 'квитанция', 1, { происхождение, состояние: { городскаяКопия: ключ, текст: содержание } })) return сказать(S, 'В сумке нет места. Выписка остаётся у писаря; можно получить позже, запись не пропала.');
  к.копии[ключ] = true;
  return сказать(S, `Писарь выдаёт бумажную копию: ${содержание} Запись в журнале и переносимая квитанция — разные вещи.`, true);
}

export function прочестьРешение(S, лично = false) {
  const к = кварталы(S), день = S.сцена?.вход?.день ?? S.мир.день;
  if (день < 19) return сказать(S, день >= 18 ? 'Повестка на день 19: открытый разбор задержаний ночи 17-го. Без обвинения людей должны отпустить утром 18-го; Совет не продлевает срок задним числом.' : 'На доске нет сегодняшнего открытого разбора. Писарь объясняет, как подать своё обращение.');
  if (день === 19 && !заседание(S)) return сказать(S, 'Открытый разбор назначен на дневной отрезок. После него здесь останется выписка.');
  const присутствовал = лично && заседание(S);
  к.совет.решение = 'Изъятые при малом задержании вещи вернуть по описи, если к утру 18-го не оформлено дело с заявителем и проверяемым основанием.';
  if (присутствовал) к.совет.присутствовал = true;
  к.совет.прочитано = S.мир.день;
  свидетельство(S, 'совет_решение_19');
  const сцена = присутствовал
    ? 'Писарь читает время задержания, заявление, свидетельство и опись. Тобб спрашивает о грузе конторы; Вейт — о проверяемой записи; Бранка требует не держать человека за чужой страх. '
    : 'Писарь показывает запись прошедшего разбора. Одвин читает её сейчас; личного присутствия на заседании в его истории нет. ';
  return сказать(S, сцена + к.совет.решение + ' Писарь отмечает исполнителей; без поддержки Дорров или Нотариуса печать сама спор не решит.', true);
}

export function задержатьЗаПорядок(S) {
  const к = кварталы(S);
  if (к.караул?.статус === 'задержан') return сказать(S, 'Причина и утренний срок уже записаны. Повторного задержания поверх старого нет.');
  к.караул = { причина: 'Одвин прошёл за стол закрытых жалоб после ясного требования караула остановиться', заявитель: 'дежурный караула — непосредственный свидетель', ответственный: 'старший управского караула', день: S.мир.день, отрезок: S.мир.отрезок, доДня: S.мир.день + 1, доОтрезка: 'утро', статус: 'задержан', изъято: [] };
  if (S.сцена) S.сцена.комната = 'камера';
  сказать(S, `Старший караула записывает видимое нарушение порядка, себя как ответственного и срок до утра дня ${к.караул.доДня}. Без оформленного обвинения — выпуск. Вещи остаются при Одвине; опись изъятого пуста. Можно дождаться срока или попросить проверить запись.`, true);
}

export function проверитьКараул(S) {
  const к = кварталы(S), з = к.караул;
  if (!з) return сказать(S, 'Караул получает жалобу названного человека или пресекает видимое нарушение. По малому делу без обвинения срок — до следующего утра; документ, свидетель и поручитель проверяются по записи. Чужие имена без основания не раскрывают.');
  if (з.статус === 'задержан' && S.мир.день >= з.доДня) {
    з.статус = 'выпущен'; з.выпуск = { день: S.мир.день, отрезок: S.мир.отрезок, причина: 'малый срок истёк, обвинение не предъявлено' };
    свидетельство(S, 'караул_собственный_выпуск');
    return сказать(S, 'Утренний срок истёк; заявленного обвинения нет. Старший записывает выпуск. Изъятых вещей не было, при себе всё осталось по прежней описи.', true);
  }
  return сказать(S, `В журнале: ${з.причина}. Ответственный — ${з.ответственный}. Срок — утро дня ${з.доДня}. Статус: ${з.статус}.`);
}

export function дождатьсяВыпуска(S) {
  const з = кварталы(S).караул;
  if (!з || з.статус !== 'задержан') return проверитьКараул(S);
  // Срок ограничен одним утром. Время идёт обычным путём; тело и день не замораживаются.
  for (let i = 0; i < 4 && S.мир.день < з.доДня; i++) потратитьОтрезок(S);
  проверитьКараул(S);
  if (S.сцена) S.сцена.конец = 'уйти';
}

export function показатьДокумент(S, uid) {
  const x = привестиВещи(S).find(v => v.uid === uid);
  if (!x || !вещь(x.тип)?.бумага || x.состояние.промокло) return сказать(S, 'Нужен читаемый документ при себе. Мокрый или отсутствующий лист здесь не подтверждают.');
  const к = кварталы(S);
  if (к.документы[uid]) return сказать(S, 'Этот лист уже предъявлен. Повторная сверка не добавляет плату, сведения или награду; документ остаётся вашим.');
  к.документы[uid] = { день: S.мир.день, тип: x.тип, источник: 'личная сверка Нотариусом видимых знаков за перегородкой' };
  свидетельство(S, `нотариус_предъявлен_${uid}`);
  return сказать(S, 'Лист возвращается на вашу сторону стола. За перегородкой повторяют дату и видимые знаки. О намерениях прежних владельцев ответа нет. Подтверждено только предъявление этого экземпляра; платы за него нет.', true);
}

export function записьОбоза(S, день) {
  if (!ДНИ_ОБОЗОВ.includes(день) || день > S.мир.день) return сказать(S, 'Такого прибытия ещё нет в книге. Запись не заменяют догадкой.');
  const к = кварталы(S);
  if (!к.записиВорот.includes(день)) {
    к.записиВорот.push(день);
    свидетельство(S, `застава_обоз_${день}`);
    S.мир.журналДня.push(`Застава: прочитана открытая запись прибытия обоза дня ${день}; источник — книга караула.`);
  }
  return сказать(S, `В книге заставы за день ${день}: большой обоз, телега с треснувшим ободом. Записано прибытие, а не состав закрытых грузов или чужие намерения. За пропущенную разгрузку задним числом не платят.`);
}

export function бумагаНаЗаставе(S, uid) {
  const x = привестиВещи(S).find(x => x.uid === uid);
  if (!x || !вещь(x.тип)?.бумага) return сказать(S, 'Нужно предъявить настоящий лист при себе. Названия документа недостаточно.');
  if (x.состояние.промокло) return сказать(S, 'Караульный не разбирает мокрую запись. Сначала восстановите лист; он остаётся у вас.');
  const копия = x.состояние.городскаяКопия;
  if (копия && кварталы(S).копии[копия]) {
    const к = кварталы(S);
    if (к.проверкиВорот[uid]) return сказать(S, 'Этот экземпляр уже сверен. Повторной платы или отметки не требуется.');
    к.проверкиВорот[uid] = { день: S.мир.день, основание: копия, источник: 'караул сверил номер городской записи' };
    return сказать(S, `Караульный сверяет номер «${копия}» с городской книгой. Номер совпал; отметка проверки остаётся в журнале заставы, бумага у Одвина. Это подтверждает запись, а не право на закрытую дорогу или чужой груз.`, true);
  }
  return сказать(S, 'Караульный возвращает лист: «Здесь нет распоряжения о проходе или городской записи, которую я могу сверить. Морской билет не открывает сухопутную створку». Отказ с причиной; бумага и деньги остались при вас.');
}

export function взятьГородскуюРаботу(S, id) {
  const р = работа(id);
  if (!р || !р.где.includes(S.мир.район) || !р.когда.includes(S.мир.отрезок) || S.мир.смена) return сказать(S, 'Распорядитель уже закончил этот набор. Вернитесь в рабочие часы.');
  const д = доступность(S, р);
  if (!д.можно) return сказать(S, `Сегодня не берут: ${д.почему}. Платы и расхода времени нет.`);
  if (S.сцена) S.сцена.конец = 'уйти';
  // Карточка смены становится единственным источником платы, счёта, риска и времени.
  return начатьСмену(S, р);
}

export function купитьРыбу(S) {
  if (S.мир.район !== 'рыбацкий-берег' || !['утро', 'день', 'вечер'].includes(S.мир.отрезок) || S.герой.кошель < 2 || !можноПоложить(S, 'рыба'))
    return сказать(S, 'Рыбу можно купить днём за 2 гроша, когда в сумке есть место. Деньги и вещи остались как были.');
  if (!положить(S, 'рыба', 1, { происхождение: 'рыбный сход' })) return false;
  S.герой.кошель -= 2;
  return сказать(S, 'Хозяйка заворачивает вяленую треску: рыба в сумке, −2 гроша. «После неё захочется пить».', true);
}

export function снятьНеделю(S) {
  const г = S.герой;
  if (!['утро', 'вечер'].includes(S.мир.отрезок)) return сказать(S, 'Хозяйка принимает утром и вечером. Сейчас деньги не берут.');
  if (г.жильё?.id === 'угол') return сказать(S, 'По договору каморки отдельная недельная плата не нужна. Это другая дверь того же дома.');
  if (г.жильё?.id === 'вдова' && г.жильё.оплачено_по >= S.мир.день) return сказать(S, `Ваша неделя уже оплачена по день ${г.жильё.оплачено_по} включительно. Повторной платы нет.`);
  if (г.кошель < 25) return сказать(S, 'Нужно 25 грошей. Хозяйка не берёт часть платы и не трогает прежние вещи.');
  г.кошель -= 25;
  г.жильё = { id: 'вдова', оплачено_по: S.мир.день + 6 };
  (г.хранилище ??= {}).вдова ??= [];
  кварталы(S).встречиВдовы.push(S.мир.день);
  return сказать(S, `Хозяйка выдаёт ключ недельной комнаты и записывает 25 грошей: семь ночей по день ${г.жильё.оплачено_по}. Сундук на 16 мест. Каморка по долгому договору остаётся отдельным помещением.`, true);
}

export function спатьВДоме(S) {
  const г = S.герой, ж = г.жильё;
  if (S.мир.отрезок !== 'ночь' || !(ж?.id === 'угол' || ж?.id === 'вдова' && ж.оплачено_по >= S.мир.день)) return сказать(S, 'Ночлег доступен ночью в оплаченном помещении. Сначала поговорите с хозяйкой об условиях.');
  сказать(S, 'Хозяйка узнаёт шаги на лестнице. Сегодня можно закрыть дверь и спокойно выспаться.', true);
  if (S.сцена) S.сцена.конец = 'уйти';
  лечьСпать(S, { ...ЖИЛЬЁ.find(x => x.id === 'вдова'), id: ж.id, имя: ж.id === 'угол' ? 'Каморка по договору' : 'Комната у вдовы', цена: 0 });
}

export function услугаШвеи(S, id) {
  if (!обычныйПриём(S)) return сказать(S, 'Мастерица принимает утром и днём. Сейчас вещь и деньги остаются у вас.');
  if (!купитьУслугу(S, id)) return сказать(S, '«Нечего подшивать или не хватает платы». Вещь остаётся прежней, деньги не списаны.');
  кварталы(S).швея = { день: S.мир.день, услуга: id, uid: S.герой.одежда.база.uid };
  return сказать(S, 'Мастерица проводит пальцем вдоль крепкого шва, довольная результатом. Работа закончена при вас; мастерица возвращает ту же одежду.', true);
}

// v13 меняет географию, не права, экземпляры или уже оплаченную смену.
export function мигрироватьКварталы(S) {
  const сц=S.сцена;
  if(сц?.отрезок==='ночь'&&сц.вход?.день<S.мир.день&&!сц.отложеннаяНочь)сц.ночьЗакрытаДоМиграции=true;
  if (S.мир.район === 'локи') S.мир.район = 'рыбацкий-берег';
  const перенесены = { 'лачуга-локи': 'рыбацкий-берег', ночлежка: 'жилые-улицы', лекарь: 'жилые-улицы' };
  if (перенесены[S.сцена?.место]) S.мир.район = перенесены[S.сцена.место];
  if (S.мир.смена?.работа === 'чтец') {
    S.мир.смена.район = 'сухопутные-ворота';
    S.мир.район = 'сухопутные-ворота';
  }
  кварталы(S);
  return S;
}
