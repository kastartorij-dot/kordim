// Сопоставление гири с доковой книгой. Судьбой журнала управляет единая нить-бренна.js.
import { естьВещь } from './вещи.js';
import { выводБренна,состояниеЖурнала,решитьЖурнал,итогБренна } from './нить-бренна.js';
const состояния={вернуть:'возвращён',дорр:'у_дорра',нотариус:'продан',сжечь:'сожжён',оставить:'оставлен'};
export const бренн=S=>(S.мир.сверкаВесов??={сопоставил:false,поручение:false});
export function условиеБренна(S,вид){
 const б=S.мир.сверкаВесов??{сопоставил:false,поручение:false},с=S.мир.свидетельства??[];
 if(вид==='копия-веса')return с.includes('brenn_office_entry')&&!с.includes('brenn_alt_weight');
 if(вид==='сопоставить')return !б.сопоставил&&выводБренна(S).узлов>=5&&с.includes('brenn_office_entry')&&(естьВещь(S,'гиря')||с.includes('brenn_alt_weight'));
 if(вид==='поручение')return состояниеЖурнала(S)==='у_дорра'&&!б.поручение;
 return !!состояния[вид]&&б.сопоставил&&['получен','оставлен'].includes(состояниеЖурнала(S))&&состояниеЖурнала(S)!==состояния[вид]&&естьВещь(S,'второй-журнал');
}
export function применитьБренна(S,вид){
 if(!условиеБренна(S,вид))return false;
 const б=бренн(S);
 if(вид==='копия-веса'){S.мир.свидетельства.push('brenn_alt_weight');S.мир.журналДня.push('Доковый эталон сверён с выпиской Браса. Это заменяет перенос гири, но не остальные свидетельства.');return true;}
 if(вид==='сопоставить'){б.сопоставил=true;S.мир.журналДня.push('Доковая книга и гиря либо эталон сопоставлены. Разница веса проверена; виновник смерти этими записями не установлен.');return true;}
 if(вид==='поручение'){б.поручение=true;S.герой.кошель+=12;S.мир.журналДня.push('Опись на складе сверена для Дорра. Выплата 12 гр. за отдельную работу, один раз.');return true;}
 return решитьЖурнал(S,состояния[вид]);
}
export const сводкаБренна=S=>{const в=выводБренна(S);return [в.узлов+' из 9 мест дали свидетельства.',в.текст,S.мир.сверкаВесов?.сопоставил?'Вес сопоставлен с доковой книгой.':'В доковой весовой можно бесплатно сверить эталон и сопоставить его с книгой после пяти источников.',итогБренна(S)];};
