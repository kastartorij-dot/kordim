// Кража во сне. Общая для сна на карте (движок/действия.js) и для ночи в сцене ночлежки (движок/ночлежка.js).
// Шанс — [раз, из скольких]; у кого при себе больше 100 гр., у того шанс в полтора раза выше. Берут последнюю
// вещь из сумки, не «важную» и не «дело»; если вещей нет — половину кошеля вниз.
import { бросок } from './случай.js';
import { привестиВещи, потерятьВещь, вещь as типВещи } from './вещи.js';

export function шансКражи(S, [а, б], множитель = 1) {
  return Math.min(1, а / б * (S.герой.кошель > 100 ? 1.5 : 1) * множитель);
}

// Один бросок: случится ли кража. Шанс 0 (кошелёк у хозяина) бросок не тратит.
export function кражаСлучилась(S, шанс, множитель = 1) {
  const ш = шансКражи(S, шанс, множитель);
  return ш > 0 && бросок(S) < ш;
}

// Сама кража: строка для журнала дня или null, если взять было нечего.
export function украсть(S, имяЖилья) {
  // Слово часовни про запас: рядом оказывается человек из тех, кому помогала Уна, и вора останавливают.
  const слово=S.мир.покров;
  const ночь=S.сцена?.вход?.день??S.мир.день;
  const здесь=S.сцена?.место==='ночлежка'||(!S.сцена&&S.мир.район==='жилые-улицы'&&имяЖилья==='Ночлежка');
  if (слово?.активен && здесь && ночь >= (слово.с??0) && ночь <= (слово.до??((слово.с??ночь)+7))) {
    S.мир.покров.активен = false;
    S.мир.покров.потрачено = S.мир.день;
    S.мир.журналДня.push('Тон получил просьбу Уны, следил за койкой и остановил вора. Обещанный присмотр использован один раз');
    return null;
  }
  const добыча = [...привестиВещи(S)].reverse().find(x => !типВещи(x.тип)?.важно && !типВещи(x.тип)?.дело && !x.дело);
  if (добыча) {
    потерятьВещь(S, добыча.uid, `украли во сне (${имяЖилья})`);
    return S.мир.журналДня.at(-1);
  }
  const у = Math.floor(S.герой.кошель / 2);
  if (у <= 0) return null;
  S.герой.кошель -= у;
  const строка = `${имяЖилья}: украли ${у} гр.`;
  S.мир.журналДня.push(строка);
  return строка;
}
