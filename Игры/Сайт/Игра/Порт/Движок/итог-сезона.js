// Итог сезона по разделам для экрана финала: что вышло с целью, люди, отец, как он жил.
// Общий для дня 30 (Движок/цели.js) и раннего отъезда (Движок/уехать.js), поэтому уехавший
// получает тот же полный итог. Тексты страниц «Люди» и «Бренн» — Данные/финал.js.
// Плоский список «строки» — прежние короткие строки для журнала и проверок (итогСвязей, итогиРаботников).
// Здесь нет подсказок «что сделать дальше»: финал рассказывает, а не советует.
import { НОЧЛЕГИ_СЛОВАМИ, числа } from '../Данные/цели.js';
import { ФИНАЛ, СУДЬБЫ, ДОМ_В_ФИНАЛЕ } from '../Данные/финал.js';
import { ЛИНИИ } from '../Данные/связи.js';
import { итогСвязей, исходСвязи } from './связи.js';
import { РАБОТНИКИ_ДОМА, итогиРаботников } from '../Данные/работники-дома.js';
import { выводБренна, итогБренна } from './нить-бренна.js';
import { фразыЗаписей } from '../Данные/нить-бренна.js';

const УЕХАЛ = ['по-книге', 'по-руке', 'локи'];
// Записи о самом журнале отца на странице «Бренн» заменяет абзац о его судьбе.
const ПРО_ЖУРНАЛ = ['brenn_second_journal', 'brenn_second_journal_seen'];
const уехал = S => УЕХАЛ.includes(S.мир.уехать?.исход);

export function фактыЖизни(S) {
  const м = S.мир, строки = [];
  const смен = Object.values(м.работы ?? {}).reduce((n, р) => n + (р.смен ?? 0), 0);
  if (смен) строки.push(`Смен отработано: ${смен}.`);
  const ночи = Object.entries(м.ночи ?? {}).filter(([, n]) => n > 0)
    .map(([ключ, n]) => `${НОЧЛЕГИ_СЛОВАМИ[ключ] ?? ключ} — ${числа(n, ['ночь', 'ночи', 'ночей'])}`);
  if (ночи.length) строки.push(`Ночевал: ${ночи.join('; ')}.`);
  const слухов = (м.слухиОГерое ?? []).length;
  if (слухов) строки.push(`О нём ходят слухи: ${слухов}.`);
  const бренн = (м.свидетельства ?? []).filter(id => id.startsWith('brenn_')).length;
  if (бренн) строки.push(`О Бренне найдено записей и слов: ${бренн}.`);
  const обещаний = (м.обещания ?? []).length;
  if (обещаний) строки.push(`Оставил обещаний: ${обещаний}.`);
  return строки;
}

// Люди: абзац на каждую личную линию в порядке линий.
function людиВФинале(S) {
  const абзацы = [];
  for (const кто of Object.keys(ЛИНИИ)) {
    const с = S.мир.связи?.[кто], исход = с && исходСвязи(с);
    if (!исход) continue;
    const судьба = СУДЬБЫ[кто] ?? {};
    const отъезд = уехал(S) && (исход === 'вместе' || исход === 'дружба') ? судьба[исход + 'Отъезд'] : null;
    if (отъезд ?? судьба[исход]) абзацы.push(отъезд ?? судьба[исход]);
  }
  return абзацы;
}

// «Синий час»: один абзац о работниках дома, которых герой спросил сам; своя страница, чтобы «Люди» не уходили под прокрутку.
function домВФинале(S) {
  const спрошены = Object.keys(РАБОТНИКИ_ДОМА).filter(id => РАБОТНИКИ_ДОМА[id].итог && S.мир.диалоги?.[id]?.факты?.includes('дом_ответ'));
  return спрошены.length ? [[ДОМ_В_ФИНАЛЕ.вступление, ...спрошены.map(id => ДОМ_В_ФИНАЛЕ[id] ?? РАБОТНИКИ_ДОМА[id].итог)].join(' ')] : [];
}

// Отец: вступление по уровню, честная граница, судьба журнала (если он был в руках) — абзацами;
// фразы самих записей — отдельным списком, экран показывает их мелко после вступления.
function отецВФинале(S) {
  const в = выводБренна(S), О = ФИНАЛ.отец;
  if (!в.узлов) return { абзацы: [О.неСпрашивал], записи: [] };
  const понял = в.уровень === 'понимание' || в.уровень === 'полная';
  const абзацы = [понял ? О[в.уровень] : О.слух(числа(в.узлов, ['места', 'мест', 'мест']))];
  if (S.мир.сверкаВесов?.сопоставил) абзацы.push(О.сверено);
  else if (понял) абзацы.push(О.граница);
  const с = в.состояние;
  const журнал = уехал(S) && (с === 'получен' || с === 'оставлен') ? ФИНАЛ.журнал.увёз : ФИНАЛ.журнал[с];
  if (журнал) абзацы.push(журнал);
  const записи = фразыЗаписей(new Set((S.мир.свидетельства ?? []).filter(id => !ПРО_ЖУРНАЛ.includes(id))));
  return { абзацы, записи };
}

// Короткие строки об отце для журнала: без подсказок, судьба книги — только если о ней знали.
function отецКратко(S) {
  const в = выводБренна(S);
  if (!в.узлов && в.состояние === 'не_выдан') return [ФИНАЛ.отец.неСпрашивал];
  const строки = [`Свидетельства об отце — из ${числа(в.узлов, ['места', 'мест', 'мест'])} из девяти.`];
  if (S.мир.сверкаВесов?.сопоставил) строки.push('Вес сопоставлен с доковой книгой.');
  if (в.состояние !== 'не_выдан') строки.push(итогБренна(S));
  return строки;
}

export function разделыИтога(S, детали = []) {
  const отец = отецВФинале(S);
  return { цель: [...детали], люди: людиВФинале(S), дом: домВФинале(S), отец: отец.абзацы, записиОтца: отец.записи, жизнь: фактыЖизни(S) };
}

// Плоский итог в прежнем порядке: цель, жизнь, люди, отец — короткими строками журнала.
export const строкиИтога = (S, р) => [...р.цель, ...р.жизнь, ...итогСвязей(S), ...итогиРаботников(S), ...отецКратко(S)];
