// Время внутри места (Р19): то же, что снаружи. Место открыто в свои отрезки (Данные/места.js, «когда»)
// и может закрываться раньше конца отрезка («доДеления»). Сколько делений осталось до закрытия —
// столько можно потратить внутри; дальше «время вышло»: дочитать начатое и выйти.
import { место } from '../Данные/места.js';
import { ОТРЕЗКИ, ДЕЛЕНИЙ, деление, ёмкость } from './время.js';

const закрытиеВ = (м, отрезок, cap) => Math.min(cap, м.доДеления?.[отрезок] ?? cap);

export function открытоСейчас(S, местоId) {
  const м = место(местоId);
  if (!м || !м.когда.includes(S.мир.отрезок)) return false;
  return деление(S) < закрытиеВ(м, S.мир.отрезок, ёмкость(S));
}

// Делений до закрытия места (или до рассвета, если оно открыто всю ночь). Без сцены — 0.
export function доЗакрытия(S, местоId = S.сцена?.место) {
  if (!местоId || S.мир.рассветВСцене) return 0;
  const м = место(местоId);
  if (!м) return 0;
  const cap = ёмкость(S);
  let i = ОТРЕЗКИ.indexOf(S.мир.отрезок), д = деление(S), всего = 0;
  while (i < ОТРЕЗКИ.length) {
    const о = ОТРЕЗКИ[i];
    if (!м.когда.includes(о)) break;
    const конец = закрытиеВ(м, о, cap);
    всего += Math.max(0, конец - д);
    if (конец < cap) break;
    i += 1; д = 0;
  }
  return всего;
}

// Сколько прошло с открытия места сегодня и сколько оно открыто всего (для шапки и тинта «Синего часа»).
export function прошлоСОткрытия(S, местоId = S.сцена?.место) {
  const м = место(местоId);
  if (!м) return { прошло: 0, всего: 0 };
  const i = ОТРЕЗКИ.indexOf(S.мир.отрезок);
  if (!м.когда.includes(ОТРЕЗКИ[i])) return { прошло: 1, всего: 1 };
  let нач = i;
  while (нач > 0 && м.когда.includes(ОТРЕЗКИ[нач - 1])) нач -= 1;
  let всего = 0;
  for (let j = нач; j < ОТРЕЗКИ.length && м.когда.includes(ОТРЕЗКИ[j]); j++) {
    const к = закрытиеВ(м, ОТРЕЗКИ[j], ДЕЛЕНИЙ);
    всего += к;
    if (к < ДЕЛЕНИЙ) break;
  }
  return { прошло: Math.min(всего, (i - нач) * ДЕЛЕНИЙ + деление(S)), всего };
}

// Сколько делений ещё можно потратить в этом визите: до закрытия места, а у мест с пределом визита
// (модуль.пределВизита — правило самого места, как три платы у Локи) — не больше остатка предела.
export function осталосьВМесте(S) {
  const с = S.сцена;
  if (!с || с.времяВышло) return 0;
  const предел = место(с.место)?.модуль.пределВизита;
  const доЗакр = доЗакрытия(S);
  return предел ? Math.min(доЗакр, Math.max(0, предел - (с.ходы ?? 0))) : доЗакр;
}
