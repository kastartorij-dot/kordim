// Номер изменения мира хранится в сохранении. Кнопка, построенная до предыдущего
// действия, больше не может повторно списать деньги или время.
export function обернутьШаг(S, действия) {
  const номер = S.мир.шаг ?? 0;
  return действия.map(д => ({ ...д, выполнить(S2) {
    if (!д.можно || (S2.мир.шаг ?? 0) !== номер) return null;
    const результат = д.выполнить(S2);
    S2.мир.шаг = номер + 1;
    return результат;
  } }));
}
