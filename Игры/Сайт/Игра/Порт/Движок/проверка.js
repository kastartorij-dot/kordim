// Проверки диалогов: 2d6 + модификатор ≥ порог (концепт диалогов §4, ПЛАН_ДОРАБОТКИ П05.6). Без DOM.
// Бросок — функция (зерно кампании, id проверки, номер попытки), а не «следующее число из потока»: поэтому «назад»,
// загрузка и любое постороннее действие дают тот же результат. Переиграть можно только изменив модификатор.
import { ступеньГолоса } from './голоса.js';
import { естьВещь } from './вещи.js';
import { верностьТемы } from './знание.js';
import { ПОДТВЕРЖДЕНО } from './знание.js';

export const ПОРОГИ = { лёгко: 6, средне: 8, трудно: 10, оченьТрудно: 12 };
export const ПОРОГ_СЛОВОМ = { 6: 'Лёгко', 8: 'Средне', 10: 'Трудно', 12: 'Очень трудно' };
export const МОД_ОТ = -2, МОД_ДО = 5;
const УМ = ['МЕРА', 'СТРОКА', 'ИГЛА', 'МОЛВА', 'ЧУТЬЁ', 'ОТЕЦ', 'ДЫМ'];

export const порогЧислом = п => (typeof п === 'number' ? п : ПОРОГИ[п] ?? 8);

// Точный шанс успеха в процентах: перебор 36 исходов двух кубиков.
export function шанс(порог, мод) {
  let ок = 0;
  for (let a = 1; a <= 6; a++) for (let b = 1; b <= 6; b++) if (a + b + мод >= порог) ок++;
  return Math.round((ок / 36) * 100);
}

// Хеш строки → поток 32-битных чисел (cyrb128-подобный). Никакого состояния снаружи.
function поток(строка) {
  let h1 = 1779033703, h2 = 3144134277, h3 = 1013904242, h4 = 2773480762;
  for (let i = 0; i < строка.length; i++) {
    const k = строка.charCodeAt(i);
    h1 = h2 ^ Math.imul(h1 ^ k, 597399067); h2 = h3 ^ Math.imul(h2 ^ k, 2869860233);
    h3 = h4 ^ Math.imul(h3 ^ k, 951274213); h4 = h1 ^ Math.imul(h4 ^ k, 2716044179);
  }
  let a = (h1 ^ h2 ^ h3 ^ h4) >>> 0;
  return () => { a = (a + 0x6D2B79F5) >>> 0; let t = Math.imul(a ^ (a >>> 15), a | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}
export function кубики(зерно, id, попытка) {
  const р = поток(`${зерно}|${id}|${попытка}`);
  return [Math.floor(р() * 6) + 1, Math.floor(р() * 6) + 1];
}

// Модификатор = ступень голоса + факты − нужды; части для разбора по нажатию на чип.
export function модификатор(S, п, ctx = {}) {
  const части = [];
  const ст = ступеньГолоса(S, п.голос);
  if (ст) части.push({ что: 'голос ' + п.голос, д: ст });
  for (const ф of п.факты ?? []) {
    if (ф.тема && верностьТемы(S, ф.тема) === ПОДТВЕРЖДЕНО) части.push({ что: ф.что ?? 'тема подтверждена', д: 1 });
    if (ф.предмет && естьВещь(S, ф.предмет)) части.push({ что: ф.что ?? 'нужная вещь', д: 1 });
    if (ф.вид && (S.герой.вид ?? 3) >= ф.вид) части.push({ что: ф.что ?? 'подходящий вид', д: 1 });
    if (ф.распол && (S.мир.люди?.[ф.распол.кто]?.распол ?? 0) >= ф.распол.от) части.push({ что: ф.что ?? 'расположение', д: 1 });
    if (ф.факт && (S.мир.диалоги?.[ф.факт.кто]?.факты ?? []).includes(ф.факт.ид)) части.push({ что: ф.что ?? 'уже известно', д: 1 });
  }
  const т = S.герой.тело;
  if (УМ.includes(п.голос)) {
    if (т.отдых <= 1) части.push({ что: 'не выспался', д: -1 });
    if (т.сыт === 0) части.push({ что: 'голодный', д: -1 });
  }
  if (п.голос === 'ЧУТЬЁ' && (S.герой.хмель ?? 0) >= 2) части.push({ что: 'хмель', д: -1 });
  if ((п.голос === 'ЧУТЬЁ' || п.голос === 'МОЛВА') && (S.герой.напряжение ?? 0) >= 3) части.push({ что: 'внимание уходит', д: -1 });
  const сумма = части.reduce((а, ч) => а + ч.д, 0);
  return { значение: Math.max(МОД_ОТ, Math.min(МОД_ДО, сумма)), части };
}

const состояние = (S, id) => (S.мир.проверки[id] ??= { попыток: 0, модПровала: null, итог: null });

// Можно ли пробовать сейчас. Белая: после провала закрыта, пока модификатор не вырос («ещё раз»). Красная: одна попытка на игру.
// Белая после успеха закрыта: награду второй раз не получить.
export function статус(S, id, п, мод) {
  const с = S.мир.проверки[id];
  if (!с || с.итог === null) return { можно: true, новая: true };
  if (п.тип === 'красная') return { можно: false, почему: 'красная проверка: попытка была' };
  if (с.итог === 'успех') return { можно: false, почему: 'это уже удалось' };
  if (п.сброс && п.сброс(S)) return { можно: true, ещёРаз: true };
  if (мод > (с.модПровала ?? -99)) return { можно: true, ещёРаз: true };
  return { можно: false, почему: 'пока ничего не изменилось' };
}

// Карточка проверки для чипа в варианте.
export function карточка(S, id, п, ctx) {
  const мод = модификатор(S, п, ctx);
  const порог = порогЧислом(п.порог);
  const ст = статус(S, id, п, мод.значение);
  return { голос: п.голос, порог, слово: ПОРОГ_СЛОВОМ[порог] ?? String(порог), мод, шанс: шанс(порог, мод.значение), тип: п.тип ?? 'белая', ...ст };
}

// Бросок. Пишет S.мир.проверки[id]; повторный вызов для той же попытки даёт тот же результат.
export function бросить(S, id, п, ctx) {
  const мод = модификатор(S, п, ctx);
  const порог = порогЧислом(п.порог);
  const с = состояние(S, id);
  const попытка = с.попыток + 1;
  const [a, b] = кубики(S.мир.зерноКампании, id, попытка);
  const сумма = a + b + мод.значение;
  const успех = сумма >= порог;
  с.попыток = попытка;
  с.итог = успех ? 'успех' : 'провал';
  if (!успех) с.модПровала = мод.значение;
  return { успех, кубики: [a, b], сумма, порог, мод, шанс: шанс(порог, мод.значение), попытка };
}

// Пассивная: без нажатия, один раз на id за сейв. Провал ничего не показывает — игрок не знает, что пропустил.
export function пассивная(S, id, п, ctx) {
  const с = S.мир.проверки[id];
  if (с && с.итог !== null) return с.итог === 'успех';
  return бросить(S, id, п, ctx).успех;
}
