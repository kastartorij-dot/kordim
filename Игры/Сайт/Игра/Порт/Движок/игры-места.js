// Мини-игры в месте (шаг 12): «Торг» у лотка и «Кости». Без DOM; данные — Данные/торг.js и Данные/кости.js.
// Пока идёт игра, сцена показывает её карточку и её ходы вместо действий комнаты: Движок/разговор.js спрашивает
// ходыИгры / видИгры, а эффект места `игра: { вид, … }` начинает партию. Состояние — S.сцена.игра (переживает
// сохранение вместе со сценой); то, что помнится дольше визита, — в записи места (торг дня, спрошенные вопросы).
// Начать игру даром; итог применяется один раз при закрытии и стоит один ход визита.
import { ТОРГ, СЛОВА_ТОРГА, ТЕРПЕНИЕ } from '../Данные/торг.js';
import { КОСТИ, ШАНС_СЛОВАМИ } from '../Данные/кости.js';
import { цена, раундов, максРаундов, верных, промахов, сказано, перегнул, можноТорговаться, можноДавить, сказатьДовод, давить, итогПокупки, деньСцены } from './торг.js';
import { кубики } from './проверка.js';
import { ступеньНомер } from './ремёсла.js';
import { можноПоложить, имяВещи } from './вещи.js';

const подставить = (текст, ц) => текст.replace('{цена}', String(ц));
const сумма = к => к[0] + к[1];
export const ГРАНИ = ['⚀', '⚁', '⚂', '⚃', '⚄', '⚅'];
const кость = v => `${ГРАНИ[v - 1]} ${v}`;

export const играИдёт = S => !!S.сцена?.игра;

// ── начало ───────────────────────────────────────────────────────────────
// Каждый ход игры стирает историю «назад»: бросок и ответ продавца нельзя подсмотреть и переиграть.
const безОтката = S => { S.история = []; };

export function начатьИгру(S, з) {
  const с = S.сцена;
  if (!с || с.игра) return false;
  безОтката(S);
  if (з.вид === 'торг') {
    const т = ТОРГ[з.товар];
    if (!т) return false;
    с.игра = { вид: 'торг', товар: з.товар, совет: null, отпал: null, реплика: подставить(СЛОВА_ТОРГА.начало, цена(S, з.товар)) };
    return true;
  }
  if (з.вид === 'кости') {
    const п = КОСТИ[з.партия];
    if (!п) return false;
    с.игра = { вид: 'кости', партия: з.партия, кон: 1, его: null, мои: null, переброшена: null, стадия: 'решение', реплика: п.начало, итог: null };
    бросить(S);
    return true;
  }
  return false;
}

// ── кости: броски из зерна кампании ──────────────────────────────────────
const основа = S => `кости:${S.сцена.игра.партия}:${деньСцены(S)}`;
const зерно = S => S.мир.зерноКампании ?? S.мир.сид ?? 0;
function бросить(S) {
  const и = S.сцена.игра, п = КОСТИ[и.партия];
  и.мои = кубики(зерно(S), основа(S) + ':мои', и.кон);
  и.его = п.соперникПервым ? кубики(зерно(S), основа(S) + ':его', и.кон) : null;
  и.переброшена = null; и.стадия = 'решение';
}

// Соперник, что бросает после (моряк): если не впереди (проигрывает или вровень) — перебрасывает меньшую кость один раз.
function ходСоперника(S, мояСумма) {
  const и = S.сцена.игра;
  const к = кубики(зерно(S), основа(S) + ':его', и.кон);
  if (сумма(к) <= мояСумма) {
    const i = к[0] <= к[1] ? 0 : 1, было = к[i];
    к[i] = кубики(зерно(S), основа(S) + ':его-переброс', и.кон)[0];
    и.егоПереброс = { было, стало: к[i] };
  }
  return к;
}

// Исход для моей итоговой суммы: { выигрыш, вровень, проигрыш } долями.
function исходыПротив(п, его, м) {
  if (п.соперникПервым) { const g = сумма(его); return { выигрыш: +(м > g), вровень: +(м === g), проигрыш: +(м < g) }; }
  let в = 0, р = 0, пр = 0;
  for (let a = 1; a <= 6; a++) for (let b = 1; b <= 6; b++) {
    if (a + b > м) { пр += 1 / 36; continue; }
    const старшая = Math.max(a, b);
    for (let c = 1; c <= 6; c++) { const s = старшая + c; if (s > м) пр += 1 / 216; else if (s === м) р += 1 / 216; else в += 1 / 216; }
  }
  return { выигрыш: в, вровень: р, проигрыш: пр };
}

// Шанс каждого решения: оставить или перебросить одну кость.
export function шансыКостей(S) {
  const и = S.сцена.игра, п = КОСТИ[и.партия];
  const оставить = исходыПротив(п, и.его, сумма(и.мои));
  const переброс = [0, 1].map(i => {
    const итог = { выигрыш: 0, вровень: 0, проигрыш: 0 };
    for (let v = 1; v <= 6; v++) {
      const к = [...и.мои]; к[i] = v;
      const x = исходыПротив(п, и.его, сумма(к));
      for (const ключ in итог) итог[ключ] += x[ключ] / 6;
    }
    return итог;
  });
  return { оставить, переброс };
}

// Подпись шанса: грамотный считает числом, остальные видят словами.
export function словоШанса(S, ш) {
  if (S.герой.ремёсла?.грамота) return `выиграешь ${Math.round(ш.выигрыш * 100)}%` + (ш.вровень > 0.005 ? ` · вровень ${Math.round(ш.вровень * 100)}%` : '');
  const p = ш.выигрыш + ш.вровень / 2;
  return ШАНС_СЛОВАМИ.find(([от]) => p >= от)[1];
}

// ── ходы ─────────────────────────────────────────────────────────────────
// ctx: { применить(S, эффект места), времяИдёт(S, ходов) } — из Движок/разговор.js.
export function ходыИгры(S, ctx) {
  const и = S.сцена?.игра;
  if (!и) return [];
  const ходы = и.вид === 'торг' ? ходыТорга(S, и, ctx) : ходыКостей(S, и, ctx);
  return ходы.map(х => ({ ...х, ход: S2 => { безОтката(S2); х.ход(S2); } }));
}

function закрыть(S, ctx, реплика, эффект = null) {
  const с = S.сцена;
  с.игра = null;
  с.реплика = реплика; с.мояреплика = '';
  if (эффект) ctx.применить(S, эффект);
  ctx.времяИдёт(S, 1);
}

function ходыТорга(S, и, ctx) {
  const т = ТОРГ[и.товар], ц = цена(S, и.товар), имя = имяВещи(т.вещь);
  const ходы = [];
  const ход = (id, текст, подпись, можно, почему, f) => ходы.push({ id: `игра:торг:${id}`, вид: 'вариант', текст, подпись, можно, почему, ход: f });
  if (можноТорговаться(S, и.товар)) {
    for (const д of т.доводы) {
      if (сказано(S, и.товар).includes(д.id)) continue;
      if (д.условие?.отрезок && д.условие.отрезок !== S.сцена.отрезок) continue;
      const нетДенег = д.сразу && S.герой.кошель < ц;
      const отпал = и.отпал === д.id;
      ход('довод:' + д.id, д.текст, '', !нетДенег && !отпал,
        отпал ? 'не довод: ремесло видит' : нетДенег ? 'столько при себе нет' : null,
        S2 => {
          const р = сказатьДовод(S2, и.товар, д.id);
          if (!р) return;
          S2.сцена.игра.реплика = р.реплика;
          if (р.перегиб) ctx.применить(S2, { распол: { [т.продавец]: -1 } });
        });
    }
  }
  const ст = ступеньНомер(S, т.ремесло);
  if (ст >= 0 && !и.совет && можноТорговаться(S, и.товар))
    ход('совет', 'Присмотреться, как учит ремесло', т.ремесло, true, null, S2 => {
      const x = S2.сцена.игра;
      x.совет = т.совет;
      if (ст >= 1) x.отпал = т.доводы.find(д => !д.верный && !сказано(S2, x.товар).includes(д.id))?.id ?? null;
    });
  if (можноДавить(S, и.товар))
    ход('давить', 'Давить на цену дальше', 'продавец потеряет терпение', true, null, S2 => {
      const р = давить(S2, и.товар);
      if (!р) return;
      S2.сцена.игра.реплика = р.реплика;
      ctx.применить(S2, { распол: { [т.продавец]: -1 } });
    });
  const мало = S.герой.кошель < ц, нетМеста = !можноПоложить(S, т.вещь);
  ход('купить', `Беру за ${ц} гр.`, `${ц} гр. · 1 ход`, !мало && !нетМеста, мало ? 'не хватает грошей' : нетМеста ? 'в сумке нет места' : null, S2 => {
    const ц2 = цена(S2, и.товар);
    if (S2.герой.кошель < ц2 || !можноПоложить(S2, т.вещь)) return;
    const р = итогПокупки(S2, и.товар);
    S2.герой.кошель -= ц2;
    S2.мир.журналДня.push(`Торг: ${имя} за ${ц2} гр.${ц2 < т.запрос ? ` (просили ${т.запрос})` : ''}`);
    закрыть(S2, ctx, р.реплика, { предмет: т.вещь, разВДень: и.товар, ...(р.распол ? { распол: { [т.продавец]: р.распол } } : {}) });
  });
  ход('уйти', 'Не беру', раундов(S, и.товар) ? '1 ход' : 'даром', true, null, S2 => {
    if (!раундов(S2, и.товар)) { const с = S2.сцена; с.игра = null; с.реплика = СЛОВА_ТОРГА.ушёл; return; }
    закрыть(S2, ctx, СЛОВА_ТОРГА.ушёл);
  });
  return ходы;
}

const памятьКостей = (S, п) => ((S.мир.места[п.место] ??= {}).кости ??= { спросил: [], спрашивал: [] });

function ходыКостей(S, и, ctx) {
  const п = КОСТИ[и.партия];
  const ходы = [];
  const ход = (id, текст, подпись, f, можно = true, почему = null) => ходы.push({ id: `игра:кости:${id}`, вид: 'вариант', текст, подпись, можно, почему, ход: f });
  if (и.стадия === 'решение') {
    const ш = шансыКостей(S);
    ход('оставить', `Оставить ${кость(и.мои[0])} и ${кость(и.мои[1])}`, словоШанса(S, ш.оставить), S2 => решить(S2, null, ctx));
    const порядок = и.мои[0] === и.мои[1] ? [0] : [0, 1].sort((a, b) => и.мои[a] - и.мои[b]);
    for (const i of порядок) ход('переброс:' + i, `Перебросить ${кость(и.мои[i])}`, словоШанса(S, ш.переброс[i]), S2 => решить(S2, i, ctx));
  } else if (и.стадия === 'ничья') {
    ход('ещё', 'Бросить ещё раз', 'ничья переигрывается', S2 => { const x = S2.сцена.игра; x.кон += 1; бросить(S2); x.реплика = 'Горм собирает кости и бросает снова.'; });
  } else if (и.стадия === 'вопрос') {
    const пам = памятьКостей(S, п);
    for (const в of п.вопросы.filter(в => !пам.спросил.includes(в.id)))
      ход('вопрос:' + в.id, в.текст, 'твой вопрос · 1 ход', S2 => {
        памятьКостей(S2, п).спросил.push(в.id);
        S2.мир.журналДня.push(`Кости с Гормом: выиграл, спросил — ${в.текст.replace(/[«»]/g, '')}`);
        закрыть(S2, ctx, в.ответ, { ...(в.эффект ?? {}), разВДень: 'кости' });
      });
  } else if (и.стадия === 'ответ') {
    const в = п.егоВопросы.find(x => !памятьКостей(S, п).спрашивал.includes(x.id));
    ход('ответ:' + в.id, в.кнопка, 'честно · 1 ход', S2 => {
      памятьКостей(S2, п).спрашивал.push(в.id);
      S2.мир.журналДня.push(`Кости с Гормом: проиграл, ответил правду. ${в.текст}`);
      закрыть(S2, ctx, в.ответ, { ...(в.эффект ?? {}), разВДень: 'кости' });
    });
  }
  return ходы;
}

// Решение Одвина: оставить (i = null) или перебросить кость i. Потом — исход партии.
function решить(S, i, ctx) {
  const и = S.сцена.игра, п = КОСТИ[и.партия];
  if (и.стадия !== 'решение') return;
  if (i !== null) { и.мои = [...и.мои]; и.мои[i] = кубики(зерно(S), основа(S) + ':переброс:' + i, и.кон)[0]; и.переброшена = i; }
  const м = сумма(и.мои);
  if (!п.соперникПервым) и.его = ходСоперника(S, м);
  const g = сумма(и.его);
  const пер = и.егоПереброс ? ` (перебросил ${кость(и.егоПереброс.было)} — вышло ${кость(и.егоПереброс.стало)})` : '';
  const счёт = `Ты: ${кость(и.мои[0])} и ${кость(и.мои[1])} — ${м}. ${п.имя}: ${кость(и.его[0])} и ${кость(и.его[1])} — ${g}${пер}.`;
  if (и.партия === 'таверна') {
    const ст = п.ставка, исход = м > g ? 'выигрыш' : м < g ? 'проигрыш' : 'вровень';
    if (исход === 'выигрыш') S.герой.кошель += ст;
    if (исход === 'проигрыш') S.герой.кошель -= ст;
    S.мир.журналДня.push(`Кости с моряком: ${исход === 'выигрыш' ? `+${ст}` : исход === 'проигрыш' ? `−${ст}` : '±0'} гр.`);
    закрыть(S, ctx, счёт + '\n\n' + п[исход], { разВДень: 'кости-таверна', ...(исход === 'выигрыш' ? { распол: { [п.соперник]: 1 } } : {}) });
    return;
  }
  if (м === g) { и.стадия = 'ничья'; и.реплика = счёт + '\n\nВровень. Горм не встаёт: «Ещё раз».'; return; }
  const пам = памятьКостей(S, п);
  if (м > g) {
    if (п.вопросы.every(в => пам.спросил.includes(в.id))) { S.мир.журналДня.push('Кости с Гормом: выиграл, вопросов больше нет'); закрыть(S, ctx, счёт + '\n\n' + п.всё, { разВДень: 'кости' }); return; }
    и.стадия = 'вопрос'; и.реплика = счёт + '\n\nГорм кладёт ладони на стол. «Спрашивай».';
    return;
  }
  if (п.егоВопросы.every(в => пам.спрашивал.includes(в.id))) { S.мир.журналДня.push('Кости с Гормом: проиграл'); закрыть(S, ctx, счёт + '\n\n' + п.молчит, { разВДень: 'кости' }); return; }
  и.стадия = 'ответ';
  и.реплика = счёт + '\n\n' + п.егоВопросы.find(x => !пам.спрашивал.includes(x.id)).текст;
}

// ── вид для экрана ───────────────────────────────────────────────────────
export function видИгры(S) {
  const и = S.сцена?.игра;
  if (!и) return null;
  if (и.вид === 'торг') {
    const т = ТОРГ[и.товар];
    return {
      вид: 'торг', заголовок: `Торг · ${имяВещи(т.вещь)}`, видно: т.видно, реплика: и.реплика, совет: и.совет,
      цена: цена(S, и.товар), запрос: т.запрос, раунд: раундов(S, и.товар), раундов: максРаундов(S),
      терпение: Math.max(0, ТЕРПЕНИЕ - промахов(S, и.товар)), из: ТЕРПЕНИЕ, перегиб: перегнул(S, и.товар), верных: верных(S, и.товар),
      правило: 'Один довод за раунд. Верный опирается на то, что видно, и сбавляет цену; неверный злит продавца. Ниже честной цены не уступят.',
    };
  }
  const п = КОСТИ[и.партия];
  return {
    вид: 'кости', заголовок: `Кости · ${п.имя}`, реплика: и.реплика, стадия: и.стадия, кон: и.кон,
    мои: и.мои && { кости: и.мои, сумма: сумма(и.мои), переброшена: и.переброшена },
    его: и.его && { кто: п.имя, кости: и.его, сумма: сумма(и.его) },
    ставка: п.ставка ?? null, точно: !!S.герой.ремёсла?.грамота,
    правило: п.соперникПервым
      ? 'У каждого две кости, больше сумма — выиграл. Его бросок виден; свою кость можно один раз перебросить. Вровень — бросаете снова.'
      : 'У каждого две кости, больше сумма — выиграл. Ты бросаешь первым и можешь один раз перебросить кость; он бросает после и перебросит меньшую, если не впереди. Вровень — ставки обратно.',
  };
}
