// Варианты живых мини-игр в самой игре (с 03.11, круг 5): что выпадает на этот раз — по тому, который раз,
// где и в какой день. Без DOM. Сами варианты (нрав торговца, груз, противник, накладная) — в модулях песочницы
// (Движок/песочница/<игра>.js, экспорт варианты), их подводки и следы для игры — в данных игр.
//
// Счётчик партий — S.мир.партии[ключ] = { раз, был }: сколько партий сыграно и какой вариант был последним.
// Поле необязательное: в старом сохранении его нет — значит, партий ещё не было; версия сохранения та же.
//
// Вариант в данных: { id, где?, когда?, … }
//   где — где он вообще может выпасть (фильтр): { работа: [...], товар: [...], разОт: n };
//   когда — особый случай дня (тянет к себе): { отрезок, рыночный, расчётный, обоз, товар }.
// Первый раз — всегда первый вариант списка (самый понятный). Дальше — из особых, если день особый,
// иначе из обычных; никогда не тот же, что в прошлый раз, если есть из чего выбрать. Выбор от зерна дня и номера
// партии, поэтому перезагрузка и «назад» дают тот же вариант.
import { рыночныйДень, расчётныйДень, деньОбоза } from '../Данные/календарь.js';

export const партия = (S, ключ) => S.мир.партии?.[ключ] ?? { раз: 0, был: null };

export function отметитьПартию(S, ключ, вариант) {
  const п = партия(S, ключ);
  (S.мир.партии ??= {})[ключ] = { раз: п.раз + 1, был: вариант ?? п.был };
}

// Что сегодня за день и час: для условий где / когда.
export function ситуация(S, { день = S.мир.день, отрезок = S.мир.отрезок, ...ещё } = {}) {
  return { день, отрезок, рыночный: рыночныйДень(день), расчётный: расчётныйДень(день), обоз: деньОбоза(день), ...ещё };
}

const совпало = (условие, с) => Object.entries(условие).every(([к, v]) => (к === 'разОт' ? с.раз >= v : [].concat(v).includes(с[к])));

function хэш(строка) {
  let h = 2166136261;
  for (const ч of строка) h = Math.imul(h ^ ч.codePointAt(0), 16777619);
  return h >>> 0;
}

// Вариант (запись из списка) для ключа партии в этой ситуации.
export function выбратьВариант(S, ключ, список, с) {
  const п = партия(S, ключ);
  if (!п.раз) return список[0];
  const сит = { ...с, раз: п.раз };
  const годные = список.filter(в => !в.где || совпало(в.где, сит));
  const особые = годные.filter(в => в.когда && совпало(в.когда, сит));
  // особый день, но его вариант был в прошлый раз — тогда обычный: каждый вечер одно и то же не выпадет
  const из = [особые, годные.filter(в => !в.когда), годные, список]
    .map(к => к.filter(в => в.id !== п.был)).find(к => к.length) ?? список;
  return из[хэш(`${ключ}:${сит.день}:${п.раз}`) % из.length];
}

// Вариант по id (старое сохранение без варианта — первый).
export const вариантПо = (список, id) => список.find(в => в.id === id) ?? список[0];
