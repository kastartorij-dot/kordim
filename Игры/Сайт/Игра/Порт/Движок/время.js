export const ОТРЕЗКИ = ['утро', 'день', 'вечер', 'ночь'];
export const снимокТела = S => ({ отдых: S.герой.тело.отдых, цел: S.герой.тело.цел });

// ── Одна шкала (Р19, концепт `Документы/Материалы/Концепты/Время_одна_шкала_12_11/`) ──
// В отрезке 6 делений, в сутках 24. Всё, что занимает время, тратит деления одной шкалы:
// вопрос в месте — как в данных (`ходы`), дорога 1–3, смена 6. Без сил (отдых 0) или
// с разбитым телом (цел 0) в отрезке только 4 деления: день короче, а не дороже.
export const ДЕЛЕНИЙ = 6;
export const ДЕЛЕНИЙ_УСТАЛ = 4;
export const ПОЗДНО = 3; // делений ночи, после которых сон на 1 хуже
export const устал = S => S.герой.тело.отдых === 0 || S.герой.тело.цел === 0;
export const ёмкость = S => (устал(S) ? ДЕЛЕНИЙ_УСТАЛ : ДЕЛЕНИЙ);
export const деление = S => S.мир.деление ?? 0;
export const осталось = S => Math.max(0, ёмкость(S) - деление(S));
export const можноЛечь = S => S.мир.отрезок === 'вечер' || S.мир.отрезок === 'ночь';
export const поздно = S => S.мир.отрезок === 'ночь' && деление(S) > ПОЗДНО;

// Граница отрезка: следующий с деления 0. false — это был рассвет.
function границаОтрезка(S) {
  const i = ОТРЕЗКИ.indexOf(S.мир.отрезок);
  if (i >= ОТРЕЗКИ.length - 1) return false;
  S.мир.отрезок = ОТРЕЗКИ[i + 1];
  S.мир.деление = 0;
  if (S.сцена) S.сцена.отрезок = S.мир.отрезок; // внутри места время то же, что снаружи
  проверитьСроки(S);
  return true;
}

// Деление на улице: дождь и мокрая одежда — по делениям вне крыши; груз — только в дороге (тюк тяжёл в пути, а не в ожидании).
function наУлице(S, вПути) {
  const м = S.мир, т = S.герой.тело, у = (м.улица ??= { дождь: 0, мокро: 0, груз: 0 });
  // Только грузовой тюк: гиря Бренна тоже занимает два места, но нести её не тяжелее обычного (иначе нить о Бренне калечит героя)
  if (вПути && привестиВещи(S).some(x => вещь(x.тип)?.категория === 'груз')) {
    if (++у.груз >= 3) { у.груз = 0; т.отдых = Math.max(0, т.отдых - 1); м.журналДня.push('Тяжёлый груз: силы −1'); }
  } else if (вПути) у.груз = 0;
  if (мокраяОдежда(S)) {
    if (++у.мокро >= ДЕЛЕНИЙ) { у.мокро = 0; т.отдых = Math.max(0, т.отдых - 1); м.журналДня.push('Мокрая одежда тяжелеет: силы −1'); }
  } else у.мокро = 0;
  if (м.погода === 'дождь') {
    if (защищёнОтДождя(S)) у.дождь = 0;
    else if (++у.дождь >= 4) {
      у.дождь = 0;
      if (м.промокалДень !== м.день) { намокнуть(S); намочитьБумаги(S); м.промокалДень = м.день; }
    }
  }
}

// Без сил тело отказывает раз в день (ГДД §5): первое дело на нуле — «отключился», цел −1.
function отметитьУсталость(S, тело) {
  const м = S.мир;
  if (тело.отдых === 0 && м.отключкаДень !== м.день) {
    м.отключкаДень = м.день;
    отметитьФакт(S, 'кризис_тела');
    S.герой.тело.цел = Math.max(0, S.герой.тело.цел - 1);
    м.журналДня.push('Отключился на ходу: цел −1');
  } else if (тело.отдых !== 0 && тело.цел === 0 && м.разбитДень !== м.день) {
    м.разбитДень = м.день;
    м.журналДня.push('Еле тащишься на разбитом теле');
  }
}

// Главная функция времени. n делений; улица — дождь, мокрая одежда и груз.
// Рассвет закрывает сутки без сна. Внутри места сутки не закрываются посреди сцены:
// время встаёт на последнем делении ночи, а закрывает их выход в город (вернутьсяВГород).
// дорога — путь между районами (улица и груз). держатьРассвет — дойти до последнего деления ночи и не закрыть сутки (дорога домой и сразу сон).
export function потратить(S, n, { улица = false, дорога = false, телоНаСтарте = null, держатьРассвет = false } = {}) {
  if (S.мир.конецДня || S.мир.кампанияЗавершена || !(n > 0)) return S;
  отметитьУсталость(S, телоНаСтарте ?? снимокТела(S));
  const день = S.мир.день;
  for (let k = 0; k < n; k++) {
    if (S.мир.день !== день || S.мир.конецДня || S.мир.рассветВСцене) break;
    if (улица || дорога) наУлице(S, дорога);
    S.мир.деление = деление(S) + 1;
    if (S.мир.деление < ёмкость(S)) continue;
    if (границаОтрезка(S)) continue;
    // рассвет
    S.мир.деление = ёмкость(S);
    if (S.сцена) { S.мир.рассветВСцене = true; break; }
    if (держатьРассвет) break;
    закончитьДень(S, null); // ночь ушла на дела, не на сон
    break;
  }
  проверитьСроки(S);
  return S;
}

// Рассвет, дождавшийся конца сцены: закрыть сутки без сна (выход из места, ожидание в камере).
export function рассвет(S) {
  if (!S.мир.рассветВСцене) return S;
  S.мир.рассветВСцене = false;
  if (!S.мир.конецДня && !S.мир.кампанияЗавершена) закончитьДень(S, null);
  return S;
}

// Пропустить остаток отрезка: «подождать до вечера». С деления 0 — ровно отрезок.
export function следующийОтрезок(S) {
  if (S.мир.конецДня || S.мир.кампанияЗавершена) return S;
  return потратить(S, Math.max(1, осталось(S)));
}

// Старое имя для действий «на весь отрезок» (дорога, работа, ожидание): остаток отрезка на улице.
export function потратитьОтрезок(S, телоНаСтарте = снимокТела(S)) {
  if (S.мир.конецДня || S.мир.кампанияЗавершена) return S;
  return потратить(S, Math.max(1, осталось(S)), { улица: true, телоНаСтарте });
}

// сон — вариант ночлега из данных/жильё.js (объект); у бессонной ночи его нет.
// Лечь можно с вечера; потратил на ночные дела больше половины ночи — отдыха на 1 меньше.
export function лечьСпать(S, сон) {
  if(S.сцена?.ночьЗакрытаДоМиграции&&S.мир.день>S.сцена.вход.день){
    if(S.сцена.ночьЗакрытаДоМиграции==='завершена')return S;
    // Старый движок уже закрыл эти сутки при входе. Досыпаем оплаченную ночь, не старим вещи и сроки второй раз.
    const день=S.сцена.вход.день, прежний=S.мир.конецДня?.день===день?S.мир.конецДня:S.мир.хроника?.find(x=>x.день===день);
    if(сон){
      const т=S.герой.тело, потеря=прежний?.причины?.some(x=>(x.includes('Отдых −1: ночь без сна')||x.includes('Силы −1: ночь без сна')))?1:0;
      т.отдых=Math.min(3,т.отдых+потеря+(сон.отдых??0));т.тепло=Math.max(0,Math.min(3,т.тепло+(сон.тепло??0)));
      S.герой.напряжение=Math.max(0,(S.герой.напряжение??0)-1);if(сон.отдых>=2)S.герой.боль=Math.max(0,(S.герой.боль??0)-1);
      const строка='Завершён оплаченный ночлег из прежней версии; следующий день сохранён.';
      for(const итог of [прежний,...(S.мир.хроника??[]).filter(x=>x.день===день)])if(итог){итог.выспался=true;итог.сон=сон.имя;итог.причины=(итог.причины??[]).filter(x=>!x.includes('ночь без сна'));итог.журнал=[...new Set([...(итог.журнал??[]),...S.мир.журналДня,строка])];}
      S.мир.ночьБезСна=null;S.мир.журналДня=[];
    }
    S.сцена.ночьЗакрытаДоМиграции='завершена';return S;
  }
  if (S.мир.конецДня || S.мир.кампанияЗавершена) return S;
  if (сон && поздно(S)) {
    сон = { ...сон, отдых: Math.max(0, (сон.отдых ?? 0) - 1) };
    S.мир.журналДня.push('Лёг поздно: силы на 1 меньше');
  }
  закончитьДень(S, сон ?? null);
  return S;
}

// Итог дня пишется в S.мир.конецДня — экран конца дня показывается, пока он
// не снят (так он переживает и перезагрузку страницы после автосейва).
function закончитьДень(S, сон) {
  const итог = {
    день: S.мир.день,
    выспался: !!сон,
    сон: сон ? сон.имя : null,
    журнал: [],
    причины: [],
    предупреждение: false,
  };
  применитьТело(S, сон, итог);
  старениеВещей(S, итог);
  просрочитьЗалоги(S, итог);
  проверитьДела(S, итог);
  убывание(S); // фракции забывают тех, кто не работает на них (ГДД §7)
  if (итог.день === 30) S.мир.журналДня.push(итогБренна(S));
  const ночи = (S.мир.ночи ??= {}), ключНочи = сон ? сон.id : 'без-сна';
  ночи[ключНочи] = (ночи[ключНочи] ?? 0) + 1;
  закрытьДеньСвязей(S);
  закрытьДеньЦелей(S, итог);
  ночьМыслей(S, сон, итог.день);
  S.мир.день += 1;
  обновитьСезон(S);
  S.мир.отрезок = ОТРЕЗКИ[0];
  S.мир.деление = 0;
  S.мир.рассветВСцене = false;
  проверитьСроки(S); // срок до конца дня видит все действия ночи, затем попадает в итог
  обновитьНить(S, S.мир.день);
  обновитьСоциальнуюПамять(S, итог); // итог.день — закрываемые сутки, S.мир.день уже следующий
  итог.журнал = S.мир.журналДня.slice();
  S.мир.конецДня = итог;
  // Хроника: три последних итога дня для экрана «Журнал» (старые выпадают).
  (S.мир.хроника ??= []).push({ день: итог.день, журнал: итог.журнал, причины: итог.причины, выспался: итог.выспался, сон: итог.сон });
  if (S.мир.хроника.length > 3) S.мир.хроника.splice(0, S.мир.хроника.length - 3);
  S.мир.ночьБезСна = сон ? null : S.мир.день;
  S.мир.погода = ((S.мир.день * 7 + (S.мир.сид ?? 0)) % 5 < 2) ? 'дождь' : 'ясно';
  S.мир.улица = { дождь: 0, мокро: 0, груз: 0 };
  S.мир.журналДня = [];
  return S;
}

