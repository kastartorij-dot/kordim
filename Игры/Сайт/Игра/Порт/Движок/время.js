// Цена во времени для подписи кнопки (решение автора 12.11: без слова, точками).
// До трёх делений — ромбы; длиннее — ромбы и где кончится: «◆◆◆◆◆◆ · до вечера», «кончится днём».
const РОД = { утро: 'утра', день: 'дня', вечер: 'вечера', ночь: 'ночи' };
const ТВОР = { утро: 'утром', день: 'днём', вечер: 'вечером', ночь: 'ночью' };
export function ценаВремени(S, n) {
  if (!(n > 0)) return 'даром';
  if (n <= 3) return '◆'.repeat(n);
  const cap = ёмкость(S);
  let i = ОТРЕЗКИ.indexOf(S.мир.отрезок), д = деление(S) + n;
  while (д >= cap && i < 3) { д -= cap; i += 1; }
  const конец = д >= cap ? 'до утра' : д === 0 ? `до ${РОД[ОТРЕЗКИ[i]]}` : `кончится ${ТВОР[ОТРЕЗКИ[i]]}`;
  return (n <= ДЕЛЕНИЙ ? '◆'.repeat(n) + ' · ' : '') + конец;
}
