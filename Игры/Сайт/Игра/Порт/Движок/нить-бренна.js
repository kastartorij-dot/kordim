// Нить Бренна: решения о журнале, каналы знания и отложенные последствия.
import { естьВещь, убратьТип } from './вещи.js';
import { применитьЭффект } from './эффекты.js';
import { датьТему, СЛЫШАЛ } from './знание.js';
import { узлыИУровень, собратьВывод } from '../Данные/нить-бренна.js';

export const деньНити = S => S.сцена?.вход?.день ?? S.мир.день;
export function нить(S) {
  return S.мир.нитьБренна ??= { решение: null, день: null, знают: {}, выполнено: {}, очередь: [] };
}
export function состояниеЖурнала(S) {
  return S.мир.нитьБренна?.решение ?? ((S.мир.свидетельства ?? []).includes('brenn_second_journal') ? 'получен' : 'не_выдан');
}
const флаги = { оставлен:'журнал_у_одвина', возвращён:'журнал_в_весовой', у_дорра:'журнал_у_дорра', продан:'журнал_у_нотариуса', сожжён:'журнал_сожжён' };
const эффекты = {
  возвращён: { una:{}, bras:{}, gorm:{}, rest_dorr:{}, tobb:{}, svish:{}, весовщик:{} },
  у_дорра: { rest_dorr:{}, bras:{распол:{bras:-1}}, gorm:{распол:{gorm:-1}}, tobb:{}, svish:{}, veyt:{} },
  продан: { notarius:{}, veyt:{}, bras:{распол:{bras:-1}}, gorm:{распол:{gorm:-1}}, una:{распол:{una:-2}} },
  сожжён: { una:{распол:{una:2}}, bras:{распол:{bras:1}}, gorm:{} },
  оставлен: { una:{} },
};
function один(S, ключ, э) {
  const н = нить(S);
  if (н.выполнено[ключ]) return;
  н.выполнено[ключ] = true;
  применитьЭффект(S, э, { источник:'нить', откуда:'нить Бренна' });
}
export function узнатьЖурнал(S, кто, канал='рассказ', решение=состояниеЖурнала(S), день=деньНити(S)) {
  const н = нить(S);
  if (!флаги[решение] && решение !== 'получен') return false;
  if (н.знают[кто]?.решение === решение) return false;
  н.знают[кто] = { решение, день, канал };
  один(S, решение+':'+кто, эффекты[решение]?.[кто] ?? {});
  return true;
}
export function обновитьНить(S, день=деньНити(S)) {
  const н = нить(S);
  for (const событие of н.очередь) {
    if (событие.день > день || событие.готово) continue;
    событие.готово = true;
    for (const кто of событие.кто ?? []) узнатьЖурнал(S, кто, 'слух', событие.решение, событие.день);
    if (событие.э) один(S, событие.ключ, событие.э);
    if (событие.тема) датьТему(S, событие.тема, СЛЫШАЛ, 'город');
  }
}
export function решитьЖурнал(S, решение) {
  if (!Object.hasOwn(флаги, решение) || !естьВещь(S,'второй-журнал')) return false;
  const н = нить(S);
  if (н.решение && н.решение !== 'оставлен') return false;
  if (н.решение === решение) return false;
  const места = { возвращён:'контора-дорров', у_дорра:'контора-дорров', продан:['рынок','приемная-нотариуса'], сожжён:'часовня', оставлен:'часовня' };
  const комнаты = { возвращён:'весовая-дорров', у_дорра:'кабинет-дорров', продан:S.сцена?.место==='приемная-нотариуса'?['приёмная','перегородка']:'слухи-рынка' };
  if (![].concat(места[решение]).includes(S.сцена?.место) || (комнаты[решение] && ![].concat(комнаты[решение]).includes(S.сцена.комната))) return false;
  н.решение = решение; н.день = деньНити(S);
  if (!S.мир.флаги.includes(флаги[решение])) S.мир.флаги.push(флаги[решение]);
  if (решение !== 'оставлен') убратьТип(S, 'второй-журнал');
  const сразу = { оставлен:{тень:1}, возвращён:{}, у_дорра:{гроши:60,фракции:{ножи:8}}, продан:{гроши:100,фракции:{картель:3},тень:2}, сожжён:{закрытьОбязательство:'долг-перед-мёртвым'} };
  один(S, решение+':сразу', сразу[решение]);
  const свидетели = { возвращён:['весовщик','svish','tobb'], у_дорра:['rest_dorr'], продан:S.сцена?.место==='рынок'?['notarius','veyt']:['notarius'], сожжён:['una'], оставлен:['una'] };
  for (const кто of свидетели[решение]) узнатьЖурнал(S, кто, 'свидетель', решение);
  const очередь = (через, кто, э, тема) => н.очередь.push({ день:н.день+через, решение, кто, э, тема, ключ:решение+':город:'+через });
  if (решение === 'возвращён') {
    очередь(1,['rest_dorr'],{фракции:{ножи:-2}},'zhurnal_vozvrashchen');
    очередь(2,['bras','yora','pin','veyt','starshaya','yarna','ola','niya','freya','povariha'],{фракции:{картель:-2},репутация:3});
    очередь(4,['gorm']);
  }
  if (решение === 'у_дорра') {
    очередь(1,['tobb'],null,'zhurnal_u_dorra'); очередь(2,['svish']);
    очередь(3,['bras','yora','pin','veyt']); очередь(5,['gorm'],null,'brenna_prodali');
  }
  if (решение === 'продан') {
    очередь(1,['bras','yora','pin','veyt'],{репутация:-3},'zhurnal_notariyu');
    очередь(3,['una','gorm','branka','nim','ton','mila','vorn_healer','rest_dorr']);
    очередь(5,[],null,'brenna_prodali');
  }
  S.мир.журналДня.push('Второй журнал: '+решение+'.');
  применитьЭффект(S,{итогДела:{id:'второй-журнал',тип:'решение',выплата:решение==='продан'?100:решение==='у_дорра'?60:0,выбор:решение}},{источник:'нить'});
  return true;
}
export function выводБренна(S) {
  const записи = new Set(S.мир.свидетельства ?? []), {уровень,узлы} = узлыИУровень(записи);
  const состояние = состояниеЖурнала(S);
  return { уровень, узлов:узлы.length, текст:уровень==='понимание'||уровень==='полная' ? собратьВывод(уровень,записи,состояние) : 'Пока есть отдельные записи. Сопоставь показания с доковой книгой, ночлежкой и карточкой лекаря.', состояние };
}
export function итогБренна(S) {
  const с = состояниеЖурнала(S);
  return с==='не_выдан'?'Книга осталась у Уны.':с==='получен'||с==='оставлен'?'Книга у Одвина.':{возвращён:'Книга возвращена в весовую.',у_дорра:'Книга у Дорра.',продан:'Книга продана Нотариусу.',сожжён:'Книга сожжена.'}[с];
}
