// Торг у лотка: сколько раундов дано, какая цена сейчас, какие доводы уже сказаны. Без DOM и без имён:
// товары, цены, доводы и слова лежат в данные/торг.js; ходы мини-игры — Движок/игры-места.js. Состояние хранится
// в записи места (S.мир.места[...].торг) и сбрасывается с новым днём, поэтому миграция сохранений не нужна.
// Вернуться к лотку в тот же день можно: раунды, сказанные доводы и терпение продавца остаются.
import { РАУНДЫ_ПО_ОТРЕЗКУ, ТОРГ, СЛОВА_ТОРГА, ТЕРПЕНИЕ } from '../Данные/торг.js';
import { расчётныйДень } from '../Данные/календарь.js';

const подставить = (текст, цена) => текст.replace('{цена}', String(цена));

// День, в который игрок вошёл в место. Ночью вход сразу закрывает сутки (движок/время.js), и S.мир.день внутри
// сцены уже следующий; условия дня («день 13», «нечётный», «раз в день») должны смотреть на день входа.
export const деньСцены = S => S.сцена?.вход?.день ?? S.мир.день;

export function торгДня(S) {
  const м = S.мир.места[S.сцена.место];
  const день = деньСцены(S);
  const т = (м.торг ??= { день, раундов: {}, перегиб: {} });
  if (т.день !== день) Object.assign(т, { день, раундов: {}, перегиб: {}, верных: {}, промахов: {}, доводы: {} });
  т.верных ??= {}; т.промахов ??= {}; т.доводы ??= {};
  return т;
}

// Сколько раундов торга у этого отрезка сегодня.
export function максРаундов(S) {
  const база = РАУНДЫ_ПО_ОТРЕЗКУ[S.сцена.отрезок] ?? 0;
  if (база === 0) return 0;
  return Math.max(1, база - (расчётныйДень(деньСцены(S)) ? 1 : 0));
}

export const раундов = (S, товар) => Math.min(торгДня(S).раундов[товар] ?? 0, максРаундов(S));
export const верных = (S, товар) => Math.min(торгДня(S).верных[товар] ?? 0, раундов(S, товар));
export const промахов = (S, товар) => торгДня(S).промахов[товар] ?? 0;
export const сказано = (S, товар) => торгДня(S).доводы[товар] ?? [];
export const перегнул = (S, товар) => !!торгДня(S).перегиб[товар];

// Текущая цена: первая цена минус скидки верных доводов, но не ниже пола отрезка.
export function цена(S, товар) {
  const т = ТОРГ[товар];
  const пол = S.сцена.отрезок === 'вечер' ? т.пол.вечер : т.пол.день;
  const скидка = т.скидки.slice(0, верных(S, товар)).reduce((a, x) => a + x, 0);
  return Math.max(пол, т.запрос - скидка);
}

export const можноТорговаться = (S, товар) => раундов(S, товар) < максРаундов(S) && !перегнул(S, товар);
export const можноДавить = (S, товар) => максРаундов(S) > 0 && раундов(S, товар) >= максРаундов(S) && !перегнул(S, товар);

// Довод: один раунд. Верный сбавляет цену, неверный тратит терпение; второй промах — перегиб.
// Возвращает { реплика, перегиб } или null, если довод сейчас не сказать.
export function сказатьДовод(S, товар, id) {
  const т = торгДня(S), д = ТОРГ[товар].доводы.find(x => x.id === id);
  if (!д || !можноТорговаться(S, товар) || сказано(S, товар).includes(id)) return null;
  т.раундов[товар] = (т.раундов[товар] ?? 0) + 1;
  (т.доводы[товар] ??= []).push(id);
  if (д.верный) {
    т.верных[товар] = (т.верных[товар] ?? 0) + 1;
    const последний = раундов(S, товар) >= максРаундов(S);
    return { реплика: подставить(д.ответ, цена(S, товар)) + (последний ? '\n\n' + подставить(СЛОВА_ТОРГА.последний, цена(S, товар)) : ''), перегиб: false };
  }
  т.промахов[товар] = промахов(S, товар) + 1;
  if (промахов(S, товар) >= ТЕРПЕНИЕ) { т.перегиб[товар] = true; return { реплика: д.ответ + '\n\n' + СЛОВА_ТОРГА.перегиб, перегиб: true }; }
  return { реплика: д.ответ + '\n\n' + СЛОВА_ТОРГА.предупреждение, перегиб: false };
}

// Давить после последнего раунда: скидки нет, продавец теряет терпение.
export function давить(S, товар) {
  if (!можноДавить(S, товар)) return null;
  торгДня(S).перегиб[товар] = true;
  return { реплика: СЛОВА_ТОРГА.перегиб, перегиб: true };
}

// Прежний раунд без выбора довода (старые эффекты места `торг`): засчитывается как верный.
export function сделатьРаунд(S, товар) {
  const т = торгДня(S);
  if (можноТорговаться(S, товар)) {
    т.раундов[товар] = (т.раундов[товар] ?? 0) + 1;
    т.верных[товар] = (т.верных[товар] ?? 0) + 1;
    const последний = раундов(S, товар) >= максРаундов(S);
    return { реплика: подставить(СЛОВА_ТОРГА[последний ? 'последний' : 'уступил'], цена(S, товар)), перегиб: false };
  }
  return давить(S, товар) ?? { реплика: null, перегиб: false };
}

// Что покупка делает с расположением продавца: торговался по делу — +1, не торговался — −1 (Пин «презирает тех,
// кто не торгуется»), давил сверх меры — 0 (расположение уже потеряно при перегибе). Возвращает { реплика, распол }.
export function итогПокупки(S, товар) {
  if (перегнул(S, товар)) return { реплика: СЛОВА_ТОРГА.куплено, распол: 0 };
  if (раундов(S, товар) === 0) return { реплика: СЛОВА_ТОРГА.безТорга, распол: -1 };
  if (верных(S, товар) === 0) return { реплика: СЛОВА_ТОРГА.куплено, распол: 0 };
  return { реплика: СЛОВА_ТОРГА.купленоТорг, распол: 1 };
}
