export function место(id) {
  return МЕСТА.find(м => м.id === id) ?? null;
}

// Темы, что известны с начала игры всем (у места они помечены «всегда»).
export function всегдаТемы() {
  const т = [];
  for (const м of МЕСТА)
    for (const [id, тема] of Object.entries(м.модуль.ТЕМЫ))
      if (тема.всегда && !т.includes(id)) т.push(id);
  return т;
}
