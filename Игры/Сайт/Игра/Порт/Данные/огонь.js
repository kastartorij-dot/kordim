import { расчётныйДень } from './календарь.js';

export const ДВЕ_ВСПЫШКИ = [4, 9, 12, 17, 20, 24, 27];   // ждут судно без пошлин
export const ШТОРМ_ДЕНЬ = 16;                              // огонь гаснет, ломается заслонка
export const ВСЕГО_ДНЕЙ = 30;

export function режимНочи(день) {
  if (день === ШТОРМ_ДЕНЬ) return 'шторм';
  if (расчётныйДень(день)) return 'долгая тьма';
  if (ДВЕ_ВСПЫШКИ.includes(день)) return 'две вспышки';
  return 'ровный';
}

