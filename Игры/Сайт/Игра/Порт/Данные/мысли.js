// Кабинет мыслей (шаг 12, ПЛАН_ДОРАБОТКИ «Кабинет мыслей»). Три исходных образца из концепта диалогов §11
// и четыре мысли под главные цели из Документы/Разработка/Шаг_12_Мини_игры_мастерство_мысли/Девять_новых_мыслей.md
// (М1–М4, приняты для прототипа; тексты начала и завершения перенесены оттуда).
//
// Правила, которые держит движок (Движок/мысли.js):
//   • три места; мысль предлагается поводом — сценой (эффект `мысль` в диалоге) или состоянием мира (`повод`);
//   • игрок сам кладёт мысль на место; зреет она полноценными снами — под крышей, не под открытым небом;
//   • пока зреет — голос `плюс` −1 (мысль сырая и путает); созрела — `плюс` +1 и `минус` −1 в любой проверке;
//   • вклад мыслей в один голос не больше ±1: одинаковые не складываются, противоположные гасят друг друга;
//   • созревшая мысль открывает ветку `реплика` у одного человека; без мысли ветки нет;
//   • отпустить можно всегда: прожитые ночи и все плюсы и минусы пропадают сразу, начать заново — с первой ночи.
//
// повод(S) → 'основной' | 'запасной' | null — читает только S, без импорта движков (иначе круг через проверку).

const свидетельствБренна = S => (S.мир.свидетельства ?? []).filter(id => id.startsWith('brenn_')).length;
const ночей = (S, ...виды) => виды.reduce((n, в) => n + (S.мир.ночи?.[в] ?? 0), 0);
const делГотово = S => {
  const д = S.мир.дела ?? [];
  return (Array.isArray(д) ? д : Object.values(д)).filter(з => ['готово', 'выполнено'].includes(з?.статус)).length;
};

