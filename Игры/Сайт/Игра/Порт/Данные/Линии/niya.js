// Сначала — пока действует обещание; после первой встречи там она бывает каждое утро (это её время, а не работа).
export function нияНаРынке(S) {
  const с = S.мир.связи?.niya;
  if (!с) return false;
  if ((S.сцена?.отрезок ?? S.мир.отрезок) !== 'утро') return false;
  if (с.обещания.some(о => о.ид === 'ния-рынок' && о.статус === 'дано')) return true;
  return ['вне-работы', 'поворот', 'решение', 'после'].includes(с.этап);
}

