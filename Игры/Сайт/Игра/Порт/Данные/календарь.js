// Календарь сезона (ГДД §4, журнал 19.09 «Дни недели»). Только данные: движок читает отсюда.
// РЫНОЧНЫЕ_ДНИ — решение по миру за автором; по умолчанию каждый седьмой день с третьего.
// Убрать рынок совсем — очистить массив: работы, у которых есть поле «рынок», просто платят обычно.
// Праздники канона (запись 29: «Начало жатвы», «Зимний огонь») сюда встают так же — числом дня.
export const РЫНОЧНЫЕ_ДНИ = [3, 10, 17, 24];
export const ПРАЗДНИКИ = []; // [{ день, имя }] — ждёт канона

export const рыночныйДень = день => РЫНОЧНЫЕ_ДНИ.includes(день);
// Канон: Горм не начинает важных разговоров в чётные дни — значит, круг Горма смотрит в нечётные.
export const нечётныйДень = день => день % 2 === 1;


