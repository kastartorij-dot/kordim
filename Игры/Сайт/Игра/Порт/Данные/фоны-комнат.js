// Варианты района по часу и погоде: тот же район, другой вид. Первое подходящее правило побеждает.
export const ВИДЫ_РАЙОНА = [
  { район: 'торговый', погода: 'дождь', не: ['ночь'], файл: 'Быт/рынок-дождь.webp' },
  { район: 'торговый', время: ['вечер'], файл: 'Быт/рынок-закрыт.webp' },
  { район: 'трущобы', время: ['ночь'], файл: 'Быт/трущобы-ночь.webp' },
  { район: 'доки', время: ['утро'], погода: 'ясно', файл: 'Быт/причал-утро.webp' },
];
export function видРайона(районId, время, погода) {
  const п = ВИДЫ_РАЙОНА.find(в => в.район === районId && (!в.время || в.время.includes(время))
    && (!в.погода || в.погода === погода) && !(в.не ?? []).includes(время));
  return п?.файл ?? null;
}

// Экран ночи: где спал. Часовня и свой угол — без кадра (район в темноте); под небом в доках — причальный вариант.
export function кадрНочлега(сонId, районId) {
  if (сонId === 'небо') return районId === 'доки' ? 'Быт/небо-доки.webp' : 'Быт/небо.webp';
  return { ночлежка: 'Быт/ночлежка.webp', койка: 'Быт/койка.webp', вдова: 'Быт/вдова.webp' }[сонId] ?? null;
}

