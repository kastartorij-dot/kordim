// Пути для поиска фона комнаты: сперва свой файл в папках места, потом таблица. Пустой список — фона нет.
export function путиФона(местоId, комнатаId, папки = []) {
  const пути = [];
  папки.forEach(п => ['.jpg', '.webp', '.png'].forEach(р => пути.push(п + комнатаId + р)));
  const т = ФОНЫ_КОМНАТ[местоId];
  if (т) {
    const ф = комнатаId in т ? т[комнатаId] : т['*'];
    if (ф) пути.push(ф);
  }
  return пути;
}

