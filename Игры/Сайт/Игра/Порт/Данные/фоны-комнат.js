// Пути для поиска фона комнаты: сперва свой файл в папках места, потом таблица. Пустой список — фона нет.
// Комната, названная в таблице (или покрытая '*'), берёт файл сразу — без проб трёх несуществующих имён:
// на телефоне каждая проба — лишний запрос до показа фона. Своих файлов у таких комнат нет (тест фоны-комнат.mjs).
export function путиФона(местоId, комнатаId, папки = []) {
  const т = ФОНЫ_КОМНАТ[местоId];
  const ф = т ? (комнатаId in т ? т[комнатаId] : т['*']) : undefined;
  if (ф) return [ф];
  const пути = [];
  папки.forEach(п => ['.webp', '.jpg', '.png'].forEach(р => пути.push(п + комнатаId + р)));
  return пути;
}

