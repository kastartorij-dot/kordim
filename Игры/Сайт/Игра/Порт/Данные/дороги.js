const РЯДОМ = { локи: 'рыбацкий-берег' }; // старое имя района лачуги в сохранениях
export function дорога(откуда, куда) {
  const а = РЯДОМ[откуда] ?? откуда, б = РЯДОМ[куда] ?? куда;
  if (а === б) return 0;
  return ДОРОГИ[`${а}|${б}`] ?? ДОРОГИ[`${б}|${а}`] ?? 2;
}
