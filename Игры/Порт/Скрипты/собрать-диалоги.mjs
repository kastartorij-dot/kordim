const строки = [];
const добавить = (...x) => строки.push(...x);
const код = x => '`' + JSON.stringify(x) + '`';
const блок = (метка, текст) => {
  if (текст === undefined || текст === null || текст === '') return;
  if (Array.isArray(текст)) { текст.forEach((v, i) => блок(`${метка}${текст.length > 1 ? ` ${i + 1}` : ''}`, v)); return; }
  if (typeof текст === 'object') {
    добавить(`- **${метка}${текст.если ? ` (${код(текст.если)})` : ''}:** ${текст.т ?? текст.текст ?? codeObject(текст)}`);
    return;
  }
  добавить(`- **${метка}:** ${String(текст).replaceAll('\n', '<br>')}`);
};
const codeObject = x => код(x);
const поля = (объект, исключить = []) => {
  for (const [ключ, значение] of Object.entries(объект ?? {}))
    if (!исключить.includes(ключ) && значение !== undefined) добавить(`- ${ключ}: ${код(значение)}`);
};
function фраза(д, тид, подход, кто) {
  const свой = д.ФРАЗЫ_ЛИЧНО?.[кто]?.[тид]?.[подход];
  if (свой) return свой;
  const ему = !д.ЛЮДИ[кто]?.она && (д.ФРАЗЫ_ЕМУ?.[тид]?.[подход] ?? ФРАЗЫ_ЕМУ_ГОРОДА[тид]?.[подход]);
  if (ему) return ему;
  const т = д.ФРАЗЫ?.[тид] ?? РЕЕСТР[тид]?.фразы;
  return tValue(т, подход) ?? (д.ТЕМЫ[тид] ?? РЕЕСТР[тид])?.ярлык ?? тид;
}
function tValue(т, подход) { return т?.[подход] ?? т?.прямо; }
function комнаты(д, кто) {
  return Object.entries(д.КОМНАТЫ).filter(([, к]) => к.люди?.includes(кто)).map(([, к]) => к.имя);
}
function лор(кто) {
  const карточка = ЛОР_НПС[кто];
  if (!карточка) throw new Error(`Нет лора для НПС: ${кто}`);
  добавить('#### Лор для написания диалогов', '');
  for (const [поле, метка] of Object.entries({ основа: 'Основа', голос: 'Как писать голос', опора: 'На что опираться', границы: 'Что учитывать' })) {
    if (!карточка[поле]) throw new Error(`В карточке ${кто} нет поля ${поле}`);
    блок(метка, карточка[поле]);
  }
  const ссылки = карточка.источники.map(путь => {
    if (!existsSync(new URL(`../Документы/${путь}`, import.meta.url))) throw new Error(`Нет источника: ${путь}`);
    const имя = путь.endsWith('00_КАНОН_Мастер_Кордим.md') ? 'мастер-канон' : путь.split('/').at(-1);
    return `[${имя}](<${путь}>)`;
  });
  добавить('', `Источники: ${ссылки.join('; ')}.`, '');
}
function обычные(д, кто) {
  for (const [тид, подходы] of Object.entries(д.Р?.[кто] ?? {})) {
    const тема = д.ТЕМЫ?.[тид] ?? РЕЕСТР[тид];
    добавить(`#### ${тема?.ярлык ?? тид} (${тид})`, '');
    if (тема?.порог !== undefined) добавить(`Условие темы: расположение от ${тема.порог}.`, '');
    for (const [подход, ответ] of Object.entries(подходы)) {
      добавить(`**Манера: ${подход}.**`, '');
      const манеры = подход === 'любой' ? ['прямо', 'мягко', 'деньгами'] : [подход];
      for (const м of манеры) блок(`Герой (${м})`, фраза(д, тид, м, кто));
      блок('Ответ НПС', ответ.т);
      if (ответ.поПерсонажу) for (const [персонаж, текст] of Object.entries(ответ.поПерсонажу))
        блок(`Ответ для персонажа «${персонаж}»`, текст);
      for (const дальше of ответ.дальше ?? []) {
        блок('Продолжение', дальше.т);
        if (дальше.э && Object.keys(дальше.э).length) добавить(`- Эффект продолжения: ${код(дальше.э)}`);
      }
      if (ответ.э && Object.keys(ответ.э).length) добавить(`- Эффект: ${код(ответ.э)}`);
      поля(ответ, ['т', 'э', 'дальше', 'поПерсонажу']);
      добавить('');
    }
  }
  if (д.ОТГОВОРКИ?.[кто]) { добавить('#### Нет ответа на тему', ''); блок('НПС', д.ОТГОВОРКИ[кто]); добавить(''); }
}
function граф(г) {
  добавить('#### Вступление', '');
  блок('Первый разговор', г.вступление); блок('Повторный разговор', г.снова);
  for (const вид of г.видят ?? []) блок('Что замечает', вид);
  добавить('');
  for (const [ид, ветка] of Object.entries(г.ветки)) {
    добавить(`#### Ветка «${ветка.ярлык}» (${ид})`, '');
    if (ветка.реплика) блок('Реплика при входе', ветка.реплика);
    поля(ветка, ['ярлык', 'реплика', 'узлы', 'уже']);
    if (ветка.уже) блок('При повторе', ветка.уже);
    for (const [узелИд, узел] of Object.entries(ветка.узлы)) {
      добавить(`**Узел ${узелИд}**`, '');
      if (узел.текст) блок('Текст', узел.текст);
      if (узел.при) добавить(`- При входе: ${код(узел.при)}`);
      for (const голос of узел.голоса ?? []) { блок(`Голос ${голос.голос}`, голос.т); поля(голос, ['голос', 'т']); }
      for (const вариант of узел.варианты ?? []) {
        добавить(`- **Выбор ${вариант.ид}:** ${вариант.текст}`);
        поля(вариант, ['ид', 'текст', 'ответ', 'голоса', 'успех', 'провал']);
        if (вариант.ответ) блок('Ответ', вариант.ответ);
        for (const голос of вариант.голоса ?? []) блок(`Голос ${голос.голос}`, голос.т);
        for (const исход of ['успех', 'провал']) if (вариант[исход]) {
          добавить(`  - **${исход}:**`);
          блок('Ответ', вариант[исход].ответ);
          for (const голос of вариант[исход].голоса ?? []) блок(`Голос ${голос.голос}`, голос.т);
          поля(вариант[исход], ['ответ', 'голоса']);
        }
      }
      добавить('');
    }
  }
}

