def where(f):
  rs=rooms.get(f)
  if not rs: return OTHER.get(f,'')
  by={}
  for r in rs: by.setdefault(r['место'],[]).append(r['комната'])
  return '; '.join(m+(': '+', '.join(k) if len(k)>1 or k[0]!=m else '') for m,k in by.items())
def grp(f,pk):
  rs=rooms.get(f)
  if rs: return rs[0]['место']
  return next(g for p,g in GROUPS if f.startswith(p))

