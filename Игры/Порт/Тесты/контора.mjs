// Шаг 8, Контора Дорров: две пошлины, ревизия, признаки близнецов, кабинет, билеты.
// node Порт/тест/контора.mjs
import assert from 'node:assert/strict';
import { новоеСостояние } from '../Движок/состояние.js';
import { войти, действияСцены, вернутьсяВГород } from '../Движок/разговор.js';
import { датьТему, верностьТемы } from '../Движок/знание.js';
import { естьВещь } from '../Движок/вещи.js';

const кнопка = (S, текст) => действияСцены(S).find(а => а.текст === текст || а.текст.startsWith(текст));
const нажать = (S, текст) => { const а = кнопка(S, текст); assert.ok(а, `нет кнопки «${текст}»`); assert.equal(а.можно, true, `«${текст}» недоступна: ${а.почему}`); а.выполнить(S); };
const пойти = (S, к) => действияСцены(S).find(а => а.id === `пойти:${к}`).выполнить(S);
const осмотреть = (S, д) => действияСцены(S).find(а => а.id === `рассмотреть:${д}`).выполнить(S);
function вКонторе(день = 2, кошель = 100, начало = 'семья', S0 = null) {
  const S = S0 ?? новоеСостояние(начало, 3);
  S.мир.район = 'доки'; S.мир.день = день; S.мир.отрезок = 'утро'; S.герой.кошель = кошель;
  войти(S, 'контора-дорров');
  return S;
}
const м = S => S.мир.места['контора-дорров'];
const ножи = S => S.мир.очки.ножи;

// ── по книге: 6 гр., квитанция, счётчик, слух про грузы становится проверенным
{
  const S = вКонторе();
  датьТему(S, 'kladbishche_kitov', 'слышал');
  assert.equal(верностьТемы(S, 'kladbishche_kitov'), 'слышал');
  нажать(S, 'Оформить запись по книге');
  assert.equal(S.герой.кошель, 94);
  assert.equal(естьВещь(S, 'квитанция'), true);
  assert.equal(м(S).счётчики['по-книге'], 1);
  assert.equal(верностьТемы(S, 'kladbishche_kitov'), 'подтверждено', 'квитанция подтвердила слух');
  assert.equal(кнопка(S, 'Оформить запись по книге'), undefined, 'один раз в день');
  assert.equal(S.мир.тень ?? 0, 0, 'по книге тени нет');
}

// ── по руке: 4 гр., Ножи +1, долг чести, тени сразу нет
{
  const S = вКонторе();
  const до = ножи(S);
  нажать(S, 'Передать пошлину по руке');
  assert.equal(S.герой.кошель, 96);
  assert.equal(ножи(S), до + 1);
  assert.ok(м(S).флаги.includes('долг_чести'));
  assert.equal(м(S).счётчики['по-руке'], 1);
  assert.equal(S.мир.тень ?? 0, 0, 'тень приходит с ревизией, а не сразу');
  assert.equal(естьВещь(S, 'квитанция'), false);
}

// ── ревизия: первый визит со дня 12; платившие по руке — тень +1, платившие по книге — нет; враньё про стражу ясно
{
  const S = вКонторе(2);
  нажать(S, 'Передать пошлину по руке');
  датьТему(S, 'lozh_strazha');
  вернутьсяВГород(S);
  вКонторе(11, 100, null, S);
  assert.equal(S.мир.тень ?? 0, 0, 'до дня 12 ревизии ещё не было');
  вернутьсяВГород(S);
  вКонторе(12, 100, null, S);
  assert.equal(S.мир.тень, 1, 'ревизия: тень +1 тому, кто платил по руке');
  assert.equal(верностьТемы(S, 'lozh_strazha'), 'опровергнуто');
  вернутьсяВГород(S);
  вКонторе(13, 100, null, S);
  assert.equal(S.мир.тень, 1, 'ревизия один раз');
}
{
  const S = вКонторе(2);
  нажать(S, 'Оформить запись по книге');
  вернутьсяВГород(S);
  вКонторе(12, 100, null, S);
  assert.equal(S.мир.тень ?? 0, 0, 'плативший по книге в безопасности');
  нажать(S, 'Помочь Тоббу при ревизии');
  assert.equal(кнопка(S, 'Помочь Тоббу при ревизии'), undefined);
}

// ── кабинет закрыт чужим; открывается Ножами, двумя платежами по руке или знанием про близнецов
{
  const чужой = вКонторе();
  assert.equal(действияСцены(чужой).some(а => а.id === 'пойти:кабинет-дорров'), false);

  const платил = вКонторе(2);
  нажать(платил, 'Передать пошлину по руке');
  assert.equal(действияСцены(платил).some(а => а.id === 'пойти:кабинет-дорров'), false, 'одного платежа мало');
  вернутьсяВГород(платил);
  вКонторе(3, 100, null, платил);
  нажать(платил, 'Передать пошлину по руке');
  assert.equal(действияСцены(платил).some(а => а.id === 'пойти:кабинет-дорров'), true, 'после двух платежей по руке пускают');

  const знающий = вКонторе();
  датьТему(знающий, 'dorry_dvoe', 'слышал');
  assert.equal(действияСцены(знающий).some(а => а.id === 'пойти:кабинет-дорров'), true);

  const свой = вКонторе(2, 100, 'бумаги');
  свой.мир.фракции.ножи = 1;
  assert.equal(действияСцены(свой).some(а => а.id === 'пойти:кабинет-дорров'), true, 'ступень Ножей +1');
}

// ── признаки: один за визит, три подтверждают тему, пять открывают выбор
{
  const S = вКонторе();
  датьТему(S, 'dorry_dvoe', 'слышал');
  осмотреть(S, 'часы');
  assert.deepEqual(м(S).память.признаки, ['часы']);
  assert.match(S.сцена.реплика, /1 из 6/);
  осмотреть(S, 'дверь');
  assert.deepEqual(м(S).память.признаки, ['часы'], 'второй признак за визит не засчитан');
  осмотреть(S, 'часы');
  assert.equal(м(S).память.признаки.length, 1, 'один и тот же признак дважды не считается');
  вернутьсяВГород(S);
  const порядок = [['дверь', 'приёмная'], ['стулья', 'кабинет'], ['чернильницы', 'кабинет'], ['шрам', 'кабинет']];
  let день = 3;
  for (const [деталь, комната] of порядок) {
    вКонторе(день++, 100, null, S);
    if (комната === 'кабинет') пойти(S, 'кабинет-дорров');
    осмотреть(S, деталь);
    if (м(S).память.признаки.length === 3) assert.equal(верностьТемы(S, 'dorry_dvoe'), 'подтверждено', 'три признака: слух стал знанием');
    if (м(S).память.признаки.length < 5) assert.equal(кнопка(S, 'Назвать вслух'), undefined);
    вернутьсяВГород(S);
  }
  assert.equal(м(S).память.признаки.length, 5);
}

// ── пять признаков: назвать вслух (Ножи −2, тень +1) или промолчать (Ножи +1); один выбор
for (const исход of ['вслух', 'молчать']) {
  const S = вКонторе();
  датьТему(S, 'dorry_dvoe', 'слышал');
  (м(S).память ??= {}).признаки = ['часы', 'походка', 'стул', 'чернильница', 'шрам'];
  пойти(S, 'кабинет-дорров');
  const до = ножи(S), тень = S.мир.тень ?? 0;
  if (исход === 'вслух') {
    нажать(S, 'Назвать вслух');
    assert.equal(ножи(S), до - 2);
    assert.equal(S.мир.тень, тень + 1);
    assert.ok(м(S).флаги.includes('назвал_вслух'));
  } else {
    нажать(S, 'Дать понять, что знаешь');
    assert.equal(ножи(S), до + 1);
    assert.ok(м(S).флаги.includes('дорр_запомнил'));
  }
  assert.equal(кнопка(S, 'Назвать вслух'), undefined, 'выбор сделан');
  assert.equal(кнопка(S, 'Дать понять, что знаешь'), undefined);
}
{
  const S = вКонторе();
  датьТему(S, 'dorry_dvoe', 'слышал');
  (м(S).память ??= {}).признаки = ['часы', 'походка', 'стул', 'чернильница'];
  пойти(S, 'кабинет-дорров');
  assert.equal(кнопка(S, 'Назвать вслух'), undefined, 'четырёх признаков мало');
}

// ── единый маршрут по книге: расписание → рейс → 20 сейчас +40 до посадки
function выбратьРейс(S) {
  нажать(S,'Прочесть расписание и условия двух путей');
  нажать(S,'Выбрать береговой рейс на день 24');
}
{
  const S = вКонторе(5);
  выбратьРейс(S);
  нажать(S,'Записаться по книге: 20 сейчас, 40 до посадки');
  assert.equal(S.герой.кошель,80);
  assert.equal(естьВещь(S,'билет'),false,'пока это запись, а не билет');
  assert.equal(кнопка(S,'Принять поручительство Ножей'),undefined,'второй билет не продают');
  assert.equal(кнопка(S,'Записаться по книге:'),undefined);
  const доплата=кнопка(S,'Внести остаток за билет: 40 грошей');
  assert.ok(доплата?.можно);
  доплата.выполнить(S);
  assert.equal(S.герой.кошель,40);
  assert.equal(естьВещь(S,'билет'),true);
  assert.equal(кнопка(S,'Внести остаток за билет:'),undefined);
  доплата.выполнить(S);
  assert.equal(S.герой.кошель,40,'устаревшая кнопка не списывает повторно');
}
{
  const S = вКонторе(17);
  нажать(S,'Прочесть расписание и условия двух путей');
  assert.equal(кнопка(S,'Выбрать береговой рейс'),undefined,'после дня16 не выбирают рейс с новой записью');
  assert.equal(кнопка(S,'Записаться по книге:'),undefined,'после дня16 по книге не записывают');
  assert.equal(кнопка(S,'Принять поручительство Ножей'),undefined,'срок новой записи одинаков для двух денежных путей');
}
{
  const S = вКонторе(5,30);
  S.мир.фракции.ножи=1;
  выбратьРейс(S);
  assert.equal(кнопка(S,'Принять поручительство Ножей').можно,false,'не хватает40гр.');
}
// ── путь по руке до дня16:40гр.,Ножи+1,названное обязательство,тема и билет
{
  const S = вКонторе(16);
  S.мир.фракции.ножи=1;
  const до=ножи(S);
  выбратьРейс(S);
  const поручительство=кнопка(S,'Принять поручительство Ножей');
  нажать(S,'Принять поручительство Ножей');
  assert.equal(S.герой.кошель,60);
  assert.equal(естьВещь(S,'билет'),true);
  assert.equal(ножи(S),до+1);
  assert.ok(м(S).флаги.includes('долг_чести'));
  assert.ok(S.мир.темы.includes('bilet_po_ruke'));
  assert.equal(S.мир.обязательства.уехать_услуга.статус,'активно');
  assert.equal(кнопка(S,'Записаться по книге:'),undefined);
  поручительство.выполнить(S);
  assert.equal(S.герой.кошель,60);
  assert.equal(ножи(S),до+1,'устаревшая кнопка не повторяет награду');
}

