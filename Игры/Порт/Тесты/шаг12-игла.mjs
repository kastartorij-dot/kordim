// Шаг 12: мини-игра «Игла» в смене «Бить наколки по заказам». node Игры/Порт/Тесты/шаг12-игла.mjs
// Данные: шесть заказов по три этапа, у этапа один верный ход. Смена: заказ встаёт на место обычного случая,
// этапы идут по порядку, совет ремесла один на заказ, итог применяется один раз, «огрех» — без наказания,
// заказы кончаются, партия переживает сохранение, кнопки — те, что рисует карточка задачи.
import assert from 'node:assert/strict';
import { новоеСостояние, мигрировать } from '../Движок/состояние.js';
import { доступныеДействия } from '../Движок/действия.js';
import { работа } from '../Данные/работы.js';
import { начатьСмену, видСмены, авто } from '../Движок/смена.js';
import { ИГЛА, ИСХОДЫ_ИГЛЫ } from '../Данные/игла.js';
import { учётИгры } from '../Движок/мини-игры.js';
import { исходИглы, стенд } from '../Движок/игла.js';

const клик = (S, id) => { const а = доступныеДействия(S).find(x => x.id === id); assert.ok(а, 'есть кнопка ' + id + ': ' + ids(S).join(' | ')); assert.ok(а.можно, 'доступна ' + id); а.выполнить(S); };
const ids = S => доступныеДействия(S).map(а => а.id);
const копия = S => мигрировать(JSON.parse(JSON.stringify(S)));
const заказ = S => ИГЛА.find(з => з.id === S.мир.смена.задача.задание);
// Пройти этап: выбрать вариант (верный или первый неверный) и подтвердить.
const этап = (S, верно) => {
  const ш = заказ(S).шаги[S.мир.смена.задача.шаг];
  клик(S, 'смена:задача:вариант:' + (верно ? ш.верный : ш.варианты.find(в => в.id !== ш.верный).id));
  клик(S, 'смена:задача:записать');
};

// ── данные ───────────────────────────────────────────────────────────────
{
  assert.equal(ИГЛА.length, 6);
  assert.deepEqual(ИГЛА.map(з => з.сложность), ['лёгкое', 'лёгкое', 'среднее', 'среднее', 'трудное', 'трудное'], 'порядок от лёгких');
  assert.equal(new Set(ИГЛА.map(з => з.id)).size, 6);
  for (const з of ИГЛА) {
    for (const п of ['подводка', 'чисто', 'годно', 'огрех']) assert.ok(з[п]?.trim(), з.id + ': ' + п);
    assert.deepEqual(з.шаги.map(ш => ш.этап), ['Рисунок', 'Игла', 'Клиент'], з.id);
    for (const ш of з.шаги) {
      for (const п of ['вопрос', 'совет', 'ход', 'промах']) assert.ok(ш[п]?.trim(), з.id + ': ' + п);
      assert.ok(ш.факты.length >= 2 && ш.факты.every(f => f.trim()), з.id + ': факты');
      assert.equal(ш.варианты.length, 3, з.id);
      assert.equal(new Set(ш.варианты.map(в => в.id)).size, 3, з.id);
      assert.equal(ш.варианты.filter(в => в.id === ш.верный).length, 1, з.id + ': один верный');
    }
    // Верный ход не всегда на одном месте — иначе заказ проходится наугад одной клавишей.
    assert.ok(new Set(з.шаги.map(ш => ш.варианты.findIndex(в => в.id === ш.верный))).size >= 2, з.id + ': верный на разных местах');
    assert.ok(!/секунд|гильди|Нож|Братств/i.test(JSON.stringify(з)), з.id + ': без секунд и без знаков фракций');
  }
  assert.deepEqual([3, 2, 1, 0].map(исходИглы), ['чисто', 'годно', 'огрех', 'огрех']);
  assert.ok(Object.values(ИСХОДЫ_ИГЛЫ).every(и => и.заголовок && и.журнал));
  // Награда не выше обычных случаев колоды наколок («платит больше» — до 3 гр.).
  assert.deepEqual(работа('наколки').задача.удача, { гроши: 2 });
}

// Вечер в доках с иглой в руках.
function вечерВДоках(S, день) {
  Object.assign(S.мир, { день, отрезок: 'вечер', район: 'доки', конецДня: null, смена: null, нитьДень: день });
  Object.assign(S.герой.тело, { сыт: 4, отдых: 4, тепло: 4, цел: 4 });
}

// ── первая смена — без заказа; вторая — заказ, три этапа, «чисто», пара грошей сверху ──
{
  const S = новоеСостояние('наколки', 5);
  S.герой.кошель = 50;
  вечерВДоках(S, 1);
  начатьСмену(S, работа('наколки'));
  assert.notEqual(S.мир.смена.стадия, 'задача', 'первая смена — без заказа');
  авто(S);
  assert.equal(S.мир.смена, null);
  вечерВДоках(S, 2);
  const кошель = S.герой.кошель, отрезок = S.мир.отрезок;
  начатьСмену(S, работа('наколки'));
  assert.equal(S.мир.смена.стадия, 'задача');
  assert.equal(S.мир.смена.задача.игра, 'игла');
  assert.equal(S.мир.смена.задача.задание, 'i01-yakor', 'первое — лёгкое');
  assert.equal(S.мир.смена.задача.совет.вид, 'слово', '«умеешь» даёт подсказку');
  assert.equal(S.герой.кошель, кошель); assert.equal(S.мир.отрезок, отрезок, 'пока заказ идёт, время стоит');

  const в = видСмены(S);
  assert.equal(в.задача.игра, 'Игла');
  assert.equal(в.задача.заголовокФактов, 'Этап 1 из 3 · Рисунок');
  assert.equal(в.задача.подводка, ИГЛА[0].подводка);
  assert.equal(в.задача.варианты.length, 3);
  assert.ok(в.текст.includes('Клиент садится'));
  // Кнопки — из набора, который рисует карточка задачи: запись, варианты, совет. Отказа посреди работы нет.
  assert.deepEqual(ids(S), ['смена:задача:записать', 'смена:задача:вариант:a', 'смена:задача:вариант:b', 'смена:задача:вариант:c', 'смена:задача:совет']);
  assert.equal(доступныеДействия(S)[0].можно, false, 'без выбора делать нечего');
  assert.equal(доступныеДействия(S)[0].текст, 'Так и сделаю');

  // Выбор меняется до подтверждения; совет — один раз на заказ и только на своём этапе.
  клик(S, 'смена:задача:вариант:a'); клик(S, 'смена:задача:вариант:b');
  assert.equal(S.мир.смена.задача.выбор, 'b');
  клик(S, 'смена:задача:совет');
  assert.equal(видСмены(S).задача.совет, ИГЛА[0].шаги[0].совет);
  клик(S, 'смена:задача:записать');
  const в2 = видСмены(S).задача;
  assert.equal(в2.заголовокФактов, 'Этап 2 из 3 · Игла');
  assert.equal(в2.подводка, ИГЛА[0].шаги[0].ход, 'на следующем этапе видно, что вышло');
  assert.equal(в2.совет, null, 'подсказка прошлого этапа не переходит дальше');
  assert.ok(!ids(S).includes('смена:задача:совет'), 'второй совет на заказ не взять');
  assert.equal(S.мир.смена.задача.выбор, null, 'выбор этапа сброшен');
  assert.deepEqual(в2.этапы.map(x => x.верно), [true, null, null]);

  // Переживает сохранение посреди заказа.
  const S2 = копия(S);
  assert.equal(S2.мир.смена.задача.шаг, 1);
  этап(S2, true);
  assert.equal(доступныеДействия(S2)[0].текст, 'Так и закончу', 'последний этап назван');
  этап(S2, true);
  assert.equal(S2.мир.смена.стадия, 'итог');
  assert.equal(S2.мир.смена.задача.исход, 'чисто');
  const плата = S2.мир.смена.плата, расходники = работа('наколки').цена.расходники;
  assert.equal(S2.герой.кошель, кошель + плата - расходники + 2, 'чисто: плата смены и пара грошей сверху');
  assert.notEqual(S2.мир.отрезок, отрезок, 'время тратится, когда смена закрыта');
  const и = видСмены(S2);
  assert.equal(и.задача.заголовокИтога, 'Чисто');
  assert.ok(и.текст.includes(ИГЛА[0].чисто) && и.текст.includes(ИГЛА[0].шаги[2].ход), 'итог говорит, что вышло на последнем этапе, и исход');
  assert.ok(и.текст.includes('рисунок — верно ✓'), 'этапы названы словом и знаком, не цветом');
  assert.deepEqual(и.задача.варианты, [], 'на итоге нет подписи «Так сходится»');
  assert.deepEqual(учётИгры(S2, 'игла').решены, ['i01-yakor']);
  assert.equal(S2.мир.счётчики.мини_игла_чисто, 1);
  assert.ok(S2.мир.журналДня.includes('Заказ на наколку: чисто.'));

  // Повторная загрузка итоговой карточки ничего не применяет снова.
  const S3 = копия(S2), к3 = S3.герой.кошель;
  клик(S3, 'смена:дальше');
  assert.equal(S3.мир.смена, null); assert.equal(S3.герой.кошель, к3);

  // Через смену — следующий заказ; огрех: без наказания, смена платит как обычно.
  вечерВДоках(S3, 3); начатьСмену(S3, работа('наколки'));
  assert.notEqual(S3.мир.смена.стадия, 'задача', 'не чаще чем через смену'); авто(S3);
  вечерВДоках(S3, 4); начатьСмену(S3, работа('наколки'));
  assert.equal(S3.мир.смена.задача?.задание, 'i02-slovo');
  const к4 = S3.герой.кошель, п4 = S3.мир.смена.плата;
  этап(S3, false); этап(S3, false); этап(S3, true);
  const и4 = видСмены(S3);
  assert.equal(S3.мир.смена.задача.исход, 'огрех');
  assert.equal(и4.задача.заголовокИтога, 'С огрехом');
  assert.equal(S3.герой.кошель, к4 + п4 - расходники, 'огрех: плата смены без надбавки и без штрафа');
  assert.ok(и4.текст.includes(ИГЛА[1].огрех));
  assert.ok(и4.текст.includes('рисунок — мимо ✗'));
  assert.ok(S3.мир.журналДня.includes('Заказ на наколку: с огрехом.'));
  // Промах на этапе виден на следующем.
}
{
  const S = новоеСостояние('наколки', 6);
  стенд.начать(S);
  этап(S, false);
  assert.equal(видСмены(S).задача.подводка, ИГЛА[0].шаги[0].промах);
  этап(S, true); этап(S, true);
  assert.equal(S.мир.смена.задача.исход, 'годно');
  assert.equal(видСмены(S).задача.заголовокИтога, 'Годно');
}

// ── «набил руку»: совет убирает неверный ход текущего этапа, выбор на нём снимается ──
{
  const S = новоеСостояние('наколки', 7);
  стенд.начать(S, { ступень: 'набил руку' });
  этап(S, true);
  const ш = заказ(S).шаги[1], неверный = ш.варианты.find(в => в.id !== ш.верный).id;
  клик(S, 'смена:задача:вариант:' + неверный);
  клик(S, 'смена:задача:совет');
  const в = видСмены(S).задача;
  assert.equal(в.отсев, true);
  assert.equal(в.варианты.find(x => x.отпал).id, неверный);
  assert.equal(S.мир.смена.задача.выбор, null, 'выбор на отпавшем снят');
  assert.equal(доступныеДействия(S).find(а => а.id === 'смена:задача:вариант:' + неверный).можно, false);
  const S2 = копия(S);
  assert.equal(видСмены(S2).задача.варианты.find(x => x.отпал).id, неверный, 'после загрузки отпавший не возвращается');
  этап(S2, true);
  assert.equal(видСмены(S2).задача.варианты.some(x => x.отпал), false, 'на следующем этапе всё снова доступно');
}

// ── заказы кончаются: шесть выданы по разу, бот проходит каждую смену, сверху — не больше 12 гр. ──
{
  const S = новоеСостояние('наколки', 9);
  S.мир.работы.наколки = { смен: 8, видели: ['nak_dom', 'nak_znak_nozhej'], дни: [], последний: null };
  let задач = 0;
  for (let день = 1; день <= 40; день++) {
    вечерВДоках(S, день);
    S.герой.кошель = 100;
    начатьСмену(S, работа('наколки'));
    if (S.мир.смена.стадия === 'задача') задач++;
    авто(S); // бот: первый доступный — запись, если выбор есть, иначе первый вариант
    assert.equal(S.мир.смена, null, 'бот закрывает смену с заказом');
  }
  assert.equal(задач, 6, 'каждый заказ выдан один раз');
  assert.equal(учётИгры(S, 'игла').решены.length, 6);
  const сч = S.мир.счётчики;
  assert.equal((сч.мини_игла_чисто ?? 0) + (сч.мини_игла_годно ?? 0) + (сч.мини_игла_огрех ?? 0), 6);
}

// ── заказ пропал из данных после обновления: смену можно закрыть, плата сохраняется ──
{
  const S = новоеСостояние('наколки', 10);
  стенд.начать(S);
  S.мир.смена.задача.задание = 'i99-net';
  assert.deepEqual(ids(S), ['смена:задача:дальше']);
  const к = S.герой.кошель;
  клик(S, 'смена:задача:дальше');
  assert.equal(S.мир.смена.стадия, 'итог'); assert.ok(S.герой.кошель > к);
  assert.deepEqual(учётИгры(S, 'игла').решены, []);
}

