// Регрессии UI: реальные подписи цены, времени и риска из доступных действий.
import assert from 'node:assert/strict';
import { новоеСостояние } from '../Движок/состояние.js';
import { доступныеДействия } from '../Движок/действия.js';
import { РАЙОНЫ } from '../Данные/районы.js';
import { ЖИЛЬЁ } from '../Данные/жильё.js';
import { КАТЕГОРИИ, категорияДействия, подписьДействия, предупреждениеДействия } from '../Движок/представление-действий.js';
const категории = new Set(КАТЕГОРИИ.map(x => x[0]));
for (const р of РАЙОНЫ) for (const о of ['утро','день','вечер','ночь']) for (const отдых of [0,3]) {
  const S = новоеСостояние('семья', 12);
  S.мир.район = р.id; S.мир.отрезок = о; S.герой.тело.отдых = отдых;
  const до = JSON.stringify(S);
  for (const д of доступныеДействия(S)) {
    if (д.вид !== 'переход' && д.id !== 'отрезок:здесь') assert.ok(категории.has(категорияДействия(д)), д.id);
    const подпись = подписьДействия(д);
    if (д.подпись) assert.ok(подпись.includes(д.подпись), 'сохраняется исходная цена/плата: ' + д.id);
    if (д.вид === 'место') assert.match(подпись, /1 отрезок/);
    if (д.вид === 'переход' && отдых === 0) assert.match(подпись, /2 отрезка/);
    if (д.id.startsWith('сон:')) {
      assert.match(подпись, /до следующего утра/);
      assert.ok(!подпись.includes('без затрат времени'), 'сон не бесплатный по времени');
      const ж = ЖИЛЬЁ.find(x => x.id === д.id.slice(4));
      assert.equal(предупреждениеДействия(д,S).includes('половину кошеля'), !!ж.риск);
    }
    if (д.вид === 'еда') assert.match(подпись, /без затрат времени/);
  }
  assert.equal(JSON.stringify(S), до, 'осмотр действий не меняет состояние');
}
console.log('Интерфейс: стоимость, усталость, посещение, сон, риск и категории в 40 состояниях — OK');

// Главное меню: новая игра с повреждённым авто оставляет резерв и ручной слот.
const { сброситьАвтосейв } = await import('../Движок/состояние.js');
const память = new Map([['порт-теней-авто','повреждено'],['порт-теней-слот-1','ручной слот']]);
globalThis.localStorage = { getItem: к=>память.get(к)??null, setItem:(к,в)=>память.set(к,в), removeItem:к=>память.delete(к) };
сброситьАвтосейв();
assert.equal(память.has('порт-теней-авто'),false);
assert.equal(память.get('порт-теней-слот-1'),'ручной слот');
assert.ok([...память].some(([к,в])=>к.startsWith('порт-теней-авто-резерв-') && в==='повреждено'));
console.log('Главное меню: повреждённый автосейв сохранён в резерв, ручной слот остался — OK');

// Иллюстрированный план не раскрывает названия комнат и не меняет состояние.
const { войти, видПлана } = await import('../Движок/разговор.js');
const Sплан = новоеСостояние('семья',12);
Sплан.мир.район = 'торговый'; Sплан.мир.отрезок = 'вечер'; войти(Sплан,'синий-час');
const снимок = JSON.stringify(Sплан);
const п = видПлана(Sплан);
assert.equal(JSON.stringify(Sплан), снимок);
assert.equal(п.клетки.filter(к=>к.тут).length,1);
assert.equal(п.клетки.find(к=>к.тут).id,'krylco');
assert.ok(п.клетки.filter(к=>!к.открыт).every(к=>к.имя==='?'));
assert.equal(п.клетки.find(к=>к.id==='komnata_nii').цена,60);
assert.deepEqual(new Set(п.этажи.flatMap(э=>э.комнаты)),new Set(п.клетки.map(к=>к.id)));
Sплан.мир.места['синий-час'].осмотрено.push('zal:stol');
assert.equal(видПлана(Sплан).клетки.find(к=>к.id==='zal').имя,'Общий зал');
console.log('План дома: скрытые названия, текущая комната, цена, этажи и отсутствие мутации — OK');
