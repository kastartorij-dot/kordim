// 2. Каждая вещь, которую карточки выдают или требуют, есть в каталоге.
{
  const найдены = new Set();
  const идти = о => {
    if (Array.isArray(о)) return о.forEach(идти);
    if (!о || typeof о !== 'object') return;
    for (const [к, з] of Object.entries(о)) {
      if (к === 'вещь' || к === 'убратьВещь') найдены.add(з);
      if (к === 'предмет' || к === 'безПредмета') [].concat(з).forEach(и => найдены.add(и));
      идти(з);
    }
  };
  идти(Object.values(КОЛОДЫ)); идти(БОЙ);
  const нет = [...найдены].filter(и => typeof и === 'string' && !ВЕЩИ[и]);
  assert.deepEqual(нет, [], `вещи из карточек отсутствуют в каталоге: ${нет.join(', ')}`);
}

