// Страницы финала «Люди» и «Бренн» (Движок/итог-сезона.js, тексты — Данные/финал.js).
// Запуск: node Игры/Порт/Тесты/финал.mjs. Состояния собираются напрямую: здесь проверяется выбор текста,
// а не путь к исходу — пути проверяют шаг11-*.mjs и шаг9-*.mjs.
import assert from 'node:assert/strict';
import { новоеСостояние } from '../Движок/состояние.js';
import { связь } from '../Движок/связи.js';
import { разделыИтога, строкиИтога } from '../Движок/итог-сезона.js';
import { ФИНАЛ, СУДЬБЫ, ДОМ_В_ФИНАЛЕ } from '../Данные/финал.js';

const состояние = () => новоеСостояние('семья', 7);
const линия = (S, кто, поля) => Object.assign(связь(S, кто), поля);
const люди = S => разделыИтога(S).люди;
const отец = S => разделыИтога(S).отец;
const подсказка = /Сопоставь|можно бесплатно|ЗАГОТОВКА/;

// Тексты судеб: у каждой линии есть все исходы, без пустых строк и пометок.
for (const [кто, судьба] of Object.entries(СУДЬБЫ))
  for (const ключ of ['вместе', 'вместеОтъезд', 'дружба', 'дружбаОтъезд', 'отказ', 'позже', 'пауза', 'расстались', 'знакомы', 'доступ'])
    assert.ok(судьба[ключ] && !подсказка.test(судьба[ключ]), `${кто}.${ключ}`);

// Исход линии выбирает свой абзац; незнакомых линий на странице нет.
{
  const S = состояние();
  assert.deepEqual(люди(S), []);
  линия(S, 'freya', { этап: 'после', статус: 'вместе', решение: { что: 'да' } });
  линия(S, 'tava', { этап: 'решение', статус: 'нет', решение: { что: 'позже' } });
  линия(S, 'niya', { этап: 'знакомство', доступ: 3 });
  assert.deepEqual(люди(S), [СУДЬБЫ.freya.вместе, СУДЬБЫ.niya.доступ, СУДЬБЫ.tava.позже], 'порядок линий и исходы');
  // Журнал и прежние проверки читают короткие строки — они не изменились.
  const строки = строкиИтога(S, разделыИтога(S));
  assert.ok(строки.some(x => /Фрея: вы вместе/.test(x)) && строки.some(x => /Это был доступ, а не близость/.test(x)));
  // Уехавший герой: «вместе» и дружба получают прощальный вариант, остальное как было.
  S.мир.уехать = { исход: 'по-книге' };
  assert.deepEqual(люди(S), [СУДЬБЫ.freya.вместеОтъезд, СУДЬБЫ.niya.доступ, СУДЬБЫ.tava.позже], 'отъезд');
  // «Остался у судна» — не отъезд.
  S.мир.уехать = { исход: 'остался' };
  assert.equal(люди(S)[0], СУДЬБЫ.freya.вместе);
}

// Работники дома — одним абзацем на своей странице и только те, кого герой спросил.
{
  const S = состояние();
  S.мир.диалоги = { starshaya: { факты: ['дом_ответ'] }, kim: { факты: ['дом_ответ'] }, betta: { факты: [] } };
  assert.deepEqual(люди(S), [], 'работники дома — своя страница, не «Люди»');
  const [дом] = разделыИтога(S).дом;
  assert.ok(дом.startsWith(ДОМ_В_ФИНАЛЕ.вступление) && дом.includes(ДОМ_В_ФИНАЛЕ.starshaya) && дом.includes(ДОМ_В_ФИНАЛЕ.kim));
  assert.ok(!дом.includes(ДОМ_В_ФИНАЛЕ.betta), 'не спрошенная Бетта не попадает в итог');
}

// Бренн: от «не расспросил» до понимания и судьбы журнала, без подсказок игроку.
{
  const S = состояние();
  assert.deepEqual(отец(S), [ФИНАЛ.отец.неСпрашивал]);
  S.мир.свидетельства = ['brenn_bras_word', 'brenn_gorm_word'];
  assert.match(отец(S)[0], /из 2 мест из девяти/);
  S.мир.свидетельства = ['brenn_bras_word'];
  assert.match(отец(S)[0], /из 1 места из девяти/);
  assert.match(разделыИтога(S).записиОтца[0], /Брас говорит/, 'фразы самих записей — отдельным списком');
  S.мир.свидетельства = ['brenn_bras_word', 'brenn_cell17', 'brenn_gorm_word', 'brenn_hostel_book', 'brenn_healer_card', 'brenn_second_journal'];
  S.мир.нитьБренна = { решение: 'сожжён' };
  const п = отец(S);
  assert.equal(п[0], ФИНАЛ.отец.понимание);
  assert.ok(п.includes(ФИНАЛ.отец.граница) && п.includes(ФИНАЛ.журнал.сожжён), п.join(' | '));
  assert.ok(!п.some(x => подсказка.test(x)), 'в финале нет подсказок');
  assert.ok(!разделыИтога(S).записиОтца.some(x => /частные записи отца/.test(x)), 'о журнале говорит абзац судьбы, не запись');
  S.мир.сверкаВесов = { сопоставил: true };
  assert.ok(отец(S).includes(ФИНАЛ.отец.сверено) && !отец(S).includes(ФИНАЛ.отец.граница));
  // Журнал на руках у уехавшего — уезжает с ним.
  S.мир.нитьБренна = { решение: 'оставлен' };
  S.мир.уехать = { исход: 'локи' };
  assert.equal(отец(S).at(-1), ФИНАЛ.журнал.увёз);
}

console.log('Финал: судьбы трёх линий, отъезд, работники дома, страница «Бренн» — OK');
