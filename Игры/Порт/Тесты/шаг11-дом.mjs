// Шаг 11, пакет 5: работники «Синего часа». Запуск: node Игры/Порт/Тесты/шаг11-дом.mjs
// У каждого работника из реестра — желание, что держит, условия ухода/пребывания; у тех, кто не цель «Вытащить», —
// написанный ответ в разговоре и строка итога сезона. Ола не участвует (решение автора) — и это написано в карточке.
import assert from 'node:assert/strict';
import { новоеСостояние } from '../Движок/состояние.js';
import { войти, действияСцены } from '../Движок/разговор.js';
import { итогСезона } from '../Движок/цели.js';
import { МЕСТА } from '../Данные/места.js';
import { РАБОТНИКИ_ДОМА, итогиРаботников } from '../Данные/работники-дома.js';
import { РАБОТНИЦЫ } from '../Данные/вытащить.js';
import { нажать, вХаб, ветка } from './утилиты/линии.js';

const дом = МЕСТА.find(м => м.id === 'синий-час').модуль;

// ── карточки: все работники дома из реестра, без пустых полей ─────────────
const работники = Object.keys(дом.ЛЮДИ).filter(id => id !== 'yarna'); // Ярна — хозяйка, не работница
assert.deepEqual(работники.sort(), Object.keys(РАБОТНИКИ_ДОМА).sort(), 'карточка у каждого работника дома');
for (const [id, р] of Object.entries(РАБОТНИКИ_ДОМА)) {
  for (const поле of ['имя', 'желание', 'держит', 'уход']) assert.ok(р[поле]?.length > 0, `${id}: ${поле}`);
  if (р.участвует === false) {
    assert.match(р.уход, /не участвует/, `${id}: причина неучастия написана`);
    assert.ok(!дом.ДИАЛОГИ[id].хаб.includes('дом_ответ') && !РАБОТНИЦЫ[id], `${id}: не предлагается ни в линии, ни в «Вытащить»`);
    continue;
  }
  // У каждого участвующего ответ есть в игре: цель «Вытащить» или ветка разговора.
  const ветвь = р.ответ === 'уйти' ? 'дом_ответ' : р.ответ;
  assert.ok(РАБОТНИЦЫ[id] || дом.ДИАЛОГИ[id].ветки[ветвь], `${id}: ответ есть в игре`);
  if (р.ответ === 'уйти') assert.ok(р.итог, `${id}: личный итог`);
}

// ── в игре: спросить старшую, повариху и Сиба ──────────────────────────
function у(кто, комната) {
  const S = новоеСостояние('семья', 61);
  S.мир.день = 5; S.мир.отрезок = 'вечер'; S.мир.район = 'доки'; S.герой.кошель = 300;
  S.герой.тело = { сыт: 3, отдых: 3, тепло: 3, цел: 3 };
  // Доверие 1 — порог ветки; как его набрать, проверяют графы шага 10. Здесь — что ответ написан и запоминается.
  S.мир.люди[кто] = { спрошено: [], исчерпано: [], распол: 1 };
  войти(S, 'синий-час');
  S.сцена.вошёл = true; S.сцена.комната = комната; S.сцена.диалог = null; S.сцена.собеседник = null;
  S.мир.места['синий-час'].визитов = 2;
  нажать(S, `заговорить:${кто}`); вХаб(S);
  return S;
}
const ответы = [];
const комнатаКого = кто => Object.entries(дом.КОМНАТЫ).find(([, К]) => К.люди.includes(кто))[0];
const спросить = Object.entries(РАБОТНИКИ_ДОМА).filter(([, р]) => р.ответ === 'уйти').map(([id]) => id);
assert.equal(спросить.length, 13, 'старшая, повариха, Сиб и десять жителей шага 10');
for (const кто of спросить) {
  const ясно = 'ясно';
  const S = у(кто, комнатаКого(кто));
  assert.ok(действияСцены(S).some(а => а.id === 'ветка:дом_ответ'), `${кто}: ветка ответа видна при доверии 1`);
  ветка(S, 'дом_ответ', ясно);
  assert.ok(S.мир.диалоги[кто].факты.includes('дом_ответ'));
  const строки = итогиРаботников(S);
  assert.deepEqual(строки, [РАБОТНИКИ_ДОМА[кто].итог]);
  S.мир.день = 30; S.мир.итогСезона = null;
  assert.ok(итогСезона(S).строки.includes(РАБОТНИКИ_ДОМА[кто].итог), `${кто}: строка в итоге сезона`);
  ответы.push(кто);
}
assert.equal(ответы.length, 13);
// Без разговора итог о человеке не пишется: игра не знает того, чего герой не спросил.
assert.deepEqual(итогиРаботников(новоеСостояние('семья', 62)), []);

console.log('шаг 11 (работники дома): все проверки пройдены');
