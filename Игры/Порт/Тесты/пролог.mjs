// Пролог (монтаж 12.11): файлы на месте, планы ролика по порядку и внутри файла, строки короткие,
// у каждого начала — короткий абзац. Показ (видео, канат, касания) проверяется в браузере.
// node Игры/Порт/Тесты/пролог.mjs
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ВСТУПЛЕНИЕ } from '../Данные/вступление.js';
import { НАЧАЛА } from '../Данные/герой.js';

const П = ВСТУПЛЕНИЕ.пролог, РЕС = fileURLToPath(new URL('../Ресурсы/', import.meta.url));
for (const ф of [П.ролик, ...Object.values(П.стоп)]) assert.ok(fs.existsSync(РЕС + ф), 'нет ' + ф);
assert.ok(fs.statSync(РЕС + П.ролик).size < 3e6, 'ролик легче 3 МБ — его смотрят с телефона');
for (const имя of ['прибытие', 'сходня', 'город']) assert.ok(П.планы[имя] && П.стоп[имя], 'план и стоп-кадр: ' + имя);
let прежний = 0;
for (const [имя, п] of Object.entries(П.планы)) { assert.ok(п.с >= прежний && п.по > п.с && п.по <= 10.6, 'план вне порядка: ' + имя); прежний = п.по; }
const строки = [...П.тьма, П.наБарже, ...Object.values(П.планы).map(п => п.т).filter(Boolean), ...Object.values(П.бросок), ...П.разговор.map(р => р.т), П.удар, ВСТУПЛЕНИЕ.цель];
for (const т of строки) assert.ok(т.length <= 80, 'строка пролога длиннее 80 знаков: ' + т);
assert.ok(['удача', 'недолёт', 'перелёт'].every(к => П.бросок[к]), 'три исхода броска');
assert.ok(!/секунд|гильди|маги/i.test(строки.join(' ')), 'снятые слова');
for (const н of НАЧАЛА) assert.ok(ВСТУПЛЕНИЕ.коротко[н.id]?.length <= 140, 'короткий абзац начала ' + н.id);
console.log(`пролог: ok — ${строки.length} строк, самая длинная ${Math.max(...строки.map(т => т.length))} знаков`);
