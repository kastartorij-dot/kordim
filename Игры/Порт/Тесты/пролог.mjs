// Пролог (12.11): файлы на месте, субтитры по порядку внутри ролика, строки короткие, у каждого начала — короткий абзац.
// Сам показ (видео, бросок, касания) проверяется в браузере. node Игры/Порт/Тесты/пролог.mjs
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ВСТУПЛЕНИЕ } from '../Данные/вступление.js';
import { НАЧАЛА } from '../Данные/герой.js';

const П = ВСТУПЛЕНИЕ.пролог, РЕС = fileURLToPath(new URL('../Ресурсы/', import.meta.url));
for (const ф of [П.ролик, П.кадрРолика, ВСТУПЛЕНИЕ.кадры.прибытие]) assert.ok(fs.existsSync(РЕС + ф), 'нет ' + ф);
assert.ok(fs.statSync(РЕС + П.ролик).size < 4e6, 'ролик легче 4 МБ — его смотрят с телефона');
let прежний = 0;
for (const с of П.субтитры) { assert.ok(с.с >= прежний && с.по > с.с && с.по <= 15, 'субтитр вне порядка: ' + с.т); прежний = с.по; }
const строки = [...П.тьма, ...П.субтитры.map(с => с.т), ...Object.values(П.бросок), ...П.разговор.map(р => р.т), П.удар, ВСТУПЛЕНИЕ.цель];
for (const т of строки) assert.ok(т.length <= 80, 'строка пролога длиннее 80 знаков: ' + т);
assert.ok(!/секунд|гильди|маги/i.test(строки.join(' ')), 'снятые слова');
for (const н of НАЧАЛА) assert.ok(ВСТУПЛЕНИЕ.коротко[н.id]?.length <= 140, 'короткий абзац начала ' + н.id);
console.log(`пролог: ok — ${строки.length} строк, самая длинная ${Math.max(...строки.map(т => т.length))} знаков`);
