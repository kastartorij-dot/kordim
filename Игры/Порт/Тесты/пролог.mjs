// Пролог (третья версия 12.11, без видео): файлы на месте, у каждого говорящего есть голова, строки короткие,
// три исхода броска, у каждого начала — короткий абзац. Показ (вода, канат, касания) проверяется в браузере.
// node Игры/Порт/Тесты/пролог.mjs
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ВСТУПЛЕНИЕ } from '../Данные/вступление.js';
import { НАЧАЛА } from '../Данные/герой.js';
import { ОЗВУЧКА_ПРОЛОГА, ГОЛОСА_ПРОЛОГА, ПРОБЫ } from '../Данные/озвучка-пролога.js';

const П = ВСТУПЛЕНИЕ.пролог, РЕС = fileURLToPath(new URL('../Ресурсы/', import.meta.url));
for (const ф of [П.кадр, П.ролик, ...Object.values(П.стоп)]) assert.ok(fs.existsSync(РЕС + ф), 'нет ' + ф);
assert.ok(fs.statSync(РЕС + П.ролик).size < 3e6, 'ролик легче 3 МБ');
for (const р of П.разговор.filter(р => р.кто)) {
  const г = П.голоса[р.кто];
  assert.ok(г?.имя && г.лицо && fs.existsSync(РЕС + г.лицо), 'нет головы говорящего: ' + р.кто);
}
const строки = [...П.рассказ, П.сходня, ...Object.values(П.бросок), ...П.разговор.map(р => р.т), П.удар, ВСТУПЛЕНИЕ.цель];
for (const т of строки) assert.ok(т.length <= 80, 'строка пролога длиннее 80 знаков: ' + т);
assert.ok(['удача', 'недолёт', 'перелёт'].every(к => П.бросок[к]), 'три исхода броска');
assert.ok(!/секунд|гильди|маги/i.test(строки.join(' ')), 'снятые слова');
for (const н of НАЧАЛА) assert.ok(ВСТУПЛЕНИЕ.коротко[н.id]?.length <= 140, 'короткий абзац начала ' + н.id);
// Озвучка: у каждой строки есть субтитр, теги только в квадратных скобках, слова без тегов совпадают с субтитром.
const слова = т => т.replace(/\[[^\]]*\]/g, ' ').toLowerCase().replace(/ё/g, 'е').match(/[а-яa-z0-9]+/g)?.join(' ') ?? '';
const субтитр = ключ => { const [а, б] = ключ.split('.'); return а === 'удар' ? П.удар : а === 'сходня' ? П.сходня : а === 'рассказ' ? П.рассказ[+б] : а === 'бросок' ? П.бросок[б] : П.разговор[+б]?.т; };
for (const с of ОЗВУЧКА_ПРОЛОГА) {
  const т = субтитр(с.ключ);
  assert.ok(т, 'нет субтитра для ' + с.ключ);
  assert.ok(ГОЛОСА_ПРОЛОГА[с.кто], 'нет голоса ' + с.кто);
  assert.equal(слова(с.синтез), слова(т), 'слова озвучки расходятся с субтитром: ' + с.ключ);
}
for (const [кто, ключи] of Object.entries(ПРОБЫ)) for (const к of ключи) assert.ok(ОЗВУЧКА_ПРОЛОГА.some(с => с.ключ === к && с.кто === кто), 'проба без строки: ' + к);
console.log(`пролог: ok — ${строки.length} строк, самая длинная ${Math.max(...строки.map(т => т.length))} знаков`);
