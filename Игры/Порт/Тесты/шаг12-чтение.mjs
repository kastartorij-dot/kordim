// Шаг 12: мини-игра «Чтение комнаты» — рынок, двор Горма, лекарь. node Игры/Порт/Тесты/шаг12-чтение.mjs
// Два взгляда, потом ответ; таймера нет. Верно с нужной приметой — тема, верно наугад — деталь, неверно — промах.
// Чтение одно на место за всю игру, итог один раз и стоит один ход, «назад» его не переигрывает, шов уровня.
import assert from 'node:assert/strict';
import { новоеСостояние, мигрировать } from '../Движок/состояние.js';
import { войти, действияСцены, видСцены } from '../Движок/разговор.js';
import { ЧТЕНИЯ, ВЗГЛЯДОВ } from '../Данные/чтение.js';
import { РЕЕСТР } from '../Данные/темы.js';
import { место } from '../Данные/места.js';
import { учётЧтения, уровеньЧтения, стенд } from '../Движок/чтение.js';
const стендДвора = { начать: S => стенд.начать(S, { вариант: 'двор' }) }, стендЛекаря = { начать: S => стенд.начать(S, { вариант: 'лекарь' }) };
import { уровеньИзДоли, уровеньИзСчёта, уровеньИтога } from '../Движок/уровень.js';
import { завершитьИглу } from '../Движок/игла.js';
import { СТЕНД_ИГР as СТЕНД } from '../Движок/мини-игры.js';
// Здесь проверяется спокойный режим (выбор хода): в игре с 03.11 идёт живой слой, его — Тесты/живые-игры.mjs.
import { СЛОЙ } from '../Движок/уровень.js';
СЛОЙ.живой = false;

const ids = S => действияСцены(S).map(а => а.id);
const ход = (S, id) => { const а = действияСцены(S).find(х => х.id === 'игра:чтение:' + id); assert.ok(а, `нет хода ${id}: ` + ids(S).join(' | ')); а.выполнить(S); };
const копия = S => мигрировать(JSON.parse(JSON.stringify(S)));

// ── данные: приметы и ответы на месте, награды — то, что в комнате уже есть ──
for (const [id, ч] of Object.entries(ЧТЕНИЯ)) {
  const к = место(ч.место)?.модуль?.КОМНАТЫ?.[ч.комната];
  assert.ok(к, id + ': комната есть');
  assert.equal(ч.куда.length, 4, id); assert.ok(ч.нужно.every(x => ч.куда.some(к2 => к2.id === x)), id + ': нужные приметы есть');
  assert.equal(ч.варианты.filter(в => в.id === ч.верный).length, 1, id);
  assert.ok(РЕЕСТР[ч.отлично.тема], id + ': тема существует');
  assert.ok(к.детали.some(д => д.id === ч.нормально.деталь), id + ': деталь из этой комнаты');
  assert.ok(ч.плохо.trim() && ч.начало.trim() && ч.вопрос.trim());
  assert.ok(!/секунд|гильди/i.test(JSON.stringify(ч)), id);
}
// Уровни спокойного режима и шва.
{
  const ч = ЧТЕНИЯ.рынок;
  assert.equal(уровеньЧтения(ч, ['весы'], 'b'), 'отлично');
  assert.equal(уровеньЧтения(ч, ['полка', 'корзины'], 'b'), 'нормально', 'верно наугад');
  assert.equal(уровеньЧтения(ч, ['весы', 'толпа'], 'a'), 'плохо');
  assert.deepEqual([1, 0.9, 0.6, 0.2].map(уровеньИзДоли), ['отлично', 'отлично', 'нормально', 'плохо']);
  assert.deepEqual([3, 2, 1, 0].map(n => уровеньИзСчёта(n, 3)), ['отлично', 'нормально', 'плохо', 'плохо']);
  // Итог песочницы { уровень, очки } — тот же уровень; без уровня — по доле очков.
  assert.deepEqual([{ уровень: 'отлично', очки: 3 }, { очки: 0.6 }, 'нормально', null, 'чушь'].map(уровеньИтога), ['отлично', 'нормально', 'нормально', 'плохо', 'плохо']);
}

const наРынке = () => { const S = новоеСостояние('семья', 4); Object.assign(S.мир, { район: 'торговый', день: 3, отрезок: 'день' }); войти(S, 'рынок'); return S; };

// ── рынок: два взгляда, верный ответ с приметой — тема, один ход, один раз за игру ──
{
  const S = наРынке();
  const х0 = S.сцена.ходы, тем0 = S.мир.темы.length;
  const а = действияСцены(S).find(х => х.текст === 'Присмотреться к комнате');
  assert.ok(а && а.можно); а.выполнить(S);
  assert.equal(S.сцена.ходы, х0, 'начать даром');
  const в = видСцены(S).игра;
  assert.equal(в.вид, 'чтение'); assert.equal(в.вопрос, ЧТЕНИЯ.рынок.вопрос); assert.equal(в.строки[0], 'Взглядов: 0 из 2');
  assert.equal(ids(S).filter(x => x.includes(':взгляд:')).length, 4);
  assert.equal(ids(S).filter(x => x.includes(':ответ:')).length, 3, 'ответить можно и сразу');
  ход(S, 'взгляд:весы');
  assert.equal(S.история.length, 0, 'взгляд не переигрывается «назад»');
  assert.equal(видСцены(S).игра.реплика, ЧТЕНИЯ.рынок.куда[0].примета);
  const S2 = копия(S);
  ход(S2, 'взгляд:полка');
  assert.equal(ids(S2).filter(x => x.includes(':взгляд:')).length, 0, `взглядов ${ВЗГЛЯДОВ}`);
  assert.ok(видСцены(S2).игра.строки.some(x => x.startsWith('Видно: Кошка')), 'увиденное остаётся на карточке');
  ход(S2, 'ответ:b');
  assert.equal(S2.сцена.игра, null);
  assert.equal(S2.сцена.ходы, х0 + 1, 'итог — один ход');
  assert.ok(S2.мир.темы.includes('giri_legche'));
  assert.equal(S2.мир.темы.length, тем0 + 1);
  assert.equal(S2.сцена.итогИгры.заголовок, 'Прочёл');
  assert.ok(S2.мир.журналДня.includes('Чтение комнаты: прочёл.'));
  assert.ok(!действияСцены(S2).some(х => х.текст === 'Присмотреться к комнате'), 'чтение места — один раз за игру');
}
// ── верно наугад — деталь комнаты (осмотрена, текст в итоге); неверно — промах без награды ──
{
  const S = наРынке();
  действияСцены(S).find(х => х.текст === 'Присмотреться к комнате').выполнить(S);
  ход(S, 'взгляд:полка'); ход(S, 'взгляд:корзины'); ход(S, 'ответ:b');
  assert.equal(S.сцена.итогИгры.уровень, 'нормально');
  assert.ok(S.мир.места.рынок.осмотрено.includes('ворота-рынка:кошка'));
  assert.ok(S.сцена.реплика.includes('Кошка по имени Гиря'), 'текст детали в итоге');
  assert.ok(!S.мир.темы.includes('giri_legche'));
}
{
  const S = новоеСостояние('семья', 5);
  стендДвора.начать(S);
  const тем0 = S.мир.темы.length;
  ход(S, 'ответ:a');
  assert.equal(S.сцена.итогИгры.уровень, 'плохо');
  assert.equal(S.сцена.реплика, ЧТЕНИЯ.двор.плохо);
  assert.equal(S.мир.темы.length, тем0);
  assert.ok(действияСцены(S).some(х => х.текст === 'Уйти'), 'после промаха место открыто');
}
// ── двор и лекарь: верное чтение даёт свою тему ──
for (const [с, id, тема] of [[стендДвора, 'двор', 'rany_boytsov'], [стендЛекаря, 'лекарь', 'seraya_radost']]) {
  const S = новоеСостояние('бумаги', 6);
  assert.equal(с.начать(S), true, id);
  ход(S, 'взгляд:' + ЧТЕНИЯ[id].нужно[0]); ход(S, 'ответ:' + ЧТЕНИЯ[id].верный);
  assert.ok(S.мир.темы.includes(тема), id);
  assert.deepEqual(учётЧтения(S).решены, [id]);
}
assert.equal(стенд.начать(новоеСостояние('наколки', 7)), true);
// Действие «Присмотреться» есть в каждой из трёх комнат при обычном входе.
for (const [id, район] of [['рынок', 'торговый'], ['двор', 'трущобы'], ['лекарь', 'жилые-улицы']]) {
  const S = новоеСостояние('семья', 8); Object.assign(S.мир, { район, день: 3, отрезок: 'день' });
  войти(S, ЧТЕНИЯ[id].место); S.сцена.комната = ЧТЕНИЯ[id].комната;
  const а = действияСцены(S).find(х => х.текст === 'Присмотреться к комнате');
  assert.ok(а?.можно, id + ': действие «Присмотреться» в комнате'); а.выполнить(S);
  assert.equal(S.сцена.игра?.чтение, id);
}
// Живой итог в «Иглу»: заказ закрывается тем же исходом, что спокойный режим дал бы за три верных этапа.
{
  const S = новоеСостояние('наколки', 9);
  СТЕНД.find(с => с.id === 'игла').начать(S);
  assert.equal(завершитьИглу(S, { уровень: 'отлично', очки: 97 }), true);
  assert.equal(S.мир.смена.задача.исход, 'чисто');
}
console.log('шаг 12, «Чтение комнаты»: проверки пройдены');
