assert.equal(СЛОЙ.живой, true, 'в игре (не на стенде) по умолчанию живой слой');
const стенд = id => СТЕНД_ИГР.find(с => с.id === id);
const копия = S => мигрировать(JSON.parse(JSON.stringify(S)));
const ходы = S => (S.мир.смена ? доступныеДействия(S).filter(а => а.группа === 'смена') : действияСцены(S));
const ход = (S, id, итог) => {
  const а = ходы(S).find(х => х.id === id);
  assert.ok(а, `нет хода ${id}: ` + ходы(S).map(х => х.id).join(' | '));
  assert.ok(а.можно !== false, id + ' недоступен');
  а.выполнить(S, итог);
};
const текстом = f => { СЛОЙ.живой = false; try { f(); } finally { СЛОЙ.живой = true; } };
const итог = (уровень, очки = { плохо: 0.2, нормально: 0.6, отлично: 0.95 }[уровень]) => ({ уровень, очки });

// След расчётов: всё о герое и мире, кроме номера шага (выбор — несколько касаний, живая игра — одно), текста
// итога и внутренностей самой партии. Торг дня — без списка сказанных доводов и промахов (у живой их нет).
function след(S) {
  const мир = JSON.parse(JSON.stringify(S.мир));
  delete мир.шаг;
  if (мир.смена) мир.смена = { стадия: мир.смена.стадия, строки: мир.смена.итог?.строки ?? null, плата: мир.смена.плата ?? null };
  // Сколько раундов ушло, важно только «торговался или нет»: после перегиба дальше торговаться нельзя в обоих слоях.
  for (const м of Object.values(мир.места ?? {})) if (м.торг) {
    for (const к of ['доводы', 'промахов']) delete м.торг[к];
    м.торг.раундов = Object.fromEntries(Object.entries(м.торг.раундов ?? {}).map(([к, v]) => [к, v > 0]));
  }
  const сцена = S.сцена && { место: S.сцена.место, комната: S.сцена.комната, игра: !!S.сцена.игра, уровень: S.сцена.итогИгры?.уровень ?? null, флаги: S.сцена.флагиВечера ?? null, ходов: S.сцена.ходов ?? null, времяВышло: !!S.сцена.времяВышло };
  return { герой: S.герой, мир, сцена };
}
const сверить = (живой, текстовый, что) => assert.deepEqual(след(живой), след(текстовый), что);

// Ход «живая» — один, с модулем песочницы и навыком 0–2; модуль на месте и отдаёт запустить().
function живойХод(S, id, игра) {
  const А = ходы(S), ж = А.filter(а => а.живая);
  assert.equal(ж.length, 1, 'один живой ход: ' + А.map(а => а.id).join(' | '));
  assert.equal(ж[0].id, id);
  assert.equal(ж[0].живая.игра, игра);
  assert.ok([0, 1, 2].includes(ж[0].живая.навык), 'навык 0–2: ' + ж[0].живая.навык);
  assert.ok(ж[0].живая.заголовок, 'у окна есть заголовок');
  const код = readFileSync(new URL(`../Движок/песочница/${игра}.js`, import.meta.url), 'utf8');
  assert.match(код, /export async function запустить\(/, игра + ': вход запустить()');
  // Построить ходы и показать вид — не менять состояние: до итога игры сохранять нечего.
  const до = JSON.stringify(S);
  ходы(S); S.мир.смена ? видЗадачи(S) : видИгры(S);
  assert.equal(JSON.stringify(S), до, 'ходы и вид не меняют состояние');
  // Перезагрузка посреди игры: сохранено состояние до хода — после загрузки тот же ход на месте.
  assert.ok(ходы(копия(S)).some(а => а.id === id && а.живая), 'после перезагрузки занятие начинается заново');
  // Текстового выбора нет.
  assert.ok(!А.some(а => /:(вариант|записать|совет|довод|давить|оставить|переброс|ответ|взгляд|кивок):?/.test(а.id)), 'нет ходов выбора: ' + А.map(а => а.id).join(' | '));
}

const проверено = [];

// ── Вес и Счёт: отлично и нормально — «сошлось» (как верный ответ), плохо — «не сошлось» ──
for (const [игра, ступень] of [['вес', 'умеешь'], ['счёт', 'умеешь']]) {
  const S0 = новоеСостояние('бумаги', 11);
  assert.ok(стенд(игра).начать(S0, { ступень }), игра + ': смена с задачей');
  живойХод(S0, 'смена:задача:живая', игра);
  const в = видЗадачи(S0);
  assert.ok(в.живая && !в.варианты.length && !в.факты.length && !в.вопрос, игра + ': карточка без вопроса и ответов');
  const з = задание(игра, S0.мир.смена.задача.задание);
  const поТексту = верно => { const T = копия(S0); текстом(() => { ход(T, 'смена:задача:вариант:' + (верно ? з.верный : з.варианты.find(x => x.id !== з.верный).id)); ход(T, 'смена:задача:записать'); }); return T; };
  const удача = поТексту(true), ошибка = поТексту(false);
  assert.equal(удача.мир.смена.стадия, 'итог');
  for (const у of УРОВНИ) {
    const S = копия(S0);
    ход(S, 'смена:задача:живая', итог(у));
    assert.equal(S.мир.смена.стадия, 'итог', `${игра}/${у}: смена закрыта`);
    сверить(S, у === 'плохо' ? ошибка : удача, `${игра}/${у}: те же деньги, люди, отметки, что у ${у === 'плохо' ? 'неверного' : 'верного'} ответа`);
    assert.equal(S.мир.смена.итог.текст, ЖИВЫЕ_ИТОГИ[игра][у === 'плохо' ? 'ошибка' : 'удача'], `${игра}/${у}: текст итога без чисел задания`);
    assert.equal(видЗадачи(S).заголовокИтога, у === 'плохо' ? 'Не сошлось' : 'Сошлось');
  }
  // Окно брошено посреди игры — провал с понятным текстом.
  const Б = копия(S0);
  ход(Б, 'смена:задача:живая', { уровень: 'плохо', очки: 0, брошено: true });
  сверить(Б, ошибка, игра + ': брошено = не сошлось');
  assert.equal(Б.мир.смена.итог.текст, ЖИВЫЕ_ИТОГИ.брошено);
  // «Отложить» — как прежде: уточнение, потом задача уходит без последствий.
  const О = копия(S0), Отекст = копия(S0);
  ход(О, 'смена:задача:отложить'); ход(О, 'смена:задача:отложить-да');
  текстом(() => { ход(Отекст, 'смена:задача:отложить'); ход(Отекст, 'смена:задача:отложить-да'); });
  сверить(О, Отекст, игра + ': отложить — как в спокойном режиме');
  // Бот без итога (ход вызван без партии) — провал.
  const Бот = копия(S0);
  ход(Бот, 'смена:задача:живая');
  сверить(Бот, ошибка, игра + ': ход без итога — провал');
  проверено.push(игра);
}

