// ── Торг: отлично — все раунды верны, нормально — все, кроме одного, плохо — перегиб; покупка — как прежде ──
for (const вариант of ['кафтан:день', 'кафтан:вечер', 'плащ:день']) {
  const S0 = новоеСостояние('бумаги', 3);
  assert.ok(стенд('торг').начать(S0, { вариант, ступень: 'умеешь' }), 'торг: партия ' + вариант);
  живойХод(S0, 'игра:торг:живая', 'торг');
  const товар = вариант.split(':')[0];
  const { ТОРГ } = await import('../Данные/торг.js');
  const т = ТОРГ[товар], макс = вариант.endsWith('вечер') ? 3 : 2;
  const верные = т.доводы.filter(д => д.верный && (!д.условие?.отрезок || д.условие.отрезок === S0.сцена.отрезок)).map(д => д.id);
  const неверные = т.доводы.filter(д => !д.верный).map(д => д.id);
  const поТексту = (доводы, купить) => { const T = копия(S0); текстом(() => { for (const д of доводы) ход(T, 'игра:торг:довод:' + д); if (купить) ход(T, 'игра:торг:купить'); else ход(T, 'игра:торг:уйти'); }); return T; };
  const план = {
    отлично: верные.slice(0, макс),
    нормально: [...верные.slice(0, макс - 1), неверные[0]],
    плохо: неверные.slice(0, 2),
  };
  assert.equal(план.отлично.length, макс, 'хватает верных доводов на ' + вариант);
  for (const у of УРОВНИ) for (const купить of [true, false]) {
    const S = копия(S0);
    ход(S, 'игра:торг:живая', итог(у));
    assert.ok(S.сцена.игра, 'после торга — ещё у прилавка');
    assert.ok(!ходы(S).some(а => а.живая), 'второй раз за день не торгуются');
    ход(S, купить ? 'игра:торг:купить' : 'игра:торг:уйти');
    сверить(S, поТексту(план[у], купить), `торг ${вариант}/${у}/${купить ? 'купил' : 'ушёл'}: цена, расположение Пина, время`);
  }
  проверено.push('торг');
}

// ── Кости: отлично — выигрыш, нормально — вровень, плохо — проигрыш ──
{
  // Моряк в таверне: ставка 2 гр. Сверка с костями спокойного режима, где кон вышел тем же исходом.
  const S0 = новоеСостояние('бумаги', 9);
  assert.ok(стенд('кости').начать(S0, { вариант: 'таверна', ступень: 'нет' }), 'кости: таверна');
  живойХод(S0, 'игра:кости:живая', 'кости');
  const было = S0.герой.кошель;
  for (const у of УРОВНИ) {
    const S = копия(S0);
    ход(S, 'игра:кости:живая', итог(у));
    assert.equal(S.герой.кошель - было, { отлично: 2, нормально: 0, плохо: -2 }[у], 'кости/таверна/' + у);
    assert.ok(!S.сцена.игра, 'кон один');
  }
  // Тот же исход у спокойного режима (кубики из зерна) — те же деньги, расположение и журнал.
  let сверено = 0;
  for (let зерно = 1; зерно < 40 && сверено < 3; зерно++) {
    const Z = новоеСостояние('бумаги', зерно);
    стенд('кости').начать(Z, { вариант: 'таверна', ступень: 'нет' });
    const T = копия(Z);
    текстом(() => ход(T, 'игра:кости:оставить'));
    const д = T.герой.кошель - Z.герой.кошель, у = д > 0 ? 'отлично' : д < 0 ? 'плохо' : 'нормально';
    const S = копия(Z);
    ход(S, 'игра:кости:живая', итог(у));
    сверить(S, T, 'кости/таверна: как кон спокойного режима с исходом ' + ИСХОД_КОСТЕЙ[у]);
    сверено++;
  }
  assert.equal(сверено, 3);
  // Горм: выиграл — спрашиваешь, проиграл — отвечаешь, вровень — ещё одна живая партия.
  const G = новоеСостояние('бумаги', 9);
  assert.ok(стенд('кости').начать(G, { вариант: 'горм', ступень: 'нет' }), 'кости: Горм');
  живойХод(G, 'игра:кости:живая', 'кости');
  const В = копия(G); ход(В, 'игра:кости:живая', итог('отлично'));
  assert.equal(В.сцена.игра.стадия, 'вопрос');
  assert.ok(ходы(В).some(а => а.id.startsWith('игра:кости:вопрос:')) && !ходы(В).some(а => а.живая), 'после выигрыша — вопрос словами');
  const П = копия(G); ход(П, 'игра:кости:живая', итог('плохо'));
  assert.equal(П.сцена.игра.стадия, 'ответ');
  const Н = копия(G); ход(Н, 'игра:кости:живая', итог('нормально'));
  assert.equal(Н.сцена.игра.стадия, 'ничья');
  живойХод(Н, 'игра:кости:живая', 'кости');
  ход(Н, 'игра:кости:живая', итог('отлично'));
  assert.equal(Н.сцена.игра.стадия, 'вопрос', 'ничья переиграна живой партией');
  assert.equal(Н.сцена.игра.кон, 2);
  проверено.push('кости');
}

