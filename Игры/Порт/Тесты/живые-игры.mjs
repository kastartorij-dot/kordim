// Живые мини-игры в игре (с 03.11 вместо выбора хода). node Игры/Порт/Тесты/живые-игры.mjs
// Все семь занятий дают один ход «живая» (экран открывает Движок/песочница/<игра>.js поверх сцены), а итог
// { уровень, очки } проходит через те же расчёты, что прежний выбор: деньги, время, расположение, ремесло, отметки.
// Сверка — с тем же состоянием, доведённым спокойным режимом (СЛОЙ.живой = false) до того же уровня.
// Ещё: окно брошено посреди игры — провал; бот без итога — провал; перезагрузка до итога ничего не меняет.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
