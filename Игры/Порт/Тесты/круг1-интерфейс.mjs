// ── PR004-20: у одного собеседника нет кнопок с одинаковым текстом ────────────
function безДублей(S, где) {
  const тексты = действияСцены(S).map(а => а.текст + '|' + (а.подпись ?? ''));
  const дубли = тексты.filter((т, i) => тексты.indexOf(т) !== i);
  assert.deepEqual(дубли, [], `${где}: одинаковые кнопки`);
}
{
  const S = встать(новая(6), 'синий-час', { кто: 'ola', подход: 'мягко' });
  нажать(S, 'дело:slovo_pered_yarnoy:предложить'); нажать(S, 'дело:slovo_pered_yarnoy:принять');
  assert.equal(запись(S, 'slovo_pered_yarnoy').шаг, 'просить');
  // Разговор с Ярной в кабинете: окно диалога собирает дела всех трёх тонов сразу — так и появлялся дубль.
  S.сцена.комната = 'kabinet'; S.сцена.собеседник = 'yarna';
  S.сцена.диалог = { кто: 'yarna', режим: 'хаб', ветка: null, узел: null, откуда: null, лента: [], комната: 'kabinet' };
  безДублей(S, 'Ярна');
  const просьбы = действияСцены(S).filter(а => /^Попросить Ярну отпустить Олу/.test(а.текст));
  assert.ok(просьбы.length <= 1, 'одна кнопка просьбы за Олу');
  // ни у одного собеседника в первом вечере «Синего часа» нет одинаковых надписей
  for (const кто of Object.keys(место('синий-час').модуль.ЛЮДИ)) { S.сцена.собеседник = кто; безДублей(S, кто); }
}

