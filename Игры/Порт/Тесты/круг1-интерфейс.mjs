// ── Громкость: ползунки 0–100, старые выключатели переводятся в числа ─────────
{
  const { громкостиИз, ГРОМКОСТИ } = await import('../Движок/настройки-интерфейса.js');
  assert.deepEqual(громкостиИз({}), ГРОМКОСТИ, 'по умолчанию — как прежнее «средне» и «вкл»');
  assert.deepEqual(громкостиИз({ музыка: 'выкл', громкость: 'громко', звуки: 'выкл' }), { музыка: 0, звуки: 0 });
  assert.deepEqual(громкостиИз({ музыка: 'вкл', громкость: 'тихо', звуки: 'вкл' }), { музыка: 30, звуки: 70 });
  assert.equal(громкостиИз({ музыка: 'вкл', громкость: 'средне' }).музыка, 60);
  assert.equal(громкостиИз({ музыка: 'вкл', громкость: 'громко' }).музыка, 100);
  assert.deepEqual(громкостиИз({ музыка: 45, звуки: 0 }), { музыка: 45, звуки: 0 }, 'новые числа читаются как есть');
  assert.deepEqual(громкостиИз({ музыка: 140, звуки: -3 }), { музыка: 100, звуки: 0 }, 'вне шкалы — к краю');
  globalThis.document ??= { addEventListener() {} }; // звук.js вешает слушатели на документ при загрузке
  const { громкостьМузыки, множительЗвуков } = await import('../Движок/звук.js');
  assert.equal(громкостьМузыки(0), 0, '0 — тишина');
  assert.equal(множительЗвуков(0), 0, '0 — тишина');
  assert.ok(Math.abs(громкостьМузыки(60) - 0.4) < 0.02, '60 ≈ прежнее «средне» (0.4)');
  assert.ok(Math.abs(громкостьМузыки(30) - 0.2) < 0.02 && Math.abs(громкостьМузыки(100) - 0.68) < 1e-9);
  assert.equal(множительЗвуков(70), 1, '70 — прежний уровень звуков');
}

