const новая = (сид = 1, начало = 'семья') => { const S = новоеСостояние(начало, сид); S.герой.кошель = 100; S.мир.день = 4; return S; };
const место = id => МЕСТА.find(м => м.id === id);
function встать(S, id, { кто = null, подход = null } = {}) {
  const м = место(id);
  Object.assign(S.мир, { район: м.район, отрезок: м.когда[0], конецДня: null });
  войти(S, id);
  if (id === 'синий-час') S.сцена.вошёл = true;
  if (кто) { S.сцена.собеседник = кто; S.сцена.диалог = null; S.сцена.реплика = ''; }
  if (подход) S.сцена.подход = подход;
  return S;
}
const кнопка = (S, id) => действияСцены(S).find(а => а.id === id);
const нажать = (S, id) => { const к = кнопка(S, id); assert.ok(к?.можно, `нет доступной кнопки ${id}`); к.выполнить(S); };
const вГород = (S, район, отрезок) => { if (S.сцена) вернутьсяВГород(S); Object.assign(S.мир, { район, отрезок, конецДня: null }); };
const ночь = S => { S.мир.отрезок = 'ночь'; лечьСпать(S, null); const и = S.мир.конецДня; S.мир.конецДня = null; return и; };

// ── PR004-11: цель видна до выбора, пробы не попадают в итог дня ──────────────
{
  const S = новая(1); S.мир.день = 3;
  const п = сводкаЦели(S).предложение;
  assert.equal(п.length, Object.values(ЦЕЛИ).filter(г => г.готова).length, 'все готовые цели предложены');
  for (const г of п) { assert.ok(г.кратко, `${г.id}: суть`); assert.ok(г.шаг && г.шаг.length > 10, `${г.id}: первый шаг виден до выбора`); }
  for (const id of ['угол', 'имя', 'вытащить', 'уехать']) { assert.ok(выбратьЦель(S, id)); assert.ok(снятьЦель(S)); }
  assert.ok(выбратьЦель(S, 'имя'));
  const итог = ночь(S);
  const строки = итог.журнал.filter(с => /^Цель /.test(с));
  assert.deepEqual(строки, ['Цель выбрана: Имя'], 'в итоге дня только окончательный выбор: ' + строки.join(' | '));
  // На следующий день снятая цель — уже решение, а не проба: оно в итоге.
  assert.ok(снятьЦель(S));
  const итог2 = ночь(S);
  assert.deepEqual(итог2.журнал.filter(с => /^Цель /.test(с)), ['Цель снята: Имя. Принятые обещания остаются.']);
}
{ // Выбрал — снял — выбрал снова ту же: в итоге одна строка
  const S = новая(2); S.мир.день = 3;
  выбратьЦель(S, 'угол'); снятьЦель(S); выбратьЦель(S, 'угол');
  assert.deepEqual(ночь(S).журнал.filter(с => /^Цель /.test(с)), ['Цель выбрана: Свой угол']);
}

