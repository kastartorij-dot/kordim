// Шаг 11, пакет 4: линия Тавы настоящими действиями. Запуск: node Игры/Порт/Тесты/шаг11-тава.mjs
// Рыночная история (пропавший ящик и обещание со сроком), вечер у прилавка, её ответ;
// «не сейчас», пока у героя другая связь; без сцены близости (решение автора).
import assert from 'node:assert/strict';
import { новоеСостояние } from '../Движок/состояние.js';
import { связь, решить, расстаться, отметитьВстречу } from '../Движок/связи.js';
import { сценыБлизости } from '../Скрипты/сцены-близости.mjs';
import { есть, нажать, конецДня, вХаб, ветка, рынок, нажатьТекст, естьТекст } from './утилиты/линии.js';

const УЛИКА = 'Спросить у весов про ящик Тавы';
const у_прилавка = (S, отрезок = 'день') => { рынок(S, отрезок, 'еда-рынка'); нажать(S, 'заговорить:tava'); вХаб(S); };

function начало(seed) {
  const S = новоеСостояние('ремесло', seed);
  S.мир.день = 3;
  у_прилавка(S);
  ветка(S, 'дело', 'помочь');
  вХаб(S);
  конецДня(S); у_прилавка(S);
  assert.equal(связь(S, 'tava').этап, 'встречи');
  assert.ok(есть(S, 'ветка:ящик'));
  return S;
}
function найтиЯщик(S) {
  ветка(S, 'ящик', 'найду', 'ясно');
  рынок(S, 'день', 'ворота-рынка');
  assert.ok(естьТекст(S, УЛИКА));
  нажатьТекст(S, УЛИКА);
  assert.ok(!естьТекст(S, УЛИКА), 'улика одна');
  у_прилавка(S);
  ветка(S, 'ящик_найден', 'вечер', 'ясно');
  assert.equal(связь(S, 'tava').обещания[0].статус, 'сдержано');
  assert.equal(S.мир.люди.tava.распол, 2);
}
function вечерУПрилавка(S, вариант) {
  конецДня(S); у_прилавка(S, 'вечер');
  ветка(S, 'ремни', вариант, 'дальше', 'ясно');
  assert.equal(связь(S, 'tava').этап, 'вне-работы');
}

// ── «да»: нашёл ящик, держал ремень, сказал «мне тоже» ──────────────────
{
  const S = начало(51);
  найтиЯщик(S);
  у_прилавка(S);
  assert.ok(!есть(S, 'ветка:ремни'), 'днём прилавок открыт, ремни — после колокола');
  вечерУПрилавка(S, 'держать');
  assert.equal(S.мир.люди.tava.распол, 3);
  конецДня(S); у_прилавка(S, 'вечер');
  ветка(S, 'поворот', 'тоже', 'ясно');
  конецДня(S); у_прилавка(S, 'вечер');
  ветка(S, 'решение');
  assert.equal(связь(S, 'tava').решение.что, 'да');
  нажать(S, 'вариант:решение:принять'); нажать(S, 'вариант:решение:ясно');
  ветка(S, 'после', 'вечер', 'ясно');
  assert.equal(связь(S, 'tava').статус, 'вместе');
  assert.equal(S.сцена.нужнаСцена ?? null, null, 'у Тавы нет сцены близости');
}

// ── деньги за пропажу ничего не дают; торг о ней — стоит доверия ─────────
{
  const S = начало(52);
  ветка(S, 'ящик', 'заплачу');
  assert.equal(S.мир.люди.tava.распол, 1);
  нажать(S, 'вариант:ящик:найду'); нажать(S, 'вариант:ящик:ясно');
  рынок(S, 'день', 'ворота-рынка'); нажатьТекст(S, УЛИКА);
  у_прилавка(S); ветка(S, 'ящик_найден', 'вечер', 'ясно');
  вечерУПрилавка(S, 'откуда'); // доверие без влечения
  конецДня(S); у_прилавка(S, 'вечер');
  ветка(S, 'поворот', 'как_тебе', 'ясно');
  конецДня(S); у_прилавка(S, 'вечер');
  ветка(S, 'решение');
  assert.equal(связь(S, 'tava').решение.что, 'дружба');
  const до = S.мир.люди.tava.распол;
  нажать(S, 'вариант:решение:подарок'); нажать(S, 'вариант:решение:ясно');
  assert.equal(S.мир.люди.tava.распол, до - 1);
  assert.equal(связь(S, 'tava').решение.что, 'дружба', 'подарок ответ не перевешивает');
  ветка(S, 'после', 'прилавок', 'ясно');
}

// ── другая связь: «не сейчас»; герой сам говорит, что свободен, — она отвечает заново ──
{
  const S = начало(53);
  найтиЯщик(S);
  вечерУПрилавка(S, 'держать');
  отметитьВстречу(S, 'freya'); решить(S, 'freya', 'да'); // другая линия уже «вместе»
  конецДня(S); у_прилавка(S, 'вечер');
  ветка(S, 'поворот');
  assert.ok(S.сцена.диалог.лента.some(з => /ты не один/.test(з.т)));
  нажать(S, 'вариант:поворот:тоже'); нажать(S, 'вариант:поворот:ясно');
  конецДня(S); у_прилавка(S, 'вечер');
  ветка(S, 'решение');
  assert.equal(связь(S, 'tava').решение.что, 'позже', 'делить она не готова, хоть числа и высоки');
  нажать(S, 'вариант:решение:принять'); нажать(S, 'вариант:решение:ясно');
  ветка(S, 'после', 'не_свободен', 'ясно');
  расстаться(S, 'freya');
  ветка(S, 'после', 'свободен', 'ясно', 'ясно');
  assert.equal(связь(S, 'tava').решение.что, 'да');
  assert.equal(связь(S, 'tava').статус, 'вместе');
}

// ── нарушенное обещание: ящик не найден в срок — линия стоит ─────────────
{
  const S = начало(54);
  ветка(S, 'ящик', 'найду', 'ясно');
  for (let i = 0; i < 4; i++) конецДня(S);
  assert.equal(связь(S, 'tava').обещания[0].статус, 'нарушено');
  assert.equal(S.мир.люди.tava.распол, 0);
  рынок(S, 'день', 'ворота-рынка');
  assert.ok(!естьТекст(S, УЛИКА), 'после срока улику не ищут');
  у_прилавка(S);
  assert.ok(!есть(S, 'ветка:ящик_найден') && !есть(S, 'ветка:ящик'));
}

assert.ok(!сценыБлизости().some(з => з.сцена.startsWith('tava')), 'сцен близости у Тавы нет');
console.log('шаг 11 (линия Тавы): все проверки пройдены');
