  assert.equal(Р.герой.кошель, кошель);
  assert.equal(имя(Р).просьба, 'отказ');
  assert.equal(Р.мир.люди.gorm.распол, -1);
  // не хватает денег на обмен: кнопка недоступна, ничего не списано
  const Н = новая(9); выбратьЦель(Н, 'имя'); письмоЧестно(Н); Н.герой.кошель = 5;
  const а = вСцене(Н, ...СТОЛ, /Честно назвать конфликт/);
  assert.equal(а.можно, false);
  assert.equal(Н.герой.кошель, 5);
