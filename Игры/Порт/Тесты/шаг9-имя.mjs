const новая = (день = 3, начало = 'семья', кошель = 200) => {
  const S = новоеСостояние(начало, 7);
  S.мир.день = день; S.мир.отрезок = 'утро'; S.герой.кошель = кошель;
  return S;
};
function конецДня(S) {
  S.мир.отрезок = 'ночь'; лечьСпать(S, null);
  const итог = S.мир.конецДня; S.мир.конецДня = null; S.мир.отрезок = 'утро'; return итог;
}
const доДня = (S, день) => { while (S.мир.день < день) конецДня(S); };
const ступень = (S, к) => S.мир.фракции[к];

// Шаг по сценам: войти → перейти в комнату → нажать действие по тексту → выйти.
function вСцене(S, место, комната, шаблон) {
  вернутьсяВГород(S);
  S.мир.район = { 'приемная-нотариуса':'торговый', меняльная: 'торговый', 'контора-дорров': 'доки', 'двор-горма': 'трущобы', часовня: 'маяк' }[место];
  S.мир.отрезок = 'утро';
  войти(S, место);
  let к = 0;
  while (S.сцена.комната !== комната && к++ < 5) {
    const шаг = действияСцены(S).find(а => а.id.startsWith('пойти:') && а.id !== `пойти:${S.сцена.комната}`);
    // ближайший путь: прямой сосед или через общую комнату
    const прямой = действияСцены(S).find(а => а.id === `пойти:${комната}`);
    (прямой ?? шаг).выполнить(S);
  }
  assert.equal(S.сцена.комната, комната, `не дошли до комнаты ${комната}`);
  const а = действияСцены(S).find(х => шаблон.test(х.текст));
  return а ?? null;
}
const жми = (S, место, комната, шаблон) => {
  const а = вСцене(S, место, комната, шаблон);
  assert.ok(а, `нет действия ${шаблон} в ${комната}`);
  assert.equal(а.можно !== false, true, `действие недоступно: ${шаблон}`);
  а.выполнить(S);
  вернутьсяВГород(S);
};
const нет = (S, место, комната, шаблон) => assert.equal(вСцене(S, место, комната, шаблон), null, `не должно быть: ${шаблон}`);
