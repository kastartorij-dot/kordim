  assert.equal(И.мир.люди.rest_dorr.распол, 0, 'Дорр: +1 за честное посредничество, −1 за исполненную просьбу Горма');
  assert.equal(вСцене(И, ...СТОЛ, /Исполнить просьбу Горма/), null, 'второй раз не просят');
