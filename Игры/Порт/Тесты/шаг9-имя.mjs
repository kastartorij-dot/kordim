  // чётный день: просьбы нет
  const Ч = новая(10); выбратьЦель(Ч, 'имя'); имя(Ч).письмо = 'доставлено';
  assert.equal(вСцене(Ч, ...СТОЛ, /Исполнить просьбу Горма/), null, 'в чётный день Горма нет');
  // исполнить: братство +2, против той, кому помог больше (ножи — по письму)
  const И = новая(9); выбратьЦель(И, 'имя'); письмоЧестно(И);
  жми(И, ...СТОЛ, /Исполнить просьбу Горма/);
