// П03: вещи переходят между карманом, одеждой, сундуком, залогом и Сибом без копий.
import assert from 'node:assert/strict';
import { новоеСостояние, мигрировать, ВЕРСИЯ } from '../Движок/состояние.js';
import { положить, слоты, свободных, найтиВещь, использоватьВещь, старениеВещей, намочитьБумаги, износить, естьВещь, потерятьВещь } from '../Движок/вещи.js';
import { купитьВещь, продатьВещь, убратьВСундук, взятьИзСундука, заложитьВещь, выкупитьВещь, просрочитьЗалоги, сдатьНож, вернутьСданное, взятьНапрокат, вернутьПрокат, восстановитьПотерянное, купитьУслугу, доступныеПокупки, описатьВещь } from '../Движок/хозяйство.js';
import { надеть, видОдежды, запачкать, постирать, починить, намокнуть, описаниеОдежды } from '../Движок/одежда.js';
import { потратитьОтрезок } from '../Движок/время.js';
import { условие } from '../Движок/условия.js';
import { доступныеДействия } from '../Движок/действия.js';
import { войти, действияСцены, вернутьсяВГород } from '../Движок/разговор.js';

const создать = () => новоеСостояние('семья', 12);
const итоги = () => ({ причины: [] });

{
  const S = создать();
  assert.equal(ВЕРСИЯ, 12);
  assert.equal(S.герой.одежда.база.тип, 'рабочая');
  assert.equal(S.герой.вид, 1);
  assert.equal(положить(S, 'бинт', 3), true);
  assert.equal(S.герой.при_себе.length, 1);
  assert.equal(S.герой.при_себе[0].количество, 3);
  assert.equal(положить(S, 'бинт'), true);
  assert.equal(S.герой.при_себе.length, 2);
  assert.equal(положить(S, 'груз'), true);
  assert.equal(слоты(S).filter(x => x !== null).length, 4);
  S.герой.тело.цел = 1;
  assert.equal(свободных(S), 3);
  assert.equal(S.герой.при_себе.length, 3, 'рана не удаляет уже взятые вещи');
  assert.equal(слоты(S)[7].блок, true);
}

{
  const S = создать();
  S.версия = 7;
  S.герой.при_себе = ['пирог', 'нож', 'пирог'];
  S.герой.одежда = null;
  мигрировать(S);
  assert.equal(S.версия, ВЕРСИЯ);
  assert.deepEqual(S.герой.при_себе.map(x => x.тип), ['пирог', 'нож', 'пирог']);
  assert.equal(new Set(S.герой.при_себе.map(x => x.uid)).size, 3);
  assert.equal(естьВещь(S, 'нож'), true);
  assert.equal(условие(S, { предмет: 'нож' }), true);
}

{
  const S = создать(); S.версия = 7;
  S.герой.одежда = null; S.герой.вид = 3;
  мигрировать(S);
  assert.equal(S.герой.одежда.база.тип, 'рабочая', 'старый вид не создаёт дорогой костюм');
  assert.equal(S.герой.одежда.база.состояние.опрятность, 3, 'опрятность сохраняется в ткани');
  assert.equal(видОдежды(S), 1);
  assert.match(описаниеОдежды(S).состояние, /вычищена/);
}

{
  const S = создать();
  assert.equal(положить(S, 'пирог'), true);
  const uid = S.герой.при_себе[0].uid;
  S.герой.тело.сыт = 1;
  assert.match(использоватьВещь(S, uid), /сыт \+2/);
  assert.equal(S.герой.тело.сыт, 3);
  assert.equal(найтиВещь(S, uid), null);
  положить(S, 'пирог');
  S.мир.день = 3;
  старениеВещей(S, итоги());
  assert.equal(S.герой.при_себе[0].тип, 'сухарь');
  положить(S, 'письмо');
  assert.equal(намочитьБумаги(S), 1);
  assert.equal(S.герой.при_себе.find(x => x.тип === 'письмо').состояние.промокло, true);
  положить(S, 'отмычка');
  const инструмент = S.герой.при_себе.find(x => x.тип === 'отмычка');
  for (let i = 0; i < 3; i++) износить(S, инструмент.uid);
  assert.equal(инструмент.состояние.сломано, true);
}

{
  const S = создать();
  S.герой.жильё = { id: 'вдова', оплачено_по: 7 };
  положить(S, 'нож');
  const uid = S.герой.при_себе[0].uid;
  assert.equal(убратьВСундук(S, uid, 'вдова'), true);
  assert.equal(S.герой.при_себе.length, 0);
  assert.equal(S.герой.хранилище.вдова[0].uid, uid);
  assert.equal(взятьИзСундука(S, uid, 'вдова'), true);
  assert.equal(S.герой.хранилище.вдова.length, 0);
  assert.equal(S.герой.при_себе[0].uid, uid);
  S.сцена = { место: 'синий-час', сданныеВещи: [] };
  assert.equal(сдатьНож(S), true);
  assert.equal(естьВещь(S, 'нож'), false);
  assert.equal(S.сцена.сданныеВещи[0].uid, uid);
  вернутьСданное(S);
  assert.equal(естьВещь(S, 'нож'), true);
  assert.equal(S.сцена.сданныеВещи.length, 0);
}

{
  const S = создать(); S.мир.район = 'торговый';
  assert.equal(купитьВещь(S, 'кафтан'), true);
  const x = S.герой.при_себе[0];
  assert.equal(надеть(S, x.uid), true);
  assert.equal(S.герой.при_себе[0].тип, 'рабочая');
  assert.equal(видОдежды(S), 1);
  запачкать(S, 2);
  assert.equal(видОдежды(S), 0);
  assert.equal(постирать(S), true);
  assert.equal(видОдежды(S), 1);
  const старый = S.герой.при_себе[0];
  assert.equal(продатьВещь(S, старый.uid), true);
  assert.equal(S.герой.при_себе.length, 0);
}

{
  const S = создать(); S.мир.район = 'трущобы';
  assert.equal(купитьВещь(S, 'купеческая'), false, 'прилавок не продаёт товары других районов');
  assert.equal(купитьВещь(S, 'кафтан'), true);
  const кафтан = S.герой.при_себе[0];
  assert.match(описатьВещь(кафтан), /чужая нашивка/);
  assert.equal(надеть(S, кафтан.uid), true);
  assert.match(описаниеОдежды(S).состояние, /чужая нашивка/);
  S.мир.район = 'торговый';
  assert.equal(купитьУслугу(S, 'снятьМетку'), true);
  assert.equal(S.герой.одежда.база.состояние.метка, undefined);

  S.герой.одежда.верх = { uid: 'верх-тест', тип: 'накидка', состояние: { грязь: 1, рвано: true } };
  assert.equal(постирать(S), true);
  assert.equal(S.герой.одежда.верх.состояние.грязь, 0);
  assert.equal(починить(S), true);
  assert.equal(S.герой.одежда.верх.состояние.рвано, false);
  assert.equal(намокнуть(S), true);
  assert.equal(S.герой.одежда.верх.состояние.сырость, 1);
  const отдых = S.герой.тело.отдых;
  потратитьОтрезок(S);
  assert.equal(S.герой.тело.отдых, отдых - 1, 'мокрый верх утяжеляет дорогу');
}

{
  const S = создать(); S.мир.район = 'торговый'; S.герой.кошель = 300;
  assert.equal(купитьВещь(S, 'купеческая'), true);
  assert.equal(надеть(S, S.герой.при_себе[0].uid), true);
  assert.equal(видОдежды(S), 3);
  const покупка = доступныеПокупки(S).find(x => x.id === 'купить:рыба');
  assert.equal(покупка.цена, 3);
  const до = S.герой.кошель;
  assert.equal(купитьВещь(S, 'рыба'), true);
  assert.equal(S.герой.кошель, до - 3, 'показанная надбавка совпадает со списанием');
  S.герой.тело.сыт = 1;
  const еда = доступныеДействия(S).find(x => x.id === 'еда:хлеб');
  assert.equal(еда.цена, 2);
  const передЕдой = S.герой.кошель;
  еда.выполнить(S);
  assert.equal(S.герой.кошель, передЕдой - 2);
}

{
  const S = создать(); S.мир.район = 'торговый'; S.мир.отрезок = 'вечер';
  положить(S, 'нож');
  const uid = S.герой.при_себе[0].uid;
  войти(S, 'синий-час');
  const сдать = действияСцены(S).find(x => x.текст.startsWith('Выложить нож'));
  assert.ok(сдать?.можно);
  сдать.выполнить(S);
  assert.equal(естьВещь(S, 'нож'), false);
  assert.equal(S.сцена.сданныеВещи[0].uid, uid);
  вернутьсяВГород(S);
  assert.equal(найтиВещь(S, uid)?.тип, 'нож');
}

{
  const S = создать(); S.мир.район = 'торговый';
  положить(S, 'письмо');
  const uid = S.герой.при_себе[0].uid;
  assert.equal(потерятьВещь(S, uid, 'утрата'), true);
  assert.equal(естьВещь(S, 'письмо'), false);
  assert.equal(восстановитьПотерянное(S, uid), true);
  assert.equal(естьВещь(S, 'письмо'), true);
  assert.equal(S.герой.при_себе[0].состояние.копия, true);
}

{
  const S = создать(); S.мир.район = 'торговый';
  положить(S, 'нож');
  const uid = S.герой.при_себе[0].uid;
  assert.equal(заложитьВещь(S, uid), true);
  assert.equal(S.герой.при_себе.length, 0);
  assert.equal(S.герой.залог[0].вещь.uid, uid);
  assert.equal(выкупитьВещь(S, uid), true);
  assert.equal(S.герой.при_себе[0].uid, uid);
  заложитьВещь(S, uid);
  S.мир.день = 9;
  просрочитьЗалоги(S, итоги());
  assert.equal(S.герой.залог.length, 0);
  assert.equal(выкупитьВещь(S, uid), false);
}

{
  const S = создать(); S.мир.район = 'торговый';
  assert.equal(взятьНапрокат(S, 'плащ'), true);
  const x = S.герой.при_себе[0];
  assert.equal(продатьВещь(S, x.uid), false);
  assert.equal(вернутьПрокат(S, x.uid), true);
  assert.equal(S.герой.при_себе.length, 0);
  assert.ok(доступныеДействия(S).some(x => x.id === 'прокат:плащ'));
}

console.log('Шаг 3: экземпляры, миграция, стопки, крупный груз, травма, порча, сундук, нож у Сиба, одежда, залог и прокат прошли.');
