// Круг 3: стенд мини-игр (Движок/стенд-игр.js). node Игры/Порт/Тесты/стенд-игр.mjs
// Каждая игра списка стартует с любым заданием и любой ступенью ремесла, доигрывается ботом до исхода,
// исход называет изменения по-русски; стенд не трогает localStorage и ставит звук на ноль.
import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
// Любое обращение к хранилищу игры — ошибка: стенд живёт только в памяти.
Object.defineProperty(globalThis, 'localStorage', { configurable: true, get() { throw new Error('стенд полез в localStorage'); } });
const { игры, откуда, ЗАПАСНОЙ_СПИСОК, варианты, ступени, ремесло, запустить, идёт, снимок, исход, изолироватьХранилище, КЛЮЧ_НАСТРОЕК } = await import('../Движок/стенд-игр.js');
const { доступныеДействия } = await import('../Движок/действия.js');
const { действияСцены } = await import('../Движок/разговор.js');
// Стенд — страница текстовых игр (стенд-игр.html): там СЛОЙ.живой выключен по адресу страницы.
(await import('../Движок/уровень.js')).СЛОЙ.живой = false;

// ── список ──
const список = игры();
assert.ok(список.length >= 4, 'в списке есть минимум четыре готовые игры: ' + откуда());
for (const и of список) {
  for (const п of ['id', 'имя', 'где', 'описание']) assert.ok(typeof и[п] === 'string' && и[п].trim(), `${и.id}: ${п}`);
  assert.equal(typeof и.начать, 'function', и.id + ': начать');
  assert.ok(!/секунд|гильди/i.test(JSON.stringify([и.имя, и.где, и.описание, варианты(и)])), и.id + ': без секунд и гильдии');
}
assert.equal(new Set(список.map(и => и.id)).size, список.length, 'id не повторяются');
for (const id of ['вес', 'счёт', 'торг', 'кости']) assert.ok(ЗАПАСНОЙ_СПИСОК.some(и => и.id === id), 'запасной список: ' + id);

// ── бот: до конца игры ──
const ПОРЯДОК = [/:записать$/, /:вариант:/, /:купить$/, /:довод:/, /:оставить$/, /:вопрос:/, /:ответ:/, /:ещё$/, /:уйти$/];
function ход(S) {
  const А = S.мир.смена ? доступныеДействия(S).filter(а => а.группа === 'смена') : действияСцены(S);
  const можно = А.filter(а => а.можно !== false);
  for (const р of ПОРЯДОК) { const а = можно.find(x => р.test(x.id ?? '')); if (а) { а.выполнить(S); return; } }
  assert.ok(можно.length, 'нет доступных ходов: ' + А.map(а => подписьХода(а)).join(', '));
  можно[0].выполнить(S);
}
const подписьХода = а => `${а.id}${а.можно === false ? '(нельзя)' : ''}`;
function доиграть(и, S) {
  const до = снимок(S);
  for (let i = 0; i < 40 && идёт(и, S); i++) ход(S);
  assert.ok(!идёт(и, S), `${и.id}: игра не кончилась за 40 ходов`);
  return исход(до, снимок(S));
}

// ── каждая игра, каждый вариант, каждая ступень: и активный список, и запасной (он должен оставаться рабочим) ──
let партий = 0;
for (const и of new Set([...список, ...ЗАПАСНОЙ_СПИСОК])) {
  for (const в of вариантыИлиПусто(и)) {
    for (const ст of ступени(и).length ? ступени(и) : [undefined]) {
      const S = запустить(и, { вариант: в?.id, ступень: ст, сид: 12 });
      assert.ok(идёт(и, S), `${и.id} ${в?.id} ${ст}: стартует`);
      assert.ok(!S.мир.конецДня, и.id + ': старт не заканчивает день');
      if (ст && ремесло(и, в?.id)) {
        const р = S.герой.ремёсла?.[ремесло(и, в?.id)];
        assert.equal(р?.ступень ?? 'нет', ст, `${и.id} ${в?.id}: ступень ${ст} выставлена`);
      }
      const строки = доиграть(и, S);
      for (const р of строки) assert.ok(р.текст && ['плюс', 'минус', 'ноль'].includes(р.знак), и.id + ': строка исхода');
      партий++;
    }
  }
}
function вариантыИлиПусто(и) { return варианты(и).length ? варианты(и) : [undefined]; }
assert.ok(партий >= 60, 'сыграно партий: ' + партий);

// ── ступень и задание действительно влияют ──
{
  const вес = ЗАПАСНОЙ_СПИСОК.find(и => и.id === 'вес');
  const а = запустить(вес, { вариант: 'w05-dve-bochki', ступень: 'нет', сид: 1 });
  assert.equal(а.мир.смена.задача.задание, 'w05-dve-bochki', 'выбранное задание');
  assert.equal(а.мир.смена.задача.совет.вид, null, 'без ремесла совета нет');
  assert.equal(запустить(вес, { вариант: 'w05-dve-bochki', ступень: 'умеешь', сид: 1 }).мир.смена.задача.совет.вид, 'слово');
  assert.equal(запустить(вес, { вариант: 'w05-dve-bochki', ступень: 'набил руку', сид: 1 }).мир.смена.задача.совет.вид, 'отсев');
  const счёт = ЗАПАСНОЙ_СПИСОК.find(и => и.id === 'счёт');
  assert.deepEqual(ступени(счёт), ['умеешь', 'набил руку'], 'чтецу без грамоты задач не дают — «нет» не предлагается');
  const торг = ЗАПАСНОЙ_СПИСОК.find(и => и.id === 'торг');
  assert.equal(ремесло(торг, 'кафтан:день'), 'наколки');
  assert.equal(ремесло(торг, 'плащ:вечер'), 'грузчик');
  assert.ok(запустить(торг, { вариант: 'плащ:вечер', сид: 1 }).сцена.игра.товар === 'плащ');
}

// ── исход: торг оставляет вещь и минус в кошеле; таверна — плюс или минус ──
{
  const торг = ЗАПАСНОЙ_СПИСОК.find(и => и.id === 'торг');
  const S = запустить(торг, { вариант: 'кафтан:вечер', ступень: 'умеешь', сид: 5 });
  const до = снимок(S);
  действияСцены(S).find(а => а.id === 'игра:торг:купить').выполнить(S);
  const строки = исход(до, снимок(S));
  assert.ok(строки.some(р => р.вид === 'деньги' && р.знак === 'минус'), 'покупка: деньги ушли — ' + JSON.stringify(строки));
  assert.ok(строки.some(р => р.вид === 'вещь' && /кафтан/i.test(р.текст)), 'покупка: вещь получена');
  assert.deepEqual(исход(снимок(S), снимок(S)), [], 'без изменений — пустой исход');
}

// ── изоляция: хранилище в памяти, звук ноль, настройки игрока читаются, но не пишутся ──
{
  const записано = [];
  const настоящее = { getItem: к => (к === КЛЮЧ_НАСТРОЕК ? JSON.stringify({ размер: 'крупный', музыка: 100, звуки: 100 }) : null), setItem: (к, з) => записано.push([к, з]), removeItem: к => записано.push([к]) };
  const окно = {}; Object.defineProperty(окно, 'localStorage', { configurable: true, value: настоящее });
  const { хранилище, звук } = изолироватьХранилище(окно);
  assert.notEqual(окно.localStorage, настоящее, 'localStorage подменён');
  const н = JSON.parse(окно.localStorage.getItem(КЛЮЧ_НАСТРОЕК));
  assert.equal(н.музыка, 0); assert.equal(н.звуки, 0); assert.equal(н.размер, 'крупный', 'размер текста игрока сохранён');
  окно.localStorage.setItem(КЛЮЧ_НАСТРОЕК, JSON.stringify({ звуки: 30, музыка: 90 }));
  окно.localStorage.setItem('порт-теней-авто', 'x');
  assert.equal(JSON.parse(хранилище.getItem(КЛЮЧ_НАСТРОЕК)).музыка, 0, 'музыка остаётся нулём');
  assert.equal(хранилище.getItem('порт-теней-авто'), 'x', 'прочее — в памяти');
  звук(true); assert.equal(JSON.parse(хранилище.getItem(КЛЮЧ_НАСТРОЕК)).звуки, 70, 'звук можно включить только в стенде');
  звук(false); assert.equal(JSON.parse(хранилище.getItem(КЛЮЧ_НАСТРОЕК)).звуки, 0);
  assert.deepEqual(записано, [], 'в настоящее хранилище игрока ничего не писали');
}

// ── файлы страницы на месте и связаны ──
{
  const html = readFileSync(new URL('../стенд-игр.html', import.meta.url), 'utf8');
  assert.ok(html.includes('Стенд для автора, не часть игры'), 'подпись');
  assert.ok(/href="\.\/index\.html"[^>]*>\s*←\s*в игру/.test(html), 'ссылка в игру');
  assert.ok(html.includes('Движок/интерфейс.css') && html.includes('Движок/стенд-игр.css') && html.includes('Движок/стенд-экран.js'));
  assert.ok(!/localStorage/.test(readFileSync(new URL('../Движок/стенд-экран.js', import.meta.url), 'utf8').replace(/\/\/.*$/gm, '')), 'страница стенда сама в localStorage не лезет');
  for (const ф of ['Движок/стенд-игр.css', 'Движок/стенд-экран.js', 'Движок/стенд-игр.js']) assert.ok(existsSync(new URL('../' + ф, import.meta.url)), ф);
  const публикация = readFileSync(new URL('../Скрипты/publish.mjs', import.meta.url), 'utf8');
  assert.ok(публикация.includes('стенд-игр.html'), 'publish.mjs копирует стенд');
}
console.log(`ок: стенд-игр — ${список.length} игр, партий ${партий}, список: ${откуда()}`);
