// ── шторм, день 16: галерея закрыта, помощь с заслонкой даёт Ножей и репутацию
{
  const S = наМаяке(16, 'вечер');
  нажать(S, 'Подняться по лестнице'); пойти(S, 'фонарная');
  assert.equal(действияСцены(S).some(а => а.id === 'пойти:галерея'), false, 'в шторм на галерее нельзя');
  const ножи = S.мир.очки.ножи, реп = S.мир.очки.репутация, отдых = S.герой.тело.отдых;
  нажать(S, 'Помочь закрепить заслонку');
  assert.equal(S.мир.очки.ножи, ножи + 1);
  assert.equal(S.мир.очки.репутация, реп + 1);
  assert.equal(S.герой.тело.отдых, отдых - 1);
  assert.equal(кнопка(S, 'Помочь закрепить заслонку'), undefined);
  const другой = наМаяке(15, 'вечер');
  нажать(другой, 'Подняться по лестнице'); пойти(другой, 'фонарная');
  assert.equal(кнопка(другой, 'Помочь закрепить заслонку'), undefined, 'шторм только в день 16');
  assert.equal(действияСцены(другой).some(а => а.id === 'пойти:галерея'), true);
}

// ── чайник: два раза «почти», на третий — знак доверия
{
  const S = наМаяке(2, 'день');
  нажать(S, 'Подняться по лестнице'); пойти(S, 'фонарная');
  S.герой.тело.тепло = 1;
  нажать(S, 'Выпить с Ифо чаю');
  assert.match(ответ(S), /почти/);
  assert.equal(S.герой.тело.тепло, 2);
  assert.equal(кнопка(S, 'Выпить с Ифо чаю'), undefined, 'одна кружка в день');
  for (const [день, ожидание] of [[3, /почти/], [4, /наконец закипает/], [5, /кипит как положено/]]) {
    вернутьсяВГород(S);
    наМаяке(день, 'день', 100, S);
    нажать(S, 'Подняться по лестнице'); пойти(S, 'фонарная');
    if (день === 4) assert.equal(S.мир.люди.ifo?.распол ?? 0, 0);
    нажать(S, 'Выпить с Ифо чаю');
    assert.match(ответ(S), ожидание, `день ${день}`);
    if (день === 4) { assert.ok(м(S).флаги.includes('чай_готов')); assert.equal(S.мир.люди.ifo.распол, 1); }
  }
  assert.equal(м(S).счётчики.чай, 4);
}

