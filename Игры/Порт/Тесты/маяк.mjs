import { хаб, отойти as закрытьБеседу } from './утилиты/диалог.js';
// Шаг 8, Маяк: три зоны слышимости, ветер на галерее, режимы огня, прогноз Гвоздя, код, шторм, чай.
// node Порт/тест/маяк.mjs
import assert from 'node:assert/strict';
import { новоеСостояние } from '../Движок/состояние.js';
import { войти, действияСцены, вернутьсяВГород, видСцены } from '../Движок/разговор.js';
import { датьТему, верностьТемы } from '../Движок/знание.js';
import { режимНочи } from '../Данные/огонь.js';

const кнопка = (S, текст) => действияСцены(S).find(а => а.текст === текст || а.текст.startsWith(текст));
const нажать = (S, текст) => { const а = кнопка(S, текст); assert.ok(а, `нет кнопки «${текст}»`); assert.equal(а.можно, true, `«${текст}» недоступна: ${а.почему}`); а.выполнить(S); };
const пойти = (S, к) => { const а = действияСцены(S).find(а => а.id === `пойти:${к}`); assert.ok(а, `нет перехода в ${к}`); а.выполнить(S); };
const осмотреть = (S, д) => действияСцены(S).find(а => а.id === `рассмотреть:${д}`).выполнить(S);
const говорить = (S, кто) => {действияСцены(S).find(а => а.id === `заговорить:${кто}`).выполнить(S); хаб(S);};
const спросить = (S, тид) => { const id=тид==='mayak_ogon'?'огонь':'сведения_'+тид; const а=действияСцены(S).find(а=>а.id==='ветка:'+id);assert.ok(а?.можно,'нет ветки '+id);а.выполнить(S); };
const отойти = S => закрытьБеседу(S);
const ответ = S => видСцены(S).диалог?.лента.map(l=>l.т??'').join('\n') ?? S.сцена.реплика;
const тень = S => S.мир.тень ?? 0;
const м = S => S.мир.места.маяк;

function наМаяке(день = 3, отрезок = 'вечер', кошель = 100, S0 = null) {
  const S = S0 ?? новоеСостояние('семья', 7);
  S.мир.район = 'маяк'; S.мир.день = день; S.мир.отрезок = отрезок; S.герой.кошель = кошель;
  войти(S, 'маяк');
  return S;
}
const вГалерею = S => { нажать(S, 'Подняться по лестнице'); пойти(S, 'фонарная'); пойти(S, 'галерея'); };

// ── дорога наверх: подножие → лестница → фонарная → галерея; подъём стоит отдыха, если он уже ниже трёх
{
  const S = наМаяке();
  assert.equal(действияСцены(S).some(а => а.id.startsWith('заговорить:')), false, 'внизу никого нет');
  assert.equal(действияСцены(S).some(а => а.id.startsWith('пойти:')), false, 'наверх только по лестнице');
  нажать(S, 'Подняться по лестнице');
  assert.equal(S.сцена.комната, 'лестница');
  assert.equal(S.герой.тело.отдых, 3, 'отдых 3: ступени не в счёт');
  assert.ok(действияСцены(S).some(а => а.id === 'заговорить:gvozd'));
  пойти(S, 'фонарная');
  assert.ok(действияСцены(S).some(а => а.id === 'заговорить:ifo'));
  пойти(S, 'галерея');
  assert.ok(действияСцены(S).some(а => а.id === 'заговорить:ifo'), 'смотритель выходит на галерею');
  пойти(S, 'фонарная'); пойти(S, 'лестница'); пойти(S, 'подножие-маяка');
  assert.equal(S.сцена.комната, 'подножие-маяка');
}
for (const [было, стало] of [[2, 1], [1, 0]]) {
  const S = наМаяке(3, 'вечер', 100);
  S.герой.тело.отдых = было;
  нажать(S, 'Подняться по лестнице');
  assert.equal(S.герой.тело.отдых, стало, `отдых ${было} → ${стало}`);
  assert.ok(S.мир.журналДня.some(с => с.includes('Сто сорок семь ступеней')));
}

// ── уши: фонарная и лестница слышат, галерея нет
function утекло(S, кто, тема) {
  датьТему(S, тема);
  говорить(S, кто);
  const до = тень(S);
  спросить(S, тема);
  return тень(S) - до;
}
{
  const S = наМаяке();
  нажать(S, 'Подняться по лестнице');
  assert.equal(утекло(S, 'gvozd', 'kladbishche_kitov'), 1, 'на лестнице эхо: Гвоздь слышит и несёт Ножам');
  assert.match(S.мир.ушло.kladbishche_kitov, /ножи/);
  assert.ok(S.мир.журналДня.some(с => с.includes('Ифо отчитывается Ножам')));
}
{
  const S = наМаяке();
  нажать(S, 'Подняться по лестнице'); пойти(S, 'фонарная');
  assert.equal(утекло(S, 'ifo', 'mayak_ogon'), 1, 'в фонарной слышит смотритель');
  assert.equal(S.мир.ушло.mayak_ogon, 'ножи');
}
{
  // дешёвая тема не утекает и в фонарной
  const S = наМаяке();
  нажать(S, 'Подняться по лестнице'); пойти(S, 'фонарная');
  assert.equal(утекло(S, 'ifo', 'smotritel_ne_slushaet'), 0, 'ценность 1 — не утечка');
}
{
  // галерея: ветер, тема не утекает, слова теряются, пока не придвинешься
  const S = наМаяке();
  вГалерею(S);
  датьТему(S, 'mayak_ogon');
  говорить(S, 'ifo');
  assert.ok(кнопка(S, 'Придвинуться, чтобы расслышать'));
  спросить(S, 'mayak_ogon');
  assert.match(ответ(S), /Ветер/, 'пока не придвинулся, ответ не прозвучал');
  assert.match(ответ(S), /Ветер уносит слова/);
  assert.doesNotMatch(ответ(S), /по просьбе Ножей\. Почему — спроси у них\./, 'полной реплики нет');
  assert.equal(S.мир.люди.ifo.спрошено.includes('mayak_ogon:прямо'), false, 'вопрос не засчитан');
  assert.equal(S.сцена.ходы, 0, 'ход не потрачен');
  нажать(S, 'Придвинуться, чтобы расслышать');
  assert.equal(S.сцена.ходы, 1, 'придвинуться стоит ход');
  assert.equal(кнопка(S, 'Придвинуться, чтобы расслышать'), undefined);
  спросить(S, 'mayak_ogon');
  assert.match(ответ(S), /Режим меняют по просьбе Ножей\. Почему — спроси у них\./);
  assert.equal(тень(S), 0, 'на галерее никто не слышит');
  assert.equal(S.мир.ушло?.mayak_ogon, undefined);
  // отошёл — ветер снова уносит слова
  отойти(S);
  говорить(S, 'ifo');
  assert.ok(кнопка(S, 'Придвинуться, чтобы расслышать'), 'после разговора придвигаться нужно снова');
}

