// ── прогноз Гвоздя на завтра: 3 гр., в четверти случаев он путает; сверка на следующий вечер
function сидПрогноза(верно) {
  for (let с = 1; с < 500; с++) {
    const S = наМаяке(3, 'вечер'); S.мир.сид = с;
    нажать(S, 'Подняться по лестнице');
    нажать(S, 'Купить у Гвоздя режим на завтра');
    if ((м(S).память.прогноз[4] === режимНочи(4)) === верно) return с;
  }
  assert.fail('нет зерна');
}
for (const верно of [true, false]) {
  const S = наМаяке(3, 'вечер'); S.мир.сид = сидПрогноза(верно);
  нажать(S, 'Подняться по лестнице');
  assert.equal(кнопка(S, 'Купить у Гвоздя режим на завтра').подпись, '3 гр. · иногда он путает · 1 ход');
  нажать(S, 'Купить у Гвоздя режим на завтра');
  assert.equal(S.герой.кошель, 97);
  assert.match(ответ(S), /Завтра ночью/);
  assert.equal(кнопка(S, 'Купить у Гвоздя режим на завтра'), undefined, 'раз в день');
  вернутьсяВГород(S);
  наМаяке(4, 'вечер', 97, S);
  вГалерею(S);
  нажать(S, 'Записать, как горит огонь');
  assert.match(ответ(S), верно ? /не ошибся/ : /Он ошибся/);
  assert.equal(м(S).память.сверка.at(-1).верно, верно);
}
{
  const S = наМаяке(3, 'вечер', 2);
  нажать(S, 'Подняться по лестнице');
  assert.equal(кнопка(S, 'Купить у Гвоздя режим на завтра').можно, false, 'нет 3 гр.');
}

