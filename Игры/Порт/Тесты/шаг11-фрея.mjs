// Шаг 11, пакет 2: линия Фреи настоящими действиями. Запуск: node Игры/Порт/Тесты/шаг11-фрея.mjs
// Три партии с разными поступками дают разные её ответы: «да», «дружба» и спор с ответом.
// Плюс встреча вне работы, жизнь после решения, отсутствие и примирение, отклик на исход «Вытащить», итог сезона.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { новоеСостояние } from '../Движок/состояние.js';
import { войти, действияСцены, вернутьсяВГород, догрузитьСцену } from '../Движок/разговор.js';
import { лечьСпать } from '../Движок/время.js';
import { связь, итогСвязей } from '../Движок/связи.js';
import { итогСезона } from '../Движок/цели.js';
import { ПРАВИЛА } from '../Данные/связи.js';

const ids = S => действияСцены(S).map(а => а.id);
const нажать = (S, id) => {
  const а = действияСцены(S).find(х => (id instanceof RegExp ? id.test(х.id) : х.id === id));
  assert.ok(а, `нет действия ${id} (${S.сцена?.место}/${S.сцена?.комната}): ${ids(S).join(', ')}`);
  assert.notEqual(а.можно, false, `${id}: ${а.почему}`);
  а.выполнить(S);
};
const есть = (S, id) => ids(S).includes(id);
function конецДня(S) {
  if (S.сцена) вернутьсяВГород(S);
  S.мир.отрезок = 'ночь'; лечьСпать(S, null); S.мир.конецДня = null; S.мир.отрезок = 'утро';
}
const доДня = (S, д) => { while (S.мир.день < д) конецДня(S); };
function вХаб(S) {
  for (let i = 0; i < 5 && S.сцена.диалог?.режим !== 'хаб'; i++) {
    const а = действияСцены(S).find(х => х.id.startsWith('вариант:') && !/уйти|уйду|позже/.test(х.id + х.текст));
    assert.ok(а, 'нет перехода в хаб'); а.выполнить(S);
  }
}
// Вечер: до встречи вне работы — только оплаченная комната (вход 20 + 60), после — площадка у окна без оплаты.
function вечер(S, куда = 'к ней') {
  if (S.сцена) вернутьсяВГород(S);
  S.герой.кошель = Math.max(S.герой.кошель, 200);
  S.герой.тело = { сыт: 3, отдых: 3, тепло: 3, цел: 3 };
  S.мир.район = 'доки'; S.мир.отрезок = 'вечер';
  войти(S, 'синий-час');
  нажать(S, 'вариант:вход:платить'); нажать(S, 'вариант:вход:войти');
  for (const к of ['zal', 'lestnica']) нажать(S, `пойти:${к}`);
  if (куда !== 'комната' && есть(S, 'пойти:ploshchadka')) нажать(S, 'пойти:ploshchadka'); else нажать(S, 'подняться:komnata_frei');
  нажать(S, 'заговорить:freya'); вХаб(S);
}
const ветка = (S, в, ...варианты) => { нажать(S, `ветка:${в}`); for (const x of варианты) нажать(S, `вариант:${в}:${x}`); };
function рынок(S) {
  if (S.сцена) вернутьсяВГород(S);
  S.мир.район = 'торговый'; S.мир.отрезок = 'день';
  войти(S, 'рынок');
  for (let i = 0; i < 3 && S.сцена.диалог; i++) вХаб(S);
  if (S.сцена.комната !== 'ветошь-рынка') нажать(S, 'пойти:ветошь-рынка');
}
const читать = id => readFile(new URL(`../Сцены/Близость/${id}.md`, import.meta.url), 'utf8');

// Общее начало: знакомство и Сиб (доверие 2) в день 3, второй вечер в день 4 — этап «встречи».
function начало(seed) {
  const S = новоеСостояние('семья', seed);
  S.мир.день = 3;
  вечер(S);
  ветка(S, 'знакомство', 'молчать', 'ясно');
  ветка(S, 'сиб', 'в_ответ', 'слово', 'ясно');
  assert.equal(S.мир.люди.freya.распол, 2);
  конецДня(S); вечер(S);
  assert.equal(связь(S, 'freya').этап, 'встречи');
  assert.ok(есть(S, 'ветка:день'), 'после встреч Фрея говорит о дне');
  return S;
}

// ── партия А: цена дня, потом приглашение; своя нитка; «я тоже» → её «да» ──
{
  const S = начало(31);
  ветка(S, 'день', 'цена');
  assert.equal(S.мир.люди.freya.распол, 2, 'вопрос о цене дня не даёт и не отнимает доверия');
  нажать(S, 'вариант:день:прости');
  assert.equal(связь(S, 'freya').обещания[0].статус, 'дано');
  нажать(S, 'вариант:день:ясно');
  assert.ok(!есть(S, 'ветка:поворот'), 'поворот — только после встречи вне работы');
  конецДня(S); рынок(S);
  assert.ok(есть(S, 'заговорить:freya'), 'Фрея днём в ряду ветоши');
  нажать(S, 'заговорить:freya'); вХаб(S);
  ветка(S, 'нитки', 'своя', 'дальше', 'ясно');
  const с = связь(S, 'freya');
  assert.equal(с.этап, 'вне-работы');
  assert.equal(с.обещания[0].статус, 'сдержано');
  assert.equal(с.влечение, 1);
  assert.equal(S.мир.люди.freya.распол, 3);
  конецДня(S); рынок(S);
  assert.ok(!есть(S, 'заговорить:freya'), 'на следующий день её на рынке нет');
  вечер(S);
  assert.equal(S.сцена.комната, 'ploshchadka', 'после встречи днём Фрея выходит на площадку без оплаченной комнаты');

  вечер(S);
  ветка(S, 'поворот', 'тоже', 'ясно');
  assert.equal(связь(S, 'freya').этап, 'поворот');
  assert.ok(!есть(S, 'ветка:решение'), 'ответ — не в тот же день');
  конецДня(S); вечер(S);
  ветка(S, 'решение');
  assert.equal(связь(S, 'freya').решение.что, 'да');
  нажать(S, 'вариант:решение:да_принять'); нажать(S, 'вариант:решение:ясно');
  assert.equal(связь(S, 'freya').статус, 'вместе');

  ветка(S, 'после');
  assert.equal(связь(S, 'freya').этап, 'после');
  const доступ = связь(S, 'freya').доступ, кошель = S.герой.кошель;
  нажать(S, 'вариант:после:остаться');
  assert.equal(S.сцена.нужнаСцена, 'freya_личная');
  assert.equal(S.герой.кошель, кошель, 'личная сцена не оплачивается героем');
  assert.equal(связь(S, 'freya').доступ, доступ, 'личная сцена — не доступ');
  await догрузитьСцену(S, читать);
  assert.match(S.сцена.реплика, /Это не работа/);
  assert.doesNotMatch(S.сцена.реплика, /ЗАГОТОВКА/, 'пометку автора игрок не видит');

  // Отсутствие: пауза, затем примирение по её доверию.
  for (let i = 0; i <= ПРАВИЛА.отсутствие.пауза; i++) конецДня(S);
  assert.equal(связь(S, 'freya').статус, 'пауза');
  вечер(S);
  ветка(S, 'после', 'вернуться', 'ясно');
  assert.equal(связь(S, 'freya').статус, 'вместе');

  // Итог сезона называет линию по её состоянию: сразу после примирения — вместе;
  // если до конца сезона герой больше не пришёл — отсутствие честно заканчивает связь.
  assert.ok(итогСвязей(S).some(с => /Фрея: вы вместе/.test(с)));
  доДня(S, 30); конецДня(S);
  assert.ok(итогСезона(S).строки.some(с => /Фрея: вы расстались/.test(с)), итогСезона(S).строки.join(' | '));
}

// ── партия Б: хотел заплатить на рынке и не сказал «я тоже» → «дружба»; спор её не меняет ──
{
  const S = начало(32);
  ветка(S, 'день', 'прийти', 'ясно');
  конецДня(S); рынок(S);
  нажать(S, 'заговорить:freya'); вХаб(S);
  ветка(S, 'нитки', 'заплатить');
  assert.equal(S.мир.люди.freya.распол, 2, 'предложение денег вне работы не даёт доверия');
  нажать(S, 'вариант:нитки:корзина'); нажать(S, 'вариант:нитки:дальше'); нажать(S, 'вариант:нитки:ясно');
  assert.equal(S.мир.люди.freya.распол, 3, 'доверие даёт поступок, а не деньги');
  assert.equal(связь(S, 'freya').влечение, 0);
  конецДня(S); вечер(S);
  ветка(S, 'поворот', 'как_тебе', 'ясно');
  конецДня(S); вечер(S);
  ветка(S, 'решение');
  assert.equal(связь(S, 'freya').решение.что, 'дружба', 'без влечения ответ — дружба, сколько бы ни было доверия');
  const до = S.мир.люди.freya.распол;
  нажать(S, 'вариант:решение:спорить'); нажать(S, 'вариант:решение:ясно');
  assert.equal(связь(S, 'freya').решение.что, 'дружба', 'спор не меняет её ответ');
  assert.equal(S.мир.люди.freya.распол, до - 1);
  ветка(S, 'после');
  assert.ok(!есть(S, 'вариант:после:остаться'), 'дружба без близости');
  нажать(S, 'вариант:после:окно'); нажать(S, 'вариант:после:ясно');
}

// ── партия Г: только деньги — линия не идёт дальше, как бы часто ни оплачивалась комната ──
{
  const S = начало(35);
  ветка(S, 'день', 'прийти', 'ясно');
  конецДня(S); рынок(S);
  нажать(S, 'заговорить:freya'); вХаб(S);
  ветка(S, 'нитки', 'заплатить', 'дальше', 'ясно');
  for (let i = 0; i < 3; i++) {
    конецДня(S); вечер(S, 'комната'); нажать(S, 'остаться');
    assert.ok(['freya_1', 'freya_2'].includes(S.сцена.нужнаСцена), 'оплаченная сцена, не личная');
  }
  assert.equal(связь(S, 'freya').доступ, 3);
  assert.equal(S.мир.люди.freya.распол, 2, 'три оплаченных вечера не дали доверия');
  assert.equal(связь(S, 'freya').влечение, 0);
  assert.ok(!есть(S, 'ветка:поворот'), 'без доверия 3 поворота нет');
}

// ── партия В: нарушенное обещание прийти днём ──
{
  const S = начало(33);
  ветка(S, 'день', 'прийти', 'ясно');
  for (let i = 0; i < 4; i++) конецДня(S);
  const с = связь(S, 'freya');
  assert.equal(с.обещания[0].статус, 'нарушено');
  assert.equal(S.мир.люди.freya.распол, 1, 'нарушенное слово стоит доверия');
  assert.equal(с.этап, 'встречи', 'без встречи вне работы линия не идёт дальше');
  рынок(S);
  assert.ok(!есть(S, 'заговорить:freya'));
}

// ── исход «Вытащить» с рычагом рвёт связь ──
{
  const S = начало(34);
  S.мир.связи.freya.статус = 'вместе'; S.мир.связи.freya.решение = { что: 'да', день: 4 };
  S.мир.вытащить = { ...(S.мир.вытащить ?? {}), решение: { исход: 'разрушено', день: 4, выслушал: true } };
  вечер(S);
  ветка(S, 'после_выбора', 'ясно');
  assert.equal(связь(S, 'freya').статус, 'расстались');
}

