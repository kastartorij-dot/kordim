// Круг 2: хвосты текстов, найденные в круге 1. node Игры/Порт/Тесты/хвосты-круга1.mjs
import assert from 'node:assert/strict';
import { МЕСТА } from '../Данные/места.js';
import { РАЙОНЫ } from '../Данные/районы.js';
import { НАЧАЛА } from '../Данные/герой.js';
import { МЫСЛИ } from '../Данные/мысли.js';
import { ДЕЛА } from '../Данные/дела.js';
import boec from '../Данные/Диалоги/boec.js';
import notarius from '../Данные/Диалоги/notarius.js';
import sibilla from '../Данные/Диалоги/sibilla.js';

// Боец: вход не повторяет реплику ветки «Нижняя лавка».
const вход = boec.ветки.вход.узлы.старт.варианты.map(в => в.текст);
assert.ok(!вход.some(т => /присесть/i.test(т)), 'вход бойца не спрашивает «Можно присесть?» перед веткой «Можно присесть рядом?»');

// Жители кварталов: вступление и ответ «О работе здесь» — разные строки.
for (const м of МЕСТА) for (const [id, г] of Object.entries(м.модуль.ДИАЛОГИ ?? {})) {
  const в = г.ветки?.ni_o_chem ?? г.ветки?.порядок;
  if (!в || typeof в.узлы.старт.текст === 'function') continue;
  assert.ok(!в.узлы.старт.текст.includes(г.вступление), `${м.id}/${id}: вступление дважды`);
}

// Сибилла отвечает на «Не помешаю?»; кнопки её дел — по-русски и целиком.
const помешаю = sibilla.ветки.вход.узлы.старт.варианты.find(в => в.текст === '«Не помешаю?»');
assert.ok(помешаю.ответ?.length, 'у Сибиллы есть ответ на «Не помешаю?»');
for (const id of ['pravda_o_kladbishche', 'odin_dorr_ili_dva']) assert.doesNotMatch(ДЕЛА[id].шаги[0].кнопка, /нужно про/);

// Мысль про границу помощи не пересказывает разговор, которого могло не быть.
const м = МЫСЛИ.gde_ostanovitsya;
assert.doesNotMatch(м.начало, /назвал границу|спросил, где мне остановиться/);
assert.notEqual(м.название, 'Где мне остановиться', 'название не читается как «где ночевать»');

// Нотариус на «вы», без «ровного» голоса во вступлении (выдача письма в цели-места.js уже «ровная»).
const речь = JSON.stringify(notarius);
assert.doesNotMatch(речь, /спрашивай"|Подпишешь|твой вывод/);
assert.doesNotMatch(notarius.вступление, /ровн/);

// Описания районов: «держит/держат» не больше одного раза; начала не кончаются одинаковым кошельком.
const держ = Object.values(РАЙОНЫ).map(р => р.описание ?? '').join(' ').match(/держ(ит|ат)/g) ?? [];
assert.ok(держ.length <= 1, `«держит» в описаниях районов: ${держ.length}`);
assert.ok(НАЧАЛА.filter(н => /кошел/.test(н.описание)).length <= 1, 'кошелёк не повторяется в описаниях начал');

console.log('Хвосты круга 1: боец, жители кварталов, Сибилла, мысль о границе, Нотариус, районы и начала — OK');
