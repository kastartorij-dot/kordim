// Перенос сохранения файлом (шаг 14): экспорт отдаёт слот как есть, импорт кладёт в автосейв и бережёт прежний.
// node Игры/Порт/Тесты/перенос-сохранения.mjs
import assert from 'node:assert/strict';
const хран = new Map();
globalThis.localStorage = { getItem: к => (хран.has(к) ? хран.get(к) : null), setItem: (к, v) => хран.set(к, String(v)), removeItem: к => хран.delete(к) };
const { новоеСостояние, сохранить, загрузить, экспортСохранения, импортСохранения, ВЕРСИЯ } = await import('../Движок/состояние.js');

const S = новоеСостояние('семья', 7); S.мир.день = 5; S.герой.кошель = 77;
сохранить(S, 1);
assert.equal(экспортСохранения(2), null, 'пустой слот не экспортируется');
const файл = экспортСохранения(1);
assert.ok(файл && JSON.parse(файл).мир.день === 5);

// Другое устройство: свой автосейв уже есть.
const старый = новоеСостояние('бумаги', 9); старый.мир.день = 2; сохранить(старый, 'авто');
const р = импортСохранения('﻿' + файл + '\n');
assert.deepEqual(р, { можно: true, день: 5 });
const З = загрузить('авто');
assert.equal(З.мир.день, 5); assert.equal(З.герой.кошель, 77);
const резервы = [...хран.keys()].filter(к => к.includes('-авто-резерв-'));
assert.equal(резервы.length, 1, 'прежний автосейв — в резерве');
assert.equal(JSON.parse(хран.get(резервы[0])).мир.день, 2);

// Мусор и будущая версия — отказ, автосейв не тронут.
assert.equal(импортСохранения('не json').можно, false);
assert.equal(импортСохранения('{"мир":{}}').можно, false);
assert.match(импортСохранения(JSON.stringify({ ...JSON.parse(файл), версия: ВЕРСИЯ + 1 })).причина, /новее|новой версии/);
assert.equal(загрузить('авто').мир.день, 5);
console.log('перенос-сохранения: ok');
