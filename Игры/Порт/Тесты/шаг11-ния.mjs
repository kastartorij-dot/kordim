// Шаг 11, пакет 3: линия Нии настоящими действиями. Запуск: node Игры/Порт/Тесты/шаг11-ния.mjs
// Разные поступки дают три разных её ответа — «да», «дружба», прямое «нет»; жалость стоит доверия,
// а написанный ответ «выкупать нечего» заменяет её отсутствие в «Вытащить».
import assert from 'node:assert/strict';
import { новоеСостояние } from '../Движок/состояние.js';
import { догрузитьСцену } from '../Движок/разговор.js';
import { связь } from '../Движок/связи.js';
import { ПРАВИЛА } from '../Данные/связи.js';
import { РАБОТНИЦЫ } from '../Данные/вытащить.js';
import { есть, нажать, конецДня, вХаб, ветка, вечерДома, рынок, читатьСцену } from './утилиты/линии.js';

const КОМНАТА = ['zal', 'lestnica', 'komnata_nii'];
const вечер = S => вечерДома(S, 'niya', КОМНАТА);
const утро = S => рынок(S, 'утро', 'еда-рынка');

// Начало: тишина и «твоё нет не обсуждается» — доверие 2; второй вечер — этап «встречи».
function начало(seed) {
  const S = новоеСостояние('семья', seed);
  S.мир.день = 3;
  вечер(S);
  ветка(S, 'порог', 'тишина', 'ясно');
  ветка(S, 'границы', 'принимаю', 'ясно');
  assert.equal(S.мир.люди.niya.распол, 2);
  конецДня(S); вечер(S);
  assert.equal(связь(S, 'niya').этап, 'встречи');
  assert.ok(есть(S, 'ветка:утро'));
  return S;
}
function завтрак(S, ...варианты) {
  конецДня(S); утро(S);
  assert.ok(есть(S, 'заговорить:niya'), 'Ния утром у лотков');
  нажать(S, 'заговорить:niya'); вХаб(S);
  ветка(S, 'завтрак', ...варианты);
}
function повернуть(S, вариант) {
  конецДня(S); вечер(S);
  ветка(S, 'поворот', вариант, 'ясно');
  assert.ok(!есть(S, 'ветка:решение'), 'ответ — на следующий день');
  конецДня(S); вечер(S);
  ветка(S, 'решение');
  return связь(S, 'niya').решение.что;
}

// ── «да»: стоять рядом молча, сказать прямо ─────────────────────────────
{
  const S = начало(41);
  ветка(S, 'утро', 'рядом', 'ясно');
  завтрак(S, 'молча', 'дальше', 'ясно');
  assert.equal(связь(S, 'niya').этап, 'вне-работы');
  assert.equal(S.мир.люди.niya.распол, 3);
  // её утро теперь открыто каждый день, обещание уже сдержано
  конецДня(S); утро(S);
  assert.ok(есть(S, 'заговорить:niya'));
  нажать(S, 'заговорить:niya'); вХаб(S);
  assert.ok(есть(S, 'ветка:утро_после') && !есть(S, 'ветка:завтрак'));
  assert.equal(повернуть(S, 'прямо'), 'да');
  нажать(S, 'вариант:решение:да_принять'); нажать(S, 'вариант:решение:ясно');
  assert.equal(связь(S, 'niya').статус, 'вместе');
  ветка(S, 'после');
  const кошель = S.герой.кошель, доступ = связь(S, 'niya').доступ;
  нажать(S, 'вариант:после:остаться');
  assert.equal(S.сцена.нужнаСцена, 'niya_личная');
  assert.equal(S.герой.кошель, кошель);
  assert.equal(связь(S, 'niya').доступ, доступ);
  await догрузитьСцену(S, читатьСцену);
  assert.match(S.сцена.реплика, /ЗАГОТОВКА АВТОРА/);
  // утро у лотков продолжает линию: встреча там отодвигает паузу
  for (let i = 0; i < ПРАВИЛА.отсутствие.пауза - 1; i++) конецДня(S);
  утро(S); нажать(S, 'заговорить:niya'); вХаб(S); ветка(S, 'утро_после', 'ясно');
  конецДня(S); конецДня(S);
  assert.equal(связь(S, 'niya').статус, 'вместе', 'утренние встречи — тоже встречи');
  // расставание словами
  вечер(S); ветка(S, 'после', 'расстаться', 'ясно');
  assert.equal(связь(S, 'niya').статус, 'расстались');
}

// ── «дружба»: хотел угостить, исправился; бережный ответ без влечения ─────
{
  const S = начало(42);
  ветка(S, 'утро', 'угощу');
  assert.equal(S.мир.люди.niya.распол, 2, 'предложение заплатить не даёт доверия');
  нажать(S, 'вариант:утро:понял'); нажать(S, 'вариант:утро:ясно');
  завтрак(S, 'угостить', 'молча', 'дальше', 'ясно');
  assert.equal(S.мир.люди.niya.распол, 3);
  assert.equal(связь(S, 'niya').влечение, 1);
  assert.equal(повернуть(S, 'бережно'), 'дружба');
  нажать(S, 'вариант:решение:принять'); нажать(S, 'вариант:решение:ясно');
  ветка(S, 'после');
  assert.ok(!есть(S, 'вариант:после:остаться'));
}

// ── прямое «нет»: она рассказала о лавке, но влечения нет; жалость стоит доверия ──
{
  const S = начало(43);
  ветка(S, 'утро', 'рядом', 'ясно');
  завтрак(S, 'куда', 'дальше', 'ясно');
  assert.equal(S.мир.люди.niya.распол, 3);
  assert.equal(связь(S, 'niya').влечение, 0);
  assert.equal(повернуть(S, 'бережно'), 'нет', 'без влечения и без просьбы о дружбе — прямое «нет»');
  assert.equal(связь(S, 'niya').статус, 'отказ');
  нажать(S, 'вариант:решение:жалость'); нажать(S, 'вариант:решение:ясно');
  assert.equal(S.мир.люди.niya.распол, 2);
  assert.equal(связь(S, 'niya').решение.что, 'нет', 'жалость не меняет ответ');
  // утро у лотков остаётся её; отказ виден спокойно
  конецДня(S); утро(S); нажать(S, 'заговорить:niya'); вХаб(S);
  ветка(S, 'утро_после');
  assert.ok(S.сцена.диалог.лента.some(з => /гость, которому не рады меньше/.test(з.т)));
  // «выкуп»: помнит, что уже говорила о лавке
  конецДня(S); вечер(S);
  ветка(S, 'выкуп', 'на_своё');
  assert.ok(S.сцена.диалог.лента.some(з => /Я тебе уже говорила у лотков/.test(з.т)));
}

// ── «Вытащить»: Нию выкупать не нужно — это написанный ответ, не пустая карточка ──
assert.equal(РАБОТНИЦЫ.niya, undefined, 'Ния не цель выкупа');
{
  const S = начало(44);
  ветка(S, 'выкуп', 'ясно');
  assert.ok(S.мир.диалоги.niya.факты.includes('ния_не_нужен_выкуп'));
}

console.log('шаг 11 (линия Нии): все проверки пройдены');
