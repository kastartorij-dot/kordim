// Все восемь мест: первый/повторный визит, осмотр каждой комнаты, обратный путь,
// реальное закрытое время или явно круглосуточный караул/оплаченное жильё.
for (const м of ГОРОДСКИЕ_МЕСТА) {
  const S = свежее();
  вход(S, м.id);
  const первый = видСцены(S).реплика;
  assert.ok(typeof первый === 'string' && первый.length > 25);
  assert.equal(S.мир.отрезок, 'утро', `${м.id}: осмотр не берёт отрезок смены`);
  assert.ok(действияСцены(S).length);
  const д = м.модуль;
  for (const [id, к] of Object.entries(д.КОМНАТЫ)) {
    if (id === 'камера') continue;
    S.сцена.комната = id;
    const a = действияСцены(S).find(a => a.вид === 'рассмотреть');
    assert.ok(a, `${м.id}/${id}: есть осмотр`);
    a.выполнить(S);
    assert.equal(typeof видСцены(S).реплика, 'string');
    assert.ok(действияСцены(S).some(a => a.вид === 'финал'), `${м.id}/${id}: есть выход`);
    for (const сосед of к.соседи) assert.ok(д.КОМНАТЫ[сосед], `${id}: сосед существует`);
  }
  вернутьсяВГород(S);
  вход(S, м.id);
  assert.notEqual(видСцены(S).реплика, первый, `${м.id}: повторный вход изменился`);
  assert.deepEqual(Object.keys(S.мир.фракции).sort(), ['братство', 'картель', 'ножи']);
  вернутьсяВГород(S);
  S.мир.отрезок = 'ночь';
  if (!м.когда.includes('ночь')) {
    assert.equal(можноВойти(S, м.id).можно, false);
    assert.ok(можноВойти(S, м.id).почему);
  }
}

