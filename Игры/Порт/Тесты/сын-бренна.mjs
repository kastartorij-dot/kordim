// Круг 2, PR005-02 «Линия отца не замечает сына»: node Игры/Порт/Тесты/сын-бренна.mjs
// В первые дни есть видимый шаг к вопросу об отце (дело «Что стало с Бренном»: грузчик у навеса → весовщик),
// а люди, которые помнят Бренна, в начале «семья» узнают в герое сына. В «бумагах» и «ремесле» эти строки молчат.
import assert from 'node:assert/strict';
import { новоеСостояние } from '../Движок/состояние.js';
import { войти, действияСцены, вернутьсяВГород } from '../Движок/разговор.js';
import { запись, сводкаДел } from '../Движок/дела.js';
import { МЕСТА } from '../Данные/места.js';

const ДЕЛО = 'chto_stalo_s_brennom';
const нов = (начало = 'семья', день = 1) => { const S = новоеСостояние(начало, 7); S.мир.день = день; return S; };
const лента = S => (S.сцена?.диалог?.лента ?? []).map(з => з.т).join('\n');
const кнопка = (S, id) => действияСцены(S).find(а => а.id === id);
const нажать = (S, id) => {
  const к = кнопка(S, id);
  assert.ok(к, `нет кнопки ${id}; есть: ${действияСцены(S).map(а => а.id).join(' | ')}`);
  assert.notEqual(к.можно, false, `${id} недоступна: ${к.почему}`);
  к.выполнить(S);
  return к;
};
// Прийти в место в его первый открытый отрезок, в нужную комнату, и заговорить с человеком.
function заговорить(S, местоId, кто, { комната = null, отрезок = null } = {}) {
  if (S.сцена) вернутьсяВГород(S);
  const м = МЕСТА.find(x => x.id === местоId);
  S.мир.район = м.район; S.мир.отрезок = отрезок ?? м.когда[0]; S.мир.конецДня = null;
  войти(S, местоId);
  if (комната) S.сцена.комната = комната;
  нажать(S, `заговорить:${кто}`);
  return S;
}
const ветки = S => действияСцены(S).filter(а => а.вид === 'ветка').map(а => а.id);

// ── 1. Дело об отце: видно с первого дня, ведёт от навеса к весовой, наград и сроков нет ──────────
for (const начало of ['семья', 'бумаги', 'наколки']) {
  const S = нов(начало);
  заговорить(S, 'причал-грузчиков', 'gruzchik', { отрезок: 'день' });
  нажать(S, `дело:${ДЕЛО}:спросить`);
  assert.match(лента(S) + '\n' + S.мир.журналДня.join('\n'), /У сходни тебе уже сказали/, `${начало}: грузчик отвечает об отце, не узнавая заново`);
  const р = запись(S, ДЕЛО);
  assert.equal(р.статус, 'активно', `${начало}: дело в журнале`);
  assert.equal(р.срок_до, null, 'без срока');
  const строка = сводкаДел(S).find(д => д.id === ДЕЛО);
  assert.match(строка.следующий, /весовой/, 'журнал говорит, куда идти дальше');
  const кошель = S.герой.кошель;
  заговорить(S, 'контора-дорров', 'весовщик', { комната: 'весовая-дорров' });
  нажать(S, `дело:${ДЕЛО}:весовая`);
  assert.equal(запись(S, ДЕЛО).статус, 'готово');
  assert.equal(S.герой.кошель, кошель, 'дело ничего не платит');
}

// ── 2. Знавшие Бренна узнают сына — только в начале «семья» ─────────────────────────────────────
const узнают = [
  ['весовщик', S => заговорить(S, 'контора-дорров', 'весовщик', { комната: 'весовая-дорров' }), S => нажать(S, 'ветка:весы'), /Бреннов сын/],
  ['хозяин таверны', S => заговорить(S, 'таверна', 'hozyain'), S => { нажать(S, 'вариант:вход:подойти'); нажать(S, 'ветка:бренн'); }, /То-то лицо знакомое/],
  ['Марна', S => заговорить(S, 'причал-грузчиков', 'marna', { отрезок: 'день' }), S => нажать(S, 'ветка:печать'), /подпись у него стоила дороже денег/],
  ['Брас', S => заговорить(S, 'рынок', 'bras', { отрезок: 'день' }), () => {}, /на твоё лицо, потом на плечи/],
];
for (const [кто, прийти, спросить, узнал] of узнают) {
  const С = нов('семья', 3); прийти(С); спросить(С);
  assert.match(лента(С), узнал, `«семья»: ${кто} узнаёт сына`);
  for (const начало of ['бумаги', 'наколки']) {
    const Б = нов(начало, 3); прийти(Б); спросить(Б);
    assert.doesNotMatch(лента(Б), узнал, `«${начало}»: ${кто} не узнаёт без начала «семья»`);
  }
}

// ── 3. Вейт: строка «Бреннов сын вернулся» на доске — ветка есть только у «семьи» ─────────────────
{
  const С = нов('семья', 2);
  заговорить(С, 'рынок', 'veyt', { комната: 'слухи-рынка', отрезок: 'день' });
  if (кнопка(С, 'вариант:вход:к_доске')) нажать(С, 'вариант:вход:к_доске');
  assert.ok(ветки(С).includes('ветка:скарре'), '«семья»: у Вейта есть ветка про Бренна: ' + ветки(С));
  нажать(С, 'ветка:скарре');
  assert.match(лента(С), /Бреннов сын вернулся/);
  const Б = нов('бумаги', 2);
  заговорить(Б, 'рынок', 'veyt', { комната: 'слухи-рынка', отрезок: 'день' });
  if (кнопка(Б, 'вариант:вход:к_доске')) нажать(Б, 'вариант:вход:к_доске');
  assert.ok(!ветки(Б).includes('ветка:скарре'), '«бумаги»: ветки про доску с фамилией нет');
}

// ── 4. Хозяин таверны показывает дорогу к навесу при любом начале ──────────────────────────────
for (const начало of ['семья', 'бумаги', 'наколки']) {
  const S = нов(начало, 1);
  заговорить(S, 'таверна', 'hozyain');
  нажать(S, 'вариант:вход:подойти');
  нажать(S, 'ветка:бренн');
  assert.match(лента(S), /у навеса на причале/, `${начало}: хозяин говорит, где спрашивать`);
}


// ── 5. Без протечек и повторов (круг 2, Критик): дело не пересказывает находки Браса и старшого заранее,
// формула «ни разу не свесил лишнего» — только у старшого в смене, «одни… другие» о Бренне — один раз, жесты узнавания разные.
{
  const { ДЕЛА } = await import('../Данные/дела.js');
  const { ТЕМЫ_РАБОТ } = await import('../Данные/темы-работ.js');
  const дело = JSON.stringify(ДЕЛА[ДЕЛО]);
  assert.doesNotMatch(дело, /Брас|пломб|у весов уже не было|задолго до смерти|свесил лишнего|выходит, Скарре/, 'дело не опережает свидетельства и вступление');
  assert.doesNotMatch(ТЕМЫ_РАБОТ.brenn_vesy.текст, /свесил лишнего/);
  const fs = await import('node:fs');
  const тексты = ['Данные/дела.js', 'Данные/темы-работ.js', 'Данные/Диалоги/hozyain.js', 'Данные/Диалоги/veyt.js', 'Данные/Диалоги/весовщик.js', 'Данные/Диалоги/bras.js', 'Данные/Диалоги/состав-жителей.js']
    .map(ф => fs.readFileSync(new URL('../' + ф, import.meta.url), 'utf8')).join('\n');
  const оБренне = тексты.split('\n').filter(с => /Бренн|Скарре/.test(с));
  assert.equal(оБренне.filter(с => /[Оо]дни .*други/.test(с)).length, 1, '«одни… другие» о Бренне — один раз');
  assert.equal(оБренне.filter(с => /дольше, чем на|дольше обычного|задерживает на тебе взгляд/.test(с)).length, 0, 'жесты узнавания не повторяют друг друга');
}

console.log('Сын Бренна: дело об отце с первого дня, отклики знавших Бренна в «семье», без них в «бумагах» и «ремесле» — OK');
