// Шаг 12: мини-игры «Торг» и «Кости» в местах. node Игры/Порт/Тесты/шаг12-торг-кости.mjs
// Данные торга сходятся с полом цены, шансы костей посчитаны честно, кон в таверне не выгоден садящемуся,
// Горм переигрывает ничью и помнит заданные вопросы, партия переживает сохранение, «назад» её не переигрывает.
// Подробные проверки торга у Пина — Тесты/рынок.mjs, кости Горма по исходам — Тесты/двор.mjs.
import assert from 'node:assert/strict';
import { новоеСостояние, мигрировать } from '../Движок/состояние.js';
import { войти, действияСцены, вернутьсяВГород, видСцены } from '../Движок/разговор.js';
import { кубики } from '../Движок/проверка.js';
import { шансыКостей, словоШанса } from '../Движок/игры-места.js';
import { ТОРГ, РАУНДЫ_ПО_ОТРЕЗКУ } from '../Данные/торг.js';
import { КОСТИ } from '../Данные/кости.js';
import { датьРемесло } from '../Движок/ремёсла.js';

const кнопка = (S, текст) => действияСцены(S).find(а => (а.текст ?? '').startsWith(текст));
const нажать = (S, текст) => { const а = кнопка(S, текст); assert.ok(а, `нет кнопки «${текст}»: ` + действияСцены(S).map(х => х.текст).join(' | ')); assert.equal(а.можно, true, а.почему); а.выполнить(S); };
const играть = (S, ид) => { const а = действияСцены(S).find(х => х.id === 'игра:кости:' + ид); assert.ok(а, `нет хода ${ид}: ` + действияСцены(S).map(х => х.id).join(' | ')); а.выполнить(S); };
const сумма = к => к[0] + к[1];
const копия = S => мигрировать(JSON.parse(JSON.stringify(S)));

// ── данные торга: верных доводов хватает до пола, неверные есть, ниже пола цена не падает ──
for (const [id, т] of Object.entries(ТОРГ)) {
  for (const отрезок of ['день', 'вечер']) {
    const N = РАУНДЫ_ПО_ОТРЕЗКУ[отрезок];
    const верные = т.доводы.filter(д => д.верный && (!д.условие?.отрезок || д.условие.отрезок === отрезок));
    assert.ok(верные.length >= N, `${id}, ${отрезок}: верных доводов на все раунды`);
    const скидка = т.скидки.slice(0, N).reduce((a, x) => a + x, 0);
    assert.equal(Math.max(т.пол[отрезок], т.запрос - скидка), т.пол[отрезок], `${id}, ${отрезок}: верные доводы доводят до пола`);
    assert.ok(т.запрос - т.скидки.reduce((a, x) => a + x, 0) <= т.пол[отрезок], `${id}: скидки не обещают ниже пола`);
  }
  assert.ok(т.доводы.filter(д => !д.верный).length >= 1, id + ': есть неверный довод');
  assert.ok(т.доводы.filter(д => д.верный).every(д => д.ответ.includes('{цена}')), id + ': верный ответ называет цену');
  assert.ok(т.видно.length >= 3 && т.совет && т.ремесло, id + ': видно, совет, ремесло');
  assert.ok(!/секунд|гильди/i.test(JSON.stringify(т)), id);
}

// ── кости: шансы — доли, «оставить» против известной суммы — наверняка ──
{
  const S = { герой: { ремёсла: {} }, сцена: { игра: { партия: 'горм', мои: [3, 4], его: [2, 5] } } };
  const ш = шансыКостей(S);
  assert.deepEqual(ш.оставить, { выигрыш: 0, вровень: 1, проигрыш: 0 });
  for (const x of ш.переброс) assert.ok(Math.abs(x.выигрыш + x.вровень + x.проигрыш - 1) < 1e-9);
  assert.ok(Math.abs(ш.переброс[0].выигрыш - 3 / 6) < 1e-9, 'перебросить 3 при 4 против 7: выше на 4, 5, 6');
  assert.equal(словоШанса(S, ш.оставить), 'как повезёт', 'без грамоты — словами');
  S.герой.ремёсла.грамота = { ступень: 'умеешь' };
  assert.equal(словоШанса(S, ш.переброс[0]), 'выиграешь 50% · вровень 17%', 'с грамотой — числом');
}
// Кон в таверне: даже лучшая игра садящегося в среднем не в плюс — денег из воздуха нет.
{
  let ev = 0;
  for (let a = 1; a <= 6; a++) for (let b = 1; b <= 6; b++) {
    const ш = шансыКостей({ герой: { ремёсла: {} }, сцена: { игра: { партия: 'таверна', мои: [a, b], его: null } } });
    ev += Math.max(...[ш.оставить, ...ш.переброс].map(x => x.выигрыш - x.проигрыш)) / 36;
  }
  assert.ok(ev < 0 && ev > -0.3, 'ожидание лучшей игры в таверне чуть ниже нуля: ' + ev.toFixed(3));
}

// ── таверна: один кон за вечер, ставка 2 гр., исход из кубиков ──
const вТаверне = (кошель = 20, з = 1) => {
  const S = новоеСостояние('бумаги', 7); S.мир.район = 'доки'; S.мир.отрезок = 'вечер'; S.мир.день = 4; S.герой.кошель = кошель; S.мир.зерноКампании = з;
  войти(S, 'таверна'); return S;
};
// Исход «оставить» при этом зерне: сумма моих против броска моряка с его перебросом.
const исходТаверны = з => {
  const осн = `кости:таверна:4`, м = сумма(кубики(з, осн + ':мои', 1)), к = кубики(з, осн + ':его', 1);
  if (сумма(к) <= м) к[к[0] <= к[1] ? 0 : 1] = кубики(з, осн + ':его-переброс', 1)[0];
  return м > сумма(к) ? 'выигрыш' : м < сумма(к) ? 'проигрыш' : 'вровень';
};
const зерно = f => { for (let з = 1; ; з++) if (f(з)) return з; };
for (const [исход, д] of [['выигрыш', 2], ['проигрыш', -2], ['вровень', 0]]) {
  const S = вТаверне(20, зерно(з => исходТаверны(з) === исход));
  const х0 = S.сцена.ходы;
  нажать(S, 'Сыграть с моряком в кости');
  assert.equal(видСцены(S).игра.его, null, 'моряк бросает после тебя');
  assert.equal(S.история.length, 0, 'свой бросок увиден — «назад» нет');
  играть(S, 'оставить');
  assert.equal(S.герой.кошель, 20 + д, исход);
  assert.equal(S.сцена.ходы, х0 + 1);
  assert.ok(S.мир.журналДня.some(с => с.startsWith('Кости с моряком')), исход);
  assert.equal(кнопка(S, 'Сыграть с моряком в кости'), undefined, 'один кон за вечер');
}
assert.equal(кнопка(вТаверне(1), 'Сыграть с моряком в кости'), undefined, 'без двух грошей не садятся');

// ── Горм: ничья переигрывается, заданные вопросы помнятся, партия переживает сохранение ──
const воДворе = (день, з) => {
  const S = новоеСостояние('семья', 7); S.мир.район = 'трущобы'; S.мир.день = день; S.мир.отрезок = 'день'; S.герой.кошель = 50; S.мир.зерноКампании = з;
  войти(S, 'двор-горма'); действияСцены(S).find(а => а.id === 'пойти:стол-горма').выполнить(S); return S;
};
const гормДня = (з, день, кон = 1) => [сумма(кубики(з, `кости:горм:${день}:мои`, кон)), сумма(кубики(з, `кости:горм:${день}:его`, кон))];
{
  const з = зерно(з => { const [м, е] = гормДня(з, 3); return м === е; });
  const S = воДворе(3, з);
  нажать(S, 'Сыграть с Гормом в кости на вопрос');
  const К = копия(S);
  assert.deepEqual(К.сцена.игра, S.сцена.игра, 'партия в сохранении');
  assert.deepEqual(действияСцены(К).map(х => х.id), действияСцены(S).map(х => х.id));
  играть(S, 'оставить');
  assert.equal(S.сцена.игра.стадия, 'ничья');
  assert.match(S.сцена.игра.реплика, /Вровень/);
  играть(S, 'ещё');
  assert.equal(S.сцена.игра.кон, 2);
  assert.equal(S.сцена.игра.стадия, 'решение');
}
{
  // Три нечётных дня подряд выигрываем: о Бренне, о деньгах, а на третий спрашивать уже нечего.
  const S = воДворе(3, зерно(з => { const [м, е] = гормДня(з, 3); return м > е; }));
  const выиграть = (день, вопрос) => {
    if (день > 3) { вернутьсяВГород(S); S.мир.день = день; S.мир.отрезок = 'день'; S.мир.зерноКампании = зерно(з => { const [м, е] = гормДня(з, день); return м > е; }); войти(S, 'двор-горма'); действияСцены(S).find(а => а.id === 'пойти:стол-горма').выполнить(S); }
    нажать(S, 'Сыграть с Гормом в кости на вопрос'); играть(S, 'оставить');
    if (вопрос) играть(S, 'вопрос:' + вопрос);
  };
  выиграть(3, 'бренн');
  выиграть(5, 'деньги');
  assert.equal(S.мир.люди.gorm?.распол ?? 0, 1, 'ответ «почему не на деньги» — расположение');
  выиграть(7, null);
  assert.equal(S.сцена.игра, null);
  assert.equal(S.сцена.реплика.endsWith(КОСТИ.горм.всё), true, 'спрашивать больше нечего');
  assert.deepEqual(S.мир.места['двор-горма'].кости.спросил, ['бренн', 'деньги']);
}
// С грамотой шанс числом прямо на кнопке.
{
  const S = воДворе(3, 5); датьРемесло(S, 'грамота');
  нажать(S, 'Сыграть с Гормом в кости на вопрос');
  assert.ok(действияСцены(S).every(х => /%|уже/.test(х.подпись)), действияСцены(S).map(х => х.подпись).join(' | '));
}

