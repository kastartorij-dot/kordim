// Шаг 8, Часовня: исповедь (правда даёт слово часовни, ложь гасит свечу), убежище на ночь, свечи, поминальный день.
// node Тесты/часовня.mjs
import assert from 'node:assert/strict';
import { новоеСостояние } from '../Движок/состояние.js';
import { войти, можноВойти, действияСцены, вернутьсяВГород, видСцены } from '../Движок/разговор.js';
import { доступныеДействия } from '../Движок/действия.js';
import { кражаСлучилась } from '../Движок/кража.js';
import { привестиВещи } from '../Движок/вещи.js';

const кнопка = (S, текст) => действияСцены(S).find(а => а.текст === текст || а.текст.startsWith(текст));
const нажать = (S, текст) => { const а = кнопка(S, текст); assert.ok(а, `нет кнопки «${текст}»`); assert.equal(а.можно, true, `«${текст}» недоступна`); а.выполнить(S); };
const осмотреть = (S, д) => действияСцены(S).find(а => а.id === `рассмотреть:${д}`).выполнить(S);
const м = S => S.мир.места.часовня;

function вЧасовне(день = 3, отрезок = 'день', S0 = null) {
  const S = S0 ?? новоеСостояние('семья', 7);
  S.мир.район = 'маяк'; S.мир.день = день; S.мир.отрезок = отрезок; S.герой.кошель = 50;
  войти(S, 'часовня');
  return S;
}
// Три факта о герое: заём у менялы, подкова левой рукой, за ним следят. Остальные слоты — «чистые».
function сФактами(S) {
  S.мир.места.меняльная = { дом: 0, долг: 0, флаги: [], осмотрено: [], визитов: 1, заём: { сумма: 20, долг: 22, до: 10 } };
  S.мир.места['двор-горма'] = { дом: 0, долг: 0, флаги: ['горм_видит'], осмотрено: [], визитов: 1 };
  S.мир.тень = 1;
  return S;
}
// Нажать «Сказать» у высказываний, подходящих под условие (верно / неверно).
function сказатьВсе(S, верно) {
  const и = S.сцена.исповедь;
  const нужные = и.высказывания.map((в, i) => ({ в, i })).filter(({ в }) => в.верно === верно);
  for (const { в } of нужные) нажать(S, `Сказать: «${в.текст}»`);
  return нужные.length;
}
const высказывания = S => S.сцена.исповедь.высказывания;

// ── мало фактов: «приходи, когда будет что сказать», без штрафа и без траты дня
{
  const S = вЧасовне();
  const тень = S.мир.тень ?? 0;
  нажать(S, 'Исповедаться Уне');
  assert.match(S.сцена.реплика, /Приходи, когда будет что сказать/);
  assert.equal(S.сцена.исповедь ?? null, null, 'стол не раскрыт');
  assert.equal(S.сцена.комната, 'неф-часовни');
  assert.equal(S.мир.тень ?? 0, тень, 'тень не тронута');
  assert.equal(м(S).дниДействий?.исповедь, undefined, 'день не потрачен');
  assert.equal(!!кнопка(S, 'Исповедаться Уне'), true, 'можно прийти ещё раз в тот же день');
}

// ── стол: пять высказываний, среди них всегда хоть одно вранье; молчание ничего не стоит
{
  const S = сФактами(вЧасовне());
  нажать(S, 'Исповедаться Уне');
  assert.equal(S.сцена.комната, 'исповедальня');
  assert.match(S.сцена.реплика, /Что за тобой числится/);
  assert.equal(высказывания(S).length, 5);
  assert.ok(высказывания(S).some(в => !в.верно), 'на столе есть враньё');
  assert.ok(высказывания(S).some(в => в.верно), 'и есть правда');
  assert.equal(new Set(высказывания(S).map(в => в.id)).size, 5, 'высказывания не повторяются');
  // враньё не подписано: кнопки у правды и у вранья выглядят одинаково
  const тексты = высказывания(S).map(в => `Сказать: «${в.текст}»`);
  for (const т of тексты) assert.equal(кнопка(S, т).подпись ?? '', '', 'подсказки на кнопке нет');
  const тень = S.мир.тень, ход = S.мир.отрезок;
  нажать(S, 'Закончить исповедь');
  assert.match(S.сцена.реплика, /Ты молчишь/);
  assert.equal(S.сцена.комната, 'неф-часовни');
  assert.equal(S.мир.тень, тень);
  assert.equal(!!S.мир.выдано?.покров_часовни, false, 'слово часовни не потрачено');
  assert.notEqual(S.мир.отрезок, undefined);
  assert.equal(ход, S.мир.отрезок, 'молчание не съедает отрезок');
  assert.equal(кнопка(S, 'Исповедаться Уне'), undefined, 'второй раз в тот же день нельзя');
}

// ── правда: слово часовни. Тень −1 сразу или про запас
{
  const S = сФактами(вЧасовне());
  нажать(S, 'Исповедаться Уне');
  const сказано = сказатьВсе(S, true);
  assert.ok(сказано >= 3, `правдивых высказываний ${сказано}`);
  нажать(S, 'Закончить исповедь');
  assert.match(S.сцена.реплика, /Слово часовни/);
  assert.ok(кнопка(S, 'Попросить Уну убрать от тебя чужие глаза'), 'тень не нулевая — выбор есть');
  assert.ok(кнопка(S, 'Оставить слово Уны про запас'));
  assert.equal(S.мир.тень, 1);
  нажать(S, 'Попросить Уну убрать от тебя чужие глаза');
  assert.equal(S.мир.тень, 0, 'Тень −1');
  assert.equal(S.мир.выдано.покров_часовни, true);
  assert.equal(S.сцена.комната, 'неф-часовни');
  assert.deepEqual(м(S).память.исповедано.length > 0, true, 'память места хранит исповеданное');
  assert.equal(м(S).счётчики.исповедей, 1);
  assert.ok(S.мир.журналДня.some(с => с.includes('Исповедался в часовне без лжи')));
  assert.ok(S.мир.журналДня.some(с => с.includes('Слово часовни: Тень −1')));
  // второй раз за сезон слова не дают, но правда засчитывается
  S.мир.день = 5; S.мир.тень = 1;
  вернутьсяВГород(S);
  вЧасовне(5, 'день', S);
  нажать(S, 'Исповедаться Уне');
  сказатьВсе(S, true);
  нажать(S, 'Закончить исповедь');
  assert.match(S.сцена.реплика, /Своё слово за тебя она в этом сезоне уже сказала/);
  assert.equal(кнопка(S, 'Оставить слово Уны про запас'), undefined);
  assert.equal(S.мир.тень, 1, 'второго слова нет');
  assert.equal(м(S).счётчики.исповедей, 2);
}

// ── слово про запас: остановит следующую кражу во сне, один раз
{
  const S = сФактами(вЧасовне());
  нажать(S, 'Исповедаться Уне');
  сказатьВсе(S, true);
  нажать(S, 'Закончить исповедь');
  нажать(S, 'Оставить слово Уны про запас');
  assert.equal(S.мир.покров.активен, true);
  assert.equal(S.мир.тень, 1, 'про запас — тень не тронута');
  вернутьсяВГород(S);
  // под открытым небом шанс кражи 1/6: подбираем зерно, при котором вор приходит
  const шанс = [1, 6];
  let сид = 0;
  for (let с = 1; с < 3000 && !сид; с++) { const К = JSON.parse(JSON.stringify(S)); К.мир.сид = с; if (кражаСлучилась(К, шанс)) сид = с; }
  assert.ok(сид, 'нашлось зерно кражи');
  S.мир.сид = сид; S.мир.район = 'маяк'; S.мир.отрезок = 'ночь'; S.мир.день = 6;
  const добро = привестиВещи(S).length, деньги = S.герой.кошель;
  const сон = доступныеДействия(S).find(а => а.id === 'сон:небо');
  assert.ok(сон, 'под открытым небом спать можно');
  сон.выполнить(S);
  assert.equal(привестиВещи(S).length, добро, 'вещи целы');
  assert.equal(S.герой.кошель, деньги, 'деньги целы');
  assert.equal(S.мир.покров.активен, false, 'слово потрачено');
  assert.equal(S.мир.покров.потрачено, 6, 'слово потрачено в ту ночь, когда пришёл вор');
  // без слова та же кража состоялась бы
  const Б = сФактами(вЧасовне());
  Б.мир.сид = сид; Б.мир.район = 'маяк'; Б.мир.отрезок = 'ночь'; Б.мир.день = 6; Б.сцена = null;
  const добро2 = привестиВещи(Б).length, деньги2 = Б.герой.кошель;
  доступныеДействия(Б).find(а => а.id === 'сон:небо').выполнить(Б);
  assert.ok(привестиВещи(Б).length < добро2 || Б.герой.кошель < деньги2, 'без слова часовни ворует');
}

// ── ложь: свеча гаснет, Тень +1, три дня молчания; убежище и просьбы закрыты, потом открываются
{
  const S = сФактами(вЧасовне(3));
  нажать(S, 'Исповедаться Уне');
  сказатьВсе(S, false);
  const тень = S.мир.тень;
  нажать(S, 'Закончить исповедь');
  assert.match(S.сцена.реплика, /Свеча в её руке гаснет/);
  assert.equal(S.мир.тень, тень + 1);
  assert.equal(м(S).память.закрытоДо, 6);
  assert.equal(м(S).счётчики.лжи, 1);
  assert.equal(!!S.мир.выдано?.покров_часовни, false, 'слова нет');
  assert.ok(S.мир.журналДня.some(с => с.includes('Соврал в часовне')));
  // сразу после — Уна молчит
  assert.equal(кнопка(S, 'Исповедаться Уне'), undefined, 'в тот же день нельзя');
  вернутьсяВГород(S);
  вЧасовне(5, 'день', S);
  нажать(S, 'Исповедаться Уне');
  assert.match(S.сцена.реплика, /три дня не разговаривает/);
  assert.equal(S.сцена.исповедь ?? null, null);
  вернутьсяВГород(S);
  // убежище: до дня 6 нет, с дня 6 есть
  S.мир.район = 'маяк'; S.мир.отрезок = 'ночь'; S.мир.день = 5;
  assert.equal(доступныеДействия(S).some(а => а.id === 'сон:часовня'), false, 'до дня 6 убежища нет');
  S.мир.день = 6;
  assert.equal(доступныеДействия(S).some(а => а.id === 'сон:часовня'), true, 'с дня 6 убежище снова есть');
  вЧасовне(6, 'день', S);
  нажать(S, 'Исповедаться Уне');
  assert.equal(S.сцена.комната, 'исповедальня', 'и исповедь снова открыта');
}

// ── ложь не копит Тень выше трёх
{
  const S = сФактами(вЧасовне(3));
  S.мир.тень = 3;
  нажать(S, 'Исповедаться Уне');
  сказатьВсе(S, false);
  нажать(S, 'Закончить исповедь');
  assert.equal(S.мир.тень, 3);
}

// ── убежище на ночь: 1 гр., укрыт, только в районе маяка
{
  const S = новоеСостояние('семья', 7);
  S.мир.район = 'маяк'; S.мир.отрезок = 'ночь'; S.мир.день = 4; S.герой.кошель = 10;
  const сон = доступныеДействия(S).find(а => а.id === 'сон:часовня');
  assert.ok(сон, 'убежище есть ночью у маяка');
  assert.equal(сон.цена, 1);
  assert.match(сон.подпись, /1 гр\./);
  сон.выполнить(S);
  assert.equal(S.герой.кошель, 9);
  const Д = новоеСостояние('семья', 7);
  Д.мир.район = 'доки'; Д.мир.отрезок = 'ночь'; Д.мир.день = 4;
  assert.equal(доступныеДействия(Д).some(а => а.id === 'сон:часовня'), false, 'в доках убежища нет');
  const В = новоеСостояние('семья', 7);
  В.мир.район = 'маяк'; В.мир.отрезок = 'вечер'; В.мир.день = 4;
  assert.equal(можноВойти(В, 'часовня').можно, false, 'вечером закрыто на звон');
}

// ── свечи: за Бренна и за Ярну; стена свечей читается
{
  const S = вЧасовне(4);
  осмотреть(S, 'стена');
  assert.match(S.сцена.реплика, /Свечей за твоих людей здесь пока нет/);
  const до = S.герой.кошель;
  нажать(S, 'Поставить свечу за Ярну');
  assert.equal(S.герой.кошель, до - 1);
  assert.equal(м(S).память.свеча_за_ярна, true);
  assert.equal(кнопка(S, 'Поставить свечу за Ярну'), undefined, 'вторую не ставят');
  осмотреть(S, 'стена');
  assert.match(S.сцена.реплика, /Ярна/);
  нажать(S, 'Поставить свечу за Бренна');
  осмотреть(S, 'стена');
  assert.match(S.сцена.реплика, /Бренн, Ярна/);
}

// ── поминальный день: помощь только в день 20 и один раз
{
  const до = вЧасовне(19);
  assert.equal(кнопка(до, 'Помочь в поминальный день'), undefined, 'в день 19 нет');
  const S = вЧасовне(20);
  const реп = S.мир.очки.репутация ?? 0;
  нажать(S, 'Помочь в поминальный день');
  assert.equal(S.мир.очки.репутация, реп + 1);
  assert.equal(кнопка(S, 'Помочь в поминальный день'), undefined, 'второй раз нет');
}

// ── тема «часовня не доносит» открывается разговором с Уной и не зависит от исповеди
{
  const S = вЧасовне(4);
  assert.ok(видСцены(S).реплика);
  assert.ok(действияСцены(S).some(а => а.id === 'заговорить:una'), 'Уна на месте');
}

