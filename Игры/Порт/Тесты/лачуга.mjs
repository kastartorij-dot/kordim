  нет(S, 'Отдать чужую правду: «Горм и чётные дни»');
  нет(S, 'Отдать чужую правду: «у Локи'); // его собственная тема не плата
  нажать(S, 'Отдать чужую правду: «огонь маяка»');
  assert.ok(S.мир.флаги.includes('проход_локи'), 'ценность 2 покрыла вес 2');
  assert.ok(S.мир.места['лачуга-локи'].память.знает.some(з => з.includes('огонь маяка')), 'Локи запомнил, что ты ему сказал');
