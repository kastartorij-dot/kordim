// Шаг 8, Меняльная: заём (взять, продлить, вернуть, просрочка), оплата комнаты вперёд, проверка кассы, тайны Кипа.
// node Порт/тест/меняльная.mjs
import assert from 'node:assert/strict';
import { новоеСостояние } from '../Движок/состояние.js';
import { войти, действияСцены, вернутьсяВГород } from '../Движок/разговор.js';
import { доступныеДействия } from '../Движок/действия.js';
import { естьВещь } from '../Движок/вещи.js';
import { сводкаЖурнала } from '../Движок/сводка.js';

const кнопка = (S, текст) => действияСцены(S).find(а => а.текст === текст || а.текст.startsWith(текст));
const нажать = (S, текст) => { const а = кнопка(S, текст); assert.ok(а, `нет кнопки «${текст}»`); assert.equal(а.можно, true, `«${текст}» недоступна: ${а.почему}`); а.выполнить(S); };
function уМенялы(день = 2, начало = 'бумаги', кошель = 100) {
  const S = новоеСостояние(начало, 5);
  S.мир.район = 'торговый'; S.мир.день = день; S.мир.отрезок = 'утро'; S.герой.кошель = кошель;
  войти(S, 'меняльная');
  return S;
}
const м = S => S.мир.места.меняльная;

// ── заём: взять, нельзя второй, виден в журнале, вернуть
{
  const S = уМенялы();
  нажать(S, 'Взять заём: 20 гр.');
  assert.equal(S.герой.кошель, 120);
  assert.equal(м(S).долг, 22, '+10%: 20 → 22');
  assert.equal(S.мир.обязательства['заём-меняльной'].статус, 'активно');
  assert.equal(S.мир.обязательства['заём-меняльной'].срок.день, 9);
  assert.equal(кнопка(S, 'Взять заём'), undefined, 'второй заём пока долг не отдан — нельзя');
  assert.equal(сводкаЖурнала(S).долги[0].сумма, 22, 'долг виден в журнале');
  assert.equal(сводкаЖурнала(S).обязательства[0].название, 'Заём меняльной');
  нажать(S, 'Отдать долг');
  assert.equal(S.герой.кошель, 98);
  assert.equal(м(S).долг, 0);
  assert.equal(S.мир.обязательства['заём-меняльной'].статус, 'выполнено');
  assert.ok(кнопка(S, 'Взять заём: 40 гр.'), 'после возврата можно новый заём');
}

// ── суммы займов и процент
{
  const S = уМенялы(2, 'бумаги', 10);
  нажать(S, 'Взять заём: 60 гр.');
  assert.equal(м(S).долг, 66);
}

// ── продление: один раз, +10% суммы, срок +7
{
  const S = уМенялы();
  нажать(S, 'Взять заём: 40 гр.');
  assert.equal(м(S).долг, 44);
  const прод = кнопка(S, 'Продлить заём на неделю');
  assert.match(прод.подпись, /\+4 гр\./);
  нажать(S, 'Продлить заём на неделю');
  assert.equal(м(S).долг, 48);
  assert.equal(S.мир.обязательства['заём-меняльной'].срок.день, 16);
  assert.equal(кнопка(S, 'Продлить заём на неделю'), undefined, 'второй раз не продлевают');
}

// ── просрочка: при следующем визите долг +25%, картель −1, один раз; продлить нельзя, вернуть можно
{
  const S = уМенялы();
  const до = S.мир.очки.картель;
  нажать(S, 'Взять заём: 20 гр.');
  вернутьсяВГород(S);
  S.мир.день = 10; S.мир.отрезок = 'утро';
  войти(S, 'меняльная');
  assert.equal(S.мир.обязательства['заём-меняльной'].статус, 'истекло');
  assert.equal(м(S).долг, 28, '22 × 1,25 = 27,5 → 28');
  assert.equal(S.мир.очки.картель, до - 1, 'картель −1');
  assert.equal(кнопка(S, 'Продлить заём на неделю'), undefined, 'просроченный не продлевают');
  вернутьсяВГород(S);
  S.мир.день = 11; S.мир.отрезок = 'утро';
  войти(S, 'меняльная');
  assert.equal(м(S).долг, 28, 'просрочка применяется один раз');
  нажать(S, 'Отдать долг');
  assert.equal(м(S).долг, 0);
  assert.ok(кнопка(S, 'Взять заём: 20 гр.'), 'после просроченного долга новый заём тоже можно');
  нажать(S, 'Взять заём: 20 гр.');
  assert.equal(S.мир.обязательства['заём-меняльной'].статус, 'активно', 'новый заём получает новую свечу');
}

// ── заём, вернутый вовремя, штрафа не получает
{
  const S = уМенялы();
  const до = S.мир.очки.картель;
  нажать(S, 'Взять заём: 20 гр.');
  нажать(S, 'Отдать долг');
  вернутьсяВГород(S);
  S.мир.день = 12; S.мир.отрезок = 'утро';
  войти(S, 'меняльная');
  assert.equal(S.мир.очки.картель, до);
  assert.equal(м(S).долг, 0);
}

// ── нет денег на возврат
{
  const S = уМенялы(2, 'бумаги', 0);
  нажать(S, 'Взять заём: 20 гр.');
  S.герой.кошель = 5;
  assert.equal(кнопка(S, 'Отдать долг').можно, false);
}

// ── комната вперёд: 25 гр., квитанция, ночью у вдовы платить не надо, повторно нельзя
{
  const S = уМенялы(3, 'бумаги', 100);
  нажать(S, 'Оплатить неделю комнаты вперёд');
  assert.equal(S.герой.кошель, 75);
  assert.deepEqual(S.герой.жильё, { id: 'вдова', оплачено_по: 9 });
  assert.equal(естьВещь(S, 'квитанция'), true);
  assert.equal(кнопка(S, 'Оплатить неделю комнаты вперёд'), undefined);
  вернутьсяВГород(S);
  S.мир.отрезок = 'ночь';
  const сон = доступныеДействия(S).find(а => а.id === 'сон:вдова');
  assert.ok(сон, 'вдова в районе');
  assert.equal(сон.цена, 0, 'ночь уже оплачена');
}
{
  const S = уМенялы(3, 'бумаги', 20);
  assert.equal(кнопка(S, 'Оплатить неделю комнаты вперёд').можно, false, 'не хватает 25 гр.');
}

// ── вклад: потолок 150
{
  const S = уМенялы();
  м(S).вклад = 140;
  нажать(S, 'Положить 10 грошей на свой счёт');
  assert.equal(м(S).вклад, 150);
  assert.equal(кнопка(S, 'Положить 10 грошей на свой счёт'), undefined, 'выше 150 не принимают');
}

// ── проверка кассы, день 14: один ответ из трёх, только при вкладе больше 100
{
  const объяснил = уМенялы(14);
  м(объяснил).вклад = 110;
  const тень0 = объяснил.мир.тень ?? 0;
  нажать(объяснил, 'Объяснить правдой');
  assert.equal(объяснил.мир.тень ?? 0, тень0);
  assert.equal(кнопка(объяснил, 'Назвать меньшую сумму'), undefined, 'ответ дан');

  const солгал = уМенялы(14);
  м(солгал).вклад = 110;
  const до = солгал.мир.очки.картель;
  нажать(солгал, 'Назвать меньшую сумму');
  assert.equal(солгал.мир.тень, 1, 'ложь: тень +1');
  assert.equal(солгал.мир.очки.картель, до - 1, 'ложь: картель −1');

  const взнос = уМенялы(14);
  м(взнос).вклад = 110;
  нажать(взнос, 'Заплатить взнос');
  assert.equal(взнос.герой.кошель, 95);

  const мало = уМенялы(14);
  м(мало).вклад = 100;
  assert.equal(кнопка(мало, 'Объяснить правдой'), undefined, '100 гр. не повод для проверки');
  const другой = уМенялы(13);
  м(другой).вклад = 140;
  assert.equal(кнопка(другой, 'Объяснить правдой'), undefined, 'не в день 14');
}

// ── Кип: тайна и книга процентов
{
  const S = уМенялы();
  действияСцены(S).find(а => а.id === 'пойти:коридор-меняльной').выполнить(S);
  нажать(S, 'Купить у Кипа мелкую тайну');
  assert.ok(S.мир.темы.includes('podyomnik'));
  assert.equal(S.герой.кошель, 90);
  assert.equal(кнопка(S, 'Купить у Кипа мелкую тайну'), undefined, 'вторую тайну он не продаст');
  действияСцены(S).find(а => а.id === 'рассмотреть:проценты').выполнить(S);
  assert.ok(S.мир.темы.includes('notarius_vidit_vklady'));
}

