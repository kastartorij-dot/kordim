// Общая приёмка шага 9: три начала, границы сезона, выбор и сохранённые итоги.
// Денежные/социальные маршруты и их баланс проверяются отдельно (шаг 13).
import assert from 'node:assert/strict';
import { НАЧАЛА } from '../Данные/герой.js';
import { новоеСостояние, мигрировать } from '../Движок/состояние.js';
import { выбратьЦель, снятьЦель, зафиксироватьЦель, действияЦелей, сводкаЦели } from '../Движок/цели.js';
import { лечьСпать, следующийОтрезок, потратитьОтрезок } from '../Движок/время.js';
import { войти, вернутьсяВГород } from '../Движок/разговор.js';
import { взятьОбязательство } from '../Движок/сроки.js';
import { уехать, применитьУехать, следующийШагУехать } from '../Движок/уехать.js';
import { состояниеСезона } from '../Движок/сезон.js';

const ЦЕЛИ = ['угол', 'имя', 'вытащить', 'уехать'];
const новая = (начало, день = 3) => {
  const S = новоеСостояние(начало, 23);
  S.мир.день = день;
  return S;
};
const ночь = S => { S.мир.отрезок = 'ночь'; лечьСпать(S, null); };
const копия = S => мигрировать(JSON.parse(JSON.stringify(S)));

// После финала нельзя снять цель или изменить сохранённый исход старой кнопкой.
{
  const S = новая('семья', 30);
  выбратьЦель(S, 'угол');
  const снять = действияЦелей(S).find(a => a.id === 'цель:снять');
  ночь(S);
  S.мир.конецДня = null;
  const до = JSON.stringify(S);
  assert.equal(снять.выполнить(S), false, 'кнопка прошлого сезона не снимает цель');
  assert.equal(JSON.stringify(S), до);
  assert.equal(действияЦелей(S).some(a => a.id.startsWith('цель:')), false);
  assert.equal(зафиксироватьЦель(S, 'имя'), false);
  assert.match(сводкаЦели(S).шаг, /окончен/);
}

// Все начала видят один набор целей. Поздний выбор не подделывает старые события.
for (const { id: начало } of НАЧАЛА) {
  for (const день of [1, 2, 3, 14, 22, 30, 31]) for (const цель of ЦЕЛИ) {
    const S = новая(начало, день);
    const до = JSON.stringify(S);
    assert.equal(выбратьЦель(S, цель), день >= 3 && день <= 30);
    if (день < 3 || день > 30) assert.equal(JSON.stringify(S), до);
    else {
      assert.equal(S.мир.цели.выбранаДень, день);
      assert.ok(сводкаЦели(S).шаг.length > 20);
      assert.equal(S.мир.имя, undefined, 'выбор не выдаёт письмо задним числом');
    }
  }
  for (const цель of ЦЕЛИ) {
    const S = новая(начало); выбратьЦель(S, цель);
    assert.equal(зафиксироватьЦель(S, цель), true);
    const до = JSON.stringify(S);
    assert.equal(снятьЦель(S), false);
    assert.equal(выбратьЦель(S, ЦЕЛИ.find(id => id !== цель)), false);
    assert.equal(зафиксироватьЦель(S, 'неизвестная'), false);
    assert.equal(JSON.stringify(S), до, 'ключевое обязательство не меняется кнопкой выбора');
  }
  for (const цель of [null, ...ЦЕЛИ]) {
    const S = новая(начало, 30);
    if (цель) выбратьЦель(S, цель);
    S.мир.журналДня.push('Последнее действие тридцатого дня.');
    ночь(S);
    const T = копия(S), итог = T.мир.итогСезона;
    assert.equal(T.мир.день, 31);
    assert.deepEqual(T.мир.сезон, { номер: 1, начат: 1, день: 30, завершён: true });
    assert.equal(итог.цель, цель);
    assert.ok(итог.заголовок.length > 5);
    assert.ok(итог.текст.length > 20);
    assert.ok(T.мир.конецДня.журнал.includes('Последнее действие тридцатого дня.'));
    const до = JSON.stringify(T);
    лечьСпать(T, null);
    следующийОтрезок(T);
    потратитьОтрезок(T);
    assert.equal(JSON.stringify(T), до, 'незакрытый экран итога не пропускает следующий день');
    T.мир.конецДня = null;
    ночь(T);
    assert.deepEqual(T.мир.итогСезона, итог, 'свободная жизнь не переписывает итог');
    assert.equal(T.мир.конецДня.финал, undefined);
  }
}

// Дата кампании, день сезона и снимок итога независимы; v13 и откат мигрируют.
{
  const S = новая('наколки', 29);
  S.версия = 13; delete S.мир.сезон;
  S.история = [JSON.stringify({ ...S, история: [] })];
  const T = копия(S);
  assert.equal(T.мир.сезон.день, 29);
  assert.equal(JSON.parse(T.история[0]).мир.сезон.день, 29);
  const до = JSON.stringify(T); мигрировать(T); assert.equal(JSON.stringify(T), до);
  ночь(T); T.мир.конецДня = null; ночь(T);
  assert.equal(T.мир.сезон.день, 30);
  T.мир.конецДня = null; ночь(T);
  assert.equal(T.мир.день, 32);
  assert.equal(T.мир.сезон.номер, 1, 'сезон 2 не запускается без содержания');
  assert.equal(T.мир.сезон.день, 30);
}

// Старый сейв за днём 30 не обходит итог навсегда и не выдаёт восстановление за историю.
{
  const S = новая('семья', 35); S.версия = 13; delete S.мир.сезон;
  const T = копия(S); ночь(T);
  assert.equal(T.мир.итогСезона.восстановленНаДне, 35);
  assert.match(T.мир.итогСезона.строки.join(' '), /не снимок прошлого/);
}

// Пропуск подтверждения объяснён сразу, есть запасной путь, а не совет сделать невозможное.
for (const { id: начало } of НАЧАЛА) {
  const S = новая(начало, 15); выбратьЦель(S, 'уехать');
  применитьУехать(S, 'слух'); ночь(S);
  assert.match(S.мир.конецДня.причины.join(' '), /последний день записи/);
  S.мир.конецДня = null;
  применитьУехать(S, 'рейс-береговой'); применитьУехать(S, 'книга');
  S.мир.день = 21; ночь(S);
  assert.equal(уехать(S).исход, 'не-подтвердил');
  assert.match(следующийШагУехать(S), /Локи/);
  assert.doesNotMatch(следующийШагУехать(S), /^Подтверди место/);
  S.мир.конецДня = null; S.мир.день = 25; S.мир.флаги.push('проход_локи');
  assert.equal(применитьУехать(S, 'локи'), true);
  S.мир.день = 28; S.мир.отрезок = 'день';
  assert.equal(применитьУехать(S, 'посадка'), true);
  const T = копия(S), до = JSON.stringify(T);
  assert.equal(состояниеСезона(T).день, 28);
  лечьСпать(T, null); следующийОтрезок(T); потратитьОтрезок(T);
  assert.equal(JSON.stringify(T), до, 'ранний отъезд нельзя продолжить вызовом времени');
}

// Отказ отличается от жизни без выбранной цели; смена не стирает долги и обещания.
for (const { id: начало } of НАЧАЛА) {
  const S = новая(начало);
  S.мир.долги.push({ кому: 'Орш', сумма: 36 });
  взятьОбязательство(S, { id: 'приёмка-обещание', название: 'Ранее данное слово', срок: { день: 30, отрезок: 'ночь', граница: 'конец' } });
  выбратьЦель(S, 'угол');
  assert.equal(снятьЦель(S), true);
  assert.equal(выбратьЦель(S, 'имя'), true);
  assert.equal(S.мир.долги[0].сумма, 36);
  assert.equal(S.мир.обязательства['приёмка-обещание'].статус, 'активно');
  assert.equal(снятьЦель(S), true);
  S.мир.день = 30; ночь(S);
  assert.equal(S.мир.итогСезона.исход, 'отказ-от-цели');
  assert.match(S.мир.итогСезона.строки.join(' '), /Свой угол.*Имя/);
}

// Последний ночной визит остаётся в дне 30 до выхода; итог включает действие.
{
  const S = новая('бумаги', 30);
  S.мир.район = 'доки'; S.мир.отрезок = 'ночь';
  войти(S, 'ночлежка');
  assert.equal(S.мир.день, 30);
  assert.equal(S.мир.итогСезона, undefined);
  S.мир.журналДня.push('Дело завершено в последнем ночном визите.');
  const T = копия(S);
  вернутьсяВГород(T);
  assert.equal(T.мир.день, 31);
  assert.ok(T.мир.конецДня.финал);
  assert.ok(T.мир.конецДня.журнал.includes('Дело завершено в последнем ночном визите.'));
  const до = JSON.stringify(T); вернутьсяВГород(T);
  assert.equal(JSON.stringify(T), до, 'повторный выход не закрывает сутки снова');
}

console.log('Шаг9 приёмка: три начала, ранний/поздний выбор, отказ, смена без списания долгов, последний визит и неизменный финал — OK');
