// Одна шкала времени (Р19, решение автора 12.11): правила — Документы/Материалы/Концепты/Время_одна_шкала_12_11/.
// В отрезке 6 делений; вход в место даром; дорога 1–3; смена 6; сон с вечера; без сил отрезок 4 и работы нет.
import assert from 'node:assert/strict';
import { новоеСостояние, мигрировать } from '../Движок/состояние.js';
import { потратить, следующийОтрезок, лечьСпать, осталось, ёмкость, ценаВремени, ДЕЛЕНИЙ } from '../Движок/время.js';
import { доступныеДействия } from '../Движок/действия.js';
import { войти, вернутьсяВГород, действияСцены, времяИдёт, применитьВСцене } from '../Движок/разговор.js';
import { доЗакрытия, открытоСейчас } from '../Движок/часы-места.js';
import { дорога, ДОРОГИ } from '../Данные/дороги.js';
import { РАЙОНЫ } from '../Данные/районы.js';
import { ЖИЛЬЁ } from '../Данные/жильё.js';
import { положить } from '../Движок/вещи.js';

const нов = (начало = 'семья', сид = 7) => новоеСостояние(начало, сид);
const действие = (S, id) => доступныеДействия(S).find(д => д.id === id);

// 1. Шкала: 6 делений в отрезке, граница отрезка, рассвет без сна.
{
  const S = нов();
  assert.equal(S.мир.деление, 0);
  assert.equal(ёмкость(S), ДЕЛЕНИЙ);
  потратить(S, 5);
  assert.deepEqual([S.мир.отрезок, S.мир.деление], ['утро', 5]);
  потратить(S, 1);
  assert.deepEqual([S.мир.отрезок, S.мир.деление], ['день', 0], 'шестое деление — новый отрезок');
  потратить(S, 6 * 3 - 1);
  assert.deepEqual([S.мир.отрезок, S.мир.деление], ['ночь', 5]);
  потратить(S, 1);
  assert.equal(S.мир.конецДня?.выспался, false, 'рассвет без сна закрывает сутки');
  assert.equal(S.мир.день, 2); assert.equal(S.мир.деление, 0);
}

// 2. Без сил отрезок короче: 4 деления, а цена действий та же.
{
  const S = нов(); S.герой.тело.отдых = 0;
  assert.equal(ёмкость(S), 4);
  потратить(S, 4);
  assert.equal(S.мир.отрезок, 'день');
  assert.ok(S.мир.журналДня.includes('Отключился на ходу: цел −1'), 'раз в день без сил — отключка');
  потратить(S, 1);
  assert.equal(S.мир.журналДня.filter(x => x.startsWith('Отключился')).length, 1, 'отключка не повторяется за день');
}

// 3. Дороги: таблица на все пары, 1–3, симметрично; кнопка подписана ромбами и тратит ровно столько.
{
  const ид = РАЙОНЫ.map(р => р.id);
  assert.equal(Object.keys(ДОРОГИ).length, ид.length * (ид.length - 1) / 2);
  for (const а of ид) for (const б of ид) if (а !== б) {
    assert.ok([1, 2, 3].includes(дорога(а, б)), `${а}→${б}`);
    assert.equal(дорога(а, б), дорога(б, а));
  }
  const S = нов(); S.мир.район = 'доки';
  const к = действие(S, 'переход:жилые-улицы');
  assert.equal(к.подпись, '◆◆◆');
  к.выполнить(S);
  assert.deepEqual([S.мир.район, S.мир.отрезок, S.мир.деление], ['жилые-улицы', 'утро', 3]);
  // Из Жилых улиц утром можно успеть к разгрузке (раньше дорога съедала утро).
  S.мир.район = 'жилые-улицы'; S.мир.деление = 0;
  действие(S, 'переход:доки').выполнить(S);
  assert.ok(действие(S, 'работа:разгрузка')?.можно, 'утренняя разгрузка после дороги из Жилых улиц');
}

// 4. Вход в место даром; вопрос — деление; место закрывается в свой час; «Синий час» — до середины ночи.
{
  const S = нов(); S.мир.район = 'доки'; S.мир.отрезок = 'вечер';
  войти(S, 'таверна');
  assert.equal(S.мир.деление, 0, 'вход не тратит времени');
  assert.equal(доЗакрытия(S), 6);
  времяИдёт(S, 2);
  assert.deepEqual([S.мир.отрезок, S.мир.деление], ['вечер', 2], 'время в месте — время мира');
  времяИдёт(S, 10);
  assert.ok(S.сцена.времяВышло, 'таверна закрылась');
  assert.deepEqual([S.мир.отрезок, S.мир.деление], ['ночь', 0], 'после закрытия часы не бегут');
  вернутьсяВГород(S);
  assert.equal(S.мир.день, 1, 'визит не съедает ночь');

  const Б = нов(); Б.мир.район = 'торговый'; Б.мир.отрезок = 'вечер';
  assert.ok(открытоСейчас(Б, 'синий-час'));
  Б.мир.отрезок = 'ночь'; Б.мир.деление = 2;
  assert.ok(открытоСейчас(Б, 'синий-час'), 'дом открыт до середины ночи');
  Б.мир.деление = 3;
  assert.equal(открытоСейчас(Б, 'синий-час'), false, 'с середины ночи дом закрыт');
  assert.equal(действие(Б, 'место:синий-час').можно, false);
  Б.мир.отрезок = 'вечер'; Б.мир.деление = 0; Б.герой.кошель = 100;
  войти(Б, 'синий-час');
  assert.equal(доЗакрытия(Б), 9, 'вечер 6 + полночи 3');
}

// 5. Ночная смена до рассвета, начать можно в первые три деления; без сил работы нет.
{
  const S = нов(); S.мир.район = 'доки'; S.мир.отрезок = 'ночь';
  S.герой.ремёсла.кулак = { ступень: 'умеешь', зарубки: 0 };
  const о = действие(S, 'работа:охрана');
  assert.ok(о?.можно, 'охрана в таверне ночью');
  assert.match(о.подпись, /до утра/);
  S.мир.деление = 3;
  const поздно = действие(S, 'работа:охрана');
  assert.equal(поздно.можно, false); assert.match(поздно.почему, /уже идёт/);
  S.мир.деление = 0; действие(S, 'работа:охрана').выполнить(S);
  for (let i = 0; i < 8 && S.мир.смена; i++) (доступныеДействия(S).find(x => x.можно) ?? доступныеДействия(S)[0]).выполнить(S);
  assert.equal(S.мир.конецДня?.выспался, false, 'ночная смена — до рассвета, без сна');
  const У = нов(); У.мир.район = 'доки'; У.герой.тело.отдых = 0;
  const р = действие(У, 'работа:разгрузка');
  assert.equal(р.можно, false); assert.match(р.почему, /нет сил/);
}

// 6. Сон с вечера; поздно лёг — отдых на 1 меньше.
{
  const S = нов(); S.мир.район = 'доки'; S.мир.отрезок = 'вечер';
  assert.ok(действие(S, 'сон:койка'), 'лечь можно с вечера');
  const койка = ЖИЛЬЁ.find(x => x.id === 'койка');
  const Р = нов(); Р.мир.отрезок = 'ночь'; Р.мир.деление = 1; Р.герой.тело.отдых = 1;
  лечьСпать(Р, койка);
  assert.equal(Р.герой.тело.отдых, 1 + койка.отдых, 'рано лёг — полный сон');
  const П = нов(); П.мир.отрезок = 'ночь'; П.мир.деление = 4; П.герой.тело.отдых = 1;
  лечьСпать(П, койка);
  assert.equal(П.герой.тело.отдых, 1 + койка.отдых - 1, 'поздно лёг — на 1 меньше');
  assert.ok(П.мир.конецДня.журнал.includes('Лёг поздно: силы на 1 меньше'));
}

// 7. «Домой» вечером — отдельная кнопка; ночью дорога в свой район — домой и сон.
{
  const S = нов(); S.герой.жильё = { id: 'вдова', оплачено_по: 9 }; S.мир.район = 'торговый'; S.мир.отрезок = 'вечер';
  assert.equal(действие(S, 'переход:жилые-улицы').подпись, '◆', 'вечером дорога — дорога');
  const д = действие(S, 'домой');
  assert.match(д.подпись, /домой, сон у вдовы · ◆/);
  д.выполнить(S);
  assert.equal(S.мир.конецДня?.сон, 'Комната у вдовы');
  assert.equal(S.мир.район, 'жилые-улицы');
}

// 8. Дождь — по делениям на улице; груз — только в дороге.
{
  const S = нов(); S.мир.погода = 'дождь';
  потратить(S, 3, { улица: true });
  assert.notEqual(S.мир.промокалДень, S.мир.день, 'три деления под дождём — ещё сухо');
  потратить(S, 1, { улица: true });
  assert.equal(S.мир.промокалДень, S.мир.день, 'четвёртое — промок');
  const Г = нов(); положить(Г, 'груз'); const было = Г.герой.тело.отдых;
  следующийОтрезок(Г);
  assert.equal(Г.герой.тело.отдых, было, 'с тюком ждать не тяжело');
  потратить(Г, 3, { дорога: true });
  assert.equal(Г.герой.тело.отдых, было - 1, 'три деления дороги с тюком — отдых −1');
}

// 9. Подписи времени: ромбы и «до/кончится».
{
  const S = нов();
  assert.equal(ценаВремени(S, 0), 'даром');
  assert.equal(ценаВремени(S, 2), '◆◆');
  assert.equal(ценаВремени(S, 6), '◆◆◆◆◆◆ · до дня');
  S.мир.деление = 3;
  assert.equal(ценаВремени(S, 6), '◆◆◆◆◆◆ · кончится днём');
  assert.equal(ценаВремени(S, 12), 'кончится вечером');
  assert.equal(осталось(S), 3);
}

// 10. Старое сохранение v14 со сценой: отрезок списан авансом — сцена догоняет мир, плата не повторяется.
{
  const S = нов(); S.мир.район = 'доки'; S.мир.отрезок = 'вечер';
  войти(S, 'таверна');
  const старое = JSON.parse(JSON.stringify(S));
  старое.версия = 14; delete старое.мир.деление; старое.мир.отрезок = 'ночь'; старое.сцена.отрезок = 'вечер';
  const X = мигрировать(старое);
  assert.equal(X.версия, 16); assert.equal(X.мир.деление, 0); assert.equal(X.сцена.отрезок, 'ночь');
  assert.ok(действияСцены(X).length, 'сцена жива после миграции');
}

// 11. Шкалы героя (Р20): раны, боли, жажды и счётчиков привычек нет; напряжение поднимает тяжёлая сцена.
