  const старое = JSON.parse(JSON.stringify(S)); старое.версия = 15; старое.герой.рана = 1; старое.герой.привычкаТабак = 2;
  const X = мигрировать(старое);
  assert.equal(X.герой.рана, undefined); assert.equal(X.герой.привычкаТабак, undefined);
