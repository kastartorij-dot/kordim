// Шаг 11, приёмка (пакет 6): три линии в одной партии. Запуск: node Игры/Порт/Тесты/шаг11-приёмка.mjs [--report]
// Кнопки — настоящие кнопки движка; после каждого нажатия и каждой ночи партия сохраняется и загружается,
// игра продолжается с загруженного состояния (Тесты/утилиты/линии.js, включитьСохранение).
// Допущение, записанное в отчёте: деньги и тело перед визитом подставляются (≥200 гр., тело 3/3/3/3) —
// экономика сезона — задача шага 13 (PR001-17); оплата входа и комнаты при этом списывается по-настоящему.
// Проверяется PR001-16: разные поступки — разные итоги; деньги — только доступ; повтор вопроса ничего не двигает;
// реакции на несколько связей последовательны и зависят от человека.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { новоеСостояние } from '../Движок/состояние.js';
import { итогСезона } from '../Движок/цели.js';
import { сводкаЖурнала } from '../Движок/сводка.js';
import { есть, нажать, конецДня, доДня, вХаб, ветка, вечерДома, рынок, нажатьТекст, включитьСохранение, сколькоЗагрузок } from './утилиты/линии.js';

включитьСохранение();
const отчёт = process.argv.includes('--report');
const журнал = [];
const заметка = (S, т) => журнал.push(`День ${S.мир.день}: ${т}`);
const с = (S, кто) => S.мир.связи?.[кто];
const дов = (S, кто) => S.мир.люди?.[кто]?.распол ?? 0;
const сказала = (S, re) => (S.сцена?.диалог?.лента ?? []).some(з => re.test(з.т ?? ''));

const комнатаФреи = S => вечерДома(S, 'freya', ['zal', 'lestnica', 'komnata_frei']);
const площадка = S => вечерДома(S, 'freya', ['zal', 'lestnica', 'ploshchadka']);
const комнатаНии = S => вечерДома(S, 'niya', ['zal', 'lestnica', 'komnata_nii']);
const прилавок = (S, отрезок) => { рынок(S, отрезок, 'еда-рынка'); нажать(S, 'заговорить:tava'); вХаб(S); };
const лотки = S => { рынок(S, 'утро', 'еда-рынка'); нажать(S, 'заговорить:niya'); вХаб(S); };
const ряд = S => { рынок(S, 'день', 'ветошь-рынка'); нажать(S, 'заговорить:freya'); вХаб(S); };

// ── партия 1: три линии одновременно ────────────────────────────────────
const S = новоеСостояние('семья', 11);
S.мир.день = 3; S.мир.сезон.день = 3; // день кампании и день сезона совпадают в первом сезоне
прилавок(S, 'день');
ветка(S, 'дело', 'помочь'); вХаб(S);
комнатаФреи(S);
assert.equal(S.герой.кошель, 200 - 80, 'вход 20 и комната 60 списаны');
ветка(S, 'знакомство', 'молчать', 'ясно');
ветка(S, 'сиб', 'в_ответ', 'слово', 'ясно');
нажать(S, 'ветка:сиб');
assert.equal(дов(S, 'freya'), 2, 'повтор пройденного вопроса не даёт доверия');
ветка(S, 'день', 'прийти', 'ясно');
заметка(S, 'Тава — помощь с корзиной (доверие 1). Фрея — оплаченный вечер: молчание и слово о Сибе (доверие 2); повтор «Сиба» ничего не дал; приглашение днём.');

конецДня(S); ряд(S);
ветка(S, 'нитки', 'своя', 'дальше', 'ясно');
прилавок(S, 'день');
assert.equal(с(S, 'tava').этап, 'встречи');
ветка(S, 'ящик', 'найду', 'ясно');
рынок(S, 'день', 'ворота-рынка'); нажатьТекст(S, 'Спросить у весов про ящик Тавы');
прилавок(S, 'день');
ветка(S, 'ящик_найден', 'вечер', 'ясно');
прилавок(S, 'вечер');
ветка(S, 'ремни', 'держать', 'дальше', 'ясно');
assert.equal(с(S, 'freya').этап, 'вне-работы'); assert.equal(с(S, 'tava').этап, 'вне-работы');
assert.equal(дов(S, 'freya'), 3); assert.equal(дов(S, 'tava'), 3);
заметка(S, 'Фрея — нитка «для своей» в ряду ветоши. Тава — ящик найден у весов Браса в срок, вечер у прилавка.');

конецДня(S); комнатаНии(S);
ветка(S, 'порог', 'тишина', 'ясно'); ветка(S, 'границы', 'принимаю', 'ясно');
ветка(S, 'утро', 'рядом', 'ясно');
конецДня(S); лотки(S);
ветка(S, 'завтрак', 'молча', 'дальше', 'ясно');
assert.equal(с(S, 'niya').этап, 'вне-работы');
заметка(S, 'Ния — один оплаченный вечер (тишина, её «нет» принято, приглашение), затем завтрак у лотков молча.');

площадка(S);
ветка(S, 'поворот', 'тоже', 'ясно');
конецДня(S); площадка(S);
ветка(S, 'решение', 'да_принять', 'ясно');
assert.equal(с(S, 'freya').статус, 'вместе');
заметка(S, 'Фрея — поворот и её «да» на следующий день, на площадке у окна без оплаченной комнаты.');

// Ния и Тава узнают о Фрее — каждая по-своему.
конецДня(S); лотки(S);
нажать(S, 'ветка:поворот');
assert.ok(сказала(S, /бываешь у Фреи/), 'Ния называет другую связь по имени');
нажать(S, 'вариант:поворот:прямо'); нажать(S, 'вариант:поворот:ясно');
прилавок(S, 'вечер');
нажать(S, 'ветка:поворот');
assert.ok(сказала(S, /ты не один/), 'Тава спрашивает о другой связи');
нажать(S, 'вариант:поворот:тоже'); нажать(S, 'вариант:поворот:ясно');
конецДня(S); лотки(S);
ветка(S, 'решение', 'да_принять', 'ясно');
assert.equal(с(S, 'niya').решение.что, 'да', 'Ния не против другой связи, пока не врут');
прилавок(S, 'вечер');
ветка(S, 'решение', 'принять', 'ясно');
assert.equal(с(S, 'tava').решение.что, 'позже', 'Тава не делит: «не сейчас» при тех же числах');
assert.equal(дов(S, 'tava'), 3);
площадка(S);
нажать(S, 'ветка:после');
assert.ok(сказала(S, /не только у меня/), 'Фрея видит вторую связь и спрашивает о честности');
нажать(S, 'вариант:после:окно'); нажать(S, 'вариант:после:ясно');
заметка(S, 'Ния — «да», назвав Фрею. Тава — «не сейчас», пока он не один. Фрея спрашивает только о честности.');

const журналЛичное = сводкаЖурнала(S).связи.map(x => `${x.имя}: ${x.текст} (${x.числа})`);
assert.equal(журналЛичное.length, 3);
const послеРешений = JSON.stringify({ ...S, сцена: null }); // для просмотра экрана: город, день решений

// Дальше герой видит Фрею каждые три дня, к Нии не приходит: отсутствие честно ведёт к паузе и расставанию.
const деньРешения = S.мир.день;
for (let д = деньРешения + 3; д <= 29; д += 3) { доДня(S, д); площадка(S); ветка(S, 'после', 'окно', 'ясно'); }
доДня(S, 30); конецДня(S);
const итог = итогСезона(S).строки;
for (const re of [/Фрея: вы вместе/, /Тава ответила «не сейчас»/, /Ния: (вы давно не виделись|вы расстались)/])
  assert.ok(итог.some(x => re.test(x)), `${re}: ${итог.join(' | ')}`);
заметка(S, 'Итог сезона: ' + итог.filter(x => /Фрея|Ния|Тава/.test(x)).join(' '));

// ── партия 2: те же люди, только деньги ─────────────────────────────────
const Q = новоеСостояние('семья', 11);
Q.мир.день = 3; Q.мир.сезон.день = 3; // день кампании и день сезона совпадают в первом сезоне
for (let i = 0; i < 3; i++) {
  комнатаФреи(Q); нажать(Q, 'остаться');
  assert.ok(['freya_1', 'freya_2'].includes(Q.сцена.нужнаСцена), 'оплаченная сцена, не личная');
  конецДня(Q);
}
assert.equal(с(Q, 'freya').доступ, 3);
assert.equal(дов(Q, 'freya'), 0, 'три оплаченных вечера не дали доверия');
комнатаФреи(Q);
assert.ok(!есть(Q, 'ветка:день') && !есть(Q, 'ветка:поворот'), 'без поступков Фрея не зовёт днём');
доДня(Q, 30); конецДня(Q);
const итогQ = итогСезона(Q).строки.filter(x => /Фрея/.test(x));
assert.ok(итогQ.some(x => /оплаченных вечеров — 3\. Это был доступ, а не близость/.test(x)), итогQ.join(' | '));
журнал.push(`Только деньги: три оплаченных вечера, доступ ${с(Q, 'freya').доступ}, доверие ${дов(Q, 'freya')}; итог: ${итогQ.join(' ')}`);

console.log(журнал.map(x => '· ' + x).join('\n'));
console.log('Журнал «Личное» после решений: ' + журналЛичное.join(' | '));
console.log(`Сохранений и загрузок: ${сколькоЗагрузок()}`);
if (отчёт) {
  const каталог = 'Документы/Разработка/Шаг_11_Личные_отношения/Приёмка_25_10_2026';
  fs.mkdirSync(каталог, { recursive: true });
  fs.writeFileSync(`${каталог}/три-линии-сохранение.json`, JSON.stringify(S));
  fs.writeFileSync(`${каталог}/после-решений-сохранение.json`, послеРешений);
  fs.writeFileSync(`${каталог}/трасса.md`, ['# Трасса приёмки шага 11', '', 'Вывод `node Тесты/шаг11-приёмка.mjs --report`.', '', ...журнал.map(x => '- ' + x), '', '## Журнал «Личное» после решений', '', ...журналЛичное.map(x => '- ' + x), '', `Сохранений и загрузок: ${сколькоЗагрузок()}.`, ''].join('\n'));
}
console.log('шаг 11 (приёмка трёх линий): все проверки пройдены');
