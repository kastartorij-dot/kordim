import { РЕЕСТР } from '../Данные/темы.js';

const кнопка = (S, текст) => действияСцены(S).find(а => а.текст === текст || а.текст.startsWith(текст));
const нажать = (S, текст) => { const а = кнопка(S, текст); assert.ok(а, `нет кнопки «${текст}»`); assert.equal(а.можно, true, `«${текст}» недоступна: ${а.почему}`); а.выполнить(S); return а; };
const пойти = (S, комната) => действияСцены(S).find(а => а.id === `пойти:${комната}`).выполнить(S);
function вРынке(день, отрезок, кошель = 100, начало = 'семья') {
  const S = новоеСостояние(начало, 7);
  S.мир.район = 'торговый'; S.мир.день = день; S.мир.отрезок = отрезок; S.герой.кошель = кошель;
  войти(S, 'рынок');
  return S;
}
const распол = (S, кто) => S.мир.люди[кто]?.распол ?? 0;

// ── торг (шаг 12): игра начинается даром, на экране только её ходы, один довод за раунд, пол отрезка
const ход = (S, id) => { const а = действияСцены(S).find(х => х.id === 'игра:торг:' + id); assert.ok(а, 'нет хода ' + id + ': ' + действияСцены(S).map(х => х.id).join(' | ')); assert.equal(а.можно, true, id + ' недоступен: ' + а.почему); а.выполнить(S); };
const есть = (S, id) => действияСцены(S).find(х => х.id === 'игра:торг:' + id);
{
  const S = вРынке(2, 'день');
  пойти(S, 'ветошь-рынка');
  assert.equal(максРаундов(S), 2);
  assert.equal(цена(S, 'кафтан'), 15, 'первая цена');
  assert.match(кнопка(S, 'Торговаться за кафтан').подпись, /сейчас 15 гр\./, 'цена видна на кнопке');
  const х0 = S.сцена.ходы;
  нажать(S, 'Торговаться за кафтан');
  assert.equal(S.сцена.ходы, х0, 'начать торг даром');
  assert.ok(действияСцены(S).every(а => а.id.startsWith('игра:торг:')), 'пока идёт торг — только его ходы');
  assert.deepEqual(видСцены(S).игра.видно, ТОРГ.кафтан.видно, 'всё нужное видно на экране');
  assert.equal(есть(S, 'довод:вечер'), undefined, 'днём довода о закрытии ряда нет');
  ход(S, 'довод:локоть');
  assert.equal(цена(S, 'кафтан'), 13);
  assert.match(видСцены(S).игра.реплика, /13 гр\./, 'реплика называет новую цену');
  assert.equal(S.история.length, 0, 'сказанного не воротишь: «назад» после довода нет');
  ход(S, 'довод:сразу');
  assert.equal(цена(S, 'кафтан'), 12, 'днём пол — честная цена');
  assert.equal(действияСцены(S).filter(а => а.id.includes(':довод:')).length, 0, 'раунды кончились');
  assert.ok(есть(S, 'давить'), 'давить можно');
  // покупка по торгу: цена списана, вещь выдана, Пин доволен, ушёл ровно один ход
  const до = S.герой.кошель;
  ход(S, 'купить');
  assert.equal(до - S.герой.кошель, 12);
  assert.equal(естьВещь(S, 'кафтан'), true);
  assert.equal(распол(S, 'pin'), 1, 'торговался по делу — расположение +1');
  assert.equal(S.сцена.ходы, х0 + 1, 'итог торга — один ход');
  assert.equal(S.сцена.игра, null);
  assert.ok(S.мир.журналДня.some(с => с === 'Торг: Залатанный кафтан за 12 гр. (просили 15)'));
  assert.equal(кнопка(S, 'Торговаться за кафтан'), undefined, 'второй кафтан в тот же день не продаётся');
  assert.ok(кнопка(S, 'Торговаться за плащ'), 'плащ — отдельный лот');
}

// ── вечером раундов три, довод о закрытии ряда и пол ниже
{
  const S = вРынке(2, 'вечер');
  пойти(S, 'ветошь-рынка');
  assert.equal(максРаундов(S), 3);
  нажать(S, 'Торговаться за кафтан');
  for (const д of ['локоть', 'вечер', 'сразу']) ход(S, 'довод:' + д);
  assert.equal(цена(S, 'кафтан'), 11, 'вечером пол на 1 ниже дневного');
}

// ── день расчёта: на раунд меньше
