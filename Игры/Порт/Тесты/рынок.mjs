// ── отказ: тот же день помнит сказанное; новый день — торг заново
{
  const S = вРынке(2, 'день');
  пойти(S, 'ветошь-рынка');
  нажать(S, 'Торговаться за кафтан');
  const х0 = S.сцена.ходы;
  ход(S, 'довод:локоть'); ход(S, 'уйти');
  assert.equal(S.сцена.ходы, х0 + 1, 'отказ после торга — тоже ход');
  assert.equal(естьВещь(S, 'кафтан'), false);
  нажать(S, 'Торговаться за кафтан');
  assert.equal(цена(S, 'кафтан'), 13, 'вернулся в тот же день — цена та же');
  assert.equal(есть(S, 'довод:локоть'), undefined, 'сказанное второй раз не скажешь');
  const х1 = S.сцена.ходы; ход(S, 'уйти');
  вернутьсяВГород(S);
  S.мир.день = 3; S.мир.отрезок = 'день';
  войти(S, 'рынок'); пойти(S, 'ветошь-рынка');
  assert.equal(цена(S, 'кафтан'), 15, 'новый день — торг заново');
  assert.ok(х1 >= х0);
}

// ── ремесло подсказывает: «умеешь» — словами, «набил руку» — неверный довод отпадает
