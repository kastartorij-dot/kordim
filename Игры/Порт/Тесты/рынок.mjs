import assert from 'node:assert/strict';
import { новоеСостояние } from '../Движок/состояние.js';
import { войти, действияСцены, вернутьсяВГород, видСцены } from '../Движок/разговор.js';
import { цена, максРаундов } from '../Движок/торг.js';
import { естьВещь, привестиВещи } from '../Движок/вещи.js';
import { вернутьПрокат } from '../Движок/хозяйство.js';
