// ── неверные доводы: первый — предупреждение, второй — перегиб, расположение −1 один раз
{
  const S = вРынке(2, 'вечер');
  пойти(S, 'ветошь-рынка');
  нажать(S, 'Торговаться за кафтан');
  ход(S, 'довод:пуговицы');
  assert.equal(цена(S, 'кафтан'), 15, 'неверный довод не сбавляет');
  assert.equal(видСцены(S).игра.терпение, 1);
  assert.match(видСцены(S).игра.реплика, /Ещё один такой довод/);
  assert.equal(распол(S, 'pin'), 0);
  ход(S, 'довод:ярлык');
  assert.equal(видСцены(S).игра.перегиб, true);
  assert.equal(распол(S, 'pin'), -1);
  assert.equal(действияСцены(S).filter(а => а.id.includes(':довод:')).length, 0, 'после перегиба доводов нет, хотя раунд остался');
  assert.equal(есть(S, 'давить'), undefined, 'повторно давить нельзя');
  ход(S, 'купить');
  assert.equal(распол(S, 'pin'), -1, 'после перегиба покупка расположения не меняет');
}

// ── давил сверх меры после последнего раунда: −1, цена не падает
