// Шаг 8, Рынок: торг, прокат на вечер, последний колокол, проверка гирь, день расчёта, темы чёрного ряда.
// node Порт/тест/рынок.mjs
import assert from 'node:assert/strict';
import { новоеСостояние } from '../Движок/состояние.js';
import { войти, действияСцены, вернутьсяВГород } from '../Движок/разговор.js';
import { цена, максРаундов } from '../Движок/торг.js';
import { естьВещь, привестиВещи } from '../Движок/вещи.js';
import { вернутьПрокат } from '../Движок/хозяйство.js';
import { видПодарка } from '../Движок/подарки.js';
import { ТОРГ } from '../Данные/торг.js';
import { РЕЕСТР } from '../Данные/темы.js';

const кнопка = (S, текст) => действияСцены(S).find(а => а.текст === текст || а.текст.startsWith(текст));
const нажать = (S, текст) => { const а = кнопка(S, текст); assert.ok(а, `нет кнопки «${текст}»`); assert.equal(а.можно, true, `«${текст}» недоступна: ${а.почему}`); а.выполнить(S); return а; };
const пойти = (S, комната) => действияСцены(S).find(а => а.id === `пойти:${комната}`).выполнить(S);
function вРынке(день, отрезок, кошель = 100, начало = 'семья') {
  const S = новоеСостояние(начало, 7);
  S.мир.район = 'торговый'; S.мир.день = день; S.мир.отрезок = отрезок; S.герой.кошель = кошель;
  войти(S, 'рынок');
  return S;
}
const распол = (S, кто) => S.мир.люди[кто]?.распол ?? 0;

// ── торг: цена по раундам, пол отрезка
{
  const S = вРынке(2, 'день');
  пойти(S, 'ветошь-рынка');
  assert.equal(максРаундов(S), 2);
  assert.equal(цена(S, 'кафтан'), 15, 'первая цена');
  assert.match(кнопка(S, 'Купить кафтан').текст, /15 гр\./);
  assert.match(кнопка(S, 'Купить кафтан').подпись, /15 гр\./, 'цена видна на кнопке');
  нажать(S, 'Поторговаться за кафтан');
  assert.equal(цена(S, 'кафтан'), 13);
  assert.match(S.сцена.реплика, /13 гр\./, 'реплика называет новую цену');
  нажать(S, 'Поторговаться за кафтан');
  assert.equal(цена(S, 'кафтан'), 12, 'днём пол — честная цена');
  assert.equal(кнопка(S, 'Поторговаться за кафтан'), undefined, 'раунды кончились');
  assert.ok(кнопка(S, 'Давить на цену дальше'), 'давить можно');
  // покупка по торгу: цена списана, вещь выдана, Пин доволен
  const до = S.герой.кошель;
  нажать(S, 'Купить кафтан');
  assert.equal(до - S.герой.кошель, 12);
  assert.equal(естьВещь(S, 'кафтан'), true);
  assert.equal(распол(S, 'pin'), 1, 'торговался — расположение +1');
  assert.equal(кнопка(S, 'Купить кафтан'), undefined, 'второй кафтан в тот же день не продаётся');
}

// ── вечером раундов три и пол ниже
{
  const S = вРынке(2, 'вечер');
  пойти(S, 'ветошь-рынка');
  assert.equal(максРаундов(S), 3);
  for (let i = 0; i < 3; i++) нажать(S, 'Поторговаться за кафтан');
  assert.equal(цена(S, 'кафтан'), 11, 'вечером пол на 1 ниже дневного');
}

// ── день расчёта: на раунд меньше
{
  const S = вРынке(7, 'день');
  пойти(S, 'ветошь-рынка');
  assert.equal(максРаундов(S), 1);
  нажать(S, 'Поторговаться за кафтан');
  assert.equal(цена(S, 'кафтан'), 13);
  assert.equal(кнопка(S, 'Поторговаться за кафтан'), undefined);
  const S2 = вРынке(7, 'вечер');
  assert.equal(максРаундов(S2), 2, 'вечером расчётного дня два раунда');
}

// ── не торговался: первая цена и расположение −1
{
  const S = вРынке(2, 'день');
  пойти(S, 'ветошь-рынка');
  const до = S.герой.кошель;
  нажать(S, 'Купить кафтан');
  assert.equal(до - S.герой.кошель, 15);
  assert.equal(распол(S, 'pin'), -1, 'Пин презирает тех, кто не торгуется');
}

// ── давил сверх меры: расположение −1 один раз, цена не падает
{
  const S = вРынке(2, 'день');
  пойти(S, 'ветошь-рынка');
  нажать(S, 'Поторговаться за кафтан'); нажать(S, 'Поторговаться за кафтан');
  нажать(S, 'Давить на цену дальше');
  assert.equal(распол(S, 'pin'), -1);
  assert.equal(цена(S, 'кафтан'), 12);
  assert.equal(кнопка(S, 'Давить на цену дальше'), undefined, 'повторно давить нельзя');
  const до = распол(S, 'pin');
  нажать(S, 'Купить кафтан');
  assert.equal(распол(S, 'pin'), до, 'после перегиба покупка расположения не меняет');
}

// ── торг сбрасывается с новым днём и живёт в сохранении
{
  const S = вРынке(2, 'день');
  пойти(S, 'ветошь-рынка');
  нажать(S, 'Поторговаться за кафтан');
  вернутьсяВГород(S);
  S.мир.день = 3; S.мир.отрезок = 'день';
  войти(S, 'рынок'); пойти(S, 'ветошь-рынка');
  assert.equal(цена(S, 'кафтан'), 15, 'новый день — торг заново');
}

// ── слишком мало денег и нет места
{
  const S = вРынке(2, 'день', 5);
  пойти(S, 'ветошь-рынка');
  assert.equal(кнопка(S, 'Купить кафтан').можно, false);
  assert.equal(кнопка(S, 'Взять приказчичий костюм на вечер').можно, false);
}

// ── прокат на вечер: 13 гр. сразу, 10 вернуть в срок целиком, опоздание — залог пропал
{
  const S = вРынке(2, 'день', 50);
  пойти(S, 'ветошь-рынка');
  нажать(S, 'Взять приказчичий костюм на вечер');
  assert.equal(S.герой.кошель, 37, 'плата 3 и залог 10');
  const костюм = привестиВещи(S).find(x => x.тип === 'приказчичья');
  assert.ok(костюм, 'костюм в сумке');
  assert.deepEqual(костюм.состояние.прокат, { залог: 10, плата: 3, до: 3 });
  assert.equal(кнопка(S, 'Взять приказчичий костюм на вечер'), undefined, 'второй в тот же день не дают');
  вернутьсяВГород(S);
  assert.equal(вернутьПрокат(S, костюм.uid), true);
  assert.equal(S.герой.кошель, 47, 'в срок вернулся весь залог, плата осталась у Пина');
}
{
  const S = вРынке(2, 'день', 50);
  пойти(S, 'ветошь-рынка');
  нажать(S, 'Взять приказчичий костюм на вечер');
  const костюм = привестиВещи(S).find(x => x.тип === 'приказчичья');
  вернутьсяВГород(S);
  S.мир.день = 5;
  assert.equal(вернутьПрокат(S, костюм.uid), true);
  assert.equal(S.герой.кошель, 37, 'опоздал — залог остался у Пина');
}

// ── последний колокол: вечером, один раз в день, +1 сыт, ход
{
  const S = вРынке(2, 'вечер');
  S.герой.тело.сыт = 1;
  пойти(S, 'еда-рынка');
  const ходы = S.сцена.ходы;
  нажать(S, 'Дождаться последнего колокола');
  assert.equal(S.герой.тело.сыт, 2);
  assert.equal(S.сцена.ходы, ходы + 1, 'колокол тратит ход');
  assert.equal(кнопка(S, 'Дождаться последнего колокола'), undefined, 'второй раз за день нельзя');
  const Д = вРынке(2, 'день');
  пойти(Д, 'еда-рынка');
  assert.equal(кнопка(Д, 'Дождаться последнего колокола'), undefined, 'колокол только вечером');
}

// ── проверка гирь, день 11: один выбор из трёх
{
  const тишина = вРынке(11, 'день');
  нажать(тишина, 'Промолчать о гирях');
  assert.equal(тишина.мир.очки.картель, 1, 'молчание: картель +1 очко');
  assert.equal((тишина.мир.свидетельства ?? []).includes('market_weights_check'), false, 'молчание не оставляет свидетельства');
  assert.equal(кнопка(тишина, 'Подтвердить при людях'), undefined, 'выбор сделан');

  const правда = вРынке(11, 'день');
  const тень = правда.мир.тень ?? 0;
  нажать(правда, 'Подтвердить при людях');
  assert.ok(правда.мир.свидетельства.includes('market_weights_check'));
  assert.equal(правда.мир.тень, тень + 1, 'подтвердить опасно: тень +1');
  assert.equal(кнопка(правда, 'Промолчать о гирях'), undefined);

  const ночью = вРынке(11, 'ночь');
  пойти(ночью, 'ночной-ряд');
  const ходы = ночью.сцена.ходы;
  нажать(ночью, 'Помочь Брасу ночью перебрать гири');
  assert.ok(ночью.мир.свидетельства.includes('market_weights_check'));
  assert.equal(ночью.мир.тень ?? 0, 0, 'ночью без свидетелей: тени нет');
  assert.equal(ночью.сцена.ходы, ходы + 2, 'ночная сверка стоит два хода');

  const чужой = вРынке(12, 'день');
  assert.equal(кнопка(чужой, 'Промолчать о гирях'), undefined, 'вне дня 11 выбора нет');
}

// ── темы: клейма (только у грузчика), чёрный ряд и табак с юга
{
  const без = вРынке(2, 'день', 100, 'бумаги'); // у начала «бумаги» ремесло грамота, не грузчик
  assert.equal(без.герой.ремёсла.грузчик, undefined);
  действияСцены(без).find(а => а.id === 'рассмотреть:клейма').выполнить(без);
  assert.equal(без.мир.темы.includes('giri_legche'), false, 'без ремесла разницу клейм не видно');
  assert.equal(действияСцены(без).some(а => а.id === 'рассмотреть:клейма-знаток'), false);

  const груз = вРынке(2, 'день');
  груз.герой.ремёсла = { грузчик: { ступень: 'умеешь', зарубки: 0 } };
  действияСцены(груз).find(а => а.id === 'рассмотреть:клейма-знаток').выполнить(груз);
  assert.ok(груз.мир.темы.includes('giri_legche'));
  assert.equal(РЕЕСТР.giri_legche.опасна, 'картель');
}
{
  const S = вРынке(2, 'день');
  пойти(S, 'слухи-рынка');
  действияСцены(S).find(а => а.id === 'рассмотреть:мел').выполнить(S);
  assert.ok(S.мир.темы.includes('chernyj_ryad'));
  вернутьсяВГород(S);
  S.мир.день = 2; S.мир.отрезок = 'ночь';
  войти(S, 'рынок'); пойти(S, 'ночной-ряд');
  нажать(S, 'Положить три гроша на доску');
  assert.ok(S.мир.темы.includes('tabak_yug'));
  assert.equal(естьВещь(S, 'табак'), true);
  assert.equal(кнопка(S, 'Положить три гроша на доску'), undefined, 'раз в ночь');
}
{
  const S = вРынке(2, 'ночь');
  пойти(S, 'ночной-ряд');
  assert.equal(кнопка(S, 'Положить три гроша на доску'), undefined, 'без пароля окно молчит');
  S.мир.фракции.картель = 1;
  assert.ok(кнопка(S, 'Положить три гроша на доску'), 'знакомство с картелем тоже пароль');
  // у начала «бумаги» картель знает героя с первого дня: окно открыто без темы
  const Б = вРынке(2, 'ночь', 100, 'бумаги');
  пойти(Б, 'ночной-ряд');
  assert.equal(Б.мир.темы.includes('chernyj_ryad'), false);
  assert.ok(кнопка(Б, 'Положить три гроша на доску'), '«бумаги»: картель +1 с начала');
}

// ── Пин не берёт подарков
assert.equal(видПодарка('pin', { тип: 'пирог' }), 'отвергнутый');
assert.equal(видПодарка('pin', { тип: 'табак' }), 'отвергнутый');

// ── данные согласованы: цена торга не ниже пола, скидки идут в потолок
for (const [id, т] of Object.entries(ТОРГ)) {
  assert.ok(т.запрос > т.пол.день && т.пол.день > т.пол.вечер, `${id}: запрос > дневной пол > вечерний пол`);
  assert.ok(т.скидки.reduce((a, x) => a + x, 0) >= т.запрос - т.пол.вечер, `${id}: скидок хватает дойти до вечернего пола`);
}

console.log('Рынок: торг, прокат, колокол, проверка гирь, расчётный день, темы и подарки — OK');
