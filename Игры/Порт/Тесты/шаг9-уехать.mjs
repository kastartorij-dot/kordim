// Уехать: три физических пути, все платежи и необратимый ранний финал.
import assert from 'node:assert/strict';
import {новоеСостояние} from '../Движок/состояние.js';
import {МЕСТА} from '../Данные/места.js';
import {войти,действияСцены,вернутьсяВГород} from '../Движок/разговор.js';
import {выбратьЦель,итогСезона,сводкаЦели} from '../Движок/цели.js';
import {уехать,условиеУехать,закрытьДеньУехать,исходУехать} from '../Движок/уехать.js';
import {доступныеДействия} from '../Движок/действия.js';
const новая=()=>{const S=новоеСостояние('бумаги',21);S.мир.день=3;S.мир.отрезок='утро';S.мир.район='доки';S.герой.кошель=200;выбратьЦель(S,'уехать');return S;};
function сцена(S,id,день,комната){if(S.сцена)вернутьсяВГород(S);S.мир.день=день;S.мир.отрезок='утро';S.мир.район=МЕСТА.find(м=>м.id===id).район;S.мир.конецДня=null;войти(S,id);assert.ok(S.сцена);if(комната)S.сцена.комната=комната;}
const найти=(S,re)=>действияСцены(S).find(a=>re.test(a.текст));
const жми=(S,re)=>{const а=найти(S,re);assert.ok(а,'нет действия '+re);assert.ok(а.можно,а.почему);а.выполнить(S);};
function запись(S,путь='книга',рейс='24'){
 сцена(S,'контора-дорров',3);
 жми(S,/Прочесть расписание/);
 assert.match(сводкаЦели(S).шаг,/16/);
 жми(S,рейс==='24'?/Выбрать береговой/:/Выбрать поздний/);
 if(путь==='рука')S.мир.фракции.ножи=1;
 жми(S,путь==='книга'?/Записаться по книге/:/Принять поручительство/);
 assert.equal(S.мир.цели.зафиксирована,true);
}
// Официальный билет: цена60 ровно один раз; ранний финал на24, затем действий нет.
{
 const S=новая();запись(S);assert.equal(S.герой.кошель,180);
 assert.equal(найти(S,/Записаться по книге/),undefined);
 сцена(S,'контора-дорров',10);жми(S,/Подтвердить место/);
 сцена(S,'контора-дорров',17);жми(S,/держаться раннего/);жми(S,/Внести остаток/);
 assert.equal(S.герой.кошель,140);assert.equal(найти(S,/Внести остаток/),undefined);
 сцена(S,'выход-к-судам',24);жми(S,/Оглянуться на берег/);жми(S,/Взойти на борт/);
 assert.equal(S.мир.день,24);assert.equal(S.мир.кампанияЗавершена,true);
 assert.equal(S.сцена,null);assert.equal(S.мир.конецДня.отъезд,true);
 assert.equal(S.мир.итогСезона.исход,'по-книге');
 assert.equal(доступныеДействия(S).length,0);
}
// По руке: доплата не требуется, обязательство названо и не исчезает при отъезде.
{
 const S=новая();запись(S,'рука','28');assert.equal(S.герой.кошель,160);
 сцена(S,'контора-дорров',11);жми(S,/Подтвердить место/);
 сцена(S,'контора-дорров',17);жми(S,/ждать безопасный/);
 сцена(S,'выход-к-судам',28);жми(S,/Взойти на борт/);
 assert.equal(S.мир.итогСезона.исход,'по-руке');
 assert.equal(S.мир.обязательства.уехать_услуга.статус,'активно');
 assert.match(S.мир.итогСезона.строки.join(' '),/запечатанный ответ/);
}
// Смена из работы подтверждает место независимо от бумажного разговора.
{
 const S=новая();запись(S);S.мир.работы={разгрузка:{смен:1}};
 сцена(S,'причал-грузчиков',12);жми(S,/Подтвердить место уже сыгранной/);
 assert.equal(уехать(S).подтверждено,true);
}
// Последние решения на причале: остаться и отдать место — самостоятельные исходы без отъезда.
for(const [действие,исход] of [[/Остаться ради/,'остался'],[/Передать своё место/,'передал']]){
 const S=новая();запись(S);
 сцена(S,'контора-дорров',10);жми(S,/Подтвердить место/);
 сцена(S,'контора-дорров',17);жми(S,/ждать безопасный/);
 сцена(S,'выход-к-судам',28);жми(S,действие);
 assert.equal(исходУехать(S),исход);assert.equal(S.мир.кампанияЗавершена,undefined);
 assert.equal(найти(S,/Взойти на борт/),undefined);
}
// Неоплаченный остаток блокирует посадку; пропуск назван, оплаченная услуга Локи даёт запасной путь.
{
 const S=новая();запись(S);сцена(S,'контора-дорров',10);жми(S,/Подтвердить место/);
 сцена(S,'контора-дорров',17);жми(S,/держаться раннего/);
 сцена(S,'выход-к-судам',24);assert.equal(найти(S,/Взойти на борт/),undefined);
 вернутьсяВГород(S);S.мир.день=24;const и={причины:[]};закрытьДеньУехать(S,и);
 assert.equal(исходУехать(S),'сорван');assert.match(и.причины.join(' '),/35/);
 S.мир.флаги.push('проход_локи');
 сцена(S,'лачуга-локи',25);жми(S,/Уточнить проход на позднее/);
 assert.equal(уехать(S).путь,'локи');assert.equal(уехать(S).остаток,0);
 assert.equal(S.герой.кошель,180,'Локи использует ранее оплаченную услугу, не списывает золото');
 сцена(S,'выход-к-судам',28);жми(S,/Взойти на борт/);assert.equal(S.мир.итогСезона.исход,'локи');
}
// Без поручительства оплаченного Прохода у Локи нет бесплатной записи.
{
 const S=новая();сцена(S,'лачуга-локи',19);
 assert.equal(найти(S,/Уточнить проход на позднее/),undefined);
}
// Пещеры и склад предупреждают до риска, допуск реален; награда склада одноразовая.
{
 const S=новая();сцена(S,'пещеры',5);
 assert.equal(найти(S,/Запомнить тропу/).можно,true);жми(S,/Запомнить тропу/);
 assert.ok(S.мир.флаги.includes('знает_пещеры'));
 assert.equal(действияСцены(S).some(a=>a.id==='пойти:сухой-карман'),false);
 S.мир.фракции.ножи=3;
 assert.equal(действияСцены(S).some(a=>a.id==='пойти:сухой-карман'),true);
 сцена(S,'склад',6);жми(S,/Назвать поручительство/);
 assert.equal(действияСцены(S).some(a=>a.id==='пойти:внутри-склада'),true);
}
// Срок и погода имеют предупреждения; незавершённость объяснена в сезонном итоге.
{
 const S=новая();запись(S);вернутьсяВГород(S);S.мир.день=20;
 const и={причины:[]};закрытьДеньУехать(S,и);assert.match(и.причины.join(' '),/подтверждения/);
 S.мир.день=24;закрытьДеньУехать(S,и);assert.equal(итогСезона(S).исход,'не-подтвердил');
 assert.match(итогСезона(S).текст,/не подтверждены/);
}
