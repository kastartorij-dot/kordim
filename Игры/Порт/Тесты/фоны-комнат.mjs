// Таблица фонов комнат и портреты жителей: места и комнаты существуют, файлы лежат в Ресурсы/, у каждой комнаты с таблицей есть путь.
// node Игры/Порт/Тесты/фоны-комнат.mjs
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { МЕСТА } from '../Данные/места.js';
import { ФОНЫ_КОМНАТ, путиФона, подНебом, КАДРЫ_РАБОТ, кадрРаботы, ВИДЫ_РАЙОНА, видРайона, кадрНочлега, КАДРЫ_ИТОГА_СМЕНЫ } from '../Данные/фоны-комнат.js';
import { работа } from '../Данные/работы.js';

const РЕС = fileURLToPath(new URL('../Ресурсы/', import.meta.url));
const есть = п => fs.existsSync(РЕС + п);
let своих = 0, изТаблицы = 0, всего = 0;
for (const [местоId, т] of Object.entries(ФОНЫ_КОМНАТ)) {
  const м = МЕСТА.find(м => м.id === местоId);
  assert.ok(м, 'нет места ' + местоId);
  for (const [к, ф] of Object.entries(т)) {
    if (к !== '*') assert.ok(м.модуль.КОМНАТЫ[к], `${местоId}: нет комнаты ${к}`);
    if (ф !== null) assert.ok(есть(ф), `${местоId}/${к}: нет файла ${ф}`);
  }
}
for (const м of МЕСТА) for (const id of Object.keys(м.модуль.КОМНАТЫ)) {
  всего++;
  const пути = путиФона(м.id, id, м.модуль.КАРТИНКИ?.папкиФонов ?? []);
  const найден = пути.find(есть);
  if (!найден) continue;
  if (пути.indexOf(найден) < пути.length - (ФОНЫ_КОМНАТ[м.id] && (ФОНЫ_КОМНАТ[м.id][id] ?? ФОНЫ_КОМНАТ[м.id]['*']) ? 1 : 0)) своих++; else изТаблицы++;
}
assert.ok(своих + изТаблицы >= 40, `фон есть у ${своих + изТаблицы} комнат из ${всего}, ждали не меньше 40`);
// Кадры работ: работа есть, файл лежит.
for (const id of КАДРЫ_РАБОТ) { assert.ok(работа(id), 'нет работы ' + id); assert.ok(есть(кадрРаботы(id)), 'нет кадра ' + id); }
assert.equal(кадрРаботы('локи'), null);

// Быт: файлы на месте; виды района по часу и погоде; ночлег.
for (const в of ВИДЫ_РАЙОНА) assert.ok(есть(в.файл), 'нет ' + в.файл);
for (const ф of Object.values(КАДРЫ_ИТОГА_СМЕНЫ)) assert.ok(есть(ф), 'нет ' + ф);
assert.equal(видРайона('торговый', 'день', 'дождь'), 'Быт/рынок-дождь.webp');
assert.equal(видРайона('торговый', 'ночь', 'дождь'), null);
assert.equal(видРайона('трущобы', 'день', 'ясно'), null);
assert.equal(видРайона('трущобы', 'ночь', 'дождь'), 'Быт/трущобы-ночь.webp');
for (const [id, р] of [['небо', 'доки'], ['небо', 'трущобы'], ['ночлежка'], ['койка'], ['вдова']]) assert.ok(есть(кадрНочлега(id, р)), 'ночлег ' + id);
assert.equal(кадрНочлега('часовня'), null);

// Дождь только под открытым небом: площадь да, часовня и Синий час внутри — нет.
assert.ok(подНебом('Места/торговая-площадь.webp') && подНебом('Синий_Час/Фоны/krylco.webp'));
assert.ok(!подНебом('Места/порт-часовня-внутри.webp') && !подНебом('Синий_Час/Фоны/zal.webp'));

// Портрет, названный у жителя, находится в одной из папок лиц его места (.jpg ищется и как .png/.webp).
for (const м of МЕСТА) for (const [id, ч] of Object.entries(м.модуль.ЛЮДИ)) {
  if (!ч.портрет) continue;
  const варианты = [ч.портрет, ч.портрет.replace(/\.jpg$/, '.webp')];
  assert.ok((м.модуль.КАРТИНКИ?.папкиЛиц ?? []).some(п => варианты.some(ф => есть(п + ф))), `${м.id}/${id}: нет портрета ${ч.портрет}`);
}
// Таблица не прячет своих файлов: у комнаты из таблицы нет собственного <id>.webp/.jpg/.png.
for (const м of МЕСТА) for (const id of Object.keys(м.модуль.КОМНАТЫ)) {
  const т = ФОНЫ_КОМНАТ[м.id]; if (!т || !(id in т ? т[id] : т['*'])) continue;
  for (const п of м.модуль.КАРТИНКИ?.папкиФонов ?? []) for (const р of ['.webp', '.jpg', '.png'])
    assert.ok(!есть(п + id + р), `${м.id}/${id}: свой файл ${п + id + р} перекрыт таблицей`);
}
console.log(`фоны-комнат: ok — своих ${своих}, из таблицы ${изТаблицы}, без фона ${всего - своих - изТаблицы} из ${всего}`);
