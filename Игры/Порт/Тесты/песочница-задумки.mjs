// Задумки песочницы: пять живых мини-игр грузятся без DOM и отдают вход, как семь старых. node Игры/Порт/Тесты/песочница-задумки.mjs
// Саму игру (холст, ввод) проверяют в браузере; здесь — список, описи, смыслы исходов и навык(S).
import assert from 'node:assert/strict';
import { ЗАДУМКИ } from '../Движок/песочница/задумки.js';

const СТАРЫЕ = ['мотив', 'игла', 'вес', 'торг', 'кости', 'комната', 'счёт'];
assert.equal(ЗАДУМКИ.length, 5, 'пять задумок');
assert.equal(new Set(ЗАДУМКИ.map(з => з.id)).size, 5, 'id не повторяются');
for (const з of ЗАДУМКИ) {
  assert.ok(!СТАРЫЕ.includes(з.id), з.id + ': не совпадает со старой игрой');
  assert.ok(з.имя && з.где, з.id + ': имя и где');
  const м = await import(`../Движок/песочница/${з.id}.js`);
  assert.equal(typeof м.запустить, 'function', з.id + ': запустить');
  assert.equal(м.ОПИСЬ.id, з.id, з.id + ': опись');
  assert.ok(м.ОПИСЬ.имя && м.ОПИСЬ.где, з.id + ': опись с местом');
  for (const у of ['плохо', 'нормально', 'отлично']) assert.ok(м.СМЫСЛ[у]?.trim(), `${з.id}: смысл «${у}»`);
  assert.ok(!/секунд|гильди|маги/i.test(JSON.stringify([з, м.ОПИСЬ, м.СМЫСЛ])), з.id + ': без снятых слов');
  const S = { герой: { ремёсла: {} }, мир: {} };
  const н = м.навык(S);
  assert.ok(Number.isInteger(н) && н >= 0 && н <= 2, з.id + ': навык(S) 0..2');
}
// Тали растёт с ремеслом грузчика.
{
  const { навык } = await import('../Движок/песочница/тали.js');
  assert.equal(навык({ герой: { ремёсла: {} } }), 0);
  assert.equal(навык({ герой: { ремёсла: { грузчик: { ступень: 'умеешь' } } } }), 1);
  assert.equal(навык({ герой: { ремёсла: { грузчик: { ступень: 'мастер' } } } }), 2);
}
console.log('песочница-задумки: ok');
