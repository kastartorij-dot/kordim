const сон = id => ЖИЛЬЁ.find(ж => ж.id === id);
const копия = S => мигрировать(JSON.parse(JSON.stringify(S)));
const спать = (S, id = 'койка') => { S.мир.конецДня = null; S.мир.отрезок = 'ночь'; лечьСпать(S, id ? сон(id) : null); const ж = S.мир.конецДня.журнал; S.мир.конецДня = null; return ж; };
const часть = (S, голос) => модификатор(S, { голос }).части.find(ч => ч.что.startsWith('мысли'))?.д ?? 0;
const слов = т => т.trim().split(/\s+/).length;
const нов = (начало = 'семья') => { const S = новоеСостояние(начало, 7); S.герой.кошель = 300; return S; };

// ── данные ───────────────────────────────────────────────────────────────
{
  assert.equal(МЫСЛЕЙ_МЕСТ, 3);
  assert.equal(Object.keys(МЫСЛИ).length, 12, 'три исходных и девять из черновика');
  // Три исходных образца — как в концепте диалогов §11.
  for (const [id, плюс, минус] of [['syn_vesovshchika', 'ОТЕЦ', 'ДЫМ'], ['dolg_rychag', 'СТРОКА', 'ОТЕЦ'], ['nikto_ne_zhdyot', 'ДЫМ', 'МОЛВА']]) {
    assert.equal(МЫСЛИ[id].вид, 'исходная'); assert.equal(МЫСЛИ[id].плюс, плюс, id); assert.equal(МЫСЛИ[id].минус, минус, id);
  }
  assert.deepEqual(Object.values(МЫСЛИ).filter(м => м.вид === 'цель').map(м => м.цель).sort(), ['вытащить', 'имя', 'угол', 'уехать']);
  assert.deepEqual(Object.values(МЫСЛИ).filter(м => м.вид === 'ремесло').map(м => м.ремесло).sort(), ['грамота', 'грузчик', 'наколки']);
  assert.deepEqual(Object.keys(МЫСЛИ).filter(id => МЫСЛИ[id].вид === 'решение').sort(), ['net_eto_otvet', 'pochinit_slovo']);
  const люди = new Set(МЕСТА.flatMap(м => Object.keys(м.модуль?.ДИАЛОГИ ?? {})));
  for (const [id, м] of Object.entries(МЫСЛИ)) {
    assert.ok([2, 3].includes(м.ночей), id + ': два или три сна');
    assert.notEqual(м.плюс, м.минус, id);
    assert.ok(слов(м.начало) >= 40 && слов(м.начало) <= 70, id + ': начало 40–70 слов, сейчас ' + слов(м.начало));
    assert.ok(слов(м.итог) >= 60 && слов(м.итог) <= 100, id + ': завершение 60–100 слов, сейчас ' + слов(м.итог));
    for (const п of ['откуда', 'запасной', 'польза', 'ограничение']) assert.ok(м[п]?.trim(), id + ': ' + п);
    assert.ok(!/секунд/i.test(JSON.stringify(м)), id + ': без секунд');
    assert.ok(!/гильди/i.test(JSON.stringify(м)), id + ': без гильдии');
    assert.ok(люди.has(м.реплика.кто), id + ': собеседник ' + м.реплика.кто + ' существует');
    // Реплика — ветка у этого человека, видимая только при созревшей мысли.
    const г = МЕСТА.map(x => x.модуль?.ДИАЛОГИ?.[м.реплика.кто]).find(Boolean);
    assert.ok(г.хаб.includes('мысль_' + id) && г.ветки['мысль_' + id].если.мысль === id, id + ': ветка в хабе');
  }
}

// ── поводы в сцене у Сиба: правда об отце → «Сын весовщика», уход от ответа → «Никто не ждёт» ──
{
  const кн = (S, т) => действияСцены(S).find(x => (x.текст ?? '').includes(т) && x.можно !== false);
  const жми = (S, т) => { const а = кн(S, т); if (!а) throw new Error(`нет кнопки «${т}»: ` + действияСцены(S).map(x => x.текст).join(' | ')); а.выполнить(S); };
  const кПоздно = () => {
    const S = нов('наколки'); S.мир.отрезок = 'вечер'; S.мир.район = 'торговый';
    S.мир.люди.sib = { спрошено: [], исчерпано: [], распол: 3, знаком: true }; S.мир.места['синий-час'] = { визитов: 4, осмотрено: [], дом: 0 };
    войти(S, 'синий-час'); жми(S, 'Держи. Двадцать'); жми(S, 'Войти.'); жми(S, 'Заговорить с: Сиб');
    S.сцена.ходы = 3; жми(S, 'когда все внутри'); жми(S, 'Говори.'); жми(S, 'Слушать дальше.');
    return S;
  };
  const А = кПоздно(); жми(А, 'Не хочу об этом.');
  assert.deepEqual(мысли(А).можно, ['nikto_ne_zhdyot']);
  assert.ok(А.мир.журналДня.some(с => с.includes('Новая мысль: «Никто не ждёт»')));
  const Б = кПоздно(); жми(Б, 'Отец. Схоронили');
  assert.deepEqual(мысли(Б).можно, ['syn_vesovshchika'], 'правда об отце даёт мысль при любом исходе броска');
  // «Нет — это ответ»: Сиб не берёт монету, Одвин убирает её без уговоров.
  // «Починить слово»: обещал зайти, срок истёк — и всё-таки пришёл сам.
  const уСиба = () => {
    const S = нов('наколки'); S.мир.отрезок = 'вечер'; S.мир.район = 'торговый';
    S.мир.люди.sib = { спрошено: [], исчерпано: [], распол: 3, знаком: true }; S.мир.места['синий-час'] = { визитов: 4, осмотрено: [], дом: 0 };
    return S;
  };
  const В = уСиба();
  войти(В, 'синий-час'); жми(В, 'Держи. Двадцать'); жми(В, 'Войти.'); жми(В, 'Заговорить с: Сиб');
  assert.deepEqual(мысли(В).можно, [], 'одно появление у Сиба мысли не даёт');
  жми(В, 'монета'); жми(В, 'Убрать монету.');
  assert.deepEqual(мысли(В).можно, ['net_eto_otvet']);
  const Г = уСиба();
  (Г.мир.обязательства ??= {})['сиб:зайти'] = { id: 'сиб:зайти', название: 'Зайти к Сибу', срок: { день: 0, отрезок: 'вечер', граница: 'конец' }, статус: 'истекло' };
  войти(Г, 'синий-час'); жми(Г, 'Держи. Двадцать'); жми(Г, 'Войти.'); жми(Г, 'Заговорить с: Сиб');
  заметитьМысли(Г);
  assert.equal(мысли(Г).поводы.pochinit_slovo?.как, 'основной', 'пришёл к Сибу после просроченного обещания');
}

// ── поводы ремёсел: три грузовые смены без травмы, проверенная дощечка с грамотой, отложенная пьяная наколка ──
{
  const S = нов();
  S.мир.работы.разгрузка = { смен: 2 }; S.мир.работы['обозная-разгрузка'] = { смен: 1 };
  S.герой.рана = 1; заметитьМысли(S);
  assert.ok(!мысли(S).можно.includes('tyazhest_remeslo'), 'с раной «чисто донёс» не считается');
  S.герой.рана = 0; заметитьМысли(S);
  assert.equal(мысли(S).поводы.tyazhest_remeslo.как, 'основной');
  const Т = нов(); Т.мир.счётчики = { мини_вес_удача: 1 }; заметитьМысли(Т);
  assert.equal(мысли(Т).поводы.tyazhest_remeslo.как, 'запасной', 'сверка веса сошлась');
  // «Прочесть вместе» — только у грамотного героя.
  const Ч = нов('семья'); Ч.мир.счётчики = { мини_счёт_удача: 1 };
  if (Ч.герой.ремёсла?.грамота) delete Ч.герой.ремёсла.грамота;
  заметитьМысли(Ч); assert.ok(!мысли(Ч).можно.includes('prochest_vmeste'), 'без грамоты не предлагается');
  датьРемесло(Ч, 'грамота'); заметитьМысли(Ч);
  assert.equal(мысли(Ч).поводы.prochest_vmeste.как, 'основной');
  // «Сначала спросить»: выбор «Отложить до утра» у пьяного клиента несёт повод; строка видна в итоге смены.
  const п = НАКОЛКИ.find(с => с.id === 'nak_pyanyj').выбор.find(о => о.текст === 'Отложить до утра');
  assert.equal(п.эффект.мысль, 'snachala_sprosit');
  const Н = нов('наколки');
  assert.ok(применитьЭффект(Н, п.эффект).includes('новая мысль: «Сначала спросить, потом колоть»'));
  assert.ok(мысли(Н).можно.includes('snachala_sprosit'));
  assert.deepEqual(применитьЭффект(Н, { мысль: 'snachala_sprosit' }), [], 'повтор строки не даёт');
  // Запасные социальных: отошёл, не навязывая; одно обещание истекло, другое выполнено.
  const О = нов(); О.мир.вытащить = { навязал: 0, ждётДо: 5 };
  О.мир.обязательства = { а: { статус: 'истекло' }, б: { статус: 'выполнено' } };
  заметитьМысли(О);
  assert.equal(мысли(О).поводы.net_eto_otvet.как, 'запасной');
  assert.equal(мысли(О).поводы.pochinit_slovo.как, 'запасной');
  const Х = нов(); Х.мир.вытащить = { навязал: 1, ждётДо: 5 }; заметитьМысли(Х);
  assert.ok(!мысли(Х).можно.includes('net_eto_otvet'), 'после навязанной помощи — нет');
}

// ── поводы мира: проверяются к ночи; повтор ничего не добавляет ─────────────
{
  const S = нов();
  спать(S);
  assert.deepEqual(мысли(S).можно, [], 'без повода мыслей нет');
  S.мир.темы.push('dolgi_doma');
  S.мир.угол = { осмотрена: true, статус: 'нет' }; S.мир.ночи.вдова = 1;
  S.мир.имя = { письмо: 'доставлено', путь: 'запечатанным' };
  S.мир.вытащить = { навязал: 0, стоп: true, границы: [] };
  S.мир.уехать = { слышал: true, рейс: 'береговой', исход: null };
  const ж = спать(S);
  assert.deepEqual(мысли(S).можно.sort(), ['dolg_rychag', 'gde_ostanovitsya', 'imya_po_delam', 'ne_otkuda_a_kuda', 'pozhit_prezhde_chem_platit'].sort());
  assert.ok(ж.some(с => с.includes('Новая мысль: «Долг — это рычаг»')), 'итог дня называет новую мысль');
  for (const id of мысли(S).можно) assert.equal(мысли(S).поводы[id].как, 'основной', id);
  assert.equal(предложитьМысль(S, 'dolg_rychag'), false, 'повторный повод ничего не добавляет');
  // Запасные: две ночи под небом → «Никто не ждёт»; две записи о Бренне → «Сын весовщика».
  S.мир.ночи.небо = 2; S.мир.свидетельства = ['brenn_office_entry', 'brenn_hostel_book'];
  спать(S);
  assert.equal(мысли(S).поводы.nikto_ne_zhdyot.как, 'запасной');
  assert.equal(мысли(S).поводы.syn_vesovshchika.как, 'запасной');
  assert.match(сводкаМыслей(S).можно.find(м => м.id === 'nikto_ne_zhdyot').откуда, /^Дважды ночевал/);
  // Вскрытое письмо не даёт «Имя по делам»; свой угол по договору не даёт «Пожить, прежде чем платить».
  const В = нов(); В.мир.имя = { письмо: 'доставлено', путь: 'вскрыл' }; В.мир.угол = { осмотрена: true, статус: 'действует' }; В.мир.ночи = { вдова: 3 };
  спать(В); assert.deepEqual(мысли(В).можно, []);
}

// ── три места, созревание, общая формула ────────────────────────────────
{
  const S = нов();
  for (const id of ['syn_vesovshchika', 'imya_po_delam', 'ne_otkuda_a_kuda', 'nikto_ne_zhdyot']) предложитьМысль(S, id);
  assert.ok(обдумать(S, 'syn_vesovshchika') && обдумать(S, 'imya_po_delam') && обдумать(S, 'ne_otkuda_a_kuda'));
  assert.equal(обдумать(S, 'nikto_ne_zhdyot'), false, 'четвёртого места нет');
  const к = действияМыслей(S).find(д => д.id === 'мысль:обдумать:nikto_ne_zhdyot');
  assert.equal(к.можно, false); assert.match(к.почему, /три места/);
  // Пока зреют: плюс −1, минуса ещё нет.
  assert.equal(часть(S, 'ОТЕЦ'), -1); assert.equal(часть(S, 'ДЫМ'), 0); assert.equal(часть(S, 'МОЛВА'), -1, 'две зреющие МОЛВЫ не складываются');
  // Под небом и без сна мысль не зреет.
  assert.ok(спать(S, 'небо').some(с => с.includes('под открытым небом')));
  S.мир.отрезок = 'ночь'; S.мир.конецДня = null; следующийОтрезок(S); S.мир.конецДня = null;
  assert.equal(мысли(S).места[0].ночи.length, 0, 'ни небо, ни бессонная ночь не считаются');
  спать(S, 'ночлежка');
  assert.equal(мысли(S).места[0].ночи.length, 1);
  ночьМыслей(S, сон('койка'), мысли(S).места[0].ночи[0]);
  assert.equal(мысли(S).места[0].ночи.length, 1, 'одна ночь не считается дважды');
  const ж = спать(S, 'вдова');
  assert.ok(созрела(S, 'syn_vesovshchika') && !созрела(S, 'imya_po_delam'), 'два сна для отца, три для имени');
  assert.ok(ж.some(с => с.startsWith('Мысль созрела: «Сын весовщика»')));
  assert.equal(часть(S, 'ОТЕЦ'), 1); assert.equal(часть(S, 'ДЫМ'), -1);
  assert.ok(модификатор(S, { голос: 'ОТЕЦ' }).части.some(ч => ч.что === 'мысли: Сын весовщика' && ч.д === 1), 'часть видна в разборе проверки');
  спать(S);
  assert.ok(созрела(S, 'imya_po_delam') && созрела(S, 'ne_otkuda_a_kuda'));
  assert.equal(часть(S, 'МОЛВА'), 1, 'две созревшие МОЛВЫ дают +1, не +2');
  assert.equal(часть(S, 'ДЫМ'), -1, 'два минуса ДЫМУ дают −1');
  assert.equal(часть(S, 'ЧУТЬЁ'), -1);
  // Сохранение и загрузка — те же места, ночи и поводы.
  const К = копия(S);
  assert.deepEqual(К.герой.мысли, S.герой.мысли);
  assert.equal(часть(К, 'ОТЕЦ'), 1);
  // Отказ: бонус и минус уходят сразу, мысль снова ждёт и начинается с первой ночи.
  assert.ok(отпустить(К, 'syn_vesovshchika'));
  assert.equal(часть(К, 'ОТЕЦ'), 0); assert.equal(часть(К, 'ДЫМ'), -1, 'минус ДЫМУ остаётся только от «Не откуда, а куда»');
  assert.ok(мысли(К).можно.includes('syn_vesovshchika'));
  assert.ok(К.мир.журналДня.some(с => с.includes('отпущена: её плюс и минус ушли')));
  assert.ok(обдумать(К, 'nikto_ne_zhdyot'));
  assert.equal(часть(К, 'ДЫМ'), -1, 'зреющая «Никто не ждёт» даёт ДЫМ −1');
  спать(К); спать(К);
  assert.equal(часть(К, 'ДЫМ'), 0, 'созревшая «Никто не ждёт» гасит минус «Не откуда»');
  assert.ok(обдумать(К, 'syn_vesovshchika') === false, 'места снова заняты');
  assert.ok(отпустить(К, 'imya_po_delam') && обдумать(К, 'syn_vesovshchika'));
  assert.equal(мысли(К).места.find(x => x.id === 'syn_vesovshchika').ночи.length, 0, 'повторное обдумывание с нуля');
  assert.match(сводкаМыслей(К).места.find(м => м?.id === 'syn_vesovshchika').отказ, /0 из 2 ночей/);
}

// ── реплики: ветка у человека открыта только созревшей мыслью ───────────────
{
  const S = нов();
  предложитьМысль(S, 'ne_otkuda_a_kuda'); обдумать(S, 'ne_otkuda_a_kuda');
  assert.equal(если(S, { мысль: 'ne_otkuda_a_kuda' }, 'tobb'), false);
  спать(S); спать(S);
  assert.equal(если(S, { мысль: 'ne_otkuda_a_kuda' }, 'tobb'), false, 'зреет — ещё рано');
  спать(S);
  assert.equal(если(S, { мысль: 'ne_otkuda_a_kuda' }, 'tobb'), true);
  assert.equal(если(S, { безМысли: 'ne_otkuda_a_kuda' }, 'tobb'), false);
  // Старый сейв: в S.герой.мысли пустой массив-заглушка или поля нет — всё читается как пустой кабинет.
  const С = нов(); С.герой.мысли = [];
  assert.equal(вкладМыслей(С, 'ОТЕЦ'), null);
  assert.deepEqual(сводкаМыслей(С).места, [null, null, null]);
  delete С.герой.мысли; спать(С); assert.deepEqual(мысли(С).места, []);
}

