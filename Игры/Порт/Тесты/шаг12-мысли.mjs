// Шаг 12: кабинет мыслей. node Игры/Порт/Тесты/шаг12-мысли.mjs
// Три места, созревание полноценными снами (ночь не считается дважды), три исходных образца из сцены у Сиба
// и поводов мира, четыре мысли под цели, три ремесла и два социальных решения, общая формула проверки,
// отказ без остатка бонуса, сохранение, реплики.
import assert from 'node:assert/strict';
import { новоеСостояние, мигрировать } from '../Движок/состояние.js';
import { войти, действияСцены } from '../Движок/разговор.js';
import { лечьСпать, следующийОтрезок } from '../Движок/время.js';
import { модификатор } from '../Движок/проверка.js';
import { если } from '../Движок/диалог.js';
import { МЫСЛИ, МЫСЛЕЙ_МЕСТ } from '../Данные/мысли.js';
import { ЖИЛЬЁ } from '../Данные/жильё.js';
import { МЕСТА } from '../Данные/места.js';
import { применитьЭффект } from '../Движок/эффекты.js';
import { датьРемесло } from '../Движок/ремёсла.js';
