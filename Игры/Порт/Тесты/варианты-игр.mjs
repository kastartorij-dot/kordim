// Варианты живых игр «Торг», «Вес», «Кости», «Счёт» (круг 5). node Игры/Порт/Тесты/варианты-игр.mjs
// 1. Каждый модуль песочницы отдаёт варианты [{ id, имя }] и принимает { вариант }; данные игры ссылаются только на них.
// 2. В игре варианты сменяются при повторах: первый раз — самый понятный, подряд одно и то же не выпадает,
//    особый день (рыночный, расчёта, обоза, вечер, плащ) тянет свой вариант; вариант и цена уходят в окно игры.
// 3. Сложность — бот с человеческой задержкой (~200–250 мс) и шумом глаза и руки (Тесты/утилиты/бот-живых.js):
//    без навыка в основном «нормально» и «плохо», «отлично» редко; навык помогает.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { новоеСостояние } from '../Движок/состояние.js';
import { доступныеДействия } from '../Движок/действия.js';
import { действияСцены } from '../Движок/разговор.js';
import { СТЕНД_ИГР, видЗадачи } from '../Движок/мини-игры.js';
import { стендМеста } from '../Движок/игры-места.js';
import { цена } from '../Движок/торг.js';
import { выбратьВариант, отметитьПартию, партия } from '../Движок/варианты-игр.js';
import { НРАВ_ТОРГА } from '../Данные/торг.js';
import { КОСТИ } from '../Данные/кости.js';
import { ВАРИАНТЫ_ЖИВЫХ } from '../Данные/вес-и-счёт.js';
import * as торг from '../Движок/песочница/торг.js';
import * as вес from '../Движок/песочница/вес.js';
import * as кости from '../Движок/песочница/кости.js';
import * as счёт from '../Движок/песочница/счёт.js';
import { ботТорга, ботВеса, уровень, раскладка } from './утилиты/бот-живых.js';

// ── 1. Экспорт вариантов ──
const В_ИГРЕ = {
  торг: НРАВ_ТОРГА,
  кости: [...КОСТИ.горм.варианты, ...КОСТИ.таверна.варианты],
  вес: ВАРИАНТЫ_ЖИВЫХ.вес,
  счёт: ВАРИАНТЫ_ЖИВЫХ.счёт,
};
for (const [id, м] of Object.entries({ торг, вес, кости, счёт })) {
  assert.ok(Array.isArray(м.варианты) && м.варианты.length >= 4 && м.варианты.length <= 6, id + ': 4–6 вариантов');
  for (const в of м.варианты) assert.ok(в.id && в.имя, id + ': у варианта id и имя');
  assert.equal(new Set(м.варианты.map(в => в.id)).size, м.варианты.length, id + ': id не повторяются');
  const код = readFileSync(new URL(`../Движок/песочница/${id}.js`, import.meta.url), 'utf8');
  assert.match(код, /export async function запустить\(контейнер, \{[^}]*вариант[^}]*\}/, id + ': запустить принимает вариант');
  // в игре — те же id, и каждый вариант песочницы где-то в игре выпадает
  assert.deepEqual(В_ИГРЕ[id].map(в => в.id).sort(), м.варианты.map(в => в.id).sort(), id + ': варианты игры = варианты песочницы');
  for (const в of В_ИГРЕ[id]) assert.ok(в.подводка, `${id}/${в.id}: подводка перед партией`);
}

// ── 2. Выбор варианта ──
{
  const S = новоеСостояние('бумаги', 1);
  const список = [{ id: 'а' }, { id: 'б' }, { id: 'в', где: { разОт: 2 } }, { id: 'г', когда: { рыночный: true } }];
  assert.equal(выбратьВариант(S, 'проба', список, { день: 3, рыночный: true }).id, 'а', 'первый раз — первый вариант, даже в особый день');
  отметитьПартию(S, 'проба', 'а');
  assert.equal(выбратьВариант(S, 'проба', список, { день: 3, рыночный: true }).id, 'г', 'особый день тянет свой вариант');
  assert.equal(выбратьВариант(S, 'проба', список, { день: 4, рыночный: false }).id, 'б', 'второй раз: не прошлый и не «с третьего раза»');
  отметитьПартию(S, 'проба', 'г');
  assert.notEqual(выбратьВариант(S, 'проба', список, { день: 3, рыночный: true }).id, 'г', 'особый вариант подряд не повторяется');
  assert.deepEqual(партия(S, 'проба'), { раз: 2, был: 'г' });
  assert.deepEqual(партия(новоеСостояние('бумаги', 1), 'проба'), { раз: 0, был: null }, 'старое сохранение без счётчика — ноль партий');
}

const итог = у => ({ уровень: у, очки: { плохо: 0.2, нормально: 0.6, отлично: 0.9 }[у] });
const живой = (S, ходы) => { const а = ходы(S).filter(х => х.живая); assert.equal(а.length, 1, 'один живой ход'); return а[0]; };
const ходыМеста = S => действияСцены(S);
const ходыСмены = S => доступныеДействия(S).filter(а => а.группа === 'смена');
const подряд = (ряд, что) => { for (let k = 1; k < ряд.length; k++) assert.notEqual(ряд[k], ряд[k - 1], `${что}: подряд одно и то же (${ряд.join(', ')})`); };

// Торг: десять дней у Пина — днём, вечером, в рыночный день, в день расчёта, за плащ.
{
  const ряд = [];
  let партии;
  const дни = [[2, 'день', 'кафтан'], [3, 'день', 'кафтан'], [4, 'вечер', 'кафтан'], [5, 'день', 'плащ'], [6, 'день', 'кафтан'], [7, 'день', 'кафтан'],
    [8, 'день', 'кафтан'], [9, 'вечер', 'кафтан'], [10, 'день', 'кафтан'], [11, 'день', 'кафтан'], [12, 'день', 'кафтан'], [13, 'день', 'кафтан']];
  for (const [день, отрезок, товар] of дни) {
    const S = новоеСостояние('бумаги', 3);
    S.мир.партии = партии;
    assert.ok(стендМеста(S, { место: 'рынок', район: 'торговый', отрезок, день, комната: 'ветошь-рынка', кошель: 100, игра: { вид: 'торг', товар } }), 'торг: день ' + день);
    const в = S.сцена.игра.вариант;
    const подводка = НРАВ_ТОРГА.find(н => н.id === в).подводка;
    assert.ok(S.сцена.игра.реплика.endsWith(подводка), 'торг: подводка нрава на карточке перед партией');
    const х = живой(S, ходыМеста);
    assert.equal(х.живая.вход.вариант, в, 'торг: вариант уходит в окно игры');
    // цена в окне — из товара: первая цена и то, что выйдет при каждом исходе
    assert.equal(х.живая.вход.просит, цена(S, товар), 'торг: окно просит цену товара, а не свои 48');
    const ц = х.живая.вход.цены;
    const у = ['отлично', 'нормально', 'плохо'][ряд.length % 3];
    х.выполнить(S, итог(у));
    if (у !== 'плохо') assert.equal(цена(S, товар), ц[у], `торг: после «${у}» цена ${ц[у]}, как обещало окно`);
    const след = НРАВ_ТОРГА.find(н => н.id === в).след?.[у];
    if (след) assert.ok(S.сцена.игра.реплика.endsWith(след), 'торг: след нрава после партии');
    ряд.push(в);
    партии = S.мир.партии;
  }
  assert.equal(ряд[0], 'тихий', 'торг: первый раз — тихий час');
  assert.equal(ряд[1], 'дёрганый', 'торг: рыночный день (3) — толчея');
  assert.equal(ряд[2], 'ленивый', 'торг: вечер — Пин ленится');
  assert.equal(ряд[3], 'упрямый', 'торг: плащ — Пин упрямится');
  assert.equal(ряд[5], 'торопится', 'торг: день расчёта (7)');
  assert.ok(new Set(ряд).size >= 5, 'торг: за двенадцать партий — хотя бы пять нравов: ' + ряд.join(', '));
  подряд(ряд, 'торг');
  // кафтан у Пина: 15 → 12 (а не 48 → 30 песочницы)
  const S = новоеСостояние('бумаги', 3);
  стендМеста(S, { место: 'рынок', район: 'торговый', отрезок: 'день', день: 2, комната: 'ветошь-рынка', кошель: 100, игра: { вид: 'торг', товар: 'кафтан' } });
  assert.deepEqual([живой(S, ходыМеста).живая.вход.просит, живой(S, ходыМеста).живая.вход.цены.отлично], [15, 12], 'торг: кафтан — 15 → 12');
}

// Кости в таверне: моряки меняются от вечера к вечеру; у Горма всегда Горм.
{
  const ряд = [];
  let партии;
  for (let день = 2; день <= 16; день += 2) {
    const S = новоеСостояние('бумаги', 9);
    S.мир.партии = партии;
    assert.ok(стендМеста(S, { место: 'таверна', район: 'доки', отрезок: 'вечер', день, игра: { вид: 'кости', партия: 'таверна' } }), 'кости: вечер ' + день);
    const в = S.сцена.игра.вариант;
    assert.ok(S.сцена.игра.реплика.endsWith(КОСТИ.таверна.варианты.find(x => x.id === в).подводка), 'кости: подводка соперника');
    const х = живой(S, ходыМеста);
    assert.equal(х.живая.вход.вариант, в);
    const у = ['отлично', 'плохо', 'нормально'][ряд.length % 3];
    х.выполнить(S, итог(у));
    const исход = { отлично: 'выигрыш', плохо: 'проигрыш', нормально: 'вровень' }[у];
    const слова = КОСТИ.таверна.варианты.find(x => x.id === в)[исход] ?? КОСТИ.таверна[исход];
    assert.ok(S.сцена.реплика.startsWith(слова), `кости/${в}/${исход}: свой след соперника`);
    ряд.push(в);
    партии = S.мир.партии;
  }
  assert.equal(ряд[0], 'моряк', 'кости: первый раз — обычный моряк');
  assert.ok(new Set(ряд).size >= 4, 'кости: за восемь вечеров — все четыре моряка: ' + ряд.join(', '));
  подряд(ряд, 'кости');
  const S = новоеСостояние('бумаги', 9);
  стендМеста(S, { место: 'двор-горма', район: 'трущобы', отрезок: 'день', день: 3, игра: { вид: 'кости', партия: 'горм' } });
  assert.equal(живой(S, ходыМеста).живая.вход.вариант, 'горм', 'кости: у Горма — Горм');
}

// Вес и Счёт: задача на смене несёт вариант; подводка на карточке; итог — свой.
for (const [игра, ступень, работа, ожидания] of [
  ['вес', 'умеешь', 'разгрузка', { 0: 'мешки' }],
  ['счёт', 'умеешь', 'чтец', { 0: 'сумма' }],
]) {
  const ряд = [];
  let партии;
  for (let k = 0; k < 10; k++) {
    const S = новоеСостояние('бумаги', 11);
    S.мир.партии = партии;
    S.мир.день = 2 + k;
    assert.ok(СТЕНД_ИГР.find(с => с.id === игра).начать(S, { ступень }), `${игра}: смена ${k}`);
    assert.equal(S.мир.смена.работа, работа);
    const т = S.мир.смена.задача;
    const вар = ВАРИАНТЫ_ЖИВЫХ[игра].find(в => в.id === т.вариант);
    assert.ok(вар, игра + ': у задачи вариант');
    assert.equal(видЗадачи(S).подводка, вар.подводка, игра + ': подводка варианта на карточке смены');
    const х = живой(S, ходыСмены);
    assert.equal(х.живая.вход.вариант, т.вариант, игра + ': вариант уходит в окно игры');
    х.выполнить(S, итог(k % 2 ? 'плохо' : 'отлично'));
    const исход = k % 2 ? 'ошибка' : 'удача';
    if (вар[исход]) assert.equal(S.мир.смена.итог.текст, вар[исход], `${игра}/${т.вариант}: свой итог`);
    ряд.push(т.вариант);
    партии = S.мир.партии;
  }
  for (const [k, id] of Object.entries(ожидания)) assert.equal(ряд[k], id, `${игра}: партия ${k} — ${id}`);
  assert.ok(new Set(ряд).size >= 4, `${игра}: за десять смен — хотя бы четыре варианта: ${ряд.join(', ')}`);
  подряд(ряд, игра);
  if (игра === 'счёт') {
    // дни 4 и 9 — обозы, 7 — расчёт: печать и строки дважды тянутся к своим дням
    assert.equal(ряд[2], 'печать', 'счёт: день обоза (4) — печати');
    assert.equal(ряд[5], 'дубль', 'счёт: день расчёта (7) — недельный счёт');
  }
}
// «Старые весы» — только на причале (разгрузка), у весовщика весы в порядке.
assert.deepEqual(ВАРИАНТЫ_ЖИВЫХ.вес.find(в => в.id === 'старые').где, { работа: 'разгрузка' });

// ── 3. Сложность ботом ──
// Торг и Вес — по чистой физике. Порог: без навыка «отлично» ≤ 15 %, «нормально» + «плохо» ≥ 85 %;
// с «набил руку» «отлично» заметно чаще. Задержка руки — 200 и 250 мс.
const СТРОКИ = [];
for (const [имя, м, бот, N] of [['торг', торг, ботТорга, 160], ['вес', вес, ботВеса, 100]]) {
  for (const в of м.варианты) {
    const по = (навык, задержка) => раскладка(Array.from({ length: N }, (_, s) => уровень(бот(м, { вариант: в.id, навык, сид: s * 31 + 7, задержка }).очки, м.ПОРОГИ)));
    for (const задержка of [0.2, 0.25]) {
      const р0 = по(0, задержка);
      const р2 = по(2, задержка);
      СТРОКИ.push(`${имя}/${в.id} ${задержка * 1000} мс: нет ${р0.плохо}/${р0.нормально}/${р0.отлично} · набил руку ${р2.плохо}/${р2.нормально}/${р2.отлично}`);
      assert.ok(р0.отлично <= 15, `${имя}/${в.id}: без навыка «отлично» редко (${р0.отлично} %)`);
      assert.ok(р0.плохо <= 80, `${имя}/${в.id}: без навыка выиграть можно (плохо ${р0.плохо} %)`);
      assert.ok(р2.отлично >= р0.отлично + 20, `${имя}/${в.id}: навык помогает (${р0.отлично} → ${р2.отлично} %)`);
    }
  }
}
if (process.argv.includes('-v')) console.log(СТРОКИ.join('\n'));
console.log('варианты игр: ок');
