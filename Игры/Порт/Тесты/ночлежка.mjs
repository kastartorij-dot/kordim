  assert.ok(S.мир.журналДня.some(с => с.includes('Тон Брикс знает')));
  assert.equal(н(S).карты.includes('шаги'), false);
  const день = S.мир.день;
  доутра(S);
  assert.equal(S.сцена, null, 'сцена закрыта: утро');
  assert.ok(S.мир.конецДня, 'экран конца дня');
