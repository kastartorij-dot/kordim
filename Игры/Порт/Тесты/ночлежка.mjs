const кнопка = (S, текст) => действияСцены(S).find(а => а.текст === текст || а.текст.startsWith(текст));
const нажать = (S, текст) => { const а = кнопка(S, текст); assert.ok(а, `нет кнопки «${текст}»`); assert.equal(а.можно, true, `«${текст}» недоступна: ${а.почему}`); а.выполнить(S); };
const пойти = (S, к) => действияСцены(S).find(а => а.id === `пойти:${к}`).выполнить(S);
const распол = (S, кто) => S.мир.люди[кто]?.распол ?? 0;
const м = S => S.мир.места.ночлежка;
const н = S => S.сцена.ночь;

function вНочлежке(день = 3, кошель = 100, отрезок = 'вечер', S0 = null) {
  const S = S0 ?? новоеСостояние('семья', 7);
  S.мир.район = 'трущобы'; S.мир.день = день; S.мир.отрезок = отрезок; S.герой.кошель = кошель;
  S.мир.погода = 'ясно';
  войти(S, 'ночлежка');
  return S;
}
const клон = S => JSON.parse(JSON.stringify(S));
// Подбираем зерно монеты, при котором кнопка даёт нужный исход, и ставим его в настоящее состояние.
function сидГде(S, лечь, условие) {
  for (let с = 1; с < 3000; с++) {
    const S2 = клон(S);
    S2.мир.сид = с;
    нажатьТихо(S2, лечь);
    if (условие(S2)) { S.мир.сид = с; return с; }
  }
  assert.fail(`не нашлось зерна для «${лечь}»`);
}
const нажатьТихо = (S, текст) => кнопка(S, текст).выполнить(S);
const колодаСейчас = S => действияСцены(S).filter(а => а.текст !== 'Дождаться утра');
// Пройти ночь до конца, каждый раз выбирая вариант с номером «какой» (0 — первый). Возвращает тексты выбора.
function доутра(S, какой = 0) {
  const выборы = [];
  for (let i = 0; i < 12; i++) {
    const ут = кнопка(S, 'Дождаться утра');
    if (ут) { ут.выполнить(S); return выборы; }
    const все = колодаСейчас(S);
    const а = все[Math.min(какой, все.length - 1)];
    выборы.push(а.текст);
    а.выполнить(S);
  }
  assert.fail('ночь не кончилась');
}
const строкиУтра = S => S.мир.конецДня.журнал;

