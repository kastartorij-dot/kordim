// ── книга кроватей: ночи считаются, на пятой — Братство +1; шестая не добавляет; донос Тона после второго хранения
{
  const S = вНочлежке(1, 200);
  const брат0 = S.мир.очки.братство;
  for (let ночь = 1; ночь <= 6; ночь++) {
    if (ночь > 1) вНочлежке(ночь, S.герой.кошель, 'вечер', (S.мир.день = ночь, S.сцена = null, S));
    S.герой.кошель = 200;
    нажать(S, 'Отдать кошелёк Тону и лечь');
    доутра(S);
    assert.equal(м(S).счётчики.ночей, ночь);
    if (ночь === 1) assert.equal(S.мир.темы.includes('ton_gormu'), false, 'одного хранения мало');
    if (ночь === 2) {
      assert.equal(S.мир.темы.includes('ton_gormu'), true, 'второе хранение: заметил число для Горма');
      assert.ok(S.мир.конецДня.журнал.some(с => с.includes('мальчишку к Горму')));
    }
    if (ночь < 5) assert.equal(S.мир.очки.братство, брат0, `ночь ${ночь}: ещё не свой`);
    if (ночь === 5) { assert.equal(S.мир.очки.братство, брат0 + 1); assert.ok(S.мир.конецДня.журнал.some(с => с.includes('в книгу кроватей'))); }
    if (ночь === 6) assert.equal(S.мир.очки.братство, брат0 + 1, 'свой один раз');
    S.мир.конецДня = null;
  }
}

