// ── одеяло: с дня 21 без него осенние холода отнимают тепло
for (const [день, берём] of [[20, false], [21, false], [21, true]]) {
  const S = вНочлежке(день, 100);
  if (день < 21) assert.equal(кнопка(S, 'Взять у Тона одеяло'), undefined, 'до дня 21 одеяла не продают');
  else if (берём) { нажать(S, 'Взять у Тона одеяло'); assert.equal(S.герой.кошель, 98); }
  else assert.ok(кнопка(S, 'Взять у Тона одеяло'));
  S.герой.тело.тепло = 3; S.герой.одежда = S.герой.одежда;
  нажать(S, 'Отдать кошелёк Тону и лечь');
  доутра(S);
  const причины = S.мир.конецДня.причины.join('|');
  if (день >= 21 && !берём) assert.match(причины, /осенние холода/, `день ${день}: без одеяла холода`);
  else assert.doesNotMatch(причины, /осенние холода/, `день ${день}, одеяло ${берём}: холодов нет`);
  if (берём) assert.equal(S.мир.конецДня.сон, 'Ночлежка, с одеялом');
}

// ── колода: сапог слышит 0–2 случая, под головой — минимум один; все карты встречаются
{
  const виденоСапог = new Set(), виденоГолова = new Set(), число = { сапог: new Set(), голова: new Set() };
  for (let с = 1; с <= 400; с++) {
    for (const [где, текст] of [['сапог', 'Лечь, кошелёк в сапог'], ['голова', 'Лечь, кошелёк под голову']]) {
      const S = вНочлежке(3, 100);
      S.мир.сид = с;
      пойти(S, 'общая-комната');
      нажать(S, текст);
      const карты = н(S).карты.filter(к => к !== 'шаги');
      число[где].add(карты.length);
      for (const к of н(S).карты) (где === 'сапог' ? виденоСапог : виденоГолова).add(к);
      assert.equal(new Set(карты).size, карты.length, 'одна карта дважды за ночь не выпадает');
      // постояльцы трое, без женщины в платке в ясную ночь
      assert.equal(н(S).постояльцы.length, 3);
      assert.equal(н(S).постояльцы.includes('platok'), false, 'женщина в платке приходит только в дождь');
    }
  }
  assert.deepEqual([...число.сапог].sort(), [0, 1, 2]);
  assert.deepEqual([...число.голова].sort(), [1, 2], 'чуткий слышит хотя бы один случай');
  for (const к of КОЛОДА) {
    if (к.id === 'записка') assert.equal(виденоСапог.has(к.id), false, 'без крошек записки нет');
    else assert.ok(виденоСапог.has(к.id), `карта «${к.id}» ни разу не выпала`);
  }
}

