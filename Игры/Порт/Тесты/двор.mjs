// Шаг 8, Двор Горма: чётные и нечётные дни, подкова, слова-табу, кости на вопрос, большая стирка, ставка на большой бой.
// node Порт/тест/двор.mjs
import assert from 'node:assert/strict';
import { новоеСостояние } from '../Движок/состояние.js';
import { войти, можноВойти, действияСцены, вернутьсяВГород } from '../Движок/разговор.js';
import { бросок } from '../Движок/случай.js';
import { верностьТемы } from '../Движок/знание.js';

const кнопка = (S, текст) => действияСцены(S).find(а => а.текст === текст || а.текст.startsWith(текст));
const нажать = (S, текст) => { const а = кнопка(S, текст); assert.ok(а, `нет кнопки «${текст}»`); assert.equal(а.можно, true, `«${текст}» недоступна: ${а.почему}`); а.выполнить(S); };
const пойти = (S, к) => действияСцены(S).find(а => а.id === `пойти:${к}`).выполнить(S);
const осмотреть = (S, д) => действияСцены(S).find(а => а.id === `рассмотреть:${д}`).выполнить(S);
const распол = (S, кто) => S.мир.люди[кто]?.распол ?? 0;
const брат = S => S.мир.очки.братство;
function воДворе(день = 3, кошель = 100, S0 = null) {
  const S = S0 ?? новоеСостояние('семья', 7);
  S.мир.район = 'трущобы'; S.мир.день = день; S.мир.отрезок = 'день'; S.герой.кошель = кошель;
  войти(S, 'двор-горма');
  return S;
}
const м = S => S.мир.места['двор-горма'];
// Монета честная: зерно подбираем так, чтобы следующий бросок был нужным.
const сидДля = выигрыш => { for (let с = 1; ; с++) if ((бросок({ мир: { сид: с } }) < 0.5) === выигрыш) return с; };

// ── календарь на стене честно называет день; Горм у стола только в нечётный
{
  const чёт = воДворе(4);
  осмотреть(чёт, 'календарь');
  assert.match(чёт.сцена.реплика, /день 4, он чётный: Горм не говорит/);
  пойти(чёт, 'стол-горма');
  assert.equal(действияСцены(чёт).some(а => а.id === 'заговорить:gorm'), false, 'в чётный день Горм молчит');
  assert.equal(кнопка(чёт, 'Сыграть с Гормом в кости'), undefined, 'и в кости не играет');
  assert.equal(кнопка(чёт, 'Пообещать Горму'), undefined, 'и обещаний не принимает');

  const нечёт = воДворе(3);
  осмотреть(нечёт, 'календарь');
  assert.match(нечёт.сцена.реплика, /день 3, он нечётный: Горм принимает/);
  пойти(нечёт, 'стол-горма');
  assert.equal(действияСцены(нечёт).some(а => а.id === 'заговорить:gorm'), true);
}

// ── ночью двор закрыт; вечером открыт и день сцены не меняется
{
  const S = новоеСостояние('семья', 7);
  S.мир.район = 'трущобы'; S.мир.день = 3; S.мир.отрезок = 'ночь';
  assert.equal(можноВойти(S, 'двор-горма').можно, false, 'ночью во двор не пускают');
  S.мир.отрезок = 'вечер'; S.герой.кошель = 100;
  войти(S, 'двор-горма');
  осмотреть(S, 'календарь');
  assert.match(S.сцена.реплика, /день 3, он нечётный/);
}

// ── учёт визитов: счётчик чётных и нечётных, запись в журнал только за чётный
{
  const S = воДворе(4);
  assert.equal(м(S).счётчики.чётных, 1);
  assert.ok(S.мир.журналДня.some(с => с.includes('Горм молча зачёркивает и этот день')), 'чётный визит попал в журнал');
  вернутьсяВГород(S);
  const до = S.мир.журналДня.length;
  воДворе(5, 100, S);
  assert.equal(м(S).счётчики.нечётных, 1);
  assert.equal(S.мир.журналДня.length, до, 'нечётный визит строки в журнал не добавляет');
}

// ── подкова: правая — Горм +1, левая — Братство −1 и «Горм видит»; один раз за всю игру, обе вместе нельзя
{
  const S = воДворе(3);
  const до = распол(S, 'gorm');
  осмотреть(S, 'подкова');
  assert.match(S.сцена.реплика, /правой рукой/);
  нажать(S, 'Коснуться подковы правой рукой');
  assert.equal(распол(S, 'gorm'), до + 1);
  assert.equal(кнопка(S, 'Коснуться подковы правой рукой'), undefined, 'в этот день уже касался');
  assert.equal(кнопка(S, 'Коснуться подковы левой рукой'), undefined, 'вторую руку в тот же день не дают');
  вернутьсяВГород(S);
  воДворе(5, 100, S);
  assert.equal(кнопка(S, 'Коснуться подковы правой рукой'), undefined, 'правая — один раз за всю игру');
  assert.ok(кнопка(S, 'Коснуться подковы левой рукой'), 'левая ещё не касалась');
}
{
  const S = воДворе(3);
  const до = брат(S);
  нажать(S, 'Коснуться подковы левой рукой');
  assert.equal(брат(S), до - 1);
  assert.ok(м(S).флаги.includes('горм_видит'));
  вернутьсяВГород(S);
  воДворе(5, 100, S);
  assert.equal(кнопка(S, 'Коснуться подковы левой рукой'), undefined, 'левая тоже одна на игру');
}

// ── слова-табу: Бранка учит им за помощь с бельём; обещание «в последний раз» стоит Братства, другое — расположения Горма
{
  const S = воДворе(3);
  assert.equal(S.мир.темы.includes('gorm_tabu'), false);
  const до = брат(S);
  нажать(S, 'Помочь развесить бельё');
  assert.equal(брат(S), до + 1);
  assert.ok(S.мир.темы.includes('gorm_tabu'), 'Бранка подсказала три слова');
  assert.equal(кнопка(S, 'Помочь развесить бельё'), undefined, 'бельё раз в день');
}
{
  const S = воДворе(3);
  пойти(S, 'стол-горма');
  const до = брат(S);
  assert.equal(кнопка(S, 'Пообещать Горму: «Это в последний раз»').текст.includes('слово-табу'), false, 'без Бранки табу не помечено');
  нажать(S, 'Пообещать Горму: «Это в последний раз»');
  assert.equal(брат(S), до - 1, 'слово-табу стоит Братства');
  assert.equal(кнопка(S, 'Пообещать Горму: «Приду, когда позовёшь»'), undefined, 'одно обещание за визит');
  assert.equal(кнопка(S, 'Пообещать Горму: «Это в последний раз»'), undefined);
}
{
  const S = воДворе(3);
  нажать(S, 'Помочь развесить бельё');
  пойти(S, 'стол-горма');
  assert.ok(кнопка(S, 'Пообещать Горму: «Это в последний раз»').текст.includes('слово-табу'), 'после Бранки табу помечено');
  const до = распол(S, 'gorm');
  нажать(S, 'Пообещать Горму: «Приду, когда позовёшь»');
  assert.equal(распол(S, 'gorm'), до + 1);
  assert.equal(кнопка(S, 'Пообещать Горму: «Это в последний раз»'), undefined);
  вернутьсяВГород(S);
  воДворе(5, 100, S);
  пойти(S, 'стол-горма');
  assert.ok(кнопка(S, 'Пообещать Горму: «Приду, когда позовёшь»'), 'на следующий нечётный день обещание снова доступно');
}

// ── кости на вопрос: выиграл — слово Бренна и тема; проиграл — Горм знает, чей ты сын
{
  const S = воДворе(3);
  пойти(S, 'стол-горма');
  S.мир.сид = сидДля(true);
  нажать(S, 'Сыграть с Гормом в кости на вопрос');
  assert.match(S.сцена.реплика, /весы врут/);
  assert.ok(S.мир.темы.includes('gorm_kosti'));
  assert.ok(S.мир.свидетельства.includes('brenn_gorm_word'));
  assert.equal(м(S).флаги.includes('горм_знает_сына'), false);
  assert.equal(S.герой.кошель, 100, 'на деньги Горм не играет');
  assert.equal(кнопка(S, 'Сыграть с Гормом в кости'), undefined, 'одна партия в день');
}
{
  const S = воДворе(3);
  пойти(S, 'стол-горма');
  S.мир.сид = сидДля(false);
  нажать(S, 'Сыграть с Гормом в кости на вопрос');
  assert.match(S.сцена.реплика, /чей ты сын/);
  assert.ok(м(S).флаги.includes('горм_знает_сына'));
  assert.equal((S.мир.свидетельства ?? []).includes('brenn_gorm_word'), false);
  assert.equal(S.мир.темы.includes('gorm_kosti'), false);
  assert.equal(S.герой.кошель, 100);
}

// ── доска с зарубками у стола Горма: тема «Горм и чётные дни»
{
  const S = воДворе(3);
  пойти(S, 'стол-горма');
  осмотреть(S, 'календарь');
  assert.ok(S.мир.темы.includes('gorm_chetnye'), 'доска с зарубками даёт тему');
}

// ── Ним: слух «Горм слёг» продаётся за 2 гр. один раз; это ложь, и город сам её опровергнет
{
  const S = воДворе(3);
  нажать(S, 'Купить у Нима весточку про Горма');
  assert.equal(S.герой.кошель, 98);
  assert.ok(S.мир.темы.includes('lozh_gorm'));
  assert.equal(кнопка(S, 'Купить у Нима весточку про Горма'), undefined);
  assert.notEqual(верностьТемы(S, 'lozh_gorm'), 'подтверждено', 'ложь не подтверждена');
}
{
  const S = воДворе(3, 1);
  assert.equal(кнопка(S, 'Купить у Нима весточку про Горма').можно, false, 'не хватает 2 гр.');
}

// ── чётный день: двор детский, можно судить игру в бой; Бранка теплеет
{
  const S = воДворе(4);
  assert.equal(кнопка(S, 'Рассудить детскую игру в бой') !== undefined, true);
  const до = распол(S, 'branka');
  нажать(S, 'Рассудить детскую игру в бой');
  assert.equal(распол(S, 'branka'), до + 1);
  assert.equal(кнопка(S, 'Рассудить детскую игру в бой'), undefined, 'раз в день');
}
{
  const S = воДворе(3);
  assert.equal(кнопка(S, 'Рассудить детскую игру в бой'), undefined, 'в нечётный день детей во дворе нет');
}

// ── Бранка называет имена тем, кого она к себе расположила (два уровня), либо большой стиркой на день 10
{
  const S = воДворе(4);
  assert.equal(кнопка(S, 'Спросить Бранку, кого Горм положил'), undefined, 'чужому не скажет');
  S.мир.люди.branka = { спрошено: [], исчерпано: [], распол: 2 };
  нажать(S, 'Спросить Бранку, кого Горм положил');
  assert.ok(S.мир.темы.includes('branka_znaet'));
  assert.equal(кнопка(S, 'Спросить Бранку, кого Горм положил'), undefined, 'тема уже известна');
}
{
  const S = воДворе(9);
  assert.equal(кнопка(S, 'Помочь с большой стиркой'), undefined, 'стирка только в день 10');
  вернутьсяВГород(S);
  воДворе(10, 100, S);
  const до = брат(S);
  нажать(S, 'Помочь с большой стиркой');
  assert.equal(брат(S), до + 1);
  assert.ok(S.мир.темы.includes('branka_znaet'));
  assert.equal(кнопка(S, 'Помочь с большой стиркой'), undefined);
  вернутьсяВГород(S);
  воДворе(12, 100, S);
  assert.equal(кнопка(S, 'Помочь с большой стиркой'), undefined, 'после дня 10 стирки нет');
}

// ── ставка на большой бой: только день 25, 5 гр.; выиграл — вдвое (+10), проиграл — потерял
for (const день of [24, 26]) {
  const S = воДворе(день);
  assert.equal(кнопка(S, 'Поставить 5 гр.'), undefined, `в день ${день} большого боя нет`);
}
{
  const S = воДворе(25);
  S.мир.сид = сидДля(true);
  нажать(S, 'Поставить 5 гр.');
  assert.equal(S.герой.кошель, 105, '−5 ставка, +10 выигрыш');
  assert.match(S.сцена.реплика, /десять грошей/);
  assert.equal(кнопка(S, 'Поставить 5 гр.'), undefined, 'одна ставка в день');
}
{
  const S = воДворе(25);
  S.мир.сид = сидДля(false);
  нажать(S, 'Поставить 5 гр.');
  assert.equal(S.герой.кошель, 95);
  assert.match(S.сцена.реплика, /ложится первым/);
}
{
  const S = воДворе(25, 4);
  assert.equal(кнопка(S, 'Поставить 5 гр.').можно, false, 'без 5 гр. ставку не примут');
}

