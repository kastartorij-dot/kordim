// Бот с человеческой задержкой для живых игр песочницы (чистые ядра без холста): видит то, что было
// ~200–250 мс назад, с шумом глаза, и жмёт с шумом руки. Нужен, чтобы проверять сложность расчётом, а не на глаз.

// Простое зерно случайности (mulberry32): партии повторяются.
export function зерно(n) {
  let a = n >>> 0;
  return () => {
    a = (a + 0x6D2B79F5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
export const гаусс = с => Math.sqrt(-2 * Math.log(1 - с())) * Math.cos(2 * Math.PI * с());

// Торг: держать, пока рамка (с упреждением по скорости) левее метки. Видит метку и рамку с задержкой.
export function ботТорга({ новаяСделка, шагСделки, очкиСделки }, { вариант, навык, сид, задержка = 0.22, глаз = 0.025, рука = 0.05 }) {
  const с = новаяСделка({ вариант, навык, случ: зерно(сид) });
  const сб = зерно(сид * 7 + 3);
  const dt = 1 / 60;
  const прошлое = [];
  const з = задержка + сб() * 0.04 - 0.02;
  let держит = false;
  let доРешения = 0;
  let провал = 0;
  for (let k = 0; k < 60 * 60; k++) {
    прошлое.push({ цель: с.цель, рамка: с.рамка, скор: с.скор });
    // человек поправляет руку рывками, ~8 раз в секунду, и иногда на миг отвлекается
    доРешения -= dt;
    провал -= dt;
    if (провал <= 0 && сб() < dt * 0.35) провал = 0.25 + сб() * 0.25;
    if (доРешения <= 0 && провал <= 0) {
      доРешения = 0.09 + сб() * 0.08;
      const i = Math.max(0, прошлое.length - 1 - Math.round(з / dt));
      const в = прошлое[i];
      const цель = в.цель + гаусс(сб) * глаз;
      const скор = в.скор + гаусс(сб) * 0.1;
      const будет = в.рамка + скор * (з + 0.2) + гаусс(сб) * рука;
      держит = будет < цель;
    }
    if (шагСделки(с, dt, держит)) break;
  }
  return { очки: очкиСделки(с), итог: с.итог, t: с.t };
}

export const уровень = (о, [а, б]) => (о >= б ? 'отлично' : о >= а ? 'нормально' : 'плохо');
export function раскладка(список) {
  const р = { плохо: 0, нормально: 0, отлично: 0 };
  for (const у of список) р[у]++;
  const n = список.length;
  return Object.fromEntries(Object.entries(р).map(([к, v]) => [к, Math.round((v / n) * 100)]));
}

// Вес: смотрит середину качания стрелки за последние 0,8 с (с задержкой), по рискам решает, какую гирьку
// положить или снять; клик стоит 0,45–0,8 с; пишет, когда стрелка видимо замерла у нуля.
export function ботВеса(м, { вариант, навык, сид, задержка = 0.22, глаз = 0.012 }) {
  const в = м.новыеВесы({ вариант, навык, случ: зерно(сид) });
  const сб = зерно(сид * 13 + 5);
  const dt = 1 / 60;
  const з = задержка + сб() * 0.04 - 0.02;
  const след = [];
  let занят = 0.6;
  for (let k = 0; k < 60 * 120 && !в.кончено; k++) {
    const событие = м.шагВесов(в, dt);
    if (событие === 'пора') { м.записатьВес(в, true); след.length = 0; занят = 0.5; continue; }
    след.push(м.стрелка(в) - в.ноль + гаусс(сб) * глаз);
    занят -= dt;
    if (занят > 0) continue;
    const сдвиг = Math.round(з / dt);
    const окно = след.slice(Math.max(0, след.length - сдвиг - 96), Math.max(0, след.length - сдвиг));
    if (окно.length < 60) continue;
    const сейчас = окно[окно.length - 1];
    const скор = (сейчас - окно[окно.length - 7]) / (6 * dt);
    const размах = Math.max(...окно) - Math.min(...окно);
    const середина = окно.reduce((a, b) => a + b, 0) / окно.length;
    // стрелка лежит на упоре — разница больше восьми мер
    const упор = Math.abs(середина) > 0.82;
    if (!упор && размах > 0.16) continue; // ждёт, пока качание уляжется
    const мер = упор ? Math.sign(середина) * 9 : середина / м.ДЕЛЕНИЕ + гаусс(сб) * 0.18;
    const надо = Math.round(мер * 2) / 2;
    if (надо >= 0.5) {
      const г = м.ГИРИ.find(x => x <= надо) ?? 0.5;
      м.положитьГирю(в, г);
      след.length = 0;
      занят = 0.45 + сб() * 0.35;
    } else if (надо <= -0.5) {
      м.снятьГирю(в);
      след.length = 0;
      занят = 0.45 + сб() * 0.35;
    } else if (Math.abs(сейчас) < в.зона * 0.9 && Math.abs(скор) / 2.2 < в.покойСкор * 0.9) {
      м.записатьВес(в);
      след.length = 0;
      занят = 0.6 + сб() * 0.3;
    }
  }
  return { очки: м.очкиВесов(в), книга: в.книга };
}
