// Тестам: поставить часы мира так, чтобы до закрытия текущего места оставалось n делений (Р19).
// Раньше тесты выставляли S.сцена.ходы; теперь конец вечера — это время мира, а не счётчик визита.
import { доЗакрытия } from '../../Движок/часы-места.js';

export function оставить(S, n) {
  for (const о of ['ночь', 'вечер', 'день', 'утро']) for (let д = 5; д >= 0; д--) {
    S.мир.отрезок = о; S.мир.деление = д;
    if (S.сцена) S.сцена.отрезок = о;
    if (доЗакрытия(S) === n) return S;
  }
  throw new Error(`нет времени, при котором до закрытия ${n}`);
}
