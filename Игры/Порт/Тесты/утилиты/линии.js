// Помощники маршрутных проверок шага 11: настоящие кнопки движка, без подстановки состояния.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { войти, действияСцены, вернутьсяВГород } from '../../Движок/разговор.js';
import { лечьСпать } from '../../Движок/время.js';
import { сохранить, загрузить } from '../../Движок/состояние.js';

// Режим приёмки: после каждого нажатия партия сохраняется и загружается, игра продолжается с загруженного состояния.
let сЗагрузкой = false, загрузок = 0;
const память = new Map();
export function включитьСохранение() {
  сЗагрузкой = true;
  globalThis.localStorage = { getItem: k => память.get(k) ?? null, setItem: (k, v) => память.set(k, String(v)), removeItem: k => память.delete(k) };
}
export const сколькоЗагрузок = () => загрузок;
function черезСохранение(S) {
  if (!сЗагрузкой) return;
  const до = JSON.stringify(S);
  сохранить(S, 'авто');
  const L = загрузить('авто');
  assert.ok(L, 'партия загружается');
  assert.equal(JSON.stringify(L), до, 'загрузка не меняет партию');
  for (const k of Object.keys(S)) delete S[k];
  Object.assign(S, L);
  загрузок++;
}

export const ids = S => действияСцены(S).map(а => а.id);
export const есть = (S, id) => ids(S).includes(id);
export function нажать(S, id) {
  const а = действияСцены(S).find(х => (id instanceof RegExp ? id.test(х.id) : х.id === id));
  assert.ok(а, `нет действия ${id} (${S.сцена?.место}/${S.сцена?.комната}): ${ids(S).join(', ')}`);
  assert.notEqual(а.можно, false, `${id}: ${а.почему}`);
  а.выполнить(S);
  черезСохранение(S);
}
export function конецДня(S) {
  if (S.сцена) вернутьсяВГород(S);
  S.мир.отрезок = 'ночь'; лечьСпать(S, null); S.мир.конецДня = null; S.мир.отрезок = 'утро';
  черезСохранение(S);
}
export const доДня = (S, д) => { while (S.мир.день < д) конецДня(S); };
export function вХаб(S) {
  for (let i = 0; i < 5 && S.сцена.диалог?.режим !== 'хаб'; i++) {
    const а = действияСцены(S).find(х => х.id.startsWith('вариант:') && !/уйти|уйду|позже|попрощаться/.test(х.id + х.текст));
    assert.ok(а, 'нет перехода в хаб'); а.выполнить(S);
  }
}
export const ветка = (S, в, ...варианты) => { нажать(S, `ветка:${в}`); for (const x of варианты) нажать(S, `вариант:${в}:${x}`); };
const бодрый = S => { S.герой.кошель = Math.max(S.герой.кошель, 200); S.герой.тело = { сыт: 3, отдых: 3, тепло: 3, цел: 3 }; };

// Вечер в «Синем часе» у человека: путь — комнаты после входа, последняя — где он.
export function вечерДома(S, кто, путь) {
  if (S.сцена) вернутьсяВГород(S);
  бодрый(S);
  S.мир.район = 'доки'; S.мир.отрезок = 'вечер';
  войти(S, 'синий-час');
  нажать(S, 'вариант:вход:платить'); нажать(S, 'вариант:вход:войти');
  for (const к of путь) if (S.сцена.комната !== к) нажать(S, (к.startsWith('komnata') ? 'подняться:' : 'пойти:') + к); // «Войти.» уже ведёт в зал
  нажать(S, `заговорить:${кто}`); вХаб(S);
}
// Рынок в нужный отрезок; комната — ряд, где ждут.
export function рынок(S, отрезок, комната) {
  if (S.сцена) вернутьсяВГород(S);
  бодрый(S);
  S.мир.район = 'торговый'; S.мир.отрезок = отрезок;
  войти(S, 'рынок');
  for (let i = 0; i < 3 && S.сцена.диалог; i++) вХаб(S);
  if (S.сцена.комната !== комната) нажать(S, `пойти:${комната}`);
}
export const читатьСцену = id => readFile(new URL(`../../Сцены/Близость/${id}.md`, import.meta.url), 'utf8');
// Комнатное действие по тексту кнопки (у них номерные id).
export function нажатьТекст(S, текст) {
  const а = действияСцены(S).find(х => х.текст === текст);
  assert.ok(а, `нет кнопки «${текст}»: ${действияСцены(S).map(х => х.текст).join(' | ')}`);
  а.выполнить(S);
  черезСохранение(S);
}
export const естьТекст = (S, текст) => действияСцены(S).some(х => х.текст === текст);
