// Боты для живых задумок (Движок/песочница/разлив.js, разноска.js, узел.js): играют «как человек» —
// видят состояние игры, решают с задержкой реакции 200–250 мс и с дрожью руки. Нужны, чтобы проверить сложность:
// навык «нет» — в основном «нормально» и «плохо», «отлично» — редко. Запуск — Тесты/задумки-боты.mjs.
const гаусс = () => { let u = 0, v = 0; while (!u) u = Math.random(); while (!v) v = Math.random(); return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v); };
export const реакция = () => Math.max(0.15, 0.225 + 0.04 * гаусс()); // секунды

// Отложенные действия: бот «решил» сейчас, рука сделает через реакцию.
function рука() {
  const дела = [];
  return {
    потом(через, f) { дела.push({ t: через, f }); },
    шаг(dt) { for (const д of [...дела]) { д.t -= dt; if (д.t <= 0) { дела.splice(дела.indexOf(д), 1); д.f(); } } },
    занята: () => дела.length > 0,
    сброс() { дела.length = 0; },
  };
}

// ── Разлив ─────────────────────────────────────────────────────────────
// Как человек: льёт, отпускает чуть раньше расчёта (ожидаемый уровень — налито + что летит + что дольётся, пока
// кувшин выпрямляется; оценка «на глаз» ±25%, упреждение на свою реакцию ~0,85 ± 0,2), потом доливает короткими
// нажатиями; лишней пене даёт лечь, если гость терпит; горячее льёт вполнаклона. Подаёт через реакцию.
export function ботРазлива() {
  const р = рука();
  const ЛЬЁТ = 140;
  let стадия = 'нет', ждать = 0, глаз = 1, упреждение = 1, запас = 6, доливов = 0;
  const нажать = (и, вниз, через = реакция()) => р.потом(через, () => и.клавиша('Space', вниз));
  return (и, dt = 1 / 60) => {
    р.шаг(dt);
    const о = и.отладка();
    if (!о?.сосуд || о.въезд > 0) {
      if (стадия !== 'нет' && стадия !== 'новый') { р.сброс(); и.клавиша('Space', false); }
      стадия = о?.сосуд ? 'новый' : 'нет';
      return;
    }
    const с = о.сосуд;
    if (стадия === 'нет' || стадия === 'новый') {
      стадия = 'ждёт'; ждать = реакция(); доливов = 0;
      глаз = 1 + 0.25 * гаусс(); упреждение = 0.85 + 0.2 * гаусс(); запас = 6 + 3 * Math.abs(гаусс());
    }
    if (р.занята()) return;
    if (ждать > 0) { ждать -= dt; return; }
    const шир = с.w >= 104 ? 104 / с.w : Math.sqrt(104 / с.w);
    const поток = а => ЛЬЁТ * о.поток * Math.pow(Math.max(0, (а - 0.3) / 0.7), 1.4);
    const летит = поток(о.наклон) * о.полёт * шир;
    const дольёт = поток(о.наклон) * Math.max(0, о.наклон - 0.3) / о.выпрям * 0.45 * шир;
    const цельВсего = с.h * с.черта;
    const винаНадо = с.вино && о.жидкость === 'вино';
    const цель = винаНадо ? цельВсего * с.вино : цельВсего;
    const есть = винаНадо ? о.вина : о.уровень + о.пена * 0.1;
    const ждём = есть + (летит + дольёт) * глаз + поток(о.наклон) * шир * 0.225 * упреждение;
    const пустойКовш = Number.isFinite(о.ковш) && о.ковш <= 0;
    if (стадия === 'ждёт') { стадия = 'льёт'; нажать(и, true, 0.02); return; }
    if (стадия === 'льёт') {
      if (о.брызги && о.наклон > 0.68) { стадия = 'вполнаклона'; нажать(и, false, реакция() * 0.5); return; }
      if (ждём >= цель - запас || пустойКовш) { стадия = 'отпустил'; ждать = 0; нажать(и, false); }
      return;
    }
    if (стадия === 'вполнаклона') {
      if (ждём >= цель - запас) { стадия = 'отпустил'; return; }
      if (о.наклон < 0.55 && !пустойКовш) { стадия = 'льёт'; нажать(и, true, реакция() * 0.5); }
      return;
    }
    if (стадия === 'отпустил') {
      // ждать, пока кувшин выпрямится и струя долетит
      if (о.наклон > 0.3 || поток(о.наклон) > 0) return;
      ждать = 0.2 + реакция();
      стадия = 'смотрит';
      return;
    }
    if (стадия === 'смотрит') {
      if (о.черпает > 0) return;
      const недолив = цель - есть;
      if (!с.шапка && !винаНадо && о.пена > 16 && о.уровень < цель - 2) { ждать = 0.3; return; } // пусть пена ляжет
      if (недолив > 3 + 2 * Math.abs(гаусс()) && доливов < (Number.isFinite(о.ковш) ? 10 : 6)) {
        доливов++;
        стадия = 'долив';
        нажать(и, true, 0.02);
        // короткое нажатие: дольше, если не хватает много
        нажать(и, false, Math.max(0, (0.32 - о.наклон) / о.клон) + Math.max(0.1, Math.min(0.6, 0.12 + недолив / 110) + 0.03 * гаусс()));
        return;
      }
      if (винаНадо) { стадия = 'вода'; р.потом(реакция() + 0.15, () => и.клавиша('KeyQ', true)); return; }
      стадия = 'подаёт';
      р.потом(реакция() + 0.1, () => и.клавиша('Enter', true));
      return;
    }
    if (стадия === 'долив') { стадия = 'отпустил'; return; }
    if (стадия === 'вода') { стадия = 'ждёт'; ждать = реакция() * 0.5; доливов = 0; return; }
  };
}

// ── Разноска ───────────────────────────────────────────────────────────
// Как человек: срочное — первым, дальше ближайшее по пути; раз в реакцию смотрит вперёд и ставит указатель
// по дороге, обходит того, кто прямо на пути; у стражи идёт шагом; в густой толпе кричит «Посторонись!».
// Рука дрожит: указатель ±8 точек.
export function ботРазноски() {
  let думать = 0, цель = null;
  const указ = { x: 0, y: 0 };
  return (и, dt = 1 / 60) => {
    const о = и.отладка();
    if (!о) return;
    думать -= dt;
    if (думать > 0) return;
    думать = реакция();
    const г = о.герой;
    const ост = о.свёртки.map((с, i) => ({ ...с, i })).filter(с => !с.отдан);
    if (!ост.length) return;
    const срочный = ост.find(с => с.вид === 'срочно');
    if (!цель || о.свёртки[цель].отдан) цель = (срочный ?? ост.reduce((а, б) => (о.расстояние(б.i, г.x, г.y) < о.расстояние(а.i, г.x, г.y) ? б : а))).i;
    // точка пути на 3 клетки вперёд
    let p = { x: г.x, y: г.y };
    for (let k = 0; k < 3; k++) { const n = о.следующая(цель, p.x, p.y); if (!n) break; p = n; }
    const т = о.свёртки[цель].точка;
    if (Math.hypot(т.x - г.x, т.y - г.y) < 70) p = т;
    let dx = p.x - г.x, dy = p.y - г.y;
    const д = Math.hypot(dx, dy) || 1;
    dx /= д; dy /= д;
    // кучка зевак впереди — обойти по касательной, как обходят толпу
    for (const к of о.кучки ?? []) {
      const rx = к.x - г.x, ry = к.y - г.y, вперёд = rx * dx + ry * dy, вбок = rx * dy - ry * dx;
      if (вперёд > 0 && вперёд < 140 && Math.abs(вбок) < к.r + 14) {
        const бок = вбок > 0 ? 1 : -1;
        const ndx = dx + -dy * бок * 1.6, ndy = dy + dx * бок * 1.6, дн = Math.hypot(ndx, ndy) || 1;
        dx = ndx / дн; dy = ndy / дн;
      }
    }
    // кто на пути: в конусе впереди ближе 50
    const помехи = [...о.люди, ...о.тележки, ...о.стражи].filter(ч => {
      const rx = ч.x - г.x, ry = ч.y - г.y, вперёд = rx * dx + ry * dy, вбок = Math.abs(rx * dy - ry * dx);
      return вперёд > 0 && вперёд < 55 && вбок < (ч.r ?? 12) + 16;
    });
    if (помехи.length) {
      const ч = помехи[0];
      const бок = (ч.x - г.x) * dy - (ч.y - г.y) * dx > 0 ? 1 : -1; // обойти с другой стороны
      const ndx = dx - dy * бок * 1.1, ndy = dy + dx * бок * 1.1;
      dx = ndx; dy = ndy;
      const д2 = Math.hypot(dx, dy) || 1; dx /= д2; dy /= д2;
      if (помехи.length >= 2 && о.окриков > 0 && Math.random() < 0.5) и.клавиша('Space', true);
    }
    const страж = о.стражи.some(с => Math.hypot(с.x - г.x, с.y - г.y) < 120 && с.отдых <= 0);
    const хрупкое = о.свёртки.some(с => !с.отдан && с.вид === 'хрупкий');
    const даль = страж ? 22 : помехи.length ? (хрупкое ? 16 : 30) : 90;
    указ.x = г.x + dx * даль + 8 * (Math.random() * 2 - 1);
    указ.y = г.y + dy * даль + 8 * (Math.random() * 2 - 1);
    и.мышь('двиг', указ.x, указ.y);
  };
}
