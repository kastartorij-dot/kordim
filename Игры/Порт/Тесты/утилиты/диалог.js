import assert from 'node:assert/strict';
import { действияСцены } from '../../Движок/разговор.js';
export function хаб(S) {
  for(let i=0;i<12&&S.сцена?.диалог?.режим==='ветка';i++){
    const A=действияСцены(S).filter(a=>a.вид==='вариант'&&a.можно);
    const а=A.find(a=>!a.закреплён)??A[0];assert.ok(а,'нет выхода из приветствия');а.выполнить(S);
  }
  assert.ok(S.сцена?.диалог?.режим==='хаб','ожидался хаб');
}
export function отойти(S) {
  for(let i=0;i<12&&S.сцена?.собеседник&&!S.сцена.конец;i++){
    const A=действияСцены(S).filter(a=>a.можно);
    const а=A.find(a=>a.id==='отойти')??A.find(a=>a.id==='закончить')??A.find(a=>a.вид==='вариант'&&a.закреплён)??A.find(a=>a.вид==='вариант');
    assert.ok(а,'нет выхода из беседы');а.выполнить(S);
  }
  assert.ok(!S.сцена?.собеседник||S.сцена.конец,'беседа должна закрыться');
}
export function нажать(S,id){const a=действияСцены(S).find(a=>a.id===id);assert.ok(a?.можно,'нет действия '+id);a.выполнить(S);}
