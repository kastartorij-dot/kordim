// Шаг 11, пакет 1: общий каркас личных линий. Запуск: node Игры/Порт/Тесты/шаг11.mjs
// Проверяет раздельные оси (доверие, влечение, доступ), этапы по порядку, решение человека,
// отсутствие героя, обещания, примирение, выбор сцены без цены и наличие всех файлов сцен.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { новоеСостояние } from '../Движок/состояние.js';
import { войти, действияСцены, догрузитьСцену, выбратьСценуБлизости } from '../Движок/разговор.js';
import { лечьСпать } from '../Движок/время.js';
import { МЕСТА } from '../Данные/места.js';
import { ЛИНИИ, ЭТАПЫ, ПРАВИЛА } from '../Данные/связи.js';
import { связь, отметитьВстречу, сдвинутьЭтап, оплаченныйВечер, решить, примириться, расстаться,
  пообещать, сдержать, поступок, применитьСвязь, условиеСвязи, другиеСвязи } from '../Движок/связи.js';
import { если } from '../Движок/диалог.js';
import { сводкаЖурнала } from '../Движок/сводка.js';
import { сценыБлизости, недостающиеСцены } from '../Скрипты/сцены-близости.mjs';

const новая = (день = 3) => {
  const S = новоеСостояние('семья', 11);
  S.мир.день = день; S.герой.кошель = 500;
  return S;
};
const дов = (S, кто, n) => { (S.мир.люди[кто] ??= { спрошено: [], исчерпано: [] }).распол = n; };
function конецДня(S) {
  S.мир.отрезок = 'ночь'; лечьСпать(S, null);
  S.мир.конецДня = null; S.мир.отрезок = 'утро';
}
const нажать = (S, id) => { const а = действияСцены(S).find(х => х.id === id); assert.ok(а, `нет действия ${id} в ${S.сцена?.комната}: ${действияСцены(S).map(х => х.id).join(', ')}`); а.выполнить(S); };

// ── три линии записаны, этапы полные ────────────────────────────────────
assert.deepEqual(Object.keys(ЛИНИИ), ['freya', 'niya', 'tava']);
assert.deepEqual(ЭТАПЫ, ['нет', 'знакомство', 'встречи', 'вне-работы', 'поворот', 'решение', 'после']);

// ── ранние этапы: встречи в разные дни и доверие, не одна долгая беседа ──
{
  const S = новая();
  отметитьВстречу(S, 'freya');
  assert.equal(связь(S, 'freya').этап, 'знакомство');
  отметитьВстречу(S, 'freya'); // тот же день — не вторая встреча
  assert.equal(связь(S, 'freya').этап, 'знакомство');
  S.мир.день += 1; отметитьВстречу(S, 'freya');
  assert.equal(связь(S, 'freya').этап, 'знакомство', 'без доверия встречи не становятся сближением');
  дов(S, 'freya', 1); S.мир.день += 1; отметитьВстречу(S, 'freya');
  assert.equal(связь(S, 'freya').этап, 'встречи');
  // поздние этапы — по одному и только эффектом
  assert.equal(сдвинутьЭтап(S, 'freya', 'поворот'), false, 'этап не перескакивает');
  assert.equal(сдвинутьЭтап(S, 'freya', 'вне-работы'), true);
  assert.equal(сдвинутьЭтап(S, 'freya', 'вне-работы'), false, 'повтор этапа ничего не меняет');
  assert.ok(связь(S, 'freya').история.some(з => з.что === 'этап: вне-работы'));
  // чужая линия не затронута
  assert.equal(S.мир.связи.niya, undefined);
}

// ── оплаченный вечер: доступ растёт, доверие, влечение и этап — нет ─────
{
  const S = новая();
  дов(S, 'freya', 1); отметитьВстречу(S, 'freya');
  for (let i = 0; i < 5; i++) оплаченныйВечер(S, 'freya');
  const с = связь(S, 'freya');
  assert.equal(с.доступ, 5);
  assert.equal(с.влечение, 0);
  assert.equal(S.мир.люди.freya.распол, 1);
  assert.equal(с.этап, 'знакомство');
}

// ── выбор сцены: по доверию и этапу, высокое доверие без встреч не открывает вторую ──
{
  const К = МЕСТА.find(м => м.id === 'синий-час').модуль.КОМНАТЫ;
  for (const кто of ['freya', 'niya']) {
    const б = К[кто === 'freya' ? 'komnata_frei' : 'komnata_nii'].близость;
    assert.equal(б.распол, undefined, `${кто}: оплаченный вечер не даёт доверия`);
    const S = новая();
    S.сцена = { собеседник: кто }; // условие графа читает собеседника только через кто
    дов(S, кто, 4); отметитьВстречу(S, кто);
    assert.equal(выбратьСценуБлизости(S, б, кто), `${кто}_1`, `${кто}: доверие 4 без повторных встреч — первая сцена`);
    S.мир.день += 1; отметитьВстречу(S, кто);
    assert.equal(связь(S, кто).этап, 'встречи');
    assert.equal(выбратьСценуБлизости(S, б, кто), `${кто}_2`);
    дов(S, кто, 1);
    assert.equal(выбратьСценуБлизости(S, б, кто), `${кто}_1`, `${кто}: этап без доверия — первая сцена`);
  }
}

// ── настоящий вечер: «остаться» у Фреи ничего не прибавляет к доверию ────
{
  const S = новая(4);
  S.мир.отрезок = 'вечер'; S.мир.район = 'доки';
  войти(S, 'синий-час');
  нажать(S, 'вариант:вход:платить'); нажать(S, 'вариант:вход:войти');
  нажать(S, 'пойти:zal'); нажать(S, 'пойти:lestnica');
  нажать(S, 'подняться:komnata_frei');
  нажать(S, 'заговорить:freya');
  for (let i = 0; i < 5 && S.сцена.диалог?.режим !== 'хаб'; i++) {
    const а = действияСцены(S).find(х => х.id.startsWith('вариант:') && !/уйти|уйду|позже/.test(х.id + х.текст));
    а.выполнить(S);
  }
  const до = S.мир.люди.freya?.распол ?? 0;
  нажать(S, 'остаться');
  assert.equal(S.мир.люди.freya?.распол ?? 0, до, 'цена комнаты не покупает доверие');
  assert.equal(связь(S, 'freya').доступ, 1);
  assert.equal(S.сцена.нужнаСцена, 'freya_1');
  await догрузитьСцену(S, id => readFile(new URL(`../Сцены/Близость/${id}.md`, import.meta.url), 'utf8'));
  assert.match(S.сцена.реплика, /Фрея закрывает дверь/);
  const ж = сводкаЖурнала(S).связи.find(x => x.кто === 'freya');
  assert.ok(ж, 'линия видна в журнале');
  assert.match(ж.числа, /оплаченных вечеров 1 — это доступ, а не близость/);
}

// ── её решение: «нет» не отменяют числа и не снимает примирение ─────────
{
  const S = новая();
  дов(S, 'niya', 4);
  применитьСвязь(S, 'niya', { влечение: 5 });
  assert.equal(связь(S, 'niya').влечение, ПРАВИЛА.влечение[1], 'влечение ограничено');
  решить(S, 'niya', 'нет');
  assert.equal(связь(S, 'niya').статус, 'отказ');
  assert.equal(условиеСвязи(S, 'niya', { решение: 'да' }), false);
  assert.equal(примириться(S, 'niya'), false);
  assert.equal(расстаться(S, 'niya'), false, 'нечего заканчивать');
  // новое решение — только её же
  решить(S, 'niya', 'дружба');
  assert.equal(связь(S, 'niya').статус, 'дружба');
}

// ── отсутствие героя: пауза, расставание, примирение ────────────────────
{
  const S = новая(2);
  отметитьВстречу(S, 'tava');
  решить(S, 'tava', 'да');
  // дни считаются по закрытию суток: встреча днём 2, пауза — при закрытии дня 2 + пауза
  for (let i = 0; i <= ПРАВИЛА.отсутствие.пауза; i++) конецДня(S);
  assert.equal(связь(S, 'tava').статус, 'пауза');
  assert.ok((S.мир.хроника ?? []).some(д => д.журнал.some(с => /Тава давно тебя не видела/.test(с))), 'пауза записана в журнал дня');
  for (let i = ПРАВИЛА.отсутствие.пауза; i < ПРАВИЛА.отсутствие.расставание; i++) конецДня(S);
  assert.equal(связь(S, 'tava').статус, 'расстались');
  assert.ok(связь(S, 'tava').история.some(з => з.что === 'расстались: отсутствие'));
  assert.equal(примириться(S, 'tava'), true);
  assert.equal(связь(S, 'tava').статус, 'вместе');
}

// ── обещания: сдержанное и нарушенное ───────────────────────────────────
{
  const S = новая(5);
  дов(S, 'freya', 2);
  пообещать(S, 'freya', { ид: 'дом-напротив', что: 'сходить с ней к дому напротив', дней: 2 });
  пообещать(S, 'freya', { ид: 'окно', что: 'прийти к окну', дней: 1 });
  assert.equal(пообещать(S, 'freya', { ид: 'окно', что: 'повтор' }), false);
  assert.equal(условиеСвязи(S, 'freya', { обещание: 'окно' }), true);
  assert.equal(сдержать(S, 'freya', 'дом-напротив'), true);
  конецДня(S); // день 5
  assert.equal(связь(S, 'freya').обещания.find(о => о.ид === 'окно').статус, 'дано', 'срок — до конца дня 6');
  конецДня(S); // день 6
  const об = связь(S, 'freya').обещания;
  assert.equal(об.find(о => о.ид === 'окно').статус, 'нарушено');
  assert.equal(об.find(о => о.ид === 'дом-напротив').статус, 'сдержано');
  assert.equal(S.мир.люди.freya.распол, 1, 'нарушенное слово стоит доверия');
  assert.equal(условиеСвязи(S, 'freya', { обещание: ['окно', 'нарушено'] }), true);
}

// ── поступки однократны; несколько связей видны друг другу ──────────────
{
  const S = новая();
  дов(S, 'freya', 0);
  assert.equal(поступок(S, 'freya', 'починка', { доверие: 1 }), true);
  assert.equal(поступок(S, 'freya', 'починка', { доверие: 1 }), false);
  assert.equal(S.мир.люди.freya.распол, 1);
  решить(S, 'freya', 'да'); решить(S, 'tava', 'да');
  assert.deepEqual(другиеСвязи(S, 'tava'), ['freya']);
  assert.equal(условиеСвязи(S, 'tava', { другаяСвязь: true }), true);
  assert.equal(условиеСвязи(S, 'niya', { другаяСвязь: true, кто: 'niya' }), true);
}

// ── условие графа понимает «связь» ──────────────────────────────────────
{
  const S = новая();
  S.сцена = { диалог: { кто: 'freya' } };
  дов(S, 'freya', 1); отметитьВстречу(S, 'freya'); S.мир.день += 1; отметитьВстречу(S, 'freya');
  assert.equal(если(S, { связь: { этапОт: 'встречи' } }), true);
  assert.equal(если(S, { связь: { этапОт: 'поворот' } }), false);
  assert.equal(если(S, { связь: { кто: 'tava', этапОт: 'знакомство' } }), false);
}

// ── все сцены близости лежат файлом ─────────────────────────────────────
assert.ok(сценыБлизости().length >= 4);
assert.deepEqual(await недостающиеСцены(), [], 'нет файла сцены — ошибка сборки');

