function ест(S, A) {
  const т = S.герой.тело;
  if (т.сыт <= 1) { const е = дешёвый(годные(A, 'еда')); if (е) return е; }
  if (т.тепло <= 1) { const п = по(A, 'еда:похлёбка'); if (п) return п; }
  return null;
}
function ночлег(S, A) {
  const сны = годные(A, 'сон');
  const заНочь = а => (а.id === 'сон:вдова' && а.цена === 25 ? 25 / 7 : а.цена);
  const т = S.герой.тело;
  const нужен = т.отдых <= 2 || т.цел <= 2 ? 3 : 2;
  const хорошие = сны.filter(а => а.отдых >= 2).sort((а, б) => заНочь(а) - заНочь(б));
  return (нужен === 3 ? сны.filter(а => а.отдых >= 3).sort((а, б) => заНочь(а) - заНочь(б))[0] : null) ?? хорошие[0] ?? дешёвый(сны);
}

// Политики выбора на карточках: смотрят в эффекты вариантов, а не в тексты.
const сумма = (э, к) => (Array.isArray(э) ? э : [э]).reduce((а, x) => а + (x?.[к] ?? 0), 0);
const ф = (э, к) => (Array.isArray(э) ? э : [э]).reduce((а, x) => а + Object.values(x?.[к] ?? {}).reduce((b, v) => b + v, 0), 0);
