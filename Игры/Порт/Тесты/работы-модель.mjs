import { случайСмены as случай } from '../Движок/смена.js';
function лучший(A, оценка) {
  const в = A.filter(а => а.можно && /^смена:выбор:\d+$/.test(а.id));
  if (!в.length) return A.find(а => а.можно);
  return [...в].sort((a, b) => оценка(+b.id.split(':')[2]) - оценка(+a.id.split(':')[2]))[0];
}

export function бот(план, опц = {}) {
  return (S, A) => {
    const { отрезок, район } = S.мир;
    const е = ест(S, A);
    if (е) return е;
    let [цель, работы = []] = план[отрезок];
    if (цель === 'маяк' && отрезок === 'вечер' && (S.герой.тело.отдых < 3 || S.герой.тело.цел < 2 || S.мир.фракции.ножи < 1)) цель = 'доки';
    const разбит = S.герой.тело.отдых === 0 || S.герой.тело.цел === 0;
    if (отрезок === 'вечер' && разбит) return ночлег(S, A) ?? A.find(a => a.id === 'отрезок:здесь');
    if (отрезок === 'ночь') {
      // работа ночью (охрана, маяк), если она в плане и доступна, иначе спать
      for (const id of работы) { const а = по(A, `работа:${id}`); if (а && выгодно(S, id, опц)) return а; }
      if (район !== цель && цель && план.ночь[0] !== район) { const х = по(A, `переход:${цель}`); if (х && опц.ходитьНочью) return х; }
      return ночлег(S, A) ?? A.find(a => a.id === 'отрезок:здесь');
    }
    if (район !== цель) { const х = по(A, `переход:${цель}`); if (х) return х; }
    for (const id of работы) {
      const а = по(A, `работа:${id}`);
      if (а && выгодно(S, id, опц)) return а;
    }
    return A.find(a => a.id === 'отрезок:здесь');
  };
}

// «Тело садится» — не работать за полцены; отдых 1 и меньше — не брать работу с ценой отдыха.
function выгодно(S, id, опц) {
  const р = работа(id);
  const { садится } = условияПлаты(S, р);
  if (садится && !опц.жаднее) return false;
  const отд = (р.цена?.отдых ?? 0) + допОтдых(S, р);
  if (отд && S.герой.тело.отдых - отд < 1 && !опц.жаднее) return false;
  if (р.цена?.риск && S.герой.тело.цел <= 1) return false;
  if ((id === 'охрана' || id === 'маяк') && (S.герой.тело.отдых < 3 || S.герой.тело.цел < 2)) return false; // ночные — не подряд
  if (опц.нужно && !опц.нужно(S, id)) return false;
  return true;
}

export function прогон(началоId, сид, стратегия, опц = {}, подготовка = null) {
  const S = новоеСостояние(началоId, сид);
  if (подготовка) подготовка(S);
  const план = typeof стратегия === 'string' ? ПЛАНЫ[стратегия] : стратегия;
  const ходить = бот(план, опц);
  const р = { заработок: 0, жизнь: 0, кошель: {}, смен: {}, дн: { работа: 0, дорога: 0, простой: 0 }, минТело: { сыт: 3, отдых: 3, тепло: 3, цел: 3 }, минВид: 3, голодныхДней: 0, нулейЦел: 0, ошибки: [], тем: 0 };
  let шаги = 0;
  const политика = ПОЛИТИКИ[опц.политика ?? 'первый'];
  const выбор = A => политика(A, S);
  while (S.мир.день <= ДНИ && шаги++ < 5000) {
    if (S.мир.смена) { авто(S, выбор); continue; }
    const A = доступныеДействия(S);
    const а = ходить(S, A);
    if (!а) { р.ошибки.push(`нет хода: день ${S.мир.день} ${S.мир.отрезок} ${S.мир.район}`); break; }
    const до = S.герой.кошель;
    if (а.вид === 'работа') { const id = а.id.split(':')[1]; р.смен[id] = (р.смен[id] ?? 0) + 1; р.дн.работа++; }
    else if (а.вид === 'переход') р.дн.дорога++;
    else if (а.вид === 'ждать' && S.мир.отрезок !== 'ночь') р.дн.простой++;
    а.выполнить(S);
    if (S.мир.смена) авто(S, выбор);
    const d = S.герой.кошель - до;
    if (d > 0) р.заработок += d; else р.жизнь -= d;
    for (const [к, v] of Object.entries(S.герой.тело)) {
      р.минТело[к] = Math.min(р.минТело[к], v);
      if (!Number.isInteger(v) || v < 0 || v > 3) р.ошибки.push(`${к}=${v}`);
    }
    р.минВид = Math.min(р.минВид, S.герой.вид);
    if (S.герой.кошель < 0 || !Number.isFinite(S.герой.кошель)) р.ошибки.push(`кошель ${S.герой.кошель}`);
    if (S.мир.конецДня) {
      const д = S.мир.конецДня.день;
      if (S.герой.тело.сыт === 0) р.голодныхДней++;
      if (S.герой.тело.цел === 0) р.нулейЦел++;
      if (ОТМЕТКИ.includes(д)) р.кошель[д] = S.герой.кошель;
      S.мир.конецДня = null;
    }
  }
  р.S = S;
  р.тем = S.мир.темы.length;
  return р;
}

const ср = (арр, ф, з = 0) => (арр.reduce((с, x) => с + ф(x), 0) / арр.length).toFixed(з);

export function таблица(началоId, стратегия, опц = {}, подготовка = null) {
  const g = ЗЕРНА.map(с => прогон(началоId, с, стратегия, опц, подготовка));
  const ошиб = g.flatMap(x => x.ошибки);
  const ступ = г => Object.entries(г.S.герой.ремёсла).map(([и, р]) => `${и}:${р.ступень[0]}${р.зарубки}`).join(',');
  const фр = г => ['ножи', 'картель', 'братство'].map(к => г.S.мир.фракции[к]).join('/');
  const отд0 = ср(g, x => x.минТело.отдых, 1);
  return {
    строка: `| ${стратегия}${опц.политика ? ' / ' + опц.политика : ''} | ${началоId} | ${ср(g, x => x.заработок / ДНИ, 1)} | ${ср(g, x => x.жизнь / ДНИ, 1)} | ${ОТМЕТКИ.map(д => ср(g, x => x.кошель[д] ?? 0)).join(' | ')} | ${отд0}/${ср(g, x => x.минТело.цел, 1)} | ${ср(g, x => x.нулейЦел, 1)} | ${g.map(фр).join(' ')} | ${ступ(g[0])} |`,
    ошибки: ошиб, g,
  };
}

