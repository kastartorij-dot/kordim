// Шаг 12: стенд мини-игр. node Игры/Порт/Тесты/шаг12-стенд.mjs
// У каждой игры есть стенд { id, имя, где, описание, начать(S) }; СТЕНД_ИГР собирает все семь игр
// («Чтение комнаты» — одной, место — вариант). Каждая начать(S) на новом состоянии любого начала запускает игру без ошибок,
// а первый доступный ход проходит. Порядок загрузки модулей не важен (стенды не тянут разговор и смену напрямую).
import assert from 'node:assert/strict';
import { новоеСостояние, мигрировать } from '../Движок/состояние.js';
import { СТЕНД_ИГР } from '../Движок/мини-игры.js';
import { доступныеДействия } from '../Движок/действия.js';
import { действияСцены } from '../Движок/разговор.js';
import { видСмены } from '../Движок/смена.js';

assert.deepEqual(СТЕНД_ИГР.map(с => с.id), ['вес', 'счёт', 'торг', 'кости', 'игла', 'мотив', 'чтение']);
for (const с of СТЕНД_ИГР) {
  for (const п of ['id', 'имя', 'где', 'описание']) assert.ok(typeof с[п] === 'string' && с[п].trim(), с.id + ': ' + п);
  assert.equal(typeof с.начать, 'function', с.id);
}
const вСмене = new Set(['вес', 'счёт', 'игла']);
for (const начало of ['семья', 'бумаги', 'наколки']) for (const с of СТЕНД_ИГР) {
  const S = новоеСостояние(начало, 11);
  assert.equal(с.начать(S), true, `${начало}: ${с.id} начинается`);
  if (вСмене.has(с.id)) {
    assert.equal(S.мир.смена?.стадия, 'задача', с.id);
    assert.equal(видСмены(S).задача.игра, с.имя, с.id);
    const а = доступныеДействия(S).find(x => x.можно);
    assert.ok(а, с.id + ': есть ход'); а.выполнить(S);
  } else {
    assert.ok(S.сцена?.игра, с.id + ': партия идёт');
    const а = действияСцены(S).find(x => x.можно);
    assert.ok(а, с.id + ': есть ход'); а.выполнить(S);
  }
  // Состояние стенда — обычное сохранение.
  мигрировать(JSON.parse(JSON.stringify(S)));
}
// Контракт страницы стенда (шапка Движок/стенд-игр.js): каждый вариант с каждой разумной ступенью запускается,
// выбранное задание и ступень доходят до игры.
const ремеслоИгры = (с, в) => (typeof с.ремесло === 'function' ? с.ремесло(в) : с.ремесло) ?? null;
for (const с of СТЕНД_ИГР) {
  const варианты = (с.варианты ?? []).map(в => в.id);
  assert.ok(варианты.length >= 2, с.id + ': есть из чего выбрать');
  assert.ok(с.подписьВарианта && с.подписьДругого, с.id + ': подписи');
  assert.ok((с.варианты ?? []).every(в => в.id && в.имя), с.id + ': у варианта id и имя');
  for (const вариант of варианты) {
    const рем = ремеслоИгры(с, вариант);
    for (const ступень of рем ? с.ступени ?? ['нет', 'умеешь', 'набил руку'] : [undefined]) {
      const S = новоеСостояние('семья', 13);
      assert.equal(с.начать(S, { вариант, ступень }), true, `${с.id}: ${вариант}, ${ступень}`);
      if (рем) assert.equal(S.герой.ремёсла[рем]?.ступень ?? 'нет', ступень, `${с.id}: ступень дошла`);
      if (вСмене.has(с.id)) assert.equal(S.мир.смена.задача.задание, вариант, с.id + ': выдано выбранное задание');
    }
  }
}
{ const S = новоеСостояние('семья', 14); СТЕНД_ИГР.find(с => с.id === 'чтение').начать(S, { вариант: 'лекарь' }); assert.equal(S.сцена.игра.чтение, 'лекарь'); }
{ const S = новоеСостояние('семья', 15); СТЕНД_ИГР.find(с => с.id === 'мотив').начать(S, { вариант: 'm3-dlinnaya:0' }); assert.equal(S.сцена.игра.песня, 'm3-dlinnaya'); assert.equal(S.мир.люди.nora.распол, 0); }
{ const S = новоеСостояние('семья', 16); СТЕНД_ИГР.find(с => с.id === 'кости').начать(S, { вариант: 'таверна' }); assert.equal(S.сцена.игра.партия, 'таверна'); }
console.log('шаг 12, стенд мини-игр: проверки пройдены');
