// Прогон 004, P1: род героя (PR004-01), выдуманное прошлое (PR001-05) и район нотариуса в подсказке «Имени» (PR004-02).
// Запуск: node Игры/Порт/Тесты/прогон004.mjs
import assert from 'node:assert/strict';
import { Р } from '../Данные/Места/синий-час.js';
import { ЖИТЕЛИ } from '../Данные/Диалоги/жители.js';
import { новоеСостояние } from '../Движок/состояние.js';
import { имя, следующийШагИмени } from '../Движок/имя.js';
import { выбратьЦель } from '../Движок/цели.js';
import { место } from '../Данные/места.js';
import { район } from '../Данные/районы.js';

// Все строки структуры, с путём до них.
function* строки(x, путь = '') {
  if (typeof x === 'string') yield [путь, x];
  else if (Array.isArray(x)) for (const [i, v] of x.entries()) yield* строки(v, `${путь}[${i}]`);
  else if (x && typeof x === 'object') for (const [k, v] of Object.entries(x)) yield* строки(v, путь ? `${путь}.${k}` : k);
}

// Снятые формулировки: герой только что приехал и нигде в доме не работал; к нему обращаются в мужском роде.
const СНЯТО = [
  /дошла своими/, /раз уж дошла/, /на трети дома/, /[Тт]воя вязь у меня/, /[Тт]воя работа у половины/,
  /снизу, из конторы/, /из конторы снизу/, /вы снизу\?/, /слышу через пол/, /помню по голосу/,
];
// Женская форма глагола после «ты» в речи жителя (реплики героя в «» к работницам — допустимы).
const ЖЕНСКИЙ_К_ГЕРОЮ = /(^|[^а-яё«])(ты|раз уж|наконец)\s+(дошла|пришла|вернулась|зашла|поднялась|приехала)(?=[^а-яё]|$)/i;

const найдено = [];
for (const [где, источник] of [['синий-час.Р', Р], ['жители', ЖИТЕЛИ]]) {
  for (const [путь, т] of строки(источник)) {
    const репликаГероя = /варианты\[\d+\]\.(текст|реплика)$/.test(путь) || /^«/.test(т);
    if (СНЯТО.some(р => р.test(т)) || (!репликаГероя && ЖЕНСКИЙ_К_ГЕРОЮ.test(т))) найдено.push(`${где}.${путь}: ${т.slice(0, 80)}`);
  }
}
assert.deepEqual(найдено, [], 'снятые формулировки о прошлом героя или женский род:\n' + найдено.join('\n'));

// Ответ старшей на тему «наколки» для начала «ремесло» узнаёт мастера по коже, а не по работе в доме.
const наколки = Р.starshaya.nakolki.любой.поПерсонажу.наколки;
assert.match(наколки, /кожа|Игольщик/);
assert.doesNotMatch(наколки, /твою работу|твоя работа/i);

// Подсказка цели «Имя» называет район и часы приёмной Нотариуса из данных места.
const S = новоеСостояние('наколки', 7);
S.мир.день = 3; S.мир.отрезок = 'утро';
выбратьЦель(S, 'имя');
имя(S);
const подсказка = следующийШагИмени(S);
const приёмная = место('приемная-нотариуса');
const районПриёмной = район(приёмная.район).имя;
assert.ok(подсказка.includes(`Нотариус в приёмной (${районПриёмной}, ${приёмная.когда.join(' или ')})`), подсказка);
assert.ok(!подсказка.includes('Торговый квартал'), подсказка);
assert.ok(подсказка.includes(`в контору (${район(место('контора-дорров').район).имя})`), подсказка);

console.log('прогон004: ok —', найдено.length, 'нарушений; подсказка:', подсказка);
