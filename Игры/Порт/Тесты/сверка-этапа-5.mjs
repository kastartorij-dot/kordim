// Проверка этапа 5: тексты состояний экрана «Герой» — слово в слово из таблиц Порт-задание-5.md.
// node Игры/Порт/Тесты/сверка-этапа-5.mjs
// Разбирает таблицы задания (тело, фракции, тень), названия фракций и слова репутации и сверяет с Данные/состояния.js;
// обратно: любая строка длиннее 12 символов в данных обязана быть в задании.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { ТЕЛО, ФРАКЦИИ, СТУПЕНИ, ТЕНЬ, РЕПУТАЦИЯ, В_ПОРЯДКЕ } from '../Данные/состояния.js';
import { словоРепутации } from '../Движок/сводка.js';

const МД = join(dirname(fileURLToPath(import.meta.url)), '..', 'Документы', 'Архив', 'Задания_Этапов_2_5', 'Этап_5_экраны_задание.md');
const строки = fs.readFileSync(МД, 'utf8').replace(/\r\n/g, '\n').split('\n');
const ошибки = [];
const плохо = с => ошибки.push(с);
const разрешено = new Set();
let проверок = 0;
const сверить = (что, факт, ожид) => { проверок++; разрешено.add(ожид); if (факт !== ожид) плохо(`${что}: в данных «${факт}», в задании «${ожид}»`); };

let раздел = '';
const ключФракции = { '−3': '-3', '−2': '-2', '−1': '-1', '0': '0', '+1': '1', '+2': '2', '+3': '3' };
for (const л of строки) {
  if (/^\| полоска \|/.test(л)) { раздел = 'тело'; continue; }
  if (/^\| значение \| фракция/.test(л)) { раздел = 'фракции'; continue; }
  if (/^\| тень \| строка \|/.test(л)) { раздел = 'тень'; continue; }
  if (!л.startsWith('|')) { if (л.trim()) раздел = раздел === 'тело' || раздел === 'фракции' || раздел === 'тень' ? '' : раздел; continue; }
  const ячейки = л.split('|').slice(1, -1).map(x => x.trim());
  if (/^-+$/.test(ячейки[0].replace(/:/g, ''))) continue;
  const снять = т => { const м = /^«(.*)»$/.exec(т); return м ? м[1] : null; };
  if (раздел === 'тело' && ячейки.length === 3) {
    const [к, а, б] = ячейки;
    if (!ТЕЛО[к]) { плохо(`в задании полоска «${к}», в данных нет`); continue; }
    сверить(`тело ${к}=1`, ТЕЛО[к][1], снять(а));
    сверить(`тело ${к}=0`, ТЕЛО[к][0], снять(б));
  } else if (раздел === 'фракции' && ячейки.length === 2) {
    const к = ключФракции[ячейки[0]];
    if (к === undefined) { плохо(`ступень «${ячейки[0]}» не разобрана`); continue; }
    сверить(`ступень ${ячейки[0]}`, СТУПЕНИ[к], снять(ячейки[1]));
  } else if (раздел === 'тень' && ячейки.length === 2) {
    сверить(`тень ${ячейки[0]}`, ТЕНЬ[Number(ячейки[0])], снять(ячейки[1]));
  }
}

// названия фракций
{
  const л = строки.find(x => x.startsWith('Названия фракций:'));
  const имена = [...л.matchAll(/«([^»]+)»/g)].map(м => м[1]);
  const данные = Object.values(ФРАКЦИИ);
  if (имена.join('|') !== данные.join('|')) плохо(`названия фракций: в данных ${данные}, в задании ${имена}`);
  проверок++; имена.forEach(и => разрешено.add(и));
}

// репутация: слова и границы
{
  const н = строки.findIndex(x => x.startsWith('Репутация —'));
  let к = н;
  while (строки[к].trim()) к++;
  const л = строки.slice(н, к).join(' '); // абзац переносится на следующую строку
  const слова = [...л.matchAll(/«([^»]+)»/g)].map(м => м[1]);
  if (слова.join('|') !== РЕПУТАЦИЯ.map(x => x.слово).join('|')) плохо(`слова репутации: в данных ${РЕПУТАЦИЯ.map(x => x.слово)}, в задании ${слова}`);
  проверок++; слова.forEach(с => разрешено.add(с));
  const ожид = { '-3': 'дурная', '-2': 'дурная', '-1': 'сомнительная', '0': 'никакая', '1': 'добрая', '2': 'громкая', '3': 'громкая' };
  for (const [з, с] of Object.entries(ожид)) { проверок++; if (словоРепутации(Number(з)) !== с) плохо(`репутация ${з}: «${словоРепутации(Number(з))}», ожидалось «${с}»`); }
}

// «в порядке» — из задания
проверок++;
if (!строки.some(л => л.includes(`«${В_ПОРЯДКЕ}»`))) плохо('«в порядке» нет в задании');
разрешено.add(В_ПОРЯДКЕ);

// обратная проверка: в данных нет своих строк длиннее 12 символов
(function обойти(v) {
  if (typeof v === 'string') { if (v.length > 12 && !разрешено.has(v)) плохо(`в данных строка, которой нет в задании: ${v}`); }
  else if (Array.isArray(v)) v.forEach(обойти);
  else if (v && typeof v === 'object') Object.entries(v).forEach(([к, x]) => { if (к !== 'название') обойти(x); });
})([ТЕЛО, ФРАКЦИИ, СТУПЕНИ, ТЕНЬ, РЕПУТАЦИЯ]);

console.log(`Проверено привязок и строк: ${проверок}.`);
if (ошибки.length) { console.log('\nРАСХОЖДЕНИЯ:\n- ' + ошибки.join('\n- ')); process.exit(1); }
console.log('Сверка прошла: все тексты состояний (тело 1 и 0 у четырёх полосок, семь ступеней, четыре строки тени, названия фракций, слова репутации) дословно из задания.');
