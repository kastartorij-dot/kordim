import assert from 'node:assert/strict';

async function чистыйВечер(p, опции) {
  // Рабочая одежда пачкается на заработке. Сиб замечает её при каждом входе;
  // обычная платная стирка сохраняет отношение дома без фарма вина и подарков.
  await p.slot('утро');
  await p.travel('трущобы');
  if (p.S.герой.одежда.база.состояние.грязь || p.S.герой.одежда.база.состояние.кровь) {
    await p.service('стирка');
  }
  await p.visit('синий-час', { at: 'вечер', ...опции });
}

// Общий маршрут трёх начал. Состояние меняют только кнопки driver;
// после каждого клика driver сохраняет и загружает партию заново.
// Платная первая встреча — разговор, без покупки близости и подарков.
export async function пройтиФрею(p) {
  await p.until(3);
  await p.goal('вытащить');
  await p.earn(90, { byDay: 14 });
  assert.ok(p.S.мир.день <= 14, 'На знакомство остаётся время до календарных окон Фреи');

  // Первый оплаченный вечер: 20 за вход, 60 за комнату, четыре местных хода.
  // Два разных поступка дают по одной одноразовой прибавке доверия.
  await чистыйВечер(p, { room: 'lestnica' });
  await p.scene('подняться:komnata_frei');
  await p.talk('freya');
  await p.scene('ветка:знакомство');
  await p.scene('вариант:знакомство:молчать');
  await p.scene('вариант:знакомство:ясно');
  await p.scene('ветка:сиб');
  await p.scene('вариант:сиб:в_ответ');
  await p.scene('вариант:сиб:слово');
  await p.scene('вариант:сиб:ясно');
  assert.ok(p.S.мир.диалоги.freya.факты.includes('фрея_молчали'));
  assert.ok(p.S.мир.диалоги.freya.факты.includes('фрея_слово'));
  assert.equal(p.S.мир.люди.freya.распол, 2, 'Доверие получено двумя разными разговорами');
  await p.leave();
  await p.note('Фрея: знакомство, совместное молчание и обещание сохранить её тайну; доверие 2.');

  // Дальнейшие встречи на площадке не требуют оплаты комнаты.
  await p.earn(35, { byDay: 19 });
  await p.until(6);
  await чистыйВечер(p, { room: 'ploshchadka' });
  assert.ok(p.S.мир.день <= 24, 'Разговор о причинах проходит в дни 6–24');
  await p.scene(/^Спросить, чего она хочет на самом деле$/u);
  await p.scene(/^Предложить помощь, ничего не обещая$/u);
  await p.scene(/^Пообещать действовать только по её слову$/u);
  await p.scene(/^Спросить про Сиба и дверь$/u);
  await p.scene(/^Спросить про шитьё$/u);
  assert.equal(p.S.мир.вытащить.этап, 'обещание');
  assert.deepEqual(p.S.мир.вытащить.причины, ['сиб', 'шитьё']);
  assert.equal(p.S.мир.люди.freya.распол, 4);
  await p.leave();

  // Первая ночь и работа обсуждаются до переговоров, а не выдаются фикстурой.
  // Вино даёт дому основание открыть кабинет: вся встреча укладывается в 6 ходов.
  await p.until(14);
  await p.earn(50, { byDay: 23 });
  await чистыйВечер(p, { room: 'zal' });
  assert.ok(p.S.мир.день <= 24, 'План после дома обсуждён до закрытия окна');
  await p.scene(/^Заказать вина$/u);
  await p.room('ploshchadka');
  await p.scene(/^Спросить, куда она пошла бы первой ночью$/u);
  await p.scene(/^Предложить уход: первую ночь и работу$/u);
  await p.scene(/^Спросить, возьмёт ли её на работу та, для кого она шьёт$/u);
  await p.room('zal');
  await p.scene(/^Поговорить с хозяйкой$/u);
  await p.scene(/^Прийти к Ярне вместе с Фреей$/u);
  assert.equal(p.S.мир.вытащить.план, 'уход');
  assert.ok(p.S.мир.вытащить.опоры.includes('работа'));
  assert.equal(p.S.мир.вытащить.переговоры.способ, 'вместе');
  assert.equal(p.S.мир.вытащить.переговоры.итог, 'принято');
  assert.equal(p.S.мир.вытащить.рычаг, false, 'Согласие получено без шантажа');
  await p.leave();
  await p.note('Фрея сама подготовила работу; Ярна выслушала её и согласилась без рычага и выкупа.');

  await p.earn(35, { byDay: 27 });
  await p.until(24);
  await чистыйВечер(p, { room: 'ploshchadka' });
  assert.ok(p.S.мир.день <= 29, 'Одвин пришёл выслушать решение лично');
  await p.scene(/^Выслушать её решение$/u);
  assert.equal(p.S.мир.вытащить.решение.исход, 'с-одвином');
  assert.equal(p.S.мир.вытащить.решение.выслушал, true);
  await p.leave();

  // Проверяем продолжение после сделки: новая площадка, та же память человека.
  await p.visit('дом-вдовы', { room: 'двор-соседей' });
  await p.scene(/^Навестить Фрею после её решения$/u);
  await p.talk('freya');
  await p.scene('ветка:вместе');
  await p.scene('вариант:вместе:спросить');
  await p.scene('вариант:вместе:рассказать');
  assert.equal(p.S.мир.вытащить.после, true);
  assert.ok(p.S.мир.диалоги.freya.факты.includes('фрея_спросили_дома'));
  await p.leave();
  await p.finish();
  assert.equal(p.S.мир.итогСезона.цель, 'вытащить');
  assert.equal(p.S.мир.итогСезона.исход, 'с-одвином');
}
