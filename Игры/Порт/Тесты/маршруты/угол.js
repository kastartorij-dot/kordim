import assert from 'node:assert/strict';

export async function пройтиУгол(p) {
  p.until(3); p.goal('угол');
  // Самое бедное из двух неремесленных начал использует предусмотренный
  // кредит: итог обязан назвать цену обязательства, а не спрятать долг.
  if(p.начало==='семья') {
    p.visit('меняльная',{room:'окно-меняльной',npc:'orsh'});
    p.scene(/Взять заём: 40 гр/);p.leave();
    p.note('Для задатка и первого взноса взят настоящий заём Орша; долг останется частью итогового результата.');
  }
  p.earn(90,{byDay:7});
  p.visit('дом-вдовы',{room:'каморка',at:'вечер'});
  p.scene(/Спросить.*свободной комнате/);
  p.scene('рассмотреть:осмотр-комнаты');
  p.scene(/Подписать договор/);
  assert.equal(p.S.мир.угол.статус,'действует');p.leave();
  for(const день of [7,14,21,28]) {
    if(p.S.мир.угол.взносы[день]!=='ждёт')continue;
    p.earn(30,{byDay:день});p.until(день);
    p.visit('дом-вдовы',{room:'каморка',at:'вечер'});
    p.scene(/Внести взнос/);p.leave();
    assert.equal(p.S.мир.угол.долг,0,'взнос не просрочен');
  }
  p.finish();assert.equal(p.S.мир.итогСезона.исход,p.начало==='семья'?'ценой-обязательства':'без-долга');
}
