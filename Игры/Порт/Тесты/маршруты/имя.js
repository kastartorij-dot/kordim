import assert from 'node:assert/strict';

// Полная партия от выбранного начала: ни один сюжетный статус, день или
// фракционное очко здесь не выставляется напрямую. Между визитами герой живёт
// через общие игровые действия маршрута; после каждого клика проверяем новый S.
export async function пройтиИмя(p) {
  await p.until(3);
  await p.goal('имя');
  p.note('Имя: доставить доверенное письмо, назвать конфликт, открыто выбрать сторону.');

  await p.visit('приемная-нотариуса', { room: 'перегородка', npc: 'notarius' });
  assert.ok(p.S.мир.день <= 8, 'Предложение письма ещё действует');
  await p.scene(/Взять запечатанное письмо/);
  assert.equal(p.S.мир.имя.письмо, 'взял');
  const срокПисьма = p.S.мир.имя.письмоСрокДень;
  await p.leave();

  await p.visit('контора-дорров', { room: 'кабинет-дорров', npc: 'rest_dorr' });
  assert.ok(p.S.мир.день <= срокПисьма, 'До последнего дня доставки остаётся время');
  await p.scene(/Передать письмо Дорру и попросить вскрыть при тебе/);
  assert.equal(p.S.мир.имя.письмо, 'доставлено');
  assert.equal(p.S.мир.имя.путь, 'с-разрешения');
  assert.equal(p.S.мир.обязательства.имя_письмо.статус, 'выполнено');
  await p.leave();

  // Десять грошей на честный обмен зарабатываются до срока предложения Кипа.
  await p.earn(40, { byDay: 8 });
  await p.until(9);
  await p.slot('утро');
  await p.visit('двор-горма', { room: 'стол-горма', npc: 'gorm' });
  assert.equal(p.S.мир.день % 2, 1, 'Горм принимает только в нечётный день');
  await p.scene(/Честно назвать конфликт и предложить обмен/);
  assert.equal(p.S.мир.имя.просьба, 'обмен');
  await p.leave();

  await p.visit('меняльная', { room: 'коридор-меняльной', npc: 'kip' });
  assert.ok(p.S.мир.день >= 9 && p.S.мир.день <= 16, 'Предложение Кипа ещё действует');
  await p.scene(/Отказаться от денег Кипа/);
  assert.equal(p.S.мир.имя.бесплатное, 'отказ');
  assert.equal(p.S.мир.имя.долгКипу, false);
  await p.leave();

  // Публичное решение, служба и последний вызов делаются в разные дни.
  // Поздняя служба поддерживает заслуженное положение до итога сезона;
  // обычная работа и естественное забывание фракций продолжают действовать.
  await p.until(24);
  await p.slot('утро');
  await p.visit('часовня', { room: 'неф-часовни', npc: 'una' });
  await p.scene(/Принять знак Ножей/);
  assert.equal(p.S.мир.имя.договор.вид, 'сторона');
  assert.equal(p.S.мир.имя.договор.сторона, 'ножи');
  assert.equal(p.S.мир.цели.зафиксирована, true);
  await p.leave();

  await p.until(27);
  await p.slot('утро');
  await p.visit('контора-дорров', { room: 'приёмная-дорров', npc: 'tobb' });
  assert.ok(p.S.мир.день <= 28, 'Срок службы стороне не вышел');
  await p.scene(/Подтвердить для Дорра запись о судне/);
  assert.equal(p.S.мир.имя.служба.ножи, true);
  assert.equal(p.S.мир.обязательства.имя_служба.статус, 'выполнено');
  await p.leave();

  await p.until(29);
  await p.slot('утро');
  await p.visit('часовня', { room: 'неф-часовни', npc: 'una' });
  assert.ok(p.S.мир.день >= 26 && p.S.мир.день <= 29, 'Последний вызов доступен');
  await p.scene(/Доказать верность стороне/);
  assert.equal(p.S.мир.имя.вызов, 'выполнил');
  assert.ok(p.S.мир.фракции.ножи >= 2, 'Сторона признаёт Одвина своим');
  await p.leave();

  await p.finish();
  assert.equal(p.S.мир.итогСезона.цель, 'имя');
  assert.equal(p.S.мир.итогСезона.исход, 'человек-стороны');
  p.note('Имя: письмо и служба выполнены в срок; публичный выбор подтверждён последним вызовом.');
  return p.S.мир.итогСезона;
}
