// Круг 2, пачка «Ночлег, чистота и заработок первой недели»: node Игры/Порт/Тесты/круг2-первая-неделя.mjs
// Каждое правило пачки — отдельный раздел; падение любого — код выхода 1.
import { новоеСостояние } from '../Движок/состояние.js';
import { доступныеДействия } from '../Движок/действия.js';
import { войти, действияСцены, вернутьсяВГород } from '../Движок/разговор.js';
import { авто } from '../Движок/смена.js';

const плохо = [];
const проверить = (условие, что) => { console.log((условие ? 'OK   ' : 'ПРОВАЛ ') + что); if (!условие) плохо.push(что); };
const кнопкаСцены = (S, т) => действияСцены(S).find(x => x.текст.includes(т));
const жми = (S, т) => { const а = кнопкаСцены(S, т); if (!а) throw new Error('нет кнопки: ' + т + ' | ' + действияСцены(S).map(x => x.текст).join(' / ')); а.выполнить(S); };
const действие = (S, id) => доступныеДействия(S).find(д => д.id === id);

// ── PR005-01: «пойти домой» с оплаченной комнатой у вдовы, ночная дорога подписана ценой ──
{
  const вечерВСинемЧасе = S => {
    S.мир.район = 'торговый'; S.мир.отрезок = 'вечер';
    войти(S, 'синий-час'); жми(S, 'Держи. Двадцать'); жми(S, 'Войти.'); жми(S, 'Пойти: Крыльцо');
  };
  // Комната оплачена: дверь говорит, куда ведёт, и после итога герой спит у вдовы в Жилых улицах.
  const S = новоеСостояние('семья', 5);
  S.герой.кошель = 200; S.герой.жильё = { id: 'вдова', оплачено_по: 7 };
  вечерВСинемЧасе(S);
  const дверь = кнопкаСцены(S, 'Выйти и пойти домой');
  проверить(/сон: комната у вдовы/.test(дверь?.подпись ?? ''), `подпись двери называет ночлег: «${дверь?.подпись}»`);
  жми(S, 'Выйти и пойти домой'); жми(S, 'Выйти.');
  проверить(!!S.сцена?.итог, 'итог вечера показан до ухода');
  вернутьсяВГород(S);
  const н = S.мир.конецДня;
  проверить(н?.выспался === true && н?.сон === 'Комната у вдовы', `ночь у вдовы, не без сна (${н?.сон ?? 'без сна'})`);
  проверить(S.мир.район === 'жилые-улицы', 'утро в Жилых улицах');

  // Без своего ночлега — дверь честно говорит, что дома нет, и герой остаётся ночью в квартале.
  const Б = новоеСостояние('семья', 5);
  Б.герой.кошель = 200;
  вечерВСинемЧасе(Б);
  const д2 = кнопкаСцены(Б, 'Выйти и пойти домой');
  проверить(/своего ночлега нет/.test(д2?.подпись ?? ''), `без жилья подпись честная: «${д2?.подпись}»`);
  жми(Б, 'Выйти и пойти домой'); жми(Б, 'Выйти.'); вернутьсяВГород(Б);
  проверить(!Б.мир.конецДня && Б.мир.отрезок === 'ночь' && Б.мир.район === 'торговый', 'без жилья — ночь в Торговом, выбор ночлега за игроком');
  const дорога = действие(Б, 'переход:доки');
  проверить(/ночь без сна/.test(дорога?.подпись ?? ''), `ночная дорога подписана ценой: «${дорога?.подпись}»`);

  // Ночная дорога в район своей комнаты — это дорога домой и сон, а не бессонная ночь.
  const Н = новоеСостояние('семья', 5);
  Н.герой.жильё = { id: 'вдова', оплачено_по: 7 }; Н.мир.район = 'доки'; Н.мир.отрезок = 'ночь';
  const домой = действие(Н, 'переход:жилые-улицы');
  проверить(/дорога и сон: комната у вдовы/.test(домой?.подпись ?? ''), `дорога домой подписана: «${домой?.подпись}»`);
  проверить(/ночь без сна/.test(действие(Н, 'переход:торговый')?.подпись ?? ''), 'дорога не домой ночью — «ночь без сна»');
  домой.выполнить(Н);
  проверить(Н.мир.конецДня?.сон === 'Комната у вдовы' && Н.мир.район === 'жилые-улицы', 'ночная дорога домой закончилась сном у вдовы');

  // Оплата кончилась — дома больше нет, подпись снова честная.
  const П = новоеСостояние('семья', 5);
  П.герой.жильё = { id: 'вдова', оплачено_по: 3 }; П.мир.день = 4; П.мир.район = 'доки'; П.мир.отрезок = 'ночь';
  проверить(/ночь без сна/.test(действие(П, 'переход:жилые-улицы')?.подпись ?? ''), 'просроченная комната — дорога снова без сна');
  // Днём дорога как прежде: отрезок, без слова о сне.
  П.мир.отрезок = 'день';
  проверить(действие(П, 'переход:жилые-улицы')?.подпись === '1 отрезок', 'днём подпись дороги не изменилась');
}

// ── PR004-09: грязь — путь к чистоте в запрете, ночь не делает одежду «грязной» сама, штраф дома в сцене ──
{
  const смена = (S, id) => { действие(S, 'работа:' + id).выполнить(S); авто(S); while (S.мир.смена) действие(S, 'смена:дальше')?.выполнить(S) ?? (S.мир.смена = null); };
  const грязь = S => S.герой.одежда.база.состояние.грязь ?? 0;
  const спатьНаУлице = S => { S.мир.отрезок = 'ночь'; действие(S, 'сон:небо').выполнить(S); S.мир.конецДня = null; };

  // «Семья», день 1: разгрузка пачкает (и это видно на кнопке), ночь на улице не добавляет до запрета.
  const S = новоеСостояние('семья', 7);
  проверить(/пачкает одежду/.test(действие(S, 'работа:разгрузка')?.подпись ?? ''), 'грязная работа подписана заранее');
  смена(S, 'разгрузка');
  проверить(грязь(S) === 1, `после разгрузки грязь 1 (${грязь(S)})`);
  спатьНаУлице(S);
  проверить(грязь(S) === 1 && S.мир.день === 2, `ночь на улице не довела до «грязной» (${грязь(S)})`);
  const разноска = Х => { const К = JSON.parse(JSON.stringify(Х)); К.мир.район = 'торговый'; К.мир.отрезок = 'день'; return действие(К, 'работа:разноска'); };
  проверить(разноска(S)?.можно === true, 'день 2: разноска открыта после разгрузки и ночи на улице');
  S.мир.отрезок = 'утро'; S.мир.район = 'доки';

  // Вторая разгрузка без стирки — к людям не подпустят, и причина говорит, где и за сколько отмыться.
  смена(S, 'разгрузка');
  const р2 = разноска(S);
  проверить(р2?.можно === false && /Трущобах — 2 гр\./.test(р2?.почему ?? ''), `в запрете есть путь: «${р2?.почему}»`);

  // Бедное начало возвращает доступ за один день: стирка 2 гр. в Трущобах или работа в бане без денег.
  const С = JSON.parse(JSON.stringify(S));
  С.мир.район = 'трущобы'; С.мир.отрезок = 'день';
  const стирка = действие(С, 'услуга:стирка');
  проверить(стирка?.можно === true && стирка.цена === 2, 'в Трущобах есть стирка за 2 гр.');
  стирка.выполнить(С);
  проверить(разноска(С)?.можно === true, 'после стирки разноска снова открыта');
  const Б = JSON.parse(JSON.stringify(S));
  Б.герой.кошель = 0; Б.мир.район = 'трущобы'; Б.мир.отрезок = 'день';
  смена(Б, 'баня');
  проверить(грязь(Б) === 0 && Б.герой.кошель > 0, `без денег: подсобить в бане — и чисто, и заработок (${Б.герой.кошель} гр.)`);

  // «Ремесло» без грязной работы: две ночи на улице — в рыночный день 3 разноска открыта.
  const Р = новоеСостояние('наколки', 7);
  спатьНаУлице(Р); спатьНаУлице(Р);
  Р.мир.район = 'торговый'; Р.мир.отрезок = 'день';
  проверить(Р.мир.день === 3 && действие(Р, 'работа:разноска')?.можно === true, `рыночный день 3 не потерян от двух ночей на улице (грязь ${грязь(Р)})`);

  // Порванная одежда и лохмотья — свой путь в причине.
  const Л = новоеСостояние('семья', 7);
  Л.герой.одежда.база.тип = 'лохмотья';
  проверить(/кафтан .* 12 гр\./.test(разноска(Л)?.почему ?? ''), 'в лохмотьях — путь: кафтан за 12 гр.');

  // Грязного в «Синем часе» Сиб встречает холоднее — и это сказано в сцене, а не только в итоге дня.
  const Г = новоеСостояние('семья', 7);
  Г.герой.кошель = 100; Г.герой.одежда.база.состояние.грязь = 2; Г.мир.район = 'торговый'; Г.мир.отрезок = 'вечер';
  войти(Г, 'синий-час');
  проверить(Г.сцена.диалог?.лента.some(з => /дом −1/.test(з.т)), 'штраф дома за грязь показан в сцене у двери');
}

if (плохо.length) { console.error('\nПРОВАЛ: ' + плохо.length); process.exit(1); }
console.log('\nВсе проверки пачки прошли.');
