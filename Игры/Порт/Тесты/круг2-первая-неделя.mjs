  проверить(/ночь без сна/.test(дорога?.подпись ?? ''), `ночная дорога подписана ценой: «${дорога?.подпись}»`);

  // Ночная дорога в район своей комнаты — это дорога домой и сон, а не бессонная ночь.
  const Н = новоеСостояние('семья', 5);
