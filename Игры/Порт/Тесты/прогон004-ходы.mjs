// Прогон 004, PR004-03 «пакет А»: честный счёт ходов визита.
// Запуск: node Игры/Порт/Тесты/прогон004-ходы.mjs
import assert from 'node:assert/strict';
import { новоеСостояние } from '../Движок/состояние.js';
import { войти, действияСцены, выбратьПодход, времяИдёт } from '../Движок/разговор.js';
import { ЖИТЕЛИ } from '../Данные/Диалоги/жители.js';

const нов = (начало = 'наколки') => {
  const S = новоеСостояние(начало, 5);
  S.мир.отрезок = 'вечер'; S.мир.район = 'торговый'; S.герой.кошель = 300;
  return S;
};
const все = S => действияСцены(S);
const кн = (S, т) => все(S).find(x => (x.текст ?? '').includes(т) && x.можно !== false);
const жми = (S, т) => { const а = кн(S, т); if (!а) throw new Error(`нет «${т}»: ` + все(S).map(x => x.текст).join(' | ')); а.выполнить(S); return S; };
const вЗал = S => { войти(S, 'синий-час'); жми(S, 'Держи. Двадцать'); жми(S, 'Войти.'); return S; }; // «Войти.» сразу в зал
// Разговор «с манерой»: собеседник без активного графа (так отвечают люди, у которых граф не открыт в этой комнате).
const сМанерой = (S, кто) => { S.сцена.собеседник = кто; S.сцена.диалог = null; S.сцена.реплика = ''; return S; };

// 1. У двери до оплаты вопросы привратнику ходов не тратят.
{
  const S = нов(); S.мир.места['синий-час'] = { визитов: 3, осмотрено: [], дом: 0, долг: 0, флаги: [] };
  войти(S, 'синий-час');
  жми(S, 'Давно тут стоишь');
  assert.equal(S.сцена.ходы, 0, 'вопрос у двери до входа — даром');
  for (let i = 0; i < 6 && S.сцена.диалог?.режим === 'ветка' && !кн(S, 'Держи. Двадцать'); i++) {
    const в = все(S).find(x => x.вид === 'вариант' && x.можно); if (!в) break; в.выполнить(S);
  }
  жми(S, 'Держи. Двадцать');
  assert.ok(S.сцена.вошёл, 'после оплаты герой вошёл');
}

// 2. «Поговорить с хозяйкой» — даром и заканчивает разговор со старшей (собеседник не переезжает в кабинет).
{
  const S = вЗал(нов('наколки'));
  жми(S, 'Заговорить с: Старшая работница');
  жми(S, 'Подойти к столу.');
  const ходы = S.сцена.ходы;
  const хоз = кн(S, 'Поговорить с хозяйкой');
  assert.ok(хоз, 'вход к хозяйке виден из разговора');
  assert.equal(хоз.подпись, 'даром');
  хоз.выполнить(S);
  assert.equal(S.сцена.ходы, ходы, 'открыть кабинет — даром');
  assert.equal(S.сцена.комната, 'kabinet');
  assert.equal(S.сцена.собеседник, null, 'старшая осталась в зале');
  assert.ok(кн(S, 'Заговорить с: Ярна Сотт'), 'в кабинете говорят с Ярной');
}

// 3. Тема задаётся один раз при любой манере, если у манеры нет своего текста.
{
  const S = вЗал(нов('наколки'));
  сМанерой(S, 'starshaya'); выбратьПодход(S, 'мягко');
  const кош = S.герой.кошель;
  все(S).find(x => x.id === 'тема:nakolki').выполнить(S);
  assert.equal(S.сцена.ходы, 1);
  const ответ = S.сцена.реплика;
  выбратьПодход(S, 'деньгами');
  const повтор = все(S).find(x => x.id === 'тема:nakolki');
  assert.equal(повтор.подпись, 'уже', 'другая манера без своего текста — «уже»');
  повтор.выполнить(S);
  assert.equal(S.сцена.ходы, 1, 'повтор другой манерой не стоит хода');
  assert.equal(S.герой.кошель, кош, 'и денег');
  assert.equal(S.сцена.реплика, ответ, 'ответ тот же, с учётом начала героя');
  // У манеры со своим текстом вопрос — новый и стоит хода (и цена видна заранее).
  const деньги = все(S).find(x => x.id === 'тема:ni_o_chem');
  assert.equal(деньги.подпись, '10 гр. · 1 ход', 'цена денежного вопроса на кнопке');
}

// 4. Последний ход: оплаченный вопрос, которым кончилось время, даёт ещё один вопрос даром; итог — после «Закончить».
{
  const S = вЗал(нов('наколки'));
  сМанерой(S, 'starshaya'); выбратьПодход(S, 'деньгами');
  S.сцена.ходы = 5;
  все(S).find(x => x.id === 'тема:ni_o_chem').выполнить(S);
  assert.ok(S.сцена.времяВышло && !S.сцена.итог, 'время вышло, визит ещё не закрыт');
  assert.match(S.сцена.реплика, /Спрашивай/, 'ответ на оплаченную реплику показан');
  const ещё = все(S).filter(x => x.вид === 'тема');
  assert.ok(ещё.length && ещё.every(x => x.подпись === 'даром' || x.подпись === 'уже'), 'последний вопрос — даром');
  выбратьПодход(S, 'мягко');
  const даром = все(S).find(x => x.вид === 'тема' && x.подпись === 'даром');
  assert.ok(даром, 'есть вопрос даром: ' + все(S).map(x => x.текст + ' ' + x.подпись).join(' | '));
  даром.выполнить(S);
  assert.equal(S.сцена.ходы, 6, 'бесплатный вопрос не добавил хода');
  assert.deepEqual(все(S).map(x => x.id), ['закончить'], 'дальше — только закончить');
  все(S)[0].выполнить(S);
  assert.ok(S.сцена.итог, 'итог посчитан после «Закончить»');
}

// 5. Ветку графа можно начать на последний ход и дочитать; потом — «Закончить».
{
  const S = вЗал(нов('наколки'));
  жми(S, 'Заговорить с: Старшая работница');
  жми(S, 'Подойти к столу.');
  S.сцена.ходы = 5;
  const в = все(S).find(x => x.id === 'ветка:знакомство');
  assert.ok(в.можно, 'ветка на ровно оставшийся ход доступна');
  в.выполнить(S);
  assert.ok(S.сцена.времяВышло);
  for (let i = 0; i < 10 && S.сцена.диалог?.режим === 'ветка'; i++) {
    const А = все(S);
    assert.ok(А.some(x => x.id === 'закончить'), 'закончить можно в любой момент');
    const вар = А.find(x => x.вид === 'вариант' && x.можно && x.закреплён) ?? А.find(x => x.вид === 'вариант' && x.можно);
    assert.ok(вар, 'начатую ветку можно дочитать'); вар.выполнить(S);
  }
  assert.deepEqual(все(S).map(x => x.id), ['закончить'], 'после ветки остаётся закончить');
}

// 6. Подписи: «не хватит ходов»; вход к старшей не повторяет название её первой ветки.
{
  const S = нов('наколки'); S.мир.места['синий-час'] = { визитов: 3, осмотрено: [], дом: 0, долг: 0, флаги: [] };
  S.мир.люди.sib = { спрошено: [], исчерпано: [], распол: 3, знаком: true };
  войти(S, 'синий-час'); жми(S, 'Держи. Двадцать'); жми(S, 'Войти.'); жми(S, 'Пойти: Крыльцо');
  жми(S, 'Заговорить с: Сиб'); S.сцена.ходы = 5;
  const поздно = все(S).find(x => x.id === 'ветка:поздно');
  assert.ok(поздно, 'двухходовая ветка Сиба видна');
  assert.equal(поздно.можно, false); assert.equal(поздно.почему, 'не хватит ходов');
  const г = ЖИТЕЛИ.starshaya, вход = г.ветки[г.вход].узлы.старт.варианты.find(x => x.ид === 'сесть');
  assert.equal(вход.текст, 'Подойти к столу.');
  assert.notEqual(вход.текст.replace(/\.$/, ''), г.ветки.знакомство.ярлык);
}

// 7. Время вышло в точке без итога вечера: после «Закончить» — сразу в город.
{
  const S = нов('бумаги'); S.мир.отрезок = 'утро';
  войти(S, 'аптека');
  времяИдёт(S, 10);
  assert.deepEqual(все(S).map(x => x.id), ['закончить']);
  все(S)[0].выполнить(S);
  assert.equal(S.сцена, null, 'из точки — в город');
}

