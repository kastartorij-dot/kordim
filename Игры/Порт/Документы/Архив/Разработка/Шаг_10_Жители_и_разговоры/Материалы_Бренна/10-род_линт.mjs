// Линт родовых форм для реплик, обращённых к герою (правило автора: женский герой запланирован, мужских форм быть не должно).
// Реплики героя: нельзя «понял», «пошёл», «я … л», краткие мужские прилагательные.
// Реплики людей: нельзя «ты … л», «ты … сам/готов/…», обращения «милый», «парень», «друг» и т. п.
// Речь человека о себе («Я уже сказал» у мужчины) не проверяется: правило касается героя.
const Б = '(?<![а-яё])', К = '(?![а-яё])';
const ГЕРОЙ_СЛОВА = ['понял', 'пошёл', 'пошел', 'пришёл', 'пришел', 'ушёл', 'ушел', 'видел', 'слышал', 'знал', 'был', 'хотел', 'решил', 'сказал', 'сделал', 'взял', 'нашёл', 'нашел', 'принёс', 'принес', 'спросил', 'согласен', 'готов', 'должен', 'рад', 'уверен', 'прав', 'сам', 'мог', 'смог'];
const ГЕРОЙ = [new RegExp(`${Б}(${ГЕРОЙ_СЛОВА.join('|')})${К}`, 'i'), new RegExp(`${Б}я\\s+(?:[а-яё-]+\\s+){0,2}[а-яё]{2,}л${К}`, 'i')];
const ЛЮДИ = [
  new RegExp(`${Б}ты\\s+(?:[а-яё-]+\\s+){0,2}[а-яё]{2,}л${К}`, 'i'),
  new RegExp(`${Б}[а-яё]{2,}л\\s+(?:ли\\s+)?ты${К}`, 'i'),
  new RegExp(`${Б}ты\\s+(?:[а-яё-]+\\s+){0,2}(сам|готов|должен|рад|уверен|прав|один)${К}`, 'i'),
  new RegExp(`${Б}(если|раз|будь|будешь|ты|тебе|тебя)\\s+(?:[а-яё-]+\\s+){0,2}(голоден|сыт|болен|здоров|пьян|трезв|готов|должен|рад|согласен|уверен|прав|жив|свободен|занят|виноват|одинок|один|сам)${К}`, 'i'),
  new RegExp(`${Б}(милый|дорогой|парень|паренёк|парнишка|друг|дружок|мальчик|сынок|брат|братец|батюшка|господин|молодой человек|приятель)${К}`, 'i'),
];
export function родовыеОшибки({ герой = [], люди = [] }) {
  const out = [];
  for (const [где, с] of герой) for (const р of ГЕРОЙ) { const м = с.match(р); if (м) out.push(`${где}: реплика героя содержит мужскую форму «${м[0].trim()}»: ${с.slice(0, 80)}`); }
  for (const [где, с] of люди) for (const р of ЛЮДИ) { const м = с.match(р); if (м) out.push(`${где}: обращение к герою содержит мужскую форму «${м[0].trim()}»: ${с.slice(0, 80)}`); }
  return out;
}
// Собирает строки графа: герой — ветка.реплика и вариант.текст; люди — всё остальное, что произносит или описывает рассказчик.
export function строкиГрафа(граф, имя = граф.человек) {
  const герой = [], люди = [];
  const л = (где, с) => { if (typeof с === 'string') люди.push([где, с]); };
  л(`${имя}.вступление`, граф.вступление); л(`${имя}.снова`, граф.снова);
  for (const в of граф.видят ?? []) л(`${имя}.видят`, в.т);
  const ветки = граф.ветки ?? { x: граф };
  for (const [бид, в] of Object.entries(ветки)) {
    if (в.реплика) герой.push([`${имя}.${бид}.реплика`, в.реплика]);
    (в.уже ?? []).forEach((с, i) => л(`${имя}.${бид}.уже[${i}]`, с));
    for (const [уид, у] of Object.entries(в.узлы ?? {})) {
      for (const э of у.текст ?? []) л(`${имя}.${бид}.${уид}`, typeof э === 'string' ? э : э.т);
      for (const в_ of у.варианты ?? []) {
        if (typeof в_.текст === 'string' && /^«/.test(в_.текст)) герой.push([`${имя}.${бид}.${уид}.${в_.ид}`, в_.текст]);
        for (const с of Object.values(в_.ответ ?? {})) л(`${имя}.${бид}.${уид}.${в_.ид}.ответ`, с);
      }
    }
  }
  return { герой, люди };
}

// Для текстов, где герой рассказывает о других людях (вывод о Бренне): мужские формы проверяются только в первом лице («я … л», «я … готов»).
const ПЕРВОЕ_ЛИЦО = [new RegExp(`${Б}я\\s+(?:[а-яё-]+\\s+){0,2}[а-яё]{2,}л${К}`, 'i'), new RegExp(`${Б}я\\s+(?:[а-яё-]+\\s+){0,2}(рад|готов|должен|уверен|согласен|прав|сам)${К}`, 'i')];
export function первоеЛицоОшибки(тексты) {
  const out = [];
  for (const [где, с] of тексты) for (const р of ПЕРВОЕ_ЛИЦО) { const м = с.match(р); if (м) out.push(`${где}: мужская форма в первом лице «${м[0].trim()}»: ${с.slice(0, 80)}`); }
  return out;
}
