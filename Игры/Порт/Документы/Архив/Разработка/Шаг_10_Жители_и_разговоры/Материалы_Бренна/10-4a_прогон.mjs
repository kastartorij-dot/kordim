// Прогон 10.4a через настоящий движок: графы подставляются в модули мест в памяти (файлы игры не меняются),
// до каждого человека идём обычными действиями сцены, потом обходим все пути диалога.
// Запуск из папки «Порт»: node Документы/На_Разбор/10-4a_прогон.mjs
import assert from 'node:assert/strict';
import { МЕСТА } from '../../Данные/места.js';
import { новоеСостояние } from '../../Движок/состояние.js';
import { войти, действияСцены } from '../../Движок/разговор.js';
import { датьТему, СЛЫШАЛ } from '../../Движок/знание.js';
import { ДИАЛОГИ_ФОНОВЫЕ } from './10-4a_фоновые_жители.js';
import { АЛЬТЕРНАТИВЫ } from './10-4a_альтернативы_Йора_Пин.js';
const ВСЕ_ГРАФЫ = { ...ДИАЛОГИ_ФОНОВЫЕ, ...АЛЬТЕРНАТИВЫ };

const ТЕМЫ_ДЛЯ_ПРОХОДА = ['lozh_gorm', 'gorm_chetnye', 'seraya_radost'];
const ФЛАГИ_МЕСТА_ДЛЯ_ПРОХОДА = ['помог_бранке', 'помог_миле']; // флаги помощи, которые по задаче внедрения будут ставить действия комнат
const найтиМесто = ид => МЕСТА.find(м => Object.values(м.модуль.КОМНАТЫ).some(к => к.люди?.includes(ид)));
const комнатаЧеловека = (м, ид) => Object.entries(м.модуль.КОМНАТЫ).find(([, к]) => к.люди?.includes(ид))[0];
const путьКомнат = (м, куда) => {
  const К = м.модуль.КОМНАТЫ, очередь = [[м.модуль.старт]], был = new Set([м.модуль.старт]);
  while (очередь.length) {
    const п = очередь.shift(), т = п.at(-1);
    if (т === куда) return п.slice(1);
    for (const с of К[т].соседи ?? []) if (!был.has(с)) { был.add(с); очередь.push([...п, с]); }
  }
  throw new Error(`нет пути до комнаты «${куда}»`);
};
const нажать = (S, ид) => {
  const а = действияСцены(S).find(x => x.id === ид);
  if (!а) throw new Error(`нет действия «${ид}». Есть: ` + действияСцены(S).map(x => x.id).join(' | '));
  if (а.можно === false) throw new Error(`действие «${ид}» недоступно: ${а.почему}`);
  а.выполнить(S);
};
const подпись = (S, кто) => {
  const д = S.сцена?.диалог, п = S.мир.диалоги?.[кто]?.ветки ?? {};
  return JSON.stringify([!!S.сцена?.собеседник, д?.режим, д?.ветка, д?.узел, Object.entries(п).map(([k, v]) => k + (v.исход ? '+' : '-'))]);
};

const итог = [];
for (const [кто, граф] of Object.entries(ВСЕ_ГРАФЫ)) {
  const м = найтиМесто(кто);
  assert.ok(м, `${кто}: человека нет ни в одном месте`);
  м.модуль.ДИАЛОГИ = { ...(м.модуль.ДИАЛОГИ ?? {}), [кто]: граф };
  const цель = комнатаЧеловека(м, кто);
  const вариантовВсего = new Set();
  for (const [бид, в] of Object.entries(граф.ветки)) for (const у of Object.values(в.узлы)) for (const в_ of у.варианты) вариантовВсего.add(`${бид}:${в_.ид}`);
  const затронуто = new Set();
  let состояний = 0, листьев = 0;

  for (const темы of [[], ТЕМЫ_ДЛЯ_ПРОХОДА.concat(ФЛАГИ_МЕСТА_ДЛЯ_ПРОХОДА.map(ф => 'флаг:' + ф))]) {
    const свежая = путь => {
      const S = новоеСостояние('семья', 72);
      S.мир.район = м.район; S.мир.отрезок = [...(м.когда ?? []), 'день'].find(о => !['ночь'].includes(о)) ?? м.когда[0];
      S.мир.день = 3; S.герой.кошель = 500;
      войти(S, м.id);
      for (const т of темы) { if (т.startsWith('флаг:')) (S.мир.места[м.id].флаги ??= []).push(т.slice(5)); else if (!S.мир.темы.includes(т)) датьТему(S, т, СЛЫШАЛ); }
      for (const к of путьКомнат(м, цель)) нажать(S, `пойти:${к}`);
      нажать(S, `заговорить:${кто}`);
      for (const шаг of путь) нажать(S, шаг);
      return S;
    };
    const видели = new Set();
    const обойти = путь => {
      const S = свежая(путь);
      const п = подпись(S, кто);
      if (видели.has(п)) return;
      видели.add(п); состояний++;
      // первая встреча: приветствие попало в ленту
      if (!путь.length) {
        const лента = (S.сцена.диалог?.лента ?? []).map(з => з.т).join('\n');
        assert.ok(лента.includes(граф.вступление), `${кто}: вступление не показано при первой встрече`);
      }
      const действия = действияСцены(S).filter(a => /^(ветка|вариант):/.test(a.id) || a.id === 'отойти');
      if (!S.сцена?.диалог?.режим) { листьев++; return; } // разговор закрыт
      for (const а of действия) {
        if (а.id === 'отойти') { листьев++; continue; }
        if (а.можно === false) continue;
        const [, , ид] = а.id.split(':');
        if (а.id.startsWith('вариант:')) затронуто.add(`${а.id.split(':')[1]}:${ид}`);
        обойти([...путь, а.id]);
      }
    };
    обойти([]);
  }
  const не = [...вариантовВсего].filter(x => !затронуто.has(x));
  assert.deepEqual(не, [], `${кто}: движок ни разу не дал выбрать варианты: ${не.join(', ')}`);
  // Повторная встреча: после пройденной ветки показывается строка из `уже`, а не заново ответ.
  {
    const S = новоеСостояние('семья', 72);
    S.мир.район = м.район; S.мир.отрезок = [...(м.когда ?? []), 'день'].find(о => о !== 'ночь') ?? м.когда[0]; S.мир.день = 3; S.герой.кошель = 500;
    войти(S, м.id); for (const к of путьКомнат(м, цель)) нажать(S, `пойти:${к}`); нажать(S, `заговорить:${кто}`);
    const первая = Object.keys(граф.ветки).find(б => б !== 'проститься' && !граф.ветки[б].если);
    нажать(S, `ветка:${первая}`);
    let шаги = 0; while (S.сцена.диалог.режим === 'ветка' && шаги++ < 6) {
      const в = действияСцены(S).find(a => a.id.startsWith('вариант:') && a.можно !== false && !a.закреплён); if (!в) break; в.выполнить(S);
    }
    assert.equal(S.сцена.диалог.режим, 'хаб', `${кто}: после ветки «${первая}» не вернулись в хаб`);
    нажать(S, `ветка:${первая}`);
    const лента = S.сцена.диалог.лента.map(з => з.т);
    assert.ok(граф.ветки[первая].уже.some(т => лента.includes(т)), `${кто}: повторный вход в «${первая}» не показал строку из «уже»`);
  }
  итог.push(`${кто.padEnd(7)} ${String(вариантовВсего.size).padStart(2)} вариантов, состояний ${String(состояний).padStart(2)}, концов ${String(листьев).padStart(2)} — все варианты достижимы, приветствие и «уже говорили» работают`);
}
console.log(итог.join('\n'));
console.log(`\nOK: ${итог.length} людей прошли через настоящий движок`);
