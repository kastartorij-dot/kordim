const ЛИНИИ_ДЛЯ_ПОНИМАНИЯ = ['Работа', 'Падение', 'Конец'];

// Какие узлы засчитаны (хотя бы одна запись) и какой уровень достигнут.
export function узлыИУровень(полученные) {
  const узлы = УЗЛЫ.filter(у => у.записи.some(з => полученные.has(з.id)));
  const линии = new Set(узлы.map(у => у.линия));
  let уровень = null;
  if (узлы.length >= 1) уровень = 'слух';
  if (узлы.length >= 5 && ЛИНИИ_ДЛЯ_ПОНИМАНИЯ.every(л => линии.has(л))) уровень = 'понимание';
  if (узлы.length === 9) уровень = 'полная';
  return { узлы, уровень };
}

// Сборка вывода: вступление уровня + фразы полученных записей по порядку узлов + нейтральное завершение + фраза о состоянии журнала.
export function собратьВывод(уровень, полученные, состояние = 'не_выдан') {
  assertСостояние(полученные, состояние);
  const { узлы } = узлыИУровень(полученные);
  const фразы = узлы.flatMap(у => {
    const есть = у.записи.filter(з => полученные.has(з.id));
    // когда одна запись узла вытесняет другую (журнал получен — «есть журнал» не повторяется; выписка получена — ярлык не повторяется), берётся более весомая
    return есть.filter(з => !(з.id.endsWith('_seen') && есть.some(x => x.id === 'brenn_second_journal')) && !(з.id.endsWith('_label') && есть.some(x => x.id === 'brenn_cell17'))).map(з => з.т);
  });
  const вступление = уровень === 'полная' ? 'Теперь складывается всё.' : 'Складывается то, что можно показать.';
  const хвост = ['Кто за этим стоял, пока неизвестно.'];
  if (СОСТОЯНИЯ_ЖУРНАЛА[состояние]) хвост.push(СОСТОЯНИЯ_ЖУРНАЛА[состояние]);
  return [вступление, ...фразы, ...хвост].join(' ');
}

function assertСостояние(полученные, состояние) {
  if (!(состояние in СОСТОЯНИЯ_ЖУРНАЛА)) throw new Error(`неизвестное состояние журнала «${состояние}»`);
  const журналНаРуках = полученные.has('brenn_second_journal');
  if (состояние === 'не_выдан' && журналНаРуках) throw new Error('журнал отмечен как не выданный, но запись «Второй журнал на руках» получена');
  if (состояние !== 'не_выдан' && !журналНаРуках) throw new Error(`состояние «${состояние}» требует полученной записи «Второй журнал на руках»`);
}
