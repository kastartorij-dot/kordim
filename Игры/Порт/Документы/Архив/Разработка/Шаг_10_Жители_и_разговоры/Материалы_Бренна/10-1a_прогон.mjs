// Прогон 10.1a через настоящий движок: ветки подставляются в заглушки графов Браса и Горма (файлы игры не меняются).
// Проверяется: ветки нет без флага сожжения и при других решениях; при флаге в памяти места есть; при одном лишь мировом флаге нет (ограничение движка); после рассказа эффект применён один раз
// (расположение Браса +1, у Горма без изменений, у обоих факт `знает_про_журнал`); повторно ветки нет.
// Запуск из папки «Порт»: node Документы/На_Разбор/10-1a_прогон.mjs
import assert from 'node:assert/strict';
import { МЕСТА } from '../../Данные/места.js';
import { новоеСостояние } from '../../Движок/состояние.js';
import { войти, действияСцены } from '../../Движок/разговор.js';
import { ВЕТКИ_РАССКАЗА } from './10-1a_рассказ_о_сожжённом_журнале.js';
import { родовыеОшибки, строкиГрафа } from './10-род_линт.mjs';

for (const [кто, ветка] of Object.entries(ВЕТКИ_РАССКАЗА)) {
  const e = родовыеОшибки(строкиГрафа({ человек: кто, ветки: { журнал: ветка } }, кто));
  assert.deepEqual(e, [], `родовые формы в ветке ${кто}:\n` + e.join('\n'));
}
const найтиМесто = ид => МЕСТА.find(м => Object.values(м.модуль.КОМНАТЫ).some(к => к.люди?.includes(ид)));
const комната = (м, ид) => Object.entries(м.модуль.КОМНАТЫ).find(([, к]) => к.люди?.includes(ид))[0];
const путь = (м, куда) => {
  const К = м.модуль.КОМНАТЫ, оч = [[м.модуль.старт]], был = new Set([м.модуль.старт]);
  while (оч.length) { const п = оч.shift(), т = п.at(-1); if (т === куда) return п.slice(1); for (const с of К[т].соседи ?? []) if (!был.has(с)) { был.add(с); оч.push([...п, с]); } }
  throw new Error('нет пути до ' + куда);
};
const нажать = (S, ид) => {
  const а = действияСцены(S).find(x => x.id === ид);
  if (!а) throw new Error(`нет действия «${ид}». Есть: ` + действияСцены(S).map(x => x.id).join(' | '));
  if (а.можно === false) throw new Error(`«${ид}» недоступно: ${а.почему}`);
  а.выполнить(S);
};
const есть = (S, ид) => действияСцены(S).some(a => a.id === ид && a.можно !== false);
const заглушка = (кто, имя, ветка) => ({
  человек: кто, имя, вступление: 'Заглушка.', снова: 'Заглушка.', хаб: ['журнал', 'проститься'],
  ветки: {
    журнал: ветка,
    проститься: { ярлык: 'попрощаться', реплика: '«Пойду.»', ходы: 0, первая: true, засчитывать: false,
      узлы: { старт: { текст: ['Кивок.'], варианты: [{ ид: 'уйти', текст: 'Уйти.', закреплён: true, дальше: 'закрыть' }] } } },
  },
});
const ждёт = { bras: +1, gorm: 0 };
const итог = [];

for (const [кто, ветка] of Object.entries(ВЕТКИ_РАССКАЗА)) {
  const м = найтиМесто(кто);
  assert.ok(м, `${кто}: человека нет в местах`);
  м.модуль.ДИАЛОГИ = { ...(м.модуль.ДИАЛОГИ ?? {}), [кто]: заглушка(кто, кто, ветка) };
  const цель = комната(м, кто);
  const начать = флаги => {
    const S = новоеСостояние('семья', 72);
    S.мир.район = м.район; S.мир.отрезок = [...(м.когда ?? []), 'день'].find(о => о !== 'ночь') ?? м.когда[0]; S.мир.день = 3; S.герой.кошель = 500;
    войти(S, м.id);
    // Графовое условие `флаг` читает флаги места (Движок/разговор.js, есть()), поэтому флаг решения кладём в память места человека.
    for (const ф of флаги.места ?? []) (S.мир.места[м.id].флаги ??= []).push(ф);
    for (const ф of флаги.мира ?? []) S.мир.флаги.push(ф);
    for (const к of путь(м, цель)) нажать(S, `пойти:${к}`); нажать(S, `заговорить:${кто}`);
    return S;
  };
  const расп = S => S.мир.люди?.[кто]?.распол ?? 0;

  // 1. Без флага и при других решениях ветки нет.
  for (const места of [[], ['журнал_у_дорра'], ['журнал_у_нотариуса'], ['журнал_в_весовой'], ['журнал_у_одвина']]) {
    assert.ok(!есть(начать({ места }), 'ветка:журнал'), `${кто}: ветка есть при флагах [${места}]`);
  }
  // 1б. Ограничение движка: мировой флаг (S.мир.флаги) графовое условие `флаг` не видит. Пока это так, решение, принятое в другом месте, до Браса и Горма не дойдёт.
  assert.ok(!есть(начать({ мира: ['журнал_сожжён'] }), 'ветка:журнал'), `${кто}: движок стал читать мировые флаги — снять ограничение из 10.1 §8 и заменить флаг на флагМира`);
  // 2. При флаге сожжения в памяти места есть; проходим.
  const S = начать({ места: ['журнал_сожжён'] });
  assert.ok(есть(S, 'ветка:журнал'), `${кто}: ветки нет при флаге журнал_сожжён`);
  const до = расп(S);
  нажать(S, 'ветка:журнал'); нажать(S, 'вариант:журнал:решено');
  assert.equal(S.мир.диалоги[кто].факты.includes('знает_про_журнал'), true, `${кто}: факт не записан`);
  assert.equal(расп(S) - до, ждёт[кто], `${кто}: расположение изменилось на ${расп(S) - до}, ожидалось ${ждёт[кто]}`);
  // 3. Выход в хаб, повторно ветки нет, награды второй раз нет.
  const последний = действияСцены(S).find(a => a.id.startsWith('вариант:'));
  последний.выполнить(S);
  assert.equal(S.сцена.диалог.режим, 'хаб', `${кто}: после рассказа не вернулись в хаб`);
  assert.ok(!есть(S, 'ветка:журнал'), `${кто}: ветка осталась после рассказа`);
  assert.equal(расп(S) - до, ждёт[кто], `${кто}: расположение изменилось повторно`);
  // 4. Через день рассказ уже не доступен.
  S.мир.день += 1;
  assert.ok(!есть(S, 'ветка:журнал'), `${кто}: ветка вернулась на следующий день`);
  итог.push(`${кто.padEnd(5)} ветки нет без флага и при флагах других решений; при журнал_сожжён рассказ проходит; расположение ${ждёт[кто] >= 0 ? '+' : ''}${ждёт[кто]} один раз; повторно ветки нет`);
}
console.log(итог.join('\n'));
console.log(`\nOK: ${итог.length} ветки прошли через настоящий движок`);
