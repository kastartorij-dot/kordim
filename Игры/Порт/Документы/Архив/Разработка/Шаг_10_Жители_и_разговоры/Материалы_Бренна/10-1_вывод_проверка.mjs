// Проверка вывода героя (10.1 §4). Запуск из папки «Порт»: node Документы/На_Разбор/10-1_вывод_проверка.mjs
// 1. Верность: каждая фраза записи пересказывает только слова самой записи (заголовок и текст из Данные/свидетельства.js).
//    Сверка не с таблицей этого проекта, а с текстом игры: слова фразы должны иметь общий префикс (4 буквы) со словом записи, числа и цитаты — совпадать.
// 2. Перебор: все наборы полученных записей × допустимые состояния журнала; вывод не называет того, чего в записях нет, и не противоречит состоянию журнала.
// 3. Последовательности: решение о журнале → получение последней улики → полный вывод.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { УЗЛЫ, ЗАПИСИ, СОСТОЯНИЯ_ЖУРНАЛА, узлыИУровень, собратьВывод } from './10-1_вывод_героя.js';
import { СВИДЕТЕЛЬСТВА } from '../../Данные/свидетельства.js';
import { первоеЛицоОшибки } from './10-род_линт.mjs';

const ид = ЗАПИСИ.map(з => з.id), N = ид.length;
assert.equal(N, 14, 'ожидалось 14 записей в девяти узлах (кроме свечи)');
const норм = с => с.toLowerCase().replaceAll('ё', 'е');
const слова = с => (норм(с).match(/[а-я]+/g) ?? []);

// 1. ВЕРНОСТЬ ТЕКСТУ ЗАПИСИ
const ДОПУСТИМЫЕ_СВОИ = w => w === 'отец' || w.startsWith('отц'); // герой называет Бренна отцом; других «своих» слов во фразах записей быть не должно
const ЗАПРЕЩЁННЫЕ_ДЕТАЛИ = [/два года/i, /услуг/i, /не пришёл/i, /партия/i, /кодом огня/i, /прочитан/i, /нетронут/i, /ничего не потребовал/i, /под дальней койкой/i, /до лучших времён/i, /кто просил/i, /лежит у Браса/i];
for (const з of ЗАПИСИ) {
  const зап = СВИДЕТЕЛЬСТВА[з.id];
  assert.ok(зап, `записи «${з.id}» нет в Данные/свидетельства.js`);
  const исходник = `${зап[0]}. ${зап[1]}`, словаИсточника = слова(исходник);
  for (const w of слова(з.т)) {
    if (w.length < 4 || ДОПУСТИМЫЕ_СВОИ(w)) continue;
    assert.ok(словаИсточника.some(s => s.length >= 4 && s.slice(0, 4) === w.slice(0, 4)),
      `«${з.id}»: слово «${w}» из фразы отсутствует в тексте записи («${исходник}»). Подробность не следует из свидетельства.`);
  }
  for (const ч of з.т.match(/\d+/g) ?? []) assert.ok(исходник.includes(ч), `«${з.id}»: число ${ч} из фразы нет в записи`);
  for (const ц of з.т.match(/«[^»]+»/g) ?? []) assert.ok(исходник.includes(ц), `«${з.id}»: цитата ${ц} из фразы нет в записи`);
  for (const р of ЗАПРЕЩЁННЫЕ_ДЕТАЛИ) assert.ok(!р.test(з.т), `«${з.id}»: в фразе вернулась подробность, которой нет в записи: ${р}`);
}
// 2. ТАБЛИЦА В ДОКУМЕНТЕ СОВПАДАЕТ С ДАННЫМИ
const md = readFileSync(fileURLToPath(new URL('./10-1_Нить_Бренна.md', import.meta.url)), 'utf-8');
for (const з of ЗАПИСИ) assert.ok(md.includes(з.т), `фразы записи «${з.id}» нет в 10-1_Нить_Бренна.md (раздел 4): документ и данные разошлись`);
for (const [с, т] of Object.entries(СОСТОЯНИЯ_ЖУРНАЛА)) if (т) assert.ok(md.includes(т), `фразы состояния «${с}» нет в 10-1_Нить_Бренна.md`);

// 3. ПЕРЕБОР
const ТОКЕНЫ = [
  [/печат/i, ['brenn_office_entry']], [/чётн/i, ['brenn_gorm_word']], [/41 грош/i, ['brenn_cell17']], [/Скарре/i, ['brenn_cell17_label']],
  [/41 ночь/i, ['brenn_hostel_book']], [/сапог/i, ['brenn_hostel_boots']], [/лёгких|карточк/i, ['brenn_healer_card']], [/Локи|(?<![а-я])долг/i, ['brenn_loki_note']],
  [/гостей маяка|визит/i, ['brenn_lighthouse_log']], [/Ифо|сигнал/i, ['brenn_ifo_word']], [/пломб/i, ['brenn_market_seal']], [/задолго/i, ['brenn_bras_word']],
  [/Брас/i, ['brenn_bras_word', 'brenn_market_seal']], [/ночлежк/i, ['brenn_hostel_book', 'brenn_hostel_boots']], [/Горм/i, ['brenn_gorm_word']], [/доковой книге/i, ['brenn_office_entry', 'brenn_second_journal_seen']],
  [/журнал|записи отца|записи весов/i, ['brenn_second_journal', 'brenn_second_journal_seen']], [/Тон /i, ['brenn_hostel_boots']],
];
const состояния = Object.keys(СОСТОЯНИЯ_ЖУРНАЛА);
let всегоНаборов = 1 << N, достигли = 0, понимание = 0, полная = 0, вариантов = 0;
for (let маска = 0; маска < всегоНаборов; маска++) {
  const набор = new Set(ид.filter((_, i) => маска & (1 << i)));
  const { уровень } = узлыИУровень(набор);
  if (уровень !== 'понимание' && уровень !== 'полная') continue;
  достигли++; уровень === 'понимание' ? понимание++ : полная++;
  for (const с of состояния) {
    const допустимо = (с === 'не_выдан') !== набор.has('brenn_second_journal');
    if (!допустимо) { assert.throws(() => собратьВывод(уровень, набор, с), /журнал/, `недопустимая пара набор/состояние «${с}» не отвергнута`); continue; }
    вариантов++;
    const т = собратьВывод(уровень, набор, с);
    for (const з of ЗАПИСИ) {
      const вытеснена = (з.id.endsWith('_seen') && набор.has('brenn_second_journal')) || (з.id.endsWith('_label') && набор.has('brenn_cell17'));
      if (!набор.has(з.id) || вытеснена) assert.ok(!т.includes(з.т), `лишняя фраза «${з.id}»: ${т}`);
      else assert.ok(т.includes(з.т), `нет фразы полученной записи «${з.id}»`);
    }
    for (const [р, нужны] of ТОКЕНЫ) if (р.test(т)) assert.ok(нужны.some(н => набор.has(н)), `вывод упоминает «${т.match(р)[0]}» без записей ${нужны}: ${т}`);
    for (const р of ЗАПРЕЩЁННЫЕ_ДЕТАЛИ) assert.ok(!р.test(т), `в выводе подробность без записи: ${р}`);
    // состояние журнала: ровно одна фраза состояния и только своя; «решать мне» — только пока журнал получен и не решён
    for (const [с2, ф] of Object.entries(СОСТОЯНИЯ_ЖУРНАЛА)) if (ф) assert.equal(т.includes(ф), с2 === с, `фраза состояния «${с2}» ${т.includes(ф) ? 'есть' : 'нет'} при состоянии «${с}»`);
    assert.equal(/решать мне/.test(т), с === 'получен', `«решать мне» при состоянии «${с}»`);
    const е = первоеЛицоОшибки([['вывод', т]]); assert.deepEqual(е, [], 'родовые формы: ' + е.join('; '));
  }
}
// 4. ПОСЛЕДОВАТЕЛЬНОСТИ «решение о журнале → последняя улика → полный вывод»
const без = (...убрать) => new Set(ид.filter(и => !убрать.includes(и)));
const РЕШЕНИЯ = ['оставлен', 'возвращён', 'у_дорра', 'продан', 'сожжён'];
for (const решение of РЕШЕНИЯ) {
  // журнал получен и решён раньше всего; последняя улика — вексель Локи; затем полный вывод
  const доЛоки = без('brenn_loki_note');
  assert.notEqual(узлыИУровень(доЛоки).уровень, 'полная', 'без Локи полной картины быть не должно');
  const послеЛоки = new Set([...доЛоки, 'brenn_loki_note']);
  assert.equal(узлыИУровень(послеЛоки).уровень, 'полная');
  const т = собратьВывод('полная', послеЛоки, решение);
  assert.ok(!/решать мне/.test(т), `после решения «${решение}» вывод всё ещё говорит «решать мне»: ${т}`);
  assert.ok(т.includes(СОСТОЯНИЯ_ЖУРНАЛА[решение]), `вывод не отражает решение «${решение}»`);
  assert.ok(т.includes('долг Локи'), 'последняя улика (Локи) не попала в полный вывод');
}
// журнал получен последним, решения ещё нет → вывод предлагает решать
{
  const послеЖурнала = без();
  const т = собратьВывод('полная', послеЖурнала, 'получен');
  assert.ok(/решать мне/.test(т), 'журнал получен последним: вывод должен оставить решение за героем');
}
// после сожжения и получения последней записи уровень «понимание» тоже согласован (журнал сожжён раньше, чем набрано пять узлов)
{
  const набор = new Set(['brenn_second_journal', 'brenn_bras_word', 'brenn_cell17', 'brenn_healer_card', 'brenn_gorm_word']);
  assert.equal(узлыИУровень(набор).уровень, 'понимание');
  const т = собратьВывод('понимание', набор, 'сожжён');
  assert.ok(т.includes('Журнала больше нет.') && !/решать мне/.test(т) && !/доковой книге/.test(т));
}
// 5. ПРИМЕР ИЗ ОТЗЫВА
const пример = new Set(['brenn_bras_word', 'brenn_gorm_word', 'brenn_hostel_book', 'brenn_healer_card', 'brenn_loki_note']);
assert.equal(узлыИУровень(пример).уровень, 'понимание');
const текстПримера = собратьВывод('понимание', пример);
assert.ok(!/печат|контор/i.test(текстПримера), 'пример: упомянута печать или контора');

const ф = n => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
const сводка = `Проверка перебирает все ${ф(всегоНаборов)} наборов записей (2^${N}); уровня «понимание» или «полная картина» достигают ${ф(достигли)}; с допустимыми состояниями журнала это ${ф(вариантов)} вариантов вывода.`;
assert.ok(md.includes(сводка), `в 10-1_Нить_Бренна.md нет верной строки о переборе. Нужна: ${сводка}`);
console.log(сводка);
console.log('Фразы записей сверены с текстом Данные/свидетельства.js; последовательности «решение → последняя улика → полный вывод» проверены для пяти решений.');
console.log('\nПример (рынок, Горм, ночлежка, лекарь, Локи):\n  ' + текстПримера);
console.log('\nОК');
