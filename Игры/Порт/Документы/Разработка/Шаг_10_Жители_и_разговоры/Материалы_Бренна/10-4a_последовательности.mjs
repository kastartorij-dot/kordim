// Проверка последовательностей «беседа → событие → повторный визит» (замечание проверки 04.10: условные ответы стояли внутри уже закрытых веток).
// Для каждого события, от которого зависит хоть что-то в графе человека (тема, флаг места), делаем так: пройти все доступные ветки без события →
// произошло событие → вернуться к человеку. Если после события не появилось ничего нового (ни новой ветки, ни новой строки «видят»), проверка падает.
// Это ловит содержимое, которое зависит от события, но лежит внутри ветки, уже закрытой первой беседой.
// Запуск из папки «Порт»: node Документы/На_Разбор/10-4a_последовательности.mjs
import assert from 'node:assert/strict';
import { МЕСТА } from '../../Данные/места.js';
import { новоеСостояние } from '../../Движок/состояние.js';
import { войти, действияСцены, вернутьсяВГород } from '../../Движок/разговор.js';
import { верностьТемы, датьТему, СЛЫШАЛ, ОПРОВЕРГНУТО } from '../../Движок/знание.js';
import { ДИАЛОГИ_ФОНОВЫЕ } from './10-4a_фоновые_жители.js';
import { АЛЬТЕРНАТИВЫ } from './10-4a_альтернативы_Йора_Пин.js';
const ВСЕ_ГРАФЫ = { ...ДИАЛОГИ_ФОНОВЫЕ, ...АЛЬТЕРНАТИВЫ };

const найтиМесто = ид => МЕСТА.find(м => Object.values(м.модуль.КОМНАТЫ).some(к => к.люди?.includes(ид)));
const комната = (м, ид) => Object.entries(м.модуль.КОМНАТЫ).find(([, к]) => к.люди?.includes(ид))[0];
const путь = (м, куда) => {
  const К = м.модуль.КОМНАТЫ, оч = [[м.модуль.старт]], был = new Set([м.модуль.старт]);
  while (оч.length) { const п = оч.shift(), т = п.at(-1); if (т === куда) return п.slice(1); for (const с of К[т].соседи ?? []) if (!был.has(с)) { был.add(с); оч.push([...п, с]); } }
  throw new Error('нет пути до ' + куда);
};
const нажать = (S, ид) => {
  const а = действияСцены(S).find(x => x.id === ид);
  if (!а) throw new Error(`нет действия «${ид}». Есть: ` + действияСцены(S).map(x => x.id).join(' | '));
  if (а.можно === false) throw new Error(`«${ид}» недоступно: ${а.почему}`);
  а.выполнить(S);
};
const есть = (S, ид) => действияСцены(S).some(a => a.id === ид && a.можно !== false);
const ветки = S => действияСцены(S).filter(a => a.id.startsWith('ветка:') && a.можно !== false).map(a => a.id).sort();
const лента = S => (S.сцена.диалог?.лента ?? []);

// Все события, от которых что-то зависит в графе человека.
const КЛЮЧИ_СОБЫТИЙ = ['тема', 'флаг'];
function события(граф) {
  const е = new Set();
  const взять = у => { if (!у) return; for (const к of КЛЮЧИ_СОБЫТИЙ) if (у[к]) е.add(`${к}:${у[к]}`); взять(у.не); (у.любое ?? []).forEach(взять); };
  for (const в of граф.видят ?? []) взять(в.если);
  for (const в of Object.values(граф.ветки)) {
    взять(в.если);
    for (const у of Object.values(в.узлы)) {
      for (const э of у.текст ?? []) if (typeof э !== 'string') взять(э.если);
      for (const в_ of у.варианты ?? []) взять(в_.если);
    }
  }
  return [...е];
}

const итог = [];
for (const [кто, граф] of Object.entries(ВСЕ_ГРАФЫ)) {
  const м = найтиМесто(кто);
  м.модуль.ДИАЛОГИ = { ...(м.модуль.ДИАЛОГИ ?? {}), [кто]: граф };
  const цель = комната(м, кто);
  const свежая = () => {
    const S = новоеСостояние('семья', 72);
    S.мир.район = м.район; S.мир.отрезок = [...(м.когда ?? []), 'день'].find(о => о !== 'ночь') ?? м.когда[0]; S.мир.день = 3; S.герой.кошель = 500;
    войти(S, м.id);
    for (const к of путь(м, цель)) нажать(S, `пойти:${к}`);
    нажать(S, `заговорить:${кто}`);
    return S;
  };
  const вХаб = S => { let н = 0; while (S.сцена.диалог?.режим === 'ветка' && н++ < 8) { const в = действияСцены(S).find(a => a.id.startsWith('вариант:') && a.можно !== false && !a.закреплён); if (!в) break; в.выполнить(S); } assert.equal(S.сцена.диалог.режим, 'хаб', `${кто}: не вернулись в хаб`); };
  const пройтиВсё = S => { for (let н = 0; н < 20; н++) { const пройдено = new Set(Object.keys(S.мир.диалоги?.[кто]?.ветки ?? {}).filter(б => S.мир.диалоги[кто].ветки[б].исход)); const следующая = ветки(S).map(x => x.slice(6)).find(б => б !== 'проститься' && !пройдено.has(б)); if (!следующая) return; нажать(S, `ветка:${следующая}`); вХаб(S); } throw new Error('цикл'); };
  // строка «видят» после перезапуска разговора (видят вычисляется при каждом начале разговора)
  const видятПослеПерезапуска = S => { нажать(S, 'отойти'); нажать(S, `заговорить:${кто}`); return лента(S).filter(з => з.вид === 'видят').map(з => з.т).join('|'); };
  const применить = (S, е) => {
    const [к, зн] = [е.slice(0, е.indexOf(':')), е.slice(е.indexOf(':') + 1)];
    if (к === 'тема') датьТему(S, зн, СЛЫШАЛ); else (S.мир.места[м.id].флаги ??= []).push(зн);
  };

  // «Вернуться» = новый визит: выйти из места и войти снова на следующий день (движок создаёт новую сцену, память людей остаётся).
  const вернуться = S => { if (есть(S, 'отойти')) нажать(S, 'отойти'); вернутьсяВГород(S); S.мир.день += 1; войти(S, м.id); for (const к of путь(м, цель)) нажать(S, `пойти:${к}`); нажать(S, `заговорить:${кто}`); };
  const ев = события(граф);
  for (const е of ев) {
    // Сценарий А: в том же визите. Все доступные ветки пройдены → наступило событие → в хабе должна появиться новая ветка.
    const S = свежая();
    пройтиВсё(S);
    const до = ветки(S);
    применить(S, е);
    const новые = ветки(S).filter(x => !до.includes(x));
    assert.ok(новые.length,
      `${кто}: после беседы наступило событие «${е}» (тот же визит), но новой ветки в хабе нет. Содержимое для этого события лежит внутри уже закрытой ветки.`);
    for (const н of новые) {
      const бид = н.slice(6), в = граф.ветки[бид];
      нажать(S, н); вХаб(S);
      for (const т of Object.values(в.узлы).flatMap(у => у.варианты).map(в_ => в_.эффект?.опровергнуть).filter(Boolean))
        assert.equal(верностьТемы(S, т), ОПРОВЕРГНУТО, `${кто}: ветка «${бид}» не опровергла слух «${т}»`);
      нажать(S, н);
      assert.ok(лента(S).some(з => (в.уже ?? []).includes(з.т)), `${кто}: повторный вход в «${бид}» не дал строку «уже говорили»`);
      вХаб(S);
    }
    // Сценарий Б: новый визит. Событие произошло после первой беседы, герой ушёл и вернулся на следующий день: новая ветка доступна, а если у человека
    // есть строка «видят» для этого события, она показывается при встрече.
    const S2 = свежая();
    пройтиВсё(S2);
    применить(S2, е);
    вернуться(S2);
    const новые2 = ветки(S2).filter(x => !до.includes(x));
    assert.deepEqual(новые2, новые, `${кто}: на следующий день после события «${е}» новые ветки другие: было ${новые}, стало ${новые2}`);
    const видят = (граф.видят ?? []).filter(в => JSON.stringify(в.если ?? {}).includes(е.split(':')[1]));
    for (const в of видят) assert.ok(лента(S2).some(з => з.вид === 'видят' && з.т === в.т), `${кто}: при новом визите нет строки «видят» для события «${е}»`);
    итог.push(`${кто.padEnd(6)} ${е.padEnd(24)} тот же визит: ветка ${новые.map(x => x.slice(6)).join(', ')}; следующий день: та же ветка${видят.length ? ' + кивок «видят»' : ''}`);
  }
}
console.log(итог.join('\n'));
console.log(`\nOK: ${итог.length} событий открывают новое содержимое после уже проведённых бесед`);
