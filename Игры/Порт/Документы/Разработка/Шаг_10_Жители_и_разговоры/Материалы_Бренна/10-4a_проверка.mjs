// Проверка 10.4a: структура графов по словарю движка (Движок/диалог.js, Движок/эффекты.js) и правилам автора для фонового НПС.
// Запуск из папки «Порт»: node Документы/На_Разбор/10-4a_проверка.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { ДИАЛОГИ_ФОНОВЫЕ, ЗАДАЧИ_ВНЕДРЕНИЯ, ДОКАЗАТЕЛЬСТВА_ОПРОВЕРЖЕНИЙ } from './10-4a_фоновые_жители.js';
import { АЛЬТЕРНАТИВЫ } from './10-4a_альтернативы_Йора_Пин.js';
const ВСЕ_ГРАФЫ = { ...ДИАЛОГИ_ФОНОВЫЕ, ...АЛЬТЕРНАТИВЫ };
import { родовыеОшибки, строкиГрафа } from './10-род_линт.mjs';

const корень = fileURLToPath(new URL('../../', import.meta.url)); // …/Порт/
const читать = п => readFileSync(корень + п, 'utf-8');

// Словарь условий — из исходника движка (если(S, у, кто)): ключи вида `у.<ключ>` и `['сыт', …]`.
const движок = читать('Движок/диалог.js');
const телесные = ['сыт', 'отдых', 'тепло', 'цел'];
const УСЛОВИЯ = new Set([...телесные, ...[...движок.matchAll(/(?<![\p{L}\d_])у\.(\p{L}+)/gu)].map(m => m[1])]);
// Словарь эффектов: свои ключи диалога + мини-язык эффектов места (эффекты.js).
const СВОИ = ['слух', 'факт', 'открыть', 'зарубка', 'тень', 'сдатьОружие', 'обещание', 'выполнено', 'один'];
const ЭФФЕКТЫ = new Set([...СВОИ, ...[...читать('Движок/эффекты.js').matchAll(/(?<![\p{L}\d_])э\.(\p{L}+)/gu)].map(m => m[1])]);
const ТЕМЫ = new Set([...читать('Данные/темы.js').matchAll(/^\s{2}([a-z_0-9]+):\s*\{/gm)].map(m => m[1]));
const ФОРМЫ_ДАЛЬШЕ = new Set(['хаб', 'назад', 'закрыть']);
const ПОЛЯ_ГРАФА = ['человек', 'имя', 'вступление', 'снова', 'хаб', 'ветки'];

const ошибки = [], инфо = { людей: 0, веток: 0, узлов: 0, вариантов: 0, строк: 0, максСлов: 0 };
const ош = (где, что) => ошибки.push(`${где}: ${что}`);

const проверитьУсловие = (где, у) => {
  if (!у) return;
  for (const к of Object.keys(у)) {
    if (!УСЛОВИЯ.has(к)) ош(где, `условие «${к}» движок не знает`);
    if (['не'].includes(к)) проверитьУсловие(где + '.не', у[к]);
    if (к === 'любое') у[к].forEach((x, i) => проверитьУсловие(`${где}.любое[${i}]`, x));
    if (к === 'тема' || к === 'нетТемы') if (!ТЕМЫ.has(у[к])) ош(где, `тема «${у[к]}» нет в реестре`);
    if (телесные.includes(к) && !(Array.isArray(у[к]) && у[к].length === 2)) ош(где, `«${к}» должен быть диапазоном [от, до]`);
  }
};
const проверитьЭффект = (где, э) => {
  if (!э) return;
  for (const к of Object.keys(э)) {
    if (!ЭФФЕКТЫ.has(к)) ош(где, `эффект «${к}» движок не знает`);
    if (['опровергнуть', 'подтвердить'].includes(к) && !ТЕМЫ.has(э[к])) ош(где, `тема «${э[к]}» нет в реестре`);
  }
};
const слов = т => String(т).replace(/[«»—]/g, ' ').trim().split(/\s+/).filter(Boolean).length;
const проверитьСтроку = (где, т) => {
  инфо.строк++;
  const с = слов(т);
  инфо.максСлов = Math.max(инфо.максСлов, с);
  if (с > 60) ош(где, `строка длиннее 60 слов (${с})`);
  if (typeof т !== 'string' || !т.trim()) ош(где, 'пустая или не строка');
};

for (const [ид, г] of Object.entries(ВСЕ_ГРАФЫ)) {
  инфо.людей++;
  for (const п of ПОЛЯ_ГРАФА) if (!г[п]) ош(ид, `нет поля «${п}»`);
  if (г.человек !== ид) ош(ид, `человек «${г.человек}» ≠ ключ`);
  // Правила автора для фонового: 1–2 темы + прощание; последняя кнопка хаба — прощание; без манер.
  const основные = г.хаб.filter(х => х !== 'проститься' && !г.ветки[х]?.если), условные = г.хаб.filter(х => г.ветки[х]?.если);
  if (основные.length < 1 || основные.length > 2) ош(ид, `безусловных тем в хабе ${основные.length}, правило автора для фонового: 1–2`);
  if (условные.length > 3) ош(ид, `условных тем ${условные.length}: больше трёх`);
  if (г.хаб.at(-1) !== 'проститься') ош(ид, 'последняя кнопка хаба — не «проститься»');
  for (const х of г.хаб) if (!г.ветки[х]) ош(ид, `в хабе «${х}», а ветки нет`);
  for (const в of Object.keys(г.ветки)) if (!г.хаб.includes(в)) ош(ид, `ветка «${в}» не показана в хабе`);
  проверитьСтроку(`${ид}.вступление`, г.вступление); проверитьСтроку(`${ид}.снова`, г.снова);
  for (const [к, в] of Object.entries(г.видят ?? [])) { проверитьУсловие(`${ид}.видят[${к}]`, в.если); проверитьСтроку(`${ид}.видят[${к}]`, в.т); }

  const идыВетки = new Set();
  for (const [бид, в] of Object.entries(г.ветки)) {
    инфо.веток++;
    const где = `${ид}.${бид}`;
    if ('манера' in в) ош(где, 'поле «манера»: правило автора — переключатель манер не используем');
    if (!в.ярлык || !в.реплика) ош(где, 'нет ярлыка или реплики героя');
    if (в.реплика && !/^«.+»$/.test(в.реплика)) ош(где, 'реплика героя не в «…»');
    проверитьУсловие(где + '.если', в.если);
    if (!Number.isInteger(в.ходы ?? 1) || (в.ходы ?? 1) < 0) ош(где, 'ходы должны быть целым ≥ 0');
    if (бид !== 'проститься') {
      if (!Array.isArray(в.уже) || в.уже.length < 2) ош(где, 'нужен список `уже` минимум из двух строк (повтор не должен быть одной фразой)');
      (в.уже ?? []).forEach((т, i) => проверитьСтроку(`${где}.уже[${i}]`, т));
    }
    if (!в.узлы?.старт) { ош(где, 'нет узла «старт»'); continue; }
    // достижимость узлов из старта
    const достигнуты = new Set(['старт']), очередь = ['старт'];
    while (очередь.length) {
      const у = в.узлы[очередь.shift()];
      for (const вар of у?.варианты ?? []) {
        const д = вар.дальше;
        if (typeof д === 'string' && !ФОРМЫ_ДАЛЬШЕ.has(д) && в.узлы[д] && !достигнуты.has(д)) { достигнуты.add(д); очередь.push(д); }
      }
    }
    for (const [уид, у] of Object.entries(в.узлы)) {
      инфо.узлов++;
      const гд = `${где}.${уид}`;
      if (!достигнуты.has(уид)) ош(гд, 'узел недостижим из «старт»');
      (Array.isArray(у.текст) ? у.текст : []).forEach((э, i) => {
        if (typeof э === 'string') проверитьСтроку(`${гд}.текст[${i}]`, э);
        else { проверитьУсловие(`${гд}.текст[${i}].если`, э.если); проверитьСтроку(`${гд}.текст[${i}]`, э.т); }
      });
      if (!Array.isArray(у.текст) || !у.текст.length) ош(гд, 'у узла нет текста');
      if (!у.варианты?.length) { ош(гд, 'узел без вариантов — тупик, выйти нельзя'); continue; }
      let выход = false;
      for (const вар of у.варианты) {
        инфо.вариантов++;
        const вг = `${гд}.${вар.ид ?? '?'}`;
        if (!вар.ид) ош(вг, 'нет ид');
        else {
          if (идыВетки.has(бид + ':' + вар.ид) ) ош(вг, 'ид варианта повторяется в ветке: награды и память склеятся');
          идыВетки.add(бид + ':' + вар.ид);
        }
        if (typeof вар.текст !== 'string' || !/^«.+»$|^[А-ЯЁ].+\.$/.test(вар.текст)) ош(вг, 'текст варианта должен быть в «…» (реплика) или действием с точкой');
        if ('манера' in вар) ош(вг, 'поле «манера» не используется');
        if ('text' in вар) ош(вг, 'лишнее поле «text»');
        проверитьУсловие(вг + '.если', вар.если); проверитьЭффект(вг + '.эффект', вар.эффект);
        const д = вар.дальше;
        if (д === undefined) ош(вг, 'нет «дальше»: переход не определён');
        else if (typeof д === 'string') {
          if (ФОРМЫ_ДАЛЬШЕ.has(д)) выход = true;
          else if (!в.узлы[д]) ош(вг, `дальше «${д}»: такого узла нет`);
        } else if (д?.ветка) { if (!г.ветки[д.ветка]) ош(вг, `дальше: ветка «${д.ветка}» не существует`); }
        else ош(вг, 'непонятная форма «дальше»');
        for (const [к, т] of Object.entries(вар.ответ ?? [])) проверитьСтроку(`${вг}.ответ[${к}]`, т);
      }
      if (!выход && !у.варианты.some(v => typeof v.дальше === 'string' && в.узлы[v.дальше])) ош(гд, 'нет пути в хаб/закрыть');
    }
    // каждая ветка, кроме прощания, обязана хоть раз вернуть в хаб
    if (бид !== 'проститься' && !Object.values(в.узлы).some(у => (у.варианты ?? []).some(v => v.дальше === 'хаб'))) ош(где, 'ветка не возвращает в хаб');
  }
}

// Опровержения и подтверждения: у каждого эффекта должно быть записанное доказательство (ДОКАЗАТЕЛЬСТВА_ОПРОВЕРЖЕНИЙ), и только для слухов о прошлом или настоящем.
{
  const нужны = new Set();
  for (const [ид, г] of Object.entries(ВСЕ_ГРАФЫ)) for (const [бид, в] of Object.entries(г.ветки)) for (const [уид, у] of Object.entries(в.узлы))
    for (const вар of у.варианты) for (const к of ['опровергнуть', 'подтвердить']) if (вар.эффект?.[к]) {
      const ключ = `${ид}.${бид}.${вар.ид}`;
      нужны.add(ключ);
      const д = ДОКАЗАТЕЛЬСТВА_ОПРОВЕРЖЕНИЙ[ключ];
      if (!д || д.length < 40) ош(ключ, `эффект «${к}: ${вар.эффект[к]}» без записанного доказательства (ДОКАЗАТЕЛЬСТВА_ОПРОВЕРЖЕНИЙ)`);
      if (вар.эффект[к] === 'lozh_strazha') ош(ключ, 'слух «lozh_strazha» о будущем: словом человека не опровергается');
    }
  for (const к of Object.keys(ДОКАЗАТЕЛЬСТВА_ОПРОВЕРЖЕНИЙ)) if (!нужны.has(к)) ош(к, 'доказательство есть, а эффекта нет');
}
// События внутри тела ветки: ветка после первого прохождения закрывается («уже говорили»), поэтому всё, что зависит от события (тема, флаг), обязано стоять на уровне ветки.
for (const [ид, г] of Object.entries(ВСЕ_ГРАФЫ)) for (const [бид, в] of Object.entries(г.ветки)) for (const [уид, у] of Object.entries(в.узлы)) {
  const проверитьТело = (где, усл) => { for (const к of ['тема', 'нетТемы', 'флаг', 'нетФлага']) if (усл?.[к]) ош(где, `условие «${к}» внутри ветки: после первой беседы оно недоступно; вынести условие на уровень ветки или в «видят»`); };
  for (const [i, э] of (у.текст ?? []).entries()) if (typeof э !== 'string') проверитьТело(`${ид}.${бид}.${уид}.текст[${i}]`, э.если);
  for (const в_ of у.варианты ?? []) проверитьТело(`${ид}.${бид}.${уид}.${в_.ид}`, в_.если);
}

// Родовые формы: реплики героя и обращения к нему (правило автора, 10-род_линт.mjs).
for (const [ид, г] of Object.entries(ВСЕ_ГРАФЫ)) for (const e of родовыеОшибки(строкиГрафа(г, ид))) ош(ид, e);

// Эффекты и условия реально используются: проверка, что словарь прочитан, а не пуст.
assert.ok(УСЛОВИЯ.size > 20 && УСЛОВИЯ.has('тема') && УСЛОВИЯ.has('флаг'), `словарь условий не прочитан (${УСЛОВИЯ.size})`);
assert.ok(ЭФФЕКТЫ.has('опровергнуть') && ЭФФЕКТЫ.has('распол'), `словарь эффектов не прочитан (${ЭФФЕКТЫ.size})`);
assert.ok(ТЕМЫ.has('lozh_gorm') && ТЕМЫ.has('seraya_radost'), 'реестр тем не прочитан');
// Повторяющиеся реплики людей: одинаковая строка у двух разных людей считается ошибкой.
const видели = new Map();
for (const [ид, г] of Object.entries(ВСЕ_ГРАФЫ)) {
  const собрать = o => JSON.stringify(o).match(/"(— [^"]+)"/g) ?? [];
  for (const с of собрать(г)) { const к = видели.get(с); if (к && к !== ид) ош(ид, `строка повторяет реплику ${к}: ${с.slice(0, 50)}…`); видели.set(с, ид); }
}

console.log(`людей ${инфо.людей}, веток ${инфо.веток}, узлов ${инфо.узлов}, вариантов ${инфо.вариантов}, строк ${инфо.строк}, самая длинная ${инфо.максСлов} слов`);
console.log(`словарь условий: ${УСЛОВИЯ.size}, эффектов: ${ЭФФЕКТЫ.size}, тем в реестре: ${ТЕМЫ.size}`);
if (ошибки.length) { console.error('\nОШИБКИ:\n' + ошибки.map(x => ' - ' + x).join('\n')); process.exit(1); }
console.log('OK: структура графов проходит проверку');

// Читаемая копия собирается из тех же данных.
const md = [];
const тип = 'фоновый';
const героев = Object.entries(ВСЕ_ГРАФЫ).reduce((n, [и, г]) => n + строкиГрафа(г, и).герой.length, 0);
md.push('# Шаг 10.4a — фоновые жители девяти мест', '',
  '**Статус:** рабочий текст, 06.10.2026. Не подключён к игре. Источники — [10-4a_фоновые_жители.js](10-4a_фоновые_жители.js) (основная партия) и [10-4a_альтернативы_Йора_Пин.js](10-4a_альтернативы_Йора_Пин.js); этот файл собран из них скриптом [10-4a_проверка.mjs](10-4a_проверка.mjs) (он же проверяет структуру). Править нужно `.js`, затем запустить скрипт. Реплики — черновик, автор их не подтверждал.', '',
  '**Основная партия — семь человек:** Свищ, Кип, Бранка, Ним, Гвоздь, Мила, Кук. **Поправка к состоянию на 08.10.2026:** в присланных диалогах 21–30 (`Разработка/Шаг_10_Жители_и_разговоры/Диалоги_НПС/`) уже есть Свищ (21), Кип (23), Бранка (25), Ним (26) и Гвоздь (29). Без присланной версии из этой партии остаются только Мила и Кук. По правилу «две версии одного человека одновременно не внедрять» первые пятеро в таком же положении, как Йора и Пин; регруппировать ли партию, решает автор.', '',
  '**Альтернативы — два человека: Тётка Йора и Пин Кроп.** В `Разработка/Шаг_10_Жители_и_разговоры/Диалоги_НПС/` уже лежат присланные версии этих двух (15 и 16). Версии ниже — альтернатива в формате графа с проверками. **Две версии одного человека в игру одновременно не ставить: внедрять либо присланные 15 и 16, либо эти.** Я ничего чужого не менял и не удалял.', '',
  'Формат — граф диалога из `Движок/диалог.js`, образец `Данные/Диалоги/сиб.js`. Тип каждого человека задан автором в `ВСЕ_ДИАЛОГИ_НПС.md`: все девять фоновые (приветствие, 1–2 безусловные темы, прощание; условные темы появляются по событию). Пары «реплика героя → ответ» строятся без переключателя манер.', '');
const РАЗДЕЛЫ = [['Основная партия (7 человек)', ДИАЛОГИ_ФОНОВЫЕ], ['Альтернативы к присланным черновикам 15 и 16 (2 человека): не внедрять вместе с ними', АЛЬТЕРНАТИВЫ]];
for (const [заголовок, графы] of РАЗДЕЛЫ) {
md.push(`## ${заголовок}`, '');
for (const [ид, г] of Object.entries(графы)) {
  md.push(`### ${г.имя} (\`${ид}\`, ${тип})`, '', `- **Первая встреча.** ${г.вступление}`, `- **Повторная.** ${г.снова}`);
  for (const в of г.видят ?? []) md.push(`- **Видит по герою** (если ${JSON.stringify(в.если).replace(/"/g, '')}). ${в.т}`);
  md.push('');
  for (const [бид, в] of Object.entries(г.ветки)) {
    const усл = в.если ? ` Доступна, если ${JSON.stringify(в.если).replace(/"/g, '')}.` : '';
    md.push(`#### ${в.ярлык}`, '', `Герой: ${в.реплика}.${усл}`.replace('».', '»'), '');
    for (const [уид, у] of Object.entries(в.узлы)) {
      md.push(`**Узел «${уид}»**`, '');
      for (const э of у.текст) md.push(typeof э === 'string' ? `> ${э}` : `> ${э.т} *(если ${JSON.stringify(э.если).replace(/"/g, '')})*`, '>');
      md.pop();
      md.push('');
      for (const вар of у.варианты) {
        const ефф = вар.эффект ? ` Эффект: \`${JSON.stringify(вар.эффект)}\`.` : '';
        const если = вар.если ? ` Если ${JSON.stringify(вар.если).replace(/"/g, '')}.` : '';
        const куда = typeof вар.дальше === 'string' ? (в.узлы[вар.дальше] ? `узел «${вар.дальше}»` : вар.дальше) : `ветка «${вар.дальше.ветка}»`;
        md.push(`- ${вар.текст} → ${куда}.${если}${ефф}`);
      }
      md.push('');
    }
    if (в.уже) md.push(`Если ветку уже проходили: ${в.уже.map(x => '«' + x + '»').join(' / ')}`, '');
  }
}
}
md.push('## Опровержения и их доказательства', '');
