// ── часы ──
const часы = (отр, дел) => `${отр} ${дел}/${ДЕЛ}`;
function сдвиг(t, n, ёмк = () => ДЕЛ) { // t = {д, о, к} день, индекс отрезка, деление
  let { д, о, к } = t;
  while (n > 0) {
    const cap = ёмк(о);
    const шаг = Math.min(n, cap - к);
    к += шаг; n -= шаг;
    if (к >= cap) { к = 0; о += 1; if (о > 3) { о = 0; д += 1; } }
  }
  return { д, о, к };
}
