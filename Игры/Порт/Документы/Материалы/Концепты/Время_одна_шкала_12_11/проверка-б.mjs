function прогон(назв, шаги) {
  let t = { д: 0, о: 0, к: 0 }, район = 'доки';
  const лог = [];
  for (const ш of шаги) {
    const до = часы(О[t.о], t.к);
    if (ш.в) { const п = дорога(район, ш.в); t = сдвиг(t, п); лог.push(`${до} дорога → ${имя(ш.в)} (${п})`); район = ш.в; continue; }
    if (ш.смена) { const р = РАБОТЫ.find(x => x.id === ш.смена); if (!р.когда.includes(О[t.о])) { лог.push(`${до} ${р.id}: НЕ БЕРУТ (${О[t.о]})`); continue; } t = сдвиг(t, р.отрезков * ДЕЛ); лог.push(`${до} смена «${р.имя}» +${р.плата} гр. → до ${часы(О[t.о], t.к)}`); continue; }
    if (ш.место) { const м = МЕСТА.find(x => x.id === ш.место); if (!м.когда.includes(О[t.о])) { лог.push(`${до} ${м.имя}: закрыто`); continue; }
      let n = 0; while (n < ш.дел && м.когда.includes(О[t.о])) { t = сдвиг(t, 1); n++; }
      лог.push(`${до} «${м.имя}»: ${n} из ${ш.дел} вопросов${n < ш.дел ? ' — закрылось' : ''} → ${часы(О[t.о], t.к)}`); continue; }
    if (ш.ждать) { const о = t.о; t = { ...t, о: О.indexOf(ш.ждать), к: 0 }; лог.push(`${до} подождать до ${ш.ждать}`); continue; }
    if (ш.сон) { const ночь = О[t.о] === 'ночь' ? t.к : 0; лог.push(`${до} сон: ${ш.сон}${ночь > 3 ? ' — поздно, отдых −1' : ' — полный отдых'}`); }
  }
  console.log(`— ${назв}\n   ` + лог.join('\n   '));
}
