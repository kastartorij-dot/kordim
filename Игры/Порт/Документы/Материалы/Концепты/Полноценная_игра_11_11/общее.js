// Общее для макетов: шапка как в игре и рисованные кодом пиксельные человечки.
// Человечки — заглушки для показа масштаба и чтения сцены, не готовый арт.

export function шапка({ день = 6, отрезок = 'вечер', где = 'Доки', погода = 'ясно', кошель = 43, тело = [3, 2, 3, 4] } = {}) {
  const сутки = ['утро', 'день', 'вечер', 'ночь'];
  const i = сутки.indexOf(отрезок);
  const полоски = n => '<b>' + [0, 1, 2, 3].map(k => `<u class="${k < n ? '' : 'нет'}"></u>`).join('') + '</b>';
  const el = document.createElement('header');
  el.className = 'hud';
  el.innerHTML = `<div class="бренд">Порт Теней<small>ранняя осень · 1026</small></div>
    <div class="день">День ${день}</div>
    <div class="сутки">${сутки.map((с, k) => `<span class="${k === i ? 'тут' : k < i ? 'было' : ''}">${с}</span>`).join('')}</div>
    <div class="тело"><i>${полоски(тело[0])}сыт</i><i>${полоски(тело[1])}отдых</i><i>${полоски(тело[2])}тепло</i><i>${полоски(тело[3])}цел</i></div>
    <div class="где">${где}<small>${погода}</small></div>
    <div class="кошель">${кошель} <small>гр.</small></div>`;
  document.body.appendChild(el);
}

const тень = (hex, k) => {
  const n = parseInt(hex.slice(1), 16);
  const f = v => Math.max(0, Math.min(255, Math.round(v * k)));
  return `rgb(${f(n >> 16)},${f((n >> 8) & 255)},${f(n & 255)})`;
};

// Сетка 16×28. Возвращает canvas в родном размере; масштаб задаётся стилем (image-rendering: pixelated).
export function человек(o = {}) {
  const W = 16, H = 28, g = Array.from({ length: H }, () => Array(W).fill(null));
  const p = (x, y, c) => { if (x >= 0 && x < W && y >= 0 && y < H && c) g[y][x] = c; };
  const r = (x, y, w, h, c) => { for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) p(x + i, y + j, c); };
  const кожа = o.кожа ?? '#c99872', волосы = o.волосы ?? '#3a2a1e', верх = o.верх ?? '#5b6468', низ = o.низ ?? '#3d3a36', обувь = o.обувь ?? '#241c17';
  // ноги или подол
  if (o.платье) {
    r(4, 16, 8, 3, o.платье); r(3, 19, 10, 6, o.платье); r(5, 25, 2, 1, обувь); r(9, 25, 2, 1, обувь);
  } else {
    r(5, 16, 6, 4, низ); r(5, 20, 2, 4, низ); r(9, 20, 2, 4, низ);
    r(4, 24, 3, 2, обувь); r(9, 24, 3, 2, обувь);
  }
  // тело и руки
  r(4, 9, 8, 7, верх); r(3, 10, 1, 5, верх); r(12, 10, 1, 5, верх);
  p(3, 15, кожа); p(12, 15, кожа);
  if (o.широкий) { r(2, 10, 1, 5, верх); r(13, 10, 1, 5, верх); p(2, 15, кожа); p(13, 15, кожа); p(3, 15, верх); p(12, 15, верх); r(3, 9, 10, 1, верх); }
  r(4, 15, 8, 1, o.пояс ?? '#2a1f18');
  if (o.жилет) { r(4, 9, 2, 6, o.жилет); r(10, 9, 2, 6, o.жилет); }
  if (o.фартук) { r(6, 11, 4, o.платье ? 11 : 8, o.фартук); }
  if (o.плащ) { r(3, 9, 2, 13, o.плащ); r(11, 9, 2, 13, o.плащ); r(4, 9, 8, 1, o.плащ); }
  // шея и голова
  r(7, 8, 2, 1, тень(кожа, .82)); r(5, 2, 6, 6, кожа);
  r(5, 1, 6, 2, волосы); p(5, 3, волосы); p(10, 3, волосы); p(4, 2, волосы); p(11, 2, волосы);
  if (o.длинные) { r(4, 2, 1, 8, волосы); r(11, 2, 1, 8, волосы); p(5, 8, волосы); p(10, 8, волосы); }
  if (o.лысый) { r(5, 1, 6, 2, кожа); p(5, 3, кожа); p(10, 3, кожа); p(4, 2, null); p(11, 2, null); g[2][4] = null; g[2][11] = null; }
  p(6, 5, '#1c1410'); p(9, 5, '#1c1410');
  if (o.борода) { r(5, 6, 6, 2, o.борода); p(7, 6, кожа); p(8, 6, кожа); }
  if (o.шляпа) { r(3, 2, 10, 1, o.шляпа); r(5, 0, 6, 2, o.шляпа); }
  if (o.платок) { r(4, 1, 8, 2, o.платок); p(4, 3, o.платок); p(11, 3, o.платок); r(11, 4, 1, 3, o.платок); }
  if (o.капюшон) { r(4, 0, 8, 2, o.капюшон); r(4, 2, 1, 7, o.капюшон); r(11, 2, 1, 7, o.капюшон); }
  if (o.мешок) { r(9, 3, 6, 6, o.мешок); r(10, 2, 4, 1, o.мешок); p(12, 12, верх); r(12, 8, 1, 3, кожа); }
  if (o.ведро) { r(13, 16, 3, 3, o.ведро); p(13, 15, '#2a1f18'); p(15, 15, '#2a1f18'); }
  if (o.кружка) { r(1, 13, 2, 2, o.кружка); }
  const c = document.createElement('canvas'); c.width = W + 2; c.height = H + 2;
  const x = c.getContext('2d');
  // контур
  x.fillStyle = 'rgba(12,9,8,.92)';
  for (let j = 0; j < H; j++) for (let i = 0; i < W; i++) if (g[j][i]) { x.fillRect(i, j + 1, 3, 1); x.fillRect(i + 1, j, 1, 3); }
  for (let j = 0; j < H; j++) for (let i = 0; i < W; i++) if (g[j][i]) {
    const край = i >= 9 || !g[j][i + 1];
    x.fillStyle = край && i >= 8 ? тень(g[j][i].startsWith('#') ? g[j][i] : '#888888', .8) : g[j][i];
    x.fillRect(i + 1, j + 1, 1, 1);
  }
  c.className = 'пикс';
  return c;
}

// Поставить человечка на страницу: x — центр, y — подошвы (экранные пиксели).
export function поставить(родитель, o, x, y, масштаб = 4, зеркало = false) {
  const c = человек(o);
  c.style.cssText = `position:absolute;left:${x - c.width * масштаб / 2}px;top:${y - c.height * масштаб + масштаб}px;width:${c.width * масштаб}px;height:${c.height * масштаб}px;${зеркало ? 'transform:scaleX(-1);' : ''}z-index:10;filter:drop-shadow(0 ${масштаб}px 0 rgba(0,0,0,.35))`;
  родитель.appendChild(c);
  return c;
}

