// Мини-игра «Мотив» (шаг 12): песня Норы в портовой таверне. Без DOM; данные — Данные/мотив.js.
// Игра места: начинает её действие таверны (эффект `игра: { вид: 'мотив' }`), ходы и вид отдаёт Движок/игры-места.js.
// Три круга, каждый — одно касание: ответ на зов (ноты строкой знаков и словами), что сделать в зале, ответ на припев.
// Звук не нужен и таймера нет. Расположение Норы (от 1) даёт раз за песню её кивок: один неверный ответ отпадает.
// Состояние — S.сцена.игра: { вид: 'мотив', песня, круг, ответы[], кивок: { взят, круг, убран }, реплика }.
// Учёт — S.мир.мини.мотив.решены: спетая песня (как бы ни вышло) не возвращается; за вечер — одна песня.
import { ПЕСНИ, НОТЫ, ПРАВИЛО_МОТИВА, ИСХОДЫ_МОТИВА, КИВОК } from '../Данные/мотив.js';
import { вход } from './стенд-вход.js';

export const КРУГОВ = 3;
export const песня = id => ПЕСНИ.find(п => п.id === id) ?? null;
export const учётМотива = S => ((S.мир.мини ??= {}).мотив ??= { решены: [] });
export const следующаяПесня = S => ПЕСНИ.find(п => !учётМотива(S).решены.includes(п.id)) ?? null;
export const исходМотива = верно => Object.entries(ИСХОДЫ_МОТИВА).find(([, и]) => верно >= и.от)[0];
const распол = (S, кто) => S.мир.люди?.[кто]?.распол ?? 0;

// Ноты строкой: «▁ ▄ █ — низко, средне, высоко».
export const строкаНот = н => н.map(x => НОТЫ[x].знак).join(' ') + ' — ' + н.map(x => НОТЫ[x].слово).join(', ');
const текстВарианта = в => в.текст ?? строкаНот(в.ноты);

// Можно ли сегодня начать: песни ещё есть, этим вечером ещё не пели (ни здесь, ни в разговоре с Норой).
export function можноПеть(S, день) {
  const м = S.мир.места?.таверна;
  return !!следующаяПесня(S) && м?.дниДействий?.мотив !== день && !(S.сцена?.флагиВечера ?? []).includes('нора_спела');
}

export function начатьМотив(S) {
  const п = следующаяПесня(S);
  if (!п) return false;
  S.сцена.игра = { вид: 'мотив', песня: п.id, круг: 0, ответы: [], кивок: { взят: false, круг: null, убран: null }, реплика: п.начало };
  return true;
}

// Ходы: варианты круга и кивок. ctx — тот же, что у костей; закрыть(S, ctx, реплика, эффект) — из игры-места.js.
export function ходыМотива(S, и, ctx, закрыть) {
  const п = песня(и.песня);
  if (!п) return [{ id: 'игра:мотив:дальше', вид: 'вариант', текст: 'Дослушать', подпись: '', можно: true, почему: null, ход: S2 => { S2.сцена.игра = null; } }];
  const к = п.круги[и.круг], ходы = [];
  const убран = и.кивок.круг === и.круг ? и.кивок.убран : null;
  for (const в of к.варианты) ходы.push({
    id: 'игра:мотив:ответ:' + в.id, вид: 'вариант', текст: текстВарианта(в), подпись: и.круг + 1 < КРУГОВ ? '' : 'итог — 1 ход',
    можно: в.id !== убран, почему: в.id === убран ? 'Нора качнула головой' : null,
    ход: S2 => ответить(S2, в.id, ctx, закрыть),
  });
  if (!и.кивок.взят && распол(S, 'nora') >= КИВОК.от) ходы.push({
    id: 'игра:мотив:кивок', вид: 'вариант', текст: КИВОК.текст, подпись: КИВОК.подпись, можно: true, почему: null,
    ход: S2 => {
      const x = S2.сцена.игра;
      if (x.кивок.взят) return;
      x.кивок = { взят: true, круг: x.круг, убран: к.варианты.find(в => в.id !== к.верный).id };
      x.реплика = (x.реплика ? x.реплика + '\n\n' : '') + КИВОК.реплика;
    },
  });
  return ходы;
}

function ответить(S, id, ctx, закрыть) {
  const и = S.сцена.игра, п = песня(и.песня), к = п.круги[и.круг];
  if (и.кивок.круг === и.круг && и.кивок.убран === id) return;
  const верно = id === к.верный;
  и.ответы.push(верно);
  const сказано = верно ? к.удача : к.промах;
  и.круг += 1;
  if (и.круг < КРУГОВ) { и.реплика = сказано; return; }
  // Итог песни: один раз — партия закрывается, песня записана спетой.
  const исход = исходМотива(и.ответы.filter(Boolean).length), о = ИСХОДЫ_МОТИВА[исход];
  const у = учётМотива(S);
  if (!у.решены.includes(п.id)) у.решены.push(п.id);
  const сч = (S.мир.счётчики ??= {}), ключ = 'мини_мотив_' + исход;
  сч[ключ] = (сч[ключ] ?? 0) + 1;
  S.мир.журналДня.push(о.журнал);
  const круги = 'Круги: ' + п.круги.map((x, i) => `${x.этап.toLowerCase()} — ${и.ответы[i] ? 'вместе ✓' : 'мимо ✗'}`).join(', ') + '.';
  let текст = `${сказано}\n\n${п[исход]}`;
  // После «спели» в тишине слышно столы: тема из слухов таверны (то же, что «Сидеть и слушать»).
  if (о.слушать) { ctx.применить(S, { слушать: true }); if (S.сцена.реплика) текст += '\n\nВ тишине после песни слышно соседний стол. ' + S.сцена.реплика; }
  закрыть(S, ctx, `${текст}\n\n${круги}`, { разВДень: 'мотив', флаг: 'нора_спела', ...(о.распол ? { распол: { nora: о.распол } } : {}) });
  S.сцена.итогМотива = { исход, заголовок: о.заголовок };
}

// Вид партии: для карточки игры и для стенда. Пока карточки «Мотива» на экране места нет, тот же текст
// кладётся в реплику сцены (текстМотива), а ходы идут обычными вариантами с номерами.
export function видМотива(S) {
  const и = S.сцена?.игра;
  if (и?.вид !== 'мотив') return null;
  const п = песня(и.песня);
  if (!п) return null;
  const к = п.круги[и.круг];
  return {
    вид: 'мотив', заголовок: 'Мотив · песня Норы', реплика: и.реплика,
    круг: и.круг + 1, из: КРУГОВ, этап: к.этап,
    зов: к.зов ? { ноты: к.зов, строка: строкаНот(к.зов) } : null,
    зал: к.реплика ?? null,
    ответы: п.круги.map((x, i) => ({ этап: x.этап, вместе: i < и.ответы.length ? и.ответы[i] : null })),
    кивок: и.кивок.круг === и.круг ? и.кивок.убран : null,
    правило: ПРАВИЛО_МОТИВА,
  };
}

export function текстМотива(S) {
  const в = видМотива(S);
  if (!в) return '';
  const было = в.ответы.filter(x => x.вместе !== null).map(x => `${x.этап}: ${x.вместе ? 'вместе ✓' : 'мимо ✗'}`).join(' · ');
  return [в.реплика, `Круг ${в.круг} из ${в.из} · ${в.этап}` + (было ? ` (${было})` : ''),
    в.зов ? `Нора поёт: ${в.зов.строка}\nКак ответить?` : `${в.зал}\nЧто сделать?`, в.зов ? в.правило : null].filter(Boolean).join('\n\n');
}

// Стенд: вечер в доках, вход в таверну, первая неспетая песня. Расположение Норы 1 — чтобы был виден кивок.
export const стенд = {
  id: 'мотив', имя: 'Мотив', где: 'Портовая таверна, вечер: «Остаться на песню Норы»',
  описание: 'Песня в три круга: ответить на зов Норы, помочь залу притихнуть, ответить на припев. Ноты — строкой знаков и словами, звук не нужен.',
  начать(S) {
    if (S.сцена) S.сцена = null;
    Object.assign(S.мир, { день: Math.max(S.мир.день, 2), отрезок: 'вечер', район: 'доки', конецДня: null, смена: null });
    ((S.мир.люди ??= {}).nora ??= { спрошено: [], исчерпано: [] }).распол = Math.max(1, распол(S, 'nora'));
    вход.войти(S, 'таверна');
    if (!S.сцена) return false;
    S.история = [];
    return вход.начатьИгру(S, { вид: 'мотив' });
  },
};
