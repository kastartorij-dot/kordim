// Ночь в ночлежке «по ходам» (карточка 5.5): куда лёг кошелёк, какие случаи выпали, что запомнил хозяин.
// Состояние ночи живёт в S.сцена.ночь и пропадает вместе со сценой. Без DOM; имена, тексты и числа — в данные/ночлежка.js.
import { ПРЯТКИ, ВОСК, СЛУЧАЕВ, ТЁПЛАЯ_КОЙКА, КНИГА_КРОВАТЕЙ, ХРАНЕНИЙ_ДО_ДОНОСА, ПОСТОЯЛЬЦЫ, КОЛОДА, СЛОВА } from '../Данные/ночлежка.js';
import { ЖИЛЬЁ } from '../Данные/жильё.js';
import { бросок } from './случай.js';
import { кражаСлучилась, украсть } from './кража.js';
import { датьТему } from './знание.js';
import { добавитьОчки } from './положение.js';
import { МАКС } from './тело.js';

const запись = S => (S.мир.места.ночлежка ??= { дом: 0, долг: 0, флаги: [], осмотрено: [], визитов: 0 });
const счётчики = S => (запись(S).счётчики ??= {});
const ночлежка = ЖИЛЬЁ.find(ж => ж.id === 'ночлежка');

export const картаСейчас = S => {
  const н = S.сцена?.ночь;
  const id = н?.карты[н.i];
  return id ? КОЛОДА.find(к => к.id === id) ?? null : null;
};
export const ночьИдёт = S => !!S.сцена?.ночь;
export const ночьОкончена = S => ночьИдёт(S) && !картаСейчас(S);

// Для кнопок: сколько будет стоить кража в этой ночи в долях (для подписи «риск 1/10»).
export const подписьРиска = (где, воск) => {
  const р = ПРЯТКИ[где].риск;
  if (!р) return 'риска нет';
  return воск ? `риск ${р[0] * ВОСК.кража}/${р[1]}` : `риск ${р[0]}/${р[1]}`;
};

function выбрать(S, список, сколько) {
  const из = [...список], вышло = [];
  while (вышло.length < сколько && из.length) вышло.push(из.splice(Math.floor(бросок(S) * из.length), 1)[0]);
  return вышло;
}

const лицоДляКарты = (н, к) => (к.лица ? н.постояльцы.find(id => к.лица.includes(id)) ?? null : undefined);

// Текст текущей карты. Лицо карты (кто бормочет, кто ушёл) выбирается тут и запоминается для выбора игрока.
export function описатьКарту(S) {
  const н = S.сцена.ночь, к = картаСейчас(S);
  if (!к) return СЛОВА.утро;
  н.лицо = лицоДляКарты(н, к) ?? null;
  const т = typeof к.текст === 'function' ? к.текст(S, н) : к.текст;
  return т.replace('{лицо}', н.лицо ? ПОСТОЯЛЬЦЫ[н.лицо].имя : 'кто-то');
}

// Ложимся: платит действие (стоит), здесь — всё остальное: тёплая койка, постояльцы, кража, колода.
export function начатьНочь(S, { где, воск = false, одеяло = false }) {
  const п = ПРЯТКИ[где], м = запись(S), ч = счётчики(S);
  const н = S.сцена.ночь = { где, воск, одеяло, чуткий: п.чуткий && !воск, вор: false, постояльцы: [], карты: [], i: 0, лицо: null };
  const строки = [СЛОВА.койка];
  if (где === 'хозяин') {
    ч.хранений = (ч.хранений ?? 0) + 1;
    (м.память ??= {}).знаетСумму = S.герой.кошель;
    строки.push(СЛОВА.хозяин);
    S.мир.журналДня.push('Тон Брикс знает, сколько у тебя при себе. Братство тоже');
  }
  if (воск) строки.push(СЛОВА.воск);
  if (бросок(S) < ТЁПЛАЯ_КОЙКА.шанс) {
    S.герой.тело.тепло = Math.min(МАКС, S.герой.тело.тепло + 1);
    строки.push(СЛОВА.тёплая);
    if (бросок(S) < ТЁПЛАЯ_КОЙКА.мелочь) { S.герой.кошель += ТЁПЛАЯ_КОЙКА.гроши; строки.push(СЛОВА.мелочь); }
  }
  const пул = Object.entries(ПОСТОЯЛЬЦЫ).filter(([, ч2]) => !ч2.только || (ч2.только === 'дождь' && S.мир.погода === 'дождь')).map(([id]) => id);
  н.постояльцы = выбрать(S, пул, 3);
  if (п.риск) н.вор = кражаСлучилась(S, п.риск, воск ? ВОСК.кража : 1);
  if (!воск) {
    const r = бросок(S);
    let сколько = СЛУЧАЕВ.find(([порог]) => r < порог)[1];
    if (н.чуткий) сколько = Math.max(1, сколько);
    const годные = КОЛОДА.filter(к => !к.служебная && (!к.нужен || к.нужен(н, S)) && (!к.лица || лицоДляКарты(н, к)));
    н.карты = выбрать(S, годные, сколько).map(к => к.id);
    if (н.вор) н.карты.unshift('шаги');
  }
  S.сцена.комната = 'койка';
  S.сцена.реплика = строки.join(' ') + '\n\n' + описатьКарту(S);
}

// Следующая карта после выбора игрока. К уже стоящей реплике (ответу на выбор) дописывается новая карта.
export function следующаяКарта(S) {
  const н = S.сцена.ночь;
  н.i += 1;
  S.сцена.реплика = (S.сцена.реплика ? S.сцена.реплика + '\n\n' : '') + описатьКарту(S);
}

// Вор у койки: чуткий хватает наверняка, остальные — с шансом в половину.
export function перехватитьВора(S, { удача, провал }) {
  const н = S.сцена.ночь;
  if (!н.вор) return;
  if (н.чуткий || бросок(S) < 0.5) {
    н.вор = false;
    S.сцена.реплика = удача;
    S.мир.журналДня.push('Поймал вора за руку: кошелёк цел');
  } else {
    S.сцена.реплика = провал;
  }
}

// Постоялец, которого услышал (бормотание, сосед): его строка-тема приходит как «слышал».
export function услышатьЛицо(S) {
  const н = S.сцена.ночь, ч = н.лицо && ПОСТОЯЛЬЦЫ[н.лицо];
  if (!ч) return;
  датьТему(S, ч.тема, 'слышал', S.сцена.место);
  S.мир.журналДня.push(`Ночью услышал: ${ч.имя}`);
}

export function запомнитьСумму(S) {
  (запись(S).память ??= {}).знаетСумму = S.герой.кошель;
  S.мир.журналДня.push('Тон Брикс спросил, что у тебя при себе, и запомнил ответ');
}

export function забытьКрошки(S) {
  const п = запись(S).память;
  if (п) delete п.крошки;
}

// Счёт ночей в книге кроватей: общий для ночи в сцене и для сна на карте (движок/действия.js).
// Пять ночей — Братство +1 («свой»); запах ночлежки остаётся на одежде сам (движок/тело.js).
export function записатьНочь(S) {
  const ч = счётчики(S);
  ч.ночей = (ч.ночей ?? 0) + 1;
  const выдано = (S.мир.выдано ??= {});
  if (ч.ночей >= КНИГА_КРОВАТЕЙ.ночей && !выдано.тон_свой) {
    выдано.тон_свой = true;
    добавитьОчки(S, 'братство', 1, 'нить');
    S.мир.журналДня.push('Тон вписал тебя в книгу кроватей как своего: Братство +1. Одежда пахнет ночлежкой');
  }
}

// Утро: если вора не остановили — кража; затем счёт ночей, донос Тона. Возвращает вариант сна для лечьСпать.
export function итогНочи(S) {
  const н = S.сцена.ночь, ч = счётчики(S);
  if (н.вор) {
    const строка = украсть(S, ночлежка.имя);
    if (строка) ч.украдено = (ч.украдено ?? 0) + 1;
  }
  записатьНочь(S);
  if ((ч.хранений ?? 0) >= ХРАНЕНИЙ_ДО_ДОНОСА && !S.мир.темы.includes('ton_gormu')) {
    датьТему(S, 'ton_gormu', undefined, S.сцена.место);
    S.мир.журналДня.push('Заметил: Тон каждое утро отправляет мальчишку к Горму с одним числом');
  }
  const имя = н.одеяло ? `${ночлежка.имя}, с одеялом` : н.воск ? `${ночлежка.имя}, воск в ушах` : ночлежка.имя;
  return { ...ночлежка, имя, отдых: ночлежка.отдых + (н.воск ? ВОСК.отдых : 0), одеяло: н.одеяло };
}
