// Заём меняльной (концепт «Девять мест», §5.3 «Долг — это таймер»): взять, продлить, просрочка. Без DOM.
// Долг лежит в записи места (S.мир.места.меняльная.долг), поэтому его уже видят журнал и действие «отдать долг»;
// срок — обязательство (движок/сроки.js), его видно в журнале. Числа — игровые параметры для баланса.
import { взятьОбязательство } from './сроки.js';
import { добавитьОчки } from './положение.js';
import { деньСцены } from './торг.js';

export const ЗАЁМ = { процент: 0.1, продление: 0.1, просрочка: 0.25, дней: 7, id: 'заём-меняльной', название: 'Заём меняльной' };

const запись = S => S.мир.места.меняльная;
const срок = день => ({ день, отрезок: 'вечер', граница: 'конец' });

// Взять заём: на руки сумма, в долг сумма + 10%. Один заём за раз.
export function взятьЗаём(S, сумма) {
  const м = запись(S);
  if (!m_свободен(м)) return false;
  const долг = Math.ceil(сумма * (1 + ЗАЁМ.процент));
  const до = деньСцены(S) + ЗАЁМ.дней;
  // прежний, закрытый заём оставил запись об обязательстве: освобождаем id для нового
  if (S.мир.обязательства?.[ЗАЁМ.id]) delete S.мир.обязательства[ЗАЁМ.id];
  if (!взятьОбязательство(S, { id: ЗАЁМ.id, название: ЗАЁМ.название, срок: срок(до) })) return false;
  S.герой.кошель += сумма;
  м.долг += долг;
  м.заём = { сумма, продлён: false, штраф: false };
  S.мир.журналДня.push(`Заём: +${сумма} гр., в долг ${долг} гр., срок до дня ${до}`);
  return true;
}
const m_свободен = м => !м.долг;

// Продлить на неделю: ещё +10% от суммы займа, один раз. Просроченный заём не продлевают.
export function продлитьЗаём(S) {
  const м = запись(S), о = S.мир.обязательства?.[ЗАЁМ.id];
  if (!м.заём || м.заём.продлён || !м.долг || о?.статус !== 'активно') return false;
  const добавка = Math.ceil(м.заём.сумма * ЗАЁМ.продление);
  м.долг += добавка;
  о.срок.день += ЗАЁМ.дней;
  м.заём.продлён = true;
  S.мир.журналДня.push(`Заём продлён: долг +${добавка} гр., срок до дня ${о.срок.день}`);
  return true;
}

// Просрочка применяется один раз при следующем визите: свеча гаснет, картель −1, долг +25%.
export function проверитьЗаём(S) {
  const м = запись(S), о = S.мир.обязательства?.[ЗАЁМ.id];
  if (!м.заём || м.заём.штраф || !м.долг || о?.статус !== 'истекло') return false;
  м.заём.штраф = true;
  const было = м.долг;
  м.долг = Math.ceil(м.долг * (1 + ЗАЁМ.просрочка));
  добавитьОчки(S, 'картель', -1, 'нить');
  S.мир.журналДня.push(`Заём просрочен: долг ${было} → ${м.долг} гр., картель недоволен`);
  return true;
}

// Состояние займа для действий данных: 'нет' | 'активен' | 'просрочен'.
export function состояниеЗайма(S) {
  const м = запись(S);
  if (!м?.долг) return 'нет';
  return S.мир.обязательства?.[ЗАЁМ.id]?.статус === 'истекло' ? 'просрочен' : 'активен';
}
export const можноПродлить = S => { const м = запись(S); return !!м?.заём && !м.заём.продлён && состояниеЗайма(S) === 'активен'; };
export const ценаПродления = S => Math.ceil((запись(S)?.заём?.сумма ?? 0) * ЗАЁМ.продление);
