// Шов мини-игр (шаг 12): правила, исход и награда игры не знают, как в неё играли. Способ игры — слой, который
// отдаёт итог одним из трёх уровней (или долей 0–1). Сейчас слой один — «спокойный»: пошаговый выбор без ловкости
// и таймера. Живой слой (ритм, ведение линии, тайминг) подключится к тем же функциям завершения:
// «Игла» — завершитьИглу (Движок/игла.js), «Мотив» — завершитьМотив (Движок/мотив.js),
// «Чтение комнаты» — завершитьЧтение (Движок/чтение.js). Без DOM.
export const УРОВНИ = ['плохо', 'нормально', 'отлично'];

// Доля 0–1 от живого слоя → уровень. Пороги общие для всех игр.
export const уровеньИзДоли = x => (x >= 0.85 ? 'отлично' : x >= 0.5 ? 'нормально' : 'плохо');

// Спокойный режим: сколько шагов из скольких сделано верно → уровень (3 из 3 — отлично, 2 из 3 — нормально).
export const уровеньИзСчёта = (верно, из) => уровеньИзДоли(из ? верно / из : 0);
