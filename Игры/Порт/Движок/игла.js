// Мини-игра «Игла» (шаг 12): заказ на наколку в смене «Бить наколки по заказам». Без DOM; данные — Данные/игла.js.
// Встаёт в смену так же, как «Вес» и «Счёт» (Движок/мини-игры.js выдаёт её и передаёт сюда ходы, вид и итог),
// и рисуется той же карточкой задачи (рендерСмены): этап за этапом выбор одним касанием и «Так и сделаю».
// Таймера и ловкости нет. Ремесло помогает один раз на заказ — на том этапе, где игрок попросит совета:
// «умеешь» — подсказка о способе, «набил руку» и выше — один неверный ход отпадает.
// Состояние — S.мир.смена.задача: { игра: 'игла', задание, шаг, ответы[], выбор, совет: { вид, взят, убран, шаг }, стадия, исход }.
// стадия 'идёт' → 'ответ' после третьего этапа; исход 'чисто' | 'годно' | 'огрех'. Отказаться посреди работы нельзя:
// любой ход ведёт к концу заказа, а смена платит как обычно.
import { ИГЛА, ИСХОДЫ_ИГЛЫ } from '../Данные/игла.js';
import { работа } from '../Данные/работы.js';
import { вход } from './стенд-вход.js';
import { уровеньИзСчёта } from './уровень.js';

export const ЭТАПОВ = 3;
export const заказ = id => ИГЛА.find(з => з.id === id) ?? null;

// Сколько этапов верно → исход.
export const исходИглы = верно => Object.entries(ИСХОДЫ_ИГЛЫ).find(([, и]) => верно >= и.от)[0];
// Шов (Движок/уровень.js): уровень любого слоя игры → исход заказа.
export const ИСХОД_ПО_УРОВНЮ = { отлично: 'чисто', нормально: 'годно', плохо: 'огрех' };
// Завершить заказ уровнем (живой слой или спокойный режим). true — задача кончилась, смену пора закрыть.
export function завершитьИглу(S, уровень) {
  const x = S.мир.смена?.задача;
  if (!x || x.стадия !== 'идёт') return false;
  x.стадия = 'ответ';
  x.исход = ИСХОД_ПО_УРОВНЮ[уровень];
  return true;
}

export function ходыИглы(S) {
  const т = S.мир.смена.задача, з = заказ(т.задание);
  if (!з || т.стадия !== 'идёт') return [];
  const ш = з.шаги[т.шаг], Х = [];
  const убран = т.совет.шаг === т.шаг ? т.совет.убран : null;
  const ход = (id, текст, можно, f) => Х.push({ id: 'смена:задача:' + id, текст, можно, ход: f });
  ход('записать', т.шаг + 1 < ЭТАПОВ ? 'Так и сделаю' : 'Так и закончу', !!т.выбор, S2 => {
    const x = S2.мир.смена.задача;
    if (!x.выбор || x.стадия !== 'идёт') return false;
    x.ответы.push(x.выбор === з.шаги[x.шаг].верный);
    x.выбор = null;
    x.шаг += 1;
    if (x.шаг < ЭТАПОВ) return false;
    return завершитьИглу(S2, уровеньИзСчёта(x.ответы.filter(Boolean).length, ЭТАПОВ));
  });
  for (const в of ш.варианты) ход('вариант:' + в.id, в.текст, в.id !== убран, S2 => {
    const x = S2.мир.смена.задача;
    if (!(x.совет.шаг === x.шаг && x.совет.убран === в.id)) x.выбор = в.id;
    return false;
  });
  if (т.совет.вид && !т.совет.взят) ход('совет', 'Совет ремесла', true, S2 => {
    const x = S2.мир.смена.задача, с = x.совет;
    if (с.взят) return false;
    с.взят = true; с.шаг = x.шаг;
    if (с.вид === 'отсев') {
      с.убран = з.шаги[x.шаг].варианты.find(в => в.id !== з.шаги[x.шаг].верный).id;
      if (x.выбор === с.убран) x.выбор = null;
    }
    return false;
  });
  return Х;
}

// Что вышло на этапе n (после ответа на него).
const реакция = (з, т, n) => (т.ответы[n] ? з.шаги[n].ход : з.шаги[n].промах);
const строкаЭтапов = (з, т) => 'Этапы: ' + з.шаги.map((ш, i) => `${ш.этап.toLowerCase()} — ${т.ответы[i] ? 'верно ✓' : 'мимо ✗'}`).join(', ') + '.';

// Вид для карточки задачи смены — те же поля, что у «Веса» (Движок/мини-игры.js → видЗадачи).
export function видИглы(S) {
  const т = S.мир.смена.задача, з = заказ(т.задание);
  if (!з) return null;
  const кончено = т.стадия === 'ответ';
  const n = Math.min(т.шаг, ЭТАПОВ - 1), ш = з.шаги[n];
  const советЗдесь = т.совет.взят && т.совет.шаг === n && !кончено;
  return {
    игра: 'Игла',
    подводка: т.шаг === 0 ? з.подводка : реакция(з, т, т.шаг - 1),
    заголовокФактов: `Этап ${n + 1} из ${ЭТАПОВ} · ${ш.этап}`,
    отметкиМожно: false,
    факты: ш.факты.map(текст => ({ текст, отмечен: false })),
    вопрос: ш.вопрос, стадия: т.стадия, исход: т.исход,
    варианты: кончено ? [] : ш.варианты.map(в => ({ id: в.id, текст: в.текст, выбран: в.id === т.выбор, отпал: т.совет.шаг === n && в.id === т.совет.убран, верный: false })),
    совет: советЗдесь && т.совет.вид === 'слово' ? ш.совет : null,
    отсев: советЗдесь && т.совет.вид === 'отсев',
    заголовокИтога: т.исход ? ИСХОДЫ_ИГЛЫ[т.исход].заголовок : null,
    решение: null,
    // Для стенда и тестов: пройденные этапы словами.
    этапы: з.шаги.map((x, i) => ({ этап: x.этап, верно: i < т.ответы.length ? т.ответы[i] : null })),
  };
}

// Итог: один раз, из закрытьЗадачу (Движок/мини-игры.js), когда «применено» уже отмечено.
// Плата за «чисто» — «задача.удача» работы; «годно» и «огрех» — только написанный исход, смена платит как обычно.
export function закрытьИглу(S, т, з, р, у, применитьЭффект, ctx) {
  const строки = [];
  if (!у.решены.includes(з.id)) у.решены.push(з.id);
  у.отказ = null;
  const к = `мини_игла_${т.исход}`;
  (S.мир.счётчики ??= {})[к] = (S.мир.счётчики[к] ?? 0) + 1;
  if (т.исход === 'чисто' && р.задача?.удача) строки.push(...применитьЭффект(S, р.задача.удача, ctx));
  return { текст: `${реакция(з, т, ЭТАПОВ - 1)}\n\n${з[т.исход]}\n\n${строкаЭтапов(з, т)}`, строки, журнал: ИСХОДЫ_ИГЛЫ[т.исход].журнал };
}

// Стенд: вечер в доках, ремесло «умеешь», одна смена уже была — следующая сразу даёт заказ.
