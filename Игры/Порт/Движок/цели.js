// Реестр целей: у каждой — своя сводка, следующий шаг, исход и тексты итога. Новая цель = одна запись.
const ПО_ЦЕЛЯМ = {
  уехать: { сводка:сводкаУехать,шаг:следующийШагУехать,исход:исходУехать,детали:деталиУехать,итоги:ИТОГИ_ОТЪЕЗДА },
  угол: { сводка: сводкаУгла, шаг: следующийШагУгла, исход: исходУгла, детали: деталиУгла, итоги: ИТОГИ_УГЛА },
  имя: { сводка: сводкаИмени, шаг: следующийШагИмени, исход: исходИмени, детали: деталиИмени, итоги: ИТОГИ_ИМЕНИ },
  вытащить: { сводка: сводкаВытащить, шаг: следующийШагВытащить, исход: исходВытащить, детали: деталиВытащить, итоги: ИТОГИ_ВЫТАЩИТЬ },
};

export function цели(S) {
  return (S.мир.цели ??= { выбрана: null, выбранаДень: null, зафиксирована: false });
}

const журнал = (S, с) => { S.мир.журналДня.push(с); return с; };
const сезонЗакрыт = S => !!S.мир.итогСезона || !!S.мир.кампанияЗавершена || S.мир.день > ДЕНЬ_ФИНАЛА;

export const доступныеЦели = S => S.мир.день >= ДЕНЬ_ВЫБОРА && S.мир.день <= ДЕНЬ_ФИНАЛА && !S.мир.итогСезона ? Object.values(ЦЕЛИ).filter(г => г.готова) : [];

export function выбратьЦель(S, id) {
  if(S.сцена||S.мир.конецДня||сезонЗакрыт(S))return false;
  const г = ЦЕЛИ[id];
  if (!г?.готова || !доступныеЦели(S).some(г=>г.id===id) || S.мир.цели?.зафиксирована || S.мир.цели?.выбрана) return false;
  const ц = цели(S);
  ц.выбрана = id; ц.выбранаДень = S.мир.день;
  // В итог дня выбор попадает при закрытии суток (записатьВыборДня): пробы «выбрал — снял» туда не пишутся.
  return true;
}

// До точки обязательства цель можно сменить; принятые договоры и долги от этого не исчезают.
export function снятьЦель(S) {
  if(S.сцена||S.мир.конецДня||сезонЗакрыт(S))return false;
  const ц = цели(S);
  if (!ц.выбрана || ц.зафиксирована) return false;
  (ц.снятые ??= []).push({ id: ц.выбрана, день: S.мир.день, сДня: ц.выбранаДень });
  ц.выбрана = null; ц.выбранаДень = null;
  return true;
}

export function зафиксироватьЦель(S, id) {
  if (!ЦЕЛИ[id]?.готова || сезонЗакрыт(S)) return false;
  const ц = цели(S);
  if (ц.зафиксирована && ц.выбрана !== id) return false;
  if (ц.выбрана && ц.выбрана !== id) журнал(S, `Цель сменилась на «${ЦЕЛИ[id].имя}»: это точка обязательства. Прежние обещания остаются.`);
  ц.выбрана = id; ц.выбранаДень ??= S.мир.день; ц.зафиксирована = true;
  return true;
}

// Единая точка для сцен: действие «вытащить» из данных места. Деньги не списываются: цель бесплатна, кроме времени.
export function применитьВытащить(S, вид) {
  const ок = применитьДействиеВытащить(S, вид);
  if (ок && вид === 'обещать') зафиксироватьЦель(S, 'вытащить');
  return ок;
}

// Единая точка для сцен: действие «имяЦели» из данных места. Деньги списаны вызывающим.
export function применитьИмя(S, вид) {
  const ок = применитьДействиеИмени(S, вид);
  if (ок && /^договор-(независимость|картель|ножи|братство)$/.test(вид)) зафиксироватьЦель(S, 'имя');
  return ок;
}

// Единая точка для сцен: действие «угол» из данных места. Деньги списаны вызывающим.
export function применитьУгол(S, вид) {
  const ок = выполнитьДействиеУгла(S, вид);
  if (ок && вид === 'подписать') зафиксироватьЦель(S, 'угол');
  return ок;
}

// Для экранов без сцены места и для проверок: списывает цену и применяет последствия один раз.
export function выполнитьУгол(S, вид) {
  const цена = стоимостьУгла(S, вид);
  if (S.герой.кошель < цена) return false;
  const было = S.герой.кошель;
  S.герой.кошель -= цена;
  if (!применитьУгол(S, вид)) { S.герой.кошель = было; return false; }
  return true;
}

const читатьЦели = S => S.мир.цели ?? {выбрана:null,выбранаДень:null,зафиксирована:false};
export function действияЦелей(S) {
  const а = [], ц = читатьЦели(S), свободно = !S.сцена && !S.мир.конецДня;
  const исходнаяЦель = ц.выбрана;
  if (!ц.выбрана) for (const г of доступныеЦели(S)) а.push({
    id: `цель:выбрать:${г.id}`, текст: `Выбрать цель: ${г.имя}`, можно: свободно, почему: 'сейчас нельзя',
    выполнить: S2 => выбратьЦель(S2, г.id),
  });
  if (ц.выбрана && !ц.зафиксирована && !сезонЗакрыт(S)) а.push({
    id: 'цель:снять', текст: 'Снять цель (обязательств ещё нет)', можно: свободно, почему: 'сейчас нельзя',
    выполнить: S2 => S2.мир.цели?.выбрана===исходнаяЦель && !S2.мир.цели?.зафиксирована ? снятьЦель(S2) : false,
  });
  а.push(...действияУгла(S));
  return а;
}

export function сводкаЦели(S) {
  const финал = S.мир.итогСезона;
  if (финал) return {
    выбрана: ЦЕЛИ[финал.цель]?.имя ?? null, завершена: true,
    шаг: `Первый сезон окончен. ${финал.заголовок}. ${финал.текст}`,
    строки: [...(финал.строки ?? [])], предложение: [], зафиксирована: true,
  };
  const ц = читатьЦели(S), день = S.мир.день;
  // Первый шаг каждой цели виден до выбора: игрок сравнивает условия, не выбирая и не снимая (PR004-11).
  const предложение = ц.выбрана ? [] : доступныеЦели(S).map(г => ({ id: г.id, имя: г.имя, кратко: г.кратко, шаг: ПО_ЦЕЛЯМ[г.id]?.шаг(S) ?? '' }));
  if (!ц.выбрана) {
    return {
      выбрана: null,
      шаг: день < ДЕНЬ_ВЫБОРА
        ? 'Первые два дня — просто жить. С третьего дня журнал предложит направление.'
        : 'Выбери направление или живи без цели: итог тридцатого дня будет и тогда.',
      строки: [], предложение, зафиксирована: false,
    };
  }
  const м = ПО_ЦЕЛЯМ[ц.выбрана];
  return { выбрана: ЦЕЛИ[ц.выбрана].имя, шаг: м.шаг(S), строки: м.сводка(S), предложение, зафиксирована: ц.зафиксирована };
}

// ── День 30 ──────────────────────────────────────────────────────────────────
// Разделы итога (цель, люди, отец, как жил) собирает Движок/итог-сезона.js — тот же, что и при раннем отъезде.
export function итогСезона(S) {
  if (S.мир.итогСезона) return S.мир.итогСезона;
  const ц = читатьЦели(S);
  let заголовок = ИТОГ_БЕЗ_ЦЕЛИ.заголовок, текст = ИТОГ_БЕЗ_ЦЕЛИ.текст, исход = 'без-цели', детали = [];
  const м = ПО_ЦЕЛЯМ[ц.выбрана];
  if (м) {
    исход = м.исход(S);
    ({ заголовок, текст } = м.итоги[исход]);
    детали = м.детали(S);
  } else if (ц.снятые?.length) {
    исход = 'отказ-от-цели';
    ({ заголовок, текст } = ИТОГ_ОТКАЗА);
    детали.push('Оставленные направления: '+[...new Set(ц.снятые.map(цель => ЦЕЛИ[цель.id]?.имя).filter(Boolean))].join(', ')+'. Принятые обещания и долги остаются.');
  }
  const разделы = разделыИтога(S, детали);
  return { день: ДЕНЬ_ФИНАЛА, сезон: состояниеСезона(S).номер, деньСезона: ДЕНЬ_ФИНАЛА,
    цель: ц.выбрана, исход, заголовок, текст, разделы, строки: строкиИтога(S, разделы) };
}

// Итог дня видит только то, чем день кончился: цель, выбранная сегодня и не снятая, и снятие цели,
// выбранной в прежние дни. Выбрать и снять в тот же день — проба, её в итоге нет (PR004-11).
function записатьВыборДня(S) {
  const ц = S.мир.цели, день = S.мир.день;
  if (!ц) return;
  const снятые = [...new Set((ц.снятые ?? []).filter(х => х.день === день && х.id !== ц.выбрана && (х.сДня ?? 0) < день).map(х => х.id))];
  for (const id of снятые) журнал(S, `Цель снята: ${ЦЕЛИ[id]?.имя ?? id}. Принятые обещания остаются.`);
  if (ц.выбрана && ц.выбранаДень === день && !(ц.снятые ?? []).some(х => х.id === ц.выбрана && (х.сДня ?? 0) < день && х.день === день))
    журнал(S, `Цель выбрана: ${ЦЕЛИ[ц.выбрана].имя}`);
}

// Вызывается из Движок/время.js при закрытии суток, до смены дня.
export function закрытьДеньЦелей(S, итог) {
  записатьВыборДня(S);
  закрытьДеньУехать(S, итог);
  закрытьДеньУгла(S, итог);
  закрытьДеньИмени(S, итог);
  закрытьДеньВытащить(S, итог);
  if (состояниеСезона(S).день >= ДЕНЬ_ФИНАЛА && !S.мир.итогСезона) {
    S.мир.итогСезона = итогСезона(S);
    if (S.мир.день > ДЕНЬ_ФИНАЛА) {
      S.мир.итогСезона.восстановленНаДне = S.мир.день;
      const пометка = `Итог первого сезона восстановлен из сохранения дня ${S.мир.день}. Он отражает доступные сейчас записи, а не снимок прошлого тридцатого дня.`;
      S.мир.итогСезона.строки.push(пометка);
      S.мир.итогСезона.разделы.жизнь.push(пометка);
    }
    итог.финал = S.мир.итогСезона;
  }
}
