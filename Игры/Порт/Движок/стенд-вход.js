// Ступень ремесла для стенда: 'нет' — ремесла нет, иначе имя ступени (зарубок столько, чтобы ступень не спорила с ними).
const ОТ = { 'умеешь': 0, 'набил руку': 10, 'мастер': 30 };
export function поставитьСтупень(S, ремесло, ступень) {
  if (!ремесло || !ступень) return;
  S.герой.ремёсла ??= {};
  if (ступень === 'нет') { delete S.герой.ремёсла[ремесло]; return; }
  S.герой.ремёсла[ремесло] = { ...(S.герой.ремёсла[ремесло] ?? {}), ступень, зарубки: ОТ[ступень] ?? 0 };
}
// Подпись варианта по заданию игры: «01 · лёгкое — начало подводки».
export const имяЗадания = (номер, сложность, текст) => {
  const к = текст.split(/[:.]/)[0];
  return `${String(номер).padStart(2, '0')} · ${сложность} — ${к.length > 56 ? к.slice(0, 54).trimEnd() + '…' : к}`;
};
