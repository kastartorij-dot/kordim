export function сводкаИмени(S) {
  const и = имя(S), с = [];
  const П = { взял: 'письмо Нотариуса у тебя', доставлено: 'письмо доставлено', возвращено: 'письмо возвращено Оршу', отказ: 'от письма отказался', сорвано: 'письмо не доставлено в срок' };
  if (П[и.письмо]) с.push(`Письмо: ${П[и.письмо]}${и.вскрыто ? ' (печать вскрыта)' : ''}.`);
  if (и.просьба) с.push(`Просьба Горма: ${{ исполнил: 'исполнена', обмен: 'договорились об обмене', отказ: 'отклонена' }[и.просьба]}.`);
  if (и.бесплатное) с.push(`«Бесплатная» услуга: ${{ принял: 'принята, за ней услуга', цена: 'цена названа вслух', отказ: 'отказался' }[и.бесплатное]}.`);
  if (и.договор) с.push(`Публичный договор: ${и.договор.вид === 'независимость' ? 'независимость' : и.договор.вид === 'сторона' ? `знак стороны (${СТОРОНА_СЛОВАМИ[и.договор.сторона]})` : 'слово не дано'}.`);
  for (const д of долги(S)) с.push(`Висит: ${д}.`);
  if (и.договор && и.договор.вид !== 'уход') с.push(`Положение: ${ступени(S)}.`);
  return с;
}

export function следующийШагИмени(S) {
  const и = имя(S), день = S.мир.день, д = и.договор;
  if (д?.вид === 'уход') return 'Слово не дано. Цель можно сменить; принятые обещания остаются.';
  if (д) {
    const хвост = [];
    if (вызовОткрыт(S)) хвост.push(`С дней 26–29 сторона (${СТОРОНА_СЛОВАМИ[сторонаВызова(S)]}) просит последний, видимый городу выбор: часовня.`);
    if (д.вид === 'независимость') {
      if (порогНезависимого(S)) return ['Равновесие достигнуто: две стороны на ступени +2, третья не ниже −1, долгов нет. Держи его до дня 30.', ...хвост].join(' ');
      const нужно = [];
      if (!двеНаДвух(S)) нужно.push('поднять две стороны до «своего» (+2): работой и службой посредника');
      if (!никтоНеНиже(S)) нужно.push('не дать третьей упасть ниже −1');
      if (долги(S).length) нужно.push(`закрыть долги (${долги(S).join('; ')})`);
      const службы = СТОРОНЫ.filter(к => !и.служба[к] && день <= ИМЯ.службаДо);
      if (службы.length) нужно.push(`служба посредника ещё есть у: ${службы.map(к => ПРИСТАВКА[к]).join(', ')} (до дня ${ИМЯ.службаДо})`);
      return [`Договор признан. Нужно: ${нужно.join('; ')}.`, ...хвост].join(' ');
    }
    if (порогСтороны(S)) return ['Ты признан человеком стороны: ступень +2 и служба выполнена. Держи это до дня 30.', ...хвост].join(' ');
    if (д.отступил) return 'Ты отступил и принял цену. Сторона знает, что на тебя нельзя положиться.';
    const н = [];
    if (!и.служба[д.сторона]) н.push(`выполнить службу стороне (${СТОРОНА_СЛОВАМИ[д.сторона]}) до дня ${ИМЯ.службаДо}`);
    if (ступень(S, д.сторона) < 2) н.push('поднять её до «своей» (+2)');
    if (долги(S).length) н.push(`закрыть долги (${долги(S).join('; ')})`);
    return [`Знак принят. Нужно: ${н.join('; ')}.`, ...хвост].join(' ');
  }
  if (условиеИмени(S, 'предложено')) return `Нотариус в приёмной (Торговый квартал, утро или день) предлагает отнести запечатанное письмо Нотариуса Ресту Дорру в контору (доки). Предложение действует до дня ${ИМЯ.письмоДни[1]}.`;
  if (и.письмо === 'взял' || и.письмо === 'сорвано') return `Письмо Нотариуса у тебя. Отнеси его Дорру в контору (доки, утро или день)${и.письмо === 'взял' ? ` до конца дня ${и.письмоСрокДень}` : ' — срок уже вышел'}. Печать можно осмотреть бесплатно; трогать её нельзя без последствий.`;
  if (условиеИмени(S, 'просьба')) return 'У Горма (Трущобы) по нечётным дням есть просьба, которая может спорить с тем, что ты уже сделал.';
  if (условиеИмени(S, 'выгода')) return `Кип в меняльной может предложить «бесплатную» услугу (дни ${ИМЯ.выгодаДни.join('–')}): подумай, чего она стоит на самом деле.`;
  if (договорВозможен(S)) return 'Публичное слово: часовня (район маяка). Там можно потребовать независимость, принять знак стороны или уйти без договора.';
  const нет = [];
  if (и.просьба === null) нет.push('решение по просьбе Горма (Трущобы, нечётный день)');
  if (и.бесплатное === null) нет.push('решение по «бесплатной» услуге Кипа');
  if (сторонОбязательств(S) < 2 && день < ИМЯ.резервДень) нет.push(`заметные обязательства разным сторонам (пока ${сторонОбязательств(S)} из 2; с ${ИМЯ.резервДень}-го дня слово примут и без них)`);
  if (день < ИМЯ.договорС) нет.push(`дождаться дня ${ИМЯ.договорС}`);
  return `Для публичного договора нужно: ${нет.join('; ') || 'ещё немного времени'}.`;
}

// ── День 30 ──────────────────────────────────────────────────────────────────
// Исход: независимый | человек-стороны | на-испытании | сторона-без-места | посредник-с-долгом |
//        скомпрометирован | не-стал-ничьим | без-договора | не-начал
export function исходИмени(S) {
  const и = имя(S), д = и.договор;
  if (д?.вид === 'уход') return 'не-стал-ничьим';
  if (!д) {
    if (и.вскрыто && и.долгВмешательства) return 'скомпрометирован';
    return и.письмо === 'нет' && и.просьба === null && и.бесплатное === null && !и.обязательства.length ? 'не-начал' : 'без-договора';
  }
  if (и.вскрыто && и.долгВмешательства) return 'скомпрометирован';
  if (д.вид === 'независимость') return порогНезависимого(S) ? 'независимый' : долги(S).length ? 'посредник-с-долгом' : 'на-испытании';
  return порогСтороны(S) ? 'человек-стороны' : 'сторона-без-места';
}

export function деталиИмени(S) {
  const и = имя(S), с = [];
  for (const д of долги(S)) с.push(`Висит: ${д}.`);
  if (и.вызов === 'пропущен') с.push('Последняя просьба стороны осталась без ответа.');
  if (и.вызов === 'отступил') с.push('В последний день Одвин отступил от своего знака.');
  if (и.вскрыто) с.push('Печать письма была вскрыта, и об этом знают.');
  if (и.просьба === 'исполнил') с.push('Он исполнил просьбу Горма, и Нотариус слышал от него другое.');
  if (и.договор) с.push(`Положение: ${ступени(S)}.`);
  const стороны = [...new Set(и.обязательства.filter(о => !о.нарушено).map(о => СТОРОНА_СЛОВАМИ[о.сторона]))];
  if (стороны.length) с.push(`Обязательства есть перед: ${стороны.join(', ')}.`);
  return с;
}
