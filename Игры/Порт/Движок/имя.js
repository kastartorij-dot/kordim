const ПИСЬМО = 'письмо-нотариуса';
const новый = () => ({
  письмо: 'нет',            // нет | взял | доставлено | возвращено | отказ | сорвано
  письмоСрокДень: null, путь: null, // путь: запечатанным | с-разрешения | вскрыл
  осмотрел: false, предупредил: false, вскрыто: false, дорзнает: false, знаетСодержание: false,
  просьба: null,            // исполнил | обмен | отказ
  бесплатное: null,         // принял | цена | отказ
  долгВмешательства: false, долгКипу: false,
  обязательства: [],        // { сторона, что, нарушено }
  договор: null,            // { вид: независимость | сторона | уход, сторона?, день }
  служба: {}, вызов: null,  // вызов: выполнил | отказ | отступил | пропущен
});

export function имя(S) {
  const и = (S.мир.имя ??= новый());
  for (const [ключ, значение] of Object.entries(новый())) и[ключ] ??= значение;
  return и;
}

const журнал = (S, с) => { S.мир.журналДня.push(с); return с; };
const цельИмя = S => S.мир.цели?.выбрана === 'имя';
const зажать = (от, до, v) => Math.max(от, Math.min(до, v));
const очки = (S, к) => S.мир.очки?.[к] ?? 0;
const ступень = (S, к) => S.мир.фракции?.[к] ?? 0;
const вОкне = (день, [а, б]) => день >= а && день <= б;
const нить = (S, к, n) => добавитьОчки(S, к, n, 'нить');
function распол(S, кто, n) {
  const л = ((S.мир.люди ??= {})[кто] ??= { спрошено: [], исчерпано: [] });
  л.распол = зажать(-2, 4, (л.распол || 0) + n);
}
function обязан(S, сторона, что) {
  const и = имя(S);
  if (!и.обязательства.some(о => о.сторона === сторона && о.что === что)) и.обязательства.push({ сторона, что, нарушено: false });
}
export const сторонОбязательств = S => new Set(имя(S).обязательства.filter(о => !о.нарушено).map(о => о.сторона)).size;

// Просроченные услуги: всё, что висит и не закрыто.
export function долги(S) {
  const и = имя(S), о = S.мир.обязательства ?? {};
  const л = [];
  if (и.долгВмешательства) л.push('возместить Нотариусу доверие за вскрытую печать');
  if (и.долгКипу) л.push('вернуть услугу Кипа');
  if (и.письмо === 'сорвано') л.push('письмо Нотариуса не доставлено в срок');
  if (о.имя_служба?.статус === 'истекло') л.push('служба стороне не выполнена в срок');
  return л;
}

// Сторона, чья просьба придёт в последний вызов: выбранная или та, что ценит Одвина больше.
export function сторонаВызова(S) {
  const д = имя(S).договор;
  if (д?.вид === 'сторона') return д.сторона;
  return [...СТОРОНЫ].sort((а, б) => очки(S, б) - очки(S, а) || СТОРОНЫ.indexOf(а) - СТОРОНЫ.indexOf(б))[0];
}

const двеНаДвух = S => КЛЮЧИ_ФРАКЦИЙ.filter(к => ступень(S, к) >= 2).length >= 2;
const никтоНеНиже = S => КЛЮЧИ_ФРАКЦИЙ.every(к => ступень(S, к) >= -1);
export function порогНезависимого(S) {
  const и = имя(S);
  return и.договор?.вид === 'независимость' && двеНаДвух(S) && никтоНеНиже(S) && долги(S).length === 0;
}
export function порогСтороны(S) {
  const и = имя(S);
  return и.договор?.вид === 'сторона' && !и.договор.отступил && ступень(S, и.договор.сторона) >= 2
    && !!и.служба[и.договор.сторона] && долги(S).length === 0;
}

// Просьба Горма спорит с услугой той стороне, которой Одвин помог больше (при равенстве — картелю).
export const сторонаКонфликта = S => (очки(S, 'ножи') > очки(S, 'картель') ? 'ножи' : 'картель');

// Договор: просьба Горма и «бесплатная» услуга решены, обязательства перед двумя сторонами есть — или настал резервный день.
const договорВозможен = S => {
  const и = имя(S);
  return цельИмя(S) && (!S.мир.цели?.зафиксирована || S.мир.цели.выбрана==='имя') && !и.договор && S.мир.день >= ИМЯ.договорС && и.просьба !== null && и.бесплатное !== null
    && (сторонОбязательств(S) >= 2 || S.мир.день >= ИМЯ.резервДень);
};
const вызовОткрыт = S => { const и = имя(S); return !!и.договор && и.договор.вид !== 'уход' && и.вызов === null && вОкне(S.мир.день, ИМЯ.вызовДни); };

export function условиеИмени(S, вид) {
  const и = имя(S), день = S.мир.день, есть = естьВещь(S, ПИСЬМО);
  const удерживаю = (и.письмо === 'взял' || и.письмо === 'сорвано') && есть;
  switch (КЛЮЧ_ДЕЙСТВИЯ[вид] ?? вид) {
    case 'предложено': return и.письмо === 'нет' && вОкне(день, [S.герой.начало === 'бумаги' ? 2 : ИМЯ.письмоДни[0], ИМЯ.письмоДни[1]]);
    case 'взять-письмо': return условиеИмени(S, 'предложено') && можноПоложить(S, ПИСЬМО);
    case 'отказ-письмо': return условиеИмени(S, 'предложено');
    case 'осмотр': return удерживаю && !и.осмотрел;
    case 'вскрыть': return удерживаю && !и.вскрыто;
    case 'разрешение': return удерживаю && !и.вскрыто;
    case 'предупредить': return удерживаю && !и.предупредил;
    case 'доставить': return удерживаю;
    case 'вернуть-письмо': return удерживаю;
    case 'возместить': return и.долгВмешательства;
    case 'вернуть-услугу': return и.долгКипу;
    case 'просьба': return цельИмя(S) && и.просьба === null && (['доставлено', 'возвращено', 'отказ', 'сорвано'].includes(и.письмо) || день >= ИМЯ.письмоДни[1] + 1);
    case 'выгода': return цельИмя(S) && и.бесплатное === null && вОкне(день, ИМЯ.выгодаДни);
    case 'договор': return договорВозможен(S);
    case 'служба-картель': case 'служба-ножи': case 'служба-братство': {
      const к = вид.slice(7), д = и.договор;
      if (!д || и.служба[к] || день > ИМЯ.службаДо) return false;
      return д.вид === 'независимость' || (д.вид === 'сторона' && д.сторона === к && !д.отступил);
    }
    case 'вызов-независимый': return вызовОткрыт(S) && и.договор.вид === 'независимость';
    case 'вызов-сторона': return вызовОткрыт(S) && и.договор.вид === 'сторона' && !и.договор.отступил;
    default: return false;
  }
}

const КЛЮЧ_ДЕЙСТВИЯ = {
  'просьба-исполнить': 'просьба', 'просьба-обмен': 'просьба', 'просьба-отказ': 'просьба',
  'выгода-принять': 'выгода', 'выгода-цена': 'выгода', 'выгода-отказ': 'выгода',
  'договор-независимость': 'договор', 'договор-картель': 'договор', 'договор-ножи': 'договор', 'договор-братство': 'договор', 'договор-уход': 'договор',
  'вызов-выполнить': 'вызов-независимый', 'вызов-отказ': 'вызов-независимый',
  'вызов-верность': 'вызов-сторона', 'вызов-отступить': 'вызов-сторона',
};

// Деньги за действие уже списаны сценой; здесь последствия. Возвращает true, если действие применено.
export function применитьДействиеИмени(S, вид) {
  const и = имя(S), день = S.мир.день, к = S.герой;
  if (!условиеИмени(S, КЛЮЧ_ДЕЙСТВИЯ[вид] ?? вид)) return false;
  switch (вид) {
    case 'взять-письмо':
      if (выдатьВещь(S, ПИСЬМО, 'приемная-нотариуса') !== 'получено') return false;
      и.письмо = 'взял'; и.письмоСрокДень = день + ИМЯ.письмоСрок;
      обязан(S, 'картель', 'письмо Нотариуса');
      взятьОбязательство(S, { id: 'имя_письмо', название: 'Письмо Нотариуса для Дорра', срок: { день: и.письмоСрокДень, отрезок: 'ночь', граница: 'конец' } });
      return true;
    case 'отказ-письмо':
      и.письмо = 'отказ'; журнал(S, 'Письмо Нотариуса: отказался везти'); return true;
    case 'осмотр':
      и.осмотрел = true; return true;
    case 'вскрыть':
      и.вскрыто = true; и.путь = 'вскрыл'; и.знаетСодержание = true;
      журнал(S, 'Печать письма Нотариуса вскрыта: след остаётся');
      return true;
    case 'разрешение':
      убратьТип(S, ПИСЬМО); закрытьОбязательство(S, 'имя_письмо');
      и.письмо = 'доставлено'; и.путь = 'с-разрешения'; и.знаетСодержание = true;
      к.кошель += ИМЯ.оплатаДоставки;
      нить(S, 'ножи', 1); распол(S, 'rest_dorr', 1); обязан(S, 'ножи', 'честное посредничество');
      журнал(S, 'Письмо прочитано при Дорре: честное посредничество');
      return true;
    case 'предупредить':
      и.предупредил = true; нить(S, 'ножи', 1); распол(S, 'rest_dorr', 1); обязан(S, 'ножи', 'предупреждение');
      журнал(S, 'Дорр предупреждён о письме Нотариуса');
      return true;
    case 'доставить': {
      const сорвано = и.письмо === 'сорвано';
      убратьТип(S, ПИСЬМО); закрытьОбязательство(S, 'имя_письмо');
      и.письмо = 'доставлено'; и.путь ??= 'запечатанным';
      if (и.вскрыто) {
        и.дорзнает = true; и.долгВмешательства = true;
        нить(S, 'ножи', -1); распол(S, 'rest_dorr', -1);
        журнал(S, 'Дорр заметил тронутую печать. За вмешательство остался долг Нотариусу');
      } else if (!сорвано) {
        к.кошель += ИМЯ.оплатаДоставки; нить(S, 'картель', 1);
      }
      return true;
    }
    case 'вернуть-письмо':
      убратьТип(S, ПИСЬМО); закрытьОбязательство(S, 'имя_письмо');
      и.письмо = 'возвращено'; нить(S, 'картель', -1);
      for (const о of и.обязательства) if (о.сторона === 'картель' && о.что === 'письмо Нотариуса') о.нарушено = true;
      журнал(S, 'Письмо Нотариуса возвращено Нотариусу не доставленным');
      return true;
    case 'возместить':
      и.долгВмешательства = false; журнал(S, 'Нотариус принял возмещение за вскрытую печать'); return true;
    case 'вернуть-услугу':
      и.долгКипу = false; журнал(S, 'Услуга Кипа возвращена'); return true;
    case 'просьба-исполнить': {
      const против = сторонаКонфликта(S);
      и.просьба = 'исполнил'; нить(S, 'братство', 2); нить(S, против, -2); распол(S, 'gorm', 1);
      распол(S, против === 'картель' ? 'orsh' : 'rest_dorr', -1);
      обязан(S, 'братство', 'просьба Горма');
      журнал(S, `Просьба Горма исполнена. ${СТОРОНА_СЛОВАМИ[против]} запомнили, что ты сказал им то, что нужно Горму`);
      return true;
    }
    case 'просьба-обмен':
      и.просьба = 'обмен'; нить(S, 'братство', 1); распол(S, 'gorm', 1);
      обязан(S, 'братство', 'просьба Горма'); журнал(S, 'С Гормом договорились об обмене: конфликт назван вслух');
      return true;
    case 'просьба-отказ':
      и.просьба = 'отказ'; распол(S, 'gorm', -1); журнал(S, 'Просьбу Горма отклонил'); return true;
    case 'выгода-принять':
      и.бесплатное = 'принял'; и.долгКипу = true; к.кошель += ИМЯ.выгодаСумма; нить(S, 'картель', 1);
      обязан(S, 'картель', 'услуга Кипа'); журнал(S, 'Кип дал деньги «просто так»: за этим стоит услуга'); return true;
    case 'выгода-цена': {
      и.бесплатное = 'цена'; к.кошель += ИМЯ.выгодаСумма;
      const м = ((S.мир.места ??= {}).меняльная ??= { дом: 0, долг: 0, флаги: [], осмотрено: [], визитов: 0 });
      м.долг += ИМЯ.выгодаДолгВслух;
      журнал(S, `Цена названа вслух: вернуть ${ИМЯ.выгодаДолгВслух} гр. Оршу`); return true;
    }
    case 'выгода-отказ':
      и.бесплатное = 'отказ'; нить(S, 'репутация', 1); журнал(S, 'От «бесплатной» услуги Кипа отказался'); return true;
    case 'договор-независимость':
      и.договор = { вид: 'независимость', день }; расширитьБюджет(S);
      журнал(S, 'Публичный договор: Одвин полезен всем и не принадлежит никому');
      return true;
    case 'договор-картель': case 'договор-ножи': case 'договор-братство': {
      const с = вид.slice(8);
      и.договор = { вид: 'сторона', сторона: с, день }; расширитьБюджет(S);
      нить(S, с, 3);
      for (const др of СТОРОНЫ.filter(x => x !== с)) нить(S, др, -1);
      обязан(S, с, 'знак стороны');
      взятьОбязательство(S, { id: 'имя_служба', название: `Служба стороне: ${СТОРОНА_СЛОВАМИ[с]}`, срок: { день: ИМЯ.службаДо, отрезок: 'ночь', граница: 'конец' } });
      журнал(S, `Публичный договор: Одвин принимает знак стороны (${СТОРОНА_СЛОВАМИ[с]})`);
      return true;
    }
    case 'договор-уход':
      и.договор = { вид: 'уход', день }; журнал(S, 'Публичное слово не дано: Одвин не стал ничьим'); return true;
    case 'служба-картель': case 'служба-ножи': case 'служба-братство': {
      const с = вид.slice(7);
      и.служба[с] = true; нить(S, с, 3);
      if (и.договор.вид === 'сторона') закрытьОбязательство(S, 'имя_служба');
      журнал(S, `Служба выполнена: ${СТОРОНА_СЛОВАМИ[с]}`); return true;
    }
    case 'вызов-выполнить':
      и.вызов = 'выполнил'; нить(S, сторонаВызова(S), 2); журнал(S, 'Последний вызов: просьба выполнена на своих условиях'); return true;
    case 'вызов-отказ':
      и.вызов = 'отказ'; журнал(S, 'Последний вызов: отказ на своих условиях, город это видел'); return true;
    case 'вызов-верность': {
      const с = и.договор.сторона;
      и.вызов = 'выполнил'; нить(S, с, 2);
      for (const др of СТОРОНЫ.filter(x => x !== с)) нить(S, др, -1);
      журнал(S, 'Последний вызов: верность стороне доказана'); return true;
    }
    case 'вызов-отступить': {
      const с = и.договор.сторона;
      и.вызов = 'отступил'; и.договор.отступил = true; нить(S, с, -3);
      журнал(S, 'Последний вызов: Одвин отступил и принял цену'); return true;
    }
    default: return false;
  }
}

// Конец суток: срок письма, пропущенный вызов. S.мир.день — закрываемые сутки.
export function закрытьДеньИмени(S, итог) {
  const и = имя(S), день = S.мир.день, строки = итог.причины;
  if (и.письмо === 'взял' && и.письмоСрокДень !== null) {
    if (день >= и.письмоСрокДень) {
      и.письмо = 'сорвано'; нить(S, 'картель', -2);
      for (const о of и.обязательства) if (о.сторона === 'картель' && о.что === 'письмо Нотариуса') о.нарушено = true;
      строки.push('Письмо Нотариуса не доставлено в срок. Картель этого не забудет; письмо всё ещё у тебя, и вернуть его или донести можно.');
    } else if (день === и.письмоСрокДень - 1) {
      строки.push('Завтра последний день, чтобы донести письмо Нотариуса до Дорра. Контора принимает утром и днём.');
    }
  }
  if (день === ИМЯ.вызовДни[1] && вызовОткрыт(S)) {
    и.вызов = 'пропущен';
    строки.push(`Просьба стороны (${СТОРОНА_СЛОВАМИ[сторонаВызова(S)]}) осталась без ответа. В порту говорят об этом без злобы, но ясность твоего имени стала меньше.`);
  }
}

