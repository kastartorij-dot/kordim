// Лачуга Локи (карточка 5.9): вход по мосткам, торг «не золотом», пять услуг. Без DOM.
// Состояние визита — S.сцена.лачуга { тихо, этап, услуга, тема }; память места — S.мир.места['лачуга-локи'].память
// { взнос, отдано[], знает[], вещей, труда, платил }. Тексты, цены и список сувениров — в Данные/лачуга.js.
import {
  БОЛЬШАЯ_ВОДА, ШУМНО_ОТ, ДОСКИ, ДОСКИ_ИМ, СУВЕНИРЫ, ВЕС_СУВЕНИРА, ВЕС_СВОЕЙ_ПРАВДЫ, УСЛУГИ, ТРУД, УЛОВ, НАХОДКА, СЛОВА, ИТОГИ, ЖУРНАЛ,
} from '../Данные/лачуга.js';
import { ВЕЩИ } from '../Данные/вещи.js';
import { СЛОТЫ } from '../Данные/часовня.js';
import { РЕЕСТР } from '../Данные/темы.js';
import { верностьТемы, подтвердить, опровергнуть } from './знание.js';
import { списокСлухов, слухАктуален, опровергнуть as опровергнутьСлух } from './слухи.js';
import { привестиВещи, убратьТип, выдатьВещь, занято, естьВещь, намочитьБумаги } from './вещи.js';
import { хватает } from './ремёсла.js';
import { деньСцены } from './торг.js';
import { МАКС } from './тело.js';

const М = S => S.мир.места[S.сцена.место];
const память = S => (М(S).память ??= { взнос: 0, отдано: [], знает: [], вещей: 0, труда: 0 });
const состояние = S => (S.сцена.лачуга ??= { тихо: null, этап: null, услуга: null, тема: null });
const флаги = S => S.мир.флаги;

export const этап = S => S.сцена?.лачуга?.этап ?? null;
export const услугаСейчас = S => S.сцена?.лачуга?.услуга ?? null;
export const тихо = S => S.сцена?.лачуга?.тихо ?? null;
export const большаяВода = S => деньСцены(S) === БОЛЬШАЯ_ВОДА;

// ── мостки ──────────────────────────────────────────────────────────────
// Тихая доска зависит от дня: левая, средняя, правая по кругу. Груз скрипит на любой доске.
export const тихаяДоска = S => (деньСцены(S) + 1) % 3;
export const нагрузка = S => занято(привестиВещи(S));
export const слишкомТяжело = S => нагрузка(S) >= ШУМНО_ОТ;

const краткоеИмя = x => (ВЕЩИ[x.тип]?.имя ?? x.тип).split(' ')[0].toLowerCase();

// Локи не видит, но слышит по скрипу и называет вслух: «пирог, гиря, чужая правда».
export function названиеВещей(S) {
  const имена = [];
  for (const x of привестиВещи(S)) { const и = краткоеИмя(x); if (!имена.includes(и)) имена.push(и); }
  const вещи = имена.slice(0, 4);
  if (S.герой.кошель > 0) вещи.push('монеты');
  if (чужиеПравды(S).some(т => т.ценность >= 2)) вещи.push('чужая правда');
  return вещи.length ? вещи.join(', ') : 'ничего у тебя нет, только ты сам';
}

function входит(S, тихоЛи, реплика) {
  состояние(S).тихо = тихоЛи;
  S.сцена.комната = 'порог-локи';
  S.сцена.реплика = `${реплика}\n\n«${названиеВещей(S)}», — говорит Локи из-за занавески, не видя тебя.`;
  S.мир.журналДня.push(тихоЛи ? 'Лачуга Локи: подошёл незамеченным' : 'Лачуга Локи: доски выдали тебя');
}

export function ступитьНаДоску(S, i) {
  if (большаяВода(S) || !(i in ДОСКИ)) return;
  const угадал = i === тихаяДоска(S);
  if (угадал && !слишкомТяжело(S)) return входит(S, true, СЛОВА.тихо);
  входит(S, false, угадал ? СЛОВА.скрипГруз : `${СЛОВА.скрип} Ты выбрал ${ДОСКИ[i]}.`);
}

// Цену Кука списало действие; он ведёт по краю, и груз его не смущает.
export const нанятьКука = S => входит(S, true, большаяВода(S) ? СЛОВА.лодка : СЛОВА.кук);

export function вВоду(S) {
  if (большаяВода(S)) return;
  S.герой.тело.тепло = Math.max(0, S.герой.тело.тепло - 1);
  намочитьБумаги(S);
  входит(S, true, СЛОВА.наВоде);
}

export function прислушатьсяКДоскам(S) {
  S.сцена.реплика = хватает(S, 'грузчик') ? СЛОВА.слушатьДоски.replace('{доска}', ДОСКИ_ИМ[тихаяДоска(S)]) : СЛОВА.слушатьДоскиНеЗнаешь;
}

// ── что можно отдать ────────────────────────────────────────────────────
export const сувениры = S => СУВЕНИРЫ.filter(id => естьВещь(S, id));
export const названиеСувенира = id => ВЕЩИ[id]?.имя ?? id;

const уОтдавал = (S, вид, ключ) => память(S).отдано.some(о => о.вид === вид && о.ключ === ключ);

// Чужая правда: подтверждённая тема, которую ещё не отдавал и которую Локи не сам рассказал.
export function чужиеПравды(S) {
  if (!S.сцена || !S.мир.места[S.сцена.место]) return [];
  return S.мир.темы
    .filter(тид => верностьТемы(S, тид) === 'подтверждено' && !уОтдавал(S, 'тема', тид) && S.мир.знания?.[тид]?.от !== 'лачуга-локи')
    .map(тид => ({ id: тид, ярлык: РЕЕСТР[тид]?.ярлык ?? тид, ценность: РЕЕСТР[тид]?.ценность ?? 1 }))
    .sort((a, b) => b.ценность - a.ценность);
}
// Своя правда: факты о тебе, что игра умеет проверять; каждый можно отдать один раз.
export const своиПравды = S => СЛОТЫ.filter(с => с.есть(S) && !уОтдавал(S, 'факт', с.id)).map(с => ({ id: с.id, текст: с.да }));

// ── торг ────────────────────────────────────────────────────────────────
export function вес(S, id) {
  let в = УСЛУГИ[id].вес;
  if (id === 'проход' && (S.мир.фракции?.ножи ?? 0) >= 3) в -= 1; // Ножи на +3: Локи даёт проход раньше
  if (большаяВода(S)) в -= 1;                                      // Локи щедрее: к нему никто не идёт
  return Math.max(1, в);
}

export const слухДляЗабвения = S => списокСлухов(S).find(з => з.статус === 'ходит' && слухАктуален(S, з)) ?? null;
export const темыДляОтвета = S => S.мир.темы
  .filter(тид => верностьТемы(S, тид) === 'слышал')
  .map(тид => ({ id: тид, ярлык: РЕЕСТР[тид]?.ярлык ?? тид }))
  .slice(0, 5);

export function доступна(S, id) {
  if (id === 'проход') return тихо(S) !== false;
  if (id === 'слово') return !флаги(S).includes('без_свидетелей');
  if (id === 'забвение') return (S.мир.тень ?? 0) > 0 || слухДляЗабвения(S) !== null;
  if (id === 'ответ') return темыДляОтвета(S).length > 0;
  if (id === 'вещь') return !(S.мир.выдано ?? {})[НАХОДКА.выдано];
  return false;
}

export function начатьТорг(S) {
  const л = состояние(S);
  л.этап = 'услуги'; л.услуга = null; л.тема = null;
  S.сцена.реплика = (S.сцена.отрезок === 'ночь' ? СЛОВА.началоНочью : СЛОВА.начатьТорг)
    + (л.тихо === false ? `\n\n${СЛОВА.проходЗакрыт}` : '') + (большаяВода(S) ? `\n\n${СЛОВА.щедрый}` : '');
}

export function завершитьТорг(S) {
  const л = состояние(S);
  л.этап = null; л.услуга = null; л.тема = null;
  S.сцена.реплика = СЛОВА.конец;
}

const описаниеЦены = (S, id) => {
  const в = вес(S, id), был = память(S).взнос;
  return `Нужно весом ${в}${был ? `, на верёвке уже ${был}` : ''}. Сувенир весит ${ВЕС_СУВЕНИРА}, своя правда ${ВЕС_СВОЕЙ_ПРАВДЫ}, чужая по ценности, час труда один.`;
};

export function выбратьУслугу(S, id) {
  const л = состояние(S);
  if (л.этап !== 'услуги' || !УСЛУГИ[id] || !доступна(S, id)) return;
  л.услуга = id; л.тема = null;
  if (id === 'ответ') { л.этап = 'тема'; S.сцена.реплика = `${УСЛУГИ[id].загадка}\n\nО чём спрашиваешь?`; return; }
  л.этап = 'плата';
  S.сцена.реплика = `${УСЛУГИ[id].загадка}\n\n${описаниеЦены(S, id)}`;
}

export function выбратьТему(S, тид) {
  const л = состояние(S);
  if (л.этап !== 'тема' || !темыДляОтвета(S).some(т => т.id === тид)) return;
  л.тема = тид; л.этап = 'плата';
  S.сцена.реплика = `Локи ждёт цену. «${РЕЕСТР[тид]?.ярлык ?? тид}»: правда или нет, он скажет один раз.\n\n${описаниеЦены(S, 'ответ')}`;
}

export function передумать(S) {
  const л = состояние(S);
  л.этап = 'услуги'; л.услуга = null; л.тема = null;
  S.сцена.реплика = СЛОВА.передумал;
}

// Золото Локи не берёт: монета остаётся у тебя, а правило запоминается темой «здесь платят не золотом».
export const предложитьЗолото = S => { S.сцена.реплика = СЛОВА.золото; };
export const предложитьЗолотоКуку = S => { S.сцена.реплика = СЛОВА.золотоКук; };

function выполнитьУслугу(S, id) {
  const м = память(S), л = состояние(S);
  const строки = [];
  let реплика = '';
  if (id === 'проход') {
    if (!флаги(S).includes('проход_локи')) флаги(S).push('проход_локи');
    if ((S.мир.тень ?? 0) > 0) S.мир.тень -= 1;
    реплика = ИТОГИ.проход; строки.push(ЖУРНАЛ.проход);
  } else if (id === 'слово') {
    if (!флаги(S).includes('без_свидетелей')) флаги(S).push('без_свидетелей');
    реплика = ИТОГИ.слово; строки.push(ЖУРНАЛ.слово);
  } else if (id === 'забвение') {
    const з = слухДляЗабвения(S), тень = (S.мир.тень ?? 0) > 0;
    if (з) опровергнутьСлух(S, з.id, 'забыто у Локи');
    if (тень) S.мир.тень -= 1;
    реплика = [з ? ИТОГИ.забвениеСлух : null, тень ? ИТОГИ.забвениеТень : null].filter(Boolean).join('\n\n');
    строки.push(`${ЖУРНАЛ.забвение}${з ? ': слух о тебе затих' : ''}${тень ? (з ? ', ' : ': ') + 'Тень −1' : ''}`);
  } else if (id === 'ответ') {
    const тид = л.тема, ложь = !!РЕЕСТР[тид]?.ложь;
    if (ложь) опровергнуть(S, тид); else подтвердить(S, тид);
    реплика = ложь ? ИТОГИ.ответЛожь : ИТОГИ.ответПравда;
    строки.push(`${ЖУРНАЛ.ответ}: «${РЕЕСТР[тид]?.ярлык ?? тид}» — ${ложь ? 'враньё' : 'правда'}`);
  } else if (id === 'вещь') {
    выдатьВещь(S, НАХОДКА.вещь, S.сцена.место);
    (S.мир.выдано ??= {})[НАХОДКА.выдано] = true;
    реплика = ИТОГИ.вещь; строки.push(ЖУРНАЛ.вещь);
  }
  for (const с of строки) S.мир.журналДня.push(с);
  м.взнос = 0;
  (м.выдано ??= []).push(id);
  м.платил = деньСцены(S);
  л.этап = 'услуги'; л.услуга = null; л.тема = null;
  return реплика;
}

// Внести плату. false — такой платы нет или нечем платить (состояние не меняется).
export function заплатить(S, вид, ключ) {
  const л = состояние(S), м = память(S), id = л.услуга;
  if (л.этап !== 'плата' || !id) return false;
  let ценность = 0, что = '', знает = null, трудРеплика = '';
  if (вид === 'сувенир') {
    if (!СУВЕНИРЫ.includes(ключ) || !естьВещь(S, ключ)) return false;
    убратьТип(S, ключ);
    ценность = ВЕС_СУВЕНИРА; что = названиеСувенира(ключ);
    м.вещей += 1;
  } else if (вид === 'труд') {
    const т = ТРУД[ключ], тело = S.герой.тело;
    if (!т || тело[т.тело] < 1) return false;
    тело[т.тело] = Math.max(0, Math.min(МАКС, тело[т.тело] - 1));
    ценность = 1; что = `труд (${ключ})`; м.труда += 1; трудРеплика = т.реплика;
  } else if (вид === 'тема') {
    const т = чужиеПравды(S).find(x => x.id === ключ);
    if (!т) return false;
    ценность = т.ценность; что = `правда «${т.ярлык}»`; знает = `что тебе известно: ${т.ярлык}`;
  } else if (вид === 'факт') {
    const ф = своиПравды(S).find(x => x.id === ключ);
    if (!ф) return false;
    ценность = ВЕС_СВОЕЙ_ПРАВДЫ; что = `своя правда («${ф.текст}»)`; знает = ф.текст;
  } else return false;
  м.отдано.push({ вид, ключ, день: деньСцены(S) });
  if (знает && !м.знает.includes(знает)) м.знает.push(знает);
  м.взнос += ценность;
  S.мир.журналДня.push(`${ЖУРНАЛ.заплатил}: ${что}`);
  const нужно = вес(S, id);
  if (м.взнос >= нужно) {
    const итог = выполнитьУслугу(S, id);
    S.сцена.реплика = [трудРеплика, итог].filter(Boolean).join('\n\n');
  } else {
    S.сцена.реплика = [трудРеплика, `${СЛОВА.взнос} Теперь на верёвке ${м.взнос} из ${нужно}.`].filter(Boolean).join('\n\n');
  }
  return true;
}

// ── улов дня ────────────────────────────────────────────────────────────
export const уловДоступен = S => !!S.сцена && !!S.мир.места[S.сцена.место]?.память?.платил
  && S.мир.места[S.сцена.место].память.платил === деньСцены(S);
export function взятьУлов(S) {
  выдатьВещь(S, УЛОВ.вещь, S.сцена.место);
  S.сцена.реплика = УЛОВ.реплика;
  S.мир.журналДня.push('Лачуга Локи: улов дня');
}

// Что Локи знает о тебе: узлы на верёвке. Читается осмотром; в конце сезона это «ты как список».
export function верёвка(S) {
  const м = S.мир.места['лачуга-локи']?.память;
  const визитов = S.мир.места['лачуга-локи']?.визитов ?? 0;
  const узлов = `Узлов на верёвке: ${визитов}. `;
  if (!м?.знает?.length && !м?.вещей && !м?.труда) return узлов + СЛОВА.узелПусто;
  const отдал = [
    м.вещей ? `вещей ${м.вещей}` : null,
    м.труда ? `часов труда ${м.труда}` : null,
    м.знает.length ? `правд ${м.знает.length}` : null,
  ].filter(Boolean).join(', ');
  return `${узлов}На твоих узлах: ${отдал}. Локи помнит: ${м.знает.length ? м.знает.join('; ') : 'ни одной правды'}.`;
}

// Единая точка входа для эффекта { лачуга: {...} } из данных места.
export function действиеЛачуги(S, д) {
  switch (д.вид) {
    case 'доска': return ступитьНаДоску(S, д.i);
    case 'кук': return нанятьКука(S);
    case 'вода': return вВоду(S);
    case 'слушать': return прислушатьсяКДоскам(S);
    case 'золотоКук': return предложитьЗолотоКуку(S);
    case 'начать': return начатьТорг(S);
    case 'услуга': return выбратьУслугу(S, д.id);
    case 'тема': return выбратьТему(S, темыДляОтвета(S)[д.слот]?.id);
    case 'плата': {
      const ключ = д.как === 'тема' ? чужиеПравды(S)[д.слот]?.id : д.как === 'факт' ? своиПравды(S)[д.слот]?.id : д.ключ;
      return заплатить(S, д.как, ключ);
    }
    case 'золото': return предложитьЗолото(S);
    case 'назад': return передумать(S);
    case 'конец': return завершитьТорг(S);
    case 'улов': return взятьУлов(S);
  }
}
