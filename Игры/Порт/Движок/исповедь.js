// Исповедь в часовне (карточка 5.8): игра сверяет слова с фактами мира. Правда даёт «слово часовни» (раз за сезон),
// ложь гасит свечу: Тень +1 и три дня молчания. Здесь не бросают кубик и ничего не уходит наверх. Без DOM.
// Состояние стола лежит в S.сцена.исповедь; память места — S.мир.места.часовня.память. Тексты и факты — в данные/часовня.js.
import { источникиУны, СЛОТЫ, ЧИСЛИТСЯ_МИНИМУМ, ПОКАЗАТЬ, ЗАКРЫТО_ДНЕЙ, СЛОВА } from '../Данные/часовня.js';
import { бросок } from './случай.js';
import { деньСцены } from './торг.js';

const М = S => S.мир.места[S.сцена.место];
const память = S => (М(S).память ??= {});
const счётчики = S => (М(S).счётчики ??= {});

export const числится = S => источникиУны(S).filter(с => с.верно);

// Часовня молчит, пока не вышел срок после лжи. Работает и вне сцены (для убежища на карте).
export function часовняЗакрыта(S) {
  const до = S.мир.места.часовня?.память?.закрытоДо;
  const день = S.сцена ? деньСцены(S) : S.мир.день;
  return до !== undefined && день < до;
}

export const этапИсповеди = S => S.сцена?.исповедь?.этап ?? null;
export const высказывание = (S, i) => S.сцена?.исповедь?.высказывания[i] ?? null;
export const ещёНеСказано = (S, i) => { const и = S.сцена?.исповедь; return !!и && и.этап === 'выбор' && !!и.высказывания[i] && !и.сказано.includes(i); };

function перемешать(S, список) {
  const из = [...список], вышло = [];
  while (из.length) вышло.push(из.splice(Math.floor(бросок(S) * из.length), 1)[0]);
  return вышло;
}

// Высказывания: признания (верно), честные отрицания (верно), отрицания факта и хвастовство (ложь). Всегда есть хоть одно враньё.
export function собратьВысказывания(S) {
  const известные = источникиУны(S).map(и => ({ ...СЛОТЫ.find(с => с.id === и.id), ...и }));
  const F = перемешать(S, известные.filter(с => с.верно)), N = перемешать(S, известные.filter(с => !с.верно));
  const a = Math.min(2, F.length), b = Math.min(2, Math.max(0, F.length - a));
  const список = [
    ...F.slice(0, a).map(с => ({ id: `${с.id}:да`, текст: с.да, источник: с.источник, верно: true })),
    ...F.slice(a, a + b).map(с => ({ id: `${с.id}:нет`, текст: с.нет, источник: с.источник, верно: false })),
  ];
  let нужноЛжи = b === 0 ? 1 : 0;
  for (const с of N) {
    if (список.length >= ПОКАЗАТЬ) break;
    if (нужноЛжи > 0) { список.push({ id: `${с.id}:да`, текст: с.да, источник: с.источник, верно: false }); нужноЛжи -= 1; }
    else список.push({ id: `${с.id}:нет`, текст: с.нет, источник: с.источник, верно: true });
  }
  return перемешать(S, список);
}

// Начать: при малом числе фактов — «приходи, когда будет что сказать» без штрафа; после лжи — молчание.
export function начатьИсповедь(S) {
  if (часовняЗакрыта(S)) { S.сцена.реплика = СЛОВА.закрыто; return false; }
  if (источникиУны(S).length < 2 || числится(S).length < ЧИСЛИТСЯ_МИНИМУМ) { S.сцена.реплика = СЛОВА.мало; return false; }
  (М(S).дниДействий ??= {}).исповедь = деньСцены(S);
  S.сцена.исповедь = { этап: 'выбор', высказывания: собратьВысказывания(S), сказано: [] };
  S.сцена.комната = 'исповедальня';
  S.сцена.реплика = СЛОВА.вопрос + '\n\nПроверяем только показанные записи и то, что Уна видела сама: ' + источникиУны(S).map(и => и.источник).join('; ') + '.';
  return true;
}

export function сказать(S, i) {
  const и = S.сцена.исповедь;
  if (!ещёНеСказано(S, i)) return;
  и.сказано.push(i);
  S.сцена.реплика = `Ты говоришь вслух: «${и.высказывания[i].текст}». Уна не отвечает и не отводит взгляд.`;
}

function выйтиВНеф(S) {
  S.сцена.исповедь = null;
  S.сцена.комната = 'неф-часовни';
}

// Итог: ложь гасит свечу; правда даёт слово часовни (раз за сезон); молчание ничего не стоит. Возвращает { готово }:
// «готово» — исповедь закончена целиком, а не ждёт выбора слова часовни (тогда ход тратится позже).
export function закончитьИсповедь(S) {
  const и = S.сцена.исповедь, п = память(S), с = счётчики(S);
  const сказано = и.сказано.map(i => и.высказывания[i]);
  if (сказано.some(x=>!x.источник)) { S.сцена.реплика='Уна просит сначала показать записи. Прежний разговор не принимается за доказательство.'; выйтиВНеф(S); return {готово:true}; }
  if (!сказано.length) { S.сцена.реплика = СЛОВА.молчал; выйтиВНеф(S); return { готово: true }; }
  if (сказано.some(x => !x.верно)) {
    S.мир.тень = Math.min(3, (S.мир.тень ?? 0) + 1);
    S.мир.теньДень = S.мир.день;
    п.закрытоДо = деньСцены(S) + ЗАКРЫТО_ДНЕЙ;
    с.лжи = (с.лжи ?? 0) + 1;
    S.сцена.реплика = СЛОВА.ложь;
    S.мир.журналДня.push('Соврал в часовне: Тень +1, Уна молчит три дня');
    выйтиВНеф(S);
    return { готово: true };
  }
  const исповедано = (п.исповедано ??= []);
  for (const x of сказано) if (!исповедано.includes(x.id)) исповедано.push(x.id);
  с.исповедей = (с.исповедей ?? 0) + 1;
  S.мир.журналДня.push(`Исповедался в часовне без лжи (${сказано.length})`);
  if ((S.мир.выдано ??= {}).покров_часовни) { S.сцена.реплика = СЛОВА.правдаБезПокрова; выйтиВНеф(S); return { готово: true }; }
  и.этап = 'покров';
  S.сцена.реплика = СЛОВА.правда;
  return { готово: false };
}

// Слово часовни: снять Тень −1 сразу или оставить про запас — оно остановит следующую кражу (движок/кража.js).
export function выбратьСлово(S, как) {
  S.мир.выдано.покров_часовни = true;
  if (как === 'тень') {
    S.мир.тень = Math.max(0, (S.мир.тень ?? 0) - 1);
    S.сцена.реплика = СЛОВА.тень;
    S.мир.журналДня.push('Слово часовни: Тень −1');
  } else {
    S.мир.покров = { активен: true, место: 'ночлежка', с: деньСцены(S)+1, до: деньСцены(S)+7 };
    S.сцена.реплика = СЛОВА.сберечь;
    S.мир.журналДня.push('Уна отправляет Тону просьбу присмотреть за койкой: с завтрашнего дня, на неделю, до первой предотвращённой кражи');
  }
  выйтиВНеф(S);
}
