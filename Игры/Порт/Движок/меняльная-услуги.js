// Именное хранение у Орша. UID и количество сохраняются, деньги за возврат не создаются.
import { привестиВещи, забрать, можноПоложить, размер, занято, имяВещи } from './вещи.js';
import { заложитьВещь, выкупитьВещь } from './хозяйство.js';
const запись = S => S.мир.места.меняльная;
const склад = S => (запись(S).хранение ??= []);
export function сдатьОршу(S, uid) {
  const x = привестиВещи(S).find(x => x.uid === uid);
  if (S.сцена?.место !== 'меняльная' || !x || x.состояние?.прокат || S.герой.кошель < 1 || занято(склад(S)) + размер(x) > 16) return false;
  const вещь = забрать(S, uid, x.количество);
  склад(S).push(вещь); S.герой.кошель -= 1;
  S.мир.журналДня.push(имяВещи(x) + ': Орш принял на хранение, плата 1 гр., возврат без платы');
  S.сцена.реплика = 'Орш вписывает вещь на твоё имя. Долг по займу не даёт ему права забрать оставленное на хранение.';
  return true;
}
export function забратьУОрша(S, uid) {
  const list = склад(S), x = list.find(x => x.uid === uid);
  if (S.сцена?.место !== 'меняльная' || !x || !можноПоложить(S, x.тип, x.количество)) return false;
  // Экземпляр переносится целиком, без слияния и потери истории.
  const свободно = 8 - (S.герой.тело.цел <= 1 ? 1 : 0) - занято(привестиВещи(S));
  if (свободно < размер(x)) return false;
  list.splice(list.indexOf(x), 1); S.герой.при_себе.push(x);
  S.мир.журналДня.push(имяВещи(x) + ': получено из хранения Орша');
  S.сцена.реплика = 'Орш сверяет запись и возвращает тот же предмет. За получение уже уплачено.';
  return true;
}
export function действияОрша() {
  const А = [];
  for (let i=0;i<16;i++) {
    А.push({ вид:'действие', текст:S=>'Оставить Оршу: '+имяВещи(привестиВещи(S)[i]), подпись:'1 гр. · хранение, 16 мест',
      условие:S=>!!привестиВещи(S)[i] && !привестиВещи(S)[i].состояние?.прокат && S.герой.кошель>=1 && занято(склад(S))+размер(привестиВещи(S)[i])<=16,
      эффект:S=>сдатьОршу(S,привестиВещи(S)[i]?.uid) });
    А.push({ вид:'действие', текст:S=>'Забрать у Орша: '+имяВещи(склад(S)[i]), подпись:'без платы',
      условие:S=>!!склад(S)[i] && 8-(S.герой.тело.цел<=1?1:0)-занято(привестиВещи(S))>=размер(склад(S)[i]),
      эффект:S=>забратьУОрша(S,склад(S)[i]?.uid) });
    А.push({ вид:'действие', текст:S=>'Заложить Оршу: '+имяВещи(привестиВещи(S)[i]), подпись:'половина цены · выкуп 7 дней',
      условие:S=>{const x=привестиВещи(S)[i];return !!x && !x.состояние?.прокат;},
      эффект:S=>{ if (!заложитьВещь(S,привестиВещи(S)[i]?.uid)) S.сцена.реплика='Орш не берёт улики, чужие поручения, прокат и вещи без продажной цены. Их можно оставить на хранение.'; else S.сцена.реплика='Сумма и срок записаны. Просрочка займа и срок залога — разные записи.'; } });
    А.push({ вид:'действие', текст:S=>'Выкупить у Орша: '+имяВещи(S.герой.залог?.[i]?.вещь), подпись:S=>(S.герой.залог?.[i]?.сумма??0)+' гр.',
      условие:S=>!!S.герой.залог?.[i] && S.мир.день<=S.герой.залог[i].выкупДо && S.герой.кошель>=S.герой.залог[i].сумма,
      эффект:S=>{if(!выкупитьВещь(S,S.герой.залог?.[i]?.вещь.uid))S.сцена.реплика='Освободи место в сумке: выкуп и плата ещё не выполнены.';} });
  }
  return А;
}
