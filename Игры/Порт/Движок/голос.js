// Дневник («Голос героя»): короткая запись от первого лица раз в несколько дней.
// Переработка Порт-Голос-героя.md под ПЛАН_ДОРАБОТКИ.md П08.5–6.
//
// Не шкала (ГДД §10): ни манеры, ни факты ничего не открывают и не закрывают,
// не меняют цен и не решают, доступна ли реплика. Они выбирают лишь, какую из уже
// написанных записей показать. Второй эффект им давать нельзя.
//
// Что изменено по сравнению со старым заданием:
//  • «тоны» заменены манерами (счётчики общения) и долговременными фактами героя;
//  • очередь: подошедшая, но не показанная запись ждёт; при показе условие проверяется
//    снова, и запись, которая перестала быть правдой, из очереди уходит;
//  • особые записи (кризис, день 15, день 25) показываются вне интервала и раньше обычных;
//    у них есть окно дней: запись «до конца осталось меньше недели» после дня 29 не нужна;
//  • интервал считается от последней показанной записи («не реже, чем через N дней»),
//    а не «день кратен трём»: пропущенный день и загрузка его не ломают;
//  • одна запись в день, повторный вызов в тот же день ничего не добавляет.

import { ГОЛОС } from '../Данные/голос.js';
import { НАСТРОЙКИ, деньИгры, телоВКризисе, списокДел, делоБезОплаты } from './шаг7-адаптер.js';

export const новыйДневник = () => ({
  показано: [],       // id в порядке появления
  очередь: [],        // подошли, но ещё не показаны
  тексты: {},        // показанный текст сохраняется, включая вариант для отложенной записи
  когда: {},          // id → день показа (для отладки; в журнале дата не пишется)
  деньРаботы: [],     // дни, в которые была оплаченная смена
  последняя: 0,       // день последней показанной записи
  сегодня: 0,         // день, когда запись уже показана (защита от повторного вызова)
});

const дневник = S => (S.герой.дневник ??= новыйДневник());

// ---------- точки записи фактов (зовёт остальной код игры) ----------

// В функции спросить(S, тид) рядом с л.спрошено.push(...): одна строка.
// Манера — ключ из МАНЕРА_В_ЗАПИСЬ; после Шага 4 — манера выбранной реплики.
export function отметитьМанеру(S, манера) {
  if (typeof манера !== 'string' || !манера) return;
  const м = (S.герой.манеры ??= {});
  м[манера] = (м[манера] ?? 0) + 1;
}

// Долговременный факт героя. Повторный вызов ничего не меняет (идемпотентно).
// Известные: 'кризис_тела' (модуль тела, когда тело впервые «сказало хватит»),
// 'помог_без_платы' (модуль дел, при закрытии помощи без выплаты).
export function отметитьФакт(S, id, данные = {}) {
  const ф = (S.герой.факты ??= {});
  if (!(id in ф)) ф[id] = { день: деньИгры(S), ...данные };
  return ф[id];
}

// Вызывать, когда оплаченная смена закончена (один раз в день достаточно).
export function отметитьРаботу(S) {
  const д = дневник(S);
  const день = деньИгры(S);
  if (!д.деньРаботы.includes(день)) д.деньРаботы.push(день);
}

// Факты записываются в момент события: лечение в тот же день не стирает кризис.
export function отметитьКризисТела(S) {
  if (телоВКризисе(S)) отметитьФакт(S, 'кризис_тела');
}

// Контракт с делами: сюда передаётся уже состоявшийся итог, функция деньги не выдаёт.
// Неизвестная выплата или отсутствующее решение не становятся «бескорыстной помощью».
export function отметитьИтогДела(S, { id, тип, выплата, выбор }) {
  if (!id || !тип || !Number.isFinite(выплата) || выплата < 0 || !выбор) return false;
  S.мир.дела ??= [];
  const старое = списокДел(S).find(з => з.id === id);
  if (старое && ['готово', 'выполнено'].includes(старое.статус)) return false;
  const з = { ...старое, id, тип, статус: 'готово', итог: { выплата, выбор, день: деньИгры(S) } };
  if (Array.isArray(S.мир.дела)) {
    const i = S.мир.дела.findIndex(д => д.id === id);
    if (i < 0) S.мир.дела.push(з); else S.мир.дела[i] = з;
  } else S.мир.дела[id] = з;
  if (делоБезОплаты(з)) отметитьФакт(S, 'помог_без_платы', { дело: id });
  return true;
}

// ---------- производные величины ----------

export function ведущаяМанера(S) {
  const м = S.герой.манеры ?? {};
  const сумма = Object.values(м).reduce((а, б) => а + б, 0);
  for (const [ключ, n] of Object.entries(м)) {
    if (n >= НАСТРОЙКИ.порогМанеры && n > сумма - n) return ключ;
  }
  return null;
}

function контекст(S, день = деньИгры(S)) {
  const манеры = S.герой.манеры ?? {};
  return {
    день,
    всегоМанер: Object.values(манеры).reduce((а, б) => а + б, 0),
    факт: id => Boolean(S.герой.факты?.[id]),
    ведущая: () => ведущаяМанера(S),
    // «с самого начала»: каждый день от первого до нынешнего — с оплаченной сменой
    безПропусков: n => {
      const дни = дневник(S).деньРаботы;
      if (день < n) return false;
      for (let d = 1; d <= день; d++) if (!дни.includes(d)) return false;
      return true;
    },
    помощьБезОплаты: () => списокДел(S).some(делоБезОплаты),
  };
}

// ---------- раз в день, в закончитьДень (после слухов: ПЛАН П02.5) ----------
// → { id, текст } показанной записи или null.
export function обновитьДневник(S, итог) {
  const д = итог?.день ?? деньИгры(S);
  const Д = дневник(S);
  const К = контекст(S, д);

  // запасной опрос: тело можно было не отметить из своего модуля
  if (!К.факт('кризис_тела') && телоВКризисе(S)) отметитьФакт(S, 'кризис_тела', { день: д });

  const подходит = id => {
    const з = ГОЛОС[id];
    if (!з || Д.показано.includes(id)) return false;
    if (з.окно && (д < з.окно[0] || д > з.окно[1])) return false;
    return Boolean(з.условие(S, К));
  };

  // Зафиксировать помощь в долговременной памяти, пока завершённое дело ещё в реестре.
  if (!К.факт('помог_без_платы')) {
    const помощь = списокДел(S).find(делоБезОплаты);
    if (помощь) отметитьФакт(S, 'помог_без_платы', { день: помощь.итог?.день ?? помощь.деньКонца ?? д });
  }

  // очередь: убрать то, что перестало быть правдой, добавить новое (в порядке реестра)
  Д.очередь = Д.очередь.filter(подходит);
  for (const id of Object.keys(ГОЛОС)) {
    if (!Д.очередь.includes(id) && подходит(id)) Д.очередь.push(id);
  }

  if (Д.сегодня === д) return null;               // одна запись в день

  // выбор: особая по приоритету, иначе обычная, но не чаще интервала
  let выбран = Д.очередь
    .filter(id => ГОЛОС[id].особая)
    .sort((a, b) => (ГОЛОС[b].приоритет ?? 0) - (ГОЛОС[a].приоритет ?? 0))[0] ?? null;
  if (!выбран && д - Д.последняя >= НАСТРОЙКИ.интервалДневника) {
    выбран = Д.очередь.find(id => !ГОЛОС[id].особая) ?? null;
  }
  if (!выбран) return null;

  Д.очередь = Д.очередь.filter(id => id !== выбран);
  Д.показано.push(выбран);
  Д.когда[выбран] = д;
  Д.последняя = д;
  Д.сегодня = д;
  const запись = ГОЛОС[выбран];
  const деньСобытия = запись.факт && S.герой.факты?.[запись.факт]?.день;
  const текст = запись.текстПозже && деньСобытия < д ? запись.текстПозже : запись.текст;
  (Д.тексты ??= {})[выбран] = текст;
  if (итог?.причины) итог.причины.push('В дневнике появилась новая запись.');
  return { id: выбран, текст };
}

// Для раздела «Голос» журнала: тексты в порядке появления, без даты.
export function сводкаДневника(S) {
  return (S.герой.дневник?.показано ?? []).map(id => S.герой.дневник.тексты?.[id] ?? ГОЛОС[id]?.текст).filter(Boolean);
}
