// Тали — разгрузка в доках. Ящик висит на канате под тележкой стрелы и качается, как маятник:
// резкий ход тележки раскачивает его, встречный — гасит. Опусти три ящика с пирса в трюм, в меченые гнёзда,
// не стукнув о борт и не макнув в воду. Мышь: куда указываешь — туда идёт тележка и туда опускается крюк.
import {
  ЦВЕТ, ШИР, ВЫС, ШРИФТ, звуки, ступеньНавыка, создатьПоле, картинка, фон, надпись, плашка, полоса,
  ограничить, звук,
} from './общее.js';
import { ступеньНомер } from '../ремёсла.js';

export const ОПИСЬ = { id: 'тали', имя: 'Тали', где: 'Разгрузка в доках' };
export const СМЫСЛ = {
  плохо: 'Ящики бились о борт, один побывал в воде. Старший пересчитает, что уцелело.',
  нормально: 'Всё в трюме и целое, хоть и с качкой. Смена засчитана.',
  отлично: 'Ящики легли в гнёзда, как поставленные руками. Старший молча кивнул.',
};
// Навык для живого слоя: ремесло грузчика (нет → 0, умеешь → 1, набил руку и выше → 2).
export const навык = S => ограничить(ступеньНомер(S, 'грузчик') + 1, 0, 2);

const СТРЕЛА = 72;
const Я = { w: 60, h: 46 };
const Г = 900; // сила тяжести, пикселей/с²
const ПИРС = 410;
const ВОДА = 458;
const ПАЛУБА = 330;
const ДНО = 495;
const ГНЁЗДА = [660, 735, 810];
const СТАТИКА = [
  { x1: 0, y1: ПИРС, x2: 300, y2: ВЫС, вид: 'пирс' },
  { x1: 300, y1: ВОДА + 14, x2: 540, y2: ВЫС, вид: 'вода' },
  { x1: 540, y1: ПАЛУБА, x2: 618, y2: ВЫС, вид: 'борт' },
  { x1: 852, y1: ПАЛУБА, x2: 940, y2: ВЫС, вид: 'борт' },
  { x1: 618, y1: ДНО, x2: 852, y2: ВЫС, вид: 'трюм' },
];

export async function запустить(контейнер, { навык = 0, тихо = false, сигнал } = {}) {
  const н = ступеньНавыка(навык);
  звук.тихо = тихо;
  const поле = создатьПоле(контейнер, { подсказка: 'Веди мышью: тележка идёт за указателем, крюк опускается туда, где он. Резко — раскачаешь; веди встречно, чтобы погасить. Стрелки — то же с клавиш.', сигнал });
  const доки = await картинка('Ресурсы/Районы/доки.webp');

  const гашение = [0.12, 0.3, 0.55][н];
  const лебёдка = 150 + 20 * н;
  const мягко = 75 + 25 * н; // скорость касания дна, при которой ящик не стукнет
  const спокойно = 40 + 15 * н; // боковая скорость при касании
  const терпение = 90 + 12 * н;

  // тележка и маятник
  let тх = 240, тv = 0, та = 0;
  let θ = 0, ω = 0;
  let L = ПИРС - Я.h - СТРЕЛА;
  let цельX = тх, цельL = L;
  let клавишами = false;
  // ящики: на пирсе, на крюке, в трюме
  const ящики = [240, 170, 100].map(x => ({ x, y: ПИРС - Я.h, где: 'пирс', стуков: 0, вода: false, очки: 0 }));
  let наКрюке = ящики[0];
  наКрюке.где = 'крюк';
  let время = 0;
  let сказ = '', сказЖизнь = 0;
  let пауза = 0;

  const крюк = () => ({ x: тх + L * Math.sin(θ), y: СТРЕЛА + L * Math.cos(θ) });
  const рамка = (к, груз) => груз
    ? { x1: к.x - Я.w / 2, y1: к.y, x2: к.x + Я.w / 2, y2: к.y + Я.h }
    : { x1: к.x - 5, y1: к.y, x2: к.x + 5, y2: к.y + 10 };
  const твёрдые = () => СТАТИКА.concat(ящики.filter(я => я.где !== 'крюк').map(я => ({ x1: я.x - Я.w / 2, y1: я.y, x2: я.x + Я.w / 2, y2: я.y + Я.h, вид: я.где === 'трюм' ? 'ящик' : 'пирс' })));
  const пересёк = (а, б) => а.x2 > б.x1 && а.x1 < б.x2 && а.y2 > б.y1 && а.y1 < б.y2;
  const сказать = s => { сказ = s; сказЖизнь = 2.4; };
  const свободные = () => ГНЁЗДА.filter(г => !ящики.some(я => я.где === 'трюм' && Math.abs(я.x - г) < Я.w));
  const вТрюме = () => ящики.filter(я => я.где === 'трюм').length;

  function поставить(я, к, vy, vx) {
    я.где = 'трюм';
    я.x = к.x;
    я.y = ДНО - Я.h;
    const гн = свободные().concat(ГНЁЗДА).sort((а, б) => Math.abs(а - к.x) - Math.abs(б - к.x))[0];
    const сдвиг = Math.abs(к.x - гн);
    const мягкость = vy <= мягко ? 1 : ограничить(1 - (vy - мягко) / 160, 0.2, 1);
    const покой = Math.abs(vx) <= спокойно ? 1 : ограничить(1 - (Math.abs(vx) - спокойно) / 90, 0.2, 1);
    const точность = сдвиг <= 8 + 5 * н ? 1 : ограничить(1 - (сдвиг - 8 - 5 * н) / 40, 0.2, 1);
    я.очки = ограничить(0.45 * мягкость + 0.25 * покой + 0.3 * точность - 0.12 * Math.min(3, я.стуков) - (я.вода ? 0.3 : 0), 0, 1);
    звуки.штамп();
    поле.дрожь(мягкость < 0.7 ? 7 : 3);
    const сл = я.очки >= 0.85 ? ['в гнездо!', ЦВЕТ.трава] : мягкость < 0.7 ? ['грохнул', ЦВЕТ.ржа] : точность < 0.7 ? ['мимо меты', ЦВЕТ.свеча] : ['стоит', ЦВЕТ.бумага];
    поле.слово(сл[0], к.x, ДНО - 80, сл[1], 28);
    if (я.очки >= 0.85) { поле.кольцо(к.x, ДНО - Я.h / 2, ЦВЕТ.трава, 70); звуки.звон(1100); }
    наКрюке = null;
    пауза = 0.35;
    if (вТрюме() >= ящики.length) итог();
    else сказать(я.очки >= 0.6 ? 'Следующий!' : 'Осторожней, там не камни.');
  }

  function итог() {
    const сумма = ящики.reduce((с, я) => с + я.очки, 0) / ящики.length;
    const спешка = время <= 55 ? 1 : ограничить(1 - (время - 55) / 120, 0.85, 1);
    поле.конец(сумма * спешка);
  }

  function шаг(dt) {
    время += dt;
    сказЖизнь = Math.max(0, сказЖизнь - dt);
    пауза = Math.max(0, пауза - dt);
    if (время >= терпение) { сказать('Хватит, сами доделаем!'); итог(); return; }
    if (клавишами) {
      const к = поле.клавиши;
      const dx = (к.has('ArrowRight') || к.has('KeyD') ? 1 : 0) - (к.has('ArrowLeft') || к.has('KeyA') ? 1 : 0);
      const dy = (к.has('ArrowDown') || к.has('KeyS') ? 1 : 0) - (к.has('ArrowUp') || к.has('KeyW') ? 1 : 0);
      цельX = ограничить(цельX + dx * 320 * dt, 90, 880);
      цельL = ограничить(цельL + dy * 220 * dt, 50, 430);
    } else {
      цельX = ограничить(поле.мышь.x, 90, 880);
      цельL = ограничить(поле.мышь.y - СТРЕЛА - (наКрюке ? Я.h / 2 : 0), 50, 430);
    }
    // тележка: скорость к цели, разгон ограничен
    const желаю = ограничить((цельX - тх) * 3.2, -270, 270);
    та = ограничить((желаю - тv) / dt, -650, 650);
    тv += та * dt;
    тх = ограничить(тх + тv * dt, 90, 880);
    // лебёдка
    const Lбыло = L;
    L = L + ограничить(цельL - L, -лебёдка * dt, лебёдка * dt);
    const Lv = (L - Lбыло) / dt;
    // маятник переменной длины под разгоняющейся опорой
    const кБыло = крюк();
    const θбыло = θ;
    const α = (-Г * Math.sin(θ) - та * Math.cos(θ) - 2 * Lv * ω) / L - гашение * ω;
    ω += α * dt;
    θ += ω * dt;
    let к = крюк();
    const груз = !!наКрюке;
    // столкновения: сверху — встал (канат провис), сбоку — отскок
    for (const т of твёрдые()) {
      const р = рамка(к, груз);
      if (!пересёк(р, т)) continue;
      const низБыл = рамка(кБыло, груз).y2;
      const vy = (к.y - кБыло.y) / dt;
      const vx = (к.x - кБыло.x) / dt;
      if (низБыл <= т.y1 + 3) {
        const нужно = т.y1 - (р.y2 - р.y1);
        L = Math.max(30, (нужно - СТРЕЛА) / Math.max(0.2, Math.cos(θ)));
        ω *= 0.9;
        к = крюк();
        if (!груз) continue;
        if (т.вид === 'вода' && !наКрюке.вода) {
          наКрюке.вода = true;
          поле.слово('в воду!', к.x, ВОДА - 30, ЦВЕТ.море, 30);
          звуки.мимо();
          поле.вспышка(ЦВЕТ.море, 0.15);
        } else if (т.вид === 'трюм') {
          поставить(наКрюке, к, vy, vx);
          return;
        } else if (vy > мягко + 30) {
          наКрюке.стуков++;
          поле.слово('стук', к.x, т.y1 - 50, ЦВЕТ.ржа, 22);
          звуки.стук();
          поле.дрожь(4);
        }
      } else {
        θ = θбыло;
        ω = -ω * 0.3;
        к = крюк();
        if (груз && Math.abs(vx) > 50) {
          наКрюке.стуков++;
          поле.слово('о борт!', к.x, к.y - 20, ЦВЕТ.ржа, 24);
          звуки.стук();
          поле.дрожь(5);
        }
      }
    }
    // пустой крюк цепляет следующий ящик на пирсе
    if (!наКрюке && пауза <= 0) {
      const след = ящики.find(я => я.где === 'пирс');
      const скорость = Math.hypot(к.x - кБыло.x, к.y - кБыло.y) / dt;
      if (след && Math.abs(к.x - след.x) < 20 + 4 * н && Math.abs(к.y + 10 - след.y) < 16 && скорость < 140) {
        наКрюке = след;
        след.где = 'крюк';
        L = след.y - СТРЕЛА;
        θ = Math.asin(ограничить((след.x - тх) / L, -0.9, 0.9));
        ω = 0;
        звуки.тик(0.3);
        поле.слово('зацепил', след.x, след.y - 30, ЦВЕТ.бумага, 20);
      }
    }
  }

  function ящик(ctx, x, y, ярко = false, мокрый = false) {
    ctx.fillStyle = мокрый ? '#5a5244' : ярко ? '#9a7a4c' : '#86683f';
    ctx.fillRect(x - Я.w / 2, y, Я.w, Я.h);
    ctx.strokeStyle = 'rgba(30,20,10,.75)';
    ctx.lineWidth = 2;
    ctx.strokeRect(x - Я.w / 2 + 1, y + 1, Я.w - 2, Я.h - 2);
    ctx.beginPath();
    ctx.moveTo(x - Я.w / 2 + 3, y + 3);
    ctx.lineTo(x + Я.w / 2 - 3, y + Я.h - 3);
    ctx.moveTo(x - Я.w / 2, y + Я.h / 2);
    ctx.lineTo(x + Я.w / 2, y + Я.h / 2);
    ctx.stroke();
    ctx.fillStyle = 'rgba(255,230,180,.18)';
    ctx.fillRect(x - Я.w / 2, y, Я.w, 3);
  }

  function нарисовать(ctx, t) {
    фон(ctx, доки, 0.72);
    // вода
    ctx.fillStyle = 'rgba(30,58,64,.9)';
    ctx.fillRect(0, ВОДА, ШИР, ВЫС - ВОДА);
    ctx.strokeStyle = 'rgba(147,199,194,.35)';
    ctx.lineWidth = 1.5;
    for (let r = 0; r < 4; r++) {
      ctx.beginPath();
      for (let x = 0; x <= ШИР; x += 12) ctx.lineTo(x, ВОДА + 6 + r * 20 + Math.sin(x / 40 + t * 1.6 + r) * 2.5);
      ctx.stroke();
    }
    // пирс
    ctx.fillStyle = '#4a3825';
    ctx.fillRect(0, ПИРС, 300, 14);
    ctx.fillStyle = '#2e2216';
    for (let x = 20; x < 300; x += 70) ctx.fillRect(x, ПИРС + 14, 12, ВЫС - ПИРС);
    // корпус судна
    ctx.fillStyle = '#3a2a1b';
    ctx.beginPath();
    ctx.moveTo(530, ПАЛУБА - 6);
    ctx.lineTo(950, ПАЛУБА - 6);
    ctx.lineTo(935, ВЫС);
    ctx.lineTo(555, ВЫС);
    ctx.closePath();
    ctx.fill();
    ctx.fillStyle = '#17110b';
    ctx.fillRect(618, ПАЛУБА, 234, ДНО - ПАЛУБА);
    ctx.fillStyle = '#5b452c';
    ctx.fillRect(530, ПАЛУБА - 8, 88, 10);
    ctx.fillRect(852, ПАЛУБА - 8, 98, 10);
    ctx.fillStyle = '#2b2015';
    ctx.fillRect(618, ДНО, 234, 8);
    // меты гнёзд мелом
    const своб = свободные();
    for (const г of ГНЁЗДА) {
      const есть = своб.includes(г);
      ctx.strokeStyle = есть ? `rgba(239,227,201,${0.45 + 0.25 * Math.sin(t * 3)})` : 'rgba(239,227,201,.15)';
      ctx.lineWidth = 2;
      ctx.beginPath();
      ctx.moveTo(г - Я.w / 2, ДНО - 2);
      ctx.lineTo(г - Я.w / 2 + 10, ДНО - 2);
      ctx.moveTo(г + Я.w / 2 - 10, ДНО - 2);
      ctx.lineTo(г + Я.w / 2, ДНО - 2);
      ctx.moveTo(г, ДНО - 8);
      ctx.lineTo(г, ДНО - 2);
      ctx.stroke();
    }
    // стрела
    ctx.fillStyle = '#2e2216';
    ctx.fillRect(40, 30, 16, ВОДА - 30);
    ctx.fillStyle = '#5b452c';
    ctx.fillRect(40, СТРЕЛА - 10, 870, 12);
    ctx.fillStyle = 'rgba(255,230,180,.2)';
    ctx.fillRect(40, СТРЕЛА - 10, 870, 3);
    ctx.strokeStyle = 'rgba(200,180,140,.35)';
    ctx.lineWidth = 1.5;
    ctx.beginPath();
    ctx.moveTo(48, 30);
    ctx.lineTo(905, СТРЕЛА - 10);
    ctx.stroke();
    // ящики на пирсе и в трюме
    for (const я of ящики) if (я.где !== 'крюк') ящик(ctx, я.x, я.y, false, я.вода);
    const след = !наКрюке && ящики.find(я => я.где === 'пирс');
    if (след) {
      ctx.strokeStyle = `rgba(231,178,99,${0.4 + 0.3 * Math.sin(t * 5)})`;
      ctx.lineWidth = 2;
      ctx.strokeRect(след.x - Я.w / 2 - 4, след.y - 4, Я.w + 8, Я.h + 8);
    }
    // тележка, канат, крюк
    const к = крюк();
    ctx.fillStyle = '#7a6040';
    ctx.fillRect(тх - 16, СТРЕЛА - 14, 32, 18);
    ctx.fillStyle = ЦВЕТ.свеча;
    ctx.beginPath();
    ctx.arc(тх, СТРЕЛА + 6, 6, 0, Math.PI * 2);
    ctx.fill();
    ctx.strokeStyle = '#c7b48c';
    ctx.lineWidth = 2;
    ctx.beginPath();
    ctx.moveTo(тх, СТРЕЛА + 6);
    ctx.lineTo(к.x, к.y);
    ctx.stroke();
    if (наКрюке) {
      ctx.save();
      ctx.translate(к.x, к.y);
      ctx.rotate(-θ * 0.25);
      ящик(ctx, 0, 0, true, наКрюке.вода);
      ctx.restore();
    } else {
      ctx.strokeStyle = '#c7b48c';
      ctx.lineWidth = 3;
      ctx.beginPath();
      ctx.arc(к.x, к.y + 6, 6, 0, Math.PI * 1.2);
      ctx.stroke();
    }
    // куда указываешь
    ctx.strokeStyle = 'rgba(239,227,201,.25)';
    ctx.setLineDash([4, 6]);
    ctx.beginPath();
    ctx.moveTo(цельX, СТРЕЛА + 8);
    ctx.lineTo(цельX, СТРЕЛА + цельL + (наКрюке ? Я.h / 2 : 0));
    ctx.stroke();
    ctx.setLineDash([]);
    // табло
    плашка(ctx, 70, 96, 220, 62);
    надпись(ctx, 'в трюме', 86, 114, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.свеча, выр: 'left' });
    надпись(ctx, `${вТрюме()} из ${ящики.length}`, 274, 114, { р: 18, выр: 'right', вес: 700 });
    const качка = Math.abs(ω) * L;
    надпись(ctx, качка < 25 ? 'висит ровно' : качка < 80 ? 'покачивается' : 'раскачался', 86, 140, { р: 16, выр: 'left', цвет: качка < 25 ? ЦВЕТ.трава : качка < 80 ? ЦВЕТ.свеча : ЦВЕТ.ржа });
    плашка(ctx, ШИР - 250, 96, 220, 48);
    надпись(ctx, 'старший у трапа', ШИР - 236, 112, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо, выр: 'left' });
    const доля = время / терпение;
    полоса(ctx, ШИР - 236, 124, 192, 10, доля, доля > 0.75 ? ЦВЕТ.ржа : доля > 0.45 ? ЦВЕТ.свеча : ЦВЕТ.бумага2);
    if (сказЖизнь > 0) {
      ctx.globalAlpha = Math.min(1, сказЖизнь);
      плашка(ctx, ШИР - 330, 152, 300, 38, { заливка: 'rgba(239,227,201,.92)', обвод: ЦВЕТ.чернила });
      надпись(ctx, `«${сказ}»`, ШИР - 180, 171, { р: 17, цвет: ЦВЕТ.чернила, тень: false });
      ctx.globalAlpha = 1;
    }
  }

  поле.кадр(нарисовать);
  await поле.старт({
    заголовок: 'Тали',
    строка: 'Разгрузка в доках: три ящика с пирса — в трюм, по меловым метам. Груз на канате качается; старший смотрит, чтобы ничего не стукнуло о борт и не ушло в воду. Повезёт с руками — позовут ещё.',
  });
  поле.отладка = () => ({ тх, θ, ω, L, крюк: крюк(), наКрюке: наКрюке && ящики.indexOf(наКрюке), ящики, время, свободные: свободные() });

  return поле.играть({
    обновить: шаг,
    нарисовать,
    мышьДвиг() { клавишами = false; },
    клавиша(код) {
      if (/^Arrow|^Key[WASD]$/.test(код)) {
        if (!клавишами) { цельX = тх; цельL = L; }
        клавишами = true;
      }
    },
  }, [0.5, 0.8]);
}
