// Вёсла — рыбацкий берег, вид сверху. Лодка с двумя вёслами: левое весло (A / левая кнопка) толкает вперёд
// и разворачивает вправо, правое (D / правая кнопка) — влево; оба разом — прямо, а взятые в лад тянут сильнее.
// Посреди бухты течение сносит вбок. Пройди три пары вех и мягко подойди к лодке у сетей.
import {
  ЦВЕТ, ШИР, ВЫС, ШРИФТ, звуки, ступеньНавыка, создатьПоле, надпись, плашка, полоса,
  ограничить, звук,
} from './общее.js';

export const ОПИСЬ = { id: 'вёсла', имя: 'Вёсла', где: 'Рыбацкий берег' };
export const СМЫСЛ = {
  плохо: 'Лодку носило по бухте, вехи прошли мимо. Рыбаки смеялись с берега.',
  нормально: 'Добрался, пусть и кругами. Сеть передана, рыбак кивнул.',
  отлично: 'Прошёл вехи по струнке и подошёл борт к борту. Рыбаки зовут ещё.',
};
// Ремесла гребца в игре нет — навык живого слоя пока не растёт (решено за автора).
export const навык = () => 0;

const ГРЕБОК = 0.5;
const ВОЗВРАТ = 0.4;
const ТЯГА = 115;
const ПОВОРОТ = 2.0;
const ЛАД = 0.13; // насколько вместе надо взять вёсла
const R_ЛОДКА = 16;
const СТАРТ = { x: 120, y: 470 };
const ФИНИШ = { x: 862, y: 84 };
const КАМНИ = [{ x: 405, y: 300, r: 24 }, { x: 650, y: 255, r: 20 }, { x: 800, y: 300, r: 26 }, { x: 330, y: 160, r: 18 }];

export async function запустить(контейнер, { навык = 0, тихо = false, сигнал } = {}) {
  const н = ступеньНавыка(навык);
  звук.тихо = тихо;
  const поле = создатьПоле(контейнер, { подсказка: 'A или левая кнопка — левое весло (лодка вправо), D или правая — правое (лодка влево). Оба разом — прямо, в лад — сильнее. Течение сносит вправо.', сигнал });

  const течение = [55, 42, 30][н];
  const ширина = 120 + 25 * н;
  const мягко = 60 + 20 * н;
  const терпение = 90 + 10 * н;
  const ВЕХИ = [
    { x: 250, y: 330, гор: true },
    { x: 540, y: 190, гор: false },
    { x: 720, y: 420, гор: true },
  ].map(в => ({ ...в, a: в.гор ? { x: в.x - ширина / 2, y: в.y } : { x: в.x, y: в.y - ширина / 2 }, b: в.гор ? { x: в.x + ширина / 2, y: в.y } : { x: в.x, y: в.y + ширина / 2 }, итог: null }));

  const л = { x: СТАРТ.x, y: СТАРТ.y, vx: 0, vy: 0, ψ: 0, ω: 0 };
  const вёсла = { лев: { фаза: 'ждёт', t: 0, сила: 1, начал: -9 }, прав: { фаза: 'ждёт', t: 0, сила: 1, начал: -9 } };
  let текВеха = 0;
  let сторона = null;
  let камней = 0, вЛад = 0;
  let время = 0;
  let удар = 0;
  const брызги = [];

  const ток = y => (y > 140 && y < 420 ? течение * Math.sin(Math.PI * (y - 140) / 280) : 4);
  const вперёд = () => ({ x: Math.sin(л.ψ), y: -Math.cos(л.ψ) });
  const бок = (p, a, b) => Math.sign((b.x - a.x) * (p.y - a.y) - (b.y - a.y) * (p.x - a.x));

  function грести(какое) {
    const в = вёсла[какое];
    if (в.фаза !== 'ждёт') return;
    в.фаза = 'гребок';
    в.t = 0;
    в.начал = время;
    в.сила = 1;
    const другое = вёсла[какое === 'лев' ? 'прав' : 'лев'];
    if (другое.фаза === 'гребок' && время - другое.начал <= ЛАД) {
      в.сила = другое.сила = 1.25;
      вЛад++;
      поле.слово('в лад', л.x, л.y - 36, ЦВЕТ.трава, 18);
    }
    звуки.хлоп();
  }

  function итог(дошёл, скорость) {
    const прошёл = ВЕХИ.filter(в => в.итог === 'да').length;
    const вехи = прошёл / ВЕХИ.length;
    const скоро = ограничить(1 - (время - 35) / 50, 0, 1);
    const подход = !дошёл ? 0 : скорость <= мягко ? 1 : ограничить(1 - (скорость - мягко) / 90, 0.2, 1);
    поле.конец(0.4 * вехи + 0.25 * скоро + 0.35 * подход - 0.08 * камней);
  }

  function шаг(dt) {
    время += dt;
    удар = Math.max(0, удар - dt);
    if (время >= терпение) { поле.слово('Темнеет, хватит', ШИР / 2, ВЫС / 2, ЦВЕТ.ржа, 30); итог(false, 0); return; }
    const f = вперёд();
    const r = { x: -f.y, y: f.x };
    let ax = 0, ay = 0, α = 0;
    for (const [имя, в] of Object.entries(вёсла)) {
      в.t += dt;
      if (в.фаза === 'гребок') {
        const усилие = Math.sin(Math.PI * в.t / ГРЕБОК) * в.сила;
        ax += f.x * ТЯГА * усилие;
        ay += f.y * ТЯГА * усилие;
        α += (имя === 'лев' ? 1 : -1) * ПОВОРОТ * усилие;
        if (Math.random() < dt * 14) брызги.push({ x: л.x - r.x * (имя === 'лев' ? 34 : -34), y: л.y - r.y * (имя === 'лев' ? 34 : -34), жизнь: 1 });
        if (в.t >= ГРЕБОК) { в.фаза = 'возврат'; в.t = 0; }
      } else if (в.фаза === 'возврат' && в.t >= ВОЗВРАТ) { в.фаза = 'ждёт'; в.t = 0; }
    }
    // вода тормозит: вдоль корпуса слабо, поперёк сильно
    const ux = л.vx - ток(л.y), uy = л.vy;
    const uf = ux * f.x + uy * f.y;
    const ur = ux * r.x + uy * r.y;
    ax += -0.7 * uf * f.x - 3 * ur * r.x;
    ay += -0.7 * uf * f.y - 3 * ur * r.y;
    л.vx += ax * dt;
    л.vy += ay * dt;
    л.ω += (α - 2.5 * л.ω) * dt;
    л.ψ += л.ω * dt;
    л.x += л.vx * dt;
    л.y += л.vy * dt;
    // края бухты и берег
    if (л.x < R_ЛОДКА || л.x > ШИР - R_ЛОДКА) { л.x = ограничить(л.x, R_ЛОДКА, ШИР - R_ЛОДКА); л.vx *= -0.3; }
    if (л.y < R_ЛОДКА || л.y > ВЫС - 40) { л.y = ограничить(л.y, R_ЛОДКА, ВЫС - 40); л.vy *= -0.3; }
    for (const к of КАМНИ) {
      const dx = л.x - к.x, dy = л.y - к.y;
      const д = Math.hypot(dx, dy) || 0.01;
      if (д < к.r + R_ЛОДКА) {
        л.x = к.x + dx / д * (к.r + R_ЛОДКА);
        л.y = к.y + dy / д * (к.r + R_ЛОДКА);
        const vn = (л.vx * dx + л.vy * dy) / д;
        if (vn < 0) { л.vx -= 1.4 * vn * dx / д; л.vy -= 1.4 * vn * dy / д; }
        л.vx *= 0.5;
        л.vy *= 0.5;
        if (удар <= 0 && Math.abs(vn) > 20) {
          камней++;
          удар = 0.8;
          звуки.стук();
          поле.дрожь(5);
          поле.слово('камень!', л.x, л.y - 30, ЦВЕТ.ржа, 22);
        }
      }
    }
    // вехи по порядку
    const в = ВЕХИ[текВеха];
    if (в) {
      if (Math.hypot(л.x - в.x, л.y - в.y) >= ширина) сторона = null;
      else {
        const с = бок(л, в.a, в.b);
        if (сторона !== null && с !== 0 && с !== сторона) {
          const t = в.гор ? (л.x - в.a.x) / ширина : (л.y - в.a.y) / ширина;
          в.итог = t >= 0 && t <= 1 ? 'да' : 'мимо';
          if (в.итог === 'да') { звуки.звон(1100); поле.кольцо(в.x, в.y, ЦВЕТ.трава, ширина / 2); }
          else { звуки.мимо(); поле.слово('мимо вех', в.x, в.y - 30, ЦВЕТ.ржа, 22); }
          текВеха++;
          сторона = null;
        } else if (с !== 0) сторона = с;
      }
    }
    // подход к лодке у сетей
    if (Math.hypot(л.x - ФИНИШ.x, л.y - ФИНИШ.y) < 40) {
      const с = Math.hypot(л.vx - ток(л.y), л.vy);
      for (const вв of ВЕХИ) if (!вв.итог) вв.итог = 'мимо';
      поле.слово(с <= мягко ? 'борт к борту' : 'ткнулся носом', ФИНИШ.x - 60, ФИНИШ.y + 50, с <= мягко ? ЦВЕТ.трава : ЦВЕТ.свеча, 24);
      if (с > мягко) { звуки.стук(); поле.дрожь(5); } else звуки.ура();
      итог(true, с);
    }
    for (const б of брызги) б.жизнь -= dt * 1.5;
    while (брызги.length && брызги[0].жизнь <= 0) брызги.shift();
  }

  function лодка(ctx, x, y, ψ, свои) {
    ctx.save();
    ctx.translate(x, y);
    ctx.rotate(ψ);
    if (свои) {
      for (const [имя, зн] of [['лев', -1], ['прав', 1]]) {
        const в = вёсла[имя];
        const мах = в.фаза === 'гребок' ? -0.7 + 1.4 * (в.t / ГРЕБОК) : в.фаза === 'возврат' ? 0.7 - 1.4 * (в.t / ВОЗВРАТ) : -0.2;
        ctx.save();
        ctx.translate(зн * 9, 0);
        ctx.rotate(зн * мах * -0.6);
        ctx.fillStyle = '#b39466';
        ctx.fillRect(зн > 0 ? 0 : -34, -1.5, 34, 3);
        ctx.fillRect(зн > 0 ? 28 : -40, -4, 12, 8);
        ctx.restore();
      }
    }
    ctx.fillStyle = свои ? '#8a6a42' : '#5d4a33';
    ctx.beginPath();
    ctx.moveTo(0, -26);
    ctx.quadraticCurveTo(12, -12, 10, 18);
    ctx.lineTo(-10, 18);
    ctx.quadraticCurveTo(-12, -12, 0, -26);
    ctx.fill();
    ctx.fillStyle = 'rgba(20,14,8,.6)';
    ctx.fillRect(-7, -4, 14, 3);
    ctx.fillRect(-7, 8, 14, 3);
    if (свои) {
      ctx.fillStyle = ЦВЕТ.свеча;
      ctx.beginPath();
      ctx.arc(0, 3, 4.5, 0, Math.PI * 2);
      ctx.fill();
    }
    ctx.restore();
  }

  function нарисовать(ctx, t) {
    const г = ctx.createLinearGradient(0, 0, 0, ВЫС);
    г.addColorStop(0, '#0f2a2e');
    г.addColorStop(1, '#173a3c');
    ctx.fillStyle = г;
    ctx.fillRect(0, 0, ШИР, ВЫС);
    // струи течения
    ctx.strokeStyle = 'rgba(147,199,194,.16)';
    ctx.lineWidth = 1.5;
    for (let i = 0; i < 26; i++) {
      const y = 150 + (i * 37) % 260;
      const v = ток(y);
      const x = ((i * 173 + t * v * 1.4) % (ШИР + 80)) - 40;
      ctx.beginPath();
      ctx.moveTo(x, y);
      ctx.lineTo(x + 20 + v * 0.5, y);
      ctx.stroke();
    }
    надпись(ctx, 'течение →', 20, 160, { р: 13, шрифт: ШРИФТ.метка, цвет: 'rgba(147,199,194,.55)', выр: 'left' });
    // берег и мостки
    ctx.fillStyle = '#4b4232';
    ctx.beginPath();
    ctx.moveTo(0, ВЫС);
    ctx.lineTo(0, 440);
    ctx.quadraticCurveTo(160, 500, 330, ВЫС);
    ctx.fill();
    ctx.fillStyle = '#5b452c';
    ctx.fillRect(СТАРТ.x - 12, СТАРТ.y + 18, 24, 60);
    // камни
    for (const к of КАМНИ) {
      ctx.fillStyle = 'rgba(147,199,194,.12)';
      ctx.beginPath();
      ctx.arc(к.x, к.y, к.r + 6 + Math.sin(t * 2 + к.x) * 2, 0, Math.PI * 2);
      ctx.fill();
      ctx.fillStyle = '#3b3a35';
      ctx.beginPath();
      ctx.arc(к.x, к.y, к.r, 0, Math.PI * 2);
      ctx.fill();
      ctx.fillStyle = 'rgba(255,240,210,.1)';
      ctx.beginPath();
      ctx.arc(к.x - к.r * 0.3, к.y - к.r * 0.3, к.r * 0.45, 0, Math.PI * 2);
      ctx.fill();
    }
    // вехи
    ВЕХИ.forEach((в, i) => {
      const тек = i === текВеха;
      const цв = в.итог === 'да' ? ЦВЕТ.трава : в.итог === 'мимо' ? 'rgba(224,127,98,.5)' : тек ? ЦВЕТ.ржа : 'rgba(224,127,98,.55)';
      ctx.strokeStyle = тек ? 'rgba(239,227,201,.45)' : 'rgba(239,227,201,.15)';
      ctx.setLineDash([3, 5]);
      ctx.lineWidth = 1.5;
      ctx.beginPath();
      ctx.moveTo(в.a.x, в.a.y);
      ctx.lineTo(в.b.x, в.b.y);
      ctx.stroke();
      ctx.setLineDash([]);
      for (const p of [в.a, в.b]) {
        ctx.fillStyle = цв;
        ctx.beginPath();
        ctx.arc(p.x, p.y + Math.sin(t * 2.4 + p.x) * 1.5, тек ? 8 : 6, 0, Math.PI * 2);
        ctx.fill();
      }
      надпись(ctx, String(i + 1), в.x, в.y + (в.гор ? -16 : 0), { р: 14, шрифт: ШРИФТ.метка, цвет: тек ? ЦВЕТ.бумага : ЦВЕТ.тихо });
    });
    // лодка у сетей
    ctx.strokeStyle = 'rgba(239,227,201,.25)';
    ctx.setLineDash([2, 4]);
    ctx.beginPath();
    ctx.arc(ФИНИШ.x, ФИНИШ.y, 40, 0, Math.PI * 2);
    ctx.stroke();
    ctx.setLineDash([]);
    лодка(ctx, ФИНИШ.x + 30, ФИНИШ.y - 6, 1.3, false);
    надпись(ctx, 'лодка у сетей', ФИНИШ.x - 20, ФИНИШ.y + 56, { р: 13, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо });
    // брызги и своя лодка
    for (const б of брызги) {
      ctx.strokeStyle = `rgba(220,240,235,${б.жизнь * 0.6})`;
      ctx.lineWidth = 1.5;
      ctx.beginPath();
      ctx.arc(б.x, б.y, 4 + (1 - б.жизнь) * 12, 0, Math.PI * 2);
      ctx.stroke();
    }
    лодка(ctx, л.x, л.y, л.ψ, true);
    // табло
    плашка(ctx, 20, 20, 260, 74);
    надпись(ctx, 'вехи', 36, 38, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.свеча, выр: 'left' });
    надпись(ctx, ВЕХИ.map(в => (в.итог === 'да' ? '●' : в.итог === 'мимо' ? '×' : '○')).join(' '), 264, 38, { р: 18, выр: 'right' });
    надпись(ctx, `в лад ${вЛад} · камней ${камней}`, 36, 62, { р: 15, выр: 'left', цвет: камней ? ЦВЕТ.ржа : ЦВЕТ.тихо });
    полоса(ctx, 36, 78, 228, 6, время / терпение, время / терпение > 0.75 ? ЦВЕТ.ржа : ЦВЕТ.бумага2);
    // вёсла: готовы ли
    for (const [имя, x] of [['лев', 310], ['прав', 380]]) {
      const в = вёсла[имя];
      плашка(ctx, x, 20, 60, 40, { заливка: в.фаза === 'ждёт' ? 'rgba(231,178,99,.18)' : 'rgba(13,19,22,.7)' });
      надпись(ctx, имя === 'лев' ? 'A' : 'D', x + 30, 40, { р: 20, шрифт: ШРИФТ.метка, вес: 700, цвет: в.фаза === 'ждёт' ? ЦВЕТ.свеча : ЦВЕТ.тихо });
    }
  }

  поле.кадр(нарисовать);
  await поле.старт({
    заголовок: 'Вёсла',
    строка: 'Рыбацкий берег: рыбаки просят отвезти починенную сеть к лодке в бухте. Пройди три пары вех, не задень камни и подойди к борту мягко. Посреди бухты течение — оно сносит вправо.',
  });
  поле.отладка = () => ({ л, вёсла, веха: текВеха, вехи: ВЕХИ, камней, вЛад, время, финиш: ФИНИШ });

  return поле.играть({
    обновить: шаг,
    нарисовать,
    мышьВниз(x, y, кн) { грести(кн === 2 ? 'прав' : 'лев'); },
    клавиша(код) {
      if (['KeyA', 'KeyQ', 'ArrowLeft'].includes(код)) грести('лев');
      else if (['KeyD', 'KeyE', 'ArrowRight'].includes(код)) грести('прав');
    },
  }, [0.45, 0.78]);
}
