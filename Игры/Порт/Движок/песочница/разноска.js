// Разноска — рынок в полдень, вид сверху. Несёшь свёртки к прилавкам по очереди сквозь толпу:
// герой идёт за указателем (или WASD/стрелки), люди и тележки движутся своими путями.
// Толкнул кого-то — встал и корзина дрогнула; второй толчок подряд — свёрток упал, надо собрать.
// «Посторонись!» (пробел или правая кнопка) раздвигает ближних, но голоса хватит на три окрика.
import {
  ЦВЕТ, ШИР, ВЫС, ШРИФТ, звуки, ступеньНавыка, создатьПоле, картинка, фон, надпись, плашка, полоса,
  ограничить, случайно, выбрать, звук,
} from './общее.js';

export const ОПИСЬ = { id: 'разноска', имя: 'Разноска', где: 'Рынок в полдень' };
export const СМЫСЛ = {
  плохо: 'Свёртки дошли помятыми и поздно, по дороге ты толкнул половину рынка.',
  нормально: 'Всё разнесено, пусть и с толчками. Лавочники платят как договаривались.',
  отлично: 'Быстро и ни одного толчка — лавочники запомнят, кого звать в другой раз.',
};
// Разноска — работа без ремесла; навык живого слоя пока не растёт (решено за автора).
export const навык = () => 0;

const ТОВАРЫ = ['рыба', 'хлеб', 'ткань', 'горшки', 'соль', 'верёвки'];
const ЛАВКИ = ТОВАРЫ.map((т, i) => {
  const верх = i < 3;
  const x = 170 + (i % 3) * 310;
  return { товар: т, x, y: верх ? 52 : ВЫС - 52, вход: { x, y: верх ? 118 : ВЫС - 118 }, верх };
});
const ДОСТАВОК = 5;
const R_ГЕРОЙ = 13;

export async function запустить(контейнер, { навык = 0, тихо = false, сигнал } = {}) {
  const н = ступеньНавыка(навык);
  звук.тихо = тихо;
  const поле = создатьПоле(контейнер, { подсказка: 'Веди героя указателем мыши (или WASD/стрелки) к светящемуся прилавку. Не толкай людей. Пробел или правая кнопка — «Посторонись!», три раза.', сигнал });
  const площадь = await картинка('Ресурсы/Места/торговая-площадь.png');

  const темп = 1 - 0.15 * н;
  const ГЕРОЙ_V = 160;
  const терпение = 75 + 10 * н;

  const герой = { x: 34, y: ВЫС / 2, vx: 0, vy: 0, стоп: 0, собирает: 0 };
  const люди = Array.from({ length: 36 - 8 * н }, (_, i) => {
    // половина идёт сквозь рынок потоком (от края к краю), остальные бродят между прилавками
    const ч = { поток: i % 2 === 0, x: случайно(120, ШИР - 40), y: случайно(140, ВЫС - 140), r: 12 + Math.random() * 4, v: случайно(50, 100) * темп, цвет: выбрать(['#4a4136', '#3b4446', '#55473a', '#40393f', '#4b4a3a']), пауза: 0, окрик: 0, тол: 0 };
    новаяЦель(ч);
    return ч;
  });
  const тележки = [0, 1, 2].map(i => ({ x: [160, ШИР - 120, 480][i], y: [330, 210, 270][i], r: 26, v: [38, 44, 30][i] * темп, dir: i === 1 ? -1 : 1, тол: 0 }));
  let клавишами = false;
  let цель = ЛАВКИ[выбрать([0, 3])];
  let доставлено = 0;
  let начатоДоставка = 0;
  let пар = 0;
  const итоги = [];
  let толчков = 0, подряд = 0, уронил = 0, когдаТолкнул = -9;
  let окриков = 3;
  let время = 0;
  let волна = null;

  function новаяЦель(ч) {
    if (ч.поток) {
      ч.цх = ч.x < ШИР / 2 ? случайно(ШИР - 120, ШИР - 30) : случайно(70, 160);
      ч.цу = ограничить(ч.y + случайно(-50, 50), 150, ВЫС - 150);
    } else {
      ч.цх = случайно(90, ШИР - 40);
      ч.цу = случайно(150, ВЫС - 150);
    }
  }
  function начатьДоставку() {
    начатоДоставка = время;
    пар = Math.hypot(цель.вход.x - герой.x, цель.вход.y - герой.y) / (ГЕРОЙ_V * 0.8) + 0.8;
  }
  начатьДоставку();

  function окрик() {
    if (окриков <= 0 || герой.собирает > 0) return;
    окриков--;
    волна = { x: герой.x, y: герой.y, жизнь: 1 };
    звуки.струна(330, 0.3);
    поле.слово('Посторонись!', герой.x, герой.y - 34, ЦВЕТ.бумага, 22);
    for (const ч of люди) {
      const d = Math.hypot(ч.x - герой.x, ч.y - герой.y);
      if (d < 150) { ч.окрик = 1.2; ч.ox = (ч.x - герой.x) / (d || 1); ч.oy = (ч.y - герой.y) / (d || 1); }
    }
  }

  function толкнул(кто, сильно) {
    кто.тол = 0.8;
    толчков++;
    подряд = время - когдаТолкнул < 3 ? подряд + 1 : 1;
    когдаТолкнул = время;
    герой.стоп = 0.35;
    звуки.стук();
    поле.дрожь(сильно ? 5 : 3);
    поле.слово(выбрать(['эй!', 'смотри куда прёшь', 'ну!', 'полегче']), кто.x, кто.y - 26, ЦВЕТ.ржа, 18);
    if (подряд >= 2) {
      подряд = 0;
      уронил++;
      герой.собирает = 1.4;
      звуки.мимо();
      поле.слово('свёрток упал', герой.x, герой.y - 40, ЦВЕТ.ржа, 24);
    }
  }

  function итог() {
    while (итоги.length < ДОСТАВОК) итоги.push(0);
    const ср = итоги.reduce((с, о) => с + о, 0) / ДОСТАВОК;
    поле.конец(ср - 0.05 * толчков - 0.1 * уронил);
  }

  function шаг(dt) {
    время += dt;
    if (время >= терпение) { поле.слово('Рынок закрывается', ШИР / 2, ВЫС / 2, ЦВЕТ.ржа, 30); итог(); return; }
    if (волна) { волна.жизнь -= dt * 1.6; if (волна.жизнь <= 0) волна = null; }
    // герой
    герой.стоп = Math.max(0, герой.стоп - dt);
    герой.собирает = Math.max(0, герой.собирает - dt);
    let жx = 0, жy = 0;
    if (клавишами) {
      const к = поле.клавиши;
      жx = (к.has('ArrowRight') || к.has('KeyD') ? 1 : 0) - (к.has('ArrowLeft') || к.has('KeyA') ? 1 : 0);
      жy = (к.has('ArrowDown') || к.has('KeyS') ? 1 : 0) - (к.has('ArrowUp') || к.has('KeyW') ? 1 : 0);
      const д = Math.hypot(жx, жy) || 1;
      жx = жx / д * ГЕРОЙ_V;
      жy = жy / д * ГЕРОЙ_V;
    } else if (поле.мышь.внутри) {
      const dx = поле.мышь.x - герой.x, dy = поле.мышь.y - герой.y;
      const д = Math.hypot(dx, dy);
      const с = Math.min(ГЕРОЙ_V, д * 4);
      if (д > 2) { жx = dx / д * с; жy = dy / д * с; }
    }
    const множ = герой.собирает > 0 ? 0 : герой.стоп > 0 ? 0.35 : 1;
    const разгон = 900 * dt;
    герой.vx += ограничить(жx * множ - герой.vx, -разгон, разгон);
    герой.vy += ограничить(жy * множ - герой.vy, -разгон, разгон);
    герой.x = ограничить(герой.x + герой.vx * dt, R_ГЕРОЙ, ШИР - R_ГЕРОЙ);
    герой.y = ограничить(герой.y + герой.vy * dt, 92, ВЫС - 92);
    // толпа
    for (const ч of люди) {
      ч.тол = Math.max(0, ч.тол - dt);
      if (ч.окрик > 0) {
        ч.окрик -= dt;
        ч.x += ч.ox * 110 * dt;
        ч.y += ч.oy * 110 * dt;
      } else if (ч.пауза > 0) ч.пауза -= dt;
      else {
        const dx = ч.цх - ч.x, dy = ч.цу - ч.y;
        const д = Math.hypot(dx, dy);
        if (д < 8) { новаяЦель(ч); if (Math.random() < 0.4) ч.пауза = случайно(0.5, 2); }
        else { ч.x += dx / д * ч.v * dt; ч.y += dy / д * ч.v * dt; }
      }
      ч.x = ограничить(ч.x, 60, ШИР - 20);
      ч.y = ограничить(ч.y, 100, ВЫС - 100);
    }
    for (const т of тележки) {
      т.тол = Math.max(0, т.тол - dt);
      т.x += т.dir * т.v * dt;
      if (т.x > ШИР - 60 || т.x < 100) т.dir *= -1;
    }
    // столкновения героя
    const скорость = Math.hypot(герой.vx, герой.vy);
    for (const ч of [...люди, ...тележки]) {
      const dx = герой.x - ч.x, dy = герой.y - ч.y;
      const д = Math.hypot(dx, dy) || 0.01;
      const мин = R_ГЕРОЙ + ч.r - 2 - н;
      if (д < мин) {
        герой.x = ч.x + dx / д * мин;
        герой.y = ч.y + dy / д * мин;
        if (ч.тол <= 0 && скорость > 40) толкнул(ч, скорость > 120);
        герой.vx *= 0.3;
        герой.vy *= 0.3;
      }
    }
    // доставка
    if (Math.hypot(герой.x - цель.вход.x, герой.y - цель.вход.y) < 34 && герой.собирает <= 0) {
      const t = время - начатоДоставка;
      const о = ограничить(1 - Math.max(0, t - пар) / (пар * 1.2), 0.2, 1);
      итоги.push(о);
      доставлено++;
      подряд = 0;
      звуки.звон(о >= 0.85 ? 1250 : 990);
      поле.кольцо(цель.вход.x, цель.вход.y, о >= 0.85 ? ЦВЕТ.трава : ЦВЕТ.свеча, 60);
      поле.слово(о >= 0.85 ? 'вовремя!' : 'держи', цель.вход.x, цель.вход.y + (цель.верх ? 40 : -40), о >= 0.85 ? ЦВЕТ.трава : ЦВЕТ.бумага, 24);
      if (доставлено >= ДОСТАВОК) { итог(); return; }
      const прежняя = цель;
      цель = выбрать(ЛАВКИ.filter(л => л !== прежняя && Math.abs(л.x - прежняя.x) + Math.abs(л.y - прежняя.y) > 300));
      начатьДоставку();
    }
  }

  function нарисовать(ctx, t) {
    фон(ctx, площадь, 0.82);
    ctx.fillStyle = 'rgba(40,36,30,.55)';
    ctx.fillRect(0, 92, ШИР, ВЫС - 184);
    ctx.strokeStyle = 'rgba(226,198,146,.05)';
    ctx.lineWidth = 1;
    for (let x = 0; x < ШИР; x += 32) for (let y = 92 + ((x / 32) % 2) * 16; y < ВЫС - 92; y += 32) ctx.strokeRect(x + 2, y + 2, 28, 28);
    // ворота рынка
    надпись(ctx, 'ворота', 30, ВЫС / 2 - 40, { р: 13, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо, выр: 'left' });
    // лавки
    for (const л of ЛАВКИ) {
      const ярко = л === цель;
      const x0 = л.x - 70, y0 = л.верх ? 10 : ВЫС - 94;
      ctx.fillStyle = '#2f2419';
      ctx.fillRect(x0, y0, 140, 84);
      for (let i = 0; i < 7; i++) {
        ctx.fillStyle = i % 2 ? (ярко ? '#9a5a3c' : '#5d3b2a') : (ярко ? '#d8c39a' : '#7d705a');
        ctx.fillRect(x0 + i * 20, л.верх ? y0 + 60 : y0, 20, 24);
      }
      надпись(ctx, л.товар, л.x, л.верх ? y0 + 32 : y0 + 54, { р: 17, шрифт: ШРИФТ.метка, цвет: ярко ? ЦВЕТ.свеча : ЦВЕТ.бумага2, вес: 700 });
      if (ярко) {
        ctx.strokeStyle = `rgba(231,178,99,${0.5 + 0.4 * Math.sin(t * 5)})`;
        ctx.lineWidth = 2;
        ctx.beginPath();
        ctx.arc(л.вход.x, л.вход.y, 30 + Math.sin(t * 5) * 3, 0, Math.PI * 2);
        ctx.stroke();
      }
    }
    // окрик
    if (волна) {
      ctx.strokeStyle = `rgba(239,227,201,${волна.жизнь * 0.5})`;
      ctx.lineWidth = 2;
      ctx.beginPath();
      ctx.arc(волна.x, волна.y, 150 * (1 - волна.жизнь) + 20, 0, Math.PI * 2);
      ctx.stroke();
    }
    // тележки
    for (const т of тележки) {
      ctx.fillStyle = '#5a4329';
      ctx.fillRect(т.x - 34, т.y - 20, 68, 40);
      ctx.fillStyle = '#7d6a4a';
      ctx.fillRect(т.x - 28, т.y - 15, 26, 30);
      ctx.fillRect(т.x + 2, т.y - 15, 26, 30);
      ctx.fillStyle = '#1e1710';
      ctx.fillRect(т.x - 26, т.y - 25, 14, 6);
      ctx.fillRect(т.x + 12, т.y - 25, 14, 6);
      ctx.fillRect(т.x - 26, т.y + 19, 14, 6);
      ctx.fillRect(т.x + 12, т.y + 19, 14, 6);
    }
    // люди
    for (const ч of люди) {
      ctx.fillStyle = ч.цвет;
      ctx.beginPath();
      ctx.ellipse(ч.x, ч.y, ч.r + 4, ч.r - 2, 0, 0, Math.PI * 2);
      ctx.fill();
      ctx.fillStyle = ч.тол > 0 ? '#8a5a48' : '#6e5a48';
      ctx.beginPath();
      ctx.arc(ч.x, ч.y, ч.r * 0.55, 0, Math.PI * 2);
      ctx.fill();
    }
    // путь-подсказка и герой
    const dx = цель.вход.x - герой.x, dy = цель.вход.y - герой.y;
    const д = Math.hypot(dx, dy) || 1;
    ctx.fillStyle = 'rgba(231,178,99,.7)';
    ctx.beginPath();
    const ax = герой.x + dx / д * 30, ay = герой.y + dy / д * 30;
    ctx.moveTo(ax + dx / д * 8, ay + dy / д * 8);
    ctx.lineTo(ax - dy / д * 6, ay + dx / д * 6);
    ctx.lineTo(ax + dy / д * 6, ay - dx / д * 6);
    ctx.fill();
    const дрож = герой.стоп > 0 ? Math.sin(t * 60) * 2 : 0;
    ctx.fillStyle = ЦВЕТ.свеча;
    ctx.beginPath();
    ctx.arc(герой.x + дрож, герой.y, R_ГЕРОЙ, 0, Math.PI * 2);
    ctx.fill();
    ctx.fillStyle = '#8d6e44';
    ctx.fillRect(герой.x + дрож + 6, герой.y - 8, 14, 16);
    ctx.strokeStyle = ЦВЕТ.чернила;
    ctx.lineWidth = 1.5;
    ctx.strokeRect(герой.x + дрож + 6, герой.y - 8, 14, 16);
    if (герой.собирает > 0) {
      ctx.strokeStyle = ЦВЕТ.ржа;
      ctx.lineWidth = 3;
      ctx.beginPath();
      ctx.arc(герой.x, герой.y, 22, -Math.PI / 2, -Math.PI / 2 + Math.PI * 2 * (1 - герой.собирает / 1.4));
      ctx.stroke();
    }
    // табло — в просветах между нижними прилавками, чтобы не закрывать площадь
    плашка(ctx, 250, 456, 150, 74, { заливка: 'rgba(13,19,22,.8)' });
    надпись(ctx, `свёрток ${Math.min(доставлено + 1, ДОСТАВОК)} из ${ДОСТАВОК}`, 325, 476, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.свеча });
    надпись(ctx, `→ ${цель.товар}`, 325, 504, { р: 22, вес: 700 });
    плашка(ctx, 560, 456, 150, 74, { заливка: 'rgba(13,19,22,.8)' });
    надпись(ctx, `толчков ${толчков}`, 635, 474, { р: 16, цвет: толчков ? ЦВЕТ.ржа : ЦВЕТ.тихо });
    надпись(ctx, `окриков ${окриков}`, 635, 496, { р: 16, цвет: окриков ? ЦВЕТ.бумага2 : ЦВЕТ.тихо });
    полоса(ctx, 574, 512, 122, 6, время / терпение, время / терпение > 0.75 ? ЦВЕТ.ржа : ЦВЕТ.бумага2);
  }

  поле.кадр(нарисовать);
  await поле.старт({
    заголовок: 'Разноска',
    строка: 'Рынок в полдень: пять свёртков — по пяти прилавкам, а между ними толпа и тележки. Толкнёшь — помнёшь товар и потеряешь время; разносчика, который всех толкает, второй раз не позовут.',
  });
  поле.отладка = () => ({ люди, тележки, герой, цель: ЛАВКИ.indexOf(цель), вход: цель.вход, доставлено, толчков, уронил, окриков, итоги, время });

  return поле.играть({
    обновить: шаг,
    нарисовать,
    мышьДвиг() { клавишами = false; },
    мышьВниз(x, y, кн) { if (кн === 2) окрик(); },
    клавиша(код) {
      if (код === 'Space') окрик();
      else if (/^Arrow|^Key[WASD]$/.test(код)) клавишами = true;
    },
  }, [0.45, 0.78]);
}
