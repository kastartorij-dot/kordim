const ВРЕМЯ = 60;
const ЦЕЛ = 4; // сколько ударов герой держит
const ЦЕНТР = 480;
const УДАР_ДЛИТ = 0.16;
const МОЙ_УДАР = 0.3;
const УХОД = 0.45;
const ЦЕНА = { уход: 12, удар: 16 };

export async function запустить(контейнер, { навык = 0, тихо = false, сигнал, соперник } = {}) {
  const н = ступеньНавыка(навык);
  звук.тихо = тихо;
  const поле = создатьПоле(контейнер, {
    подсказка: 'Он замахивается — уйди в другую сторону (← →) или закройся (↓, держать). Промахнулся — раскрылся: бей (↑ или пробел). Q — выйти из круга.',
    сигнал,
  });
  const трущобы = await картинка('Ресурсы/Районы/трущобы.webp');

  const толпа = Array.from({ length: 15 }, (_, i) => ({
    x: 20 + i * 66 + случайно(-14, 14), y: случайно(318, 346), r: случайно(20, 27), фаза: случайно(0, 6),
  }));

  let С = СОПЕРНИКИ[соперник] ?? СОПЕРНИКИ.забияка;
  let медленно = false;

  // ---------- состояние ----------
  const я = { цел: ЦЕЛ, дыхание: 100, действие: null, блок: false, покой: 0, нанёс: 0, пропустил: 0 };
  const он = { цел: С.стойкость, фаза: 'стойка', вФазе: 0, длит: 1, атака: null, двойкаБыла: false, вЗащиту: 0, отдача: 0 };
  let время = 0;
  let вышел = false;
  let развязка = null; // { слово, цвет, очки, через }
  let реплика = '';
  let репликаЖизнь = 0;

  const сказать = (s, долго = 1.6) => { реплика = s; репликаЖизнь = долго; };
  const мн = {
    замах: () => (1 + 0.12 * н) * (медленно ? 1.8 : 1),
    раскрыт: () => (1 + 0.2 * н) * (медленно ? 1.5 : 1),
    уходОкно: () => (0.34 + 0.06 * н) * (медленно ? 1.4 : 1),
  };

  function фаза(ф, длит) { он.фаза = ф; он.вФазе = 0; он.длит = длит; }
  function стойка(короче = 1) { фаза('стойка', случайно(...С.пауза) * короче * (медленно ? 1.4 : 1)); }

  function начатьАтаку(быстро = false, безФинта = false) {
    const весы = Object.entries(С.стороны);
    let r = Math.random() * весы.reduce((с, [, в]) => с + в, 0);
    let сторона = весы[0][0];
    for (const [к, в] of весы) { r -= в; if (r <= 0) { сторона = к; break; } }
    он.атака = { сторона, финт: !безФинта && Math.random() < С.финт };
    фаза('замах', случайно(...С.замах) * мн.замах() * (быстро ? 0.72 : 1));
    звуки.тик(0.08);
  }

  // уход в сторону (−1 влево, +1 вправо) спасает от удара с другой стороны и от прямого
  const спасает = (сторона, атака) => атака === 'прямо' || (сторона < 0 ? атака === 'справа' : атака === 'слева');
  function уходАктивен() {
    const д = я.действие;
    if (д?.вид !== 'уход') return null;
    const начало = 0.04;
    return д.t >= начало && д.t <= начало + мн.уходОкно() ? д.сторона : null;
  }

  function начатьДействие(вид, сторона = 0) {
    if (развязка || я.действие || я.блок) return;
    if (я.дыхание < ЦЕНА[вид]) {
      поле.слово('нет дыхания', ЦЕНТР, 440, ЦВЕТ.тихо, 20);
      звуки.ох();
      return;
    }
    я.дыхание -= ЦЕНА[вид];
    я.покой = 0;
    я.действие = { вид, сторона, t: 0, разрешён: false, длит: вид === 'уход' ? УХОД * (медленно ? 1.4 : 1) : МОЙ_УДАР };
    if (вид === 'уход') звуки.хлоп();
  }

  function яПолучил(слово) {
    я.цел--;
    я.пропустил++;
    звуки.удар(0, 1);
    звуки.мимо();
    поле.дрожь(12);
    поле.вспышка(ЦВЕТ.ржа, 0.32);
    поле.слово(слово, ЦЕНТР, 300, ЦВЕТ.ржа, 30);
    if (я.цел <= 0) кончить('упал');
  }

  function онПолучил(слово, цвет = ЦВЕТ.свеча) {
    он.цел--;
    я.нанёс++;
    он.вЗащиту = 0;
    он.отдача = 1;
    звуки.удар(0, 0.9);
    звуки.хлоп();
    поле.искры(ЦЕНТР + видСдвиг(), 210, ЦВЕТ.свеча, 18);
    поле.кольцо(ЦЕНТР + видСдвиг(), 205, цвет, 80);
    поле.слово(слово, ЦЕНТР, 130, цвет, 30);
    if (он.цел <= 0) { кончить('победа'); return; }
    фаза('шатается', 0.6);
  }

  // мой удар долетает: что сейчас делает соперник
  function мойУдарДолетел() {
    if (он.фаза === 'раскрыт') { онПолучил('чисто!'); return; }
    if (он.фаза === 'замах' && !он.атака.финт && он.вФазе / он.длит > 0.65) {
      онПолучил('обмен', ЦВЕТ.бумага);
      if (!развязка) яПолучил('и тебе');
      return;
    }
    // в защиту: дыхание ушло, а он запомнил
    звуки.стук();
    поле.слово('в защиту', ЦЕНТР, 150, ЦВЕТ.тихо, 22);
    он.вЗащиту++;
    if (он.вЗащиту >= 2 && он.фаза === 'стойка') {
      он.вЗащиту = 0;
      сказать('Ну-ну.');
      начатьАтаку(true, true);
    }
  }

  // его удар долетает
  function егоУдарДолетел() {
    const ат = он.атака;
    const ушёл = уходАктивен();
    if (ушёл !== null && спасает(ушёл, ат.сторона)) {
      звуки.тик(0.14);
      поле.слово('ушёл', ЦЕНТР - ушёл * 140, 330, ЦВЕТ.трава, 24);
      фаза('раскрыт', С.раскрыт * мн.раскрыт());
      if (Math.random() < 0.4) сказать(С.реплики[Math.floor(Math.random() * С.реплики.length)], 1.2);
      return;
    }
    if (я.блок) {
      if (я.дыхание >= С.блокЦена) {
        я.дыхание -= С.блокЦена;
        звуки.штамп();
        поле.дрожь(4);
        поле.слово('закрылся', ЦЕНТР, 330, ЦВЕТ.море, 22);
        фаза('возврат', 0.4);
        return;
      }
      я.дыхание = 0;
      яПолучил('пробил');
      if (!развязка) фаза('возврат', 0.5);
      return;
    }
    яПолучил(ушёл !== null ? 'не туда' : 'пропустил');
    if (!развязка) фаза('возврат', 0.5);
  }

  function кончить(как) {
    if (развязка) return;
    let очки;
    let слово;
    let цвет;
    if (как === 'победа') {
      очки = 0.6 + 0.4 * (я.цел / ЦЕЛ);
      слово = 'Он сел';
      цвет = ЦВЕТ.свеча;
      звуки.ура();
      поле.вспышка(ЦВЕТ.свеча, 0.25);
    } else if (как === 'упал') {
      очки = 0.4 * (я.нанёс / С.стойкость);
      слово = 'Ты на земле';
      цвет = ЦВЕТ.ржа;
    } else if (как === 'вышел') {
      очки = 0;
      слово = 'Ушёл из круга';
      цвет = ЦВЕТ.тихо;
    } else {
      const разница = я.нанёс - я.пропустил;
      очки = разница > 0 ? Math.min(0.7, 0.5 + 0.06 * разница) : 0.3;
      слово = разница > 0 ? 'По очкам — твой' : 'По очкам — его';
      цвет = разница > 0 ? ЦВЕТ.бумага : ЦВЕТ.ржа;
    }
    if (медленно) очки = Math.min(очки, 0.77);
    развязка = { слово, цвет, очки, через: 1.1 };
  }

  // ---------- рисование ----------
  function видСдвиг() {
    const д = я.действие;
    if (д?.вид !== 'уход') return 0;
    const п = д.t / д.длит;
    return -д.сторона * 130 * ограничить(Math.min(п / 0.12, (1 - п) / 0.3), 0, 1);
  }

  const ease = п => (1 - Math.cos(ограничить(п, 0, 1) * Math.PI)) / 2;

  // положение кулака соперника (сторона −1 — левый на экране, +1 — правый)
  function кулак(с, cx, k) {
    const стража = { x: cx + с * 36 * k, y: 222, r: 25 * k, впереди: false };
    const ат = он.атака;
    if (он.фаза === 'раскрыт') return { ...стража, y: 300, x: cx + с * 70 * k };
    if (он.фаза === 'шатается') return { ...стража, y: 270, x: cx + с * 60 * k };
    if (!ат || !['замах', 'удар', 'отмена', 'возврат'].includes(он.фаза)) return стража;
    const рука = ат.сторона === 'слева' ? -1 : ат.сторона === 'справа' ? 1 : 1;
    if (с !== рука) return стража;
    const назад = ат.сторона === 'прямо'
      ? { x: cx + с * 58 * k, y: 250, r: 23 * k }
      : { x: cx + с * 160 * k, y: 245, r: 25 * k };
    const цель = ат.сторона === 'прямо' ? { x: ЦЕНТР, y: 330, r: 80 } : { x: ЦЕНТР + с * 40, y: 360, r: 72 };
    const смесь = (a, b, п) => ({ x: a.x + (b.x - a.x) * п, y: a.y + (b.y - a.y) * п, r: a.r + (b.r - a.r) * п });
    if (он.фаза === 'замах') {
      const п = ат.финт ? Math.min(1, он.вФазе / (он.длит * 0.55)) : он.вФазе / он.длит;
      return { ...смесь(стража, назад, ease(п)), впереди: false };
    }
    if (он.фаза === 'отмена') return { ...смесь(назад, стража, ease(он.вФазе / он.длит)), впереди: false };
    if (он.фаза === 'удар') {
      const п = он.вФазе / он.длит;
      const дуга = ат.сторона === 'прямо' ? 0 : Math.sin(п * Math.PI) * 60 * с;
      const т = смесь(назад, цель, п * п);
      return { ...т, x: т.x + дуга, впереди: true };
    }
    return { ...смесь(цель, стража, ease(он.вФазе / он.длит)), впереди: он.вФазе / он.длит < 0.4 };
  }

  function рука(ctx, плечо, к) {
    const лх = (плечо.x + к.x) / 2 + (к.x - плечо.x > 0 ? 18 : -18);
    const лу = (плечо.y + к.y) / 2 + 30;
    ctx.strokeStyle = '#8a6448';
    ctx.lineCap = 'round';
    ctx.lineWidth = 22 + к.r * 0.25;
    ctx.beginPath();
    ctx.moveTo(плечо.x, плечо.y);
    ctx.quadraticCurveTo(лх, лу, к.x, к.y);
    ctx.stroke();
    ctx.fillStyle = '#b08362';
    ctx.beginPath();
    ctx.arc(к.x, к.y, к.r, 0, Math.PI * 2);
    ctx.fill();
    ctx.fillStyle = 'rgba(0,0,0,.25)';
    ctx.fillRect(к.x - к.r * 0.7, к.y - к.r * 0.15, к.r * 1.4, к.r * 0.12);
  }

  function нарисоватьСоперника(ctx, t) {
    const k = С.ширина;
    const сдвиг = видСдвиг();
    const качание = Math.sin(t * 3.2) * 4;
    const наклон = он.фаза === 'раскрыт' ? 14 : он.фаза === 'шатается' ? -10 * Math.sin(он.вФазе * 10) : 0;
    const cx = ЦЕНТР + сдвиг + наклон;
    const отдача = он.отдача * 14;
    ctx.save();
    // тень и ноги
    ctx.fillStyle = 'rgba(0,0,0,.45)';
    ctx.beginPath();
    ctx.ellipse(cx, 512, 120 * k, 18, 0, 0, Math.PI * 2);
    ctx.fill();
    ctx.fillStyle = '#24201d';
    ctx.fillRect(cx - 60 * k, 420, 40 * k, 92);
    ctx.fillRect(cx + 20 * k, 420, 40 * k, 92);
    // туловище
    ctx.fillStyle = С.рубаха;
    ctx.beginPath();
    ctx.moveTo(cx - 92 * k, 262 + качание);
    ctx.lineTo(cx + 92 * k, 262 + качание);
    ctx.lineTo(cx + 64 * k, 432);
    ctx.lineTo(cx - 64 * k, 432);
    ctx.closePath();
    ctx.fill();
    // голова
    const гх = cx + наклон * 0.6;
    const гу = 196 + качание - отдача;
    ctx.fillStyle = '#9c7356';
    ctx.fillRect(гх - 16 * k, гу + 26, 32 * k, 34);
    ctx.fillStyle = '#b08362';
    ctx.beginPath();
    ctx.ellipse(гх, гу, 38 * k, 46, 0, 0, Math.PI * 2);
    ctx.fill();
    ctx.fillStyle = '#2a1f18';
    ctx.beginPath();
    ctx.ellipse(гх, гу - 30, 38 * k, 20, 0, Math.PI, 0);
    ctx.fill();
    ctx.fillStyle = '#1a1309';
    ctx.fillRect(гх - 18 * k, гу - 6, 9, 5);
    ctx.fillRect(гх + 9 * k, гу - 6, 9, 5);
    // раскрыт — подбородок открыт: кольцо, которое не только цветом видно (пунктир и пульс)
    if (он.фаза === 'раскрыт') {
      const пульс = 1 + Math.sin(t * 18) * 0.06;
      ctx.save();
      ctx.strokeStyle = ЦВЕТ.свеча;
      ctx.lineWidth = 4;
      ctx.setLineDash([10, 6]);
      ctx.beginPath();
      ctx.arc(гх, гу + 6, 62 * пульс, 0, Math.PI * 2);
      ctx.stroke();
      ctx.restore();
      свет(ctx, гх, гу, 110, 0.18);
    }
    const кл = [-1, 1].map(с => ({ с, к: кулак(с, cx, k), плечо: { x: cx + с * 80 * k, y: 272 + качание } }));
    for (const { к, плечо } of кл) if (!к.впереди) рука(ctx, плечо, к);
    for (const { к, плечо } of кл) if (к.впереди) рука(ctx, плечо, к);
    ctx.restore();
  }

  // признак удара: дуга со стороны, откуда пойдёт, или сжимающееся кольцо для прямого
  function признак(ctx) {
    if (он.фаза !== 'замах') return;
    const п = он.вФазе / он.длит;
    const сПорога = 0.55 - 0.25 * н;
    if (п < сПорога && !медленно) return;
    const ат = он.атака;
    const сила = ограничить((п - сПорога) / 0.2, 0.2, 1);
    ctx.save();
    ctx.globalAlpha = сила * 0.9;
    ctx.strokeStyle = ЦВЕТ.бумага;
    ctx.lineWidth = 5;
    if (ат.финт && н >= 1) ctx.setLineDash([6, 10]);
    if (ат.сторона === 'прямо') {
      ctx.beginPath();
      ctx.arc(ЦЕНТР, 300, 150 - 90 * п, 0, Math.PI * 2);
      ctx.stroke();
    } else {
      const с = ат.сторона === 'слева' ? -1 : 1;
      const [ax, ay, кx, кy, бx, бy] = [ЦЕНТР + с * 300, 170, ЦЕНТР + с * 400, 320, ЦЕНТР + с * 220, 420];
      ctx.beginPath();
      ctx.moveTo(ax, ay);
      ctx.quadraticCurveTo(кx, кy, бx, бy);
      ctx.stroke();
      // наконечник к середине
      ctx.setLineDash([]);
      const у = Math.atan2(бy - кy, бx - кx);
      ctx.beginPath();
      ctx.moveTo(бx, бy);
      ctx.lineTo(бx - Math.cos(у - 0.5) * 26, бy - Math.sin(у - 0.5) * 26);
      ctx.moveTo(бx, бy);
      ctx.lineTo(бx - Math.cos(у + 0.5) * 26, бy - Math.sin(у + 0.5) * 26);
      ctx.stroke();
    }
    ctx.restore();
  }

  function моиКулаки(ctx) {
    const д = я.действие;
    const сд = -видСдвиг() * 0.25;
    let л = { x: 360 + сд, y: 540, r: 48 };
    let п = { x: 600 + сд, y: 540, r: 48 };
    if (я.блок) { л = { x: 432, y: 420, r: 58 }; п = { x: 528, y: 420, r: 58 }; }
    if (д?.вид === 'удар') {
      const ф = Math.sin(ограничить(д.t / д.длит, 0, 1) * Math.PI);
      п = { x: 600 + (ЦЕНТР + 10 - 600) * ф, y: 540 - 330 * ф, r: 48 - 26 * ф };
    }
    for (const к of [л, п]) {
      ctx.fillStyle = 'rgba(0,0,0,.4)';
      ctx.beginPath();
      ctx.arc(к.x + 4, к.y + 6, к.r, 0, Math.PI * 2);
      ctx.fill();
      ctx.fillStyle = '#9a7052';
      ctx.beginPath();
      ctx.arc(к.x, к.y, к.r, 0, Math.PI * 2);
      ctx.fill();
      ctx.fillStyle = 'rgba(239,227,201,.25)';
      ctx.fillRect(к.x - к.r * 0.6, к.y - к.r * 0.55, к.r * 1.2, к.r * 0.16);
    }
  }

  function нарисовать(ctx, t) {
    фон(ctx, трущобы, 0.62, видСдвиг() * 0.3);
    // толпа за кругом
    for (const ч of толпа) {
      const x = ч.x + видСдвиг() * 0.5;
      const y = ч.y + Math.sin(t * 2 + ч.фаза) * (развязка ? 6 : 2);
      ctx.fillStyle = '#0d1214';
      ctx.beginPath();
      ctx.arc(x, y, ч.r, 0, Math.PI * 2);
      ctx.fill();
      ctx.fillRect(x - ч.r * 1.3, y + ч.r * 0.6, ч.r * 2.6, 120);
    }
    // вытоптанный круг
    ctx.strokeStyle = 'rgba(203,189,158,.25)';
    ctx.lineWidth = 3;
    ctx.beginPath();
    ctx.ellipse(ЦЕНТР + видСдвиг(), 500, 400, 46, 0, 0, Math.PI * 2);
    ctx.stroke();
    свет(ctx, ЦЕНТР, 200, 340, 0.12);

    нарисоватьСоперника(ctx, t);
    признак(ctx);
    моиКулаки(ctx);

    // шапка: соперник и его стойкость
    плашка(ctx, 16, 14, 270, 58);
    надпись(ctx, С.имя, 30, 34, { р: 19, выр: 'left', вес: 500 });
    for (let i = 0; i < С.стойкость; i++) {
      ctx.fillStyle = i < он.цел ? ЦВЕТ.свеча : 'rgba(255,236,200,.12)';
      ctx.fillRect(30 + i * 26, 50, 20, 10);
    }
    // время — догорающая полоса
    полоса(ctx, 330, 24, 300, 10, 1 - время / ВРЕМЯ, ЦВЕТ.тихо);
    надпись(ctx, медленно ? 'без спешки' : 'круг', ЦЕНТР, 48, { р: 14, цвет: ЦВЕТ.тихо });
    // герой: держишься и дыхание
    плашка(ctx, 16, ВЫС - 76, 250, 60);
    надпись(ctx, 'держишься', 30, ВЫС - 60, { р: 15, выр: 'left', цвет: ЦВЕТ.бумага2 });
    for (let i = 0; i < ЦЕЛ; i++) {
      ctx.fillStyle = i < я.цел ? ЦВЕТ.трава : 'rgba(224,127,98,.35)';
      ctx.fillRect(130 + i * 30, ВЫС - 66, 22, 10);
    }
    надпись(ctx, 'дыхание', 30, ВЫС - 34, { р: 15, выр: 'left', цвет: ЦВЕТ.бумага2 });
    полоса(ctx, 130, ВЫС - 40, 120, 12, я.дыхание / 100, я.дыхание < ЦЕНА.удар ? ЦВЕТ.ржа : ЦВЕТ.море);
    // клавиши
    плашка(ctx, ШИР - 246, ВЫС - 76, 230, 60);
    надпись(ctx, '← →  уйти   ↓  закрыться', ШИР - 131, ВЫС - 58, { р: 15, цвет: ЦВЕТ.бумага2 });
    надпись(ctx, '↑ / пробел  бить   Q  выйти', ШИР - 131, ВЫС - 32, { р: 15, цвет: ЦВЕТ.бумага2 });

    if (репликаЖизнь > 0) {
      ctx.globalAlpha = ограничить(репликаЖизнь * 2, 0, 1);
      надпись(ctx, '— ' + реплика, ЦЕНТР + 170, 120, { р: 20, выр: 'left', цвет: ЦВЕТ.бумага });
      ctx.globalAlpha = 1;
    }
    if (развязка) {
      ctx.fillStyle = 'rgba(10,16,19,.45)';
      ctx.fillRect(0, 230, ШИР, 80);
      надпись(ctx, развязка.слово, ЦЕНТР, 270, { р: 44, цвет: развязка.цвет, вес: 700 });
    }
  }

  // ---------- заставка ----------
  поле.кадр(нарисовать);
  const кнопки = соперник
    ? [{ текст: 'Выйти в круг', значение: соперник }]
    : Object.entries(СОПЕРНИКИ).map(([id, с]) => ({
      текст: `${с.имя}<small>${{ забияка: 'часто и размашисто', крепкий: 'редко, тяжело, бьёт двойкой', любимец: 'быстро и с финтами' }[id]}</small>`,
      значение: id,
    }));
  кнопки.push({ текст: 'Без спешки<small>крепкий боец, медленно · не выше «нормально»</small>', значение: 'медленно' });
  const выбор = await поле.старт({
    заголовок: 'Круг',
    строка: 'Вытоптанный пятачок между двумя стенами. Ставки у стены, драться выходят по одному. Читай замах: откуда пойдёт — туда не стой.',
    кнопки,
  });
  if (выбор === 'медленно') { медленно = true; С = соперник ? (СОПЕРНИКИ[соперник] ?? СОПЕРНИКИ.крепкий) : СОПЕРНИКИ.крепкий; } else С = СОПЕРНИКИ[выбор] ?? С;
  он.цел = С.стойкость;
  стойка(0.8);
  сказать(С.реплики[0], 1.4);
  поле.отладка = () => ({ я: { ...я, действие: я.действие?.вид ?? null }, он: { фаза: он.фаза, вФазе: он.вФазе, длит: он.длит, цел: он.цел, атака: он.атака }, время, медленно });

  const р = await поле.играть({
    обновить(dt) {
      репликаЖизнь = Math.max(0, репликаЖизнь - dt);
      он.отдача = Math.max(0, он.отдача - dt * 3);
      if (развязка) {
        развязка.через -= dt;
        if (развязка.через <= 0 && !поле.кончено) поле.конец(развязка.очки);
        return;
      }
      время += dt;
      if (время >= ВРЕМЯ) { кончить('время'); return; }

      // я
      const д = я.действие;
      if (д) {
        д.t += dt;
        if (д.вид === 'удар' && !д.разрешён && д.t >= 0.14) { д.разрешён = true; мойУдарДолетел(); }
        if (д.t >= д.длит) я.действие = null;
      } else if (я.блок) {
        я.дыхание = Math.min(100, я.дыхание + 4 * dt);
      } else {
        я.покой += dt;
        if (я.покой > 0.35) я.дыхание = Math.min(100, я.дыхание + (16 + 3 * н) * dt);
      }
      if (развязка) return;

      // он
      он.вФазе += dt;
      if (он.вФазе < он.длит) return;
      switch (он.фаза) {
        case 'стойка': начатьАтаку(); break;
        case 'замах':
          if (он.атака.финт) { фаза('отмена', 0.22); break; }
          фаза('удар', УДАР_ДЛИТ);
          break;
        case 'отмена': начатьАтаку(true, true); break;
        case 'удар': егоУдарДолетел(); break;
        case 'возврат':
          if (!он.двойкаБыла && Math.random() < С.двойка) { он.двойкаБыла = true; начатьАтаку(true, true); } else { он.двойкаБыла = false; стойка(); }
          break;
        case 'раскрыт': он.двойкаБыла = false; стойка(0.7); break;
        case 'шатается': он.двойкаБыла = false; стойка(0.9); break;
      }
    },
    нарисовать,
    клавиша(код) {
      if (код === 'ArrowLeft' || код === 'KeyA') начатьДействие('уход', -1);
      else if (код === 'ArrowRight' || код === 'KeyD') начатьДействие('уход', 1);
      else if (код === 'ArrowUp' || код === 'KeyW' || код === 'Space') начатьДействие('удар');
      else if (код === 'ArrowDown' || код === 'KeyS') { if (!я.действие && !развязка) я.блок = true; }
      else if (код === 'KeyQ' && !развязка) { вышел = true; кончить('вышел'); }
    },
    клавишаВверх(код) {
      if (код === 'ArrowDown' || код === 'KeyS') я.блок = false;
    },
    // мышь и палец: края — уход, низ середины (держать) — закрыться, верх середины — бить
    мышьВниз(x, y) {
      if (x < 320) начатьДействие('уход', -1);
      else if (x > 640) начатьДействие('уход', 1);
      else if (y > 380) { if (!я.действие && !развязка) я.блок = true; }
      else начатьДействие('удар');
    },
    мышьВверх() { я.блок = false; },
  }, [0.45, 0.78]);
  return { ...р, вышел, нанёс: я.нанёс, пропустил: я.пропустил, соперник: Object.keys(СОПЕРНИКИ).find(к => СОПЕРНИКИ[к] === С) };
}
