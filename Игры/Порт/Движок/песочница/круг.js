// Круг — кулачный бой у Братства в трущобах (работа «Выйти на круг», ремесло «кулак»).
// Соперник лицом к тебе. Он замахивается — прочитай, откуда пойдёт удар, и уйди в другую сторону
// (←/→) или закройся (↓). Промахнулся — раскрылся: тут и бей (↑ или пробел). Бить в его стойку —
// в защиту и мимо дыхания; бить в самый конец замаха — обмен, достанется обоим.
// Дыхание одно на всё: уход, удар и закрытый удар его тратят, стоять — копит. Q — выйти из круга.
// Навык: признак удара виден раньше, окно ухода и раскрытие дольше, финт видно с «умеешь».
// Соперники разные по привычке: забияка часто и размашисто, крепкий редко и тяжело, Гормов любимец — финтами.
