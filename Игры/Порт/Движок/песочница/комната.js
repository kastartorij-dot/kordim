// Чтение комнаты — зал в полутьме. Курсор — взгляд со светом: веди им по залу и кликай по деталям,
// которые не на своём месте. Мало времени, промах по пустому месту съедает секунду.
import {
  ЦВЕТ, ШИР, ВЫС, ШРИФТ, звуки, ступеньНавыка, создатьПоле, картинка, фон, надпись, плашка, полоса,
  случайно, звук,
} from './общее.js';

export const ОПИСЬ = { id: 'комната', имя: 'Чтение комнаты', где: 'Зал в полутьме' };
export const СМЫСЛ = {
  плохо: 'Ты почти ничего не заметил. В разговоре будешь гадать вслепую.',
  нормально: 'Кое-что подметил — будет за что зацепиться в разговоре.',
  отлично: 'Ты прочитал зал целиком: знаешь, кто здесь был и что прятал.',
};

const НАЙТИ = 4;
// Места, где может лежать деталь (по залу, вне верхней строки и нижнего списка).
const МЕСТА = [
  [120, 380], [210, 250], [300, 420], [380, 200], [450, 340], [540, 440], [600, 230],
  [680, 380], [760, 270], [840, 430], [880, 200], [160, 160], [520, 150], [720, 160],
];

const ДЕТАЛИ = {
  нож(ctx) {
    ctx.fillStyle = '#c9ced2';
    ctx.beginPath();
    ctx.moveTo(-18, -2);
    ctx.lineTo(10, -3);
    ctx.lineTo(14, 0);
    ctx.lineTo(10, 3);
    ctx.lineTo(-18, 2);
    ctx.fill();
    ctx.fillStyle = '#4a3020';
    ctx.fillRect(-30, -3, 12, 6);
  },
  письмо(ctx) {
    ctx.fillStyle = '#e8dcc0';
    ctx.fillRect(-15, -10, 30, 20);
    ctx.strokeStyle = '#9a8a6a';
    ctx.beginPath();
    ctx.moveTo(-15, -10);
    ctx.lineTo(0, 2);
    ctx.lineTo(15, -10);
    ctx.stroke();
    ctx.fillStyle = '#9e2b25';
    ctx.beginPath();
    ctx.arc(0, 2, 4, 0, Math.PI * 2);
    ctx.fill();
  },
  ключ(ctx) {
    ctx.strokeStyle = '#c8a050';
    ctx.lineWidth = 3;
    ctx.beginPath();
    ctx.arc(-12, 0, 6, 0, Math.PI * 2);
    ctx.moveTo(-6, 0);
    ctx.lineTo(16, 0);
    ctx.moveTo(10, 0);
    ctx.lineTo(10, 6);
    ctx.moveTo(15, 0);
    ctx.lineTo(15, 5);
    ctx.stroke();
  },
  следы(ctx) {
    ctx.fillStyle = 'rgba(120,150,160,.6)';
    for (const [x, y, a] of [[-22, 6, -0.2], [-4, -4, 0.2], [14, 6, -0.2]]) {
      ctx.beginPath();
      ctx.ellipse(x, y, 5, 9, a, 0, Math.PI * 2);
      ctx.fill();
    }
  },
  монета(ctx) {
    ctx.fillStyle = '#d9b450';
    ctx.beginPath();
    ctx.arc(0, 0, 8, 0, Math.PI * 2);
    ctx.fill();
    ctx.strokeStyle = '#8a6a20';
    ctx.lineWidth = 1.5;
    ctx.stroke();
    ctx.fillStyle = '#fff3c8';
    ctx.fillRect(-3, -4, 2, 2);
  },
  перчатка(ctx) {
    ctx.fillStyle = '#6a4a35';
    ctx.beginPath();
    ctx.ellipse(0, 4, 10, 8, 0, 0, Math.PI * 2);
    ctx.fill();
    for (let f = -2; f <= 1; f++) ctx.fillRect(f * 5 - 1, -12, 4, 12);
    ctx.fillRect(9, -2, 8, 4);
  },
};
const ИМЕНА = { нож: 'нож', письмо: 'письмо с печатью', ключ: 'ключ', следы: 'мокрые следы', монета: 'чужая монета', перчатка: 'перчатка' };

export async function запустить(контейнер, { навык = 0, тихо = false, сигнал } = {}) {
  const н = ступеньНавыка(навык);
  звук.тихо = тихо;
  const поле = создатьПоле(контейнер, { подсказка: 'Веди мышью — это твой взгляд со светом. Кликни по каждой детали из списка внизу. Промах по пустому месту съедает время.', сигнал });
  const зал = await картинка('Ресурсы/Места/zal.webp');

  const ВРЕМЯ = 15 + 3 * н;
  const радиус = 85 + 22 * н;
  const тьма = document.createElement('canvas');
  тьма.width = ШИР;
  тьма.height = ВЫС;
  const тctx = тьма.getContext('2d');

  const места = [...МЕСТА].sort(() => Math.random() - 0.5);
  const детали = Object.keys(ДЕТАЛИ).sort(() => Math.random() - 0.5).slice(0, НАЙТИ).map((вид, k) => ({
    вид, x: места[k][0] + случайно(-15, 15), y: места[k][1] + случайно(-10, 10), угол: случайно(-0.6, 0.6), найдена: false,
  }));
  let штраф = 0;
  let найдено = 0;
  let мерц = 0;

  function нарисовать(ctx, t) {
    фон(ctx, зал, 0.15);
    for (const д of детали) {
      ctx.save();
      ctx.translate(д.x, д.y);
      ctx.rotate(д.угол);
      ctx.globalAlpha = д.найдена ? 1 : 0.85;
      ДЕТАЛИ[д.вид](ctx);
      ctx.restore();
      if (д.найдена) {
        ctx.strokeStyle = ЦВЕТ.свеча;
        ctx.lineWidth = 2;
        ctx.beginPath();
        ctx.arc(д.x, д.y, 26, 0, Math.PI * 2);
        ctx.stroke();
      }
    }
    // полутьма со светом взгляда
    мерц = 0.96 + Math.sin(t * 9) * 0.02 + Math.sin(t * 23) * 0.015;
    тctx.globalCompositeOperation = 'source-over';
    тctx.clearRect(0, 0, ШИР, ВЫС);
    тctx.fillStyle = 'rgba(4,7,9,.955)';
    тctx.fillRect(0, 0, ШИР, ВЫС);
    тctx.globalCompositeOperation = 'destination-out';
    const м = поле.мышь;
    if (м.внутри) {
      const r = радиус * мерц;
      const г = тctx.createRadialGradient(м.x, м.y, 0, м.x, м.y, r);
      г.addColorStop(0, 'rgba(0,0,0,1)');
      г.addColorStop(0.55, 'rgba(0,0,0,.85)');
      г.addColorStop(1, 'rgba(0,0,0,0)');
      тctx.fillStyle = г;
      тctx.fillRect(м.x - r, м.y - r, r * 2, r * 2);
    }
    // найденное остаётся чуть освещённым
    for (const д of детали.filter(д => д.найдена)) {
      const г = тctx.createRadialGradient(д.x, д.y, 0, д.x, д.y, 40);
      г.addColorStop(0, 'rgba(0,0,0,.8)');
      г.addColorStop(1, 'rgba(0,0,0,0)');
      тctx.fillStyle = г;
      тctx.fillRect(д.x - 40, д.y - 40, 80, 80);
    }
    ctx.drawImage(тьма, 0, 0, ШИР, ВЫС);
    // тёплый край света
    if (м.внутри) {
      const г = ctx.createRadialGradient(м.x, м.y, радиус * 0.4, м.x, м.y, радиус);
      г.addColorStop(0, 'rgba(231,178,99,0)');
      г.addColorStop(1, 'rgba(231,178,99,.07)');
      ctx.fillStyle = г;
      ctx.beginPath();
      ctx.arc(м.x, м.y, радиус, 0, Math.PI * 2);
      ctx.fill();
    }
    // время
    const осталось = Math.max(0, ВРЕМЯ - поле.t - штраф);
    полоса(ctx, 30, 24, 900, 6, осталось / ВРЕМЯ, осталось < 5 ? ЦВЕТ.ржа : ЦВЕТ.свеча);
    надпись(ctx, `${Math.ceil(осталось)}`, 930, 46, { р: 22, шрифт: ШРИФТ.титул, вес: 700, выр: 'right', цвет: осталось < 5 ? ЦВЕТ.ржа : ЦВЕТ.бумага });
    // список
    плашка(ctx, 30, ВЫС - 56, 900, 40);
    надпись(ctx, 'найти:', 46, ВЫС - 36, { р: 15, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо, выр: 'left' });
    детали.forEach((д, k) => {
      const x = 120 + k * 205;
      надпись(ctx, (д.найдена ? '✓ ' : '· ') + ИМЕНА[д.вид], x, ВЫС - 36, { р: 18, выр: 'left', цвет: д.найдена ? ЦВЕТ.трава : ЦВЕТ.бумага });
      if (д.найдена) {
        ctx.fillStyle = ЦВЕТ.трава;
        ctx.fillRect(x, ВЫС - 36, ctx.measureText((д.найдена ? '✓ ' : '· ') + ИМЕНА[д.вид]).width, 1.5);
      }
    });
  }

  поле.кадр(нарисовать);
  await поле.старт({
    заголовок: 'Чтение комнаты',
    строка: `Ты зашёл в зал, свет почти не горит. ${ВРЕМЯ} секунд, пока на тебя не обратили внимание. Веди взглядом — где ты смотришь, там видно. Найди четыре детали из списка внизу.`,
  });

  const очки = () => (найдено / НАЙТИ) * (найдено === НАЙТИ ? 0.85 + 0.15 * Math.max(0, ВРЕМЯ - поле.t - штраф) / ВРЕМЯ : 0.9);
  поле.отладка = () => ({ детали, найдено, штраф });

  return поле.играть({
    обновить(dt, t) {
      if (t + штраф >= ВРЕМЯ) {
        звуки.ох();
        поле.слово('на тебя смотрят', ШИР / 2, ВЫС / 2, ЦВЕТ.ржа, 34);
        поле.конец(очки());
      }
    },
    нарисовать,
    мышьВниз(x, y) {
      const д = детали.find(д => !д.найдена && Math.hypot(д.x - x, д.y - y) < 30);
      if (д) {
        д.найдена = true;
        найдено++;
        звуки.звон(900 + найдено * 150);
        поле.кольцо(д.x, д.y, ЦВЕТ.свеча, 70);
        поле.искры(д.x, д.y, ЦВЕТ.свеча, 10);
        поле.слово(ИМЕНА[д.вид], д.x, д.y - 40, ЦВЕТ.свеча, 24);
        if (найдено === НАЙТИ) {
          звуки.ура();
          поле.вспышка(ЦВЕТ.свеча, 0.15);
          поле.конец(очки());
        }
      } else {
        штраф += 1;
        звуки.хлоп();
        поле.дрожь(3);
        поле.слово('пусто · −1 с', x, y - 30, ЦВЕТ.тихо, 18);
      }
    },
  }, [0.45, 0.8]);
}
