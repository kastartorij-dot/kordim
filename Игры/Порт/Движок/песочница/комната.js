const перемешать = список => [...список].sort(() => Math.random() - 0.5);

export async function запустить(контейнер, { навык = 0, тихо = false, сигнал, вариант, впервые = false } = {}) {
  const н = ступеньНавыка(навык);
  звук.тихо = тихо;
  const id = МЕСТА_ЧТЕНИЯ[вариант] ? вариант : варианты[0].id;
  const место = МЕСТА_ЧТЕНИЯ[id];
  const поле = создатьПоле(контейнер, { подсказка: 'Веди мышью — это твой взгляд со светом. Найди вещи из списка и связку из двух примет. Обычные вещи и пустые места съедают время.', сигнал });
  const зал = await картинка(место.фон);

  const ВРЕМЯ = 22 + 3 * н + (впервые ? 6 : 0);
  const радиус = 62 + 14 * н;
  const тьма = document.createElement('canvas');
  тьма.width = ШИР;
  тьма.height = ВЫС;
  const тctx = тьма.getContext('2d');

  const связка = выбрать(место.связки);
  const одиночные = перемешать(место.одиночные.filter(в => !связка.вещи.includes(в))).slice(0, 2);
  const места = перемешать(МЕСТА);
  const поставить = (вид, k, роль) => ({
    вид, роль, x: места[k][0] + случайно(-15, 15), y: места[k][1] + случайно(-10, 10), угол: случайно(-0.5, 0.5),
    найдена: false, живая: false, фаза: Math.random() * 6,
  });
  const вещи = [
    ...одиночные.map((в, k) => поставить(в, k, 'одна')),
    ...связка.вещи.map((в, k) => поставить(в, 2 + k, 'связка')),
    ...место.обычные.map((в, k) => поставить(в, 4 + k, 'обычная')),
  ];
  // две нужные вещи видны не всегда: блеснут на пару секунд и пропадут (в первый раз — все видны)
  if (!впервые) for (const в of перемешать(вещи.filter(в => в.роль !== 'обычная')).slice(0, 2)) в.живая = true;
  const нужные = вещи.filter(в => в.роль !== 'обычная');
  const ЦИКЛ = 5.2;
  const видна = (в, t) => !в.живая || в.найдена || ((t + в.фаза) % ЦИКЛ) < 2.3 + 0.3 * н;
  const взгляд = { x: ШИР / 2, y: ВЫС / 2 };
  let штраф = 0;
  let найдено = 0;
  let подпись = null; // { заголовок, текст, цвет, жизнь }
  let всёНайдено = false; // последняя подпись ещё видна, а партия уже кончена

  const значок = (ctx, вид, x, y, к = 0.62) => {
    ctx.save();
    ctx.translate(x, y);
    ctx.scale(к, к);
    ВЕЩИ[вид](ctx);
    ctx.restore();
  };

  function нарисовать(ctx, t) {
    фон(ctx, зал, 0.15);
    for (const в of вещи) {
      if (!видна(в, t)) continue;
      // живая вещь проявляется и гаснет плавно
      const ф = в.живая && !в.найдена ? ((t + в.фаза) % ЦИКЛ) / (2.3 + 0.3 * н) : 0.5;
      ctx.save();
      ctx.translate(в.x, в.y);
      ctx.rotate(в.угол);
      ctx.scale(МЕЛКО, МЕЛКО);
      ctx.globalAlpha = в.найдена ? 1 : 0.85 * Math.min(1, Math.min(ф, 1 - ф) * 6);
      ВЕЩИ[в.вид](ctx);
      ctx.restore();
      if (в.найдена && в.роль !== 'обычная') {
        ctx.strokeStyle = в.роль === 'связка' ? ЦВЕТ.море : ЦВЕТ.свеча;
        ctx.lineWidth = 2;
        ctx.beginPath();
        ctx.arc(в.x, в.y, 24, 0, Math.PI * 2);
        ctx.stroke();
      }
    }
    // полутьма со светом взгляда
    const мерц = 0.96 + Math.sin(t * 9) * 0.02 + Math.sin(t * 23) * 0.015;
    тctx.globalCompositeOperation = 'source-over';
    тctx.clearRect(0, 0, ШИР, ВЫС);
    тctx.fillStyle = `rgba(4,7,9,${место.тьма})`;
    тctx.fillRect(0, 0, ШИР, ВЫС);
    тctx.globalCompositeOperation = 'destination-out';
    const м = поле.мышь;
    if (м.внутри) {
      const r = радиус * мерц;
      const г = тctx.createRadialGradient(взгляд.x, взгляд.y, 0, взгляд.x, взгляд.y, r);
      г.addColorStop(0, 'rgba(0,0,0,1)');
      г.addColorStop(0.5, 'rgba(0,0,0,.85)');
      г.addColorStop(1, 'rgba(0,0,0,0)');
      тctx.fillStyle = г;
      тctx.fillRect(взгляд.x - r, взгляд.y - r, r * 2, r * 2);
    }
    for (const в of вещи.filter(в => в.найдена && в.роль !== 'обычная')) {
      const г = тctx.createRadialGradient(в.x, в.y, 0, в.x, в.y, 36);
      г.addColorStop(0, 'rgba(0,0,0,.8)');
      г.addColorStop(1, 'rgba(0,0,0,0)');
      тctx.fillStyle = г;
      тctx.fillRect(в.x - 36, в.y - 36, 72, 72);
    }
    ctx.drawImage(тьма, 0, 0, ШИР, ВЫС);
    // имена у найденных вещей — прямо на месте
    for (const в of вещи.filter(в => в.найдена && в.роль !== 'обычная')) {
      надпись(ctx, ПРИМЕТЫ[в.вид].имя, в.x, в.y + 36, { р: 14, цвет: в.роль === 'связка' ? ЦВЕТ.море : ЦВЕТ.свеча, шрифт: ШРИФТ.метка });
    }
    if (м.внутри) {
      const г = ctx.createRadialGradient(взгляд.x, взгляд.y, радиус * 0.4, взгляд.x, взгляд.y, радиус);
      г.addColorStop(0, 'rgba(231,178,99,0)');
      г.addColorStop(1, 'rgba(231,178,99,.08)');
      ctx.fillStyle = г;
      ctx.beginPath();
      ctx.arc(взгляд.x, взгляд.y, радиус, 0, Math.PI * 2);
      ctx.fill();
      // где мышь — точка; свет догоняет её
      ctx.fillStyle = 'rgba(239,227,201,.7)';
      ctx.fillRect(м.x - 1.5, м.y - 1.5, 3, 3);
    }
    // время и место
    const осталось = Math.max(0, ВРЕМЯ - поле.t - штраф);
    надпись(ctx, место.имя, 30, 16, { р: 15, выр: 'left', шрифт: ШРИФТ.метка, цвет: ЦВЕТ.бумага2 });
    полоса(ctx, 30, 30, 870, 6, осталось / ВРЕМЯ, осталось < 5 ? ЦВЕТ.ржа : ЦВЕТ.свеча);
    надпись(ctx, `${Math.ceil(осталось)}`, 930, 34, { р: 24, шрифт: ШРИФТ.титул, вес: 700, выр: 'right', цвет: осталось < 5 ? ЦВЕТ.ржа : ЦВЕТ.бумага });
    // подпись находки: что это и что значит
    if (подпись) {
      ctx.globalAlpha = ограничитьДолю(подпись.жизнь * 3);
      плашка(ctx, 150, 48, 660, 62, { обвод: подпись.цвет });
      надпись(ctx, подпись.заголовок, 166, 64, { р: 17, выр: 'left', вес: 700, цвет: подпись.цвет, тень: false });
      надпись(ctx, подпись.текст, 166, 90, { р: 16, выр: 'left', цвет: ЦВЕТ.бумага, тень: false });
      ctx.globalAlpha = 1;
    }
    // список: значок и имя каждой вещи, связка — смыслом
    плашка(ctx, 30, ВЫС - 60, 900, 46);
    надпись(ctx, 'найти:', 46, ВЫС - 37, { р: 15, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо, выр: 'left' });
    let x = 104;
    for (const в of вещи.filter(в => в.роль === 'одна')) {
      значок(ctx, в.вид, x + 12, ВЫС - 37);
      const s = (в.найдена ? '✓ ' : '') + ПРИМЕТЫ[в.вид].имя;
      надпись(ctx, s, x + 30, ВЫС - 37, { р: 17, выр: 'left', цвет: в.найдена ? ЦВЕТ.трава : ЦВЕТ.бумага });
      x += 30 + ctx.measureText(s).width + 26;
    }
    const пары = вещи.filter(в => в.роль === 'связка');
    const есть = пары.filter(в => в.найдена);
    for (const в of есть) { значок(ctx, в.вид, x + 12, ВЫС - 37); x += 28; }
    const s = есть.length === 2
      ? `✓ связка: ${связка.смысл}`
      : `связка «${связка.смысл}»: ${есть.length} из 2`;
    надпись(ctx, s, x + 4, ВЫС - 37, { р: 17, выр: 'left', цвет: есть.length === 2 ? ЦВЕТ.море : ЦВЕТ.бумага2 });
  }
  const ограничитьДолю = v => Math.max(0, Math.min(1, v));

  поле.кадр(нарисовать);
  const сек = ВРЕМЯ % 10 >= 2 && ВРЕМЯ % 10 <= 4 && (ВРЕМЯ % 100 < 12 || ВРЕМЯ % 100 > 14) ? 'секунды' : 'секунд';
  await поле.старт({
    заголовок: `Чтение комнаты · ${место.имя}`,
    строка: `${место.где} ${ВРЕМЯ} ${сек}, пока на тебя не обратили внимание. Взгляд — маленький круг света, он не поспевает за мышью. Найди две вещи из списка — в списке рядом с каждой её значок — и связку: две приметы, которые вместе значат «${связка.смысл}». Найденная вещь подпишется: что это и что значит.${впервые ? '' : ' Некоторые вещи видно только мельком.'}`,
  });

  const очки = () => {
    const доля = найдено / нужные.length;
    const связана = вещи.filter(в => в.роль === 'связка' && в.найдена).length === 2;
    const запас = Math.max(0, ВРЕМЯ - поле.t - штраф) / ВРЕМЯ;
    return доля * 0.85 + (связана ? 0.05 : 0) + (найдено === нужные.length ? 0.1 * запас + 0.05 : 0);
  };
  поле.отладка = () => ({ место: id, вещи, найдено, штраф, связка: связка.смысл, взгляд, радиус, видны: вещи.filter(в => видна(в, поле.t)).map(в => в.вид) });

  return поле.играть({
    обновить(dt, t) {
      // свет взгляда тянется за мышью с запозданием
      const к = 1 - Math.exp(-dt * (5 + н));
      взгляд.x += (поле.мышь.x - взгляд.x) * к;
      взгляд.y += (поле.мышь.y - взгляд.y) * к;
      if (подпись) подпись.жизнь -= dt / 4;
      if (подпись?.жизнь <= 0) подпись = null;
      if (!всёНайдено && t + штраф >= ВРЕМЯ) {
        звуки.ох();
        поле.слово('на тебя смотрят', ШИР / 2, ВЫС / 2, ЦВЕТ.ржа, 34);
        поле.конец(очки());
      }
    },
    нарисовать,
    мышьВниз(x, y) {
      if (всёНайдено) return;
      const освещено = Math.hypot(x - взгляд.x, y - взгляд.y) < радиус * 0.9;
      const в = освещено && вещи.find(в => !в.найдена && видна(в, поле.t) && Math.hypot(в.x - x, в.y - y) < 24);
      if (в && в.роль === 'обычная') {
        в.найдена = true;
        штраф += 2;
        звуки.хлоп();
        поле.дрожь(3);
        поле.слово(`${ОБЫЧНОЕ[в.вид]} — обычное дело · −2 с`, x, y - 30, ЦВЕТ.тихо, 18);
        return;
      }
      if (в) {
        в.найдена = true;
        найдено++;
        звуки.звон(900 + найдено * 150);
        поле.кольцо(в.x, в.y, в.роль === 'связка' ? ЦВЕТ.море : ЦВЕТ.свеча, 60);
        поле.искры(в.x, в.y, ЦВЕТ.свеча, 10);
        const п = ПРИМЕТЫ[в.вид];
        const пара = вещи.filter(в2 => в2.роль === 'связка' && в2.найдена).length;
        if (в.роль === 'связка' && пара === 2) {
          звуки.ура();
          поле.вспышка(ЦВЕТ.море, 0.12);
          подпись = { заголовок: `Связка: ${связка.смысл}`, текст: связка.развязка, цвет: ЦВЕТ.море, жизнь: 1.3 };
        } else if (в.роль === 'связка') {
          подпись = { заголовок: `${п.имя} — одна из двух примет связки`, текст: п.смысл, цвет: ЦВЕТ.море, жизнь: 1 };
        } else {
          подпись = { заголовок: п.имя, текст: п.смысл, цвет: ЦВЕТ.свеча, жизнь: 1 };
        }
        if (найдено === нужные.length) {
          звуки.ура();
          поле.вспышка(ЦВЕТ.свеча, 0.15);
          // дать дочитать последнюю подпись
          всёНайдено = true;
          const о = очки();
          setTimeout(() => поле.конец(о), 1600);
        }
      } else {
        штраф += 1;
        звуки.хлоп();
        поле.дрожь(3);
        поле.слово(освещено ? 'пусто · −1 с' : 'туда не смотришь · −1 с', x, y - 30, ЦВЕТ.тихо, 18);
      }
    },
  }, [0.45, 0.8]);
}
