const ИМЕНА = {
  нож: 'нож', письмо: 'письмо с печатью', ключ: 'ключ', следы: 'мокрые следы', монета: 'чужая монета',
  перчатка: 'перчатка', плащ: 'мокрый плащ',
};
const СВЯЗКИ = [
  { смысл: 'кто-то пришёл с воды', вещи: ['следы', 'плащ'] },
  { смысл: 'кто-то платит тайком', вещи: ['монета', 'перчатка'] },
  { смысл: 'здесь что-то прятали', вещи: ['ключ', 'письмо'] },
];
const ОБЫЧНЫЕ = ['кружка', 'ложка', 'хлеб', 'огарок'];
const МЕЛКО = 0.78;

export async function запустить(контейнер, { навык = 0, тихо = false, сигнал } = {}) {
  const н = ступеньНавыка(навык);
  звук.тихо = тихо;
  const поле = создатьПоле(контейнер, { подсказка: 'Веди мышью — это твой взгляд со светом. Найди вещи из списка и связку из двух примет. Обычные вещи и пустые места съедают время.', сигнал });
  const зал = await картинка('Ресурсы/Места/zal.webp');

  const ВРЕМЯ = 22 + 3 * н;
  const радиус = 62 + 14 * н;
  const тьма = document.createElement('canvas');
  тьма.width = ШИР;
  тьма.height = ВЫС;
  const тctx = тьма.getContext('2d');

  const связка = выбрать(СВЯЗКИ);
  const одиночные = Object.keys(ИМЕНА).filter(в => !связка.вещи.includes(в)).sort(() => Math.random() - 0.5).slice(0, 2);
  const места = [...МЕСТА].sort(() => Math.random() - 0.5);
  const поставить = (вид, k, роль) => ({
    вид, роль, x: места[k][0] + случайно(-15, 15), y: места[k][1] + случайно(-10, 10), угол: случайно(-0.6, 0.6),
    найдена: false, живая: false, фаза: Math.random() * 6,
  });
  const вещи = [
    ...одиночные.map((в, k) => поставить(в, k, 'одна')),
    ...связка.вещи.map((в, k) => поставить(в, 2 + k, 'связка')),
    ...ОБЫЧНЫЕ.map((в, k) => поставить(в, 4 + k, 'обычная')),
  ];
  // две нужные вещи видны не всегда: блеснут на пару секунд и пропадут
  for (const в of вещи.filter(в => в.роль !== 'обычная').sort(() => Math.random() - 0.5).slice(0, 2)) в.живая = true;
  const нужные = вещи.filter(в => в.роль !== 'обычная');
  const ЦИКЛ = 5.2;
  const видна = (в, t) => !в.живая || в.найдена || ((t + в.фаза) % ЦИКЛ) < 2.3 + 0.3 * н;
  const взгляд = { x: ШИР / 2, y: ВЫС / 2 };
  let штраф = 0;
  let найдено = 0;

  function нарисовать(ctx, t) {
    фон(ctx, зал, 0.15);
    for (const в of вещи) {
      if (!видна(в, t)) continue;
      // живая вещь проявляется и гаснет плавно
      const ф = в.живая && !в.найдена ? ((t + в.фаза) % ЦИКЛ) / (2.3 + 0.3 * н) : 0.5;
      ctx.save();
      ctx.translate(в.x, в.y);
      ctx.rotate(в.угол);
      ctx.scale(МЕЛКО, МЕЛКО);
      ctx.globalAlpha = в.найдена ? 1 : 0.8 * Math.min(1, Math.min(ф, 1 - ф) * 6);
      ВЕЩИ[в.вид](ctx);
      ctx.restore();
      if (в.найдена && в.роль !== 'обычная') {
        ctx.strokeStyle = в.роль === 'связка' ? ЦВЕТ.море : ЦВЕТ.свеча;
        ctx.lineWidth = 2;
        ctx.beginPath();
        ctx.arc(в.x, в.y, 22, 0, Math.PI * 2);
        ctx.stroke();
      }
    }
    // полутьма со светом взгляда
    const мерц = 0.96 + Math.sin(t * 9) * 0.02 + Math.sin(t * 23) * 0.015;
    тctx.globalCompositeOperation = 'source-over';
    тctx.clearRect(0, 0, ШИР, ВЫС);
    тctx.fillStyle = 'rgba(4,7,9,.965)';
    тctx.fillRect(0, 0, ШИР, ВЫС);
    тctx.globalCompositeOperation = 'destination-out';
    const м = поле.мышь;
    if (м.внутри) {
      const r = радиус * мерц;
      const г = тctx.createRadialGradient(взгляд.x, взгляд.y, 0, взгляд.x, взгляд.y, r);
      г.addColorStop(0, 'rgba(0,0,0,1)');
      г.addColorStop(0.5, 'rgba(0,0,0,.85)');
      г.addColorStop(1, 'rgba(0,0,0,0)');
      тctx.fillStyle = г;
      тctx.fillRect(взгляд.x - r, взгляд.y - r, r * 2, r * 2);
    }
    for (const в of вещи.filter(в => в.найдена && в.роль !== 'обычная')) {
      const г = тctx.createRadialGradient(в.x, в.y, 0, в.x, в.y, 36);
      г.addColorStop(0, 'rgba(0,0,0,.8)');
      г.addColorStop(1, 'rgba(0,0,0,0)');
      тctx.fillStyle = г;
      тctx.fillRect(в.x - 36, в.y - 36, 72, 72);
    }
    ctx.drawImage(тьма, 0, 0, ШИР, ВЫС);
    if (м.внутри) {
      const г = ctx.createRadialGradient(взгляд.x, взгляд.y, радиус * 0.4, взгляд.x, взгляд.y, радиус);
      г.addColorStop(0, 'rgba(231,178,99,0)');
      г.addColorStop(1, 'rgba(231,178,99,.08)');
      ctx.fillStyle = г;
      ctx.beginPath();
      ctx.arc(взгляд.x, взгляд.y, радиус, 0, Math.PI * 2);
      ctx.fill();
      // где мышь — точка; свет догоняет её
      ctx.fillStyle = 'rgba(239,227,201,.7)';
      ctx.fillRect(м.x - 1.5, м.y - 1.5, 3, 3);
    }
    // время
    const осталось = Math.max(0, ВРЕМЯ - поле.t - штраф);
    полоса(ctx, 30, 24, 870, 6, осталось / ВРЕМЯ, осталось < 5 ? ЦВЕТ.ржа : ЦВЕТ.свеча);
    надпись(ctx, `${Math.ceil(осталось)}`, 930, 30, { р: 24, шрифт: ШРИФТ.титул, вес: 700, выр: 'right', цвет: осталось < 5 ? ЦВЕТ.ржа : ЦВЕТ.бумага });
    // список
    плашка(ctx, 30, ВЫС - 56, 900, 40);
    надпись(ctx, 'найти:', 46, ВЫС - 36, { р: 15, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо, выр: 'left' });
    let x = 112;
    for (const в of вещи.filter(в => в.роль === 'одна')) {
      const s = (в.найдена ? '✓ ' : '· ') + ИМЕНА[в.вид];
      надпись(ctx, s, x, ВЫС - 36, { р: 18, выр: 'left', цвет: в.найдена ? ЦВЕТ.трава : ЦВЕТ.бумага });
      x += ctx.measureText(s).width + 34;
    }
    const пары = вещи.filter(в => в.роль === 'связка');
    const есть = пары.filter(в => в.найдена).length;
    const s = есть === 2
      ? `✓ связка: ${связка.смысл}`
      : `· связка: ${связка.смысл} — две приметы (${есть}/2)`;
    надпись(ctx, s, x, ВЫС - 36, { р: 18, выр: 'left', цвет: есть === 2 ? ЦВЕТ.море : ЦВЕТ.бумага2 });
  }

  поле.кадр(нарисовать);
  await поле.старт({
    заголовок: 'Чтение комнаты',
    строка: `Ты зашёл в зал, свет почти не горит. ${ВРЕМЯ} секунд, пока на тебя не обратили внимание. Взгляд — маленький круг света, он не поспевает за мышью. Найди две вещи из списка и связку: две приметы, которые вместе значат «${связка.смысл}». Некоторые вещи видно только мельком.`,
  });

  const очки = () => {
    const доля = найдено / нужные.length;
    const связана = вещи.filter(в => в.роль === 'связка' && в.найдена).length === 2;
    const запас = Math.max(0, ВРЕМЯ - поле.t - штраф) / ВРЕМЯ;
    return доля * 0.85 + (связана ? 0.05 : 0) + (найдено === нужные.length ? 0.1 * запас + 0.05 : 0);
  };
  поле.отладка = () => ({ вещи, найдено, штраф, связка: связка.смысл, взгляд, радиус, видны: вещи.filter(в => видна(в, поле.t)).map(в => в.вид) });

  return поле.играть({
    обновить(dt, t) {
      // свет взгляда тянется за мышью с запозданием
      const к = 1 - Math.exp(-dt * (5 + н));
      взгляд.x += (поле.мышь.x - взгляд.x) * к;
      взгляд.y += (поле.мышь.y - взгляд.y) * к;
      if (t + штраф >= ВРЕМЯ) {
        звуки.ох();
        поле.слово('на тебя смотрят', ШИР / 2, ВЫС / 2, ЦВЕТ.ржа, 34);
        поле.конец(очки());
      }
    },
    нарисовать,
    мышьВниз(x, y) {
      const освещено = Math.hypot(x - взгляд.x, y - взгляд.y) < радиус * 0.9;
      const в = освещено && вещи.find(в => !в.найдена && видна(в, поле.t) && Math.hypot(в.x - x, в.y - y) < 22);
      if (в && в.роль === 'обычная') {
        в.найдена = true;
        штраф += 2;
        звуки.хлоп();
        поле.дрожь(3);
        поле.слово(`${в.вид} — обычное дело · −2 с`, x, y - 30, ЦВЕТ.тихо, 18);
        return;
      }
      if (в) {
        в.найдена = true;
        найдено++;
        звуки.звон(900 + найдено * 150);
        поле.кольцо(в.x, в.y, в.роль === 'связка' ? ЦВЕТ.море : ЦВЕТ.свеча, 60);
        поле.искры(в.x, в.y, ЦВЕТ.свеча, 10);
        поле.слово(ИМЕНА[в.вид], в.x, в.y - 36, ЦВЕТ.свеча, 22);
        if (в.роль === 'связка' && вещи.filter(п => п.роль === 'связка' && п.найдена).length === 2) {
          звуки.ура();
          поле.вспышка(ЦВЕТ.море, 0.12);
          поле.слово(`связка: ${связка.смысл}`, ШИР / 2, 110, ЦВЕТ.море, 28);
        }
        if (найдено === нужные.length) {
          звуки.ура();
          поле.вспышка(ЦВЕТ.свеча, 0.15);
          поле.конец(очки());
        }
      } else {
        штраф += 1;
        звуки.хлоп();
        поле.дрожь(3);
        поле.слово(освещено ? 'пусто · −1 с' : 'туда не смотришь · −1 с', x, y - 30, ЦВЕТ.тихо, 18);
      }
    },
  }, [0.45, 0.8]);
}
