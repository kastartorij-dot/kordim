// Счёт — накладная ползёт вверх. Проверяй «количество × цена = сумма» и кликай по строкам,
// где сумма неверна. Ошибку, уползшую за край, уже не поймать; ткнул в верную — клякса.
import {
  ЦВЕТ, ШИР, ВЫС, ШРИФТ, звуки, ступеньНавыка, создатьПоле, картинка, фон, надпись, плашка, полоса,
  ограничить, выбрать, звук,
} from './общее.js';

export const ОПИСЬ = { id: 'счёт', имя: 'Счёт', где: 'Накладная в конторе' };
export const СМЫСЛ = {
  плохо: 'Ошибки ушли в книгу. Недостачу потом повесят на того, кто сверял, — на тебя.',
  нормально: 'Главное поймал, кое-что проскочило. Работа засчитана.',
  отлично: 'Ни одна ошибка не прошла. В конторе запомнят, что тебе можно давать бумаги.',
};

const ТОВАРЫ = [
  ['сельдь', 'бочка'], ['соль', 'мешок'], ['смола', 'бочонок'], ['пенька', 'связка'], ['гвозди', 'ящик'],
  ['парусина', 'рулон'], ['воск', 'круг'], ['канат', 'бухта'], ['ячмень', 'мешок'], ['доска', 'пачка'],
];
const ЛИСТ = { x: 250, w: 460 };
const ШАГ = 46;

function строки(n, ошибок) {
  const где = new Set();
  while (где.size < ошибок) где.add(2 + Math.floor(Math.random() * (n - 2)));
  return Array.from({ length: n }, (_, k) => {
    const [товар, мера] = выбрать(ТОВАРЫ);
    const кол = 2 + Math.floor(Math.random() * 8);
    const цена = 3 + Math.floor(Math.random() * 22);
    const верно = кол * цена;
    let сумма = верно;
    if (где.has(k)) {
      const s = String(верно);
      const перевёртыш = s.length === 2 && s[0] !== s[1] ? Number(s[1] + s[0]) : null;
      сумма = перевёртыш && Math.random() < 0.4 ? перевёртыш : верно + выбрать([-10, -3, -2, -1, 1, 2, 3, 10]);
    }
    return { товар, мера, кол, цена, сумма, ошибка: сумма !== верно, отмечена: false, клякса: false, ушла: false };
  });
}

export async function запустить(контейнер, { навык = 0, тихо = false, сигнал } = {}) {
  const н = ступеньНавыка(навык);
  звук.тихо = тихо;
  const поле = создатьПоле(контейнер, { подсказка: 'Накладная ползёт вверх. Проверь «кол-во × цена = сумма» и кликни по строке, где сумма неверна.', сигнал });
  const контора = await картинка('Ресурсы/Места/контора-у-порта.png');

  const скорость = 30 - 5 * н;
  const всего = 16 - 2 * н;
  const ошибок = 4;
  const список = строки(всего, ошибок);
  let сдвиг = 0; // на сколько лист уполз вверх
  let наведено = -1;
  let поймано = 0;
  let ложных = 0;
  let пропущено = 0;
  let комбо = 0;

  const yСтроки = k => ВЫС + 10 + k * ШАГ - сдвиг;

  function нарисовать(ctx) {
    фон(ctx, контора, 0.7);
    // лист
    ctx.fillStyle = '#e9dcbc';
    ctx.fillRect(ЛИСТ.x, 0, ЛИСТ.w, ВЫС);
    ctx.fillStyle = 'rgba(120,90,50,.08)';
    for (let y = (-сдвиг % 23 + 23) % 23; y < ВЫС; y += 23) ctx.fillRect(ЛИСТ.x, y, ЛИСТ.w, 1);
    ctx.strokeStyle = 'rgba(158,43,37,.35)';
    ctx.beginPath();
    ctx.moveTo(ЛИСТ.x + 40, 0);
    ctx.lineTo(ЛИСТ.x + 40, ВЫС);
    ctx.stroke();
    // шапка накладной уезжает вместе со строками
    const шапка = ВЫС - 60 - сдвиг;
    if (шапка > -40) {
      надпись(ctx, 'Накладная · приход с причала', ЛИСТ.x + ЛИСТ.w / 2, шапка, { р: 22, шрифт: ШРИФТ.титул, вес: 700, цвет: ЦВЕТ.чернила, тень: false });
      надпись(ctx, 'товар · кол-во × цена = сумма, гр.', ЛИСТ.x + ЛИСТ.w / 2, шапка + 26, { р: 14, цвет: '#6a5a40', тень: false });
    }
    список.forEach((с, k) => {
      const y = yСтроки(k);
      if (y < -30 || y > ВЫС + 30) return;
      if (k === наведено && !с.отмечена) {
        ctx.fillStyle = 'rgba(231,178,99,.28)';
        ctx.fillRect(ЛИСТ.x, y - ШАГ / 2 + 3, ЛИСТ.w, ШАГ - 6);
      }
      const цв = '#2a1f12';
      надпись(ctx, String(k + 1), ЛИСТ.x + 30, y, { р: 15, цвет: '#8a7a5a', выр: 'right', тень: false });
      надпись(ctx, `${с.товар}, ${с.мера}`, ЛИСТ.x + 52, y, { р: 19, цвет: цв, выр: 'left', тень: false });
      надпись(ctx, `${с.кол} × ${с.цена} =`, ЛИСТ.x + 330, y, { р: 19, цвет: цв, выр: 'right', тень: false });
      надпись(ctx, String(с.сумма), ЛИСТ.x + 400, y, { р: 21, цвет: цв, выр: 'right', тень: false, вес: 700 });
      if (с.отмечена) {
        ctx.strokeStyle = '#9e2b25';
        ctx.lineWidth = 3;
        ctx.beginPath();
        ctx.ellipse(ЛИСТ.x + 383, y, 34, 17, -0.1, 0, Math.PI * 2);
        ctx.stroke();
        надпись(ctx, String(с.кол * с.цена), ЛИСТ.x + 422, y - 2, { р: 16, цвет: '#9e2b25', выр: 'left', тень: false, вес: 700 });
      }
      if (с.клякса) {
        ctx.fillStyle = 'rgba(26,19,9,.75)';
        ctx.beginPath();
        ctx.arc(ЛИСТ.x + 200, y, 13, 0, Math.PI * 2);
        ctx.arc(ЛИСТ.x + 214, y + 6, 7, 0, Math.PI * 2);
        ctx.fill();
      }
      if (с.ушла && с.ошибка && !с.отмечена) {
        ctx.fillStyle = 'rgba(224,127,98,.25)';
        ctx.fillRect(ЛИСТ.x, y - ШАГ / 2 + 3, ЛИСТ.w, ШАГ - 6);
      }
    });
    // край, за которым ошибку уже не поймать
    const г = ctx.createLinearGradient(0, 0, 0, 90);
    г.addColorStop(0, 'rgba(10,16,19,.95)');
    г.addColorStop(1, 'rgba(10,16,19,0)');
    ctx.fillStyle = г;
    ctx.fillRect(ЛИСТ.x, 0, ЛИСТ.w, 90);
    ctx.strokeStyle = 'rgba(224,127,98,.6)';
    ctx.setLineDash([6, 6]);
    ctx.beginPath();
    ctx.moveTo(ЛИСТ.x, 40);
    ctx.lineTo(ЛИСТ.x + ЛИСТ.w, 40);
    ctx.stroke();
    ctx.setLineDash([]);
    // счёт сбоку
    плашка(ctx, 30, 30, 190, 150);
    надпись(ctx, 'сверка', 46, 50, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.свеча, выр: 'left' });
    надпись(ctx, `поймано ${поймано} из ${ошибок}`, 46, 82, { р: 18, выр: 'left', цвет: ЦВЕТ.трава });
    надпись(ctx, `пропущено ${пропущено}`, 46, 110, { р: 18, выр: 'left', цвет: пропущено ? ЦВЕТ.ржа : ЦВЕТ.тихо });
    надпись(ctx, `кляксы ${ложных}`, 46, 138, { р: 18, выр: 'left', цвет: ложных ? ЦВЕТ.ржа : ЦВЕТ.тихо });
    const ход = ограничить(сдвиг / (ВЫС + всего * ШАГ + 20), 0, 1);
    полоса(ctx, 46, 158, 158, 6, ход, ЦВЕТ.бумага2);
    if (комбо >= 2) надпись(ctx, `${комбо} подряд`, 125, 220, { р: 26, шрифт: ШРИФТ.титул, вес: 700, цвет: ЦВЕТ.свеча });
  }

  поле.кадр(нарисовать);
  await поле.старт({
    заголовок: 'Счёт',
    строка: `Накладная с причала, ${всего} строк, в ${ошибок} из них сумма неверна. Лист ползёт вверх: проверяй, умножай в уме и кликай по строке с ошибкой, пока она не ушла за край.`,
  });

  function строкаНа(y) {
    for (let k = 0; k < список.length; k++) if (Math.abs(yСтроки(k) - y) < ШАГ / 2) return k;
    return -1;
  }

  const очки = () => ограничить((поймано - ложных * 0.5) / ошибок, 0, 1);
  поле.отладка = () => ({ список, сдвиг, yСтроки: список.map((_, k) => yСтроки(k)) });

  return поле.играть({
    обновить(dt) {
      сдвиг += скорость * dt;
      список.forEach((с, k) => {
        if (!с.ушла && yСтроки(k) < 40) {
          с.ушла = true;
          if (с.ошибка && !с.отмечена) {
            пропущено++;
            комбо = 0;
            звуки.мимо();
            поле.дрожь(4);
            поле.слово('ошибка ушла', ЛИСТ.x + ЛИСТ.w / 2, 70, ЦВЕТ.ржа, 26);
          }
        }
      });
      if (yСтроки(список.length - 1) < 20) поле.конец(очки());
    },
    нарисовать,
    мышьДвиг(x, y) {
      наведено = x > ЛИСТ.x && x < ЛИСТ.x + ЛИСТ.w ? строкаНа(y) : -1;
    },
    мышьВниз(x, y) {
      if (x < ЛИСТ.x || x > ЛИСТ.x + ЛИСТ.w) return;
      const k = строкаНа(y);
      if (k < 0) return;
      const с = список[k];
      if (с.отмечена || с.клякса || с.ушла) return;
      if (с.ошибка) {
        с.отмечена = true;
        поймано++;
        комбо++;
        звуки.штамп();
        поле.кольцо(ЛИСТ.x + 383, yСтроки(k), '#9e2b25', 60);
        поле.слово('поймал!', ЛИСТ.x + ЛИСТ.w + 70, yСтроки(k), ЦВЕТ.свеча, 28);
        if (поймано === ошибок) {
          звуки.ура();
          поле.вспышка(ЦВЕТ.свеча, 0.15);
          поле.конец(очки());
        }
      } else {
        с.клякса = true;
        ложных++;
        комбо = 0;
        звуки.мимо();
        поле.дрожь(5);
        поле.слово('тут верно', ЛИСТ.x + ЛИСТ.w + 70, yСтроки(k), ЦВЕТ.ржа, 24);
      }
    },
  }, [0.45, 0.8]);
}
