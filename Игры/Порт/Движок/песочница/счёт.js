// Строки накладной по варианту. Обычные строки не повторяются ни товаром с количеством, ни целиком.
export function строкиНакладной(вариант, n, ошибок, случ = Math.random) {
  const из = список => список[Math.floor(случ() * список.length)];
  const где = new Set();
  while (где.size < ошибок) где.add(2 + Math.floor(случ() * (n - 2)));
  const прейскурант = вариант === 'цены'
    ? [...ТОВАРЫ].sort(() => случ() - 0.5).slice(0, 5).map(([товар, мера]) => ({ товар, мера, цена: 3 + Math.floor(случ() * 20) }))
    : null;
  const было = new Set();
  const строки = [];
  for (let k = 0; k < n; k++) {
    const ошибка = где.has(k);
    if (вариант === 'дубль' && ошибка) {
      // копия одной из прежних верных строк, две–пять строк назад
      const прежние = строки.filter((с, j) => !с.ошибка && j < k - 1 && j >= k - 5);
      const образец = прежние.length ? из(прежние) : строки.find(с => !с.ошибка);
      строки.push({ ...образец, ошибка: true, отмечена: false, клякса: false, ушла: false, копия: строки.indexOf(образец) });
      continue;
    }
    let товар, мера, кол, цена;
    do {
      if (прейскурант) ({ товар, мера, цена } = из(прейскурант));
      else { [товар, мера] = из(ТОВАРЫ); цена = 3 + Math.floor(случ() * 22); }
      кол = 2 + Math.floor(случ() * 8);
    } while (было.has(товар + кол));
    было.add(товар + кол);
    const с = { товар, мера, кол, цена, сумма: кол * цена, ошибка, отмечена: false, клякса: false, ушла: false };
    if (вариант === 'сумма' && ошибка) {
      const s = String(с.сумма);
      const перевёртыш = s.length === 2 && s[0] !== s[1] ? Number(s[1] + s[0]) : null;
      с.сумма = перевёртыш && случ() < 0.4 ? перевёртыш : с.сумма + из([-10, -3, -2, -1, 1, 2, 3, 10]);
      с.верно = кол * цена;
    }
    if (вариант === 'палочки') с.принято = ошибка ? Math.max(1, кол + из([-2, -1, -1, 1])) : кол;
    if (вариант === 'цены' && ошибка) {
      с.поСписку = цена;
      с.цена = цена + из([1, 2, 2, 3, -1]);
      с.сумма = кол * с.цена;
    }
    if (вариант === 'печать') с.печать = ошибка ? из(ЧУЖИЕ) : 'наша';
    строки.push(с);
  }
  return { строки, прейскурант };
}

function штамп(ctx, x, y, вид, r = 12) {
  ctx.strokeStyle = 'rgba(140,40,34,.8)';
  ctx.fillStyle = 'rgba(140,40,34,.8)';
  ctx.lineWidth = 2;
  ctx.beginPath();
  if (вид === 'квадрат') ctx.rect(x - r, y - r, r * 2, r * 2);
  else ctx.arc(x, y, r, 0, Math.PI * 2);
  ctx.stroke();
  ctx.beginPath();
  if (вид === 'точка') {
    ctx.arc(x, y, 3, 0, Math.PI * 2);
    ctx.fill();
    return;
  }
  const к = r * 0.62;
  if (вид === 'косой') {
    ctx.moveTo(x - к, y - к); ctx.lineTo(x + к, y + к);
    ctx.moveTo(x + к, y - к); ctx.lineTo(x - к, y + к);
  } else {
    ctx.moveTo(x - к, y); ctx.lineTo(x + к, y);
    ctx.moveTo(x, y - к); ctx.lineTo(x, y + к);
  }
  ctx.stroke();
}

function палочки(ctx, x, y, n) {
  ctx.strokeStyle = '#2a1f12';
  ctx.lineWidth = 2;
  ctx.beginPath();
  let пх = x;
  for (let k = 0; k < n; k++) {
    if (k % 5 === 4) {
      ctx.moveTo(пх - 4 * 6 - 2, y + 8);
      ctx.lineTo(пх + 2, y - 8);
      пх += 10;
      continue;
    }
    ctx.moveTo(пх, y - 9);
    ctx.lineTo(пх, y + 9);
    пх += 6;
  }
  ctx.stroke();
}

let поКругу = 0;
export async function запустить(контейнер, { навык = 0, тихо = false, сигнал, вариант } = {}) {
  const н = ступеньНавыка(навык);
  звук.тихо = тихо;
  const вар = варианты.find(x => x.id === вариант) ?? варианты[поКругу++ % варианты.length];
  const поле = создатьПоле(контейнер, { подсказка: 'Накладная ползёт вверх. Найди строку с ошибкой и кликни по ней, пока она не ушла за край.', сигнал });
  const контора = await картинка('Ресурсы/Места/контора-у-порта.webp');

  const скорость = (30 - 5 * н) * вар.скорость;
  const всего = 16 - 2 * н;
  const ошибок = 4;
  const { строки: список, прейскурант } = строкиНакладной(вар.id, всего, ошибок);
  let сдвиг = 0; // на сколько лист уполз вверх
  let наведено = -1;
  let поймано = 0;
  let ложных = 0;
  let пропущено = 0;
  let комбо = 0;

  const yСтроки = k => ВЫС + 10 + k * ШАГ - сдвиг;

  function строкаЛиста(ctx, с, k, y) {
    const цв = '#2a1f12';
    надпись(ctx, String(k + 1), ЛИСТ.x + 30, y, { р: 15, цвет: '#8a7a5a', выр: 'right', тень: false });
    надпись(ctx, `${с.товар}, ${с.мера}`, ЛИСТ.x + 52, y, { р: 19, цвет: цв, выр: 'left', тень: false });
    if (вар.id === 'палочки') {
      палочки(ctx, ЛИСТ.x + 208, y, с.принято);
      надпись(ctx, `${с.кол} × ${с.цена} =`, ЛИСТ.x + 370, y, { р: 19, цвет: цв, выр: 'right', тень: false });
      надпись(ctx, String(с.сумма), ЛИСТ.x + 440, y, { р: 21, цвет: цв, выр: 'right', тень: false, вес: 700 });
    } else {
      надпись(ctx, `${с.кол} × ${с.цена} =`, ЛИСТ.x + 330, y, { р: 19, цвет: цв, выр: 'right', тень: false });
      надпись(ctx, String(с.сумма), ЛИСТ.x + 400, y, { р: 21, цвет: цв, выр: 'right', тень: false, вес: 700 });
    }
    if (вар.id === 'печать') штамп(ctx, ЛИСТ.x + 434, y, с.печать);
    if (!с.отмечена) return;
    // пометка проверяющего: что именно не так
    ctx.strokeStyle = '#9e2b25';
    ctx.lineWidth = 3;
    ctx.beginPath();
    const пометка = (x, ш, текст, тх) => {
      ctx.ellipse(x, y, ш, 17, -0.1, 0, Math.PI * 2);
      ctx.stroke();
      if (текст) надпись(ctx, текст, тх, y - 2, { р: 16, цвет: '#9e2b25', выр: 'left', тень: false, вес: 700 });
    };
    if (вар.id === 'сумма') пометка(ЛИСТ.x + 383, 34, String(с.верно), ЛИСТ.x + 422);
    else if (вар.id === 'палочки') пометка(ЛИСТ.x + 228, 40, `${с.принято}≠${с.кол}`, ЛИСТ.x + 160);
    else if (вар.id === 'цены') пометка(ЛИСТ.x + 312, 22, String(с.поСписку), ЛИСТ.x + 410);
    else if (вар.id === 'печать') пометка(ЛИСТ.x + 434, 18, 'чужая', ЛИСТ.x + 330);
    else {
      ctx.moveTo(ЛИСТ.x + 48, y);
      ctx.lineTo(ЛИСТ.x + 404, y);
      ctx.stroke();
      надпись(ctx, `= стр. ${с.копия + 1}`, ЛИСТ.x + 410, y - 2, { р: 15, цвет: '#9e2b25', выр: 'left', тень: false, вес: 700 });
    }
  }

  function нарисовать(ctx) {
    фон(ctx, контора, 0.7);
    // лист
    ctx.fillStyle = '#e9dcbc';
    ctx.fillRect(ЛИСТ.x, 0, ЛИСТ.w, ВЫС);
    ctx.fillStyle = 'rgba(120,90,50,.08)';
    for (let y = (-сдвиг % 23 + 23) % 23; y < ВЫС; y += 23) ctx.fillRect(ЛИСТ.x, y, ЛИСТ.w, 1);
    ctx.strokeStyle = 'rgba(158,43,37,.35)';
    ctx.beginPath();
    ctx.moveTo(ЛИСТ.x + 40, 0);
    ctx.lineTo(ЛИСТ.x + 40, ВЫС);
    ctx.stroke();
    // шапка накладной уезжает вместе со строками
    const шапка = ВЫС - 60 - сдвиг;
    if (шапка > -40) {
      надпись(ctx, вар.шапка, ЛИСТ.x + ЛИСТ.w / 2, шапка, { р: 22, шрифт: ШРИФТ.титул, вес: 700, цвет: ЦВЕТ.чернила, тень: false });
      const колонки = вар.id === 'палочки' ? 'товар · принято · по накладной × цена = сумма' : вар.id === 'печать' ? 'товар · кол-во × цена = сумма · печать' : 'товар · кол-во × цена = сумма, гр.';
      надпись(ctx, колонки, ЛИСТ.x + ЛИСТ.w / 2, шапка + 26, { р: 14, цвет: '#6a5a40', тень: false });
    }
    список.forEach((с, k) => {
      const y = yСтроки(k);
      if (y < -30 || y > ВЫС + 30) return;
      if (k === наведено && !с.отмечена) {
        ctx.fillStyle = 'rgba(231,178,99,.28)';
        ctx.fillRect(ЛИСТ.x, y - ШАГ / 2 + 3, ЛИСТ.w, ШАГ - 6);
      }
      строкаЛиста(ctx, с, k, y);
      if (с.клякса) {
        ctx.fillStyle = 'rgba(26,19,9,.75)';
        ctx.beginPath();
        ctx.arc(ЛИСТ.x + 200, y, 13, 0, Math.PI * 2);
        ctx.arc(ЛИСТ.x + 214, y + 6, 7, 0, Math.PI * 2);
        ctx.fill();
      }
      if (с.ушла && с.ошибка && !с.отмечена) {
        ctx.fillStyle = 'rgba(224,127,98,.25)';
        ctx.fillRect(ЛИСТ.x, y - ШАГ / 2 + 3, ЛИСТ.w, ШАГ - 6);
      }
    });
    // край, за которым ошибку уже не поймать
    const г = ctx.createLinearGradient(0, 0, 0, 90);
    г.addColorStop(0, 'rgba(10,16,19,.95)');
    г.addColorStop(1, 'rgba(10,16,19,0)');
    ctx.fillStyle = г;
    ctx.fillRect(ЛИСТ.x, 0, ЛИСТ.w, 90);
    ctx.strokeStyle = 'rgba(224,127,98,.6)';
    ctx.setLineDash([6, 6]);
    ctx.beginPath();
    ctx.moveTo(ЛИСТ.x, 40);
    ctx.lineTo(ЛИСТ.x + ЛИСТ.w, 40);
    ctx.stroke();
    ctx.setLineDash([]);
    // счёт сбоку
    плашка(ctx, 30, 30, 190, 150);
    надпись(ctx, 'сверка', 46, 50, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.свеча, выр: 'left' });
    надпись(ctx, `поймано ${поймано} из ${ошибок}`, 46, 82, { р: 18, выр: 'left', цвет: ЦВЕТ.трава });
    надпись(ctx, `пропущено ${пропущено}`, 46, 110, { р: 18, выр: 'left', цвет: пропущено ? ЦВЕТ.ржа : ЦВЕТ.тихо });
    надпись(ctx, `кляксы ${ложных}`, 46, 138, { р: 18, выр: 'left', цвет: ложных ? ЦВЕТ.ржа : ЦВЕТ.тихо });
    const ход = ограничить(сдвиг / (ВЫС + всего * ШАГ + 20), 0, 1);
    полоса(ctx, 46, 158, 158, 6, ход, ЦВЕТ.бумага2);
    надпись(ctx, вар.имя, 125, 205, { р: 16, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо });
    if (комбо >= 2) надпись(ctx, `${комбо} подряд`, 125, 240, { р: 26, шрифт: ШРИФТ.титул, вес: 700, цвет: ЦВЕТ.свеча });
    // справка сбоку: прейскурант или образец печати
    if (прейскурант) {
      плашка(ctx, 730, 120, 210, 40 + прейскурант.length * 30, { заливка: 'rgba(233,220,188,.95)', обвод: ЦВЕТ.чернила });
      надпись(ctx, 'прейскурант', 835, 140, { р: 15, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.чернила, тень: false });
      прейскурант.forEach((п, k) => {
        надпись(ctx, `${п.товар}, ${п.мера}`, 744, 170 + k * 30, { р: 17, цвет: '#2a1f12', выр: 'left', тень: false });
        надпись(ctx, String(п.цена), 926, 170 + k * 30, { р: 18, цвет: '#2a1f12', выр: 'right', тень: false, вес: 700 });
      });
    }
    if (вар.id === 'печать') {
      плашка(ctx, 760, 120, 160, 100, { заливка: 'rgba(233,220,188,.95)', обвод: ЦВЕТ.чернила });
      надпись(ctx, 'наша печать', 840, 140, { р: 15, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.чернила, тень: false });
      штамп(ctx, 840, 182, 'наша', 22);
    }
  }

  поле.кадр(нарисовать);
  await поле.старт({
    заголовок: `Счёт · ${вар.имя}`,
    строка: `Накладная на ${всего} строк. ${вар.строка} Лист ползёт вверх: кликай по строке с ошибкой, пока она не ушла за край. Ткнёшь в верную — клякса.`,
  });

  function строкаНа(y) {
    for (let k = 0; k < список.length; k++) if (Math.abs(yСтроки(k) - y) < ШАГ / 2) return k;
    return -1;
  }

  const очки = () => ограничить((поймано - ложных * 0.5) / ошибок, 0, 1);
  поле.отладка = () => ({ вариант: вар.id, список, сдвиг, yСтроки: список.map((_, k) => yСтроки(k)) });

  return поле.играть({
    обновить(dt) {
      сдвиг += скорость * dt;
      список.forEach((с, k) => {
        if (!с.ушла && yСтроки(k) < 40) {
          с.ушла = true;
          if (с.ошибка && !с.отмечена) {
            пропущено++;
            комбо = 0;
            звуки.мимо();
            поле.дрожь(4);
            поле.слово('ошибка ушла', ЛИСТ.x + ЛИСТ.w / 2, 70, ЦВЕТ.ржа, 26);
          }
        }
      });
      if (yСтроки(список.length - 1) < 20) поле.конец(очки());
    },
    нарисовать,
    мышьДвиг(x, y) {
      наведено = x > ЛИСТ.x && x < ЛИСТ.x + ЛИСТ.w ? строкаНа(y) : -1;
    },
    мышьВниз(x, y) {
      if (x < ЛИСТ.x || x > ЛИСТ.x + ЛИСТ.w) return;
      const k = строкаНа(y);
      if (k < 0) return;
      const с = список[k];
      if (с.отмечена || с.клякса || с.ушла) return;
      if (с.ошибка) {
        с.отмечена = true;
        поймано++;
        комбо++;
        звуки.штамп();
        поле.кольцо(ЛИСТ.x + 383, yСтроки(k), '#9e2b25', 60);
        поле.слово('поймал!', ЛИСТ.x + ЛИСТ.w + 70, yСтроки(k), ЦВЕТ.свеча, 28);
        if (поймано === ошибок) {
          звуки.ура();
          поле.вспышка(ЦВЕТ.свеча, 0.15);
          поле.конец(очки());
        }
      } else {
        с.клякса = true;
        ложных++;
        комбо = 0;
        звуки.мимо();
        поле.дрожь(5);
        поле.слово('тут верно', ЛИСТ.x + ЛИСТ.w + 70, yСтроки(k), ЦВЕТ.ржа, 24);
      }
    },
  }, [0.45, 0.8]);
}
