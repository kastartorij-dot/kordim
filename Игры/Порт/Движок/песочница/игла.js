      ctx.moveTo(0, 0);
      ctx.lineTo(5, -7);
      ctx.stroke();
      // рукоять с обмоткой нитью
      ctx.rotate(-0.93);
      ctx.fillStyle = '#6b4a2c';
      ctx.fillRect(38, -5, 46, 10);
      ctx.fillStyle = '#c9b48a';
