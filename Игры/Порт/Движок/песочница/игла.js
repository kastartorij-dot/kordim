const ЦЕНТР = { x: 450, y: 330 };

function сгустить(сырые) {
  const точки = [сырые[0]];
  for (let k = 1; k < сырые.length; k++) {
    const a = сырые[k - 1];
    const b = сырые[k];
    const n = Math.max(1, Math.ceil(Math.hypot(b.x - a.x, b.y - a.y) / 4));
    for (let j = 1; j <= n; j++) точки.push({ x: a.x + (b.x - a.x) * j / n, y: a.y + (b.y - a.y) * j / n });
  }
  return точки;
}
const кривая = (f, n = 120) => Array.from({ length: n + 1 }, (_, i) => f(i / n));
const безье = (a, b, c, d) => t => {
  const u = 1 - t;
  return {
    x: u * u * u * a[0] + 3 * u * u * t * b[0] + 3 * u * t * t * c[0] + t * t * t * d[0],
    y: u * u * u * a[1] + 3 * u * u * t * b[1] + 3 * u * t * t * c[1] + t * t * t * d[1],
  };
};
const ломаная = (...пары) => пары.map(([x, y]) => ({ x, y }));
const овал = (cx, cy, rx, ry, с = -Math.PI / 2) => кривая(t => ({ x: cx + Math.cos(с + t * Math.PI * 2) * rx, y: cy + Math.sin(с + t * Math.PI * 2) * ry }));

