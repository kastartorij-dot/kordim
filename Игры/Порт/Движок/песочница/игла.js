// Игла — наколка на заказ. Зажми мышь на метке и веди иглу по контуру узора.
// Ушёл с линии — клякса; слишком быстро — клиент морщится; клиент вздрагивает — успей отпустить.
import {
  ЦВЕТ, ШИР, ВЫС, ШРИФТ, звуки, ступеньНавыка, создатьПоле, картинка, фон, надпись, полоса,
  ограничить, случайно, звук,
} from './общее.js';

export const ОПИСЬ = { id: 'игла', имя: 'Игла', где: 'Наколка на заказ' };
export const СМЫСЛ = {
  плохо: 'Линия поплыла, клякс много. Клиент платит меньше и другим тебя не посоветует.',
  нормально: 'Узор читается, рука видна. Клиент расплатился и ушёл довольный.',
  отлично: 'Чистая линия. Клиент разглядывает руку и обещает прислать знакомых.',
};

// Три штриха узора: волна, кольцо, крюк. Каждый — ломаная с шагом ~4 px.
function ломаная(f, шагов = 400) {
  const сырые = Array.from({ length: шагов + 1 }, (_, i) => f(i / шагов));
  const точки = [сырые[0]];
  for (const p of сырые) {
    const п = точки[точки.length - 1];
    if (Math.hypot(p.x - п.x, p.y - п.y) >= 4) точки.push(p);
  }
  return точки;
}
const безье = (a, b, c, d) => t => {
  const u = 1 - t;
  return {
    x: u * u * u * a.x + 3 * u * u * t * b.x + 3 * u * t * t * c.x + t * t * t * d.x,
    y: u * u * u * a.y + 3 * u * u * t * b.y + 3 * u * t * t * c.y + t * t * t * d.y,
  };
};
const УЗОР = [
  { имя: 'волна', точки: ломаная(t => ({ x: 210 + t * 520, y: 236 + Math.sin(t * Math.PI * 3) * 30 })) },
  { имя: 'кольцо', точки: ломаная(t => ({ x: 470 + Math.cos(-Math.PI / 2 + t * Math.PI * 2) * 68, y: 352 + Math.sin(-Math.PI / 2 + t * Math.PI * 2) * 68 })) },
  { имя: 'крюк', точки: ломаная(безье({ x: 640, y: 300 }, { x: 760, y: 300 }, { x: 790, y: 440 }, { x: 650, y: 420 })) },
];

export async function запустить(контейнер, { навык = 0, тихо = false, сигнал } = {}) {
  const н = ступеньНавыка(навык);
  звук.тихо = тихо;
  const поле = создатьПоле(контейнер, { подсказка: 'Зажми мышь на светлой метке и веди иглу по пунктиру. Не торопись. Вздрогнет — отпусти.', сигнал });
  const [комната, клиент] = await Promise.all([картинка('Ресурсы/Места/порт-комната-у-очага.png'), картинка('Ресурсы/Лица/port_moryak_pixel.png')]);

  const допуск = 9 + 3 * н; // насколько можно уйти с линии без кляксы
  const срыв = допуск * 2.6; // дальше — игла соскочила
  const предел = 230 + 70 * н; // px/с, быстрее — больно
  const предупр = 0.7 + 0.3 * н; // сколько видно, что клиент сейчас дёрнется
  const ВРЕМЯ = 60;

  let штрих = 0;
  let i = 0;
  let ведёт = false;
  let прошлое = null;
  let прошлоеВремя = 0;
  let скорость = 0;
  let боль = 0;
  let кляксы = 0;
  let морщины = 0;
  let соскоки = 0;
  let вовремя = 0;
  let сумОткл = 0;
  let замеров = 0;
  let пройдено = 0;
  let остыл = 0;
  let лицо = 0; // >0 — морщится
  let доВздрога = случайно(4, 7);
  let фаза = 'тихо'; // тихо | предупреждение | вздрог
  let вФазе = 0;
  let задетоВздрогом = false;
  const чернила = УЗОР.map(() => []);
  const пятна = [];
  const всегоТочек = УЗОР.reduce((с, ш) => с + ш.точки.length, 0);

  function нарисовать(ctx, t) {
    фон(ctx, комната, 0.6);
    const тремор = фаза === 'предупреждение' ? Math.sin(t * 60) * 1.5 : фаза === 'вздрог' ? Math.sin(t * 40) * 9 : 0;
    ctx.save();
    ctx.translate(тремор, тремор * 0.4);
    // кожа: рука во всё поле
    const г = ctx.createLinearGradient(0, 150, 0, 500);
    г.addColorStop(0, '#9c7458');
    г.addColorStop(0.5, '#c39a78');
    г.addColorStop(1, '#8e6a50');
    ctx.fillStyle = г;
    ctx.beginPath();
    ctx.roundRect(120, 165, 740, 315, 140);
    ctx.fill();
    ctx.strokeStyle = 'rgba(60,35,20,.5)';
    ctx.lineWidth = 2;
    ctx.stroke();
    // пунктир узора
    УЗОР.forEach((ш, k) => {
      ctx.setLineDash([5, 7]);
      ctx.strokeStyle = k === штрих ? 'rgba(40,25,15,.65)' : 'rgba(40,25,15,.28)';
      ctx.lineWidth = k === штрих ? 2 : 1.5;
      ctx.beginPath();
      ш.точки.forEach((p, j) => (j ? ctx.lineTo(p.x, p.y) : ctx.moveTo(p.x, p.y)));
      ctx.stroke();
      ctx.setLineDash([]);
      // чернила
      ctx.lineCap = 'round';
      for (const [a, b, к] of чернила[k]) {
        ctx.strokeStyle = к ? '#3a2340' : '#1d2433';
        ctx.lineWidth = к ? 5 : 3.5;
        ctx.beginPath();
        ctx.moveTo(a.x, a.y);
        ctx.lineTo(b.x, b.y);
        ctx.stroke();
      }
    });
    for (const п of пятна) {
      ctx.fillStyle = 'rgba(24,26,44,.85)';
      ctx.beginPath();
      for (let у = 0; у < 9; у++) {
        const r = п.r * (0.7 + ((у * 37) % 10) / 22);
        const a = у / 9 * Math.PI * 2;
        ctx.lineTo(п.x + Math.cos(a) * r, п.y + Math.sin(a) * r);
      }
      ctx.fill();
    }
    // метка, где продолжать
    if (штрих < УЗОР.length) {
      const p = УЗОР[штрих].точки[i];
      const пульс = 0.5 + Math.sin(t * 6) * 0.5;
      ctx.strokeStyle = ведёт ? 'rgba(231,178,99,.5)' : `rgba(255,213,138,${0.6 + пульс * 0.4})`;
      ctx.lineWidth = 2;
      ctx.beginPath();
      ctx.arc(p.x, p.y, ведёт ? 8 : 12 + пульс * 5, 0, Math.PI * 2);
      ctx.stroke();
    }
    ctx.restore();

    // игла у курсора и стрелка скорости
    const м = поле.мышь;
    if (м.внутри || ведёт) {
      const быстро = скорость / предел;
      ctx.strokeStyle = '#d9dde0';
      ctx.lineWidth = 2;
      ctx.beginPath();
      ctx.moveTo(м.x, м.y);
      ctx.lineTo(м.x + 26, м.y - 34);
      ctx.stroke();
      ctx.fillStyle = '#5b3b22';
      ctx.fillRect(м.x + 22, м.y - 46, 8, 14);
      if (ведёт) {
        ctx.strokeStyle = быстро > 1 ? ЦВЕТ.ржа : быстро > 0.75 ? ЦВЕТ.свеча : ЦВЕТ.трава;
        ctx.lineWidth = 3;
        ctx.beginPath();
        ctx.arc(м.x, м.y, 20, -Math.PI / 2, -Math.PI / 2 + Math.PI * 2 * ограничить(быстро, 0, 1));
        ctx.stroke();
      }
    }

    // клиент
    const кх = ШИР - 170;
    const ку = 18;
    const дрожь = лицо > 0 || фаза === 'вздрог' ? (Math.random() * 2 - 1) * 6 : 0;
    ctx.fillStyle = 'rgba(8,12,14,.85)';
    ctx.fillRect(кх - 6 + дрожь, ку - 6, 142, 166);
    if (клиент) {
      ctx.imageSmoothingEnabled = false;
      ctx.drawImage(клиент, кх + дрожь, ку, 130, 130);
      ctx.imageSmoothingEnabled = true;
    }
    if (лицо > 0) {
      ctx.fillStyle = `rgba(224,127,98,${лицо * 0.5})`;
      ctx.fillRect(кх + дрожь, ку, 130, 130);
    }
    const сост = фаза === 'предупреждение' ? ['напрягся…', ЦВЕТ.свеча] : фаза === 'вздрог' ? ['вздрогнул!', ЦВЕТ.ржа] : лицо > 0 ? ['морщится', ЦВЕТ.ржа] : ['спокоен', ЦВЕТ.бумага2];
    надпись(ctx, 'клиент: ' + сост[0], кх + 65, ку + 145, { р: 15, шрифт: ШРИФТ.метка, цвет: сост[1] });
    if (фаза !== 'тихо') {
      const мигает = фаза === 'вздрог' || Math.sin(t * 18) > -0.3;
      if (мигает) надпись(ctx, поле.мышь.нажата ? 'Отпусти!' : 'Жди…', 480, 120, { р: 46, шрифт: ШРИФТ.титул, вес: 700, цвет: фаза === 'вздрог' ? ЦВЕТ.ржа : '#ffd58a' });
    }

    // верх: время, узор, счёт
    const осталось = ВРЕМЯ - поле.t;
    полоса(ctx, 30, 26, 300, 6, осталось / ВРЕМЯ, осталось < 10 ? ЦВЕТ.ржа : ЦВЕТ.бумага2);
    надпись(ctx, `узор ${Math.min(штрих + 1, УЗОР.length)} из ${УЗОР.length}: ${УЗОР[Math.min(штрих, УЗОР.length - 1)].имя}`, 30, 52, { р: 17, выр: 'left' });
    надпись(ctx, `кляксы ${кляксы} · морщился ${морщины}`, 30, 76, { р: 15, выр: 'left', цвет: кляксы + морщины ? ЦВЕТ.ржа : ЦВЕТ.тихо });
  }

  поле.кадр(нарисовать);
  await поле.старт({
    заголовок: 'Игла',
    строка: 'Клиент протянул руку. Зажми мышь на светлой метке и веди по пунктиру — ровно и не спеша. Когда клиент напряжётся, отпусти кнопку, пока он не дёрнулся.',
  });

  function клякса(x, y, r, слово) {
    кляксы++;
    пятна.push({ x, y, r });
    звуки.мимо();
    поле.дрожь(5);
    поле.слово(слово, x, y - 30, ЦВЕТ.ржа, 22);
  }

  function вести(x, y, dt) {
    const ш = УЗОР[штрих];
    let лучш = i;
    let d = Infinity;
    for (let j = i; j < Math.min(ш.точки.length, i + 30); j++) {
      const дd = Math.hypot(ш.точки[j].x - x, ш.точки[j].y - y);
      if (дd < d) { d = дd; лучш = j; }
    }
    if (d > срыв) {
      ведёт = false;
      клякса(x, y, 9, 'соскочила');
      return;
    }
    сумОткл += Math.min(d / допуск, 2);
    замеров++;
    if (лучш > i) {
      пройдено += лучш - i;
      i = лучш;
      if (Math.random() < 0.25) звуки.тик(0.05);
    }
    if (прошлое) чернила[штрих].push([прошлое, { x, y }, d > допуск]);
    if (d > допуск && остыл <= 0) {
      клякса(x, y, 6 + (d - допуск) * 0.4, 'клякса');
      остыл = 0.45;
    }
    // скорость
    if (прошлое && dt > 0) скорость = скорость * 0.8 + (Math.hypot(x - прошлое.x, y - прошлое.y) / dt) * 0.2;
    прошлое = { x, y };
    if (i >= ш.точки.length - 3) {
      ведёт = false;
      звуки.звон(1100 + штрих * 220);
      поле.кольцо(x, y, ЦВЕТ.свеча, 70);
      поле.искры(x, y, ЦВЕТ.свеча, 16);
      поле.слово(`${ш.имя} — есть`, x, y - 40, ЦВЕТ.свеча, 26);
      штрих++;
      i = 0;
      прошлое = null;
      if (штрих >= УЗОР.length) поле.конец(очки());
    }
  }

  function очки() {
    const доля = пройдено / всегоТочек;
    const ровность = замеров ? 1 - ограничить(сумОткл / замеров - 0.35, 0, 1) * 0.35 : 1;
    return доля * ровность - кляксы * 0.07 - морщины * 0.05 - соскоки * 0.12 + вовремя * 0.02;
  }

  поле.отладка = () => ({ штрих, i, ведёт, фаза, точки: УЗОР[штрих]?.точки, кляксы, морщины, предел });

  return поле.играть({
    обновить(dt, t) {
      остыл -= dt;
      лицо = Math.max(0, лицо - dt * 1.5);
      скорость *= Math.pow(0.02, dt); // без движения стрелка скорости опадает
      if (ведёт) {
        if (скорость > предел) боль += dt * (скорость / предел);
        else боль = Math.max(0, боль - dt * 0.5);
        if (боль > 0.3) {
          боль = 0;
          морщины++;
          лицо = 1;
          звуки.ох();
          поле.дрожь(3);
          поле.слово('ай! медленнее', поле.мышь.x, поле.мышь.y - 40, ЦВЕТ.ржа, 22);
        }
      }
      // вздрог: копится только пока колешь
      вФазе += dt;
      if (фаза === 'тихо' && ведёт) {
        доВздрога -= dt;
        if (доВздрога <= 0) {
          фаза = 'предупреждение';
          вФазе = 0;
          звуки.тик(0.3);
        }
      } else if (фаза === 'предупреждение' && вФазе > предупр) {
        фаза = 'вздрог';
        вФазе = 0;
        задетоВздрогом = false;
        поле.дрожь(8);
      } else if (фаза === 'вздрог') {
        if (поле.мышь.нажата && !задетоВздрогом) {
          задетоВздрогом = true;
          соскоки++;
          ведёт = false;
          клякса(поле.мышь.x, поле.мышь.y, 16, 'игла сорвалась');
          лицо = 1;
        }
        if (вФазе > 0.45) {
          if (!задетоВздрогом) {
            вовремя++;
            звуки.звон(880);
            поле.слово('вовремя', 480, 170, ЦВЕТ.трава, 30);
          }
          фаза = 'тихо';
          доВздрога = случайно(5, 9);
        }
      }
      if (t >= ВРЕМЯ) поле.конец(очки());
    },
    нарисовать,
    мышьВниз(x, y) {
      if (штрих >= УЗОР.length) return;
      if (фаза === 'вздрог') return;
      const p = УЗОР[штрих].точки[i];
      if (Math.hypot(p.x - x, p.y - y) <= 18 + 6 * н) {
        ведёт = true;
        прошлое = { x, y };
        скорость = 0;
        звуки.стук();
      } else {
        поле.слово('начни с метки', p.x, p.y - 30, ЦВЕТ.бумага2, 18);
      }
    },
    мышьДвиг(x, y) {
      if (!ведёт || !поле.мышь.нажата) return;
      const сейчас = performance.now();
      const dt = прошлоеВремя ? (сейчас - прошлоеВремя) / 1000 : 0.016;
      прошлоеВремя = сейчас;
      вести(x, y, dt);
    },
    мышьВверх() {
      ведёт = false;
      прошлое = null;
      прошлоеВремя = 0;
    },
  }, [0.5, 0.8]);
}
