const ТЕМП = 96;
const ДОЛЯ = 60 / ТЕМП;
const ТАКТ = ДОЛЯ * 4;
const ПОЛЁТ = 1.9;
const ЧЕРТА = 190;
// Аккорды по тактам: пары «зов Норы — ответ зала», минор, как у таверной песни.
const АККОРДЫ = ['Am', 'G', 'Am', 'E', 'F', 'G', 'Am', 'E', 'Am', 'G', 'F', 'E', 'Am', 'Am'];
const ПАР = АККОРДЫ.length / 2;
// Ступени аккорда в малой октаве: низко, средне, высоко (основной, терция, квинта).
const ТОНЫ = {
  Am: [220, 261.6, 329.6], G: [196, 246.9, 293.7], F: [174.6, 220, 261.6], E: [164.8, 207.7, 246.9],
};
// Рисунки строки в долях такта; к концу песни гуще.
const РИСУНКИ = [
  [[0, 1, 2], [0, 2, 3], [0, 1, 2, 3]],
  [[0, 1, 1.5, 2, 3], [0, 0.5, 1, 2, 3], [0, 1, 2, 2.5, 3]],
  [[0, 0.5, 1, 1.5, 2, 3], [0, 1, 1.5, 2, 2.5, 3], [0, 0.5, 1, 2, 2.5, 3]],
];
const ВЫСОТЫ = ['низко', 'средне', 'высоко'];

function высоты(n) {
  for (;;) {
    const р = [];
    let h = Math.floor(Math.random() * 3);
    for (let k = 0; k < n; k++) {
      р.push(h);
      h = ограничить(h + выбрать([-1, -1, 0, 1, 1, 2, -2]), 0, 2);
    }
    if (new Set(р).size > 1) return р;
  }
}

// Песня: строки Норы (зов) и ответы (метки игрока). Ответ — те же доли, высоты в обратном порядке.
function песняНоры(стук) {
  const зов = [];
  const ответ = [];
  for (let п = 0; п < ПАР; п++) {
    const рисунок = выбрать(РИСУНКИ[п < 2 ? 0 : п < 5 ? 1 : 2]);
    const в = высоты(рисунок.length);
    const тз = п * 2;
    const то = тз + 1;
    рисунок.forEach((д, k) => {
      const следующая = рисунок[k + 1] ?? 4;
      зов.push({ t: (тз * 4 + д) * ДОЛЯ, h: в[k], f: ТОНЫ[АККОРДЫ[тз]][в[k]] * 2, длит: (следующая - д) * ДОЛЯ * 0.92 });
      const h = в[рисунок.length - 1 - k];
      ответ.push({ t: (то * 4 + д) * ДОЛЯ, h, f: ТОНЫ[АККОРДЫ[то]][h], длит: (следующая - д) * ДОЛЯ * 0.92 });
    });
  }
  if (!стук) return { зов, метки: ответ.map(м => ({ ...м, струна: м.h, итог: null })), ответ };
  // Стучать в такт: ладонью по столу на доли, в ответах — с затактом.
  const метки = [];
  for (let т = 0; т < АККОРДЫ.length; т++) {
    const доли = т < 4 ? [0, 2] : т % 2 ? [0, 1, 2, 3, 3.5] : [0, 1, 2, 3];
    for (const д of доли) метки.push({ t: (т * 4 + д) * ДОЛЯ, h: 1, струна: 0, f: 0, итог: null });
  }
  return { зов, метки, ответ };
}

