    // метки ответа
    for (const м of метки) {
      if (м.итог && м.итог !== 'мимо') continue;
      const x = х(м.t);
      if (x > ШИР + 30 || x < -30) continue;
      const y = линия(м.струна);
      const близко = Math.abs(м.t - песня) < окноЛадно;
      ctx.globalAlpha = м.итог === 'мимо' ? 0.3 : 1;
      ctx.fillStyle = м.итог === 'мимо' ? ЦВЕТ.ржа : близко ? '#ffd58a' : ЦВЕТ.свеча;
      ctx.beginPath();
      ctx.arc(x, y, близко ? 17 : 15, 0, Math.PI * 2);
      ctx.fill();
      ctx.fillStyle = ЦВЕТ.чернила;
      ctx.beginPath();
      ctx.arc(x, y, 6, 0, Math.PI * 2);
      ctx.fill();
      ctx.globalAlpha = 1;
    }
    // Нора
    const нх = ШИР - 196;
    const ну = 34;
    const дрожь = косится > 0 ? (Math.random() * 2 - 1) * 3 * косится : 0;
    const поёт = зовСейчас ? пульс * 4 : 0;
    ctx.save();
    ctx.translate(Math.round(нх + дрожь), Math.round(ну - поёт));
    ctx.fillStyle = 'rgba(8,12,14,.86)';
    ctx.fillRect(-6, -6, 172, 236);
    портрет(ctx, нора, 0, 0, 160, 200);
    if (косится > 0) {
      ctx.fillStyle = `rgba(224,127,98,${косится * 0.3})`;
      ctx.fillRect(0, 0, 160, 200);
    }
    ctx.strokeStyle = косится > 0 ? ЦВЕТ.ржа : зовСейчас ? ЦВЕТ.море : ЦВЕТ.линияЯрко;
    ctx.lineWidth = зовСейчас ? 2 : 1;
    ctx.strokeRect(-0.5, -0.5, 161, 201);
    const подпись = косится > 0 ? ['Нора косится', ЦВЕТ.ржа] : зовСейчас ? ['Нора поёт', ЦВЕТ.море] : ['Нора слушает зал', ЦВЕТ.бумага2];
    надпись(ctx, подпись[0], 80, 216, { р: 16, шрифт: ШРИФТ.метка, цвет: подпись[1] });
