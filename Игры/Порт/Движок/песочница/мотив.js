// Мотив — вечер с Норой в таверне. Ритм: метки летят к черте, в такт жмёшь пробел/клик
// (или три струны — A S D). Попадания играют мелодию и оживляют зал, промахи — Нора сбивается.
import {
  ЦВЕТ, ШИР, ВЫС, ШРИФТ, звуки, ступеньНавыка, создатьПоле, картинка, фон, надпись, свет, полоса,
  ограничить, выбрать, звук,
} from './общее.js';

export const ОПИСЬ = { id: 'мотив', имя: 'Мотив', где: 'Вечер с Норой в таверне' };
export const СМЫСЛ = {
  плохо: 'Нора сбивалась, зал вернулся к своим разговорам. Вечер прошёл мимо.',
  нормально: 'Отыграли ровно: зал слушал, Нора довольна вечером.',
  отлично: 'Зал притих и слушал до конца. Нора запомнит этот вечер.',
};

const ТЕМП = 92;
const ДОЛЯ = 60 / ТЕМП;
const ПОЛЁТ = 1.8;
const ЧЕРТА = 180;
const ТАКТОВ = 14;
// Рисунки такта в долях; первые такты проще, к концу гуще.
const РИСУНКИ = [
  [[0, 2], [0, 1, 2, 3], [0, 2, 3]],
  [[0, 1, 2, 3], [0, 1.5, 2, 3], [0, 2, 2.5, 3], [0, 1, 2]],
  [[0, 0.5, 1, 2, 3], [0, 1, 1.5, 2, 3], [0, 1.5, 2, 2.5, 3], [0, 0.5, 1.5, 2, 3]],
];
// Пентатоника ля: три струны — низ, середина, верх.
const НОТЫ = [220, 261.6, 293.7, 329.6, 392, 440, 523.3, 587.3, 659.3];

function партия(струн) {
  const метки = [];
  let ступень = 4;
  for (let такт = 0; такт < ТАКТОВ; такт++) {
    const рисунок = выбрать(РИСУНКИ[такт < 3 ? 0 : такт < 9 ? 1 : 2]);
    for (const д of рисунок) {
      ступень = ограничить(ступень + выбрать([-2, -1, -1, 0, 1, 1, 2]), 0, НОТЫ.length - 1);
      const струна = струн === 1 ? 0 : Math.min(2, Math.floor(ступень / 3));
      метки.push({ t: (такт * 4 + д) * ДОЛЯ, струна, f: НОТЫ[ступень], итог: null });
    }
  }
  return метки;
}

export async function запустить(контейнер, { навык = 0, тихо = false, сигнал } = {}) {
  const н = ступеньНавыка(навык);
  звук.тихо = тихо;
  const поле = создатьПоле(контейнер, { подсказка: 'Жми пробел или клик, когда метка касается золотой черты. Попадай в такт — зал оживает.', сигнал });
  const [зал, нора] = await Promise.all([картинка('Ресурсы/Синий_Час/Фоны/zal_pixel.png'), картинка('Ресурсы/Лица/port_nora_linn_pixel.png')]);

  const окноТочно = 0.05 + 0.02 * н;
  const окноЛадно = 0.11 + 0.035 * н;
  let струн = 1;
  let метки = [];
  let песня = -4 * ДОЛЯ - 0.6; // время песни: 0 — первая доля первого такта
  let доляЗвук = -4;
  let жизнь = 0.45;
  let комбо = 0;
  let лучшее = 0;
  let точно = 0;
  let ладно = 0;
  let промахи = 0;
  let сбилась = 0;
  let тряскаНоры = 0;
  const вспышкаСтруны = [0, 0, 0];
  let пропуск = 0;
  const слушатели = Array.from({ length: 11 }, (_, i) => ({ x: 40 + i * 86 + Math.random() * 20, h: 60 + Math.random() * 26, порог: i / 11 }));

  const линия = с => (струн === 1 ? 372 : 312 + с * 62);

  function нарисовать(ctx) {
    const доляФаза = ((песня / ДОЛЯ) % 1 + 1) % 1;
    const пульс = Math.pow(1 - доляФаза, 3);
    фон(ctx, зал, 0.78 - жизнь * 0.4);
    // свечи над залом — ярче, когда зал живой
    for (const [x, y] of [[150, 120], [480, 90], [810, 125]]) {
      свет(ctx, x, y, 140 + жизнь * 90, 0.12 + жизнь * 0.25 + Math.random() * 0.03);
    }
    // слушатели
    for (const с of слушатели) {
      const живой = жизнь > с.порог;
      const кивок = живой ? пульс * 5 : 0;
      const y = ВЫС - с.h + кивок;
      ctx.fillStyle = живой ? '#2a2117' : '#121819';
      ctx.beginPath();
      ctx.arc(с.x, y, 17, 0, Math.PI * 2);
      ctx.fill();
      ctx.fillRect(с.x - 30, y + 14, 60, с.h);
      if (живой) {
        ctx.strokeStyle = `rgba(231,178,99,${0.35 + пульс * 0.3})`;
        ctx.lineWidth = 2;
        ctx.beginPath();
        ctx.arc(с.x, y, 17, Math.PI * 1.1, Math.PI * 1.9);
        ctx.stroke();
      }
    }
    // дорожка
    ctx.fillStyle = 'rgba(8,12,14,.72)';
    const верх = струн === 1 ? 330 : 276;
    const низ = струн === 1 ? 414 : 468;
    ctx.fillRect(0, верх, ШИР, низ - верх);
    for (let с = 0; с < струн; с++) {
      const y = линия(с);
      ctx.strokeStyle = `rgba(226,198,146,${0.18 + вспышкаСтруны[с] * 0.6})`;
      ctx.lineWidth = 1 + вспышкаСтруны[с] * 3;
      ctx.beginPath();
      ctx.moveTo(0, y);
      ctx.lineTo(ШИР, y);
      ctx.stroke();
    }
    // доли на дорожке: тонкие такты
    for (let b = Math.ceil(песня / ДОЛЯ); b < (песня + ПОЛЁТ) / ДОЛЯ + 1; b++) {
      const x = ЧЕРТА + (b * ДОЛЯ - песня) / ПОЛЁТ * (ШИР - ЧЕРТА);
      ctx.strokeStyle = b % 4 === 0 ? 'rgba(226,198,146,.22)' : 'rgba(226,198,146,.07)';
      ctx.lineWidth = 1;
      ctx.beginPath();
      ctx.moveTo(x, верх);
      ctx.lineTo(x, низ);
      ctx.stroke();
    }
    // черта
    ctx.fillStyle = `rgba(231,178,99,${0.55 + пульс * 0.45})`;
    ctx.fillRect(ЧЕРТА - 2 - пульс * 2, верх - 6, 4 + пульс * 4, низ - верх + 12);
    for (let с = 0; с < струн; с++) {
      const y = линия(с);
      ctx.strokeStyle = ЦВЕТ.свеча;
      ctx.lineWidth = 2;
      ctx.beginPath();
      ctx.arc(ЧЕРТА, y, 22 + вспышкаСтруны[с] * 8, 0, Math.PI * 2);
      ctx.stroke();
      if (струн === 3) надпись(ctx, 'ASD'[с], ЧЕРТА - 52, y, { р: 22, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.свеча, вес: 700 });
    }
    // метки
    for (const м of метки) {
      if (м.итог && м.итог !== 'мимо') continue;
      const x = ЧЕРТА + (м.t - песня) / ПОЛЁТ * (ШИР - ЧЕРТА);
      if (x > ШИР + 30 || x < -30) continue;
      const y = линия(м.струна);
      const близко = Math.abs(м.t - песня) < окноЛадно;
      ctx.globalAlpha = м.итог === 'мимо' ? 0.3 : 1;
      ctx.fillStyle = м.итог === 'мимо' ? ЦВЕТ.ржа : близко ? '#ffd58a' : ЦВЕТ.свеча;
      ctx.beginPath();
      ctx.arc(x, y, близко ? 17 : 15, 0, Math.PI * 2);
      ctx.fill();
      ctx.fillStyle = ЦВЕТ.чернила;
      ctx.beginPath();
      ctx.arc(x, y, 6, 0, Math.PI * 2);
      ctx.fill();
      ctx.globalAlpha = 1;
    }
    // Нора
    const нх = ШИР - 200;
    const ну = 40;
    const дрожь = тряскаНоры > 0 ? (Math.random() * 2 - 1) * 8 * тряскаНоры : 0;
    ctx.save();
    ctx.translate(нх + дрожь, ну - пульс * (жизнь > 0.3 ? 4 : 0));
    ctx.fillStyle = 'rgba(8,12,14,.8)';
    ctx.fillRect(-6, -6, 172, 192);
    if (нора) {
      ctx.imageSmoothingEnabled = false;
      ctx.drawImage(нора, 0, 0, 160, 160);
      ctx.imageSmoothingEnabled = true;
    }
    if (тряскаНоры > 0) {
      ctx.fillStyle = `rgba(224,127,98,${тряскаНоры * 0.45})`;
      ctx.fillRect(0, 0, 160, 160);
    }
    ctx.strokeStyle = тряскаНоры > 0 ? ЦВЕТ.ржа : ЦВЕТ.линияЯрко;
    ctx.strokeRect(-0.5, -0.5, 161, 161);
    надпись(ctx, сбилась > 0 ? 'Нора сбилась' : 'Нора поёт', 80, 172, { р: 16, шрифт: ШРИФТ.метка, цвет: сбилась > 0 ? ЦВЕТ.ржа : ЦВЕТ.бумага2 });
    ctx.restore();
    // верх: ход песни, зал, комбо
    const конецПесни = метки.length ? метки[метки.length - 1].t : 1;
    полоса(ctx, 30, 26, 360, 6, песня / конецПесни, ЦВЕТ.бумага2);
    надпись(ctx, 'зал', 30, 54, { р: 15, выр: 'left', шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо });
    полоса(ctx, 70, 49, 320, 10, жизнь, жизнь > 0.6 ? ЦВЕТ.свеча : жизнь > 0.3 ? ЦВЕТ.бумага2 : ЦВЕТ.ржа);
    if (комбо >= 3) {
      const р = 40 + Math.min(комбо, 30) * 0.8 + пульс * 6;
      надпись(ctx, `×${комбо}`, 480, 200, { р, шрифт: ШРИФТ.титул, вес: 700, цвет: комбо >= 15 ? '#ffd58a' : ЦВЕТ.свеча });
      надпись(ctx, 'в такт подряд', 480, 200 + р * 0.6, { р: 15, цвет: ЦВЕТ.бумага2 });
    }
    if (песня < 0) {
      const отсчёт = Math.ceil(-песня / ДОЛЯ);
      if (отсчёт <= 4) надпись(ctx, ['раз', 'два', 'три', 'четыре'][4 - отсчёт], 480, 200, { р: 46 + пульс * 10, шрифт: ШРИФТ.титул, вес: 700, цвет: ЦВЕТ.бумага });
    }
  }

  поле.кадр(нарисовать);
  струн = await поле.старт({
    заголовок: 'Мотив',
    строка: 'Нора поёт, ты держишь ритм. Метки летят справа к золотой черте — бей точно в момент касания. Сначала четыре доли отсчёта.',
    кнопки: [{ текст: 'Одна струна<small>пробел или клик</small>', значение: 1 }, { текст: 'Три струны<small>клавиши A S D</small>', значение: 3 }],
  });
  if (струн === 3) поле.подсказка('Три струны: A — верхняя, S — средняя, D — нижняя. Жми, когда метка касается черты.');
  метки = партия(струн);
  const всего = метки.length;

  function удар(с) {
    let цель = null;
    for (const м of метки) {
      if (м.итог || м.струна !== с) continue;
      if (Math.abs(м.t - песня) <= окноЛадно) { цель = м; break; }
      if (м.t - песня > окноЛадно) break;
    }
    const y = линия(с);
    вспышкаСтруны[с] = 1;
    if (!цель) {
      // лишний удар: Нора косится, зал чуть остывает
      пропуск++;
      жизнь = ограничить(жизнь - 0.025, 0, 1);
      комбо = 0;
      звуки.хлоп();
      поле.слово('мимо такта', ЧЕРТА + 40, y - 34, ЦВЕТ.тихо, 18);
      return;
    }
    const откл = Math.abs(цель.t - песня);
    комбо++;
    лучшее = Math.max(лучшее, комбо);
    звуки.струна(цель.f, 0.45);
    if (откл <= окноТочно) {
      цель.итог = 'точно';
      точно++;
      жизнь = ограничить(жизнь + 0.035, 0, 1);
      поле.кольцо(ЧЕРТА, y, '#ffd58a', 70);
      поле.искры(ЧЕРТА, y, '#ffd58a', 14);
      поле.слово('точно', ЧЕРТА + 60, y - 36, '#ffd58a', 24);
      if (комбо % 10 === 0) {
        поле.вспышка(ЦВЕТ.свеча, 0.18);
        поле.слово(`${комбо} подряд!`, 480, 150, ЦВЕТ.свеча, 34);
      }
    } else {
      цель.итог = 'ладно';
      ладно++;
      жизнь = ограничить(жизнь + 0.015, 0, 1);
      поле.кольцо(ЧЕРТА, y, ЦВЕТ.бумага2, 46);
      поле.слово(цель.t > песня ? 'рано' : 'поздно', ЧЕРТА + 60, y - 36, ЦВЕТ.бумага2, 20);
    }
  }

  const очки = () => (точно + ладно * 0.6) / всего - Math.min(0.15, пропуск * 0.01);

  return поле.играть({
    обновить(dt) {
      песня += dt;
      for (let с = 0; с < 3; с++) вспышкаСтруны[с] = Math.max(0, вспышкаСтруны[с] - dt * 5);
      тряскаНоры = Math.max(0, тряскаНоры - dt * 2.5);
      сбилась = Math.max(0, сбилась - dt);
      // ритм под ногами: удар на сильную долю, хлопок на слабые, отсчёт — щелчки
      while (доляЗвук * ДОЛЯ < песня + 0.12) {
        const через = доляЗвук * ДОЛЯ - песня;
        const последняя = ТАКТОВ * 4;
        if (доляЗвук < 0) звуки.тик(0.35);
        else if (доляЗвук < последняя) {
          if (доляЗвук % 2 === 0) звуки.удар(через, доляЗвук % 4 === 0 ? 0.9 : 0.55);
          else звуки.хлоп(через);
        }
        доляЗвук++;
      }
      for (const м of метки) {
        if (м.итог) continue;
        if (песня - м.t > окноЛадно) {
          м.итог = 'мимо';
          промахи++;
          комбо = 0;
          жизнь = ограничить(жизнь - 0.07, 0, 1);
          тряскаНоры = 1;
          сбилась = 0.8;
          звуки.мимо();
          поле.дрожь(4);
          поле.слово('Нора сбилась', ШИР - 120, 230, ЦВЕТ.ржа, 20);
        } else if (м.t > песня) break;
      }
      if (песня > метки[метки.length - 1].t + 1.2) поле.конец(очки());
    },
    нарисовать,
    мышьВниз(x, y) {
      if (струн === 1) return удар(0);
      const с = [0, 1, 2].reduce((лучш, i) => (Math.abs(линия(i) - y) < Math.abs(линия(лучш) - y) ? i : лучш), 0);
      удар(с);
    },
    клавиша(код) {
      if (струн === 1) {
        if (код === 'Space' || код === 'Enter') удар(0);
        return;
      }
      const с = { KeyA: 0, KeyS: 1, KeyD: 2, KeyJ: 0, KeyK: 1, KeyL: 2 }[код];
      if (с !== undefined) удар(с);
    },
  }, [0.5, 0.82]);
}
