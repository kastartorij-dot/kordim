export async function запустить(контейнер, { навык = 0, тихо = false, сигнал, вариант } = {}) {
  const н = ступеньНавыка(навык);
  звук.тихо = тихо;
  const В = взятьВариант(варианты, 'разлив', вариант);
  const вечер = ВЕЧЕРА[В.id];
  const двуКувшин = !!вечер.второй;
  const поле = создатьПоле(контейнер, {
    подсказка: 'Держи кнопку мыши или пробел — кувшин клонится и льёт. Отпускай заранее: струя ещё долетит. «Подать» — правая кнопка, Enter или кнопка справа.'
      + (двуКувшин ? ' Q или Tab — сменить кувшин.' : ''),
    сигнал,
  });
  const зал = await картинка('Ресурсы/Места/кухня-с-посудой.webp');

  const клон = 1.6 + 0.3 * н; // как быстро клонится
  const выпрям = 1.8 + 0.4 * н; // и выпрямляется
  const пенМнож = [1, 0.82, 0.64][н];
  const допуск = 5 + 2.5 * н;
  const терпение = вечер.терпение + 3 * н;

  // гости и их заказы — сразу на весь вечер; приходят по расписанию
  const гости = [];
  let когда = 0.4;
  for (let i = 0; i < вечер.гостей; i++) {
    const заказ = вечер.заказ(i);
    гости.push({ i, заказ, фраза: вечер.фраза(заказ), облик: ОБЛИКИ[i % ОБЛИКИ.length], пришёл: когда, ждал: 0, подано: [], ушёл: false, оценка: null, x: ШИР + 60 });
    // наплыв: после первых гостей — чаще
    const [а, б] = вечер.между;
    когда += случайно(а, б) * (вечер.наплыв && i >= вечер.наплыв ? 0.8 : 1);
  }

  let наклон = 0;
  let льёт = false;
  let жидкость = вечер.напиток; // что сейчас в руке (у вина — вино или вода)
  let уровень = 0, пена = 0, пролито = 0, вина = 0;
  let ковш = НАПИТКИ[вечер.напиток].ковш ?? Infinity;
  let черпает = 0;
  let въезд = 1;
  let след = []; // [время выпуска, скорость, жидкость] — что ещё в полёте
  let часы = 0;
  let чаевых = 0;
  let над = false, надКувшин = false;

  const очередь = () => гости.filter(г => !г.ушёл && г.оценка === null && г.пришёл <= часы);
  const первый = () => очередь()[0] ?? null;
  const сосуд = () => {
    const г = первый();
    if (!г) return null;
    const с = г.заказ[г.подано.length];
    return с && { ...ПОСУДА[с.посуда], ...с };
  };
  const поток = а => ЛЬЁТ_МАКС * НАПИТКИ[жидкость].поток * Math.pow(Math.max(0, (а - 0.3) / 0.7), 1.4);
  const внутри = (x, y, п) => x >= п.x && x <= п.x + п.w && y >= п.y && y <= п.y + п.h;

  function новыйСосуд() {
    уровень = 0; пена = 0; пролито = 0; вина = 0; въезд = 1; след = [];
    наклон = Math.min(наклон, 0.3);
    if (двуКувшин) жидкость = вечер.напиток;
  }

  function оценитьСосуд(с) {
    const цель = с.h * с.черта;
    const налито = уровень + пена * 0.1;
    const ош = Math.abs(налито - цель);
    const балл = о => (о <= допуск ? 1 : ограничить(1 - (о - допуск) / 32, 0, 1));
    let очки = балл(ош);
    if (с.вино) очки = 0.5 * очки + 0.5 * балл(Math.abs(вина - цель * с.вино));
    if (с.шапка) {
      const [а, б] = с.шапка;
      if (пена < а) очки -= ограничить((а - пена) / 25, 0, 0.35);
      else if (пена > б) очки -= ограничить((пена - б) / 40, 0, 0.35);
    } else if (пена > 14) очки -= ограничить((пена - 14) / 40, 0, 0.4);
    очки -= НАПИТКИ[вечер.напиток].брызги ? ограничить(пролито / 30, 0, 0.5) : ограничить(пролито / 40, 0, 0.3);
    const слово = пролито > 6 ? ['через край', ЦВЕТ.ржа] : очки >= 0.85 ? ['в самый раз!', ЦВЕТ.трава]
      : налито < цель - допуск ? ['недолив', ЦВЕТ.свеча] : пена > 20 && !с.шапка ? ['одна пена', ЦВЕТ.свеча]
        : с.вино && Math.abs(вина - цель * с.вино) > допуск ? [вина > цель * с.вино ? 'крепко' : 'жидко', ЦВЕТ.свеча] : ['сойдёт', ЦВЕТ.бумага];
    return { очки: ограничить(очки, 0, 1), слово };
  }

  // Гость уходит: доволен (заказ весь) или заждался. Оценка — качество налитого и скорость.
  function отпустить(г, заждался) {
    const ср = г.подано.length ? г.подано.reduce((с, о) => с + о, 0) / г.подано.length : 0;
    const запас = ограничить(1 - г.ждал / терпение, 0, 1); // сколько терпения осталось
    if (заждался) {
      г.ушёл = true;
      г.оценка = 0.5 * ср * г.подано.length / г.заказ.length;
      поле.слово(г.подано.length ? 'взял, что успел' : 'ушёл, не дождавшись', 780, 210, ЦВЕТ.ржа, 22);
      звуки.ох();
    } else {
      г.оценка = ср * (0.62 + 0.38 * Math.min(1, запас / 0.5));
      if (ср >= 0.7 && запас >= 0.4) {
        const медяк = запас >= 0.6 ? 2 : 1;
        чаевых += медяк;
        поле.слово(медяк > 1 ? 'чаевые: два медяка' : 'медяк на чай', 780, 210, ЦВЕТ.трава, 22);
        звуки.звон(1480);
      }
    }
    if (гости.every(x => x.ушёл || x.оценка !== null)) поле.конец(гости.reduce((с, x) => с + x.оценка, 0) / гости.length);
  }

  function подать() {
    const г = первый(), с = сосуд();
    if (!г || !с || въезд > 0) return;
    const { очки, слово } = оценитьСосуд(с);
    г.подано.push(очки);
    поле.слово(слово[0], ЧАША_X, СТОЙКА - с.h - 40, слово[1], 30);
    if (очки >= 0.85) { звуки.звон(1250); поле.искры(ЧАША_X, СТОЙКА - с.h, ЦВЕТ.свеча, 10); } else звуки.стук();
    льёт = false;
    новыйСосуд();
    if (г.подано.length >= г.заказ.length) отпустить(г, false);
  }

  function сменитьКувшин() {
    if (!двуКувшин) return;
    жидкость = жидкость === вечер.напиток ? вечер.второй : вечер.напиток;
    наклон = 0;
    звуки.тик(0.15);
  }

  function шаг(dt) {
    часы += dt;
    // терпение очереди
    for (const г of очередь()) {
      г.ждал = часы - г.пришёл;
      if (г.ждал >= терпение) {
        if (г === первый()) новыйСосуд();
        отпустить(г, true);
        if (поле.кончено) return;
      }
    }
    const с = сосуд();
    if (!с) { наклон = Math.max(0, наклон - выпрям * dt); return; }
    if (въезд > 0) { въезд = Math.max(0, въезд - dt * 2.4); return; }
    const нап = НАПИТКИ[жидкость];
    const держит = (льёт || поле.клавиши.has('Space')) && черпает <= 0;
    наклон = ограничить(наклон + (держит ? клон : -выпрям) * dt, 0, 1);
    // ковш: льёт, пока в нём есть; опустил ковш к котлу (отпустил до конца) — черпнёт заново
    let выпуск = ковш > 0 ? поток(наклон) : 0;
    if (Number.isFinite(ковш)) {
      ковш = Math.max(0, ковш - выпуск * dt);
      if (ковш < нап.ковш * 0.95 && наклон < 0.08 && черпает <= 0 && !держит) черпает = 0.55;
      if (черпает > 0) { черпает -= dt; if (черпает <= 0) { ковш = нап.ковш; звуки.тик(0.2); } }
    }
    след.push([часы, выпуск, жидкость]);
    let пришло = 0, чего = жидкость;
    while (след.length && часы - след[0][0] >= НАПИТКИ[след[0][2]].полёт) {
      const [, v, ж] = след.shift();
      пришло = v; чего = ж;
    }
    if (пришло > 0) {
      const н2 = НАПИТКИ[чего];
      let дол = пришло * шириной(с) * dt;
      if (н2.брызги) {
        const мимо = дол * н2.брызги * Math.pow(пришло / ЛЬЁТ_МАКС, 2);
        пролито += мимо;
        дол -= мимо;
        if (мимо > 0.3 && Math.random() < dt * 10) поле.искры(ЧАША_X, СТОЙКА - уровень, н2.верх, 2);
      }
      уровень += дол;
      if (чего === 'вино') вина += дол;
      пена += дол * н2.пенность * пенМнож * Math.pow(пришло / ЛЬЁТ_МАКС, 1.5);
      if (Math.random() < dt * 30) звуки.тик(0.05 + 0.1 * пришло / ЛЬЁТ_МАКС);
    }
    // пена оседает, немного становится напитком
    const осела = пена * НАПИТКИ[вечер.напиток].оседает * dt;
    пена -= осела;
    уровень += осела * 0.1;
    const лишнее = уровень + пена - с.h;
    if (лишнее > 0) {
      const сПены = Math.min(пена, лишнее);
      пена -= сПены;
      уровень -= лишнее - сПены;
      if (с.вино) вина = Math.min(вина, уровень);
      пролито += лишнее;
      if (Math.random() < dt * 8) звуки.ох();
    }
  }

  function кувшин(ctx) {
    const P = { x: ЧАША_X - 70, y: 200 };
    const нап = НАПИТКИ[жидкость];
    ctx.save();
    ctx.translate(P.x, P.y);
    ctx.rotate(наклон * 1.25);
    if (Number.isFinite(ковш)) {
      // ковш: чаша на длинной ручке
      ctx.strokeStyle = '#5b412a';
      ctx.lineWidth = 8;
      ctx.beginPath();
      ctx.moveTo(-20, -30);
      ctx.lineTo(-120, -110);
      ctx.stroke();
      ctx.fillStyle = '#6d5a44';
      ctx.beginPath();
      ctx.moveTo(-40, -40);
      ctx.quadraticCurveTo(-30, 30, 20, 20);
      ctx.lineTo(28, -60);
      ctx.closePath();
      ctx.fill();
      const доля = ковш / нап.ковш;
      if (доля > 0.02) {
        ctx.fillStyle = нап.верх;
        ctx.fillRect(-28, -40, 50, 10 + 40 * доля);
      }
    } else {
      ctx.fillStyle = жидкость === 'вода' ? '#6c7a7c' : '#7b5a3a';
      ctx.beginPath();
      ctx.moveTo(-70, 60);
      ctx.quadraticCurveTo(-82, 0, -58, -50);
      ctx.lineTo(10, -66);
      ctx.lineTo(28, -76);
      ctx.lineTo(18, -48);
      ctx.quadraticCurveTo(22, 10, 6, 60);
      ctx.closePath();
      ctx.fill();
      ctx.fillStyle = 'rgba(255,230,180,.18)';
      ctx.fillRect(-60, -40, 6, 80);
      ctx.strokeStyle = жидкость === 'вода' ? '#4b5658' : '#5b412a';
      ctx.lineWidth = 7;
      ctx.beginPath();
      ctx.arc(-68, 0, 26, Math.PI * 0.5, Math.PI * 1.5);
      ctx.stroke();
      if (двуКувшин) надпись(ctx, нап.имя, -30, 20, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.бумага });
    }
    ctx.restore();
    const а = наклон * 1.25;
    return { x: P.x + 26 * Math.cos(а) + 74 * Math.sin(а), y: P.y + 26 * Math.sin(а) - 74 * Math.cos(а) };
  }

  function гость(ctx, г, x, t, первыйВОчереди) {
    const y = СТОЙКА - 10;
    const кач = Math.sin(t * 1.7 + г.i) * 2;
    ctx.fillStyle = г.облик.тело;
    ctx.beginPath();
    ctx.ellipse(x, y - 70 + кач, 34, 80, 0, Math.PI, 0);
    ctx.fill();
    ctx.fillStyle = г.облик.голова;
    ctx.beginPath();
    ctx.arc(x, y - 168 + кач, 22, 0, Math.PI * 2);
    ctx.fill();
    if (г.облик.шапка) {
      ctx.fillStyle = г.облик.шапка;
      ctx.fillRect(x - 24, y - 194 + кач, 48, 12);
    }
    // терпение — дуга над головой: чем меньше осталось, тем короче и краснее
    const ост = ограничить(1 - г.ждал / терпение, 0, 1);
    ctx.strokeStyle = ост < 0.3 ? ЦВЕТ.ржа : ост < 0.55 ? ЦВЕТ.свеча : ЦВЕТ.трава;
    ctx.lineWidth = 4;
    ctx.beginPath();
    ctx.arc(x, y - 168 + кач, 30, -Math.PI / 2, -Math.PI / 2 + Math.PI * 2 * ост);
    ctx.stroke();
    // сколько сосудов просит
    const осталось = г.заказ.length - г.подано.length;
    if (осталось > 1 || !первыйВОчереди) надпись(ctx, '×' + осталось, x + 30, y - 200 + кач, { р: 16, цвет: ЦВЕТ.бумага2, вес: 700 });
  }

  function нарисовать(ctx, t) {
    фон(ctx, зал, 0.7);
    свет(ctx, ЧАША_X, 160, 260, 0.2);
    // очередь — справа у окна раздачи, первый ближе к кувшину
    const оч = очередь();
    оч.slice(0, 5).forEach((г, i) => {
      const цель = 680 + i * 62;
      г.x += (цель - г.x) * 0.12;
      гость(ctx, г, г.x, t, i === 0);
    });
    // раздача
    ctx.fillStyle = '#3d2c1c';
    ctx.fillRect(0, СТОЙКА, ШИР, ВЫС - СТОЙКА);
    ctx.fillStyle = '#5c432a';
    ctx.fillRect(0, СТОЙКА, ШИР, 8);
    if (оч.length > 5) надпись(ctx, `и ещё ${оч.length - 5}`, 900, СТОЙКА - 220, { р: 15, цвет: ЦВЕТ.тихо });
    const с = сосуд();
    if (с) рисоватьСосуд(ctx, t, с);
    else {
      кувшин(ctx);
      const следующий = гости.find(г => г.пришёл > часы);
      надпись(ctx, следующий ? 'у раздачи пусто — ждёшь следующего' : '', ЧАША_X, 330, { р: 18, цвет: ЦВЕТ.тихо });
    }
    // заказ
    плашка(ctx, 40, 24, 380, 104);
    const г = первый();
    const ушло = гости.filter(x => x.ушёл).length;
    const всего = гости.length;
    const сделано = гости.filter(x => x.оценка !== null).length;
    надпись(ctx, `${В.имя.toLowerCase()} · гость ${Math.min(сделано + 1, всего)} из ${всего}`, 56, 44, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.свеча, выр: 'left' });
    if (г && с) {
      надпись(ctx, `«${г.фраза}»`, 56, 72, { р: 18, выр: 'left' });
      const что = с.посуда === 'миска' ? 'миска' : `${с.имя} ${г.заказ.length > 1 ? `${г.подано.length + 1} из ${г.заказ.length}` : ''}`;
      надпись(ctx, что + (с.шапка ? ' · с шапкой' : '') + (с.вино ? ` · вина ${Math.round(с.вино * 100)}%` : ''), 56, 100, { р: 15, выр: 'left', цвет: ЦВЕТ.бумага2 });
    } else надпись(ctx, 'Очередь пуста', 56, 76, { р: 18, выр: 'left', цвет: ЦВЕТ.тихо });
    надпись(ctx, `чаевые ${чаевых}`, 404, 100, { р: 15, выр: 'right', цвет: чаевых ? ЦВЕТ.трава : ЦВЕТ.тихо });
    if (ушло) надпись(ctx, `ушли ${ушло}`, 404, 44, { р: 14, выр: 'right', цвет: ЦВЕТ.ржа });
    // кнопки
    плашка(ctx, КНОПКА.x, КНОПКА.y, КНОПКА.w, КНОПКА.h, { заливка: над ? 'rgba(231,178,99,.25)' : 'rgba(231,178,99,.1)', обвод: ЦВЕТ.свеча });
    надпись(ctx, 'Подать', КНОПКА.x + КНОПКА.w / 2, КНОПКА.y + 22, { р: 24, шрифт: ШРИФТ.титул, вес: 700, цвет: ЦВЕТ.свеча });
    надпись(ctx, 'Enter · правая кнопка', КНОПКА.x + КНОПКА.w / 2, КНОПКА.y + 44, { р: 12, цвет: ЦВЕТ.тихо });
    if (двуКувшин) {
      плашка(ctx, СМЕНА_КУВШИНА.x, СМЕНА_КУВШИНА.y, СМЕНА_КУВШИНА.w, СМЕНА_КУВШИНА.h, { заливка: надКувшин ? 'rgba(147,199,194,.22)' : 'rgba(13,19,22,.8)', обвод: ЦВЕТ.море });
      надпись(ctx, `в руке: ${НАПИТКИ[жидкость].имя}`, СМЕНА_КУВШИНА.x + 95, СМЕНА_КУВШИНА.y + 21, { р: 18, цвет: ЦВЕТ.бумага });
      надпись(ctx, 'сменить · Q / Tab', СМЕНА_КУВШИНА.x + 95, СМЕНА_КУВШИНА.y + 43, { р: 12, цвет: ЦВЕТ.тихо });
    }
    if (Number.isFinite(ковш) && с) {
      надпись(ctx, черпает > 0 ? 'черпаешь…' : ковш <= 0 ? 'ковш пуст — отпусти' : '', 250, 150, { р: 17, цвет: ковш <= 0 ? ЦВЕТ.свеча : ЦВЕТ.тихо });
    }
    // уже обслуженные
    гости.filter(x => x.оценка !== null).forEach((x, i) => надпись(ctx, x.ушёл ? '×' : x.оценка >= 0.8 ? '●' : x.оценка >= 0.45 ? '◐' : '○', 56 + i * 22, 148, { р: 19, цвет: x.ушёл ? ЦВЕТ.ржа : x.оценка >= 0.8 ? ЦВЕТ.трава : x.оценка >= 0.45 ? ЦВЕТ.свеча : ЦВЕТ.ржа }));
  }

  function рисоватьСосуд(ctx, t, с) {
    const cx = ЧАША_X + въезд * 300;
    const x0 = cx - с.w / 2;
    const y0 = СТОЙКА - с.h;
    const нап = НАПИТКИ[вечер.напиток];
    if (пролито > 0) {
      ctx.fillStyle = 'rgba(200,150,60,.35)';
      ctx.beginPath();
      ctx.ellipse(cx, СТОЙКА + 6, с.w / 2 + Math.min(80, пролито * 1.5), 6, 0, 0, Math.PI * 2);
      ctx.fill();
    }
    ctx.fillStyle = 'rgba(180,200,190,.08)';
    ctx.fillRect(x0, y0, с.w, с.h);
    const ур = Math.min(уровень, с.h);
    const г = ctx.createLinearGradient(0, СТОЙКА - ур, 0, СТОЙКА);
    г.addColorStop(0, нап.верх);
    г.addColorStop(1, нап.низ);
    ctx.fillStyle = г;
    ctx.fillRect(x0 + 3, СТОЙКА - ур, с.w - 6, ур);
    if (с.вино) {
      // вода сверху вина — светлее
      const вв = Math.min(вина, ур);
      ctx.fillStyle = 'rgba(214,150,160,.55)';
      ctx.fillRect(x0 + 3, СТОЙКА - ур, с.w - 6, ур - вв);
    }
    if (пена > 0.5) {
      ctx.fillStyle = нап.пена;
      const пв = Math.min(пена, с.h - ур);
      ctx.fillRect(x0 + 3, СТОЙКА - ур - пв, с.w - 6, пв);
      ctx.fillStyle = 'rgba(200,180,140,.5)';
      for (let i = 0; i < с.w / 9; i++) {
        ctx.beginPath();
        ctx.arc(x0 + 6 + i * 9, СТОЙКА - ур - пв + 2 + Math.sin(i * 2.1 + t * 2) * 1.5, 3, 0, Math.PI * 2);
        ctx.fill();
      }
    }
    if (нап.брызги && ур > 4) {
      // пар над горячим
      ctx.strokeStyle = 'rgba(239,227,201,.18)';
      ctx.lineWidth = 3;
      for (let i = 0; i < 3; i++) {
        ctx.beginPath();
        const bx = x0 + с.w * (0.3 + i * 0.2);
        ctx.moveTo(bx, СТОЙКА - ур - 6);
        ctx.quadraticCurveTo(bx + 10 * Math.sin(t * 2 + i), СТОЙКА - ур - 30, bx, СТОЙКА - ур - 54);
        ctx.stroke();
      }
    }
    ctx.strokeStyle = 'rgba(220,235,225,.55)';
    ctx.lineWidth = 3;
    ctx.beginPath();
    if (с.посуда === 'миска') {
      ctx.moveTo(x0 - 6, y0);
      ctx.quadraticCurveTo(x0 + 4, СТОЙКА, cx, СТОЙКА);
      ctx.quadraticCurveTo(x0 + с.w - 4, СТОЙКА, x0 + с.w + 6, y0);
    } else {
      ctx.moveTo(x0, y0);
      ctx.lineTo(x0, СТОЙКА);
      ctx.lineTo(x0 + с.w, СТОЙКА);
      ctx.lineTo(x0 + с.w, y0);
    }
    ctx.stroke();
    if (с.ручка) {
      ctx.beginPath();
      ctx.arc(x0 + с.w + 14, y0 + с.h * 0.45, с.h * 0.22, -Math.PI / 2, Math.PI / 2);
      ctx.stroke();
    }
    const черта = (доля, слово, цвет) => {
      const чy = СТОЙКА - с.h * доля;
      ctx.strokeStyle = цвет;
      ctx.lineWidth = 2;
      ctx.beginPath();
      ctx.moveTo(x0 - 14, чy);
      ctx.lineTo(x0 + 10, чy);
      ctx.stroke();
      надпись(ctx, слово, x0 - 18, чy, { р: 13, выр: 'right', цвет, шрифт: ШРИФТ.метка });
      return чy;
    };
    const чy = черта(с.черта, с.вино ? 'вода' : 'черта', ЦВЕТ.свеча);
    if (с.вино) черта(с.черта * с.вино, 'вино', '#d47a86');
    if (с.шапка) {
      ctx.fillStyle = 'rgba(239,227,201,.12)';
      ctx.fillRect(x0 - 12, чy - с.шапка[1], 8, с.шапка[1] - с.шапка[0]);
      надпись(ctx, 'шапка', x0 - 18, чy - с.шапка[1] + 4, { р: 12, выр: 'right', цвет: ЦВЕТ.бумага2, шрифт: ШРИФТ.метка });
    }
    // кувшин и струя: толщина по высоте — то, что вылилось раньше
    const н0 = кувшин(ctx);
    const низ = СТОЙКА - ур - Math.min(пена, с.h - ур);
    if (въезд <= 0) {
      const шагов = 16;
      for (let i = 0; i < шагов; i++) {
        const доля = i / шагов;
        let v = 0, ж = жидкость;
        for (let j = след.length - 1; j >= 0; j--) {
          if (след[j][0] <= часы - доля * НАПИТКИ[след[j][2]].полёт) { v = след[j][1]; ж = след[j][2]; break; }
        }
        if (v <= 0) continue;
        const y1 = н0.y + (низ - н0.y) * доля;
        const y2 = н0.y + (низ - н0.y) * (доля + 1 / шагов);
        const x = н0.x + (cx - н0.x) * доля * 0.6;
        ctx.fillStyle = НАПИТКИ[ж].верх;
        const ш = 2 + 7 * v / ЛЬЁТ_МАКС;
        ctx.fillRect(x - ш / 2, y1, ш, y2 - y1 + 1);
      }
    }
  }

  поле.кадр(нарисовать);
  await поле.старт({ заголовок: 'Разлив · ' + В.имя.toLowerCase(), строка: вечер.строка });
  поле.отладка = () => {
    const с = сосуд();
    return {
      вариант: В.id, наклон, уровень, пена, пролито, вина, жидкость, ковш, черпает, въезд, часы, чаевых, допуск, клон, выпрям,
      сосуд: с && { w: с.w, h: с.h, черта: с.черта, шапка: с.шапка ?? null, вино: с.вино ?? null, посуда: с.посуда },
      полёт: НАПИТКИ[жидкость].полёт, поток: НАПИТКИ[жидкость].поток, пенность: НАПИТКИ[вечер.напиток].пенность * пенМнож,
      оседает: НАПИТКИ[вечер.напиток].оседает, брызги: НАПИТКИ[вечер.напиток].брызги ?? 0,
      очередь: очередь().length, гости: гости.map(г => ({ оценка: г.оценка, ушёл: г.ушёл, ждал: г.ждал })), терпение,
    };
  };

  return поле.играть({
    обновить: шаг,
    нарисовать,
    мышьДвиг(x, y) { над = внутри(x, y, КНОПКА); надКувшин = двуКувшин && внутри(x, y, СМЕНА_КУВШИНА); },
    мышьВниз(x, y, кн) {
      if (кн === 2 || внутри(x, y, КНОПКА)) return подать();
      if (двуКувшин && внутри(x, y, СМЕНА_КУВШИНА)) return сменитьКувшин();
      if (кн === 0) льёт = true;
    },
    мышьВверх() { льёт = false; },
    клавиша(код, e) {
      if (код === 'Enter' || код === 'KeyE') подать();
      else if (код === 'KeyQ' || код === 'Tab') { e?.preventDefault?.(); сменитьКувшин(); }
    },
  }, [0.45, 0.8]);
}
