// Разлив — стойка портовой таверны. Держишь — кувшин клонится и льёт; отпустил — он ещё выпрямляется,
// а струя ещё летит. Поэтому отпускать надо раньше черты. Быстрая струя гонит пену, пена оседает не сразу.
// Четыре заказа разной посуды; последний — «с шапкой», там пена нужна.
import {
  ЦВЕТ, ШИР, ВЫС, ШРИФТ, звуки, ступеньНавыка, создатьПоле, картинка, фон, надпись, плашка, полоса,
  ограничить, звук, свет,
} from './общее.js';

export const ОПИСЬ = { id: 'разлив', имя: 'Разлив', где: 'Стойка портовой таверны' };
export const СМЫСЛ = {
  плохо: 'Через край, одна пена, недолив. Гости ворчат, за стойку тебя больше не пустят.',
  нормально: 'Налито честно, стойка почти сухая. Вечер прошёл без ворчания.',
  отлично: 'Каждому — до черты, пена как надо. Такую руку за стойкой запоминают.',
};
// Ремесла за стойкой в игре нет — навык не растёт (решено за автора, см. итог Механика).
export const навык = () => 0;

const СТОЙКА = 470;
const ЧАША_X = 560;
const ПОЛЁТ = 0.18; // струя летит до чаши, секунд
const ЛЬЁТ_МАКС = 165; // уровень в «кружке» за секунду при полном наклоне
const ОСНОВА_Ш = 104;
const ЗАКАЗЫ = [
  { имя: 'кружка', w: 104, h: 190, черта: 0.82, просят: 'Кружку. До черты, не меньше.' },
  { имя: 'чарка', w: 64, h: 104, черта: 0.74, просят: 'Чарку. Только не через край.' },
  { имя: 'кувшинчик', w: 144, h: 216, черта: 0.84, просят: 'Кувшинчик на стол, полный.' },
  { имя: 'кружка с шапкой', w: 104, h: 190, черта: 0.76, шапка: [10, 28], просят: 'Кружку, и чтоб пена шапкой.' },
];
const КНОПКА = { x: 760, y: 420, w: 170, h: 64 };

export async function запустить(контейнер, { навык = 0, тихо = false, сигнал } = {}) {
  const н = ступеньНавыка(навык);
  звук.тихо = тихо;
  const поле = создатьПоле(контейнер, { подсказка: 'Держи кнопку мыши или пробел — кувшин клонится и льёт. Отпускай заранее: струя ещё долетит. «Подать» — правая кнопка, Enter или кнопка справа.', сигнал });
  const зал = await картинка('Ресурсы/Места/zal.webp');

  const клон = 1.6 + 0.3 * н; // как быстро клонится
  const выпрям = 1.3 + 0.35 * н; // и выпрямляется
  const пенность = [0.5, 0.4, 0.3][н];
  const допуск = 5 + 2.5 * н;
  const терпение = 15 + 3 * н;

  let k = 0;
  let наклон = 0;
  let льёт = false;
  let уровень = 0, пена = 0, пролито = 0;
  let ждёт = 0;
  let въезд = 1; // чаша выезжает на стойку
  let след = []; // [время выпуска, скорость] — что ещё в полёте
  let часы = 0;
  const итоги = [];
  let над = false;

  const заказ = () => ЗАКАЗЫ[k];
  const поток = а => ЛЬЁТ_МАКС * Math.pow(Math.max(0, (а - 0.3) / 0.7), 1.4);
  const внутри = (x, y, п) => x >= п.x && x <= п.x + п.w && y >= п.y && y <= п.y + п.h;

  function подать(торопили = false) {
    if (k >= ЗАКАЗЫ.length || въезд > 0) return;
    const з = заказ();
    const цель = з.h * з.черта;
    const налито = уровень + пена * 0.1;
    const ош = Math.abs(налито - цель);
    let очки = ош <= допуск ? 1 : ограничить(1 - (ош - допуск) / 32, 0, 1);
    if (з.шапка) {
      const [а, б] = з.шапка;
      if (пена < а) очки -= ограничить((а - пена) / 25, 0, 0.35);
      else if (пена > б) очки -= ограничить((пена - б) / 40, 0, 0.35);
    } else if (пена > 14) очки -= ограничить((пена - 14) / 40, 0, 0.4);
    очки -= ограничить(пролито / 40, 0, 0.3);
    if (торопили) очки *= 0.85;
    очки = ограничить(очки, 0, 1);
    итоги.push(очки);
    const сл = пролито > 6 ? ['через край', ЦВЕТ.ржа] : очки >= 0.85 ? ['в самый раз!', ЦВЕТ.трава] : налито < цель - допуск ? ['недолив', ЦВЕТ.свеча] : пена > 20 && !з.шапка ? ['одна пена', ЦВЕТ.свеча] : ['сойдёт', ЦВЕТ.бумага];
    поле.слово(сл[0], ЧАША_X, СТОЙКА - з.h - 40, сл[1], 30);
    if (очки >= 0.85) { звуки.звон(1250); поле.искры(ЧАША_X, СТОЙКА - з.h, ЦВЕТ.свеча, 10); } else звуки.стук();
    k++;
    льёт = false;
    наклон = Math.min(наклон, 0.3);
    след = [];
    if (k >= ЗАКАЗЫ.length) { поле.конец(итоги.reduce((с, о) => с + о, 0) / ЗАКАЗЫ.length); return; }
    уровень = 0; пена = 0; пролито = 0; ждёт = 0; въезд = 1;
  }

  function шаг(dt) {
    часы += dt;
    if (въезд > 0) { въезд = Math.max(0, въезд - dt * 2.2); return; }
    const з = заказ();
    const держит = льёт || поле.клавиши.has('Space');
    наклон = ограничить(наклон + (держит ? клон : -выпрям) * dt, 0, 1);
    const выпуск = поток(наклон);
    след.push([часы, выпуск]);
    // что долетело за этот шаг
    let пришло = 0;
    while (след.length && часы - след[0][0] >= ПОЛЁТ) {
      const [, v] = след.shift();
      пришло = v;
    }
    if (пришло > 0) {
      const дол = пришло * (ОСНОВА_Ш / з.w) * dt;
      уровень += дол;
      пена += дол * пенность * Math.pow(пришло / ЛЬЁТ_МАКС, 1.5) * 2.2;
      if (Math.random() < dt * 30) звуки.тик(0.05 + 0.1 * пришло / ЛЬЁТ_МАКС);
    }
    // пена оседает, немного становится пивом
    const осела = пена * 0.35 * dt;
    пена -= осела;
    уровень += осела * 0.1;
    const лишнее = уровень + пена - з.h;
    if (лишнее > 0) {
      const сПены = Math.min(пена, лишнее);
      пена -= сПены;
      уровень -= лишнее - сПены;
      пролито += лишнее;
      if (Math.random() < dt * 8) звуки.ох();
    }
    ждёт += dt;
    if (ждёт >= терпение) { поле.слово('Ну сколько можно!', ЧАША_X, 120, ЦВЕТ.ржа, 24); подать(true); }
  }

  function кувшин(ctx) {
    const P = { x: ЧАША_X - 70, y: 200 };
    ctx.save();
    ctx.translate(P.x, P.y);
    ctx.rotate(наклон * 1.25);
    ctx.fillStyle = '#7b5a3a';
    ctx.beginPath();
    ctx.moveTo(-70, 60);
    ctx.quadraticCurveTo(-82, 0, -58, -50);
    ctx.lineTo(10, -66);
    ctx.lineTo(28, -76);
    ctx.lineTo(18, -48);
    ctx.quadraticCurveTo(22, 10, 6, 60);
    ctx.closePath();
    ctx.fill();
    ctx.fillStyle = 'rgba(255,230,180,.18)';
    ctx.fillRect(-60, -40, 6, 80);
    ctx.strokeStyle = '#5b412a';
    ctx.lineWidth = 7;
    ctx.beginPath();
    ctx.arc(-80, 0, 28, Math.PI * 0.55, Math.PI * 1.45);
    ctx.stroke();
    ctx.restore();
    const а = наклон * 1.25;
    return { x: P.x + 26 * Math.cos(а) + 74 * Math.sin(а), y: P.y + 26 * Math.sin(а) - 74 * Math.cos(а) };
  }

  function нарисовать(ctx, t) {
    фон(ctx, зал, 0.7);
    свет(ctx, ЧАША_X, 160, 260, 0.2);
    // стойка
    ctx.fillStyle = '#3d2c1c';
    ctx.fillRect(0, СТОЙКА, ШИР, ВЫС - СТОЙКА);
    ctx.fillStyle = '#5c432a';
    ctx.fillRect(0, СТОЙКА, ШИР, 8);
    if (k >= ЗАКАЗЫ.length) return;
    const з = заказ();
    const cx = ЧАША_X + въезд * 420;
    const x0 = cx - з.w / 2;
    const y0 = СТОЙКА - з.h;
    // лужа
    if (пролито > 0) {
      ctx.fillStyle = 'rgba(200,150,60,.35)';
      ctx.beginPath();
      ctx.ellipse(cx, СТОЙКА + 6, з.w / 2 + Math.min(80, пролито * 1.5), 6, 0, 0, Math.PI * 2);
      ctx.fill();
    }
    // чаша: стекло толстое, мутное
    ctx.fillStyle = 'rgba(180,200,190,.08)';
    ctx.fillRect(x0, y0, з.w, з.h);
    // пиво и пена
    const ур = Math.min(уровень, з.h);
    const г = ctx.createLinearGradient(0, СТОЙКА - ур, 0, СТОЙКА);
    г.addColorStop(0, '#d79a3c');
    г.addColorStop(1, '#8a5518');
    ctx.fillStyle = г;
    ctx.fillRect(x0 + 3, СТОЙКА - ур, з.w - 6, ур);
    if (пена > 0.5) {
      ctx.fillStyle = '#f1e6cc';
      const пв = Math.min(пена, з.h - ур);
      ctx.fillRect(x0 + 3, СТОЙКА - ур - пв, з.w - 6, пв);
      ctx.fillStyle = 'rgba(200,180,140,.5)';
      for (let i = 0; i < з.w / 9; i++) {
        const bx = x0 + 6 + i * 9;
        ctx.beginPath();
        ctx.arc(bx, СТОЙКА - ур - пв + 2 + Math.sin(i * 2.1 + t * 2) * 1.5, 3, 0, Math.PI * 2);
        ctx.fill();
      }
    }
    ctx.strokeStyle = 'rgba(220,235,225,.55)';
    ctx.lineWidth = 3;
    ctx.beginPath();
    ctx.moveTo(x0, y0);
    ctx.lineTo(x0, СТОЙКА);
    ctx.lineTo(x0 + з.w, СТОЙКА);
    ctx.lineTo(x0 + з.w, y0);
    ctx.stroke();
    if (з.w > 90) {
      ctx.beginPath();
      ctx.arc(x0 + з.w + 14, y0 + з.h * 0.45, з.h * 0.22, -Math.PI / 2, Math.PI / 2);
      ctx.stroke();
    }
    // черта
    const чy = СТОЙКА - з.h * з.черта;
    ctx.strokeStyle = ЦВЕТ.свеча;
    ctx.lineWidth = 2;
    ctx.beginPath();
    ctx.moveTo(x0 - 14, чy);
    ctx.lineTo(x0 + 10, чy);
    ctx.stroke();
    надпись(ctx, 'черта', x0 - 18, чy, { р: 13, выр: 'right', цвет: ЦВЕТ.свеча, шрифт: ШРИФТ.метка });
    if (з.шапка) {
      ctx.fillStyle = 'rgba(239,227,201,.12)';
      ctx.fillRect(x0 - 12, чy - з.шапка[1], 8, з.шапка[1] - з.шапка[0]);
    }
    // кувшин и струя: толщина по высоте — то, что вылилось раньше
    const н0 = кувшин(ctx);
    const низ = СТОЙКА - ур - Math.min(пена, з.h - ур);
    if (въезд <= 0) {
      const шагов = 16;
      for (let i = 0; i < шагов; i++) {
        const доля = i / шагов;
        const когда = часы - доля * ПОЛЁТ;
        let v = 0;
        for (let j = след.length - 1; j >= 0; j--) if (след[j][0] <= когда) { v = след[j][1]; break; }
        if (v <= 0) continue;
        const y1 = н0.y + (низ - н0.y) * доля;
        const y2 = н0.y + (низ - н0.y) * (доля + 1 / шагов);
        const x = н0.x + (cx - н0.x) * доля * 0.6;
        ctx.fillStyle = 'rgba(215,154,60,.9)';
        const ш = 2 + 7 * v / ЛЬЁТ_МАКС;
        ctx.fillRect(x - ш / 2, y1, ш, y2 - y1 + 1);
      }
    }
    // заказ и кнопка
    плашка(ctx, 40, 30, 330, 92);
    надпись(ctx, `заказ ${k + 1} из ${ЗАКАЗЫ.length} · ${з.имя}`, 56, 50, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.свеча, выр: 'left' });
    надпись(ctx, `«${з.просят}»`, 56, 78, { р: 18, выр: 'left' });
    const доля = ждёт / терпение;
    полоса(ctx, 56, 100, 298, 8, доля, доля > 0.75 ? ЦВЕТ.ржа : доля > 0.45 ? ЦВЕТ.свеча : ЦВЕТ.бумага2);
    плашка(ctx, КНОПКА.x, КНОПКА.y, КНОПКА.w, КНОПКА.h, { заливка: над ? 'rgba(231,178,99,.25)' : 'rgba(231,178,99,.1)', обвод: ЦВЕТ.свеча });
    надпись(ctx, 'Подать', КНОПКА.x + КНОПКА.w / 2, КНОПКА.y + 25, { р: 24, шрифт: ШРИФТ.титул, вес: 700, цвет: ЦВЕТ.свеча });
    надпись(ctx, 'Enter · правая кнопка', КНОПКА.x + КНОПКА.w / 2, КНОПКА.y + 48, { р: 12, цвет: ЦВЕТ.тихо });
    // уже поданное
    итоги.forEach((о, i) => надпись(ctx, о >= 0.85 ? '●' : о >= 0.45 ? '◐' : '○', 60 + i * 24, 146, { р: 20, цвет: о >= 0.85 ? ЦВЕТ.трава : о >= 0.45 ? ЦВЕТ.свеча : ЦВЕТ.ржа }));
  }

  поле.кадр(нарисовать);
  await поле.старт({
    заголовок: 'Разлив',
    строка: 'Вечер в портовой таверне, у стойки очередь, а разливать некому — кувшин дали тебе. Четыре заказа: до черты, не через край, без лишней пены. Кувшин выпрямляется не сразу — отпускай раньше, чем дойдёт до черты.',
  });
  поле.отладка = () => ({ k, наклон, уровень, пена, пролито, ждёт, заказ: заказ(), итоги, кнопка: КНОПКА });

  return поле.играть({
    обновить: шаг,
    нарисовать,
    мышьДвиг(x, y) { над = внутри(x, y, КНОПКА); },
    мышьВниз(x, y, кн) {
      if (кн === 2 || внутри(x, y, КНОПКА)) return подать();
      if (кн === 0) льёт = true;
    },
    мышьВверх() { льёт = false; },
    клавиша(код) {
      if (код === 'Enter' || код === 'KeyE') подать();
    },
  }, [0.45, 0.8]);
}
