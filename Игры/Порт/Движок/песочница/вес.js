// Вес — весы в доках. Подкладывай гирьки, пока стрелка не встанет в середину, и жми «записать»,
// когда она замерла. Стрелка качается и затухает; купец торопит.
import {
  ЦВЕТ, ШИР, ВЫС, ШРИФТ, звуки, ступеньНавыка, создатьПоле, картинка, фон, надпись, плашка, полоса,
  ограничить, случайно, звук,
} from './общее.js';

export const ОПИСЬ = { id: 'вес', имя: 'Вес', где: 'Весы в доках' };
export const СМЫСЛ = {
  плохо: 'В книге неверные цифры. Старший у весов это заметит, купец тоже.',
  нормально: 'Записал верно, пусть и не быстро. Смена засчитана.',
  отлично: 'Верно и быстро — купец ушёл без ворчания, старший у весов кивнул.',
};

const ГИРИ = [10, 5, 2, 1, 0.5];
const МЕШКОВ = 3;
const ОПОРА = { x: 470, y: 230 };
const ПЛЕЧО = 190;

export async function запустить(контейнер, { навык = 0, тихо = false, сигнал } = {}) {
  const н = ступеньНавыка(навык);
  звук.тихо = тихо;
  const поле = создатьПоле(контейнер, { подсказка: 'Клик по гирьке — на чашу, клик по чаше — снять. Пробел — «записать», когда стрелка замерла посередине.', сигнал });
  const доки = await картинка('Ресурсы/Районы/доки.webp');

  // Круг 4: автору было тесно — купец ждёт в полтора раза дольше, «замерла» засчитывается чуть раньше.
  const затухание = 1.3 + 0.6 * н;
  const зона = 0.04 + 0.015 * н; // рад на шкале стрелки
  const покойСкор = 0.11; // ниже этой скорости стрелка «замерла»
  const терпение = 20 + 6 * н; // секунд на мешок

  let мешок = 0;
  let груз = 0;
  let гири = [];
  let угол = 0.3;
  let скор = 0;
  let ждёт = 0;
  let знак = 1;
  let наведено = null;
  let печать = 0;
  const книга = [];
  let реплика = '';
  let репликаЖизнь = 0;
  const сказано = new Set();

  const новыйМешок = () => {
    груз = Math.round(случайно(9, 29) * 2) / 2;
    гири = [];
    ждёт = 0;
    сказано.clear();
    скор += 1.2;
  };
  const сумма = () => гири.reduce((с, г) => с + г, 0);
  const цель = () => ограничить((груз - сумма()) * 0.05, -0.42, 0.42);
  const стрелка = () => ограничить(угол * 2.2, -0.9, 0.9);

  const лоток = ГИРИ.map((г, k) => ({ г, x: 560 + k * 74, y: 462, w: 60, h: 56 }));
  const кнопка = { x: 70, y: 462, w: 200, h: 56 };
  const чашаП = () => ({ x: ОПОРА.x + Math.cos(угол) * ПЛЕЧО, y: ОПОРА.y - Math.sin(угол) * ПЛЕЧО + 120 });
  const чашаЛ = () => ({ x: ОПОРА.x - Math.cos(угол) * ПЛЕЧО, y: ОПОРА.y + Math.sin(угол) * ПЛЕЧО + 120 });

  function сказать(s) {
    реплика = s;
    репликаЖизнь = 2.6;
  }

  function гиря(ctx, x, y, г, ярко) {
    const w = 14 + Math.sqrt(г) * 9;
    const h = 10 + Math.sqrt(г) * 6;
    ctx.fillStyle = ярко ? '#c9a46a' : '#8d7650';
    ctx.fillRect(x - w / 2, y - h, w, h);
    ctx.fillStyle = 'rgba(255,240,200,.35)';
    ctx.fillRect(x - w / 2, y - h, w, 3);
    ctx.fillStyle = ярко ? '#c9a46a' : '#8d7650';
    ctx.fillRect(x - 4, y - h - 5, 8, 5);
    надпись(ctx, г === 0.5 ? '½' : String(г), x, y - h / 2, { р: 13, цвет: ЦВЕТ.чернила, тень: false, вес: 700 });
    return h;
  }

  function нарисовать(ctx, t) {
    фон(ctx, доки, 0.62);
    // шкала стрелки
    const с = стрелка();
    const сх = ОПОРА.x;
    const су = ОПОРА.y;
    ctx.lineWidth = 14;
    ctx.strokeStyle = 'rgba(8,12,14,.75)';
    ctx.beginPath();
    ctx.arc(сх, су, 150, -Math.PI / 2 - 0.95, -Math.PI / 2 + 0.95);
    ctx.stroke();
    const спокойно = Math.abs(с) < зона && Math.abs(скор) < покойСкор;
    ctx.strokeStyle = спокойно ? 'rgba(170,201,139,.95)' : 'rgba(170,201,139,.45)';
    ctx.beginPath();
    ctx.arc(сх, су, 150, -Math.PI / 2 - зона, -Math.PI / 2 + зона);
    ctx.stroke();
    for (let k = -8; k <= 8; k++) {
      const а = -Math.PI / 2 + k * 0.11;
      ctx.strokeStyle = k === 0 ? ЦВЕТ.свеча : ЦВЕТ.линияЯрко;
      ctx.lineWidth = k === 0 ? 2 : 1;
      ctx.beginPath();
      ctx.moveTo(сх + Math.cos(а) * 158, су + Math.sin(а) * 158);
      ctx.lineTo(сх + Math.cos(а) * (k % 4 === 0 ? 172 : 166), су + Math.sin(а) * (k % 4 === 0 ? 172 : 166));
      ctx.stroke();
    }
    // стойка
    ctx.fillStyle = '#3a2c1d';
    ctx.fillRect(сх - 8, су, 16, 250);
    ctx.fillRect(сх - 70, су + 240, 140, 14);
    // стрелка
    ctx.save();
    ctx.translate(сх, су);
    ctx.rotate(с);
    ctx.fillStyle = спокойно ? ЦВЕТ.трава : ЦВЕТ.свеча;
    ctx.beginPath();
    ctx.moveTo(-4, 0);
    ctx.lineTo(0, -168);
    ctx.lineTo(4, 0);
    ctx.fill();
    ctx.restore();
    // коромысло
    ctx.save();
    ctx.translate(сх, су);
    ctx.rotate(-угол);
    ctx.fillStyle = '#6b5233';
    ctx.fillRect(-ПЛЕЧО - 6, -6, ПЛЕЧО * 2 + 12, 12);
    ctx.fillStyle = 'rgba(255,230,180,.25)';
    ctx.fillRect(-ПЛЕЧО - 6, -6, ПЛЕЧО * 2 + 12, 3);
    ctx.restore();
    ctx.fillStyle = ЦВЕТ.свеча;
    ctx.beginPath();
    ctx.arc(сх, су, 9, 0, Math.PI * 2);
    ctx.fill();
    // чаши
    for (const [ч, левая] of [[чашаЛ(), true], [чашаП(), false]]) {
      ctx.strokeStyle = 'rgba(200,180,140,.6)';
      ctx.lineWidth = 1.5;
      ctx.beginPath();
      ctx.moveTo(ч.x, ч.y - 120);
      ctx.lineTo(ч.x - 60, ч.y);
      ctx.moveTo(ч.x, ч.y - 120);
      ctx.lineTo(ч.x + 60, ч.y);
      ctx.stroke();
      ctx.fillStyle = !левая && наведено === 'чаша' ? '#8a6c44' : '#6b5233';
      ctx.beginPath();
      ctx.ellipse(ч.x, ч.y, 66, 14, 0, 0, Math.PI);
      ctx.fill();
      if (левая) {
        // мешок
        const w = 70 + груз;
        ctx.fillStyle = '#7d6a4a';
        ctx.beginPath();
        ctx.ellipse(ч.x, ч.y - 30 - груз * 0.4, w / 2, 32 + груз * 0.4, 0, 0, Math.PI * 2);
        ctx.fill();
        ctx.fillStyle = '#5c4c33';
        ctx.fillRect(ч.x - 8, ч.y - 72 - груз * 0.8, 16, 12);
        надпись(ctx, `мешок ${мешок + 1}`, ч.x, ч.y - 30 - груз * 0.4, { р: 15, шрифт: ШРИФТ.метка, цвет: '#2a2216', тень: false });
      } else {
        let y = ч.y;
        let x = ч.x - 40;
        for (const г of гири) {
          гиря(ctx, x, y, г, false);
          x += 22 + Math.sqrt(г) * 4;
          if (x > ч.x + 44) { x = ч.x - 34; y -= 26; }
        }
      }
    }
    // лоток и кнопка
    плашка(ctx, 540, 440, 390, 90);
    надпись(ctx, 'гирьки · клавиши 1–5', 735, 432, { р: 13, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо });
    лоток.forEach((л, k) => {
      гиря(ctx, л.x + л.w / 2, л.y + л.h - 6, л.г, наведено === k);
      надпись(ctx, String(k + 1), л.x + 6, л.y + 8, { р: 12, цвет: ЦВЕТ.тихо, выр: 'left' });
    });
    const кнЯрко = наведено === 'записать';
    плашка(ctx, кнопка.x, кнопка.y, кнопка.w, кнопка.h, { заливка: кнЯрко ? 'rgba(231,178,99,.25)' : 'rgba(231,178,99,.1)', обвод: ЦВЕТ.свеча });
    надпись(ctx, 'Записать', кнопка.x + кнопка.w / 2, кнопка.y + 22, { р: 22, шрифт: ШРИФТ.титул, вес: 700, цвет: ЦВЕТ.свеча });
    надпись(ctx, 'пробел', кнопка.x + кнопка.w / 2, кнопка.y + 44, { р: 12, цвет: ЦВЕТ.тихо });
    // книга
    плашка(ctx, 30, 24, 230, 40 + МЕШКОВ * 28);
    надпись(ctx, 'книга весов', 46, 42, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.свеча, выр: 'left' });
    for (let k = 0; k < МЕШКОВ; k++) {
      const з = книга[k];
      const y = 70 + k * 28;
      надпись(ctx, `мешок ${k + 1}`, 46, y, { р: 16, выр: 'left', цвет: ЦВЕТ.бумага2 });
      if (з) надпись(ctx, `${з.запись} ${з.верно ? '✓' : '✗'}`, 244, y, { р: 17, выр: 'right', цвет: з.верно ? ЦВЕТ.трава : ЦВЕТ.ржа, вес: 700 });
      else if (k === мешок) надпись(ctx, '…', 244, y, { р: 17, выр: 'right', цвет: ЦВЕТ.тихо });
    }
    if (печать > 0) {
      ctx.globalAlpha = Math.min(1, печать * 2);
      ctx.strokeStyle = ЦВЕТ.ржа;
      ctx.lineWidth = 3;
      ctx.strokeRect(150, 46 + книга.length * 28 - 28 - 12, 110, 26);
      ctx.globalAlpha = 1;
    }
    // купец
    плашка(ctx, ШИР - 250, 24, 220, 70);
    надпись(ctx, 'купец ждёт', ШИР - 236, 42, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо, выр: 'left' });
    const доля = ждёт / терпение;
    const дрожь = доля > 0.8 ? Math.sin(t * 40) * 2 : 0;
    полоса(ctx, ШИР - 236 + дрожь, 58, 192, 12, доля, доля > 0.75 ? ЦВЕТ.ржа : доля > 0.45 ? ЦВЕТ.свеча : ЦВЕТ.бумага2);
    if (репликаЖизнь > 0) {
      ctx.globalAlpha = Math.min(1, репликаЖизнь);
      плашка(ctx, ШИР - 330, 104, 300, 40, { заливка: 'rgba(239,227,201,.92)', обвод: ЦВЕТ.чернила });
      надпись(ctx, `«${реплика}»`, ШИР - 180, 124, { р: 18, цвет: ЦВЕТ.чернила, тень: false });
      ctx.globalAlpha = 1;
    }
  }

  function записать(торопили = false) {
    if (мешок >= МЕШКОВ) return;
    const с = стрелка();
    const ошибка = Math.abs(груз - сумма());
    const спокойно = Math.abs(с) < зона && Math.abs(скор) < покойСкор;
    const почтиСпокойно = Math.abs(с) < зона * 2.5 && Math.abs(скор) < покойСкор * 3;
    const точность = ошибка === 0 ? 1 : ошибка <= 0.5 ? 0.55 : ошибка <= 1 ? 0.25 : 0;
    const покой = спокойно ? 1 : почтиСпокойно ? 0.75 : 0.45;
    const спешка = 1 - Math.max(0, ждёт / терпение - 0.5) * 0.4;
    const очкиМешка = точность * покой * спешка * (торопили ? 0.7 : 1);
    const запись = Number.isInteger(сумма()) ? сумма() : сумма().toFixed(1).replace('.', ',');
    книга.push({ запись, верно: точность === 1, очки: очкиМешка });
    печать = 1;
    звуки.штамп();
    поле.дрожь(4);
    if (точность === 1 && спокойно) {
      поле.вспышка(ЦВЕТ.трава, 0.15);
      поле.слово('ровно!', ОПОРА.x, ОПОРА.y - 190, ЦВЕТ.трава, 34);
      звуки.звон(1200);
    } else if (точность === 1) {
      поле.слово('верно, но стрелка ещё ходила', ОПОРА.x, ОПОРА.y - 190, ЦВЕТ.свеча, 24);
    } else {
      поле.слово('мимо веса', ОПОРА.x, ОПОРА.y - 190, ЦВЕТ.ржа, 30);
    }
    мешок++;
    if (мешок >= МЕШКОВ) {
      поле.конец(книга.reduce((с, з) => с + з.очки, 0) / МЕШКОВ);
      return;
    }
    сказать(точность === 1 ? 'Следующий!' : 'Ты уверен? Ладно, следующий.');
    новыйМешок();
  }

  function внутри(x, y, п) {
    return x >= п.x && x <= п.x + п.w && y >= п.y && y <= п.y + п.h;
  }
  function навести(x, y) {
    наведено = null;
    const k = лоток.findIndex(л => внутри(x, y, л));
    if (k >= 0) наведено = k;
    else if (внутри(x, y, кнопка)) наведено = 'записать';
    else {
      const ч = чашаП();
      if (Math.abs(x - ч.x) < 75 && y > ч.y - 80 && y < ч.y + 20) наведено = 'чаша';
    }
  }
  function положить(г) {
    if (гири.length >= 12) return;
    гири.push(г);
    скор -= 0.35 + г * 0.05;
    звуки.стук();
    поле.дрожь(2);
    const ч = чашаП();
    поле.слово(`+${г === 0.5 ? '½' : г}`, ч.x, ч.y - 70, ЦВЕТ.бумага, 20);
  }
  function снять() {
    const г = гири.pop();
    if (г === undefined) return;
    скор += 0.3 + г * 0.04;
    звуки.тик(0.2);
    const ч = чашаП();
    поле.слово(`−${г === 0.5 ? '½' : г}`, ч.x, ч.y - 70, ЦВЕТ.тихо, 20);
  }

  новыйМешок();
  поле.кадр(нарисовать);
  await поле.старт({
    заголовок: 'Вес',
    строка: 'Три мешка на весах, купец ждёт. Подкладывай гирьки на правую чашу, пока стрелка не встанет в зелёное. Записывай, когда она замерла: качается — значит, ещё рано.',
  });
  поле.отладка = () => ({ груз, сумма: сумма(), угол, скор, стрелка: стрелка(), мешок, книга, лоток, кнопка, зона });

  return поле.играть({
    обновить(dt) {
      // коромысло: пружина к равновесию с затуханием
      const ц = цель();
      скор += (-(угол - ц) * 16 - скор * затухание) * dt;
      угол += скор * dt;
      const новыйЗнак = Math.sign(стрелка()) || 1;
      if (новыйЗнак !== знак && Math.abs(скор) > 0.05) звуки.тик(0.06);
      знак = новыйЗнак;
      печать = Math.max(0, печать - dt);
      репликаЖизнь = Math.max(0, репликаЖизнь - dt);
      ждёт += dt;
      const доля = ждёт / терпение;
      if (доля > 0.45 && !сказано.has(1)) { сказано.add(1); сказать('Ну что там?'); }
      if (доля > 0.75 && !сказано.has(2)) { сказано.add(2); сказать('Время, весовщик, время!'); звуки.ох(); }
      if (доля >= 1) {
        сказать('Пиши как есть!');
        записать(true);
      }
    },
    нарисовать,
    мышьДвиг: навести,
    мышьВниз(x, y, кн) {
      навести(x, y);
      if (кн === 2) return снять();
      if (typeof наведено === 'number') положить(ГИРИ[наведено]);
      else if (наведено === 'чаша') снять();
      else if (наведено === 'записать') записать();
    },
    клавиша(код) {
      const k = ['Digit1', 'Digit2', 'Digit3', 'Digit4', 'Digit5'].indexOf(код);
      if (k >= 0) положить(ГИРИ[k]);
      else if (код === 'Backspace' || код === 'KeyZ') снять();
      else if (код === 'Space' || код === 'Enter') записать();
    },
  }, [0.5, 0.8]);
}
