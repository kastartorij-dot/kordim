// Весы с нуля. Круг 5: автору стало просто — числа между первой версией (круг 3) и кругом 4.
export function новыеВесы({ вариант = 'мешки', навык = 0, случ = Math.random } = {}) {
  const н = ступеньНавыка(навык);
  const в = {
    вариант, случ, н, t: 0,
    затухание: 1.25 + 0.4 * н,
    зона: 0.038 + 0.01 * н, // рад на шкале стрелки
    покойСкор: 0.1, // ниже этой скорости стрелка «замерла»
    терпение: 19 + 4 * н, // секунд на мешок
    ноль: 0, // сдвиг нуля у старых весов
    мешок: 0, груз: 0, гири: [], угол: 0.3, скор: 0, ждёт: 0,
    плеск: 0, плескФаза: 0, доРывка: 0, дрожь: 0, доСыпи: 0, сыпь: 0,
    книга: [], кончено: false,
  };
  if (вариант === 'старые') в.зона *= 0.85;
  if (вариант === 'старые') в.ноль = (случ() < 0.5 ? -1 : 1) * ДЕЛЕНИЕ * (2 + Math.floor(случ() * 2));
  новыйМешок(в);
  return в;
}

function новыйМешок(в) {
  const { случ } = в;
  в.груз = Math.round((9 + случ() * 20) * 2) / 2;
  в.гири = [];
  в.ждёт = 0;
  в.скор += 1.2;
  if (в.вариант === 'бочка') в.плеск = 0.9;
  if (в.вариант === 'куры') в.доРывка = 1.2 + случ() * 2;
  if (в.вариант === 'песок') в.доСыпи = 4 + случ() * 2.5;
}

export const суммаГирь = в => в.гири.reduce((с, г) => с + г, 0);
const цель = в => ограничить((в.груз - суммаГирь(в)) * 0.05, -0.42, 0.42);
export const стрелка = в => ограничить(в.угол * 2.2 + в.ноль, -0.9, 0.9);
export const спокойно = в => Math.abs(стрелка(в) - в.ноль) < в.зона && Math.abs(в.скор) < в.покойСкор;

// Шаг физики. Возвращает событие кадра: 'рывок' | 'сыпь' | 'торопит1' | 'торопит2' | 'пора' | null.
export function шагВесов(в, dt) {
  if (в.кончено) return null;
  в.t += dt;
  let событие = null;
  // коромысло: пружина к равновесию с затуханием
  let сила = -(в.угол - цель(в)) * 16 - в.скор * в.затухание;
  if (в.вариант === 'бочка') {
    // рассол ходит своим ходом и затухает медленнее стрелки
    в.плескФаза += dt * 5.2;
    сила += Math.sin(в.плескФаза) * в.плеск * 1.4;
    в.плеск = Math.max(0, в.плеск - dt * 0.22);
  }
  if (в.вариант === 'куры') {
    в.доРывка -= dt;
    в.дрожь = в.доРывка < 0.35 ? 1 : Math.max(0, в.дрожь - dt * 4);
    if (в.доРывка <= 0) {
      в.скор += (в.случ() < 0.5 ? -1 : 1) * (0.1 + в.случ() * 0.12);
      в.доРывка = 3.2 + в.случ() * 2.2;
      событие = 'рывок';
    }
  }
  if (в.вариант === 'песок') {
    в.доСыпи -= dt;
    в.сыпь = Math.max(0, в.сыпь - dt);
    if (в.доСыпи <= 0 && в.груз > 3) {
      в.груз -= 0.5;
      в.доСыпи = 7 + в.случ() * 2.5;
      в.сыпь = 1;
      событие = 'сыпь';
    }
  }
  в.скор += сила * dt;
  в.угол += в.скор * dt;
  const было = в.ждёт / в.терпение;
  в.ждёт += dt;
  const доля = в.ждёт / в.терпение;
  if (было < 0.45 && доля >= 0.45) событие ??= 'торопит1';
  if (было < 0.75 && доля >= 0.75) событие ??= 'торопит2';
  if (доля >= 1) событие = 'пора';
  return событие;
}

export function положитьГирю(в, г) {
  if (в.кончено || в.гири.length >= 12) return false;
  в.гири.push(г);
  в.скор -= 0.35 + г * 0.05;
  if (в.вариант === 'бочка') в.плеск = Math.min(1, в.плеск + 0.25);
  return true;
}
export function снятьГирю(в) {
  const г = в.гири.pop();
  if (г === undefined) return null;
  в.скор += 0.3 + г * 0.04;
  return г;
}

// Запись мешка: верно ли, замерла ли стрелка, торопил ли купец. Возвращает запись книги.
export function записатьВес(в, торопили = false) {
  if (в.кончено) return null;
  const с = стрелка(в);
  const ошибка = Math.abs(в.груз - суммаГирь(в));
  const тихо = спокойно(в);
  const почти = Math.abs(с - в.ноль) < в.зона * 2.5 && Math.abs(в.скор) < в.покойСкор * 3;
  const точность = ошибка === 0 ? 1 : ошибка <= 0.5 ? 0.55 : ошибка <= 1 ? 0.25 : 0;
  const покой = тихо ? 1 : почти ? 0.75 : 0.45;
  const спешка = 1 - Math.max(0, в.ждёт / в.терпение - 0.5) * 0.4;
  const сумма = суммаГирь(в);
  const запись = { запись: Number.isInteger(сумма) ? сумма : сумма.toFixed(1).replace('.', ','), верно: точность === 1, спокойно: тихо, очки: точность * покой * спешка * (торопили ? 0.7 : 1) };
  в.книга.push(запись);
  в.мешок++;
  if (в.мешок >= МЕШКОВ) в.кончено = true;
  else новыйМешок(в);
  return запись;
}
