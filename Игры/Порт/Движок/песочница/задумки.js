let стильЕсть = false;
export function заголовокРаздела() {
  if (!стильЕсть) {
    стильЕсть = true;
    const с = document.createElement('style');
    с.textContent = `.пс-раздел { margin: 14px 0 2px; font: 500 14px/1 var(--шрифт-метка); letter-spacing: .1em;
      color: var(--свеча); text-transform: lowercase; border-top: 1px solid var(--линия); padding-top: 12px; }
      .пс-раздел small { display: block; margin-top: 4px; font: 400 13px/1.3 var(--шрифт-текст); letter-spacing: 0; color: var(--тихо); text-transform: none; }`;
    document.head.append(с);
  }
  const з = document.createElement('p');
  з.className = 'пс-раздел';
  з.innerHTML = 'Задумки<small>новые механики, ещё не привязаны к игре</small>';
  return з;
}
