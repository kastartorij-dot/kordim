const из = (с, [а, б]) => а + с() * (б - а);

// Сделка с нуля: рамка слева, метка посередине, сделка на трети.
export function новаяСделка({ вариант = 'тихий', навык = 0, случ = Math.random } = {}) {
  const н = ступеньНавыка(навык);
  const нрав = НРАВ[вариант] ?? НРАВ.тихий;
  return {
    вариант, нрав, случ, н, t: 0,
    время: нрав.время + 2 * н,
    ширина: 0.2 + 0.02 * н,
    медленнее: 1 - 0.07 * н,
    рамка: 0.12, скор: 0,
    цель: 0.5, куда: 0.5, резв: 2, пауза: 0.6, финт: null,
    сделка: 0.3, внутри: false, итог: null,
  };
}

function новыйХод(с) {
  const { нрав, случ } = с;
  if (случ() < нрав.стоит) с.пауза = из(случ, нрав.пауза);
  let куда;
  if (нрав.тяга && случ() < 0.75) куда = из(случ, нрав.тяга);
  else {
    const д = из(случ, нрав.даль) * (случ() < 0.5 ? -1 : 1);
    куда = с.цель + д;
    if (куда < 0.06 || куда > 0.94) куда = с.цель - д;
  }
  с.куда = ограничить(куда, 0.05, 0.95);
  с.резв = (случ() < нрав.рывок ? из(случ, [8, 12]) : из(случ, нрав.резв)) * с.медленнее;
  // финт: на полпути метка развернётся почти туда, откуда шла
  с.финт = случ() < нрав.финт ? { на: (с.цель + с.куда) / 2, назад: ограничить(с.цель + (случ() - 0.5) * 0.08, 0.05, 0.95) } : null;
}

// Один шаг. держит — нажата ли кнопка. Возвращает итог ('сошлись' | 'сорвалось' | 'время') или null.
export function шагСделки(с, dt, держит) {
  if (с.итог) return с.итог;
  с.t += dt;
  // рамка: тяжёлая, с разгоном; о левый край отскакивает, у правого встаёт
  с.скор += (держит ? 2.3 : -2.1) * dt;
  с.скор = ограничить(с.скор, -0.7, 0.7);
  с.рамка += с.скор * dt;
  const пол = с.ширина / 2;
  if (с.рамка < пол) { с.рамка = пол; с.скор = Math.abs(с.скор) > 0.15 ? -с.скор * 0.35 : 0; }
  if (с.рамка > 1 - пол) { с.рамка = 1 - пол; с.скор = Math.min(0, с.скор); }
  // метка
  if (с.пауза > 0) {
    с.пауза -= dt;
    if (с.нрав.сползает) с.цель = Math.max(0.05, с.цель - с.нрав.сползает * dt);
  } else {
    if (с.финт && Math.abs(с.цель - с.финт.на) < 0.03) { с.куда = с.финт.назад; с.финт = null; }
    с.цель += (с.куда - с.цель) * (1 - Math.exp(-с.резв * dt));
    if (Math.abs(с.куда - с.цель) < 0.012) новыйХод(с);
  }
  // сделка
  с.внутри = Math.abs(с.цель - с.рамка) < с.ширина / 2;
  с.сделка += (с.внутри ? 0.13 * с.нрав.рост : -0.085 * с.нрав.спад) * dt;
  if (с.сделка >= 1) { с.сделка = 1; с.итог = 'сошлись'; }
  else if (с.сделка <= 0) { с.сделка = 0; с.итог = 'сорвалось'; }
  else if (с.t >= с.время) с.итог = 'время';
  return с.итог;
}

// Очки по итогу: полная сделка — отлично (быстрее — больше), к сроку — по тому, сколько накопилось.
export function очкиСделки(с) {
  if (с.итог === 'сошлись') return 0.8 + 0.2 * ограничить(1 - с.t / с.время, 0, 1);
  if (с.итог === 'сорвалось') return 0.1;
  return 0.2 + 0.5 * с.сделка;
}
