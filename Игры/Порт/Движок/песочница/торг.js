let поКругу = 0;
export async function запустить(контейнер, { навык = 0, тихо = false, сигнал, вариант, просит, цены, товар } = {}) {
  const н = ступеньНавыка(навык);
  звук.тихо = тихо;
  const в = варианты.find(x => x.id === вариант) ?? варианты[поКругу++ % варианты.length];
  // Цена из игры: просит — первая цена, цены — { отлично, нормально, плохо } (что выйдет при каждом исходе).
  const первая = просит ?? ПРОСИТ;
  const итоги = цены ?? { отлично: ПОЛ, нормально: Math.round((первая + ПОЛ) / 2), плохо: первая };
  const что = товар ?? (в.id === 'упрямый' ? 'плащ' : 'кафтан');
  const поле = создатьПоле(контейнер, { подсказка: 'Держи левую кнопку (или пробел) — нажим растёт, отпусти — спадает. Держи настрой Пина в рамке.', сигнал });
  const лавка = await картинка('Ресурсы/Места/lavka.webp');

  const с = новаяСделка({ вариант: в.id, навык: н });
  let реплика = '';
  let репликаЖизнь = 0;
  let тепло = 0;
  let было = null;
  let цена = первая;

  const сказать = s => { реплика = s; репликаЖизнь = 2.4; };
  const ценаСейчас = () => Math.round(первая - (первая - итоги.отлично) * с.сделка);

  function нарисовать(ctx, t) {
    фон(ctx, лавка, 0.6);
    // Пин за прилавком: в рамке — теплеет, мимо — хмурится
    const пх = 480;
    const пу = 196;
    const злость = ограничить(1 - с.сделка * 1.4 - тепло * 0.4, 0, 1);
    const поворот = (с.цель - 0.5) * 30;
    свет(ctx, пх, пу, 210, 0.1 + тепло * 0.2, злость > 0.6 ? '224,127,98' : '231,178,99');
    ctx.fillStyle = '#1a1714';
    ctx.beginPath();
    ctx.roundRect(пх - 110, пу + 44, 220, 140, 40);
    ctx.fill();
    ctx.beginPath();
    ctx.arc(пх + поворот, пу, 52, 0, Math.PI * 2);
    ctx.fill();
    ctx.strokeStyle = злость > 0.6 ? ЦВЕТ.ржа : ЦВЕТ.бумага2;
    ctx.lineWidth = 4;
    ctx.lineCap = 'round';
    const наклон = (злость - 0.3) * 14 - тепло * 6;
    const гх = пх + поворот * 1.5;
    ctx.beginPath();
    ctx.moveTo(гх - 28, пу - 14 - наклон);
    ctx.lineTo(гх - 8, пу - 14 + наклон);
    ctx.moveTo(гх + 28, пу - 14 - наклон);
    ctx.lineTo(гх + 8, пу - 14 + наклон);
    ctx.stroke();
    ctx.beginPath();
    const улыбка = (тепло - злость * 0.6) * 14;
    ctx.moveTo(гх - 18, пу + 22);
    ctx.quadraticCurveTo(гх, пу + 22 + улыбка, гх + 18, пу + 22);
    ctx.stroke();
    ctx.fillStyle = '#2d2116';
    ctx.fillRect(0, 300, ШИР, 30);
    надпись(ctx, `Пин · ${что}`, пх, 315, { р: 18, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.бумага2 });
    // цена
    плашка(ctx, 40, 30, 270, 132);
    надпись(ctx, 'Пин уступает до', 58, 52, { р: 15, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо, выр: 'left' });
    надпись(ctx, `${цена} гр.`, 58, 96, { р: 50, шрифт: ШРИФТ.титул, вес: 700, цвет: цена <= итоги.отлично ? ЦВЕТ.трава : ЦВЕТ.свеча, выр: 'left' });
    надпись(ctx, `просил ${первая} · лучшая ${итоги.отлично}`, 58, 138, { р: 15, цвет: ЦВЕТ.бумага2, выр: 'left' });
    // вариант и время
    плашка(ctx, ШИР - 300, 30, 260, 86);
    надпись(ctx, в.имя, ШИР - 282, 52, { р: 17, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.свеча, выр: 'left' });
    надпись(ctx, 'время', ШИР - 282, 90, { р: 15, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо, выр: 'left' });
    полоса(ctx, ШИР - 220, 85, 160, 8, 1 - с.t / с.время, ЦВЕТ.бумага2);
    // шкала
    const { x, y, w, h } = ШКАЛА;
    плашка(ctx, x - 20, y - 44, w + 40, h + 96);
    надпись(ctx, 'мягко', x, y - 22, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо, выр: 'left' });
    надпись(ctx, 'давишь', x + w, y - 22, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.ржа, выр: 'right' });
    const г = ctx.createLinearGradient(x, 0, x + w, 0);
    г.addColorStop(0, 'rgba(147,199,194,.12)');
    г.addColorStop(0.7, 'rgba(231,178,99,.1)');
    г.addColorStop(1, 'rgba(224,127,98,.3)');
    ctx.fillStyle = г;
    ctx.fillRect(x, y, w, h);
    // рамка нажима
    const рл = x + (с.рамка - с.ширина / 2) * w;
    ctx.fillStyle = с.внутри ? 'rgba(170,201,139,.34)' : 'rgba(239,227,201,.12)';
    ctx.fillRect(рл, y + 3, с.ширина * w, h - 6);
    ctx.strokeStyle = с.внутри ? ЦВЕТ.трава : ЦВЕТ.бумага2;
    ctx.lineWidth = 3;
    ctx.strokeRect(рл, y + 3, с.ширина * w, h - 6);
    // настрой Пина — метка
    const мх = x + с.цель * w;
    ctx.fillStyle = ЦВЕТ.свеча;
    ctx.beginPath();
    ctx.moveTo(мх, y - 4);
    ctx.lineTo(мх + 11, y + h / 2);
    ctx.lineTo(мх, y + h + 4);
    ctx.lineTo(мх - 11, y + h / 2);
    ctx.closePath();
    ctx.fill();
    ctx.strokeStyle = ЦВЕТ.чернила;
    ctx.lineWidth = 1.5;
    ctx.stroke();
    // сделка
    надпись(ctx, 'сделка', x, y + h + 28, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо, выр: 'left' });
    полоса(ctx, x + 72, y + h + 22, w - 72, 12, с.сделка, с.сделка < 0.2 ? ЦВЕТ.ржа : ЦВЕТ.трава);
    if (репликаЖизнь > 0) {
      ctx.globalAlpha = Math.min(1, репликаЖизнь);
      плашка(ctx, пх + 74, пу - 84, 330, 42, { заливка: 'rgba(239,227,201,.94)', обвод: ЦВЕТ.чернила });
      надпись(ctx, `«${реплика}»`, пх + 239, пу - 63, { р: 18, цвет: ЦВЕТ.чернила, тень: false });
      ctx.globalAlpha = 1;
    }
  }

  поле.кадр(нарисовать);
  await поле.старт({
    заголовок: `Торг · ${в.имя}`,
    строка: `${в.строка} Пин просит ${первая}. Держи кнопку — нажим растёт, отпусти — спадает, и рамка тяжёлая: разгоняется и тормозит не сразу. Пока настрой Пина в рамке, сделка растёт; полная — «по рукам» за ${итоги.отлично}.`,
  });

  поле.отладка = () => ({ ...с, нрав: undefined, случ: undefined, цена, вариант: в.id });

  return поле.играть({
    обновить(dt) {
      const итог = шагСделки(с, dt, поле.мышь.нажата || поле.клавиши.has('Space'));
      тепло = ограничить(тепло + (с.внутри ? 2 : -2) * dt, 0, 1);
      репликаЖизнь = Math.max(0, репликаЖизнь - dt);
      if (с.внутри !== было) {
        if (с.внутри && было !== null) { сказать(с.сделка > 0.7 ? 'Ну… почти уговорил.' : 'Ну… допустим.'); звуки.тик(0.15); }
        if (!с.внутри && было) сказать(с.цель > с.рамка ? 'Это всё, что ты можешь?' : 'Ты меня грабишь?');
        было = с.внутри;
      }
      const новая = ценаСейчас();
      if (новая < цена) { звуки.тик(0.25); поле.слово('−1', 250, 90, ЦВЕТ.трава, 22); }
      цена = новая;
      if (!итог) return;
      if (итог === 'сошлись') {
        цена = итоги.отлично;
        сказать(`По рукам. ${цена}.`);
        звуки.ура();
        поле.вспышка(ЦВЕТ.трава, 0.2);
      } else if (итог === 'сорвалось') {
        цена = итоги.плохо;
        сказать(`Всё. ${цена} — или иди.`);
        поле.дрожь(8);
        звуки.мимо();
      } else {
        const о = очкиСделки(с);
        цена = о >= ПОРОГИ[0] ? итоги.нормально : итоги.плохо;
        сказать(о >= ПОРОГИ[0] ? `Ладно. ${цена}, и хватит.` : `Хватит. ${цена}.`);
      }
      поле.конец(очкиСделки(с));
    },
    нарисовать,
  }, ПОРОГИ);
}
