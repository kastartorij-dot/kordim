// Торг — у Пина. Удержание: держи кнопку — нажим растёт, отпусти — спадает. Держи метку в тёплой зоне,
// пока цена ползёт вниз. Довод — рывок вперёд (правая кнопка или D). Перегнул — Пин обиделся.
import {
  ЦВЕТ, ШИР, ВЫС, ШРИФТ, звуки, ступеньНавыка, создатьПоле, картинка, фон, надпись, плашка, полоса, свет,
  ограничить, звук,
} from './общее.js';

export const ОПИСЬ = { id: 'торг', имя: 'Торг', где: 'У Пина' };
export const СМЫСЛ = {
  плохо: 'Пин обиделся или не уступил. Берёшь по его цене — или уходишь ни с чем.',
  нормально: 'Сторговались посередине. Пин ворчит, но торг ему понравился.',
  отлично: 'Цена твоя, и Пин не в обиде — он уважает тех, кто умеет торговаться.',
};

const ВРЕМЯ = 35;
const ПРОСИТ = 48;
const ХОЧЕШЬ = 30;
const ШКАЛА = { x: 150, y: 400, w: 660, h: 44 };

export async function запустить(контейнер, { навык = 0, тихо = false, сигнал } = {}) {
  const н = ступеньНавыка(навык);
  звук.тихо = тихо;
  const поле = создатьПоле(контейнер, { подсказка: 'Держи левую кнопку (или пробел) — нажим растёт, отпусти — спадает. Держи метку в тёплой зоне. Правая кнопка или D — довод.', сигнал });
  const лавка = await картинка('Ресурсы/Места/lavka.webp');

  const ширина = 0.15 + 0.05 * н;
  const ход = 1 - 0.22 * н; // как быстро гуляет настроение Пина
  const обидчив = 0.32 - 0.08 * н;

  let нажим = 0.1;
  let скор = 0;
  let держит = false;
  let центр = 0.5;
  let уступка = 0; // 0..1 — сколько сбили от его цены к твоей
  let обида = 0;
  let доводов = 3;
  let было = '';
  let реплика = '';
  let репликаЖизнь = 0;
  let тепло = 0;
  let цена = ПРОСИТ;
  let фаза = Math.random() * 10;

  const где = () => (нажим > центр + ширина / 2 ? 'над' : нажим < центр - ширина / 2 ? 'под' : 'в');
  function сказать(s) {
    реплика = s;
    репликаЖизнь = 2.4;
  }

  function нарисовать(ctx, t) {
    фон(ctx, лавка, 0.6);
    // Пин за прилавком
    const злость = обида;
    const пх = 480;
    const пу = 210;
    свет(ctx, пх, пу, 200, 0.12 + тепло * 0.2, злость > 0.5 ? '224,127,98' : '231,178,99');
    const дрожь = где() === 'над' ? Math.sin(t * 50) * 2 * злость : 0;
    ctx.fillStyle = '#1a1714';
    ctx.beginPath();
    ctx.arc(пх + дрожь, пу, 52, 0, Math.PI * 2);
    ctx.fill();
    ctx.beginPath();
    ctx.roundRect(пх - 110, пу + 44, 220, 140, 40);
    ctx.fill();
    // брови и рот — настроение
    ctx.strokeStyle = злость > 0.6 ? ЦВЕТ.ржа : ЦВЕТ.бумага2;
    ctx.lineWidth = 4;
    ctx.lineCap = 'round';
    const наклон = (злость - 0.3) * 14 - тепло * 6;
    ctx.beginPath();
    ctx.moveTo(пх - 28 + дрожь, пу - 14 - наклон);
    ctx.lineTo(пх - 8 + дрожь, пу - 14 + наклон);
    ctx.moveTo(пх + 28 + дрожь, пу - 14 - наклон);
    ctx.lineTo(пх + 8 + дрожь, пу - 14 + наклон);
    ctx.stroke();
    ctx.beginPath();
    const улыбка = (тепло - злость) * 10;
    ctx.moveTo(пх - 18 + дрожь, пу + 22);
    ctx.quadraticCurveTo(пх + дрожь, пу + 22 + улыбка, пх + 18 + дрожь, пу + 22);
    ctx.stroke();
    // прилавок
    ctx.fillStyle = '#2d2116';
    ctx.fillRect(0, 300, ШИР, 30);
    надпись(ctx, 'Пин', пх, 315, { р: 18, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.бумага2 });
    // цена
    плашка(ctx, 60, 40, 250, 120);
    надпись(ctx, 'просит', 80, 62, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо, выр: 'left' });
    надпись(ctx, `${цена} гр.`, 80, 102, { р: 48, шрифт: ШРИФТ.титул, вес: 700, цвет: уступка > 0.99 ? ЦВЕТ.трава : ЦВЕТ.свеча, выр: 'left' });
    надпись(ctx, `ты хочешь ${ХОЧЕШЬ}`, 80, 140, { р: 15, цвет: ЦВЕТ.бумага2, выр: 'left' });
    // время и обида
    плашка(ctx, ШИР - 300, 40, 250, 92);
    надпись(ctx, 'терпение Пина', ШИР - 280, 60, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо, выр: 'left' });
    полоса(ctx, ШИР - 280, 72, 210, 12, 1 - обида, обида > 0.65 ? ЦВЕТ.ржа : обида > 0.35 ? ЦВЕТ.свеча : ЦВЕТ.трава);
    надпись(ctx, 'время', ШИР - 280, 104, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо, выр: 'left' });
    полоса(ctx, ШИР - 220, 99, 150, 8, 1 - поле.t / ВРЕМЯ, ЦВЕТ.бумага2);
    // шкала нажима
    const { x, y, w, h } = ШКАЛА;
    плашка(ctx, x - 20, y - 46, w + 40, h + 92);
    надпись(ctx, 'мягко', x, y - 24, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо, выр: 'left' });
    надпись(ctx, 'давишь', x + w, y - 24, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.ржа, выр: 'right' });
    const г = ctx.createLinearGradient(x, 0, x + w, 0);
    г.addColorStop(0, 'rgba(147,199,194,.12)');
    г.addColorStop(0.7, 'rgba(231,178,99,.1)');
    г.addColorStop(1, 'rgba(224,127,98,.35)');
    ctx.fillStyle = г;
    ctx.fillRect(x, y, w, h);
    // тёплая зона
    const зл = x + (центр - ширина / 2) * w;
    const зв = где() === 'в';
    ctx.fillStyle = зв ? 'rgba(231,178,99,.55)' : 'rgba(231,178,99,.3)';
    ctx.fillRect(зл, y, ширина * w, h);
    ctx.strokeStyle = ЦВЕТ.свеча;
    ctx.lineWidth = 2;
    ctx.strokeRect(зл, y, ширина * w, h);
    // метка
    const мх = x + нажим * w;
    ctx.fillStyle = где() === 'над' ? ЦВЕТ.ржа : ЦВЕТ.бумага;
    ctx.fillRect(мх - 4, y - 10, 8, h + 20);
    ctx.beginPath();
    ctx.moveTo(мх - 10, y - 18);
    ctx.lineTo(мх + 10, y - 18);
    ctx.lineTo(мх, y - 6);
    ctx.fill();
    // уступка
    надпись(ctx, 'уступка', x, y + h + 26, { р: 14, шрифт: ШРИФТ.метка, цвет: ЦВЕТ.тихо, выр: 'left' });
    полоса(ctx, x + 80, y + h + 20, w - 80 - 150, 12, уступка, ЦВЕТ.трава);
    надпись(ctx, `доводы: ${'●'.repeat(доводов)}${'○'.repeat(3 - доводов)}`, x + w, y + h + 26, { р: 16, цвет: ЦВЕТ.свеча, выр: 'right' });
    if (репликаЖизнь > 0) {
      ctx.globalAlpha = Math.min(1, репликаЖизнь);
      плашка(ctx, пх + 70, пу - 30, 300, 40, { заливка: 'rgba(239,227,201,.92)', обвод: ЦВЕТ.чернила });
      надпись(ctx, `«${реплика}»`, пх + 220, пу - 10, { р: 18, цвет: ЦВЕТ.чернила, тень: false });
      ctx.globalAlpha = 1;
    }
  }

  поле.кадр(нарисовать);
  await поле.старт({
    заголовок: 'Торг',
    строка: `Пин просит ${ПРОСИТ}, ты хочешь ${ХОЧЕШЬ}. Держи кнопку — давишь сильнее, отпусти — отступаешь. Пока метка в тёплой зоне, цена ползёт вниз. Зона гуляет вместе с его настроением.`,
  });

  function довод() {
    if (доводов <= 0) {
      поле.слово('доводов не осталось', ШИР / 2, 360, ЦВЕТ.тихо, 20);
      return;
    }
    доводов--;
    нажим = ограничить(нажим + 0.16, 0, 1);
    скор = 0.15;
    const мх = ШКАЛА.x + нажим * ШКАЛА.w;
    if (где() === 'в') {
      уступка = ограничить(уступка + 0.14, 0, 1);
      звуки.звон(990);
      поле.кольцо(мх, ШКАЛА.y + 22, ЦВЕТ.свеча, 80);
      поле.слово('довод!', мх, ШКАЛА.y - 50, ЦВЕТ.свеча, 32);
      сказать('Хм. Тут ты прав.');
    } else if (где() === 'над') {
      обида = ограничить(обида + 0.22, 0, 1);
      звуки.мимо();
      поле.дрожь(7);
      поле.слово('перегнул', мх, ШКАЛА.y - 50, ЦВЕТ.ржа, 30);
      сказать('Это ты мне говоришь?');
    } else {
      звуки.тик(0.2);
      поле.слово('мимо', мх, ШКАЛА.y - 50, ЦВЕТ.тихо, 22);
    }
  }

  function очки(исход) {
    if (исход === 'обиделся') return уступка * 0.3;
    if (исход === 'сошлись') return 0.68 + 0.22 * (1 - обида) + 0.1 * Math.max(0, 1 - поле.t / (ВРЕМЯ * 0.8));
    return уступка * 0.75 - обида * 0.1;
  }

  поле.отладка = () => ({ нажим, скор, центр, ширина, уступка, обида, где: где() });

  return поле.играть({
    обновить(dt, t) {
      фаза += dt * ход;
      центр = ограничить(0.55 + Math.sin(фаза * 0.5) * 0.2 + Math.sin(фаза * 1.3 + 1) * 0.06, ширина / 2 + 0.05, 1 - ширина / 2 - 0.05);
      держит = поле.мышь.нажата || поле.клавиши.has('Space');
      скор += (держит ? 2.6 : -2.2) * dt;
      скор = ограничить(скор, -0.45, 0.45);
      нажим += скор * dt;
      if (нажим <= 0) { нажим = 0; скор = Math.max(0, скор); }
      if (нажим >= 1) { нажим = 1; скор = Math.min(0, скор); }
      репликаЖизнь = Math.max(0, репликаЖизнь - dt);
      const сейчас = где();
      if (сейчас === 'в') {
        уступка = ограничить(уступка + dt * 0.075, 0, 1);
        обида = Math.max(0, обида - dt * 0.03);
        тепло = Math.min(1, тепло + dt * 2);
      } else {
        тепло = Math.max(0, тепло - dt * 2);
        if (сейчас === 'над') {
          обида = ограничить(обида + dt * обидчив * (0.6 + (нажим - центр) * 2), 0, 1);
        } else {
          уступка = ограничить(уступка - dt * 0.02, 0, 1);
          обида = Math.max(0, обида - dt * 0.04);
        }
      }
      if (сейчас !== было) {
        if (сейчас === 'в') { сказать('Ну… допустим.'); звуки.тик(0.15); }
        if (сейчас === 'над') { сказать('Ты меня грабишь?'); звуки.ох(); поле.дрожь(3); }
        if (сейчас === 'под' && было) сказать('Цена есть цена.');
        было = сейчас;
      }
      const новая = Math.round(ПРОСИТ - (ПРОСИТ - ХОЧЕШЬ) * уступка);
      if (новая < цена) {
        звуки.тик(0.25);
        поле.слово('−1', 250, 90, ЦВЕТ.трава, 22);
      }
      цена = новая;
      if (обида >= 1) {
        сказать('Всё. Иди отсюда.');
        поле.дрожь(10);
        звуки.мимо();
        поле.конец(очки('обиделся'));
      } else if (уступка >= 1) {
        сказать('По рукам.');
        звуки.ура();
        поле.вспышка(ЦВЕТ.трава, 0.2);
        поле.конец(очки('сошлись'));
      } else if (t >= ВРЕМЯ) {
        сказать('Ладно, хватит.');
        поле.конец(очки('время'));
      }
    },
    нарисовать,
    мышьВниз(x, y, кн) {
      if (кн === 2) {
        поле.мышь.нажата = false;
        довод();
      }
    },
    клавиша(код) {
      if (код === 'KeyD' || код === 'KeyE') довод();
    },
  }, [0.45, 0.8]);
}
