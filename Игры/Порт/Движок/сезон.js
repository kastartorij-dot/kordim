// S.мир.день — сквозная дата кампании. Сезон имеет собственные номер и день;
// календарные события и стадии целей остаются в своих состояниях.
// После дня 30 разрешена свободная жизнь, но сезон 2 сам собой не начинается.
import { ДЕНЬ_ФИНАЛА } from '../Данные/цели.js';

export function состояниеСезона(S) {
  const начало = S.мир.сезон?.начат ?? 1;
  const день = Math.max(1, S.мир.день - начало + 1);
  const итог = S.мир.итогСезона;
  return {
    номер: S.мир.сезон?.номер ?? 1,
    начат: начало,
    день: итог?.деньСезона ?? Math.min(ДЕНЬ_ФИНАЛА, день),
    завершён: !!итог || !!S.мир.кампанияЗавершена || день > ДЕНЬ_ФИНАЛА,
  };
}

export function обновитьСезон(S) {
  S.мир.сезон = состояниеСезона(S);
  return S.мир.сезон;
}
