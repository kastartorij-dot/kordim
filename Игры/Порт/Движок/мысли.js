// Кабинет мыслей (шаг 12). Чистая логика без DOM; данные и правила — Данные/мысли.js.
// Состояние в S.герой.мысли создаётся лениво (версию сохранения не поднимаем; в старых сейвах там пустой массив-заглушка):
//   места:  [{ id, с, ночи: [день, …], созрела: день | null }] — не больше МЫСЛЕЙ_МЕСТ;
//   можно:  [id] — предложены поводом и ждут решения игрока;
//   поводы: { id: { день, как: 'основной' | 'запасной' } } — откуда взялась, для панели.
// Герой и его мысли переживают конец сезона: сезон не трогает S.герой, сон продолжает их растить.
import { МЫСЛИ, МЫСЛЕЙ_МЕСТ, НЕ_СОН } from '../Данные/мысли.js';

export function мысли(S) {
  if (!S.герой.мысли || Array.isArray(S.герой.мысли)) S.герой.мысли = { места: [], можно: [], поводы: {} };
  const м = S.герой.мысли;
  м.места ??= []; м.можно ??= []; м.поводы ??= {};
  return м;
}
const читать = S => (S.герой.мысли && !Array.isArray(S.герой.мысли) ? S.герой.мысли : { места: [], можно: [], поводы: {} });
const журнал = (S, с) => { (S.мир.журналДня ??= []).push(с); return с; };
const имя = id => `«${МЫСЛИ[id].название}»`;

export const место = (S, id) => читать(S).места.find(x => x.id === id) ?? null;
export const созрела = (S, id) => !!место(S, id)?.созрела;
export const свободноМест = S => МЫСЛЕЙ_МЕСТ - читать(S).места.length;

// Повод: мысль появляется в «можно», если её ещё нет ни там, ни на месте. Повтор ничего не добавляет.
export function предложитьМысль(S, id, как = 'основной') {
  if (!МЫСЛИ[id]) return false;
  const м = мысли(S);
  if (м.можно.includes(id) || м.места.some(x => x.id === id)) return false;
  const первый = !м.поводы[id];
  м.поводы[id] ??= { день: S.мир.день, как };
  м.можно.push(id);
  if (первый) журнал(S, `Новая мысль: ${имя(id)}. Обдумать её можно в разделе «Герой».`);
  return true;
}

// Поводы из состояния мира: проверяются к ночи. Отпущенная мысль снова в «можно» и без нового повода — она не забыта.
export function заметитьМысли(S) {
  for (const [id, д] of Object.entries(МЫСЛИ)) {
    if (читать(S).поводы[id]) continue;
    const как = д.повод?.(S);
    if (как) предложитьМысль(S, id, как);
  }
}

export function обдумать(S, id) {
  const м = мысли(S);
  if (!м.можно.includes(id) || м.места.length >= МЫСЛЕЙ_МЕСТ) return false;
  м.можно = м.можно.filter(x => x !== id);
  м.места.push({ id, с: S.мир.день, ночи: [], созрела: null });
  журнал(S, `Мысль ${имя(id)} заняла место: нужно ${МЫСЛИ[id].ночей} полноценных сна.`);
  return true;
}

// Отпустить: ночи и все плюсы и минусы пропадают сразу; мысль остаётся в «можно» и начнётся заново с первой ночи.
export function отпустить(S, id) {
  const м = мысли(S), x = м.места.find(y => y.id === id);
  if (!x) return false;
  м.места = м.места.filter(y => y !== x);
  if (!м.можно.includes(id)) м.можно.push(id);
  журнал(S, x.созрела ? `Мысль ${имя(id)} отпущена: её плюс и минус ушли.` : `Мысль ${имя(id)} отпущена недодуманной: ${x.ночи.length} из ${МЫСЛИ[id].ночей} ночей пропали.`);
  return true;
}

// Ночь: сначала зреет то, что лежит на местах (одна ночь — одна отметка, повторно день не считается), потом новые поводы.
// сон — вариант ночлега из Данные/жильё.js или null для бессонной ночи.
export function ночьМыслей(S, сон, день = S.мир.день) {
  const полноценный = !!сон && !НЕ_СОН.includes(сон.id);
  for (const x of читать(S).места) {
    if (x.созрела) continue;
    const д = МЫСЛИ[x.id];
    if (!полноценный) { журнал(S, `Мысль ${имя(x.id)} не продвинулась: ${сон ? 'под открытым небом не выспаться' : 'ночь прошла без сна'}.`); continue; }
    if (x.ночи.includes(день)) continue;
    x.ночи.push(день);
    if (x.ночи.length >= д.ночей) { x.созрела = день; журнал(S, `Мысль созрела: ${имя(x.id)}. ${д.польза} ${д.ограничение}`); }
    else журнал(S, `Мысль ${имя(x.id)} зреет: ${x.ночи.length} из ${д.ночей} ночей.`);
  }
  заметитьМысли(S);
}

// Вклад в общую формулу проверки: зреющая −1 к своему голосу, созревшая +1 к плюсу и −1 к минусу. Итог по голосу зажат в ±1.
export function вкладМыслей(S, голос) {
  let д = 0; const кто = [];
  for (const x of читать(S).места) {
    const м = МЫСЛИ[x.id];
    if (!м) continue;
    const в = x.созрела ? (м.плюс === голос ? 1 : 0) + (м.минус === голос ? -1 : 0) : (м.плюс === голос ? -1 : 0);
    if (в) { д += в; кто.push(м.название + (x.созрела ? '' : ', зреет')); }
  }
  д = Math.max(-1, Math.min(1, д));
  return д ? { что: 'мысли: ' + кто.join('; '), д } : null;
}

// Для панели: три места, ждущие мысли и тексты; цена отказа названа заранее.
export function сводкаМыслей(S) {
  const м = читать(S);
  const карточка = (id, x) => {
    const д = МЫСЛИ[id], п = м.поводы[id];
    return {
      id, название: д.название, плюс: д.плюс, минус: д.минус, ночей: д.ночей, прожито: x?.ночи.length ?? 0, созрела: !!x?.созрела,
      откуда: п?.как === 'запасной' ? д.запасной.replace(/^Или /, '').replace(/^./, c => c.toUpperCase()) : д.откуда, день: п?.день ?? null,
      текст: x?.созрела ? д.итог : д.начало, польза: д.польза, ограничение: д.ограничение,
      цена: `Пока зреет: ${д.плюс} −1 — мысль сырая и путает.`,
      отказ: x ? (x.созрела ? 'Отпустить: плюс и минус уйдут сразу, обдумывать придётся заново.' : `Отпустить: ${x.ночи.length} из ${д.ночей} ночей пропадут.`) : null,
    };
  };
  return {
    места: Array.from({ length: МЫСЛЕЙ_МЕСТ }, (_, i) => м.места[i] ? карточка(м.места[i].id, м.места[i]) : null),
    можно: м.можно.filter(id => МЫСЛИ[id]).map(id => карточка(id, null)),
    свободно: МЫСЛЕЙ_МЕСТ - м.места.length,
  };
}

// Действия панели. Отказ от мысли — без времени и денег: цена названа на кнопке.
export function действияМыслей(S) {
  const м = читать(S), своб = свободноМест(S);
  return [
    ...м.можно.filter(id => МЫСЛИ[id]).map(id => ({ id: `мысль:обдумать:${id}`, мысль: id, текст: 'Обдумывать', можно: своб > 0, почему: своб > 0 ? null : 'все три места заняты', выполнить: S2 => обдумать(S2, id) })),
    ...м.места.map(x => ({ id: `мысль:отпустить:${x.id}`, мысль: x.id, текст: 'Отпустить', можно: true, выполнить: S2 => отпустить(S2, x.id) })),
  ];
}
