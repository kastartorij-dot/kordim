// ── запуск ───────────────────────────────────────────────────────────────
// Идёт ли игра: смена с задачей или игра в месте; игра может сказать сама (идёт(S)).
export function идёт(и, S) {
  if (typeof и.идёт === 'function') return !!и.идёт(S);
  return !!S.сцена?.игра || S.мир.смена?.стадия === 'задача';
}

// Свежее состояние с готовой обстановкой. Сид можно задать (для теста), иначе — от часов: кубики каждый раз новые.
export function запустить(и, { вариант = варианты(и)[0]?.id, ступень = 'умеешь', сид = Date.now() >>> 0 } = {}) {
  let S = новоеСостояние('семья', сид);
  S.герой.кошель = 180;
  const нет = ступени(и);
  if (нет.length && !нет.includes(ступень)) ступень = нет.includes('умеешь') ? 'умеешь' : нет[0];
  const вернул = и.начать(S, { вариант, ступень });
  if (вернул && typeof вернул === 'object' && вернул.герой && вернул.мир) S = вернул;
  if (!идёт(и, S)) throw new Error(`Стенд: игра «${и.имя}» не запустилась (вариант ${вариант ?? '—'}, ступень ${ступень})`);
  return S;
}

