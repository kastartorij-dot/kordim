// ── ремесло ──────────────────────────────────────────────────────────────
function поставитьСтупень(S, ремесло, ступень) {
  if (!ремесло || !ступень) return;
  if (ступень === 'нет') { if (S.герой.ремёсла) delete S.герой.ремёсла[ремесло]; return; }
  датьРемесло(S, ремесло);
  S.герой.ремёсла[ремесло].ступень = ступень;
}

