const ПЛАНЫ = { уход: 'уход', пауза: 'пауза на пару ночей', ничего: 'ничего не готовить' };

export function сводкаВытащить(S) {
  const в = читатьВытащить(S), с = [];
  if (!в.кто) return с;
  const р = РАБОТНИЦЫ[в.кто];
  const Э = { нет: '', слышал: `${р.имя} рассказала, чего хочет`, согласие: `${р.имя} согласна принять помощь, обещания нет`, обещание: 'Обещание дано: действовать по её слову' };
  if (Э[в.этап]) с.push(`${Э[в.этап]}.`);
  if (в.причины.length) с.push(`Причины, названные ею: ${в.причины.length} из ${р.причины.length}.`);
  if (в.ярна === 'помог') с.push('Слово Ярны передано: Ярна будет должна разговор.');
  else if (в.ярна === 'взял') с.push(`Слово Ярны: донести обеим сторонам до конца дня ${в.ярнаДо}.`);
  if (в.план) с.push(`Первое место после дома: ${ПЛАНЫ[в.план]}${в.опоры.length ? `; опоры: ${в.опоры.join(', ')}` : ''}.`);
  if (в.переговоры) с.push(`Разговор с Ярной: ${в.переговоры.итог === 'принято' ? 'условия согласованы' : 'Ярна отказала'} (${в.переговоры.способ}).`);
  if (в.решение) с.push(`Её решение: ${ИТОГИ_ВЫТАЩИТЬ[в.решение.исход]?.заголовок ?? в.решение.исход}.`);
  return с;
}

export function следующийШагВытащить(S) {
  const в = читатьВытащить(S), день = S.мир.день, р = в.кто ? РАБОТНИЦЫ[в.кто] : Object.values(РАБОТНИЦЫ)[0];
  const кто = р.имя, т = расп(S, в.кто ?? работница(S));
  if (ждёт(в, день)) return `${кто} сейчас не станет об этом говорить. Вернись через ${в.ждётДо - день} дн.: ей нужно время.`;
  if (в.решение) return 'Решение принято, оно не твоё. Дальше — тридцатый день.';
  const хвост = [];
  if (в.переговоры?.итог === 'принято') {
    return день < ВЫТАЩИТЬ.ответДни[0]
      ? `Условия согласованы. С ${ВЫТАЩИТЬ.ответДни[0]}-го дня ${кто} скажет, что решила сама: приходи на площадку у окна.`
      : `${кто} ждёт на площадке у окна: она скажет, что решила. До конца дня ${ВЫТАЩИТЬ.ответДни[1]}.`;
  }
  if (в.переговоры?.итог === 'отказ') return 'Ярна отказала. Знакомство можно продолжать и не вмешиваться. Решение не отнято ни у кого.';
  if (в.этап === 'обещание') {
    const н = [];
    if (!в.стоп && в.причины.length < р.причины.length && день <= ВЫТАЩИТЬ.причиныДни[1]) н.push('узнать, что держит её (площадка у окна, дни 6–24)');
    if (в.ярна === 'нет' && день <= ВЫТАЩИТЬ.ярнаДо) н.push('старшая в зале может передать просьбу Ярны (до дня 21)');
    if (в.ярна === 'взял') н.push(`донести слово Ярны обеим сторонам: ${в.ярнаСтороны.length}/2, до конца дня ${в.ярнаДо}`);
    if (!в.планСпрошен && день >= ВЫТАЩИТЬ.планДни[0] && день <= ВЫТАЩИТЬ.планДни[1]) н.push('спросить, куда она пошла бы первой ночью (дни 14–24)');
    if (в.план && в.план !== 'ничего' && !в.опоры.length) н.push('найти хоть одну опору для первой ночи: часовня или работа');
    if (переговорыОткрыты(S)) н.push('поговорить с Ярной в кабинете (одна попытка)');
    return `Обещание дано. ${н.length ? `Сейчас можно: ${н.join('; ')}.` : 'Ничего срочного: решение за ней.'}`;
  }
  if (в.этап === 'согласие') return `${кто} готова принять помощь без обещаний. Пообещать действовать по её слову можно на площадке; отказ ничего не стоит.`;
  if (в.этап === 'слышал') return `${кто} рассказала, чего хочет. Можно предложить помощь, не обещая ничего.`;
  if (т >= ВЫТАЩИТЬ.доступ) return `${кто} выходит поговорить на площадку у окна (лестница дома). Спроси, чего она хочет, и слушай.`;
  // Доверие словами, а не числом: те же слова, что в шапке разговора (тепло дома), раунд 2.
  const пока = т <= -1 ? 'держит с тобой дистанцию' : т >= 1 ? 'уже слушает тебя с интересом, но ещё не доверяет' : 'пока просто терпит тебя';
  // Кто она и где её увидеть — без этого цель указывает в пустой зал (PR004-05).
  return `${кто} — работница «Синего часа», её комната наверху, по лестнице из зала. Она ${пока}. Чтобы она вышла поговорить на площадку у окна, нужно её доверие: подожди её на лестнице у окна (даром, раз за вечер) или говори с ней мягко. Деньги её не купят: комната наверху (${р.комнатаЦена} гр.) — плата дому за время, доверия она не добавляет.`;
}

// ── День 30 ──────────────────────────────────────────────────────────────────
// Исход: с-одвином | одна | осталась | передумала | свободна-не-хочет | разрушено |
//        ярна-отказала | без-разговора | не-обещал | навязал | не-начал
export function исходВытащить(S) {
  const в = читатьВытащить(S);
  if (!в.кто) return в.навязал ? 'навязал' : 'не-начал';
  if (в.этап !== 'обещание') return в.навязал && в.этап === 'нет' ? 'навязал' : 'не-обещал';
  if (в.решение) return в.решение.исход;
  if (в.переговоры?.итог === 'отказ') return 'ярна-отказала';
  return 'без-разговора';
}

export function деталиВытащить(S) {
  const в = читатьВытащить(S), с = [];
  if (!в.кто) return с;
  const р = РАБОТНИЦЫ[в.кто];
  const исх = исходВытащить(S);
  if (в.этап === 'обещание') {
    с.push(`Он обещал ${р.падежи.дат} действовать только по её слову.`);
    if (в.причины.length) с.push(`Он узнал причины, названные ею самой: ${в.причины.length} из ${р.причины.length}.`);
    if (в.стоп || в.границы.length) с.push('Там, где она закрыла тему, он не настаивал.');
    if (в.ярна === 'помог') с.push('Он донёс слово Ярны обеим сторонам, и Ярна в долгу за разговор.');
    if (в.план) с.push(`Первое место после дома, которое они обсудили: ${ПЛАНЫ[в.план]}.`);
    if (в.опоры.length) с.push(`Опоры, которые он помог найти: ${в.опоры.join(', ')}.`);
    if (в.рычаг) с.push('Он использовал рычаг против Ярны. Эта цена записана за ним.');
    if (в.решение && !в.решение.выслушал) с.push('Он не пришёл выслушать её решение.');
    if (исх === 'без-разговора') {
      const не = [];
      if (в.причины.length < р.причины.length && !в.стоп) не.push('части причин, которые она держала при себе');
      if (в.ярна !== 'помог') не.push('что Ярна ответила бы на слово, которое он не передал');
      if (!в.план) не.push('куда она пошла бы первой ночью');
      с.push(`Он не успел узнать: ${не.length ? не.join('; ') : 'как бы Ярна ответила'}. И не вправе решать за неё.`);
    }
  }
  return с;
}
