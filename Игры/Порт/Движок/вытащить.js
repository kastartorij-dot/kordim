// «Вытащить» (шаг 9 плана): чистая логика без DOM. Состояние в S.мир.вытащить создаётся лениво (версию сохранения не трогаем).
// События и развилки: Документы/Материалы/История_и_цели/Четыре_цели_первого_сезона.md, карточка «Вытащить».
// Правила, которые держит весь модуль: деньги ничего здесь не покупают и доверие не поднимают; решение об уходе
// принимает сама работница по состоянию, а не кнопка игрока; успех — только исход, который она подтвердила.
// Любая работница из Данные/вытащить.js РАБОТНИЦЫ подходит без правок движка (тест требует полноты записи).
import { ВЫТАЩИТЬ, РАБОТНИЦЫ, ИТОГИ_ВЫТАЩИТЬ, ТЕКСТЫ } from '../Данные/вытащить.js';
import { взятьОбязательство, закрытьОбязательство } from './сроки.js';

const ДОМ = 'синий-час';
const новый = () => ({
  кто: null,                 // id работницы (ключ РАБОТНИЦЫ)
  этап: 'нет',               // нет | слышал | согласие | обещание
  ждётДо: null,              // до какого дня она не станет об этом говорить (после навязывания или отхода)
  навязал: 0,
  причины: [], границы: [], стоп: false,
  ярна: 'нет',               // нет | взял | помог | сорвано
  ярнаДо: null, ярнаСтороны: [],
  планСпрошен: false, план: null, опоры: [], // план: уход | пауза | ничего
  переговоры: null,          // { способ, итог: принято | отказ, день }
  рычаг: false,
  решение: null,             // { исход, день, выслушал }
});

export function вытащить(S) {
  const в = (S.мир.вытащить ??= новый());
  for (const [ключ, значение] of Object.entries(новый())) в[ключ] ??= значение;
  return в;
}

const читатьВытащить = S => S.мир.вытащить ?? новый();
const журнал = (S, с) => { S.мир.журналДня.push(с); return с; };
const цельВ = S => S.мир.цели?.выбрана === 'вытащить';
const зажать = (от, до, v) => Math.max(от, Math.min(до, v));
const вОкне = (день, [а, б]) => день >= а && день <= б;

export const расп = (S, кто) => S.мир.люди?.[кто]?.распол ?? 0;
function добавитьРасп(S, кто, n) {
  const л = ((S.мир.люди ??= {})[кто] ??= { спрошено: [], исчерпано: [] });
  л.распол = зажать(-2, 4, (л.распол || 0) + n);
}
function добавитьДом(S, n) {
  const м = ((S.мир.места ??= {})[ДОМ] ??= { дом: 0, долг: 0, флаги: [], осмотрено: [], визитов: 0 });
  м.дом = зажать(-3, 3, (м.дом ?? 0) + n);
}

// Работница, с которой идёт разговор: уже выбранная, иначе та, чья площадка сейчас в сцене, иначе первая записанная.
export function работница(S) {
  const в = читатьВытащить(S);
  if (в.кто) return в.кто;
  const поСцене = Object.entries(РАБОТНИЦЫ).find(([, р]) => р.комната === S.сцена?.комната)?.[0];
  return поСцене ?? Object.keys(РАБОТНИЦЫ)[0];
}
const данные = S => РАБОТНИЦЫ[работница(S)];
const ждёт = (в, день) => в.ждётДо !== null && день < в.ждётДо;

// Услышанное от Ярны признание о двух плательщиках: подтверждённый факт, а не слух (рычаг «чужого долга» из карточки).
export const знаетОДвухПлательщиках = S => !!S.мир.люди?.yarna?.спрошено?.includes('dolgi_doma:прямо');

// Основания для разговора с Ярной (карточка: «личные причины и хотя бы одно основание»).
export function основания(S) {
  const в = читатьВытащить(S);
  return [в.причины.length >= 2, в.ярна === 'помог', в.опоры.length >= 1].filter(Boolean).length;
}

const доступно = S => {
  const в = читатьВытащить(S), р = данные(S);
  return цельВ(S) && !ждёт(в, S.мир.день) && (в.этап === 'согласие' || в.этап === 'обещание' || расп(S, работница(S)) >= ВЫТАЩИТЬ.доступ) && !!р;
};
const обещала = S => читатьВытащить(S).этап === 'обещание';
const причинаДоступна = (S, ид) => {
  const в = читатьВытащить(S);
  return доступно(S) && обещала(S) && !в.стоп && вОкне(S.мир.день, ВЫТАЩИТЬ.причиныДни) && !в.причины.includes(ид) && !в.границы.includes(ид);
};
const переговорыОткрыты = S => {
  const в = читатьВытащить(S);
  return обещала(S) && в.переговоры === null && (в.причины.length >= 1 || в.стоп);
};

export function условиеВытащить(S, вид) {
  const в = читатьВытащить(S), день = S.мир.день, п = вОкне;
  switch (вид) {
    case 'доступ': return доступно(S);
    // Бесплатный первый повод (PR004-05): на лестнице она проходит мимо, пока не готова выйти на площадку сама.
    case 'у-окна': return !!данные(S) && расп(S, работница(S)) < ВЫТАЩИТЬ.доступ;
    case 'слушать': return доступно(S) && в.этап === 'нет' && расп(S, работница(S)) >= ВЫТАЩИТЬ.доступ;
    case 'предложить-сразу': return доступно(S) && в.этап === 'нет';
    case 'предложить': return доступно(S) && в.этап === 'слышал';
    case 'навязать': return доступно(S) && (в.этап === 'нет' || в.этап === 'слышал');
    case 'отойти': return доступно(S) && ['нет', 'слышал', 'согласие'].includes(в.этап);
    case 'обещать': return доступно(S) && в.этап === 'согласие';
    case 'причина-сиб': return причинаДоступна(S, 'сиб');
    case 'причина-шитьё': return причинаДоступна(S, 'шитьё');
    case 'причина-цветок-мягко': case 'причина-цветок-прямо': return причинаДоступна(S, 'цветок');
    case 'граница': return доступно(S) && обещала(S) && !в.стоп && в.причины.length >= 1;
    case 'ярна-предложение': return доступно(S) && обещала(S) && в.ярна === 'нет' && день <= ВЫТАЩИТЬ.ярнаДо;
    case 'ярна-ножи': return в.ярна === 'взял' && !в.ярнаСтороны.includes('ножи');
    case 'ярна-картель': return в.ярна === 'взял' && !в.ярнаСтороны.includes('картель');
    case 'ярна-отчёт': return в.ярна === 'взял' && в.ярнаСтороны.length >= 2;
    case 'план-вопрос': return доступно(S) && обещала(S) && п(день, ВЫТАЩИТЬ.планДни) && !в.планСпрошен && в.план === null;
    case 'план-уход': case 'план-пауза': case 'план-ничего':
      return доступно(S) && обещала(S) && п(день, ВЫТАЩИТЬ.планДни) && в.планСпрошен && в.план === null;
    case 'опора-часовня': return обещала(S) && ['уход', 'пауза'].includes(в.план) && !в.опоры.includes('часовня');
    case 'опора-работа': return доступно(S) && обещала(S) && в.план === 'уход' && в.причины.includes('шитьё') && !в.опоры.includes('работа');
    case 'переговоры-вместе': case 'переговоры-просьба': case 'переговоры-отступить': return переговорыОткрыты(S);
    case 'переговоры-долг': return переговорыОткрыты(S) && в.ярна === 'помог';
    case 'переговоры-рычаг': return переговорыОткрыты(S) && знаетОДвухПлательщиках(S);
    case 'ответ': return доступно(S) && обещала(S) && в.переговоры?.итог === 'принято' && в.решение === null && п(день, ВЫТАЩИТЬ.ответДни);
    default: return false;
  }
}

// Решение самой работницы. Рычаг роняет её доверие и считается ценой; всё остальное — её собственная картина:
// куда идти первой ночью, есть ли опора и сколько она доверяет. Игрок не нажимает кнопку «ушла».
export function решить(S) {
  const в = читатьВытащить(S), р = РАБОТНИЦЫ[в.кто], п = р.правила, т = расп(S, в.кто);
  if (в.рычаг && т <= п.безДоверия) return 'разрушено';
  if (в.план === null || в.план === 'ничего') return 'свободна-не-хочет';
  if (в.план === 'пауза') return 'осталась';
  if (!в.опоры.length) return 'передумала';
  if (т >= п.сОдвином.доверие && в.причины.length >= п.сОдвином.причин) return 'с-одвином';
  if (в.опоры.includes('работа') && т >= п.одна.доверие) return 'одна';
  if (т >= 3) return 'одна';
  return 'передумала';
}

// Последствия. Деньги тут не списываются: все действия цели бесплатны, кроме времени вечера.
export function применитьДействиеВытащить(S, вид) {
  if (!условиеВытащить(S, вид)) return false;
  const в = вытащить(S), день = S.мир.день;
  в.кто ??= работница(S);
  const имя = РАБОТНИЦЫ[в.кто].имя, п = РАБОТНИЦЫ[в.кто].падежи;
  switch (вид) {
    case 'слушать':
      в.этап = 'слышал'; журнал(S, `${имя} сказала, чего хочет: своё окно и свой день`); return true;
    case 'предложить-сразу':
      return true; // «спроси сначала»: ничего не меняется, но и не обрывается
    case 'предложить':
      в.этап = 'согласие'; добавитьРасп(S, в.кто, 1);
      журнал(S, `${имя} согласна принять помощь, если она её собственная`); return true;
    case 'навязать':
      в.этап = 'нет'; в.навязал += 1; в.ждётДо = день + ВЫТАЩИТЬ.ожидание.навязал; добавитьРасп(S, в.кто, -1);
      журнал(S, `${имя} отошла: Одвин попытался решить за неё`); return true;
    case 'отойти':
      в.ждётДо = день + ВЫТАЩИТЬ.ожидание.отошёл;
      журнал(S, `Одвин не настаивал: ${имя} подумает сама`); return true;
    case 'обещать':
      в.этап = 'обещание';
      журнал(S, `Одвин пообещал ${п.дат} действовать только по её слову`); return true;
    case 'причина-сиб': case 'причина-шитьё': case 'причина-цветок-мягко': {
      const ид = вид === 'причина-сиб' ? 'сиб' : вид === 'причина-шитьё' ? 'шитьё' : 'цветок';
      в.причины.push(ид); добавитьРасп(S, в.кто, 1);
      журнал(S, `${имя} назвала, что её здесь держит: ${ид === 'сиб' ? 'дверь и Сиб' : ид === 'шитьё' ? 'своё шитьё и накопленное' : 'цветок старшей и память о нём'}`);
      return true;
    }
    case 'причина-цветок-прямо':
      в.границы.push('цветок'); журнал(S, `${имя} закрыла эту тему сама: Одвин уважил границу`); return true;
    case 'граница':
      в.стоп = true; добавитьРасп(S, в.кто, 1); журнал(S, `Одвин больше не расспрашивает ${п.вин}: остальное её`); return true;
    case 'ярна-предложение':
      в.ярна = 'взял'; в.ярнаДо = день + ВЫТАЩИТЬ.ярнаСрок;
      взятьОбязательство(S, { id: 'вытащить_ярна', название: 'Слово Ярны обеим сторонам', срок: { день: в.ярнаДо, отрезок: 'ночь', граница: 'конец' } });
      return true;
    case 'ярна-ножи': в.ярнаСтороны.push('ножи'); return true;
    case 'ярна-картель': в.ярнаСтороны.push('картель'); return true;
    case 'ярна-отчёт':
      в.ярна = 'помог'; закрытьОбязательство(S, 'вытащить_ярна'); добавитьДом(S, 1);
      журнал(S, 'Слово Ярны передано обеим сторонам одинаково: Ярна будет должна разговор'); return true;
    case 'план-вопрос': в.планСпрошен = true; return true;
    case 'план-уход': case 'план-пауза': case 'план-ничего':
      в.план = вид.slice(5); добавитьРасп(S, в.кто, 1);
      журнал(S, `${имя} выбрала, каким будет первое место после дома: ${в.план}`); return true;
    case 'опора-часовня': в.опоры.push('часовня'); журнал(S, 'В часовне оставлена одна ночь с людьми рядом'); return true;
    case 'опора-работа': в.опоры.push('работа'); журнал(S, `${имя} сама договорилась о работе в доме напротив`); return true;
    case 'переговоры-вместе': {
      const принято = основания(S) >= 1 && в.причины.length >= 1 && расп(S, в.кто) >= 3;
      в.переговоры = { способ: 'вместе', итог: принято ? 'принято' : 'отказ', день };
      if (принято) добавитьДом(S, 1);
      журнал(S, принято ? 'Ярна согласна отпустить, если уйти захочет сама' : 'Ярна не поверила, что это не минутное');
      return true;
    }
    case 'переговоры-долг':
      в.переговоры = { способ: 'долг', итог: 'принято', день }; добавитьДом(S, 1);
      журнал(S, 'Ярна ответила на слово как на долг: Фрея свободна, если сама захочет'); return true;
    case 'переговоры-рычаг':
      в.переговоры = { способ: 'рычаг', итог: 'принято', день }; в.рычаг = true;
      добавитьРасп(S, в.кто, -2); добавитьДом(S, -2);
      журнал(S, 'Ярна уступила слову о двух плательщиках: дверь открыта, цена названа'); return true;
    case 'переговоры-просьба': {
      const принято = основания(S) >= 2;
      в.переговоры = { способ: 'просьба', итог: принято ? 'принято' : 'отказ', день };
      журнал(S, принято ? 'Ярна согласилась: просьба была основана' : 'Ярна отказала: просьбе не хватило оснований');
      return true;
    }
    case 'переговоры-отступить':
      журнал(S, 'Одвин отступил от разговора с Ярной, не начав его'); return true;
    case 'ответ':
      в.решение = { исход: решить(S), день, выслушал: true };
      журнал(S, `${имя} приняла своё решение`); return true;
    default: return false;
  }
}

// Реплика, которая зависит от того, что получилось: ответ Ярны на разговор и решение самой работницы.
// Пустая строка — оставить реплику из данных места.
export function репликаВытащить(S, вид) {
  const в = читатьВытащить(S), т = ТЕКСТЫ[в.кто];
  if (!т) return '';
  const принято = в.переговоры?.итог === 'принято';
  switch (вид) {
    case 'ответ': return в.решение ? (т.ответ[в.решение.исход] ?? '') : '';
    case 'переговоры-вместе': return принято ? т.вместе : т.вместеОтказ;
    case 'переговоры-просьба': return принято ? т.просьбаПринята : т.просьбаОтказ;
    case 'переговоры-долг': return `${т.ярнаДолг}\n\n${т.долг}`;
    case 'переговоры-рычаг': return т.рычаг;
    default: return '';
  }
}

// Конец суток: просроченное слово Ярны; если ответ не услышан, работница решает без Одвина.
export function закрытьДеньВытащить(S, итог) {
  const в = читатьВытащить(S), день = S.мир.день, строки = итог.причины;
  if (!в.кто) return;
  if (в.ярна === 'взял' && в.ярнаДо !== null && день >= в.ярнаДо) {
    в.ярна = 'сорвано';
    строки.push('Слово Ярны не донесено до обеих сторон в срок. Она нашла другого. Это не штраф, но и долга за тобой она не запомнит.');
  }
  if (день === ВЫТАЩИТЬ.ответДни[1] && обещала(S) && в.переговоры?.итог === 'принято' && в.решение === null) {
    // «С Одвином» значит уйти рядом с ним; раз он не пришёл, она уходит одна.
    const исход = решить(S);
    в.решение = { исход: исход === 'с-одвином' ? 'одна' : исход, день, выслушал: false };
    строки.push(`${РАБОТНИЦЫ[в.кто].имя} приняла своё решение без тебя: ты не пришёл его выслушать. Оно её, и перекроить его нельзя.`);
  }
}

