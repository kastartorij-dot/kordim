// Ряды склеиваются в отрезки — путь получается коротким и без щелей между клетками.
const путь = (рис, знак) => рис.flatMap((ряд, y) => {
  const части = [];
  for (let x = 0; x < ряд.length;) {
    if (ряд[x] !== знак) { x++; continue; }
    let к = x; while (ряд[к] === знак) к++;
    части.push(`M${x} ${y}h${к - x}v1h${x - к}z`);
    x = к;
  }
  return части;
}).join('');

const готовые = {};
export function значок(имя, класс = '') {
  const рис = РИСУНКИ[имя];
  if (!рис) return '';
  готовые[имя] ??= `<path d="${путь(рис, '#')}"/><path d="${путь(рис, '+')}" fill-opacity=".42"/>`;
  return `<svg class="зн${класс ? ' ' + класс : ''}" viewBox="0 0 12 12" aria-hidden="true" shape-rendering="crispEdges" fill="currentColor">${готовые[имя]}</svg>`;
}
