// Экземпляры вещей. Все перемещения удаляют экземпляр из источника до помещения в цель.
import { ВЕЩИ, СЛОТОВ } from '../Данные/вещи.js';
import { ОДЕЖДА } from '../Данные/одежда.js';
import { МАКС } from './тело.js';

export const вещь = id => ВЕЩИ[id] ?? (ОДЕЖДА[id] ? { id, ...ОДЕЖДА[id], категория: 'одежда' } : null);
export const имяВещи = id => вещь(typeof id === 'string' ? id : id?.тип)?.имя ?? String(typeof id === 'string' ? id : id?.тип);
const тип = x => typeof x === 'string' ? x : x?.тип;
const число = x => Number.isFinite(x) ? x : 0;

function следующийUid(S) { S.герой.счётчикВещей = число(S.герой.счётчикВещей) + 1; return `в${S.герой.счётчикВещей}`; }
export function создатьВещь(S, id, доп = {}) {
  const в = вещь(id);
  return { uid: следующийUid(S), тип: id, количество: 1, создано: S.мир.день, происхождение: 'неизвестно', состояние: {}, ...(в?.прочность ? { прочность: в.прочность } : {}), ...доп };
}

export function привестиВещи(S) {
  const г = S.герой;
  г.при_себе ??= [];
  г.хранилище ??= { вдова: [], угол: [] };
  г.залог ??= [];
  for (const список of [г.при_себе, г.хранилище.вдова ??= [], г.хранилище.угол ??= []]) {
    for (let i = 0; i < список.length; i++) {
      if (typeof список[i] === 'string') список[i] = создатьВещь(S, список[i], { происхождение: 'старое сохранение' });
      else if (!список[i].uid) список[i].uid = следующийUid(S);
      список[i].количество ??= 1;
      список[i].состояние ??= {};
    }
  }
  if (typeof г.рука === 'string') г.рука = г.при_себе.find(x => x.тип === г.рука)?.uid ?? null;
  if (г.рука && !г.при_себе.some(x => x.uid === г.рука)) г.рука = null;
  return г.при_себе;
}

export const размер = x => вещь(тип(x))?.слотов ?? 1;
export const занято = список => список.reduce((n, x) => n + размер(x), 0);
export const вместимость = S => СЛОТОВ - (S.герой.тело.цел <= 1 ? 1 : 0);
export const свободных = S => Math.max(0, вместимость(S) - занято(привестиВещи(S)));
export const естьВещь = (S, id) => привестиВещи(S).some(x => x.тип === id);
export const найтиВещь = (S, uid) => привестиВещи(S).find(x => x.uid === uid) ?? null;

export function можноПоложить(S, id, n = 1, доп = {}) {
  const список = привестиВещи(S), в = вещь(id), предел = в?.стопка ?? 1;
  const местоВСтопках = предел > 1 ? список.filter(x => x.тип === id && (!доп.происхождение || x.происхождение === доп.происхождение)).reduce((a, x) => a + предел - x.количество, 0) : 0;
  const осталось = Math.max(0, n - местоВСтопках);
  return свободных(S) >= Math.ceil(осталось / предел) * (в?.слотов ?? 1);
}

export function положить(S, id, n = 1, доп = {}) {
  if (!можноПоложить(S, id, n, доп)) return false;
  const список = привестиВещи(S), предел = вещь(id)?.стопка ?? 1;
  while (n > 0) {
    const стопка = предел > 1 ? список.find(x => x.тип === id && x.количество < предел && (!доп.происхождение || x.происхождение === доп.происхождение)) : null;
    if (стопка) { const d = Math.min(n, предел - стопка.количество); стопка.количество += d; n -= d; }
    else { const d = Math.min(n, предел); список.push(создатьВещь(S, id, { количество: d, ...доп })); n -= d; }
  }
  return true;
}

// Награда не исчезает, если карманы заняты. Запись об отложенной выдаче живёт
// в сохранении; забрать её можно позже из городского списка действий.
export function выдатьВещь(S, id, происхождение = 'дело') {
  if (положить(S, id, 1, { происхождение })) return 'получено';
  const м = S.мир;
  м.номерОтложеннойВещи = (м.номерОтложеннойВещи ?? 0) + 1;
  (м.отложенныеВещи ??= []).push({ номер: м.номерОтложеннойВещи, тип: id, происхождение });
  м.журналДня.push(`${имяВещи(id)}: ждёт, пока освободится место в сумке`);
  return 'отложено';
}

export function получитьОтложенное(S, номер) {
  const список = S.мир.отложенныеВещи ?? [];
  const i = список.findIndex(x => x.номер === номер);
  if (i < 0) return false;
  const x = список[i];
  if (!положить(S, x.тип, 1, { происхождение: x.происхождение })) return false;
  список.splice(i, 1);
  S.мир.журналДня.push(`${имяВещи(x.тип)}: забрал отложенную вещь`);
  return true;
}

export function забрать(S, uid, n = 1, список = привестиВещи(S)) {
  const i = список.findIndex(x => x.uid === uid);
  if (i < 0 || список[i].количество < n) return null;
  const x = список[i];
  const целиком = x.количество === n;
  if (целиком) список.splice(i, 1);
  else x.количество -= n;
  if (S.герой.рука === uid && !список.some(y => y.uid === uid)) S.герой.рука = null;
  return целиком ? x : { ...x, uid: следующийUid(S), количество: n, состояние: { ...x.состояние } };
}

export function убратьТип(S, id) {
  const x = привестиВещи(S).find(y => y.тип === id);
  return x ? забрать(S, x.uid, 1) : null;
}

// Возвращает 8 видимых мест. Крупная вещь занимает соседнее место; травма блокирует последнее.
export function слоты(S) {
  const ответ = Array(СЛОТОВ).fill(null), список = привестиВещи(S);
  let i = 0;
  for (const x of список) {
    if (i >= СЛОТОВ) break;
    ответ[i++] = x;
    if (размер(x) === 2 && i < СЛОТОВ) ответ[i++] = { продолжение: x.uid };
  }
  if (вместимость(S) < СЛОТОВ && !ответ[СЛОТОВ - 1]) ответ[СЛОТОВ - 1] = { блок: true };
  return ответ;
}

const полон = (S, еда) => Object.keys(еда).every(к => (S.герой.тело[к] ?? 0) >= МАКС);
const запись = (S, с) => { S.мир.журналДня.push(с); return с; };

export function использоватьВещь(S, uid) {
  const x = найтиВещь(S, uid), в = вещь(x?.тип);
  if (!x || S.сцена || S.мир.конецДня) return null;
  const т = S.герой.тело;
  if (в?.еда) {
    if (полон(S, в.еда)) return null;
    забрать(S, uid, 1);
    for (const [к, n] of Object.entries(в.еда)) т[к] = Math.min(МАКС, т[к] + n);
    if (в.жажда) S.герой.жажда = Math.min(3, (S.герой.жажда ?? 0) + 1);
    return запись(S, `${в.имя}: сыт +${в.еда.сыт}${в.жажда ? ', хочется пить' : ''}`);
  }
  if (x.тип === 'бинт' && (S.герой.рана > 0 || т.цел < МАКС)) {
    забрать(S, uid, 1);
    if (S.герой.рана > 0) S.герой.рана--;
    else т.цел++;
    return запись(S, 'Перевязал рану: кровотечение остановлено или цел +1');
  }
  if (x.тип === 'настой' && (S.герой.боль > 0 || т.цел < МАКС)) {
    забрать(S, uid, 1); S.герой.боль = 0;
    S.герой.настойДень = S.мир.день;
    S.герой.привычкаНастой = Math.min(3, (S.герой.привычкаНастой ?? 0) + 1);
    return запись(S, 'Настой снял боль до утра');
  }
  if (x.тип === 'табак') {
    забрать(S, uid, 1);
    S.герой.напряжение = Math.max(0, S.герой.напряжение - 1);
    S.герой.привычкаТабак = Math.min(3, (S.герой.привычкаТабак ?? 0) + 1);
    S.герой.табакДень = S.мир.день;
    S.герой.одежда?.база && (S.герой.одежда.база.состояние.запах = true);
    return запись(S, 'Выкурил табак: напряжение −1');
  }
  return null;
}

export function вскрытьВещь(S, uid) {
  const x = найтиВещь(S, uid), в = вещь(x?.тип);
  if (!x || !в?.вскрытие || x.состояние.вскрыто || S.сцена || S.мир.конецДня) return null;
  x.состояние.вскрыто = true;
  return запись(S, в.вскрытие);
}

export function действияВещей(S) {
  return привестиВещи(S).flatMap(x => {
    const в = вещь(x.тип);
    if (в?.вскрытие) { // вещи дел, которые можно вскрыть (ящик не по описи): один раз, и это видно при сдаче
      if (x.состояние.вскрыто) return [];
      return [{ id: `вещь:вскрыть:${x.uid}`, вид: 'вещь', uid: x.uid, текст: 'Вскрыть', отрезков: 0, можно: !S.сцена && !S.мир.конецДня, почему: S.сцена ? 'сейчас нельзя' : null, выполнить(S2) { return вскрытьВещь(S2, x.uid); } }];
    }
    const можно = !S.сцена && !S.мир.конецДня && (в?.еда ? !полон(S, в.еда) : x.тип === 'бинт' ? S.герой.рана > 0 || S.герой.тело.цел < МАКС : x.тип === 'настой' ? S.герой.боль > 0 || S.герой.тело.цел < МАКС : x.тип === 'табак');
    if (!в?.еда && !['бинт', 'настой', 'табак'].includes(x.тип)) return [];
    return [{ id: `вещь:использовать:${x.uid}`, вид: 'вещь', uid: x.uid, текст: в.еда ? 'Съесть' : x.тип === 'бинт' ? 'Перевязать' : x.тип === 'настой' ? 'Выпить' : 'Курить', отрезков: 0, можно, почему: S.сцена ? 'сейчас нельзя' : !можно ? 'сейчас не нужно' : null, выполнить(S2) { return использоватьВещь(S2, x.uid); } }];
  });
}

export function старениеВещей(S, итог) {
  привестиВещи(S);
  for (const список of [S.герой.при_себе, S.герой.хранилище.вдова, S.герой.хранилище.угол]) for (const x of список) {
    const в = вещь(x.тип);
    if (в?.срок && S.мир.день - x.создано >= в.срок && в.черствеет) {
      x.тип = в.черствеет; x.создано = S.мир.день;
      итог.причины.push(`${в.имя} ${в.порча ?? 'зачерствел'}`);
    }
  }
}

export function намочитьБумаги(S) {
  let n = 0;
  for (const x of привестиВещи(S)) if (вещь(x.тип)?.бумага && !x.состояние.промокло) { x.состояние.промокло = true; n++; }
  if (n) запись(S, `Бумага промокла (${n}): текст можно восстановить у писца, если сохранилась запись`);
  return n;
}

export function износить(S, uid, n = 1) {
  const x = найтиВещь(S, uid);
  if (!x || !вещь(x.тип)?.прочность) return false;
  x.прочность = Math.max(0, (x.прочность ?? вещь(x.тип).прочность) - n);
  if (x.прочность === 0) { x.состояние.сломано = true; запись(S, `${имяВещи(x)} сломалась`); }
  return true;
}

export function потерятьВещь(S, uid, причина = 'потеря') {
  const x = найтиВещь(S, uid);
  if (!x) return false;
  забрать(S, uid, x.количество);
  (S.мир.утраченные ??= []).push({ тип: x.тип, uid: x.uid, причина, день: S.мир.день, дело: x.дело ?? null });
  if (x.дело || вещь(x.тип)?.дело) (S.мир.флаги ??= []).push('потеря_груза');
  запись(S, `${имяВещи(x)}: ${причина}`);
  return true;
}
