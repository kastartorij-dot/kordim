// Мини-игры «Вес» и «Счёт» внутри смены (шаг 12; правила — Документы/Материалы/Мини_игры_и_мысли/Вес_и_Счёт_правила.md). Без DOM.
// Задача заменяет обычный, не сюжетный случай смены. Случай при этом всё равно вытянут из колоды,
// поэтому зерно случайности движется как раньше, а выбор задания от зерна не зависит.
// Мини-игра сама не платит и не тратит время: за смену платит смена. Исход даёт только то, что
// записано у работы в «задача.удача», и применяется один раз — при закрытии смены (Движок/смена.js).
//
// Состояние идущей задачи лежит в S.мир.смена.задача и переживает перезагрузку:
// { игра, задание, совет: { вид: null|'слово'|'отсев', взят, убран }, выбор, отметки[], стадия, исход }
// стадия: 'идёт' → 'отказ?' (уточнение) → 'идёт' | 'отложено'; 'идёт' → 'ответ'. Из 'ответ'/'отложено' назад пути нет.
// Учёт по игре — S.мир.мини[игра] = { решены[], отказ }: решённое задание не возвращается, отложенное может вернуться.
import { ВЕС, СЧЁТ } from '../Данные/вес-и-счёт.js';
import { условие } from './условия.js';
import { ступеньНомер } from './ремёсла.js';

export const ИГРЫ = {
  вес: { имя: 'Вес', задания: ВЕС, факты: 'Что видно', записать: 'Записать вес', журнал: 'Сверка веса' },
  счёт: { имя: 'Счёт', задания: СЧЁТ, факты: 'Дощечка', записать: 'Так и запишу', журнал: 'Проверка записи', отметки: true },
};

export const учётИгры = (S, игра) => ((S.мир.мини ??= {})[игра] ??= { решены: [], отказ: null });
export const задание = (игра, id) => ИГРЫ[игра]?.задания.find(з => з.id === id) ?? null;

// Пора ли задаче на этой смене. Не на первой смене работы и не чаще чем через смену; задания — по порядку
// в данных (от лёгких к трудным), только ещё не решённые. Только что отложенное уступает следующему.
export function выдатьЗадачу(S, р, сч) {
  const з = р.задача;
  if (!з || !ИГРЫ[з.игра] || !условие(S, з.условие)) return null;
  if (сч.смен < 1 || (сч.задача != null && сч.смен - сч.задача < 2)) return null;
  const у = учётИгры(S, з.игра);
  const свободные = ИГРЫ[з.игра].задания.filter(x => !у.решены.includes(x.id));
  const выбор = свободные.find(x => x.id !== у.отказ) ?? свободные[0];
  if (!выбор) return null;
  сч.задача = сч.смен;
  // Ремесло работы даёт совет: «умеешь» — подсказку о способе, «набил руку» и выше — убрать один неверный ответ.
  const ст = ступеньНомер(S, з.ремесло);
  return { игра: з.игра, задание: выбор.id, совет: { вид: ст >= 1 ? 'отсев' : ст >= 0 ? 'слово' : null, взят: false, убран: null }, выбор: null, отметки: [], стадия: 'идёт', исход: null };
}

const текстИсхода = (т, слово) => {
  // «Сошлось: …» / «Не сошлось. …» уже сказано заголовком итога — не повторять.
  const без = т.replace(new RegExp('^' + слово + '[.:,]?\\s*'), '');
  return без === т ? т : без.charAt(0).toUpperCase() + без.slice(1);
};

// Кнопки задачи. ход(S) меняет состояние; true — задача кончилась, смену пора закрыть.
// Порядок важен для ботов и тестов (Движок/смена.js → авто): «записать» первым, пока ответа нет — недоступно.
export function ходыЗадачи(S) {
  const т = S.мир.смена?.задача, з = т && задание(т.игра, т.задание), и = т && ИГРЫ[т.игра];
  if (!з) return [];
  const Х = [];
  const ход = (id, текст, можно, f) => Х.push({ id: 'смена:задача:' + id, текст, можно, ход: f });
  if (т.стадия === 'отказ?') {
    ход('отложить-да', 'Отложить', true, S2 => { const x = S2.мир.смена.задача; x.стадия = 'отложено'; x.исход = 'отказ'; return true; });
    ход('вернуться', 'Вернуться', true, S2 => { S2.мир.смена.задача.стадия = 'идёт'; return false; });
    return Х;
  }
  if (т.стадия !== 'идёт') return [];
  ход('записать', и.записать, !!т.выбор, S2 => {
    const x = S2.мир.смена.задача;
    if (!x.выбор) return false;
    x.стадия = 'ответ'; x.исход = x.выбор === з.верный ? 'удача' : 'ошибка';
    return true;
  });
  for (const в of з.варианты) ход('вариант:' + в.id, в.текст, в.id !== т.совет.убран, S2 => {
    const x = S2.мир.смена.задача;
    if (в.id !== x.совет.убран) x.выбор = в.id;
    return false;
  });
  if (т.совет.вид && !т.совет.взят) ход('совет', 'Совет ремесла', true, S2 => {
    const с = S2.мир.смена.задача.совет;
    if (с.взят) return false;
    с.взят = true;
    // Отсев: первый по порядку неверный вариант. Если он был выбран, выбор снимается.
    if (с.вид === 'отсев') {
      с.убран = з.варианты.find(в => в.id !== з.верный).id;
      if (S2.мир.смена.задача.выбор === с.убран) S2.мир.смена.задача.выбор = null;
    }
    return false;
  });
  if (и.отметки) з.факты.forEach((_, i) => ход('отметка:' + i, 'Пометить строку', true, S2 => {
    const о = S2.мир.смена.задача.отметки, k = о.indexOf(i);
    if (k >= 0) о.splice(k, 1); else о.push(i);
    return false;
  }));
  ход('отложить', 'Отложить', true, S2 => { S2.мир.смена.задача.стадия = 'отказ?'; return false; });
  return Х;
}

// Итог задачи: применяется один раз, из завершить() смены. Возвращает текст итога и строки эффектов.
export function закрытьЗадачу(S, р, применитьЭффект, ctx) {
  const т = S.мир.смена?.задача, з = т && задание(т.игра, т.задание);
  if (!т || т.применено) return null;
  т.применено = true;
  const и = ИГРЫ[т.игра], у = учётИгры(S, т.игра);
  // Задание пропало из данных после обновления — снимается как отложенное, без последствий.
  if (!з) { т.исход = 'отказ'; return { текст: null, строки: [], журнал: null }; }
  const строки = [];
  if (т.исход === 'отказ') {
    у.отказ = з.id;
    return { текст: з.отказ, строки, журнал: `${и.журнал}: отложено.` };
  }
  if (!у.решены.includes(з.id)) у.решены.push(з.id);
  у.отказ = null;
  (S.мир.счётчики ??= {})[`мини_${т.игра}_${т.исход}`] = (S.мир.счётчики[`мини_${т.игра}_${т.исход}`] ?? 0) + 1;
  if (т.исход === 'удача') {
    if (р.задача?.удача) строки.push(...применитьЭффект(S, р.задача.удача, ctx));
    return { текст: текстИсхода(з.удача, 'Сошлось'), строки, журнал: `${и.журнал}: сошлось.` };
  }
  return { текст: текстИсхода(з.ошибка, 'Не сошлось'), строки, журнал: `${и.журнал}: не сошлось, запись поправлена.` };
}

// Что показывать (без вёрстки): идущая задача или её итог на карточке закрытой смены.
export function видЗадачи(S) {
  const т = S.мир.смена?.задача, з = т && задание(т.игра, т.задание), и = т && ИГРЫ[т.игра];
  if (!з) return null;
  const кончено = т.стадия === 'ответ' || т.стадия === 'отложено';
  return {
    игра: и.имя, подводка: з.подводка, заголовокФактов: и.факты, отметкиМожно: !!и.отметки && !кончено,
    факты: з.факты.map((текст, i) => ({ текст, отмечен: т.отметки.includes(i) })),
    вопрос: з.вопрос, стадия: т.стадия, исход: т.исход,
    варианты: з.варианты.map(в => ({ id: в.id, текст: в.текст, выбран: в.id === т.выбор, отпал: в.id === т.совет.убран, верный: кончено && т.стадия === 'ответ' && в.id === з.верный })),
    совет: т.совет.взят && т.совет.вид === 'слово' ? з.совет : null,
    отсев: т.совет.взят && т.совет.вид === 'отсев',
    заголовокИтога: т.исход === 'удача' ? 'Сошлось' : т.исход === 'ошибка' ? 'Не сошлось' : т.исход === 'отказ' ? 'Отложено' : null,
    решение: т.стадия === 'ответ' ? з.решение : null,
  };
}
