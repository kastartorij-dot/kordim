// Смена с задачей с готового состояния: ступень ремесла, тело в порядке, одна смена уже была, нить сегодня не придёт.
// вариант — id задания: остальные помечаются решёнными, чтобы выдалось именно оно.
function сменаСЗадачей(S, работаId, { район, отрезок, ремесло, игра, вариант, ступень = 'умеешь' }) {
  const день = Math.max(S.мир.день, 2);
  Object.assign(S.мир, { день, отрезок, район, конецДня: null, смена: null, нитьДень: день });
  Object.assign(S.герой.тело, { сыт: 4, отдых: 4, тепло: 4, цел: 4 });
  поставитьСтупень(S, ремесло, ступень);
  if (игра && вариант) учётИгры(S, игра).решены = ИГРЫ[игра].задания.map(з => з.id).filter(id => id !== вариант);
  const сч = (S.мир.работы[работаId] ??= { смен: 0, видели: [], дни: [], последний: null });
  сч.смен = Math.max(сч.смен, 1); сч.задача = null;
  начатьСмену(S, работа(работаId));
  return S.мир.смена?.стадия === 'задача';
}
