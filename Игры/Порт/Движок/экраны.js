// Строка действия: название, ниже — цена и время значками, причина и риск.
function мета(д) {
  const лишнее = ч => д.вид === 'место' && (/^вход даром$/.test(ч) || /^1 отрезок$/.test(ч));
  return подписьДействия(д).split(' · ').filter(ч => ч && !лишнее(ч)).map(ч => {
    const деньги = /гр\.|даром/.test(ч), время = !деньги && /отрез|без затрат|до следующего/.test(ч);
    const класс = /даром/.test(ч) ? 'даром' : !деньги && !время ? 'когда' : '';
    return '<span' + (класс ? ' class="' + класс + '"' : '') + '>' + (деньги ? значок('монета') : время ? значок('время') : '') + экр(ч) + '</span>';
  }).join('');
}
const карточкаДействия = (д, S) => {
  const риск = предупреждениеДействия(д, S);
  return '<button class="b действие-карточка" data-id="' + экр(д.id) + '"' + (д.можно ? '' : ' disabled') + '><strong>' + экр(названиеДействия(д)) + '</strong><span class="действие-мета">' + мета(д) + '</span>'
    + (!д.можно && д.почему ? '<span class="действие-причина">' + экр(д.почему) + '</span>' : '')
    + (риск ? '<span class="действие-риск">' + значок('нож') + экр(риск) + '</span>' : '') + '</button>';
};

