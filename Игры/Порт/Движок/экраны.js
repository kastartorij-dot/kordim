function рендерРайон(S, onПереход) {
  const поле = $('экран');
  const текущий = район(S.мир.район);
  const момент = S.мир.день + ':' + S.мир.район + ':' + S.мир.отрезок;
  if (ИНТ.момент !== момент) {
    if (S.мир.отрезок === 'ночь') ИНТ.категория = 'быт';
    else if (ИНТ.момент?.endsWith(':ночь')) ИНТ.категория = 'места';
    ИНТ.момент = момент;
  }
  const действия = доступныеДействия(S).filter(д => д.вид !== 'переход');
  const прогулка = действия.find(д => д.id === 'отрезок:здесь');
  const остальные = действия.filter(д => д !== прогулка);
  const категории = КАТЕГОРИИ.filter(([id]) => остальные.some(д => категорияДействия(д) === id));
  if (!категории.some(([id]) => id === ИНТ.категория)) ИНТ.категория = категории[0]?.[0];
  // Безопасный ночлег в других районах: с названием района; свой угол — только если он есть по договору (PR004-21).
  const безопасные = S.мир.отрезок === 'ночь' ? ЖИЛЬЁ.filter(ж => ж.открыто && !ж.риск && ж.где && !ж.где.includes(S.мир.район) && (ж.id !== 'угол' || S.герой.жильё?.id === 'угол')).map(ж => {
    const оплачено = ж.id === 'угол' || (S.герой.жильё?.id === ж.id && S.герой.жильё.оплачено_по >= S.мир.день);
    const где = ж.где.map(id => район(id)?.имя).filter(Boolean).join(', ');
    return ж.имя + (где ? ' (' + где + ')' : '') + ' — ' + (оплачено ? 'уже оплачено' : ж.цена + ' гр.' + (ж.ночей ? ' за ' + ж.ночей + ' ночей' : ''));
  }) : [];
  const списокНочлега = безопасные.join('; ').replace(/\.$/, '');
  const выбранные = остальные.filter(д => категорияДействия(д) === ИНТ.категория);
  задникРайона(S, текущий);
  поле.innerHTML = '<div class="район-экран"><section class="район-вид"><div class="район-сцена"><div class="район-название"><div class="надзаголовок">' + экр(текущий.сторона) + (текущий.фракция ? ' · ' + экр(ФРАКЦИЯ[текущий.фракция] ?? '') : '') + '</div><h1>' + экр(текущий.имя) + '</h1></div></div>'
    + '<p class="карта-описание">' + экр(текущий.описание) + '</p>'
    + (прогулка ? карточкаДействия(прогулка, S) : '')
    + (предложеннаяЦель(S) ? '<button class="b весть-цели" id="к-цели">' + значок('журнал') + '<span><b>Журнал предлагает цель</b><small>Четыре направления на сезон. Условия и первый шаг видны до выбора.</small></span></button>' : '')
    + (S.мир.журналДня.length ? '<details class="события-дня"><summary>Сегодня · ' + S.мир.журналДня.length + '</summary>' + список(S.мир.журналДня) + '</details>' : '')
    + '</section><aside class="район-действия"><div class="надзаголовок">' + значок(S.мир.отрезок) + ' ' + экр(S.мир.отрезок) + ' · день ' + S.мир.день + '</div><div class="район-шапка"><h2>Что делать?</h2><button class="b ссылка" id="на-карту">' + значок('город') + 'карта</button></div>'
    + '<div class="вкладки-действий">' + категории.map(([id,имя]) => '<button class="b' + (id === ИНТ.категория ? ' on' : '') + '" data-категория="' + id + '" aria-pressed="' + (id === ИНТ.категория) + '">' + имя + '</button>').join('') + '</div>'
    + '<div class="список-действий">' + выбранные.map(д => карточкаДействия(д,S)).join('') + '</div>'
    + (ИНТ.категория === 'быт' && безопасные.length ? '<p class="подсказка">Защита кошеля во сне: ' + экр(списокНочлега) + '. Дорога занимает отрезок — жильё лучше выбирать заранее.</p>' : '')
    + (ИНТ.категория === 'места' ? '<p class="подсказка">' + (выбранные.some(д => /без отрезка/.test(д.подпись ?? '')) ? 'Посещение места занимает один отрезок, кроме мест с пометкой «осмотр без отрезка».' : 'Посещение места занимает один отрезок.') + ' Сон выбирается отдельно.</p>' : '') + '</aside></div>';
  $('на-карту').onclick = () => { ИНТ.район = false; ИНТ.карточка = null; onПереход(S); };
  const кЦели = $('к-цели'); if (кЦели) кЦели.onclick = () => document.querySelector('#панель [data-вкладка="журнал"]')?.click();
  поле.querySelectorAll('[data-категория]').forEach(btn => {
    btn.onclick = () => {
      const верх = поле.scrollTop;
      ИНТ.категория = btn.dataset.категория;
      рендерРайон(S, onПереход);
      поле.scrollTop = верх;
      поле.querySelector('[data-категория="' + ИНТ.категория + '"]')?.focus({preventScroll:true});
    };
  });
  поле.querySelectorAll('button[data-id]').forEach(btn => {
    btn.onclick = () => {
      const д = действия.find(x => x.id === btn.dataset.id);
      if (!д?.можно) return;
      if (д.вид === 'место') звук('шаг');
      д.выполнить(S); onПереход(S);
    };
  });
}

// Итог дня: день уже переключён (Движок/время.js), здесь только показать и
// снять S.мир.конецДня. Автосейв делает index.html.
export function рендерКонецДня(S, onДальше) {
  const итог = S.мир.конецДня;
  // Шапка уже показывает новый день — до «Встретить утро» её не видно.
  $('hud').classList.add('спрятан');
  задникРайона(S, район(S.мир.район), 'темно');
  const з = document.getElementById('задник'); if (з) з.dataset.время = 'ночь';
  const сон = итог.отъезд ? '' : итог.выспался ? (итог.сон ? 'Ночь: ' + итог.сон.toLowerCase() + '.' : 'Ночь прошла во сне.') : 'Ночь прошла без сна.';
  $('экран').innerHTML = `
    <div class="ов ночь-дня">
      <div class="ночь-звёзды"></div>
      <div class="овбокс">
        ${значок('ночь', 'луна')}
        <h2>${итог.отъезд ? 'Одвин покидает порт' : 'День ' + итог.день + ' позади'}</h2>
        ${сон ? `<p class="ночь-сон">${экр(сон)}</p>` : ''}
        ${список(итог.журнал)}
        ${список(итог.причины)}
        <div class="ночь-итог">${сводкаГероя(S).тело.map(мерило).join('')}<span class="кошель">${значок('монета')}${S.герой.кошель}</span></div>
        ${итог.день === ДЕНЬ_ВЫБОРА - 1 && !S.мир.цели?.выбрана ? '<p class="ночь-сон">Утром журнал предложит направление на сезон: четыре цели, у каждой видны условия и первый шаг.</p>' : ''}
        ${итог.предупреждение ? '<p class="предупр">Ещё один серьёзный удар может стать последним.</p>' : ''}
        <button class="b sin" id="дальше">${итог.финал ? ФИНАЛ.кнопкаИтог : 'Встретить утро'}</button>
      </div>
    </div>
  `;
  показатьОкно($('экран').querySelector('.ов'));
  $('дальше').onclick = () => {
    if (итог.финал) return рендерФинал(S, итог, onДальше);
    $('hud').classList.remove('спрятан');
    звук('день');
    S.мир.конецДня = null;
    onДальше(S);
  };
}

// Финал сезона — отдельные страницы после итога ночи: исход, люди, «Синий час», Бренн, как он жил, конец.
// Итог из старого сохранения без разделов показывает свои строки на странице «Как он жил».
function рендерФинал(S, итог, onДальше, страница = 0) {
  const ф = итог.финал, К = ФИНАЛ.конец;
  const р = ф.разделы ?? { цель: [], люди: [], отец: [], жизнь: ф.строки ?? [] };
  const абзацы = т => String(т).split(/\n\s*\n/).map(а => `<p class="финал-текст">${экр(а)}</p>`).join('');
  const надпись = (итог.отъезд ? ФИНАЛ.надписьОтъезд : ФИНАЛ.надпись).replace('{день}', ф.деньСезона ?? ф.день);
  const страницы = [
    `<div class="финал-надпись">${экр(надпись)}</div><h2>${экр(ф.заголовок)}</h2>${абзацы(ЭПИЛОГИ[ф.цель]?.[ф.исход] ?? ф.текст)}`,
    р.люди.length && `<h2>${ФИНАЛ.разделы.люди}</h2>${р.люди.map(абзацы).join('')}`,
    р.дом?.length && `<h2>${ФИНАЛ.разделы.дом}</h2>${р.дом.map(абзацы).join('')}`,
    р.отец.length && `<h2>${ФИНАЛ.разделы.отец}</h2>${абзацы(р.отец[0])}${р.записиОтца?.length ? `<ul class="финал-записи">${р.записиОтца.map(з => `<li>${экр(з)}</li>`).join('')}</ul>` : ''}${р.отец.slice(1).map(абзацы).join('')}`,
    (р.цель.length || р.жизнь.length) && `<h2>${ФИНАЛ.разделы.жизнь}</h2>${список([...р.цель, ...р.жизнь])}`,
    `<h2>${экр(итог.отъезд ? К.заголовок : К.заголовокОстался)}</h2>${абзацы(итог.отъезд ? К.отъезд : К.остался)}`,
  ].filter(Boolean);
  const последняя = страница === страницы.length - 1;
  задник(путьРесурса(итог.отъезд ? КАРТИНКИ_ФИНАЛА.отъезд : КАРТИНКИ_ФИНАЛА[ф.цель]?.[ф.исход] ?? КАРТИНКИ_ФИНАЛА.иначе), { время: 'вечер' });
  $('экран').innerHTML = `
    <div class="ов финал-экран">
      <div class="овбокс">
        ${страницы[страница]}
        <div class="финал-кнопки">
          ${страница ? '<button class="b" id="финал-назад">Назад</button>' : ''}
          ${последняя
            ? `<button class="b sin" id="финал-конец">${экр(итог.отъезд ? К.кнопкаМеню : К.кнопкаОстаться)}</button>`
            : `<button class="b sin" id="финал-дальше">${экр(ФИНАЛ.кнопкаДальше)}</button>`}
        </div>
      </div>
    </div>
  `;
  показатьОкно($('экран').querySelector('.ов'));
  $('финал-назад')?.addEventListener('click', () => рендерФинал(S, итог, onДальше, страница - 1));
  $('финал-дальше')?.addEventListener('click', () => рендерФинал(S, итог, onДальше, страница + 1));
  $('финал-конец')?.addEventListener('click', () => {
    // Уехавший герой не возвращается в город: кампания закрыта, остаётся главное меню.
    if (итог.отъезд) return location.reload();
    $('hud').classList.remove('спрятан');
    звук('день');
    S.мир.конецДня = null;
    onДальше(S);
  });
}

// Выбор начала (ГДД §2): три версии одного героя.
const ЗНАЧОК_НАЧАЛА = { семья: 'герой', бумаги: 'журнал', наколки: 'вещи' };
export function рендерСтарт(onВыбор, ошибкаСохранения = null) {
  // выбор идёт после сцены прибытия, на кадре города с титром
  задник(путьРесурса(ВСТУПЛЕНИЕ.кадры.город), { время: 'утро', глубина: 'темно' });
  $('экран').innerHTML = `
    <div class="старт-экран">
      <div class="надзаголовок">Ранняя осень · 1026</div>
      <div class="карта-подпись">Одвин Скарре возвращается</div>
      <p class="карта-описание">Семь лет его здесь не было. С чем он вернулся?</p>
      ${ошибкаСохранения ? `<p class="карта-описание">Автосохранение нельзя загрузить: ${ошибкаСохранения}. При новой игре исходные данные останутся в резервной копии.</p>` : ''}
      <div class="старт-выбор">${НАЧАЛА.map(н => `
        <button class="b начало" data-id="${н.id}">
          ${значок(ЗНАЧОК_НАЧАЛА[н.id] ?? 'герой')}
          <span class="начало-имя">${экр(н.имя)}</span>
          <span class="начало-ремесло"><span>${экр(н.ремесло)}</span><span>${значок('монета')} ${н.деньги} гр.</span></span>
          <span class="начало-описание">${экр(н.описание)}</span>
        </button>`).join('')}
      </div>
    </div>
  `;
  $('экран').querySelectorAll('.начало').forEach(btn => {
    btn.onclick = () => onВыбор(btn.dataset.id);
  });
}
