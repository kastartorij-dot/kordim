// Строка итога смены: деньги и тело получают знак и цвет, остальное — как есть.
function плашкаИтога(с) {
  const т = String(с), деньги = /гр\./.test(т), тело = т.match(/^(сыт|отдых|тепло|цел)\s/i);
  const знак = /(^|\s)\+\d/.test(т) ? 'плюс' : /(^|\s)[−-]\d/.test(т) ? 'минус' : '';
  const зн = деньги ? значок('монета') : тело ? значок(тело[1].toLowerCase()) : '';
  return '<li class="' + знак + '">' + зн + экр(т) + '</li>';
}

// Мини-игра смены (шаг 12, Движок/мини-игры.js). Выбор и пометки сказаны словом и значком, не цветом;
// всё нажимается одним касанием, таймера нет. Кнопки — те же действия карточки, ищутся по id.
function блокЗадачи(з, действия) {
  const есть = id => действия.find(д => д.id === id);
  const кн = (id, текст, класс = '') => { const д = есть(id); return д ? `<button class="b ${класс}" data-id="${экр(id)}" ${д.можно ? '' : 'disabled'}>${экр(текст)}</button>` : ''; };
  const факты = з.факты.map((ф, i) => з.отметкиМожно
    ? `<li><button class="задача-строка" data-id="смена:задача:отметка:${i}" aria-pressed="${ф.отмечен}">${экр(ф.текст)}${ф.отмечен ? '<span class="задача-метка">проверено ✓</span>' : ''}</button></li>`
    : `<li>${экр(ф.текст)}</li>`).join('');
  const варианты = з.варианты.map(в => {
    const id = 'смена:задача:вариант:' + в.id, д = есть(id);
    const метка = в.отпал ? 'Отпал' : в.выбран ? 'Выбрано' : '';
    return `<button class="b задача-вариант${в.выбран ? ' on' : ''}${в.отпал ? ' отпал' : ''}" data-id="${экр(id)}" aria-pressed="${в.выбран}" ${д?.можно ? '' : 'disabled'}>
      <span>${экр(в.текст)}</span>${метка ? `<span class="задача-метка">${метка}</span>` : ''}</button>`;
  }).join('');
  const кнопки = з.стадия === 'отказ?'
    ? `<p class="задача-уточнение">Оставить без проверки?</p><div class="задача-кнопки">${кн('смена:задача:отложить-да', 'Отложить', 'sin')}${кн('смена:задача:вернуться', 'Вернуться')}</div>`
    : `<div class="задача-кнопки">${кн('смена:задача:записать', есть('смена:задача:записать')?.текст ?? 'Записать', 'sin')}${кн('смена:задача:совет', 'Совет ремесла')}${кн('смена:задача:отложить', 'Отложить')}</div>`;
  return `
    <p class="смена-текст">${экр(з.подводка)}</p>
    <div class="задача-факты"><h3>${экр(з.заголовокФактов)}</h3><ul${з.отметкиМожно ? ' class="задача-дощечка"' : ''}>${факты}</ul></div>
    ${з.совет ? `<p class="задача-совет"><b>Совет ремесла.</b> ${экр(з.совет)}</p>` : ''}
    ${з.отсев ? '<p class="задача-совет"><b>Совет ремесла.</b> Один неверный ответ отпал.</p>' : ''}
    <p class="задача-вопрос">${экр(з.вопрос)}</p>
    <div class="задача-варианты" role="group" aria-label="Ответы">${з.стадия === 'отказ?' ? '' : варианты}</div>
    ${кнопки}`;
}

// Итог мини-игры на закрытой смене: верный ответ отмечен словом, расчёт — по желанию.
function итогЗадачи(з) {
  const верный = з.варианты.find(в => в.верный);
  return (верный ? `<p class="задача-верный"><span class="задача-метка">✓ Так сходится</span> ${экр(верный.текст)}</p>` : '')
    + (з.решение ? `<details class="задача-решение"><summary>Как считали</summary><p>${экр(з.решение)}</p></details>` : '');
}

// Смена блокирует город, пока игрок не выберет исход и не закроет карточку.
// Раньше её действия возвращались движком, но экран района их не рисовал.
export function рендерСмены(S, onПереход) {
  const поле = $('экран');
  const вид = видСмены(S);
  const действия = доступныеДействия(S).filter(д => д.группа === 'смена');
  задникРайона(S);
  const строки = вид.строки?.length
    ? `<ul class="смена-итог">${вид.строки.map(плашкаИтога).join('')}</ul>`
    : '';
  const задача = вид.стадия === 'задача' && вид.задача;
  const итог = вид.стадия === 'итог' && вид.задача;
  поле.innerHTML = `
    <div class="смена-экран">
      <section class="смена-карточка${задача || итог ? ' задача' : ''}">
        <div class="надзаголовок">Работа · ${экр(район(S.мир.район)?.имя ?? '')}</div>
        <h1>${экр(вид.заголовок)}</h1>
        ${задача || итог ? `<div class="задача-игра">${экр(вид.задача.игра)}${итог ? ' · ' + экр(вид.задача.заголовокИтога ?? '') : ''}</div>` : ''}
        ${вид.текст ? `<p class="смена-текст">${экр(вид.текст)}</p>` : ''}
        ${задача ? блокЗадачи(вид.задача, действия) : ''}
        ${итог ? итогЗадачи(вид.задача) : ''}
        ${строки}
        ${задача ? '' : `<div class="смена-кнопки">${действия.map(д => `
          <button class="b" data-id="${экр(д.id)}" ${д.можно ? '' : 'disabled'}>
            ${экр(д.текст)}${д.подпись ? `<br><span class="mono">${экр(д.можно ? д.подпись : д.почему)}</span>` : ''}
          </button>`).join('')}
        </div>`}
      </section>
    </div>`;
  поле.querySelectorAll('button[data-id]').forEach(btn => {
    btn.onclick = () => {
      const д = действия.find(x => x.id === btn.dataset.id);
      if (!д?.можно) return;
      д.выполнить(S);
      onПереход(S, true);
    };
  });
}

// Значки мест района, открытых сейчас.
// Все места района: открытые сейчас — ярко, закрытые — серым (иначе днём «Синего часа» на карте будто нет).
const местаРайона = (S, районId) => МЕСТА.filter(м => м.район === районId).map(м => ({ м, открыто: можноВойти(S, м.id).можно }));

function рендерГород(S, onПереход) {
  const поле = $('экран');
  const действия = доступныеДействия(S);
  const выбран = район(ИНТ.карточка ?? S.мир.район) ?? район(S.мир.район);
  const тут = выбран.id === S.мир.район;
  const ход = действия.find(д => д.id === 'переход:' + выбран.id);
  const метка = р => экр(р.имя) + (р.id === S.мир.район ? '<small>ты здесь</small>' : '');
  const места = местаРайона(S, выбран.id);
  задник(БАЗА_КАРТЫ + КАРТА, { время: S.мир.отрезок, глубина: 'размыто' });
  const собрать = естьКартинка => {
    if (S.сцена || S.мир.смена || S.мир.конецДня || ИНТ.район) return;
    const зоны = РАЙОНЫ.map(р => '<button class="b карта-метка' + (р.id === выбран.id ? ' выбрана' : '') + '" data-р="' + р.id + '" style="--x:' + р.наКарте.x + '%;left:var(--x);top:' + р.наКарте.y + '%" aria-pressed="' + (р.id === выбран.id) + '">' + метка(р) + '</button>').join('');
    const html = '<div class="город"><section class="город-вид"><div class="надзаголовок">Порт Теней</div><h1>Город у воды</h1>'
      + (естьКартинка ? '<div class="город-полотно"><img class="город-картинка" width="1672" height="941" src="' + БАЗА_КАРТЫ + КАРТА + '" alt="Карта девяти районов Порта Теней">' + зоны + '</div><nav class="город-кнопки город-список" aria-label="Районы города">' + РАЙОНЫ.map(р => '<button class="b" data-р="' + р.id + '">' + метка(р) + '</button>').join('') + '</nav>' : '<div class="город-кнопки">' + РАЙОНЫ.map(р => '<button class="b" data-р="' + р.id + '">' + метка(р) + '</button>').join('') + '</div>')
      + '</section><aside class="город-карточка"><div class="надзаголовок">Выбранный район</div><h2>' + экр(выбран.имя) + '</h2><p class="карта-описание">' + экр(выбран.описание) + '</p><p class="действие-цена">' + (тут ? значок('место') + 'Ты здесь' : значок('время') + экр(ход?.подпись ?? '') + ' · даром') + '</p>'
      + '<button class="b sin" id="идти"' + (!тут && !ход?.можно ? ' disabled' : '') + '>' + (тут ? 'Вернуться в район' : 'Идти туда') + '</button><div class="места-карты"><h3>Места</h3>'
      + места.map(({м, открыто}) => '<div><b>' + экр(м.имя) + '</b><small class="' + (открыто ? 'открыто' : 'закрыто') + '">' + (открыто ? 'открыто' : экр(можноВойти(S, м.id).почему ?? 'закрыто')) + '</small></div>').join('')
      + '</div><p class="подсказка">Выбор района на карте не расходует время.</p></aside></div>';
    if (поле.querySelector('.город')) {
      // Выбор меняет описание справа, а рисунок и метки остаются на месте.
      const шаблон = document.createElement('template'); шаблон.innerHTML = html;
      поле.querySelector('.город-карточка').replaceWith(шаблон.content.querySelector('.город-карточка'));
      поле.querySelectorAll('[data-р]').forEach(el => {
        const выбранная = el.dataset.р === выбран.id;
        el.classList.toggle('выбрана', выбранная);
        el.setAttribute('aria-pressed', String(выбранная));
      });
    } else поле.innerHTML = html;
    поле.querySelectorAll('[data-р]').forEach(el => {
      el.onclick = () => {
        ИНТ.карточка = el.dataset.р;
        рендерГород(S, onПереход);
        поле.querySelector('[data-р="' + el.dataset.р + '"]')?.focus({preventScroll: true});
      };
    });
    $('идти').onclick = () => {
      if (!тут) { if (!ход?.можно) return; ход.выполнить(S); звук('шаг'); }
      ИНТ.карточка = null; ИНТ.район = true;
      onПереход(S);
    };
  };
  if (картаЕсть === undefined) проверитьКарту(() => собрать(картаЕсть)); else собрать(картаЕсть);
}

// В день, когда журнал начинает предлагать направление, об этом говорит сам экран района (PR004-11).
