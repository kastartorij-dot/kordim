// ── стенды ───────────────────────────────────────────────────────────────
// Вход в место — через Движок/стенд-вход.js (его наполняет Движок/мини-игры.js), игра — как от действия места.
export function стендМеста(S, { место, район, отрезок, день = 3, комната = null, кошель = 60, игра }) {
  if (S.сцена) S.сцена = null;
  Object.assign(S.мир, { день: Math.max(S.мир.день, день), отрезок, район, конецДня: null, смена: null });
  if (S.мир.день % 2 !== день % 2) S.мир.день += 1; // чётность дня важна Горму
  S.герой.кошель = Math.max(S.герой.кошель, кошель);
  вход.войти(S, место);
  if (!S.сцена) return false;
  if (комната) S.сцена.комната = комната;
  S.история = [];
  return начатьИгру(S, игра);
}

