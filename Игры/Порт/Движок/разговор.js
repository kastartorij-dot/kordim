// Фраза игрока: сначала своя для этого человека (д.ФРАЗЫ_ЛИЧНО), потом мужской вариант общей
// фразы места, потом общая фраза места, потом реестр города. Личная — самая частая причина, по
// которой один и тот же вопрос игрока звучит дословно одинаково у разных людей в одном доме.
function фраза(д, тид, подход, кто) {
  const свой = кто && д.ФРАЗЫ_ЛИЧНО?.[кто]?.[тид]?.[подход];
  if (свой) return свой;
  const ему = кто && !д.ЛЮДИ[кто]?.она && (д.ФРАЗЫ_ЕМУ?.[тид]?.[подход] ?? ФРАЗЫ_ЕМУ_ГОРОДА[тид]?.[подход]);
  if (ему) return ему;
  const т = д.ФРАЗЫ?.[тид] ?? РЕЕСТР[тид]?.фразы;
  return (т && т[подход]) || (т && т['прямо']) || (д.ТЕМЫ[тид] ?? РЕЕСТР[тид]).ярлык;
}

// Ответ человека на тему в текущем подходе: { узел, р, текст, эффект } или null, если ответа нет.
function ответ(S, кто, тид) {
  const с = S.сцена, д = Д(S);
  const узел = (д.Р[кто] || {})[тид];
  const р = узел ? узел[с.подход] || узел['любой'] || null : null;
  if (!р) return null;
  const овер = р.поПерсонажу && р.поПерсонажу[S.герой.начало];
  const текст = (typeof овер === 'string' ? овер : овер && овер.т) || р.т;
  const эффект = (овер && typeof овер === 'object' && овер.э) || р.э;
  return { узел, р, текст, эффект };
}

// Реплика, из которой ветер вынес каждое третье слово.
function рвать(текст) {
  let k = 0;
  return текст.split(/(\s+)/).map(ч => (/^\s*$/.test(ч) ? ч : (k++ % 3 === 2 ? '…' : ч))).join('');
}

// Тема уже задана, если её спрашивали этим тоном или другим тоном, но человек ответил тем же узлом
// (своего текста для этой манеры нет). Такой повтор не стоит хода и денег (PR004-03).
function уженоТемы(S, кто, тид, подход) {
  const л = S.мир.люди[кто];
  if (!л) return false;
  if (л.спрошено.includes(тид + ':' + подход)) return true;
  const узел = (Д(S).Р[кто] || {})[тид];
  if (!узел) return false;
  const свой = узел[подход] || узел['любой'];
  return л.спрошено.some(к => к.startsWith(тид + ':') && (узел[к.slice(тид.length + 1)] || узел['любой']) === свой);
}

function спросить(S, тид) {
  const с = S.сцена, д = Д(S), кто = с.собеседник;
  const л = человек(S, кто);
  const о = ответ(S, кто, тид);
  const ключТон = тид + ':' + с.подход;
  const повтор = уженоТемы(S, кто, тид, с.подход);
  // условие «хватает денег» могло устареть между построением списка и кликом — перепроверяем
  const трата = о?.эффект?.гроши < 0 && !(повтор && !о.р.дальше) ? -о.эффект.гроши : 0;
  if (трата > S.герой.кошель) return;

  // Ветер на галерее уносит часть слов: пока не придвинешься, расслышать нечего, и вопрос не засчитывается.
  if (д.КОМНАТЫ[с.комната]?.ветер && !есть(S, 'придвинулся')) {
    с.мояреплика = фраза(д, тид, с.подход, кто);
    с.реплика = `${рвать(о?.р.т ?? д.ОТГОВОРКИ[кто])}\n\nВетер уносит половину слов. Придвинься, чтобы расслышать.`;
    return;
  }

  // Попытка заплатить, которую отвергли, не является состоявшейся платой.
  if (!повтор) отметитьМанеру(S, с.подход === 'деньгами' && трата === 0 ? 'предлагал_деньги' : с.подход);
  с.мояреплика = фраза(д, тид, с.подход, кто);
  ушиСлышат(S, тид);

  if (!о) {
    с.реплика = д.ОТГОВОРКИ[кто];
    if (!повтор) {
      л.спрошено.push(ключТон);
      времяИдёт(S, 1);
    }
    return;
  }
  const { р, узел } = о;

  // Об одном и том же одним и тем же тоном второй раз — тот же ответ, но вечер на это не
  // тратится и расположение не копится (это и держит дом от фарма визитами). Кроме веток
  // с продолжением: их читают заново, чтобы дойти до конца.
  // Повтор показывает тот же ответ, что был (с поправкой на начало героя), и отмечает тон заданным.
  if (повтор && !р.дальше) {
    с.реплика = о.текст;
    if (!л.спрошено.includes(ключТон)) л.спрошено.push(ключТон);
    return;
  }
  if (!повтор) л.спрошено.push(ключТон);

  с.реплика = о.текст;
  // Недочитанную ветку можно начать заново, но расположение и дом за неё даются один раз —
  // иначе ветку, брошенную на середине, фармят визитами.
  if (о.эффект && !повтор) применить(S, о.эффект);
  if (р.тема) датьТему(S, р.тема);

  // подход против натуры: нажим стоит расположения (старое: без ограничения снизу)
  const ч = д.ЛЮДИ[кто];
  if (!повтор && ч.обижает && с.подход === ч.обижает && с.подход !== ч.любит && !узел['любой']) {
    л.распол = (л.распол || 0) - 1;
  }
  // После оплаченной реплики, которой кончилось время, — ещё один вопрос этому человеку даром:
  // заплатил за разговор — получи хотя бы один ответ (PR004-03).
  const последнийДаром = с.времяВышло && с.лишнийВопрос === кто;
  if (последнийДаром) с.лишнийВопрос = null;
  else {
    времяИдёт(S, 1);
    if (трата > 0 && с.времяВышло) с.лишнийВопрос = кто;
  }

  if (р.дальше && р.дальше.length) {
    // ВОПРОС: старая игра брала узел ветки по тону в момент «Продолжить»; ветка теперь помнит тон, с которого началась.
    с.ветка = { кто, тид, шаг: 0, подход: с.подход };
  }
}

function продолжитьВетку(S) {
  const с = S.сцена, д = Д(S), в = с.ветка;
  const узел = д.Р[в.кто][в.тид][в.подход] || д.Р[в.кто][в.тид]['любой'];
  const шаг = узел.дальше[в.шаг];
  const л = человек(S, в.кто);
  л.шаги ??= {}; // сколько шагов ветки уже прочитано — их эффекты второй раз не даются
  if (шаг.э && в.шаг >= (л.шаги[в.тид] ?? 0)) применить(S, шаг.э);
  л.шаги[в.тид] = Math.max(л.шаги[в.тид] ?? 0, в.шаг + 1);
  if (шаг.тема) датьТему(S, шаг.тема);
  с.реплика = шаг.т;
  с.мояреплика = '';
  в.шаг++;
  if (в.шаг >= узел.дальше.length) {
    человек(S, в.кто).исчерпано.push(в.тид);
    с.ветка = null;
  }
}

// Какую сцену показать: б.сцены — ступени; берётся последняя подошедшая. Ступень с «если» проверяется
// условием графа (доверие, этап линии, её решение — шаг 11), ступень с «от» — старым порогом расположения.
// Цена комнаты в выбор не входит: оплаченный вечер — доступ, а не близость.
// б.сцена — одна сцена на всю игру (старый формат, если ступеней не завели).
export function выбратьСценуБлизости(S, б, кто) {
  if (!б.сцены) return б.сцена;
  const подходит = x => (x.если ? еслиДиалога(S, x.если, кто) : расп(S, кто) >= (x.от ?? 0));
  const подходящие = б.сцены.filter(подходит);
  return (подходящие.at(-1) ?? б.сцены[0]).сцена;
}

function ходИнтим(S, б, кто) {
  const с = S.сцена;
  for (const ф of б.флаги) флаг(S, ф);
  if (б.распол) применить(S, { распол: { [кто]: б.распол } }); // старый формат; у линий шага 11 оплаченный вечер доверия не даёт
  оплаченныйВечер(S, кто);
  с.реплика = '';
  с.мояреплика = '';
  с.нужнаСцена = выбратьСценуБлизости(S, б, кто); // текст лежит файлом, его подгружает догрузитьСцену
  S.герой.напряжение = 0; // ГДД §9
}

// Пометка автора внутри файла сцены — «[ ЗАГОТОВКА АВТОРА. … ]» отдельным абзацем. Она для правки текста,
// игроку её не показываем.
const безПометокАвтора = текст => текст
  .replace(/^\[\s*ЗАГОТОВКА[^\]]*\]\s*$/gm, '')
  .replace(/\n{3,}/g, '\n\n')
  .trim();

// Подгружает текст сцены близости. читать(id) → Promise<string|null>: в браузере это fetch,
// в тесте — чтение файла. Нет файла — «Дальше — без слов.», как в старой игре.
export async function догрузитьСцену(S, читать) {
  const с = S.сцена;
  const id = с?.нужнаСцена;
  if (!id) return false;
  let текст = null;
  try { текст = await читать(id); } catch { текст = null; }
  if (S.сцена !== с || с.нужнаСцена !== id) return false;
  с.реплика = текст ? безПометокАвтора(текст.replace(/\r\n/g, '\n')) : Д(S).ЭКРАН.подпись.дальшеБезСлов;
  с.нужнаСцена = null;
  return true;
}

