function посчитатьИтог(S, причина) {
  const д = Д(S), м = М(S), Ч = д.СЧЁТ;
  const с = д.ЛЮДИ;
  // только люди этого места: работы тоже пишут в S.мир.люди («старшой», «весовщик»), и им нет карточки в комнатах
  const ключи = Object.keys(S.мир.люди).filter(к => с[к] && typeof S.мир.люди[к].распол === 'number');
  const лучший = ключи.sort((a, b) => S.мир.люди[b].распол - S.мир.люди[a].распол)[0];
  const тепло = лучший ? S.мир.люди[лучший].распол : 0;
  const ctx = { причина, тепло };
  const и = д.ИТОГИ.find(x => выполнено(S, x.если, ctx));

  const потрачено = S.сцена.кошелёкНаВходе - S.герой.кошель;
  const строки = [[Ч.потрачено, потрачено + Ч.грошей]];
  if (м.долг) строки.push([Ч.долг, м.долг + Ч.грошей]);
  строки.push([Ч.тем, String(S.мир.темы.filter(т => !д.ТЕМЫ[т]?.всегда).length)]);
  строки.push([Ч.осмотрено, String(м.осмотрено.length)]);
  строки.push([Ч.домЧитает, Ч.домИмена[String(м.дом)]]);
  if (лучший && тепло > 0) строки.push([Ч.запомнила, с[лучший].имя + ' (' + тепло + ')']);

  const утечки = д.УТЕЧКИ.filter(у => выполнено(S, у.если)).map(у => у.текст);
  return { причина, заг: и.заг, текст: и.текст, строки, утечки, потрачено };
}

