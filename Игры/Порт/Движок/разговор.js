        const хозяин = а.эффект?.финал === 'дверь' && К.люди.find(id => графКто(id)?.ветки.выход);
        if (хозяин) { диалог.выйти(S2, хозяин); return; }
        применить(S2, а.эффект);
        if (S2.сцена?.диалог && S2.сцена.реплика) S2.сцена.диалог.лента.push({вид:'нарратив',т:S2.сцена.реплика});
        // предупреждение о риске: вход в «Синий час» почти впритык — на еду и ночлег до утра не останется
