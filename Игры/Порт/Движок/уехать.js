export function следующийШагУехать(S){
 const у=читатьУехать(S);
 const запаснойПуть = S.мир.день<=27 ? ' С дней 18–27 можно договориться у Локи о Проходе на позднее судно; услуга должна быть оплачена.' : ' Оба рейса первого сезона ушли; это будет отражено в итоге.';
 if(у.исход)return ИТОГИ_ОТЪЕЗДА[у.исход].текст+(['сорван','не-подтвердил'].includes(у.исход)?запаснойПуть:'');
 if(!у.путь&&S.мир.день>16)return 'Запись на рейсы закрыта.'+запаснойПуть;
 if(!у.слышал)return 'Расписание и оба пути: Контора Дорров в доках, с дня 3.';
 if(!у.путь)return S.мир.день<=16?'Выбери рейс и запишись в конторе до дня 16: по книге 20 сейчас +40, по руке 40 и поручитель Ножей.':'Запись закрыта. С дней 18–27 Локи может предложить физический проход за уже оплаченную услугу Проход.';
 if(S.мир.день>(у.погода==='ждать'?28:(РЕЙСЫ.find(р=>р.id===у.рейс)?.день??28)))return ИТОГИ_ОТЪЕЗДА.сорван.текст;
 if(!у.подтверждено)return S.мир.день<=21?'Подтверди место у Тобба в конторе до конца дня 21: сверить документы или условия поручителя.':'Срок подтверждения места закончился в день 21.'+запаснойПуть;
 if(!у.погода)return 'С дня 16 проверь огонь на маяке или сообщение конторы. Выбери ждать поздний рейс или держаться расписания.';
 return 'Посадка: Выход к судам, доки, день '+(у.погода==='ждать'?28:РЕЙСЫ.find(р=>р.id===у.рейс).день)+', утро, день или вечер.'+(у.остаток?' До неё внеси остаток 40 гр. в конторе.':' Можно взойти, передать место или осознанно остаться.');
}
