const новыйОтъезд=()=>({слышал:false,рейс:null,путь:null,подтверждено:false,остаток:0,погода:null,последнееСлово:false,исход:null,цена:null});
function читатьУехать(S) {
 const текущее=S.мир.уехать??{},у={...новыйОтъезд(),...текущее};
 const старое=S.мир.места?.['контора-дорров']?.память;
 if(!у.путь&&старое?.билет?.тариф) {
  const книга=старое.билет.тариф==='книга';
  Object.assign(у,{слышал:true,рейс:S.мир.день<=24?'береговой':'поздний',путь:книга?'по-книге':'по-руке',
   подтверждено:true,остаток:книга&&!старое.билетОплачен?40:0,задаток:книга?20:40,
   цена:книга?'20 гр. уже внесены; остаток '+(старое.билетОплачен?0:40)+' гр.':'40 гр. уже внесены и обязательство Ножам',
   старыйБилет:true,билетВыдан:!!старое.билетОплачен});
 }
 return у;
}
export function уехать(S) {
 const приведённое=читатьУехать(S);
 S.мир.уехать??={};
 Object.assign(S.мир.уехать,приведённое);
 return S.мир.уехать;
}
const журнал=(S,с)=>S.мир.журналДня.push(с);
const можноНачать=S=>!S.мир.кампанияЗавершена && (!S.мир.цели?.зафиксирована || S.мир.цели.выбрана==='уехать');
export function условиеУехать(S,вид) {
 const у=читатьУехать(S),д=S.сцена?.вход?.день??S.мир.день; if(!можноНачать(S))return false;
 if(вид==='слух')return !у.слышал && д>=3;
 if(вид==='рейс-береговой'||вид==='рейс-поздний')return у.слышал&&!у.путь&&д<=16&&у.рейс!==вид.slice(5);
 if(вид==='книга')return !!у.рейс&&!у.путь&&д<=16;
 if(вид==='рука')return !!у.рейс&&!у.путь&&д<=16&&(S.мир.фракции?.ножи??0)>=1;
 if(вид==='подтвердить-работой')return !!у.путь&&!у.подтверждено&&д>=10&&д<=21&&(S.мир.работы?.разгрузка?.смен??0)>=1;
 if(вид==='подтвердить-бумаги')return !!у.путь&&!у.подтверждено&&д>=10&&д<=21;
 if(вид==='погода-ждать'||вид==='погода-риск')return !!у.путь&&!у.погода&&д>=16;
 if(вид==='доплата')return у.путь==='по-книге'&&у.остаток>0;
 if(вид==='локи')return д>=18&&д<=27&&!['по-книге','по-руке','локи','остался','передал'].includes(у.исход)&&у.путь!=='локи'&&S.мир.флаги.includes('проход_локи');
 if(вид==='прощание')return !!у.путь&&у.подтверждено&&!у.последнееСлово;
 const рейс=РЕЙСЫ.find(р=>р.id===у.рейс),день=у.погода==='ждать'?28:(рейс?.день??28);
 if(вид==='посадка'||вид==='остаться'||вид==='передать')return !!у.путь&&!у.исход&&у.подтверждено&&!!у.погода&&д===день&&(S.сцена?.вход?.отрезок??S.мир.отрезок)!=='ночь'&&(вид!=='посадка'||у.остаток===0);
 return false;
}
function выдатьБилет(S) {
 const у=уехать(S);
 if(у.билетВыдан||S.мир.выдано?.уехать_билет)return;
 у.билетВыдан=true;(S.мир.выдано??={}).уехать_билет=true;
 const итог=выдатьВещь(S,'билет','контора-дорров');
 журнал(S,итог==='получено'?'Оплаченный билет выдан; Тобб также сверяет посадку по книге.':'Оплаченный билет ждёт свободного места в сумке; Тобб сверит посадку по книге.');
}
export function применитьУехать(S,вид) {
 if(!условиеУехать(S,вид))return false;const у=уехать(S),д=S.сцена?.вход?.день??S.мир.день;
 switch(вид) {
 case 'слух':у.слышал=true;журнал(S,'Рейсы: береговой день 24, поздний день 28. Запись до дня 16; подтверждение до дня 21.');break;
 case 'рейс-береговой':case 'рейс-поздний':у.рейс=вид.slice(5);журнал(S,'Выбран рейс: '+РЕЙСЫ.find(р=>р.id===у.рейс).имя);break;
 case 'книга':у.путь='по-книге';у.остаток=40;у.задаток=20;у.цена='20 гр. задатка и 40 гр. до посадки';журнал(S,'Запись в судовую книгу: 20 гр. внесены, 40 гр. до посадки.');взятьОбязательство(S,{id:'уехать_место',название:'Подтвердить место на рейсе',срок:{день:21,отрезок:'ночь',граница:'конец'}});break;
 case 'рука':у.путь='по-руке';у.задаток=40;добавитьОчки(S,'ножи',1,'нить');датьТему(S,'bilet_po_ruke');{const к=S.мир.места?.['контора-дорров'];if(к&&!к.флаги.includes('долг_чести'))к.флаги.push('долг_чести');}выдатьБилет(S);у.цена='40 гр. и передать запечатанный ответ в следующем порту';взятьОбязательство(S,{id:'уехать_услуга',название:'Ножам: передать запечатанный ответ в следующем порту',срок:{день:35,отрезок:'ночь',граница:'конец'}});журнал(S,'Поручитель Ножей назвал услугу: передать запечатанный ответ в следующем порту. Плата 40 гр.');break;
 case 'подтвердить-работой':case 'подтвердить-бумаги':у.подтверждено=true;закрытьОбязательство(S,'уехать_место');журнал(S,у.путь==='по-руке'?'Одвин сверил с поручителем адрес и знак получателя: место подтверждено.':'Тобб сверил имя и запись, Одвин помог переписать грузовую опись. Место подтверждено без случайной смены.');break;
 case 'погода-ждать':у.погода='ждать';журнал(S,'Выбран безопасный поздний рейс: день 28.');break;
 case 'погода-риск':у.погода='риск';журнал(S,'Огонь и расписание проверены. Рейс остаётся на день '+РЕЙСЫ.find(р=>р.id===у.рейс).день+'. При небезопасном море капитан решит об отсрочке.');break;
 case 'доплата':у.остаток=0;выдатьБилет(S);журнал(S,'Остаток 40 гр. внесён, билет полностью оплачен.');break;
 case 'локи':у.исход=null;у.путь='локи';у.рейс='поздний';у.подтверждено=true;у.погода='ждать';у.остаток=0;у.цена='оплаченная услуга Проход Локи';закрытьОбязательство(S,'уехать_место');журнал(S,'Проход Локи: склад → лодка → позднее судно, день 28.');break;
 case 'прощание':у.последнееСлово=true;журнал(S,'Одвин оглядел берег и оставил слово тем, кто останется. Посадка ещё не обязательна.');break;
 case 'остаться':case 'передать':у.исход=вид==='остаться'?'остался':'передал';журнал(S,ИТОГИ_ОТЪЕЗДА[у.исход].текст);break;
 case 'посадка':{
  у.исход=у.путь;const сезон=состояниеСезона(S),разделы=разделыИтога(S,деталиУехать(S)),финал={день:д,сезон:сезон.номер,деньСезона:сезон.день,цель:'уехать',исход:у.исход,...ИТОГИ_ОТЪЕЗДА[у.исход],разделы,строки:строкиИтога(разделы)};
  S.мир.итогСезона=финал;S.мир.кампанияЗавершена=true;
  обновитьСезон(S);
  S.мир.конецДня={день:д,журнал:[...S.мир.журналДня],причины:[],финал,отъезд:true,выспался:false};
  S.сцена=null;break;
 }
 }return true;
}
export function закрытьДеньУехать(S,итог){
 const прочитано=читатьУехать(S);
 if (!прочитано.путь) {
  if (прочитано.слышал && S.мир.день===15) итог.причины.push('Завтра последний день записи на рейс: Контора Дорров принимает утром и днём.');
  if (прочитано.слышал && S.мир.день===16) итог.причины.push('Запись на рейсы закрылась. С дней 18–27 остаётся Проход Локи за оплаченную услугу, если ты решишь воспользоваться им.');
  return;
 }
 if(прочитано.исход)return;
 const у=уехать(S),д=S.мир.день;
 if(д===15&&!у.погода)итог.причины.push('Завтра шторм. После него проверь огонь маяка или сообщение конторы: перенос рейса не потеряется.');
 if(д===20&&!у.подтверждено)итог.причины.push('Завтра последний день подтверждения места: Тобб сверит документы или условие поручителя без случайной смены.');
 if(д>=21&&!у.подтверждено){у.исход='не-подтвердил';итог.причины.push(ИТОГИ_ОТЪЕЗДА[у.исход].текст+' До конца дня 27 остаётся возможность договориться о Проходе Локи.');return;}
 const день=у.погода==='ждать'?28:РЕЙСЫ.find(р=>р.id===у.рейс)?.день??28;
 if(д===день-1)итог.причины.push('Завтра посадка у выхода к судам. '+(у.остаток?'Осталось внести 40 гр. в конторе.':'Место оплачено.'));
 if(д>=день){у.исход=у.подтверждено?'сорван':'не-подтвердил';итог.причины.push(ИТОГИ_ОТЪЕЗДА[у.исход].текст);}
}
