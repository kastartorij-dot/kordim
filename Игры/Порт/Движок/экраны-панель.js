// Нижняя панель «Город · Герой · Вещи · Журнал» и три экрана поверх: Герой, Вещи, Журнал (этап 5).
// Они открываются поверх города и сцены места и закрываются, не трогая ни то, ни другое.
// Что показать — решают Движок/сводка.js и Движок/вещи.js; здесь только вёрстка.
import { сводкаГероя, сводкаЖурнала } from './сводка.js';
import { слоты, имяВещи, действияВещей, свободных, вместимость } from './вещи.js';
import { действияХозяйства, описатьВещь } from './хозяйство.js';
import { описаниеОдежды } from './одежда.js';
import { ИНТ } from './экраны.js';
import { показатьОкно, закрытьОкно } from './окна.js';

const $ = id => document.getElementById(id);
const экр = т => String(т).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

// Открытая вкладка панели: 'город' (ничего поверх), 'герой', 'вещи', 'журнал'.
export const ПАН = { вкладка: 'город', журнал: 'дела', вещь: null };
const ВКЛАДКИ = [['место', 'Место'], ['город', 'Город'], ['вещи', 'Вещи'], ['журнал', 'Журнал'], ['герой', 'Герой']];

const блок = (заг, тело) => `<section class="пан-блок"><h3 class="px">${экр(заг)}</h3>${тело}</section>`;

function экранГероя(S) {
  const в = сводкаГероя(S);
  const ремесло = в.ремёсла.map(р => `${экр(р.имя)} — ${экр(р.ступень)}, зарубки: ${р.зарубки}`).join('; ') || 'нет';
  const тело = в.тело.map(т => `
    <div class="строка-тела тело-${т.значение}">
      <span class="полоска px">${экр(т.название)} ${т.значение}</span>
      <span class="описание">${экр(т.строка)}</span>
    </div>`).join('');
  const пол = в.положение;
  const одежда = описаниеОдежды(S);
  const фракции = пол.фракции.map(ф => `
    <div class="строка-тела"><span class="полоска px">${экр(ф.имя)} ${ф.значение > 0 ? '+' : ''}${ф.значение}</span><span class="описание">${экр(ф.слово)}</span></div>`).join('');
  return `
    <p class="пан-имя"><b>${экр(в.имя)}</b><br><span class="mono">${экр(в.начало)}</span><br><span class="mono">${ремесло}</span></p>
    ${блок('Тело', тело)}
    ${блок('Положение', `${фракции}
      <div class="строка-тела"><span class="полоска px">Репутация ${пол.репутация.значение > 0 ? '+' : ''}${пол.репутация.значение}</span><span class="описание">${экр(пол.репутация.слово)}</span></div>
      <div class="строка-тела"><span class="полоска px">Тень ${пол.тень.значение}</span><span class="описание">${экр(пол.тень.строка)}</span></div>`)}
    ${блок('Одежда', `<p>${экр(одежда.база)} · верх: ${экр(одежда.верх)} · вид ${одежда.вид}<br><span class="mono">${экр(одежда.состояние)}</span></p>`)}
    ${блок('Состояние', `<p>Рана: ${S.герой.рана ?? 0} · боль: ${S.герой.боль ?? 0} · жажда: ${S.герой.жажда ?? 0} · хмель: ${S.герой.хмель ?? 0} · напряжение: ${S.герой.напряжение ?? 0}<br>Привычки: табак ${S.герой.привычкаТабак ?? 0}, выпивка ${S.герой.привычкаХмель ?? 0}, настой ${S.герой.привычкаНастой ?? 0}</p>`)}
    ${блок('Жильё', `<p>${экр(в.жильё)}</p>`)}`;
}

function экранВещей(S) {
  const дей = [...действияВещей(S), ...действияХозяйства(S)];
  const ячейки = слоты(S);
  const набор = ячейки.filter(x => x && !x.блок && !x.продолжение).map(x => ({ x, где: 'При себе' }));
  for (const id of ['вдова', 'угол']) for (const x of S.герой.хранилище?.[id] ?? []) набор.push({ x, где: id === 'вдова' ? 'Сундук у вдовы' : 'Свой сундук' });
  for (const з of S.герой.залог ?? []) набор.push({ x: з.вещь, где: 'Залог · выкупить до дня ' + з.выкупДо });
  for (const x of S.герой.возвратСиба ?? []) набор.push({ x, где: 'У Сиба' });
  const выбран = набор.find(н => н.x.uid === ПАН.вещь) ?? набор[0];
  ПАН.вещь = выбран?.x.uid ?? null;
  const кнопки = uid => дей.filter(x => x.uid === uid).map(д => '<button class="b" data-действие="' + экр(д.id) + '"' + (д.можно ? '' : ' disabled') + '>' + экр(д.текст) + (!д.можно && д.почему ? '<small>' + экр(д.почему) + '</small>' : '') + '</button>').join('');
  const сетка = ячейки.map((x, i) => {
    if (!x) return '<div class="ячейка пусто" title="Свободное место ' + (i+1) + '"><span aria-hidden="true">·</span></div>';
    if (x.блок) return '<div class="ячейка блок"><span>Рана</span><small>Недоступно</small></div>';
    const uid = x.продолжение ?? x.uid;
    const вещь = набор.find(н => н.x.uid === uid)?.x;
    return '<button class="b ячейка' + (uid === ПАН.вещь ? ' on' : '') + '" data-вещь="' + экр(uid) + '" aria-pressed="' + (uid === ПАН.вещь) + '">' + (x.продолжение ? '<small>Занято той же вещью</small>' : '<b>' + экр(имяВещи(x)) + (x.количество > 1 ? ' ×' + x.количество : '') + '</b>' + (S.герой.рука === uid ? '<small>В руке</small>' : '')) + '</button>';
  }).join('');
  const внешние = набор.filter(н => н.где !== 'При себе').map(н => '<button class="b вещь-в-хранилище' + (н.x.uid === ПАН.вещь ? ' on' : '') + '" data-вещь="' + экр(н.x.uid) + '"><b>' + экр(имяВещи(н.x)) + '</b><small>' + экр(н.где) + '</small></button>').join('');
  const одежда = описаниеОдежды(S), снять = дей.find(x => x.id === 'снять-верх');
  const ожидают = (S.мир.отложенныеВещи ?? []).map(x => '<p>' + экр(имяВещи(x.тип)) + ' — освободи место и забери в городе.</p>').join('');
  return '<div class="вещи-сводка">Свободно ' + свободных(S) + ' из ' + вместимость(S) + ' мест' + (вместимость(S) < 8 ? ' · рана ограничивает сумку' : '') + '</div><div class="вещи-раскладка"><section>'
    + блок('При себе', '<div class="сумка-сетка">' + сетка + '</div>')
    + (внешние ? блок('Хранение и залог', '<div class="внешние-вещи">' + внешние + '</div>') : '')
    + (ожидают ? блок('Ждут получения', ожидают) : '') + '</section><section class="вещь-подробно">'
    + (выбран ? '<div class="надзаголовок">' + экр(выбран.где) + '</div><h3>' + экр(имяВещи(выбран.x)) + '</h3>'  + '<p>' + экр(описатьВещь(выбран.x)) + '</p><div class="вещь-действия">' + кнопки(выбран.x.uid) + '</div>' : '<h3>Сумка свободна</h3><p class="подсказка">Выбери вещь, чтобы осмотреть её и увидеть доступные действия.</p>')
    + блок('Надето', '<p>' + экр(одежда.база) + ' · верх: ' + экр(одежда.верх) + '</p><p class="подсказка">' + экр(одежда.состояние) + '</p>' + (снять ? '<button class="b" data-действие="снять-верх"' + (снять.можно ? '' : ' disabled') + '>Снять верх' + (!снять.можно && снять.почему ? '<small>' + экр(снять.почему) + '</small>' : '') + '</button>' : '')) + '</section></div>';
}

function экранЖурнала(S) {
  const ж = сводкаЖурнала(S);
  const записьДела = д => `
    <div class="тема-журнала ${['просрочено', 'провалено', 'отказано'].includes(д.статус) ? 'враньё' : ''}">
      <b>${экр(д.имя)}</b> <span class="mono">${экр(д.слово)}${д.срок ? ' · ' + экр(д.срок) : ''}</span>
      <p>${экр(д.кто)} — ${экр(д.чего)}${д.вещь ? ` · при себе: ${экр(д.вещь)}` : ''}</p>
      ${д.следующий ? `<p class="mono">Дальше: ${экр(д.следующий)}</p>` : ''}
    </div>`;
  const темы = ж.темы.length ? ж.темы.map(т => `
    <div class="тема-журнала ${т.верность === 'враньё' ? 'враньё' : ''}">
      <b>${экр(т.ярлык)}</b> <span class="mono">${экр(т.верность)} ${т.точки}</span>
      ${т.ушла.length ? `<span class="mono ушла">${экр(т.ушла.join(', '))}</span>` : ''}
      ${т.текст ? `<p>${экр(т.текст)}</p>` : ''}
    </div>`).join('') : '<p class="mono">Пусто</p>';
  const люди = ж.люди.length ? ж.люди.map(л => `<div class="строка-тела"><span class="полоска">${экр(л.имя)}</span><span class="описание">${экр(л.где)} · ${экр(л.слово)}</span></div>`).join('') : '<p class="mono">Пусто</p>';
  const долги = ж.долги.length ? ж.долги.map(д => `<p>${экр(д.место)} — ${д.сумма} гр.</p>`).join('') : '<p>Долгов нет</p>';
  const вклады = ж.вклады.length ? ж.вклады.map(д => `<p>${экр(д.место)} — ${д.сумма} гр.</p>`).join('') : '<p>Вкладов нет</p>';
  const свидетельства = ж.свидетельства.length ? ж.свидетельства.map(у => `<div class="тема-журнала"><b>${экр(у.имя)}</b><p>${экр(у.текст)}</p></div>`).join('') : '<p class="mono">Пока нет записей</p>';
  const обязательства = ж.обязательства.length ? ж.обязательства.map(о => `<p>${экр(о.название)} — ${экр(о.статус)}, ${экр(о.срок)}</p>`).join('') : '<p>Нет срочных обязательств</p>';
  const дни = ж.дни.length ? ж.дни.map(д => `
    <div class="день-журнала"><b class="px">День ${д.день}</b>
      ${д.журнал.length ? `<ul class="журнал mono">${д.журнал.map(с => `<li>${экр(с)}</li>`).join('')}</ul>` : ''}
      ${д.причины.length ? `<ul class="журнал mono">${д.причины.map(с => `<li>${экр(с)}</li>`).join('')}</ul>` : ''}
    </div>`).join('') : '<p class="mono">Пусто</p>';
  const голос = ж.голос.map(т => '<p>' + экр(т) + '</p>').join('') || '<p class="mono">Пока нет записей</p>';
  const слухи = ж.слухи.map(с => '<p>' + экр(с.текст) + ' <span class="mono">' + экр(с.статус) + '</span></p>').join('') || '<p class="mono">До тебя пока ничего не дошло</p>';
  const непустой = (заг, html, есть) => есть ? блок(заг, html) : '';
  const вкладки = [['дела','Дела'],['знания','Знания'],['люди','Люди'],['дни','Дни']];
  const текущиеДела = ж.дела.filter(д => ['предложено', 'активно'].includes(д.статус));
  const завершённые = ж.дела.filter(д => !['предложено', 'активно'].includes(д.статус));
  // В полном списке сохраняются все статусы; завершённые вынесены под раскрытие.
  const активныеHTML = текущиеДела.map(записьДела).join('');
  const архивHTML = завершённые.map(записьДела).join('');
  const телоДел = блок('Текущие дела', текущиеДела.length ? активныеHTML : '<p class="подсказка">Текущих дел нет. Спроси у людей или посмотри доску в таверне.</p>')
    + непустой('Обязательства', обязательства, ж.обязательства.length)
    + непустой('Долги', долги, ж.долги.length) + непустой('Вклады', вклады, ж.вклады.length)
    + (завершённые.length ? '<details class="завершённые-дела"><summary>Завершённые дела · ' + завершённые.length + '</summary>' + архивHTML + '</details>' : '');
  const зн = непустой('Голос', голос, ж.голос.length) + непустой('Слухи об Одвине', слухи, ж.слухи.length) + непустой('Темы', темы, ж.темы.length) + непустой('Свидетельства', свидетельства, ж.свидетельства.length);
  const сегодня = S.мир.журналДня.length ? блок('Сегодня · день ' + S.мир.день, '<ul class="журнал">' + S.мир.журналДня.map(с => '<li>' + экр(с) + '</li>').join('') + '</ul>') : '';
  const содержимое = { дела: телоДел, знания: зн || '<p class="подсказка">Новых сведений пока нет.</p>', люди: люди, дни: сегодня + (ж.дни.length ? блок('Последние дни', дни) : '<p class="подсказка">Завершённых дней пока нет.</p>') };
  return '<div class="журнал-вкладки">' + вкладки.map(([id,имя]) => '<button class="b' + (ПАН.журнал === id ? ' on' : '') + '" data-журнал="' + id + '" aria-pressed="' + (ПАН.журнал === id) + '">' + имя + '</button>').join('') + '</div><div class="журнал-содержимое">' + содержимое[ПАН.журнал] + '</div>';
}

const ЭКРАНЫ = { герой: ['Герой', экранГероя], вещи: ['Вещи', экранВещей], журнал: ['Журнал', экранЖурнала] };

function убратьОверлей() {
  document.querySelectorAll('.ов.пан').forEach(o => o.remove());
}

export function рендерПанель(S, onШаг) {
  const панель = $('панель');
  if (!панель) return;
  const заперт = !!S.сцена || !!S.мир.смена || !!S.мир.конецДня;
  const открыта = ПАН.вкладка !== 'город';
  const выбран = открыта ? ПАН.вкладка : ИНТ.район ? 'место' : 'город';
  панель.innerHTML = ВКЛАДКИ.map(([id,имя]) => '<button class="b' + (выбран === id ? ' on' : '') + '" data-вкладка="' + id + '"' + ((id === 'город' || id === 'место') && заперт ? ' disabled' : '') + (выбран === id ? ' aria-current="page"' : '') + '>' + имя + '</button>').join('');
  панель.querySelectorAll('[data-вкладка]').forEach(b => {
    b.onclick = () => {
      const id = b.dataset.вкладка;
      if (id === 'город' || id === 'место') {
        ИНТ.район = id === 'место'; ИНТ.карточка = null; ПАН.вкладка = 'город';
        onШаг(S);
      } else {
        ПАН.вкладка = ПАН.вкладка === id ? 'город' : id;
        if (id === 'журнал') ПАН.журнал = 'дела';
        рендерПанель(S, onШаг);
      }
      панель.querySelector('[data-вкладка="' + id + '"]')?.focus({preventScroll:true});
    };
  });
  убратьОверлей();
  const э = ЭКРАНЫ[ПАН.вкладка];
  if (!э) return;
  const ов = document.createElement('div');
  ов.className = 'ов пан';
  ов.innerHTML = '<div class="овбокс пан-бокс"><div class="пан-шапка"><div><div class="надзаголовок">Одвин Скарре</div><h2>' + э[0] + '</h2></div><button class="b" id="пан-закрыть">Закрыть ×</button></div>' + э[1](S, onШаг) + '</div>';
  document.body.appendChild(ов);
  ов.style.bottom = панель.offsetHeight + 'px';
  const закрыть = () => {
    const прежняя = ПАН.вкладка;
    закрытьОкно(ов); ПАН.вкладка = 'город'; рендерПанель(S, onШаг);
    панель.querySelector('[data-вкладка="' + прежняя + '"]')?.focus({preventScroll:true});
  };
  $('пан-закрыть').onclick = закрыть;
  показатьОкно(ов, закрыть);
  ов.querySelectorAll('[data-журнал]').forEach(b => {
    b.onclick = () => { ПАН.журнал = b.dataset.журнал; рендерПанель(S,onШаг); document.querySelector('[data-журнал="' + ПАН.журнал + '"]')?.focus({preventScroll:true}); };
  });
  ов.querySelectorAll('[data-вещь]').forEach(b => {
    b.onclick = () => { ПАН.вещь = b.dataset.вещь; рендерПанель(S,onШаг); document.querySelector('[data-вещь="' + ПАН.вещь + '"]')?.focus({preventScroll:true}); };
  });
  ов.querySelectorAll('[data-действие]').forEach(b => {
    const номер = S.мир.шаг ?? 0;
    b.onclick = () => {
      if ((S.мир.шаг ?? 0) !== номер) return;
      const д = [...действияВещей(S), ...действияХозяйства(S)].find(x => x.id === b.dataset.действие);
      if (д && д.можно && д.выполнить(S)) { S.мир.шаг = номер + 1; onШаг(S); }
    };
  });
}
