// Окно живой мини-игры поверх экрана места или смены (с 03.11 вместо текстового выбора хода).
// Сама игра — модуль Движок/песочница/<игра>.js: запустить(контейнер, { навык, тихо, сигнал, ...живая.вход }) → Promise<{ уровень, очки }>.
// живая.вход — что ещё нужно игре от хода: вариант на этот раз, у торга цена товара.
// Ход с полем живая (Движок/уровень.js) экран отдаёт сюда: окно открывает игру, по исходу показывает слово итога,
// и только потом ход выполняется с итогом — расчёты те же, что у прежнего выбора.
// Закрыть окно до «Начать» — отказ: ничего не меняется. Бросить посреди партии — провал { уровень: 'плохо', брошено: true }.
// Пока окно открыто, ничего не сохраняется: перезагрузка возвращает к ходу, который открывает игру.
// Музыка места на время игры стихает, звук игры — по ползунку «Звуки» (0 — игра без звука).
import { показатьОкно, закрытьОкно } from './окна.js';
import { музыка, музыкаДля, множительЗвуков } from './звук.js';
import { настройкиИнтерфейса } from './настройки-интерфейса.js';

const экр = т => String(т ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;');
const СЛОВО = { плохо: 'Плохо', нормально: 'Нормально', отлично: 'Отлично' };
// Громкость звуков игры при ползунке «Звуки» на 70 — как в песочнице (Движок/песочница/общее.js, звук.громкость).
const ГРОМКОСТЬ_ПЕСОЧНИЦЫ = 0.12;

let открыто = null;
export const живаяОткрыта = () => !!открыто?.isConnected;

// Открыть игру. живая — { игра, навык, заголовок, вход? }. Итог — { уровень, очки, брошено? } или null (отказ, игра не началась).
export function открытьЖивую(живая) {
  if (живаяОткрыта()) return Promise.resolve(null);
  return new Promise(готово => {
    const сигнал = new AbortController();
    const ов = document.createElement('div');
    ов.className = 'ов живая';
    ов.innerHTML = `<div class="овбокс живая-бокс">
      <header class="живая-шапка"><h2>${экр(живая.заголовок)}</h2>
        <button class="b" data-закрыть>Бросить <small>Esc</small></button></header>
      <div class="живая-поле"></div>
      <div class="живая-слой" hidden></div></div>`;
    document.body.appendChild(ов);
    открыто = ов;
    const поле = ов.querySelector('.живая-поле'), слой = ов.querySelector('.живая-слой');
    const кнЗакрыть = ов.querySelector('[data-закрыть]');
    let кончено = false, модуль = null;

    const уровень = настройкиИнтерфейса().звуки;
    const тихо = !(уровень > 0);
    музыка(null); // музыка места стихает; вернёт её перерисовка экрана после хода (или отказ ниже)

    const выйти = итог => {
      if (кончено) return;
      кончено = true;
      сигнал.abort();
      закрытьОкно(ов);
      открыто = null;
      готово(итог);
    };
    // Игра ещё на заставке «Начать» — не начата (заставку рисует сама игра, Движок/песочница/общее.js).
    const наЗаставке = () => !!поле.querySelector('.пс-старт');
    const спросить = () => {
      if (!слой.hidden) { слой.hidden = true; слой.innerHTML = ''; return; } // Esc второй раз — назад к игре
      if (!модуль || наЗаставке()) { выйти(null); return; }
      слой.innerHTML = `<div class="живая-панель"><p>Бросить посреди игры? Это засчитается как неудача.</p>
        <div class="живая-кнопки"><button class="b" data-д="назад">Вернуться к игре</button><button class="b sin" data-д="бросить">Бросить</button></div></div>`;
      слой.hidden = false;
      слой.querySelector('[data-д="назад"]').onclick = () => { слой.hidden = true; слой.innerHTML = ''; };
      слой.querySelector('[data-д="бросить"]').onclick = () => выйти({ уровень: 'плохо', очки: 0, брошено: true });
      слой.querySelector('[data-д="назад"]').focus({ preventScroll: true });
    };
    кнЗакрыть.onclick = () => (кнЗакрыть.dataset.итог ? null : спросить());
    показатьОкно(ов, () => (кнЗакрыть.dataset.итог ? кнЗакрыть.click() : спросить()));

    Promise.all([import(`./песочница/${живая.игра}.js`), import('./песочница/общее.js')])
      .then(([м, общее]) => {
        if (кончено) return null;
        модуль = м;
        общее.звук.громкость = ГРОМКОСТЬ_ПЕСОЧНИЦЫ * множительЗвуков(уровень);
        return м.запустить(поле, { ...живая.вход, навык: живая.навык ?? 0, тихо, сигнал: сигнал.signal });
      })
      .then(р => { if (р && !кончено) показатьИтог(р); })
      .catch(e => {
        if (e?.name === 'AbortError' || кончено) return;
        console.error(e);
        // Игра не загрузилась — занятие не теряется: окно закрывается без исхода, ход остаётся на месте.
        поле.innerHTML = `<p class="живая-ошибка">Игра не запустилась: ${экр(e?.message || e)}</p>`;
        модуль = null;
        кнЗакрыть.innerHTML = 'Закрыть <small>Esc</small>';
      });

    function показатьИтог(р) {
      const итог = { уровень: р.уровень, очки: р.очки };
      слой.innerHTML = `<div class="живая-панель живая-итог"><div class="живая-слово" data-у="${экр(р.уровень)}">${экр(СЛОВО[р.уровень] ?? р.уровень)}</div>
        ${модуль?.СМЫСЛ?.[р.уровень] ? `<p>${экр(модуль.СМЫСЛ[р.уровень])}</p>` : ''}
        <div class="живая-кнопки"><button class="b sin" data-д="дальше">Дальше</button></div></div>`;
      слой.hidden = false;
      кнЗакрыть.dataset.итог = '1';
      кнЗакрыть.innerHTML = 'Дальше <small>Esc</small>';
      кнЗакрыть.onclick = () => выйти(итог);
      слой.querySelector('[data-д="дальше"]').onclick = () => выйти(итог);
      слой.querySelector('[data-д="дальше"]').focus({ preventScroll: true });
    }
  });
}

// Ход с полем живая: открыть игру, по итогу выполнить ход и перерисовать; отказ — ничего не меняется.
