// «Свой угол» (шаг 9 плана): договор на каморку у вдовы, взносы, просрочка, расторжение, возврат вещей.
// Чистая логика без DOM. Состояние живёт в S.мир.угол и создаётся лениво (миграция версии не нужна).
// Правила: Документы/Разработка/Шаг_01_История_и_правила/Четыре_цели_первого_сезона.md, карточка «Свой угол».
import { ДОГОВОР, ДЕНЬ_ФИНАЛА, ВЕСЬ_ДОГОВОР, платёжПриПодписи, числа } from '../Данные/цели.js';
import { взятьОбязательство, закрытьОбязательство } from './сроки.js';
import { привестиВещи, свободных, размер, имяВещи } from './вещи.js';

const новый = () => ({
  услышал: false, осмотрена: false, статус: 'нет', // нет | действует | расторгнут
  подписан: null, взносы: {}, // { 7: 'ждёт' | 'включён' | 'оплачен' | 'долг' }
  долг: 0, долгВзносов: [], сборов: 0, выплачен: false, расторгнут: null, // { день, причина: 'просрочка' | 'отказ' }
});

export function угол(S) {
  const у = (S.мир.угол ??= новый());
  for (const [ключ, значение] of Object.entries(новый())) у[ключ] ??= значение;
  return у;
}

const читатьУгол = S => S.мир.угол ?? новый();
const журнал = (S, с) => { S.мир.журналДня.push(с); return с; };
export const договорДействует = S => S.мир.угол?.статус === 'действует';
const ОПЛАЧЕН = ['оплачен', 'включён'];

// Ближайший ещё не оплаченный и не просроченный взнос.
const ближайшийВзнос = S => ДОГОВОР.сроки.find(d => читатьУгол(S).взносы[d] === 'ждёт') ?? null;

// Что можно заплатить сейчас: старый долг (всегда первым) и ближайший взнос, если срок близко.
export function платёж(S) {
  const у = читатьУгол(S);
  const d = у.статус === 'действует' ? ближайшийВзнос(S) : null;
  const доступен = d !== null && d - S.мир.день <= ДОГОВОР.заранеЗа;
  return { долг: у.долг, взнос: доступен ? { день: d, сумма: ДОГОВОР.взнос } : null };
}

export function зачётУгла(S) {
 const ж=S.герой.жильё;
 if(ж?.id!=='вдова'||читатьУгол(S).статус!=='нет')return 0;
 return Math.min(25, Math.floor(25*Math.min(7,Math.max(0,ж.оплачено_по-S.мир.день+1))/7));
}

export function стоимостьУгла(S, вид) {
  const п = платёж(S);
  if (вид === 'подписать') return Math.max(0,(платёжПриПодписи(S.мир.день)?.сейчас ?? 0)-зачётУгла(S));
  if (вид === 'платёж-долг') return п.долг;
  if (вид === 'платёж-всё') return п.долг + (п.взнос?.сумма ?? 0);
  if (вид === 'платёж-взнос') return п.взнос?.сумма ?? 0;
  return 0;
}

// Подпись под кнопкой: игрок видит всю сумму дня до подтверждения.
export function подписьУгла(S, вид) {
  const п = платёж(S), у = читатьУгол(S);
  if (вид === 'подписать') {
    const ц = платёжПриПодписи(S.мир.день);
    if (!ц) return '';
    const далее = ДОГОВОР.сроки.filter(d => d > S.мир.день && !ц.включено.includes(d));
    return `${ц.сейчас - зачётУгла(S)} гр.` + (зачётУгла(S) ? ` (из ${ц.сейчас}: зачтено ${зачётУгла(S)} за непрожитые ночи)` : '') + (ц.доКонцаДня ? ` и до конца дня ещё ${ц.доКонцаДня} (всего ${ц.всего})` : '')
      + (далее.length ? `; далее по ${ДОГОВОР.взнос}: дни ${далее.join(', ')}` : '');
  }
  if (вид === 'платёж-долг') return `долг ${п.долг} гр.`;
  if (вид === 'платёж-всё') return `долг ${п.долг} + взнос ${п.взнос?.сумма ?? 0} (день ${п.взнос?.день})`;
  if (вид === 'платёж-взнос') return `взнос за день ${п.взнос?.день}${п.взнос && п.взнос.день > S.мир.день ? ', заранее' : ''}`;
  if (вид === 'расторгнуть') return 'внесённое не вернётся' + (у.долг ? `, долг ${у.долг} гр. останется` : '');
  return '';
}

export function условиеУгла(S, имя) {
  const у = читатьУгол(S), п = платёж(S);
  const отрезок=S.сцена?.отрезок??S.мир.отрезок;
  if(['услышать','подписать','позднее','платёж-долг','платёж-всё','платёж-взнос','расторгнуть'].includes(имя)&&!['утро','вечер'].includes(отрезок))return false;
  switch (имя) {
    case 'услышать': return у.статус === 'нет' && !у.услышал;
    case 'слышал': return у.услышал || у.статус !== 'нет';
    case 'осмотреть': return у.статус === 'нет' && у.услышал && !у.осмотрена;
    case 'подписать': return у.статус === 'нет' && у.услышал && платёжПриПодписи(S.мир.день) !== null;
    case 'позднее': return у.статус === 'нет' && у.услышал && S.мир.день > ДОГОВОР.последняяПодпись;
    case 'платёж-долг': return у.долг > 0;
    case 'платёж-всё': return у.статус === 'действует' && у.долг > 0 && !!п.взнос;
    case 'платёж-взнос': return у.статус === 'действует' && у.долг === 0 && !!п.взнос;
    case 'расторгнуть': return у.статус === 'действует';
    default: return false;
  }
}

function напомнитьВзнос(S) {
  const d = ближайшийВзнос(S);
  if (d === null) return;
  взятьОбязательство(S, { id: `угол_взнос_${d}`, название: `Взнос за комнату: ${ДОГОВОР.взнос} гр.`, срок: { день: d, отрезок: 'ночь', граница: 'конец' } });
}

function обновитьВыплачен(S) {
  const у = читатьУгол(S);
  у.выплачен = у.статус === 'действует' && у.долг === 0 && ДОГОВОР.сроки.every(d => ОПЛАЧЕН.includes(у.взносы[d]));
  if (у.выплачен) журнал(S, 'Свой угол: договор выплачен полностью, комната за тобой');
}

// Деньги за действие списывает вызывающий (сцена места списывает «стоит»); здесь только последствия.
export function выполнитьДействиеУгла(S, вид) {
  if(вид==='услышал'&&!условиеУгла(S,'услышать'))return false;
  if(!['услышал','осмотр'].includes(вид)&&!условиеУгла(S,вид))return false;
  const у = угол(S);
  if (вид === 'услышал' && !условиеУгла(S,'услышать')) return false;
  if (вид === 'услышал') { if (!у.услышал) { у.услышал = true; журнал(S, 'Свободная каморка у вдовы: договор у вдовы'); } return true; }
  if (вид === 'осмотр') { у.услышал = true; у.осмотрена = true; return true; }
  if (!условиеУгла(S, вид)) return false;
  if (вид === 'подписать') return подписать(S);
  if (вид === 'платёж-долг' || вид === 'платёж-всё' || вид === 'платёж-взнос') return принятьПлатёж(S, вид);
  if (вид === 'расторгнуть') { расторгнуть(S, 'отказ'); return true; }
  return false;
}

function подписать(S) {
  const у = читатьУгол(S), ц = платёжПриПодписи(S.мир.день);
  if (!ц || у.статус !== 'нет') return false;
  у.зачёт = зачётУгла(S);
  у.статус = 'действует';
  у.подписан = S.мир.день;
  у.услышал = true;
  for (const d of ДОГОВОР.сроки) у.взносы[d] = ц.включено.includes(d) ? 'включён' : 'ждёт';
  S.герой.хранилище ??= {};
  if(S.герой.хранилище.вдова?.length){ (S.герой.хранилище.угол ??= []).push(...S.герой.хранилище.вдова); S.герой.хранилище.вдова=[]; }
  S.герой.жильё = { id: 'угол', договор: true };
  журнал(S, `Свой угол: договор подписан, внесено ${ц.сейчас-у.зачёт} гр. наличными${у.зачёт ? `, зачтено ${у.зачёт} за непрожитые ночи` : ''}.`);
  напомнитьВзнос(S);
  return true;
}

function принятьПлатёж(S, вид) {
  const у = читатьУгол(S), п = платёж(S);
  if (вид !== 'платёж-взнос' && п.долг > 0) {
    for (const d of у.долгВзносов) { у.взносы[d] = 'оплачен'; закрытьОбязательство(S, `угол_долг_${d}`); }
    журнал(S, `Свой угол: долг ${п.долг} гр. закрыт`);
    у.долг = 0; у.долгВзносов = [];
  }
  if (вид !== 'платёж-долг' && п.взнос) {
    у.взносы[п.взнос.день] = 'оплачен';
    закрытьОбязательство(S, `угол_взнос_${п.взнос.день}`);
    журнал(S, `Свой угол: взнос за день ${п.взнос.день} внесён`);
    напомнитьВзнос(S);
  }
  обновитьВыплачен(S);
  return true;
}

// Одвин забирает вещи из сундука. Что не влезает в карманы, ждёт у Орша — молча ничего не исчезает.
function вернутьВещи(S) {
  привестиВещи(S);
  const сундук = S.герой.хранилище.угол ?? [];
  let взято = 0, ждут = 0;
  for (const x of [...сундук]) {
    сундук.splice(сундук.indexOf(x), 1);
    if (свободных(S) >= размер(x)) { S.герой.при_себе.push(x); взято++; }
    else { (S.герой.возвратУгла ??= []).push(x); ждут++; }
  }
  return { взято, ждут };
}

export function расторгнуть(S, причина, итог = null) {
  const у = читатьУгол(S);
  if (у.статус !== 'действует') return false;
  у.статус = 'расторгнут';
  у.выплачен = false;
  у.расторгнут = { день: S.мир.день, причина };
  if (S.герой.жильё?.id === 'угол') S.герой.жильё = null;
  for (const о of Object.values(S.мир.обязательства ?? {})) if (о.id.startsWith('угол_') && о.статус === 'активно') о.статус = 'отменено';
  const { взято, ждут } = вернутьВещи(S);
  const строки = [];
  строки.push(причина === 'просрочка'
    ? 'Свой угол: договор расторгнут за просрочку. Внесённое не возвращается.'
    : 'Свой угол: договор расторгнут по твоему слову. Внесённое не возвращается.');
  if (взято) строки.push(`Из сундука комнаты забрано вещей: ${взято}.`);
  if (ждут) строки.push(`Не влезло в карманы: ${ждут}. Эти вещи ждут у вдовы у вдовы — освободи место и забери.`);
  if (у.долг) строки.push(`За тобой остался долг по комнате: ${у.долг} гр. Его можно закрыть у вдовы.`);
  строки.push('Ночлег выбирай заново: каморки у вдовы у тебя больше нет.');
  for (const с of строки) (итог ? итог.причины : S.мир.журналДня).push(с);
  return true;
}

// Конец суток (вызывается из Движок/время.js до смены дня; S.мир.день — закрываемые сутки).
export function закрытьДеньУгла(S, итог) {
  const у = читатьУгол(S), день = S.мир.день, строки = итог.причины;
  if (у.статус !== 'действует') return;
  if (ДОГОВОР.сроки.includes(день) && у.взносы[день] === 'ждёт') {
    if (у.долг > 0) {
      // Второй подряд: старый долг и новый взнос не закрыты к концу дня.
      у.взносы[день] = 'долг'; у.долг += ДОГОВОР.взнос; у.долгВзносов.push(день);
      строки.push(`Свой угол: к концу дня ${день} не закрыты ни старый долг, ни новый взнос.`);
      расторгнуть(S, 'просрочка', итог);
      return;
    }
    у.взносы[день] = 'долг'; у.долг = ДОГОВОР.взнос + ДОГОВОР.сбор; у.долгВзносов = [день]; у.сборов += 1;
    const срок = ДОГОВОР.сроки.find(d => d > день) ?? ДЕНЬ_ФИНАЛА;
    строки.push(`Свой угол: взнос за день ${день} не внесён. Долг ${у.долг} гр. (взнос ${ДОГОВОР.взнос} и сбор ${ДОГОВОР.сбор}). Закрыть его нужно до конца дня ${срок}.`
      + (срок !== ДЕНЬ_ФИНАЛА ? ` В тот день придёт и новый взнос: понадобится ${у.долг + ДОГОВОР.взнос} гр., иначе договор расторгнут.` : ''));
    взятьОбязательство(S, { id: `угол_долг_${день}`, название: `Долг за комнату: ${у.долг} гр.`, срок: { день: срок, отрезок: 'ночь', граница: 'конец' } });
  } else if (день === ДЕНЬ_ФИНАЛА && (у.долг > 0 || ДОГОВОР.сроки.some(d => у.взносы[d] === 'ждёт'))) {
    for (const d of ДОГОВОР.сроки) if (у.взносы[d] === 'ждёт') { у.взносы[d] = 'долг'; у.долг += ДОГОВОР.взнос; у.долгВзносов.push(d); }
    строки.push(`Свой угол: к концу дня ${ДЕНЬ_ФИНАЛА} долг ${у.долг} гр. не закрыт.`);
    расторгнуть(S, 'просрочка', итог);
    return;
  }
  // Предупреждение накануне срока.
  const завтра = ДОГОВОР.сроки.find(d => d === день + 1 && у.взносы[d] === 'ждёт');
  if (завтра !== undefined) {
    строки.push(у.долг > 0
      ? `Свой угол: завтра срок. К концу дня нужно ${у.долг + ДОГОВОР.взнос} гр. (долг ${у.долг} и взнос ${ДОГОВОР.взнос}), иначе договор будет расторгнут. Дом вдовы открыт утром и вечером.`
      : `Свой угол: завтра срок взноса, ${ДОГОВОР.взнос} гр. Меняльная открыта утром и днём.`);
  } else if (у.долг > 0 && день === ДЕНЬ_ФИНАЛА - 1) {
    строки.push(`Свой угол: завтра последний день, чтобы закрыть долг ${у.долг} гр. Иначе договор будет расторгнут.`);
  }
  обновитьВыплачен(S);
}

// ── Возврат вещей, не поместившихся в карманы ──────────────────────────────────
export function забратьИзУгла(S, uid) {
  const список = S.герой.возвратУгла ?? [], x = список.find(y => y.uid === uid);
  if (!x || S.мир.район !== 'жилые-улицы' || S.сцена || S.мир.конецДня || свободных(S) < размер(x)) return false;
  список.splice(список.indexOf(x), 1);
  привестиВещи(S).push(x);
  журнал(S, `${имяВещи(x)}: возвращено из комнаты`);
  return true;
}

export function действияУгла(S) {
  return (S.герой.возвратУгла ?? []).map(x => ({
    id: `угол-вещь:${x.uid}`, uid: x.uid, текст: 'Забрать у вдовы',
    можно: S.мир.район === 'жилые-улицы' && !S.сцена && свободных(S) >= размер(x),
    почему: S.мир.район !== 'жилые-улицы' ? 'вещи ждут у вдовы, Жилые улицы' : 'некуда положить',
    выполнить: S2 => забратьИзУгла(S2, x.uid),
  }));
}

// ── Журнал: сводка и следующий шаг ────────────────────────────────────────────
const взносовОплачено = у => ДОГОВОР.сроки.filter(d => ОПЛАЧЕН.includes(у.взносы[d])).length;
const займУОрша = S => S.мир.места?.меняльная?.долг ?? 0;

export function сводкаУгла(S) {
  const у = читатьУгол(S), строки = [];
  if (у.статус === 'нет') {
    if (у.услышал) {
      const ц = платёжПриПодписи(S.мир.день);
      строки.push(ц ? `Свободная каморка у вдовы. Договор: ${подписьУгла(S, 'подписать')}. Весь договор — ${ВЕСЬ_ДОГОВОР} гр.`
        : 'Договор на комнату больше не заключается: подписать его можно было до конца 14-го дня.');
    }
  } else if (у.статус === 'действует') {
    const внесено = ДОГОВОР.задаток + ДОГОВОР.взнос * взносовОплачено(у);
    строки.push(`Договор действует с дня ${у.подписан}. Внесено ${внесено} из ${ВЕСЬ_ДОГОВОР} гр.`);
    if (у.долг) строки.push(`Долг по комнате: ${у.долг} гр.`);
    const d = ближайшийВзнос(S);
    if (d !== null) строки.push(`Ближайший взнос: ${ДОГОВОР.взнос} гр. до конца дня ${d}.`);
    if (у.выплачен) строки.push('Договор выплачен полностью.');
  } else {
    строки.push(`Договор расторгнут в день ${у.расторгнут.день} (${у.расторгнут.причина === 'отказ' ? 'по твоему слову' : 'за просрочку'}).`);
    if (у.долг) строки.push(`Остался долг по комнате: ${у.долг} гр.`);
  }
  if (займУОрша(S) > 0) строки.push(`Заём у Орша: вернуть ${займУОрша(S)} гр.`);
  return строки;
}

export function следующийШагУгла(S) {
  const у = читатьУгол(S), день = S.мир.день;
  if (у.статус === 'нет') {
    if (!у.услышал) return день <= ДОГОВОР.последняяПодпись
      ? 'Узнай о свободной комнате: доска объявлений у вдовы (Жилые улицы, утро или вечер).'
      : 'Договор на комнату уже не заключается. Остаются аренда у вдовы и другие дороги.';
    if (день > ДОГОВОР.последняяПодпись) return 'Подписать договор уже нельзя. Остаются аренда у вдовы и другие дороги.';
    if (!у.осмотрена) return 'Осмотри каморку у вдовы — это бесплатно. Договор можно подписать до конца 14-го дня.';
    const ц = платёжПриПодписи(день);
    return `Подписать договор у вдовы: ${стоимостьУгла(S, 'подписать')} гр. сейчас${ц.доКонцаДня ? `, ещё ${ц.доКонцаДня} до конца дня` : ''}. Последний день подписи — 14-й.`;
  }
  if (у.статус === 'действует') {
    const п = платёж(S);
    if (у.долг > 0) {
      const d = ближайшийВзнос(S);
      const срок = ДОГОВОР.сроки.find(x => x >= день && у.взносы[x] === 'ждёт') ?? ДЕНЬ_ФИНАЛА;
      return `Закрой долг ${у.долг} гр. у вдовы до конца дня ${d === null ? ДЕНЬ_ФИНАЛА : срок}.`
        + (d !== null ? ` В тот день придёт и взнос ${ДОГОВОР.взнос} гр.: всего ${у.долг + ДОГОВОР.взнос}.` : '');
    }
    const d = ближайшийВзнос(S);
    if (d === null) return 'Договор выплачен. Комната за тобой: можно жить дальше.';
    return п.взнос
      ? `Внеси взнос ${ДОГОВОР.взнос} гр. за день ${d}: дом вдовы открыт утром и вечером.`
      : `Ближайший взнос — ${ДОГОВОР.взнос} гр. до конца дня ${d}. Внести его можно за ${числа(ДОГОВОР.заранеЗа, ['день', 'дня', 'дней'])} до срока.`;
  }
  return у.долг > 0
    ? `Договор расторгнут. Остался долг ${у.долг} гр.: его можно закрыть у вдовы.`
    : 'Договор расторгнут. Ночлег выбирай заново; вещи у тебя.';
}

// ── Итог к 30-му дню ─────────────────────────────────────────────────────────
// Исход: без-долга | ценой-обязательства | аренда | потерял | расторг-сам | не-подписал | не-начал
export function исходУгла(S) {
  const у = читатьУгол(S), заём = займУОрша(S), вдова = S.мир.ночи?.вдова ?? 0;
  if (у.статус === 'действует') return у.долг > 0 || заём > 0 ? 'ценой-обязательства' : 'без-долга';
  if (у.статус === 'расторгнут') return у.расторгнут.причина === 'отказ' ? 'расторг-сам' : 'потерял';
  if (вдова >= 7) return 'аренда';
  return у.осмотрена || у.услышал ? 'не-подписал' : 'не-начал';
}

export function деталиУгла(S) {
  const у = читатьУгол(S), заём = займУОрша(S), строки = [];
  if (у.статус === 'действует') {
    строки.push(`Договор: внесено ${ДОГОВОР.задаток + ДОГОВОР.взнос * взносовОплачено(у)} из ${ВЕСЬ_ДОГОВОР} гр.${у.сборов ? ` Сборов за просрочку: ${у.сборов}.` : ''}`);
    if (у.долг) строки.push(`Долг по договору: ${у.долг} гр.`);
  } else if (у.статус === 'расторгнут') {
    строки.push(`Договор расторгнут в день ${у.расторгнут.день}. Вещи Одвин забрал.`);
    if (у.долг) строки.push(`Долг по договору: ${у.долг} гр.`);
  }
  if (заём) строки.push(`Заём у Орша: ${заём} гр.`);
  return строки;
}
