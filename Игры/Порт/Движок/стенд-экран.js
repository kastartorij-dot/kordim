// Страница стенда мини-игр (DOM). Логика — Движок/стенд-игр.js. Экраны игр — те же, что в самой игре:
// рендерСмены («Вес», «Счёт») и рендерМесто («Торг», «Кости»), стили — Движок/интерфейс.css.
import { изолироватьХранилище, игры, откуда, варианты, ступени, ремесло, запустить, идёт, снимок, исход } from './стенд-игр.js';

// Сначала подменяем хранилище, и только потом грузим экраны игры: так стенд не читает громкость игрока
// и ничего не пишет в её localStorage, даже если какой-то экран полезет за настройкой.
const изоляция = изолироватьХранилище(window);
const { применитьНастройки } = await import('./настройки-интерфейса.js');
const { рендерСмены } = await import('./экраны.js');
const { рендерМесто } = await import('./экраны-места.js');
применитьНастройки();

const $ = id => document.getElementById(id);
const экр = т => String(т ?? '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

const П = { игра: null, вариант: null, ступень: 'умеешь', S: null, до: null, кончено: false, сид: null };
const запрос = new URLSearchParams(location.search);
if (запрос.get('сид')) П.сид = Number(запрос.get('сид')) >>> 0;

function ошибкаСтарта(е) {
  $('стенд-исход').hidden = true;
  $('экран').classList.remove('в-месте');
  $('экран').innerHTML = `<div class="смена-экран"><section class="смена-карточка"><div class="надзаголовок">Стенд</div><h1>Не запустилось</h1><p class="смена-текст">${экр(е.message ?? е)}</p></section></div>`;
}

// ── список игр ───────────────────────────────────────────────────────────
function рисоватьСписок() {
  const список = $('стенд-список');
  список.innerHTML = игры().map(и => `
    <button class="стенд-игра" type="button" data-id="${экр(и.id)}" aria-pressed="${и === П.игра}">
      <span class="имя">${экр(и.имя)}</span>
      <span class="где">${экр(и.где)}</span>
      <span class="опис">${экр(и.описание)}</span>
    </button>`).join('');
  список.querySelectorAll('.стенд-игра').forEach(б => {
    б.onclick = () => выбратьИгру(б.dataset.id);
  });
}
// Стрелки ↑ ↓ (и ← →) переходят по списку, Enter запускает — обычные кнопки это и так умеют, стрелки быстрее.
$('стенд-список').addEventListener('keydown', e => {
  const шаг = { ArrowDown: 1, ArrowRight: 1, ArrowUp: -1, ArrowLeft: -1 }[e.key];
  if (!шаг) return;
  const кнопки = [...$('стенд-список').querySelectorAll('.стенд-игра')], i = кнопки.indexOf(document.activeElement);
  if (i < 0) return;
  e.preventDefault();
  кнопки[(i + шаг + кнопки.length) % кнопки.length].focus();
});

// ── параметры партии ─────────────────────────────────────────────────────
function рисоватьУправление() {
  const ув = $('стенд-упр'), и = П.игра, в = варианты(и), рем = ремесло(и, П.вариант), ст = рем ? ступени(и) : [];
  ув.hidden = false;
  ув.innerHTML = `
    <p class="стенд-инфо"><b>${экр(и.имя)}</b> · ${экр(и.где)}<br>${экр(и.описание)}</p>
    <div class="стенд-кнопки">
      <button class="b sin" type="button" id="стенд-заново">Начать заново</button>
      ${в.length > 1 ? `<button class="b" type="button" id="стенд-другое">${экр(и.подписьДругого ?? 'Другой вариант')}</button>` : ''}
    </div>
    ${в.length > 1 ? `
    <div class="стенд-поле">
      <label for="стенд-вариант">${экр(и.подписьВарианта ?? 'Вариант')}</label>
      <select id="стенд-вариант">${в.map(x => `<option value="${экр(x.id)}"${x.id === П.вариант ? ' selected' : ''}>${экр(x.имя)}</option>`).join('')}</select>
    </div>` : ''}
    ${ст.length ? `
    <div class="стенд-поле" role="group" aria-labelledby="стенд-ступень-подпись">
      <span id="стенд-ступень-подпись">Ремесло «${экр(рем)}»</span>
      <div class="стенд-ступени">${ст.map(с => `<button class="b" type="button" data-ступень="${экр(с)}" aria-pressed="${с === П.ступень}">${экр(с)}</button>`).join('')}</div>
    </div>` : ''}`;
  $('стенд-заново').onclick = старт;
  if ($('стенд-вариант')) {
    $('стенд-вариант').onchange = e => { П.вариант = e.target.value; старт(); $('стенд-вариант').focus(); };
    $('стенд-другое').onclick = () => { const i = в.findIndex(x => x.id === П.вариант); П.вариант = в[(i + 1) % в.length].id; старт(); $('стенд-другое').focus(); };
  }
  ув.querySelectorAll('[data-ступень]').forEach(б => { б.onclick = () => { П.ступень = б.dataset.ступень; старт(); document.querySelector(`[data-ступень="${П.ступень}"]`)?.focus(); }; });
}

// ── запуск и ход игры ────────────────────────────────────────────────────
function выбратьИгру(id) {
  const и = игры().find(x => x.id === id);
  if (!и) return;
  П.игра = и;
  П.вариант = варианты(и)[0]?.id ?? null;
  if (!ступени(и).includes(П.ступень)) П.ступень = ступени(и).includes('умеешь') ? 'умеешь' : ступени(и)[0] ?? 'умеешь';
  рисоватьСписок();
  старт();
  $('стенд-список').querySelector('[aria-pressed="true"]')?.focus({ preventScroll: true });
}

function старт() {
  const и = П.игра;
  рисоватьСписок();
  рисоватьУправление();
  $('стенд-исход').hidden = true;
  $('стенд-исход').innerHTML = '';
  П.кончено = false;
  try {
    П.S = запустить(и, { вариант: П.вариант ?? undefined, ступень: П.ступень, ...(П.сид !== null ? { сид: П.сид } : {}) });
  } catch (е) { ошибкаСтарта(е); return; }
  П.до = снимок(П.S);
  обновитьАдрес();
  рисовать(П.S);
  $('экран').scrollTop = 0;
}

function обновитьАдрес() {
  const п = new URLSearchParams();
  п.set('игра', П.игра.id);
  if (П.вариант) п.set('вариант', П.вариант);
  п.set('ступень', П.ступень);
  if (П.сид !== null) п.set('сид', String(П.сид));
  history.replaceState(null, '', location.pathname + '?' + п);
}

// Каждый клик игры приходит сюда: конец партии замечаем здесь и записываем исход один раз.
function рисовать(состояние) {
  if (состояние) П.S = состояние;
  const S = П.S, экран = $('экран');
  if (!П.кончено && !идёт(П.игра, S)) закончить();
  // В месте после партии можно начать ещё одну (скажем, торг за другой товар): это новый исход.
  else if (П.кончено && идёт(П.игра, S)) { П.кончено = false; П.до = снимок(S); $('стенд-исход').hidden = true; }
  экран.classList.toggle('в-месте', !!S.сцена && !S.мир.смена);
  if (S.мир.смена) рендерСмены(S, рисовать);
  else if (S.сцена) рендерМесто(S, рисовать);
  else рисоватьПустое();
  // на телефоне исход лежит ниже игры: когда экран уже перерисован, прокручиваем к нему
  if (П.показатьИсход) {
    П.показатьИсход = false;
    $('стенд-исход').scrollIntoView({ block: 'end', behavior: matchMedia('(prefers-reduced-motion: reduce)').matches ? 'auto' : 'smooth' });
  }
}

function рисоватьПустое() {
  $('экран').innerHTML = `<div class="смена-экран"><section class="смена-карточка"><div class="надзаголовок">Стенд</div><h1>Партия сыграна</h1>
    <p class="смена-текст">Дальше в игре идёт обычный день, а стенд на этом кончается. Что получил герой — ниже.</p>
    <div class="смена-кнопки"><button class="b" type="button" id="стенд-пусто-заново">Начать заново</button></div></section></div>`;
  $('стенд-пусто-заново').onclick = старт;
}

function закончить() {
  П.кончено = true;
  const строки = исход(П.до, снимок(П.S));
  const основные = строки.filter(р => !['журнал', 'время'].includes(р.вид)), служебные = строки.filter(р => ['журнал', 'время'].includes(р.вид));
  const ов = $('стенд-исход');
  ов.hidden = false;
  ов.innerHTML = `
    <header class="исход-шапка"><h2>Что получил герой</h2><button class="b" type="button" id="стенд-исход-заново">Сыграть ещё раз</button></header>
    ${основные.length ? `<ul class="исход-список">${основные.map(р => `<li class="${р.знак}">${экр(р.текст)}</li>`).join('')}</ul>` : '<p class="подсказка">Игра сама ничего не изменила: ни денег, ни расположения, ни тем.</p>'}
    ${служебные.length ? `<ul class="исход-список служебное">${служебные.map(р => `<li>${экр(р.текст)}</li>`).join('')}</ul>` : ''}`;
  $('стенд-исход-заново').onclick = старт;
  П.показатьИсход = true;
}

// ── звук: по умолчанию выключен, включается только на этой странице ──────────
$('стенд-звук').onchange = e => изоляция.звук(e.target.checked);

// ── начало ───────────────────────────────────────────────────────────────
рисоватьСписок();
{
  const список = игры();
  const нужная = список.find(и => и.id === запрос.get('игра')) ?? список[0];
  if (!нужная) ошибкаСтарта(new Error('В стенде нет ни одной игры (' + откуда() + ').'));
  else {
    П.игра = нужная;
    const в = варианты(нужная);
    П.вариант = в.find(x => x.id === запрос.get('вариант'))?.id ?? в[0]?.id ?? null;
    const ст = запрос.get('ступень');
    if (ст) П.ступень = ст;
    if (!ступени(нужная).includes(П.ступень)) П.ступень = ступени(нужная).includes('умеешь') ? 'умеешь' : ступени(нужная)[0] ?? 'умеешь';
    старт();
  }
}
document.documentElement.dataset.стенд = откуда();
