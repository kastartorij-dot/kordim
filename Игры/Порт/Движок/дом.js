// Свой оплаченный ночлег (PR005-01): комната у вдовы на оплаченные ночи или «Свой угол» по договору.
// Ночью дорога в его район — это дорога домой и сон, а не ночь на ногах; «пойти домой» из места ведёт туда же.
import { ЖИЛЬЁ } from '../Данные/жильё.js';
import { РАЙОНЫ } from '../Данные/районы.js';
import { договорДействует } from './угол.js';
import { лечьСпать, отрезковНа } from './время.js';

export function свойНочлег(S) {
  const ж = S.герой.жильё;
  if (договорДействует(S)) return ЖИЛЬЁ.find(x => x.id === 'угол') ?? null;
  if (ж && ж.оплачено_по >= S.мир.день) return ЖИЛЬЁ.find(x => x.id === ж.id && x.ночей) ?? null;
  return null;
}

export const районДома = ж => ж?.где?.[0] ?? null;
const имяРайона = id => РАЙОНЫ.find(р => р.id === id)?.имя ?? id;

// Дорога съест ночь: ночью — всегда, вечером — когда герой валится с ног и любой шаг стоит два отрезка
// (Инженер, круг 2: уставший вечером не доходил до оплаченной комнаты и терял сон).
export const дорогаСъестНочь = S => S.мир.отрезок === 'ночь' || (S.мир.отрезок === 'вечер' && отрезковНа(S) >= 2);

// Подпись «домой» для кнопок: куда и что будет, коротко — на узком окне длинная подпись обрезается.
const ГДЕ = { вдова: 'у вдовы', угол: 'в своём углу' };
export function подписьДомой(S) {
  const ж = свойНочлег(S);
  if (!ж) return '';
  const где = ГДЕ[ж.id] ?? ж.имя.toLowerCase();
  return дорогаСъестНочь(S) ? `домой, сон ${где}` : `ночлег ${где} — к ночи`;
}

// Дойти до своего ночлега и лечь, если дорога всё равно съест ночь. Возвращает строку журнала или null.
export function идтиДомой(S) {
  const ж = свойНочлег(S);
  if (!ж || !дорогаСъестНочь(S) || S.мир.конецДня || S.мир.кампанияЗавершена) return null;
  const район = районДома(ж);
  const строка = район && район !== S.мир.район ? `${S.мир.отрезок === 'ночь' ? 'Ночью' : 'Без сил'} домой, в ${имяРайона(район)}` : null;
  if (строка) { S.мир.журналДня.push(строка); S.мир.район = район; }
  лечьСпать(S, ж);
  return строка ?? ж.имя;
}
