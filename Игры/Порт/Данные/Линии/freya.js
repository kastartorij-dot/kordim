// Фрея там днём, пока действует обещание «прийти днём», и до конца того дня, когда оно сдержано.
export function фреяНаРынке(S) {
  const с = S.мир.связи?.freya;
  if (!с) return false;
  if ((S.сцена?.отрезок ?? S.мир.отрезок) !== 'день') return false;
  const о = с.обещания.find(x => x.ид === 'фрея-рынок');
  if (!о) return false;
  if (о.статус === 'дано') return true;
  return о.статус === 'сдержано' && с.поступки.some(п => п.ид.startsWith('фрея-рынок') && п.день === S.мир.день);
}

