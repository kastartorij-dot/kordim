// Подключение личных линий шага 11 к местам: ветки в «Синем часе», встреча вне работы и жизнь после решения.
// Вызывается в конце Данные/Диалоги/подключение.js, когда графы жителей уже разложены по местам.
import { условиеВытащить } from '../../Движок/вытащить.js';
import { условиеСвязи } from '../../Движок/связи.js';
import { ВЕТКИ as ТАВА, ДЕЙСТВИЕ_ВОРОТ as ТАВА_ВОРОТА } from './tava.js';
import { ВЕТКИ_ДОМА as НИЯ_ДОМ, ГРАФ_РЫНКА as НИЯ_РЫНОК, нияНаРынке } from './niya.js';
import { ВЕТКИ_ДОМА as ФРЕЯ_ДОМ, ГРАФ_РЫНКА as ФРЕЯ_РЫНОК, ВЕТКИ_ВДОВЫ as ФРЕЯ_ВДОВА, фреяНаРынке } from './freya.js';

function добавитьВетки(г, ветки) {
  if (!г || г.линияПодключена) return;
  Object.assign(г.ветки, ветки);
  for (const id of Object.keys(ветки)) if (!г.хаб.includes(id)) г.хаб.push(id);
  г.линияПодключена = true;
}

export function подключитьЛинии(места) {
  const найти = id => места.find(м => м.id === id)?.модуль;
  const дом = найти('синий-час'), рынок = найти('рынок'), вдова = найти('дом-вдовы');

  добавитьВетки(дом?.ДИАЛОГИ?.freya, ФРЕЯ_ДОМ);
  // Площадка у окна: по цели «Вытащить» или когда Фрея уже встречалась с героем вне работы —
  // личное знакомство открывает разговор без оплаченной комнаты.
  const пл = дом?.КОМНАТЫ.ploshchadka;
  if (пл && !пл.линия) {
    const прежнее = пл.условие;
    пл.условие = S => (прежнее?.вытащить ? условиеВытащить(S, прежнее.вытащить) : true) || условиеСвязи(S, 'freya', { этапОт: 'вне-работы' });
    пл.линия = true;
  }
  if (рынок && дом && !рынок.ЛЮДИ.freya) {
    рынок.ЛЮДИ.freya = { ...дом.ЛЮДИ.freya, место: 'в ряду ветоши', условие: фреяНаРынке, вступление: ФРЕЯ_РЫНОК.вступление };
    рынок.КОМНАТЫ['ветошь-рынка'].люди.push('freya');
    (рынок.Р ??= {}).freya = { ni_o_chem: { любой: { т: '— Днём я за нитками. Это мой час.', э: {} } } };
    рынок.ДИАЛОГИ.freya = ФРЕЯ_РЫНОК;
  }
  добавитьВетки(вдова?.ДИАЛОГИ?.freya, ФРЕЯ_ВДОВА);

  добавитьВетки(дом?.ДИАЛОГИ?.niya, НИЯ_ДОМ);
  if (рынок && дом && !рынок.ЛЮДИ.niya) {
    рынок.ЛЮДИ.niya = { ...дом.ЛЮДИ.niya, место: 'у лотков с едой', условие: нияНаРынке, вступление: НИЯ_РЫНОК.вступление };
    рынок.КОМНАТЫ['еда-рынка'].люди.push('niya');
    (рынок.Р ??= {}).niya = { ni_o_chem: { любой: { т: '— Утро. Не работа.', э: {} } } };
    рынок.ДИАЛОГИ.niya = НИЯ_РЫНОК;
  }

  // Тава: вся линия — на её прилавке; улика о пропавшем ящике — у весов Браса. Сцены близости у неё нет (решение автора).
  добавитьВетки(рынок?.ДИАЛОГИ?.tava, ТАВА);
  const ворота = рынок?.КОМНАТЫ['ворота-рынка'];
  if (ворота && Array.isArray(ворота.действия) && !ворота.действия.includes(ТАВА_ВОРОТА)) ворота.действия.push(ТАВА_ВОРОТА);
}
