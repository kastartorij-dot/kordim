// Небольшие ролевые жители новых точек шага 8 используют их собственные реплики.
// Биографий и новых правил не добавляем; реальные услуги остаются в хабе.
function роль(д,id) {
 const ч=д.ЛЮДИ[id],р=д.Р?.[id]??{},ветки={};
 for(const [тема,тона]of Object.entries(р)){
  const ответ=тона.любой??тона.прямо??Object.values(тона)[0];if(!ответ?.т)continue;
  ветки[тема]={ярлык:тема==='ni_o_chem'?'О работе здесь':д.ТЕМЫ?.[тема]?.ярлык??тема.replaceAll('_',' '),первая:true,ходы:1,
   ...(тема==='ni_o_chem'?{}:{если:{тема},темаРазговора:тема}),
   уже:[typeof ответ.т==='string'?ответ.т:'— Если нужна услуга, договоримся об условиях.'],
   узлы:{старт:{текст:typeof ответ.т==='function'?S=>[].concat(ответ.т(S)):[ответ.т],при:ответ.э,
    варианты:[{ид:'ясно',текст:'Кивнуть.',дальше:'хаб'},{ид:'уйти',текст:'Отойти.',дальше:'закрыть',закреплён:true,исход:false}]}}};
 }
 if(!Object.keys(ветки).length)ветки.порядок={ярлык:'О работе здесь',первая:true,ходы:0,узлы:{старт:{текст:[ч.вступление??'— Расценки и условия оговариваем до работы.'],варианты:[{ид:'ясно',текст:'Кивнуть.',дальше:'хаб'}]}}};
 // Ответ «О работе здесь» у жителей кварталов взят из их вступления: тогда при встрече звучит не он, а рассказчик (иначе строка дважды подряд).
 const ответРаботы=ветки.порядок?ч.вступление:р.ni_o_chem&&(р.ni_o_chem.любой??р.ni_o_chem.прямо??Object.values(р.ni_o_chem)[0])?.т;
 const вступление=ч.вступление&&ч.вступление!==ответРаботы?ч.вступление:ч.имя+' отрывается от дела и ждёт вопроса.';
 return {человек:id,имя:ч.имя,вступление,снова:ч.имя+' кивает при встрече.',хаб:Object.keys(ветки),ветки};
}

export function подключитьЖителей(места) {
  дополнитьСостав(места);
  const найти = id => места.find(м=>м.id===id).модуль;
  const контора=найти('контора-дорров'), рынок=найти('рынок');
  контора.ЛЮДИ.весовщик={имя:'Доковый весовщик',место:'У доковых весов',любит:'прямо',портрет:''};
  контора.КОМНАТЫ['весовая-дорров'].люди.push('весовщик');
  if (!места.some(м=>м.id==='приемная-нотариуса')) {
  рынок.ЛЮДИ.notarius={имя:'Нотариус',место:'У ряда слухов',любит:'прямо',портрет:'',условие:{отрезок:'день'}};
  рынок.КОМНАТЫ['слухи-рынка'].люди.push('notarius');
  }
  for (const м of места) {
    const д=м.модуль;
    д.ДИАЛОГИ ??= {};
    for (const id of Object.keys(д.ЛЮДИ)) д.ДИАЛОГИ[id] = поМесту(ЖИТЕЛИ[id] ?? д.ДИАЛОГИ[id] ?? роль(д,id), м.id, id);
    const визит={ 'синий-час':['цветок_закрыт','свеча_оплачена','ола_монета','ола_цветок_закрыт','ния_хлеб','фрея_цветок_закрыт','повариха_миска','повариха_платно','ярна_цветок_закрыт'], 'таверна':['нора_спела','хозяин_смотритель_закрыт'], 'баня':['дана_ведро'], 'контора-дорров':['дорр_двое_закрыт'], 'двор-горма':['горм_бренн_закрыт'], 'лачуга-локи':['локи_занят'] }[м.id]??[];
    д.флагиВечера=[...new Set([...д.флагиВечера,...визит])];
    for (const [к,комната] of Object.entries(д.КОМНАТЫ)) {
      for (const а of Array.isArray(комната.действия)?комната.действия:[]) {
        if (typeof а.текст !== 'string') continue;
        if (а.текст.startsWith('Помочь развесить бельё')) а.эффект.флаг='помог_бранке';
        if (а.текст.startsWith('Помочь Миле')) а.эффект.флаг='помог_миле';
        if (а.текст==='Попросить Второй журнал') а.условие={...а.условие,безСвидетельства:'brenn_second_journal'};
      }
      for (const деталь of комната.детали??[]) if (деталь.свидетельство==='brenn_second_journal_seen') деталь.условие=S=>состояниеЖурнала(S)==='не_выдан';
    }
    for (const г of Object.values(д.ДИАЛОГИ)) {
      if (!ЖИТЕЛИ[г.человек]) continue;
      for (const [k,в] of Object.entries(г.ветки)) {
        if (k.startsWith('решение_')) {
          const решение=k.slice('решение_'.length);
          const ком={возвращён:'весовая-дорров',у_дорра:'кабинет-дорров',продан:места.some(м=>м.id==='приемная-нотариуса')?'перегородка':'слухи-рынка'}[решение];
          в.если=S=>естьВещь(S,'второй-журнал')&&['получен','оставлен'].includes(состояниеЖурнала(S))&&состояниеЖурнала(S)!==решение&&(!ком||S.сцена.комната===ком);
        }
        if (k.startsWith('реакция_')) { const состояние=k.slice('реакция_'.length); в.если=S=>состояниеЖурнала(S)===состояние&&S.мир.нитьБренна?.знают[г.человек]?.решение===состояние; }
      }
    }
  }
  // Шаг 12: созревшая мысль открывает одну ветку у своего человека (Данные/мысли.js, поле «реплика»); без мысли ветки не видно.
  for (const [id, мысль] of Object.entries(МЫСЛИ)) {
    const р = мысль.реплика, к = 'мысль_' + id;
    for (const м of р ? места : []) {
      const г = м.модуль.ДИАЛОГИ?.[р.кто];
      if (!г || г.ветки[к]) continue;
      г.ветки[к] = { ярлык: р.ярлык, реплика: р.ярлык, первая: true, ходы: 1, если: { мысль: id }, уже: ['— Об этом мы уже говорили.'],
        узлы: { старт: { текст: р.ответ, при: р.эффект, варианты: [{ ид: 'ясно', текст: 'Кивнуть.', дальше: 'хаб' }] } } };
      г.хаб.push(к);
    }
  }
  // Меняется содержание, а не только заголовок закрытой ветки.
  const у=ЖИТЕЛИ.una.ветки.книга;
  у.узлы.старт.текст=S=>{
    const с=состояниеЖурнала(S);
    if (с!=='не_выдан') return [с==='сожжён'?'— Книги больше нет. Решение принято при мне.':с==='получен'||с==='оставлен'?'— Книга у тебя. Носи осторожно.':'— Я передала книгу тебе. Что с ней стало, рассказывать или нет — решать тебе.'];
    if (S.мир.места.часовня?.флаги.includes('уна_доверяет')) return [(S.мир.свидетельства??[]).includes('brenn_second_journal_seen')?'— Запись сверена, журнал уже осмотрен. Можешь попросить его у меня.':'— Запись сверена. За занавесью частный журнал: рассмотри его, затем попроси книгу.'];
    const есть=(S.мир.свидетельства??[]).some(id=>['brenn_office_entry','brenn_hostel_book','brenn_healer_card'].includes(id));
    return [есть?'— У тебя есть запись, которую можно сверить. Покажи мне её, потом перейдём к журналу.':'— Бренн оставил книгу. Принеси запись из конторы, ночлежки или от лекаря. Сверим её, затем посмотришь журнал.'];
  };
  for (const а of у.узлы.старт.варианты) if (а.дальше!=='хаб') а.если={безСвидетельства:'brenn_second_journal'};
  у.если=S=>S.мир.нитьБренна?.знают.una?.решение!=='продан';
  // После известного обмена не просим принести уже отданную плату.
  const л=ЖИТЕЛИ.loki.ветки.огонь;
  л.засчитывать=false; delete л.уже;
  л.узлы.старт.текст=S=>S.мир.флаги.includes('правда_локи')?['— За правду об огне мы рассчитались. Тихую тропу я показал. Кто отдаёт приказ менять свет, я тебе из этого не назову.']:верностьТемы(S,'mayak_ogon')==='подтверждено'?['— Если можешь передать проверенную правду об огне, договоримся об обмене. Сама беседа ещё не передача.']:['— Про огонь много болтают. Проверь его сам и сопоставь записи. Кто велит менять свет, я не знаю.'];
  for (const н of Object.values(л.узлы)) for (const а of н.варианты) if (['хаб','закрыть'].includes(а.дальше)) а.исход=false;
  л.узлы.что_надо.текст=['— Сверь увиденное с записью на маяке. А потом выбери, хочешь ли передавать мне эту правду.'];
  // Память о выполненном обещании Олы не повторяет упрёк при каждом открытии.
  const о=ЖИТЕЛИ.ola.ветки.вход.узлы.старт;
  for (const т of о.текст) if (т?.если?.флаг==='тайна_ола_раскрыта') т.если.нетФакта='ола_реакция_на_тайну';
  о.при=[].concat(о.при??[],{если:{флаг:'тайна_ола_раскрыта',факт:'ола_слово'},э:{факт:'ола_реакция_на_тайну'}});
  подключитьЛинии(места);
}
