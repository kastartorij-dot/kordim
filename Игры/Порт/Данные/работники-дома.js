// Строки итога сезона: только о тех, кого герой спросил сам (ответ остался в памяти разговора).
export function итогиРаботников(S) {
  const строки = [];
  for (const [id, р] of Object.entries(РАБОТНИКИ_ДОМА)) {
    if (!р.итог) continue;
    if (S.мир.диалоги?.[id]?.факты?.includes('дом_ответ')) строки.push(р.итог);
  }
  return строки;
}
