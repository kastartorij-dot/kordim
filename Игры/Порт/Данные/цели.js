// Склонение: числа(3, ['смена','смены','смен']) → «3 смены».
export function числа(n, формы) {
  const a = Math.abs(n) % 100, b = a % 10;
  const f = a > 10 && a < 20 ? формы[2] : b === 1 ? формы[0] : b >= 2 && b <= 4 ? формы[1] : формы[2];
  return `${n} ${f}`;
}

