// «Свой угол»: 60 + 4 × 30 = 180 грошей. Ночлег и сундук после подписи входят в цену.
export const ДОГОВОР = {
  задаток: 60,
  взнос: 30,
  сбор: 10,            // один раз за первый пропуск действующего договора
  сроки: [7, 14, 21, 28],
  первыйДень: 3,       // договор предлагается с 3-го дня
  последняяПодпись: 14,
  заранеЗа: 3,         // взнос можно внести не раньше чем за три дня до срока (решение реализации)
};

// Что платится при подписи в данный день.
//  3–6:  60;  7: 60 при подписи + 30 до конца дня;  8–13: 90;  14: 120 (оба наступивших взноса сразу).
// Даты до подписи не считаются пропусками и не получают сбор.
export function платёжПриПодписи(день) {
  if (!Number.isInteger(день) || день < ДОГОВОР.первыйДень || день > ДОГОВОР.последняяПодпись) return null;
  const включено = ДОГОВОР.сроки.filter(d => d < день || (d === день && день === ДОГОВОР.последняяПодпись));
  const сейчас = ДОГОВОР.задаток + ДОГОВОР.взнос * включено.length;
  const доКонцаДня = ДОГОВОР.сроки.includes(день) && !включено.includes(день) ? ДОГОВОР.взнос : 0;
  return { сейчас, доКонцаДня, всего: сейчас + доКонцаДня, включено };
}

