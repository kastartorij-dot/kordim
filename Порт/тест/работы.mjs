// Проверка ядра действующего пакета работ: node Порт/тест/работы.mjs
// Сюжетные нити из ZIP других ИИ сюда намеренно не перенесены.
import assert from 'node:assert/strict';
import { новоеСостояние, мигрировать, ВЕРСИЯ } from '../движок/состояние.js';
import { доступныеДействия } from '../движок/действия.js';
import { работа, РАБОТЫ } from '../данные/работы.js';
import { условияПлаты, доступность, авто } from '../движок/смена.js';
import { добавитьОчки } from '../движок/положение.js';

const действие = (S, id) => доступныеДействия(S).find(а => а.id === id);

assert.equal(ВЕРСИЯ, 11);
assert.equal(РАБОТЫ.filter(р => р.открыто).length, 10);

// Работа открывает карточку; деньги и время идут только после выбора. Та же
// карточка должна восстановиться из сериализованного сохранения.
{
  const S = новоеСостояние('семья', 1);
  const р = работа('разгрузка');
  const колода = р.колода;
  const случай = колода.find(с => с.id === 'разгрузка_помочь');
  assert.ok(случай);
  р.колода = [случай];
  try {
    const начало = { день: S.мир.день, отрезок: S.мир.отрезок, кошель: S.герой.кошель, очки: S.мир.очки.ножи };
    assert.equal(действие(S, 'работа:разгрузка')?.можно, true);
    действие(S, 'работа:разгрузка').выполнить(S);
    assert.equal(S.мир.смена?.стадия, 'выбор');
    assert.equal(S.мир.день, начало.день);
    assert.equal(S.мир.отрезок, начало.отрезок);
    assert.equal(S.герой.кошель, начало.кошель);
    assert.ok(доступныеДействия(S).every(а => а.вид === 'смена'));

    const восстановлено = JSON.parse(JSON.stringify(S));
    assert.equal(восстановлено.мир.смена?.случай, случай.id);
    assert.equal(действие(восстановлено, 'смена:выбор:0')?.можно, true);
    действие(восстановлено, 'смена:выбор:0').выполнить(восстановлено);
    assert.equal(восстановлено.мир.смена?.стадия, 'итог');
    assert.equal(восстановлено.герой.кошель, начало.кошель + 12);
    assert.notEqual(восстановлено.мир.отрезок, начало.отрезок);
    assert.equal(восстановлено.мир.работы.разгрузка.смен, 1);
    assert.equal(восстановлено.мир.очки.ножи, начало.очки + 1);
    действие(восстановлено, 'смена:дальше').выполнить(восстановлено);
    assert.equal(восстановлено.мир.смена, null);
    assert.equal(действие(восстановлено, 'работа:разгрузка'), undefined);
  } finally {
    р.колода = колода;
  }
}

// Бот может закрыть обычную смену без DOM, а допуски и рыночная плата
// читаются из данных, не из текста кнопки.
{
  const S = новоеСостояние('семья', 17);
  assert.equal(доступность(S, работа('весы')).можно, false);
  S.мир.район = 'торговый';
  S.мир.отрезок = 'день';
  S.мир.день = 3;
  assert.equal(условияПлаты(S, работа('разноска')).платит, 12);
  действие(S, 'работа:разноска').выполнить(S);
  авто(S);
  assert.equal(S.мир.смена, null);
  assert.equal(S.мир.работы.разноска.смен, 1);
  assert.ok(S.герой.кошель >= 0);
}

// Предел обычных смен и мягкая миграция старого сохранения.
{
  const S = новоеСостояние('семья', 2);
  for (let i = 0; i < 30; i++) добавитьОчки(S, 'ножи', 1, 'смена');
  assert.equal(S.мир.фракции.ножи, 2);

  const старое = новоеСостояние('семья', 2);
  старое.версия = 6;
  старое.мир.фракции.ножи = 2;
  delete старое.мир.очки;
  delete старое.мир.работы;
  delete старое.мир.смена;
  delete старое.герой.вид;
  const новое = мигрировать(старое);
  assert.equal(новое.версия, ВЕРСИЯ);
  assert.equal(новое.мир.очки.ножи, 8);
  assert.deepEqual(новое.мир.работы, {});
  assert.equal(новое.мир.смена, null);
  assert.equal(новое.герой.вид, 1);
}

console.log('Работы: карточка, сохранение, плата, допуски, очки и миграция прошли.');
