import assert from 'node:assert/strict';
import { МЕСТА } from '../данные/места.js';
import { новоеСостояние, мигрировать } from '../движок/состояние.js';
import { войти, можноВойти, видСцены, действияСцены, вернутьсяВГород } from '../движок/разговор.js';
import { естьВещь, положить } from '../движок/вещи.js';
import { сводкаЖурнала } from '../движок/сводка.js';

const новые = ['рынок', 'контора-дорров', 'меняльная', 'двор-горма', 'ночлежка', 'маяк', 'лекарь', 'часовня', 'лачуга-локи'];
assert.equal(new Set(МЕСТА.map(м => м.id)).size, МЕСТА.length);
for (const id of новые) {
  const м = МЕСТА.find(м => м.id === id);
  assert.ok(м, `${id} есть в реестре`);
  const S = новоеСостояние('семья', 72);
  S.мир.район = м.район;
  S.мир.отрезок = м.когда[0];
  assert.equal(можноВойти(S, id).можно, true);
  войти(S, id);
  assert.equal(S.сцена.место, id);
  assert.ok(видСцены(S).реплика);
  assert.ok(действияСцены(S).length > 0);
  // Каждая комната достижима по двум направлениям, без потери состояния.
  for (const сосед of м.модуль.КОМНАТЫ[м.модуль.старт].соседи) {
    const туда = действияСцены(S).find(а => а.id === `пойти:${сосед}`);
    if (!туда) continue; // комнаты со своим временем суток закрыты
    туда.выполнить(S);
    assert.equal(S.сцена.комната, сосед);
    const обратно = действияСцены(S).find(а => а.id === `пойти:${м.модуль.старт}`);
    assert.ok(обратно, `${id}: обратный переход`);
    обратно.выполнить(S);
  }
  assert.equal(действияСцены(S).some(а => а.вид === 'финал'), true, `${id}: есть выход`);
  вернутьсяВГород(S);
  assert.equal(S.сцена, null);
}

{
  const S = новоеСостояние('семья', 1);
  S.мир.район = 'трущобы'; S.мир.отрезок = 'день'; S.мир.день = 2;
  войти(S, 'двор-горма');
  const кСтолу = действияСцены(S).find(а => а.id === 'пойти:стол-горма');
  кСтолу.выполнить(S);
  assert.equal(действияСцены(S).some(а => а.id === 'заговорить:gorm'), false);
  вернутьсяВГород(S);
  S.мир.день = 3; S.мир.отрезок = 'день';
  войти(S, 'двор-горма');
  действияСцены(S).find(а => а.id === 'пойти:стол-горма').выполнить(S);
  assert.equal(действияСцены(S).some(а => а.id === 'заговорить:gorm'), true);
}

{
  const S = новоеСостояние('семья', 1);
  S.мир.район = 'торговый'; S.мир.отрезок = 'ночь';
  войти(S, 'рынок');
  assert.equal(действияСцены(S).some(а => а.id === 'заговорить:bras'), false);
  assert.equal(действияСцены(S).some(а => а.id === 'пойти:еда-рынка'), false);
  действияСцены(S).find(а => а.id === 'пойти:ночной-ряд').выполнить(S);
  assert.equal(действияСцены(S).some(а => а.id === 'заговорить:ulf'), true);
}

{
  const S = новоеСостояние('семья', 1);
  S.мир.район = 'торговый'; S.мир.отрезок = 'день';
  войти(S, 'меняльная');
  действияСцены(S).find(а => а.id === 'рассмотреть:ячейки').выполнить(S);
  assert.ok(S.мир.свидетельства.includes('brenn_cell17_label'));
  const взять = действияСцены(S).find(а => а.текст === 'Взять выписку о ячейке №17');
  взять.выполнить(S);
  assert.equal(естьВещь(S, 'выписка-17'), true);
  assert.ok(S.мир.свидетельства.includes('brenn_cell17'));
  assert.equal(S.герой.кошель, 58);
  assert.equal(действияСцены(S).some(а => а.текст === 'Взять выписку о ячейке №17'), false);
  const вклад = действияСцены(S).find(а => а.текст === 'Положить 10 грошей на свой счёт');
  вклад.выполнить(S);
  assert.equal(S.мир.места.меняльная.вклад, 10);
  assert.equal(S.герой.кошель, 48);
  assert.equal(сводкаЖурнала(S).вклады[0].сумма, 10);
  действияСцены(S).find(а => а.текст === 'Снять 10 грошей со своего счёта').выполнить(S);
  assert.equal(S.герой.кошель, 58);
  assert.equal(S.мир.места.меняльная.вклад, 0);
}

{
  const S = новоеСостояние('семья', 1);
  S.мир.район = 'маяк'; S.мир.отрезок = 'день';
  S.мир.свидетельства.push('brenn_office_entry');
  войти(S, 'часовня');
  действияСцены(S).find(а => а.текст === 'Показать Уне проверенную запись о Бренне').выполнить(S);
  действияСцены(S).find(а => а.id === 'пойти:ниша-часовни').выполнить(S);
  действияСцены(S).find(а => а.id === 'рассмотреть:журнал').выполнить(S);
  const взять = действияСцены(S).find(а => а.текст === 'Попросить Второй журнал');
  assert.equal(взять.можно, true);
  взять.выполнить(S);
  assert.equal(естьВещь(S, 'второй-журнал'), true);
  assert.ok(S.мир.свидетельства.includes('brenn_second_journal'));
}

{
  const S = новоеСостояние('семья', 1);
  S.версия = 8;
  delete S.мир.свидетельства;
  мигрировать(S);
  assert.equal(S.версия, 10);
  assert.deepEqual(S.мир.свидетельства, []);
}

