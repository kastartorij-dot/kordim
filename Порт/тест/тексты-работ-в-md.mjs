// Пишет документы/Шаг_5_тексты_игры.md из данные/смены/*.js — чтобы автор читал тексты в одном месте.
// Источник правды — файлы данных; после правок в .md их переносят в данные вручную (случай по id) и гоняют тест/работы-данные.mjs.
// node Порт/тест/тексты-работ-в-md.mjs > Порт/документы/Шаг_5_тексты_игры.md
import { РАБОТЫ } from '../данные/работы.js';
import { ТЕМЫ_РАБОТ } from '../данные/темы-работ.js';

const усл = у => (у ? JSON.stringify(у).replace(/"/g, '').replace(/,/g, ', ') : 'всегда');
const абз = т => (typeof т === 'string' ? т : т.map(к => (typeof к === 'string' ? к : `[${усл(к.если)}] ${к.т}`)).join('\n\n'));
const эф = э => (э && JSON.stringify(э) !== '{}' ? JSON.stringify(э).replace(/"/g, '') : '—');
const цитата = т => абз(т).split('\n').map(с => с ? '> ' + с : '>').join('\n');

const вых = ['# Порт — работы: тексты в игре', '',
  'Снимок игровых карточек из `данные/смены/*.js`. Исходный текст другой ИИ сохранён отдельно в `от-другой-ИИ/Порт-работы-тексты.md`.',
  'Для каждого случая: когда выпадает, что делает с миром, текст, варианты и их итоги. Нить — сюжетный шаг: срабатывает раньше обычных и не чаще раза в день. «Однажды» — не повторяется.', ''];
for (const р of РАБОТЫ.filter(р => р.колода.length || р.ставка)) {
  вых.push(`## ${р.имя}`, '');
  for (const с of р.колода) {
    вых.push(`### ${с.id}${с.нить ? ' · нить' : ''}${с.однажды ? ' · однажды' : ''}${с.вес ? ` · вес ${с.вес}` : ''}`);
    вых.push(`Когда: ${усл(с.условие)}. Эффект: ${эф(с.эффект)}`, '', цитата(с.текст), '');
    for (const о of с.выбор ?? []) {
      вых.push(`- **${о.текст}**${о.условие ? ` (если ${усл(о.условие)})` : ''} — эффект: ${эф(о.эффект)}`, '', цитата(о.итог).replace(/^/gm, '  '), '');
    }
  }
  if (р.ставка) {
    вых.push(`Вступление к кругу:`, '', цитата(р.ставка.вступление), '');
    for (const с of р.ставка.соперники) {
      вых.push(`### соперник: ${с.имя} · кошелёк ${с.кошелёк} · базовый шанс ${Math.round(с.шанс * 100)}%${с.условие ? ` · если ${усл(с.условие)}` : ''}`, '');
      вых.push('Победа:', ...с.победа.тексты.map(т => '\n' + цитата(т)), '', `Эффект победы: ${эф(с.победа.эффект)}`, '');
      вых.push('Поражение:', ...с.поражение.тексты.map(т => '\n' + цитата(т)), '', `Эффект поражения: ${эф(с.поражение.эффект)}`, '');
    }
  }
}
вых.push('## Новые темы', '');
for (const [id, т] of Object.entries(ТЕМЫ_РАБОТ)) {
  вых.push(`### ${id} — «${т.ярлык}» · ценность ${т.ценность}${т.опасна ? ` · опасна: ${т.опасна}` : ''}${т.личная ? ' · личная' : ''}`, '', цитата(т.текст), '',
    `- прямо: ${т.фразы.прямо}`, `- мягко: ${т.фразы.мягко}`, `- деньгами: ${т.фразы.деньгами}`, '');
}
console.log(вых.join('\n').trimEnd());
