// Случайные законные действия по 30 дням: работы, карточки, еда, отдых, переходы и загрузка.
// node Порт/тест/шаг5-случайные-ходы.mjs
import assert from 'node:assert/strict';
import { новоеСостояние } from '../движок/состояние.js';
import { доступныеДействия } from '../движок/действия.js';

let ходов = 0;
for (let зерно = 1; зерно <= 100; зерно++) {
  let S = новоеСостояние(['семья', 'бумаги', 'наколки'][зерно % 3], зерно);
  let x = зерно >>> 0;
  const случай = () => ((x = (Math.imul(x, 1664525) + 1013904223) >>> 0) / 4294967296);
  for (let шаг = 0; S.мир.день <= 30; шаг++) {
    assert.ok(шаг < 4000, `зерно ${зерно}: день не движется`);
    if (S.мир.конецДня) S.мир.конецДня = null;
    if (случай() < 0.12) S = JSON.parse(JSON.stringify(S));
    const доступные = доступныеДействия(S).filter(a => a.можно && a.вид !== 'место');
    assert.ok(доступные.length, `зерно ${зерно}: нет выхода`);
    const смены = доступные.filter(a => a.вид === 'смена' || a.вид === 'работа');
    const сон = доступные.filter(a => a.вид === 'сон');
    const еда = доступные.filter(a => a.вид === 'еда');
    const пул = смены.length && случай() < 0.6 ? смены
      : S.герой.тело.сыт < 2 && еда.length && случай() < 0.7 ? еда
      : сон.length && случай() < 0.7 ? сон : доступные;
    const действие = пул[Math.floor(случай() * пул.length)];
    действие.выполнить(S);
    ходов++;
    for (const ключ of ['сыт', 'отдых', 'тепло', 'цел']) {
      const значение = S.герой.тело[ключ];
      assert.ok(Number.isInteger(значение) && значение >= 0 && значение <= 3, `зерно ${зерно}: ${ключ}=${значение}`);
    }
    assert.ok(Number.isFinite(S.герой.кошель) && S.герой.кошель >= 0, `зерно ${зерно}: кошель`);
    if (S.мир.смена) assert.ok(доступныеДействия(S).length, `зерно ${зерно}: карточка без выхода`);
  }
}
console.log(`Шаг 5: 100 партий по 30 дней, ${ходов} законных ходов с повторной загрузкой — без зависаний.`);
