function ест(S, A) {
  if (S.герой.тело.сыт > 1) return null;
  return дешёвый(годные(A, 'еда')) ?? null;
}

function работяга(S, A) {
  const { отрезок, район, день } = S.мир;
  const е = ест(S, A);
  if (е) return е;
  // Тяжёлую работу теперь сопровождают лечение и ремонт, иначе старый бот игнорирует новые способы восстановления.
  if (S.герой.тело.цел <= 1 && S.герой.кошель >= 5) {
    if (район !== 'торговый' && отрезок === 'утро') return по(A, 'переход:торговый');
    if (район === 'торговый') { const л = по(A, 'услуга:лекарь'); if (л) return л; }
  }
  // Раз в неделю (день 3, 10, 17, 24): утром на рынок, днём взять пирог с собой (потом разноска), на следующий день съесть.
  const п = П(S);
  const пирог = S.герой.при_себе.some(x => x.тип === 'пирог');
  if (пирог && день > (п.пирогДень ?? 0) && отрезок !== 'ночь') { const в = действияВещей(S).find(x => x.можно); if (в) return в; }
  if (день % 7 === 3 && !пирог && п.пирогДень !== день) {
    if (отрезок === 'утро' && район !== 'торговый') { const х = по(A, 'переход:торговый'); if (х) return х; }
    if (отрезок === 'день' && район === 'торговый') { const а = по(A, 'еда-собой:пирог'); if (а) { п.пирогДень = день; return а; } }
  }
  if (отрезок === 'ночь') {
    const сны = годные(A, 'сон');
    return дешёвый(сны.filter(с => с.отдых >= 2)) ?? дешёвый(сны);
  }
  if (отрезок === 'утро') { const р = по(A, 'работа:разгрузка'); if (р) return р; }
  if (отрезок === 'день') { const р = по(A, 'работа:разноска'); if (р) return р; }
  if (район !== 'доки') return по(A, 'переход:доки');
  return ждать(A);
}

const ночлег = (S, A) => {
  const сны = годные(A, 'сон');
  return дешёвый(сны.filter(с => с.отдых >= 2)) ?? дешёвый(сны);
};

// Память «сплетника» между шагами (в состояние не кладём).
const память = new WeakMap();
const П = S => { if (!память.has(S)) память.set(S, {}); return память.get(S); };

// «Сплетник» (этап 4): трёхдневный круг по трём точкам, начинающийся там, где стартует герой (в доках). День 1: таверна вечером
// (перед ней разгрузка); день 2: баня в трущобах; день 3: аптека утром или днём (и разноска). География не даёт ходить каждый вечер в таверну и одновременно работать,
// поэтому и таверна, и баня — раз в три дня.
function сплетник(S, A) {
  const { отрезок, район, день } = S.мир;
  const п = П(S);
  const тип = день % 3; // 0 — аптека, 1 — таверна, 2 — баня; день 1 — таверна
  const е = ест(S, A);
  if (е) return е;
  if (отрезок === 'ночь') return ночлег(S, A);
  const вход = id => по(A, `место:${id}`);
  const идти = р => по(A, `переход:${р}`);
  if (тип === 0) {
    if (район !== 'торговый' && (отрезок === 'утро' || отрезок === 'день')) return идти('торговый');
    if (район === 'торговый' && п.аптекаДень !== день) { const а = вход('аптека'); if (а) { п.аптекаДень = день; return а; } }
    if (район === 'торговый' && отрезок === 'день') { const р = по(A, 'работа:разноска'); if (р) return р; }
    if (отрезок === 'вечер' && район !== 'доки') return идти('доки');
  } else if (тип === 1) {
    if (район !== 'доки' && отрезок !== 'вечер') return идти('доки');
    if (отрезок === 'утро') { const р = по(A, 'работа:разгрузка'); if (р) return р; }
    if (отрезок === 'вечер' && район === 'доки') { const а = вход('таверна'); if (а) return а; }
  } else {
    if (район !== 'трущобы' && (отрезок === 'утро' || отрезок === 'день') && п.баняДень !== день) return идти('трущобы');
    if (район === 'трущобы' && п.баняДень !== день) { const а = вход('баня'); if (а) { п.баняДень = день; return а; } }
    if (отрезок === 'вечер' && район !== 'торговый') return идти('торговый');
  }
  return ждать(A);
}

