// ── визит в «Синий час» ─────────────────────────────────────────────
// Заговаривает со всеми по всем темам всеми подходами, пока есть ходы; на чётных визитах, если хватает,
// поднимается наверх и остаётся; в конце выходит. Проверяет память дома между визитами.
const КОМНАТЫ = ДОМ.КОМНАТЫ;
function путьДо(откуда, куда) {
  const очередь = [[откуда]], видел = new Set([откуда]);
  while (очередь.length) {
    const п = очередь.shift(), т = п[п.length - 1];
    if (т === куда) return п;
    for (const с of КОМНАТЫ[т].соседи) if (!КОМНАТЫ[с].цена && !видел.has(с)) { видел.add(с); очередь.push([...п, с]); }
  }
  return null;
}
const узелТемы = (кто, тид, подход) => (ДОМ.Р[кто] || {})[тид]?.[подход] ?? (ДОМ.Р[кто] || {})[тид]?.['любой'] ?? null;
const копия = v => JSON.parse(JSON.stringify(v));

async function визит(S, р, номер) {
  const кошДо = S.герой.кошель;
  const память = копия({ люди: S.мир.люди, места: S.мир.места, темы: S.мир.темы });
  if (S.мир.отрезок !== 'ночь' || !S.сцена) throw new Error('после входа ожидалась ночь и сцена');
  const ст = { готово: new Set(), комнаты: new Set(), наверх: номер % 2 === 0 };
  for (let шаг = 0; шаг < 400; шаг++) {
    const с = S.сцена;
    if (с.итог) break;
    if (с.нужнаСцена) { await догрузитьСцену(S, читатьСцену); if (S.герой.напряжение !== 0) р.ошибки.push('напряжение не обнулилось после сцены'); continue; }
    const A = действияСцены(S);
    const выбрать = a => a.выполнить(S);
    const тело = S.герой.тело;
    for (const [к, v] of Object.entries(тело)) if (!Number.isInteger(v) || v < 0 || v > 3) р.ошибки.push(`${к}=${v} внутри места`);
    if (S.герой.кошель < 0) р.ошибки.push(`кошель ${S.герой.кошель} внутри места`);
    if (с.ходы > ДОМ.ходов + 3) р.ошибки.push(`ходы ${с.ходы} — вечер не закончился`);

    // диалоги-графы (Сиб): вариант за вариантом, непройденные раньше; в хабе — новая ветка, потом «Отойти»
    if (A.some(а => а.вид === 'вариант')) {
      const видел = (ст.варианты ??= new Set());
      const в = A.find(а => а.вид === 'вариант' && а.можно && !а.закреплён && !видел.has(а.id)) ?? A.find(а => а.вид === 'вариант' && а.можно && а.закреплён) ?? A.find(а => а.вид === 'вариант' && а.можно);
      if (!в) throw new Error('в диалоге нет доступного варианта: ' + A.map(а => а.текст).join(' / '));
      видел.add(в.id); выбрать(в); continue;
    }
    if (A.some(а => а.вид === 'ветка')) {
      const н = A.find(а => а.вид === 'ветка' && а.можно && !(ст.ветки ??= new Set()).has(а.id));
      if (н) { ст.ветки.add(н.id); выбрать(н); continue; }
      ст.готово.add(с.собеседник); выбрать(A.find(а => а.id === 'отойти')); continue;
    }
    // дверь
    if (A.some(а => а.вид === 'вход')) {
      const вход = A.find(а => а.вид === 'вход' && а.можно) ?? A.find(а => а.вид === 'финал');
      выбрать(вход); continue;
    }
    const хотел = A.find(а => а.id === 'отойти');
    if (с.собеседник) {
      const кто = с.собеседник;
      const прод = A.find(а => а.id === 'продолжить') ?? A.find(а => а.id === 'спуститься');
      if (прод) { выбрать(прод); continue; }
      const новая = A.find(а => а.вид === 'тема' && а.можно && а.подпись !== 'уже' && а.подпись !== 'сказано');
      if (новая) { выбрать(новая); continue; }
      // другие подходы: сначала те, где ещё есть неспрошенное
      let сменил = false;
      for (const п of ДОМ.ЭКРАН.подходы) {
        if (п === с.подход) continue;
        выбратьПодход(S, п);
        if (действияСцены(S).some(а => а.вид === 'тема' && а.можно && а.подпись === ДОМ.ЭКРАН.слова.час)) { сменил = true; break; }
      }
      if (сменил) continue;
      выбратьПодход(S, ДОМ.ЭКРАН.подходСтарт);
      // повторный вопрос тем же тоном: ответ тот же, а расположение, ходы и деньги не меняются
      const был = A.find(а => а.вид === 'тема' && а.можно && а.подпись === ДОМ.ЭКРАН.слова.уже);
      if (был && !ст.повторил?.has(кто)) {
        (ст.повторил ??= new Set()).add(кто);
        const п = с.подход, л = S.мир.люди[кто];
        const узел = узелТемы(кто, был.тема, п);
        const до = { распол: л?.распол, ходы: с.ходы, кошель: S.герой.кошель, дом: S.мир.места[МЕСТО].дом };
        выбрать(был);
        const после = { распол: S.мир.люди[кто]?.распол, ходы: S.сцена?.ходы ?? 0, кошель: S.герой.кошель, дом: S.мир.места[МЕСТО].дом };
        if (узел && !узел.дальше && JSON.stringify(до) !== JSON.stringify(после))
          р.ошибки.push(`повтор «${кто}/${был.тема}/${п}» изменил состояние: ${JSON.stringify(до)} → ${JSON.stringify(после)}`);
        р.повторов++;
        continue;
      }
      const ост = A.find(а => а.id === 'остаться');
      if (ост && ст.наверх) { выбрать(ост); continue; }
      ст.готово.add(кто);
      выбрать(хотел); continue;
    }
    // комната
    ст.комнаты.add(с.комната);
    const говорить = A.find(а => а.вид === 'заговорить' && !ст.готово.has(а.id.split(':')[1]));
    if (говорить) { выбрать(говорить); continue; }
    if (ст.наверх && S.герой.кошель >= 60) {
      const вверх = A.find(а => а.вид === 'подняться' && а.можно && !ст.готово.has(КОМНАТЫ[а.цель].люди[0]));
      if (вверх) { выбрать(вверх); continue; }
    }
    const новая = A.find(а => а.вид === 'пойти' && !ст.комнаты.has(а.цель) && !КОМНАТЫ[а.цель].цена);
    if (новая) { выбрать(новая); continue; }
    if (с.комната === ДОМ.старт) {
      const выход = A.find(а => а.вид === 'финал');
      if (выход) { выбрать(выход); continue; }
    }
    const п = путьДо(с.комната, ДОМ.старт);
    const дальше = п && A.find(а => а.вид === 'пойти' && а.цель === п[1]);
    if (!дальше) throw new Error(`бот не нашёл выхода из комнаты ${с.комната}`);
    выбрать(дальше);
  }
  if (!S.сцена?.итог) throw new Error('визит не закончился за 400 шагов');
  const итог = S.сцена.итог;
  if (кошДо - S.герой.кошель !== итог.потрачено) р.ошибки.push(`потрачено внутри ${кошДо - S.герой.кошель}, в счёте ${итог.потрачено}`);
  р.потраченоВДоме += итог.потрачено;
  // память дома: то, что было до визита, не потеряно (спрошенное только прибавилось)
  for (const [кто, л] of Object.entries(память.люди)) {
    const н = S.мир.люди[кто];
    if (!н) { р.ошибки.push(`человек ${кто} забыт`); continue; }
    for (const к of л.спрошено) if (!н.спрошено.includes(к)) р.ошибки.push(`спрошенное ${кто}/${к} забыто`);
    for (const к of л.исчерпано) if (!н.исчерпано.includes(к)) р.ошибки.push(`исчерпанное ${кто}/${к} забыто`);
  }
  for (const т of память.темы) if (!S.мир.темы.includes(т)) р.ошибки.push(`тема ${т} забыта`);
  for (const [м, п] of Object.entries(память.места))
    for (const ф of п.флаги) if (!S.мир.места[м].флаги.includes(ф)) р.ошибки.push(`постоянный флаг ${ф} потерян`);
  return итог;
}

// ── визит в точку (аптека, таверна, баня) ───────────────────────────────
// Каждое действие внутри — через дей(): до и после сравниваются знания, тень и «ушло».
const ценность = т => РЕЕСТР[т]?.ценность ?? 0;
function дей(S, р, а) {
  const до = { зн: копия(S.мир.знания), тень: S.мир.тень, ушло: копия(S.мир.ушло ?? {}), место: S.сцена?.место, кто: S.сцена?.собеседник, темы: S.мир.темы.slice() };
  а.выполнить(S);
  // ложь ни разу не стала «подтверждено»
  for (const [т, з] of Object.entries(S.мир.знания)) if (РЕЕСТР[т]?.ложь && з.верность === 'подтверждено') р.ошибки.push(`ложь ${т} подтверждена`);
  // «слышал» → «подтверждено» — только от второго источника (моряк, боец)
  for (const [т, з] of Object.entries(до.зн)) {
    const после = S.мир.знания[т]?.верность;
    if (з.верность === 'слышал' && после === 'подтверждено' && !((до.место === 'таверна' && до.кто === 'moryak') || (до.место === 'баня' && до.кто === 'boec')))
      р.ошибки.push(`«слышал» → «подтверждено» (${т}) вне второго источника: ${до.место}/${до.кто}`);
    if (з.верность === 'слышал' && после === 'опровергнуто') { if (!(до.место === 'аптека' || (до.место === 'баня' && до.кто === 'boec'))) р.ошибки.push(`опровергнуто ${т} вне бойца и аптеки`); else р.опровергнуто++; }
    if (з.верность === 'подтверждено' && после !== 'подтверждено') р.ошибки.push(`подтверждённое ${т} стало «${после}»`);
  }
  // тень: только от ушей таверны, по разу на тему
  const ножиДо = Object.entries(до.ушло).filter(([, v]) => v.split(' ').includes('ножи')).map(([т]) => т);
  const ножиПосле = Object.entries(S.мир.ушло ?? {}).filter(([, v]) => v.split(' ').includes('ножи')).map(([т]) => т);
  const новые = ножиПосле.filter(т => !ножиДо.includes(т));
  if (S.мир.тень > до.тень && до.место !== 'таверна') р.ошибки.push(`тень выросла вне таверны (${до.место})`);
  if (новые.length && до.место !== 'таверна') р.ошибки.push(`уши вне таверны (${до.место})`);
  if (новые.some(т => ценность(т) < 2)) р.ошибки.push('уши на тему дешевле 2');
  if (S.мир.тень !== Math.min(3, до.тень + новые.length)) р.ошибки.push(`тень ${до.тень} → ${S.мир.тень} при новых ушах ${новые.length}`);
  if (S.мир.тень > 3) р.ошибки.push('тень выше 3');
  р.ушей += новые.length;
  return до;
}

const жми = (S, р, пред) => {
  if (!S.сцена) return false;
  const а = действияСцены(S).find(x => x.можно && пред(x));
  if (!а) return false;
  дей(S, р, а);
  return true;
};
