// Варианты экономики для «своего угла» (ГДД §24 п.3): node Порт/тест/экономика.mjs
// Один и тот же расчётливый бот на разных числах. Числа правятся прямо в данных
// перед прогоном — поэтому каждый вариант идёт в отдельном процессе.
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ВАРИАНТЫ = {
  'сейчас': 'числа этапа 2 как есть',
  'А': 'разгрузка не «садится» (цена серии — только отдых), разноска днём и вечером',
  'Б': 'А + своё ремесло по вечерам в доках, 20 гр. чистыми (25 минус расходники), только у кого ремесло',
};

const вариант = process.argv[2];
if (!вариант) {
  // Родитель: запускает себя на каждый вариант и собирает таблицу.
  const я = fileURLToPath(import.meta.url);
  console.log('| вариант | как живёт | начало | заработок/день | жизнь/день | свободных отрезков/день | кошель 7 | 14 | 30 |');
  console.log('|---|---|---|---|---|---|---|---|---|');
  for (const в of Object.keys(ВАРИАНТЫ)) {
    const р = spawnSync(process.execPath, [я, в], { encoding: 'utf8' });
    if (р.status) { console.error(р.stderr); process.exit(1); }
    process.stdout.write(р.stdout);
  }
  console.log('\n' + Object.entries(ВАРИАНТЫ).map(([к, v]) => `- **${к}** — ${v}`).join('\n'));
  process.exit(0);
}

const { РАБОТЫ } = await import('../данные/работы.js');
const раб = id => РАБОТЫ.find(р => р.id === id);
if (вариант === 'А' || вариант === 'Б') {
  раб('разгрузка').садится = null;
  раб('разноска').когда = ['день', 'вечер'];
}
if (вариант === 'Б') Object.assign(раб('ремесло'), { где: 'доки', когда: ['вечер'], платит: 20, открыто: true });

const { новоеСостояние } = await import('../движок/состояние.js');
const { доступныеДействия } = await import('../движок/действия.js');
const { НАЧАЛА } = await import('../данные/герой.js');
const { ОТРЕЗКИ } = await import('../движок/время.js');

const ЗЕРНА = [11, 222, 3333];
const ДНИ = 30;
const ОТМЕТКИ = [7, 14, 30];
const платит = а => Number((а.подпись.match(/\+(\d+) гр/) || [])[1] || 0);
const дешёвый = арр => [...арр].sort((а, б) => а.цена - б.цена)[0];

// Лучшая открытая работа, доступная в этот отрезок где угодно (для решения «куда идти»).
function работаВ(S, отрезок) {
  const есть = РАБОТЫ.filter(р => р.открыто && р.когда.includes(отрезок)
    && (р.id !== 'ремесло' || S.герой.начало === 'наколки'));
  return есть.sort((а, б) => б.платит - а.платит)[0] ?? null;
}

// режим: 'максимум' — вся работа, что есть; 'одна' — одна работа в день, остальное свободно.
let режим = 'максимум';
let работалДень = 0;

function ход(S, A) {
  const { отрезок, район } = S.мир;
  const т = S.герой.тело;
  const еда = A.filter(а => а.вид === 'еда' && а.можно);
  if (т.сыт <= 1 && еда.length) return дешёвый(еда);
  if (т.тепло <= 1) { const п = еда.find(а => а.id === 'еда:похлёбка'); if (п) return п; }

  if (отрезок === 'ночь') {
    const сны = A.filter(а => а.вид === 'сон' && а.можно);
    // цена за ночь: у вдовы 25 на 7 ночей, после оплаты — даром
    const заНочь = а => (а.id === 'сон:вдова' && а.цена === 25 ? 25 / 7 : а.цена);
    const хорошие = сны.filter(а => а.отдых >= 2).sort((а, б) => заНочь(а) - заНочь(б));
    return хорошие[0] ?? дешёвый(сны);
  }

  // Работа здесь и сейчас. Если платит меньше половины обычного — день отдыха.
  const здесь = A.filter(а => а.вид === 'работа' && а.можно && (а.id !== 'работа:ремесло' || S.герой.начало === 'наколки'))
    .sort((а, б) => платит(б) - платит(а))[0];
  // Урезанная оплата («тело садится») — не работать, взять день отдыха.
  const сегодня = работалДень === S.мир.день;
  const можноЕщё = режим === 'максимум' || !сегодня;
  if (здесь && можноЕщё && платит(здесь) >= 8) return здесь;
  if (режим === 'одна' && сегодня) return A.find(а => а.id === 'отрезок:здесь');

  // Куда идти: к работе следующего отрезка, а вечером — туда, где утром работа.
  const след = ОТРЕЗКИ[ОТРЕЗКИ.indexOf(отрезок) + 1];
  const цель = отрезок === 'вечер' ? работаВ(S, 'утро') : работаВ(S, след);
  if (цель && цель.где !== район) {
    const п = A.find(а => а.id === `переход:${цель.где}`);
    if (п) return п;
  }
  return A.find(а => а.id === 'отрезок:здесь');
}

function прогон(началоId, сид) {
  const S = новоеСостояние(началоId, сид);
  const р = { заработок: 0, жизнь: 0, кошель: {}, свободно: 0 };
  let шаги = 0;
  while (S.мир.день <= ДНИ && шаги++ < 10000) {
    const а = ход(S, доступныеДействия(S));
    if (а.вид === 'ждать' && S.мир.отрезок !== 'ночь') р.свободно++;
    const до = S.герой.кошель;
    if (а.вид === 'работа') работалДень = S.мир.день;
    а.выполнить(S);
    const d = S.герой.кошель - до;
    if (d > 0) р.заработок += d; else р.жизнь -= d;
    if (S.мир.конецДня) {
      if (ОТМЕТКИ.includes(S.мир.конецДня.день)) р.кошель[S.мир.конецДня.день] = S.герой.кошель;
      S.мир.конецДня = null;
    }
  }
  р.цел = S.герой.тело.цел;
  return р;
}

const ср = (арр, ф) => (арр.reduce((с, x) => с + ф(x), 0) / арр.length).toFixed(0);
const ср1 = (арр, ф) => (арр.reduce((с, x) => с + ф(x), 0) / арр.length).toFixed(1);
for (const р0 of ['максимум', 'одна']) {
  режим = р0;
  for (const н of НАЧАЛА) {
    if (вариант !== 'Б' && н.id === 'наколки') continue; // без ремесла наколки = семья с другим кошельком
    const g = ЗЕРНА.map(с => прогон(н.id, с));
    console.log(`| ${вариант} | ${р0} | ${н.id} | ${ср(g, р => р.заработок / ДНИ)} | ${ср(g, р => р.жизнь / ДНИ)} | ${ср1(g, р => р.свободно / ДНИ)} | ${ОТМЕТКИ.map(д => ср(g, р => р.кошель[д] ?? 0)).join(' | ')} |`);
  }
}
