// ── помощники ──────────────────────────────────────────────────────────────
const новая = (сид = 1) => { const S = новоеСостояние('семья', сид); S.герой.кошель = 100; S.мир.день = 4; return S; };
const место = id => МЕСТА.find(м => м.id === id);

// Встать в сцену места так, как это делает игра, и (если нужно) подойти к человеку нужным тоном.
function встать(S, id, { кто = null, подход = null, комната = null, ходов = null } = {}) {
  const м = место(id);
  S.мир.район = м.район;
  S.мир.отрезок = м.когда[0];
  S.мир.конецДня = null;
  войти(S, id);
  if (id === 'синий-час') { S.сцена.вошёл = true; }
  if (комната) S.сцена.комната = комната;
  if (кто) { S.сцена.собеседник = кто; S.сцена.реплика = ''; }
  if (подход) S.сцена.подход = подход;
  if (ходов !== null) S.сцена.ходы = ходов;
  return S;
}
const кнопки = S => действияСцены(S).filter(а => а.вид === 'дело');
const кнопка = (S, id) => действияСцены(S).find(а => а.id === id);
const нажать = (S, id) => {
  const к = кнопка(S, id);
  assert.ok(к, `нет кнопки ${id}; есть: ${кнопки(S).map(а => а.id).join(' | ')}`);
  assert.equal(к.можно, true, `${id} недоступна: ${к.почему}`);
  к.выполнить(S);
  return к;
};
const выйти = S => { if (S.сцена) вернутьсяВГород(S); };
// В город, в нужный район и отрезок.
const вГороде = (S, район, отрезок = 'день') => { выйти(S); S.мир.район = район; S.мир.отрезок = отрезок; S.мир.конецДня = null; };
const горКнопка = (S, id) => доступныеДействия(S).find(а => а.id === id);
const сдать = (S, id) => {
  const к = горКнопка(S, id);
  assert.ok(к, `нет городской кнопки ${id}`);
  assert.equal(к.можно, true, `${id} недоступна: ${к.почему}`);
  к.выполнить(S);
};
// Пролистать время до начала нужного дня (каждый конец дня проверяет сроки и вещи).
const домой = (S, день) => { while (S.мир.день < день) { S.мир.конецДня = null; следующийОтрезок(S); } S.мир.конецДня = null; };
const очки = (S, к) => S.мир.очки?.[к] ?? 0;
const вещьДела = (S, дело) => привестиВещи(S).find(x => x.дело === дело);
const ID = д => `дело:${д}`;

// ── 0. данные: все ссылки живые, деньги сходятся ────────────────────────────
{
  const волна1 = ИДЫ_ДЕЛ.filter(id => ДЕЛА[id].волна === 1);
  assert.equal(волна1.length, 10, 'десять дел первой волны');
  const РАЙОНЫ = ['доки', 'торговый', 'трущобы', 'маяк', 'локи'];
  let деньги = 0;
  for (const id of ИДЫ_ДЕЛ) {
    const д = ДЕЛА[id];
    const ids = new Set(д.шаги.map(ш => ш.id));
    assert.equal(ids.size, д.шаги.length, `${id}: шаги с повторяющимися id`);
    for (const ш of д.шаги) {
      if (ш.следующий) assert.ok(ids.has(ш.следующий), `${id}/${ш.id}: следующий «${ш.следующий}» не найден`);
      const г = ш.где;
      if (г.район) assert.ok(РАЙОНЫ.includes(г.район), `${id}/${ш.id}: район ${г.район}`);
      else {
        const м = место(г.место);
        assert.ok(м, `${id}/${ш.id}: место ${г.место}`);
        if (г.кто) assert.ok(м.модуль.ЛЮДИ[г.кто], `${id}/${ш.id}: человека ${г.кто} нет в ${г.место}`);
        if (г.комната) assert.ok(м.модуль.КОМНАТЫ[г.комната], `${id}/${ш.id}: комнаты ${г.комната} нет`);
      }
      for (const в of [ш.выдать, ш.требует, ш.принять?.выдать]) if (в) assert.ok(ВЕЩИ[в.вещь], `${id}/${ш.id}: вещи ${в.вещь} нет`);
      if (ш.тема) assert.ok(РЕЕСТР[ш.тема], `${id}/${ш.id}: темы ${ш.тема} нет`);
      assert.ok(ш.текст || ш.варианты || ш.тип === 'сведение', `${id}/${ш.id}: нет текста`);
      if (д.волна === 1) деньги += (ш.эффект?.гроши ?? 0) + (ш.деньги?.эффект?.гроши ?? 0);
    }
    assert.ok(!JSON.stringify(д).includes('НОВОЕ'), `${id}: служебная пометка попала в игровой текст`);
  }
  // Деньги по каждому делу — одна награда (у «сведений» это максимум из двух путей); сумма волны 1 — 89 гр. (концепт §4′).
  assert.equal(деньги, 89, `сумма наград ${деньги}`);
}

