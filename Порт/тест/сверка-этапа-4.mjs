// Проверка этапа 4: тексты Порт-тексты-4.md переехали в данные ДОСЛОВНО и лежат там, где сказано в файле.
// node Порт/тест/сверка-этапа-4.mjs
// 1) каждая цитата «>» (пустая «>» — «\n\n») и каждая фраза в «ёлочках» из строк «Фразы:» — ровно строка в данных;
// 2) каждая цитата лежит на своём месте: у того человека, той темы, того тона (и с теми эффектами, что названы в скобках);
// 3) в новых данных нет своих длинных текстов: любая строка длиннее 25 символов — из файла.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { АПТЕКА } from '../данные/места/аптека.js';
import { ТАВЕРНА } from '../данные/места/таверна.js';
import { БАНЯ } from '../данные/места/баня.js';
import { РЕЕСТР } from '../данные/темы.js';

const ПОРТ = join(dirname(fileURLToPath(import.meta.url)), '..');
const МД = join(ПОРТ, 'документы', 'Порт-тексты-4.md');
const текст = fs.readFileSync(МД, 'utf8').replace(/\r\n/g, '\n');
const строки = текст.split('\n');

const МЕСТА = { 'Аптека Сибиллы Рейн': АПТЕКА, 'Портовая таверна': ТАВЕРНА, 'Баня': БАНЯ };
const ЛЮДИ_ИМЕНА = { 'Сибилла Рейн': 'sibilla', 'Хозяин таверны': 'hozyain', 'Моряк с чужого корабля': 'moryak', 'Банщик': 'banshchik', 'Старый боец': 'boec' };
const ОБМЕН = [
  ['ценность темы 0', 'ноль'], ['тема — её же', 'своя'], ['тема — ложь', 'ложь'], ['у Сибиллы не осталось', 'ничего'],
  ['обмен состоялся', 'состоялся'], ['тема была **личная**', 'личная'],
];
const ошибки = [];
const плохо = с => ошибки.push(с);

// ── все строки новых данных (без ЭКРАН — это общий экран «Синего часа»)
const данные = new Set();
(function обойти(v, ключ) {
  if (typeof v === 'string') данные.add(v);
  else if (Array.isArray(v)) v.forEach(x => обойти(x));
  else if (v && typeof v === 'object') for (const [к, x] of Object.entries(v)) if (к !== 'ЭКРАН' && к !== 'КАРТИНКИ') обойти(x, к);
})([АПТЕКА, ТАВЕРНА, БАНЯ, Object.fromEntries(Object.entries(РЕЕСТР).filter(([, т]) => т.текст))]);

// ── разбор файла
const цитаты = []; // { текст, контекст }
const фразы = [];
const имена = []; // ярлыки, названия мест и людей, детали
{
  let тек = null, контекст = '';
  const закрыть = () => { if (тек) { цитаты.push({ текст: тек.join('\n'), контекст }); тек = null; } };
  for (const л of строки) {
    if (л.startsWith('>')) { (тек ??= []).push(л.replace(/^> ?/, '')); continue; }
    закрыть();
    if (л.trim()) контекст = л;
  }
  закрыть();
  for (const а of текст.split('\n\n')) {
    if (!а.startsWith('Фразы:')) continue;
    const т = а.replace(/\n/g, ' ');
    for (const тон of ['прямо', 'мягко', 'деньгами']) {
      const м = new RegExp(тон + ' «([^»]*)»').exec(т);
      if (!м) плохо(`нет фразы «${тон}» в абзаце: ${т.slice(0, 50)}`); else фразы.push(м[1]);
    }
  }
}

// ── 1. цитаты и фразы — строки данных
for (const ц of цитаты) if (!данные.has(ц.текст)) плохо(`цитата не найдена в данных (${ц.контекст.slice(0, 50)}): ${ц.текст.slice(0, 60)}`);
for (const ф of фразы) if (!данные.has(ф)) плохо(`фраза не найдена в данных: ${ф}`);

// ── 2. привязки: где цитата лежит
let место = null, человек = null, тема = null, раздел = '';
const проверить = (путь, ожид, что) => {
  const факт = путь();
  if (факт !== ожид) плохо(`не на месте: ${что} — в данных ${JSON.stringify(факт)?.slice(0, 50)}`);
};
let привязок = 0;
{
  let i = 0;
  let тек = null;
  const после = n => строки.findIndex((x, k) => k > n && x.startsWith('>'));
  const собрать = (нач) => { // цитата, что начинается со строки нач
    const в = []; let j = нач;
    while (j < строки.length && строки[j].startsWith('>')) { в.push(строки[j].replace(/^> ?/, '')); j++; }
    return { текст: в.join('\n'), конец: j };
  };
  let ожидаемаяЦитата = null; // { ключ, ...}
  const темаОтметки = {};
  for (let n = 0; n < строки.length; n++) {
    const л = строки[n];
    let м;
    if ((м = /^## (.+)$/.exec(л)) && МЕСТА[м[1]]) { место = МЕСТА[м[1]]; человек = null; имена.push(м[1]); if (место.имя !== м[1]) плохо(`имя места: ${м[1]}`); }
    if ((м = /^### (.+)$/.exec(л))) {
      раздел = м[1];
      человек = ЛЮДИ_ИМЕНА[м[1]] ?? null;
      if (человек) { имена.push(м[1]); if (место.ЛЮДИ[человек]?.имя !== м[1]) плохо(`имя человека «${м[1]}»`); }
      const т = /^(\w+) — «([^»]+)» · ценность (\d)(.*)$/.exec(м[1]);
      if (т) {
        const [, id, ярлык, ц, хвост] = т;
        const р = РЕЕСТР[id];
        имена.push(ярлык);
        if (!р) { плохо(`тема ${id} нет в реестре`); continue; }
        if (р.ярлык !== ярлык) плохо(`ярлык ${id}`);
        if (р.ценность !== +ц) плохо(`ценность ${id}`);
        if (!!р.ложь !== /ложь/.test(хвост)) плохо(`отметка «ложь» у ${id}`);
        if ((р.опасна ?? null) !== ((/опасная \(([^)]+)\)/.exec(хвост) ?? [])[1] ?? null)) плохо(`отметка «опасна» у ${id}`);
        const ц1 = собрать(после(n));
        привязок++;
        if (р.текст !== ц1.текст) плохо(`текст «что узнал» у ${id}`);
        const фр = текст.split('\n\n').find((а, k, все) => все[k - 1]?.startsWith('> ') && а.startsWith('Фразы:') && все[k - 1].includes(ц1.текст.slice(0, 20)));
        if (фр) for (const тон of ['прямо', 'мягко', 'деньгами']) {
          const мм = new RegExp(тон + ' «([^»]*)»').exec(фр.replace(/\n/g, ' '));
          if (!мм || р.фразы[тон] !== мм[1]) плохо(`фраза ${id}/${тон}`);
          привязок++;
        }
      }
      continue;
    }
    // комната и детали
    if (/^### Комната$/.test(л)) {
      const { текст: т } = собрать(после(n));
      привязок++;
      const ком = Object.values(место.КОМНАТЫ)[0];
      if (ком.текст !== т) плохо('текст комнаты ' + место.имя);
      continue;
    }
    if ((м = /^- \*\*(.+)\*\*$/.exec(л)) && место) {
      const ком = Object.values(место.КОМНАТЫ)[0];
      const { текст: т } = собрать(после(n));
      имена.push(м[1]);
      привязок++;
      const дт = ком.детали.find(d => d.имя === м[1]);
      if (!дт || дт.текст !== т) плохо(`деталь «${м[1]}» ${место.имя}`);
      continue;
    }
    // вступление, отговорка
    if (/^Вступление:$/.test(л) && человек) {
      привязок++;
      if (место.ЛЮДИ[человек].вступление !== собрать(после(n)).текст) плохо(`вступление ${человек}`);
      continue;
    }
    if (/^Отговорка/.test(л) && человек) {
      привязок++;
      if (место.ОТГОВОРКИ[человек] !== собрать(после(n)).текст) плохо(`отговорка ${человек}`);
      continue;
    }
    // «За прилавком · ей заходит **прямо**»
    if ((м = /^(.+) · (?:ей|ему) заходит \*\*(.+)\*\*\.$/.exec(л)) && человек) {
      привязок++;
      if (место.ЛЮДИ[человек].место !== м[1] || место.ЛЮДИ[человек].любит !== м[2]) плохо(`«место · любит» у ${человек}`);
      continue;
    }
    // реплика по теме и тону
    if ((м = /^(?:\*\*(\w+)\*\* — )?(прямо|мягко|деньгами|любой)(?: \((.*)\))?:$/.exec(л)) && человек) {
      if (м[1]) тема = м[1];
      const тон = м[2], пометки = м[3] ?? '';
      const { текст: т } = собрать(после(n));
      привязок++;
      const узел = место.Р[человек]?.[тема]?.[тон];
      if (!узел) { плохо(`нет узла ${человек}/${тема}/${тон}`); continue; }
      if (узел.т !== т) плохо(`реплика ${человек}/${тема}/${тон}`);
      const э = узел.э ?? {};
      const рас = /расположение \+1/.test(пометки);
      if (рас !== ((э.распол?.[человек] ?? 0) === 1)) плохо(`расположение ${человек}/${тема}/${тон}: в файле «${пометки}»`);
      const м5 = /−(\d+) гр\./.exec(пометки);
      if ((м5 ? -Number(м5[1]) : 0) !== (э.гроши ?? 0)) плохо(`деньги ${человек}/${тема}/${тон}`);
      if (/\*\*подтверждает\*\*/.test(пометки) !== !!э.подтвердить) плохо(`«подтверждает» ${человек}/${тема}/${тон}`);
      if (/\*\*опровергает\*\*/.test(пометки) !== !!э.опровергнуть) плохо(`«опровергает» ${человек}/${тема}/${тон}`);
      const дает = /даёт тему `(\w+)`/.exec(пометки);
      if ((узел.тема ?? null) !== (дает ? дает[1] : null)) плохо(`«даёт тему» ${человек}/${тема}/${тон}`);
      if (э.подтвердить && э.подтвердить !== тема) плохо(`подтверждает не ту тему ${человек}/${тема}`);
      if (э.опровергнуть && э.опровергнуть !== тема) плохо(`опровергает не ту тему ${человек}/${тема}`);
      continue;
    }
    // обмен у Сибиллы
    if ((м = /^- (.+?):$/.exec(л)) && место === АПТЕКА) {
      const пара = ОБМЕН.find(([начало]) => м[1].startsWith(начало));
      if (пара) {
        привязок++;
        if (АПТЕКА.обмен.ответы[пара[1]] !== собрать(после(n)).текст) плохо(`ответ обмена «${пара[1]}»`);
      }
      continue;
    }
    // таверна: слухи, вход, уши, кружка; баня: попариться, подпись тона
    const ц = () => собрать(после(n)).текст;
    if (место === ТАВЕРНА || место === БАНЯ || место === АПТЕКА) {
      if (/^Строка у входа/.test(л)) { привязок++; if (ТАВЕРНА.вход.строка !== ц()) плохо('строка у входа'); }
      else if ((м = /^(\w+):$/.exec(л)) && ТАВЕРНА.слухи.темы.some(x => x.тема === м[1])) {
        привязок++;
        if (ТАВЕРНА.слухи.темы.find(x => x.тема === м[1]).текст !== ц()) плохо('слух ' + м[1]);
      } else if (/^Кончились:$/.test(л)) { привязок++; if (ТАВЕРНА.слухи.кончились !== ц()) плохо('«кончились»'); }
      else if (/^\*\*Уши Ножей\*\*/.test(л)) { привязок++; if (ТАВЕРНА.уши.строка !== ц()) плохо('строка про уши'); }
      else if (/^\*\*Взять кружку\*\*/.test(л)) {
        привязок++; имена.push('Взять кружку');
        const а = ТАВЕРНА.КОМНАТЫ.zal.действия.find(x => x.текст === 'Взять кружку');
        if (!а || а.эффект.реплика !== ц() || а.стоит !== 3 || а.эффект.распол?.hozyain !== 1) плохо('«Взять кружку»');
      } else if (/^\*\*Попариться\*\*/.test(л)) {
        привязок++; имена.push('Попариться');
        const а = БАНЯ.КОМНАТЫ.parilka.действия.find(x => x.текст === 'Попариться');
        if (!а || а.эффект.реплика !== ц() || а.эффект.тепло !== 3 || а.эффект.отдых !== 1) плохо('«Попариться»');
      } else if (/^Подпись неактивного тона/.test(л)) { привязок++; if (БАНЯ.безТона.почему !== собрать(после(n)).текст) плохо('подпись тона «деньгами»'); }
      else if (/^\*\*Сидеть и слушать\*\*/.test(л)) имена.push('Сидеть и слушать');
    }
  }
}
for (const н of имена) if (!данные.has(н) && !Object.values(БАНЯ.КОМНАТЫ).concat(Object.values(ТАВЕРНА.КОМНАТЫ), Object.values(АПТЕКА.КОМНАТЫ)).some(к => к.действия.some(д => д.текст === н)))
  плохо(`название не найдено в данных: ${н}`);

// ── 3. своих длинных текстов в данных нет
const разрешено = new Set([...цитаты.map(ц => ц.текст), ...фразы, ...имена]);
const СЛУЖЕБНЫЕ = /^(radial-gradient|linear-gradient|faces\/|port\/)/;
for (const с of данные) {
  if (с.length < 25 || СЛУЖЕБНЫЕ.test(с) || разрешено.has(с)) continue;
  плохо(`в данных свой текст, которого нет в файле: ${с.slice(0, 70)}`);
}

console.log(`Цитат в файле: ${цитаты.length}; фраз: ${фразы.length}; привязок проверено: ${привязок}; строк данных: ${данные.size}.`);
if (цитаты.length !== 75 || фразы.length !== 24) ошибки.push(`ожидалось 75 цитат и 24 фразы, разобрано ${цитаты.length} и ${фразы.length}`);
if (ошибки.length) {
  console.log('\nРАСХОЖДЕНИЯ:');
  for (const е of ошибки.slice(0, 30)) console.log('- ' + е);
  process.exit(1);
}
console.log('Сверка прошла: каждая цитата и каждая фраза побуквенно в данных и на своём месте, лишних текстов нет.');
