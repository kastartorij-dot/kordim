// Тест этапа 5: node Порт/тест/вещи.mjs
// Пирог с собой, восемь слотов, «Съесть», сцена, миграция 1 → 6, сводки героя и журнала.
import { новоеСостояние, мигрировать, ВЕРСИЯ } from '../движок/состояние.js';
import { доступныеДействия } from '../движок/действия.js';
import { действияВещей, слоты, имяВещи } from '../движок/вещи.js';
import { сводкаГероя, сводкаЖурнала } from '../движок/сводка.js';
import { ТЕЛО } from '../данные/состояния.js';
import { потратитьОтрезок } from '../движок/время.js';

const ошибки = [];
const жди = (усл, что) => { if (!усл) ошибки.push(что); };
const рынок = () => { const S = новоеСостояние('семья', 1); S.мир.район = 'торговый'; S.мир.отрезок = 'день'; S.герой.кошель = 100; return S; };
const собой = S => доступныеДействия(S).find(a => a.id === 'еда-собой:пирог');

// 1. пирог с собой кладётся в слот, стоит 4 гр., не ест и не тратит отрезок
{
  const S = рынок(); S.герой.тело.сыт = 1;
  const а = собой(S);
  жди(а && а.текст === 'Пирог с собой', 'на рынке нет действия «Пирог с собой»');
  жди(а && а.можно && а.цена === 4, 'пирог с собой: цена не 4 или неактивен');
  const до = { кошель: S.герой.кошель, сыт: S.герой.тело.сыт, отрезок: S.мир.отрезок };
  а.выполнить(S);
  жди(до.кошель - S.герой.кошель === 4, 'пирог с собой стоит не 4 гр.');
  жди(S.герой.при_себе.length === 1 && S.герой.при_себе[0] === 'пирог', 'пирог не лёг в слот');
  жди(S.герой.тело.сыт === до.сыт, 'пирог с собой съеден на месте');
  жди(S.мир.отрезок === до.отрезок, 'пирог с собой потратил отрезок');
  жди(доступныеДействия(S).some(x => x.id === 'еда:пирог'), 'обычный «Пирог с рынка» пропал');
}

// 2. девятый не кладётся
{
  const S = рынок();
  for (let i = 0; i < 8; i++) { const а = собой(S); жди(а.можно, `пирог №${i + 1} не кладётся`); а.выполнить(S); }
  жди(S.герой.при_себе.length === 8, 'в слотах не восемь пирогов');
  const а = собой(S);
  жди(!а.можно && а.почему === 'некуда положить', 'девятый пирог не заблокирован с причиной «некуда положить»');
  const было = S.герой.кошель;
  жди(слоты(S).every(x => x === 'пирог') && слоты(S).length === 8, 'слоты: не восемь занятых');
  жди(S.герой.кошель === было, 'деньги ушли на неположенный пирог');
}

// 3. «Съесть»: сыт +2, не выше 3, 0 отрезков, строка в журнал; в сцене нельзя
{
  const S = рынок(); S.герой.тело.сыт = 1;
  собой(S).выполнить(S);
  const е = действияВещей(S);
  жди(е.length === 1 && е[0].текст === 'Съесть' && е[0].можно, 'в «Вещах» нет «Съесть»');
  const до = { отрезок: S.мир.отрезок, день: S.мир.день, журнал: S.мир.журналДня.length };
  е[0].выполнить(S);
  жди(S.герой.тело.сыт === 3, `после «Съесть» сыт ${S.герой.тело.сыт}, ожидалось 3`);
  жди(S.мир.отрезок === до.отрезок && S.мир.день === до.день, '«Съесть» потратил отрезок');
  жди(S.мир.журналДня.length === до.журнал + 1, '«Съесть» не дописал строку в журнал дня');
  жди(S.герой.при_себе.length === 0, 'пирог остался в слоте после «Съесть»');
}
{
  const S = рынок(); S.герой.тело.сыт = 2; собой(S).выполнить(S);
  действияВещей(S)[0].выполнить(S);
  жди(S.герой.тело.сыт === 3, 'сыт выше 3 или не дорос до 3 при сыт 2');
}
{
  const S = рынок(); собой(S).выполнить(S);
  S.сцена = { место: 'аптека' }; // внутри места
  const е = действияВещей(S)[0];
  жди(е && !е.можно && е.почему, 'в сцене места «Съесть» доступно');
}

// 4. незнакомая вещь (нож, жетон) — не падает, есть нельзя
{
  const S = рынок(); S.герой.при_себе = ['нож', 'жетон'];
  жди(действияВещей(S).length === 0, 'нож и жетон получили «Съесть»');
  жди(слоты(S)[0] === 'нож' && имяВещи('нож') === 'нож', 'незнакомая вещь не показана по id');
  try { сводкаГероя(S); сводкаЖурнала(S); } catch (e) { ошибки.push('сводка упала с ножом при себе: ' + e.message); }
}

// 5. миграция 1 → 7 (и с каждой промежуточной версии)
{
  const v1 = () => { const S = новоеСостояние('бумаги', 5); S.версия = 1; for (const к of ['журналДня', 'сид', 'отключкаДень', 'знания', 'ушло', 'хроника', 'места', 'люди']) delete S.мир[к]; for (const к of ['серии', 'холод1', 'жильё', 'при_себе']) delete S.герой[к]; delete S.сцена; delete S.история; S.мир.темы = []; return S; };
  try {
    const S = мигрировать(v1());
    жди(S.версия === 7 && ВЕРСИЯ === 7, 'миграция 1 → 7 не довела до версии 7');
    жди(Array.isArray(S.мир.хроника) && S.мир.хроника.length === 0, 'после миграции нет хроники');
    жди(Array.isArray(S.герой.при_себе), 'после миграции нет при_себе');
    жди(S.мир.знания && S.мир.ушло, 'после миграции нет знаний');
    сводкаГероя(S); сводкаЖурнала(S); доступныеДействия(S);
  } catch (e) { ошибки.push('миграция 1 → 7 упала: ' + e.message); }
  for (const в of [2, 3, 4, 5]) {
    try { const S = новоеСостояние('семья', 1); S.версия = в; delete S.мир.хроника; delete S.герой.при_себе; const М = мигрировать(S); жди(М.версия === 7 && Array.isArray(М.герой.при_себе) && Array.isArray(М.мир.хроника), `миграция ${в} → 7`); }
    catch (e) { ошибки.push(`миграция ${в} → 7 упала: ${e.message}`); }
  }
}

// 6. хроника: три последних итога, старые выпадают
{
  const S = новоеСостояние('семья', 1);
  for (let д = 0; д < 5; д++) { S.мир.отрезок = 'ночь'; потратитьОтрезок(S); S.мир.конецДня = null; }
  жди(S.мир.хроника.length === 3, `в хронике ${S.мир.хроника.length} итогов, ожидалось 3`);
  жди(S.мир.хроника.map(х => х.день).join() === '3,4,5', `хроника хранит дни ${S.мир.хроника.map(х => х.день)}, ожидалось 3,4,5`);
}

// 7. сводка героя: строки состояний из таблицы, «в порядке» на 3 и 2
{
  const S = новоеСостояние('семья', 1);
  for (const к of Object.keys(ТЕЛО)) for (const з of [3, 2, 1, 0]) {
    S.герой.тело[к] = з;
    const с = сводкаГероя(S).тело.find(x => x.ключ === к);
    const ожид = з >= 2 ? 'в порядке' : ТЕЛО[к][з];
    жди(с.строка === ожид, `тело ${к}=${з}: строка «${с.строка}»`);
  }
  S.мир.тень = 2; S.мир.репутация = -1; S.мир.фракции.ножи = -3;
  const с = сводкаГероя(S);
  жди(с.положение.тень.строка === 'За тобой ходят.', 'тень 2');
  жди(с.положение.репутация.слово === 'сомнительная', 'репутация −1');
  жди(с.положение.фракции[0].слово === 'в их район ночью лучше не ходить', 'фракция −3');
  жди(с.жильё === 'нет', 'жильё «нет»');
  S.герой.жильё = { id: 'вдова', оплачено_по: 9 };
  жди(сводкаГероя(S).жильё === 'Комната у вдовы, оплачено до дня 9', 'жильё у вдовы');
}

if (ошибки.length) { console.log('ПРОВАЛ:\n- ' + ошибки.join('\n- ')); process.exit(1); }
console.log('Все проверки пройдены: пирог с собой (4 гр., слот, без отрезка), девятый не кладётся, «Съесть» (+2, не выше 3, без отрезка, в сцене нельзя), незнакомая вещь, миграции 1…6 → 7, хроника на три дня, строки состояний.');
