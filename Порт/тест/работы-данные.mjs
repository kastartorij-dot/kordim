// Проверка данных работ без запуска игры: node Порт/тест/работы-данные.mjs
// Ловит опечатки, которые иначе всплывут через десять дней игры: неизвестная тема или вещь, флаг, который никто не ставит,
// повторный id, случай без выхода, нить без условия, лишние поля. Невнедрённые
// сюжетные нити здесь не проверяются на достижимость.
import { РАБОТЫ } from '../данные/работы.js';
import { РЕЕСТР } from '../данные/темы.js';
import { ВЕЩИ } from '../данные/вещи.js';
import { СТУПЕНИ } from '../движок/ремёсла.js';

const ошибки = [];
const жди = (ок, с) => { if (!ок) ошибки.push(с); };
const ставят = new Set(), проверяют = new Set(), ids = new Set();
const КЛЮЧИ_ЭФФЕКТА = new Set(['гроши', 'тело', 'вид', 'фракции', 'репутация', 'тень', 'тема', 'подтвердить', 'опровергнуть', 'распол', 'дом',
  'флаг', 'снятьФлаг', 'вещь', 'убратьВещь', 'услуга', 'зарубки', 'потерятьОтрезок', 'строка', 'счётчик', 'отметка', 'урок', 'обещание',
  'нарушитьОбещание', 'продатьЛичные', 'шанс', 'тогда', 'иначе']);
const КЛЮЧИ_УСЛОВИЯ = new Set(['день', 'рынок', 'нечётный', 'район', 'отрезок', 'смен', 'ремесло', 'безРемесла', 'тема', 'безТемы', 'верность', 'ушло',
  'флаг', 'нетФлага', 'фракция', 'репутация', 'тень', 'тело', 'вид', 'деньги', 'распол', 'предмет', 'безПредмета', 'дом', 'счётчик', 'прошло']);
const ЛЮДИ_ЭФФЕКТА = new Set();

function эфф(э, где) {
  if (!э) return;
  if (Array.isArray(э)) return э.forEach(x => эфф(x, где));
  for (const к of Object.keys(э)) жди(КЛЮЧИ_ЭФФЕКТА.has(к), `${где}: неизвестное поле эффекта «${к}»`);
  if (э.тема) { const id = typeof э.тема === 'string' ? э.тема : э.тема.id; жди(РЕЕСТР[id], `${где}: тема «${id}» не в реестре`); }
  for (const к of ['подтвердить', 'опровергнуть']) if (э[к]) жди(РЕЕСТР[э[к]], `${где}: тема «${э[к]}» не в реестре`);
  if (э.вещь) жди(ВЕЩИ[э.вещь], `${где}: вещь «${э.вещь}» не в реестре`);
  if (э.флаг) [].concat(э.флаг).forEach(ф => ставят.add(ф));
  if (э.шанс !== undefined) { жди(э.шанс > 0 && э.шанс < 1, `${где}: шанс вне (0,1)`); эфф(э.тогда, где); эфф(э.иначе, где); }
  if (э.гроши) жди(Math.abs(э.гроши) <= 40, `${где}: гроши ${э.гроши} — слишком много для смены`);
  if (э.зарубки) жди(СТУПЕНИ && э.зарубки.ремесло, `${где}: зарубки без ремесла`);
}
function усл(у, где) {
  if (!у) return;
  for (const к of Object.keys(у)) жди(КЛЮЧИ_УСЛОВИЯ.has(к), `${где}: неизвестное поле условия «${к}»`);
  for (const к of ['флаг', 'нетФлага']) if (у[к]) [].concat(у[к]).forEach(ф => проверяют.add(ф));
  if (у.тема) жди(РЕЕСТР[у.тема], `${где}: тема «${у.тема}» не в реестре`);
  if (у.безТемы) жди(РЕЕСТР[у.безТемы], `${где}: тема «${у.безТемы}» не в реестре`);
}
function текст(т, где) {
  // Нейтральный первый пакет намеренно использует короткие, но непустые строки.
  if (typeof т === 'string') return жди(т.trim().length > 0, `${где}: пустой текст`);
  жди(Array.isArray(т) && т.length, `${где}: текст ни строка, ни список`);
  for (const к of t_(т)) if (typeof к !== 'string') { усл(к.если, где); жди(typeof к.т === 'string', `${где}: кусок без «т»`); }
}
const t_ = т => (Array.isArray(т) ? т : []);

for (const р of РАБОТЫ) {
  жди(!ids.has(р.id), `работа ${р.id} повторяется`); ids.add(р.id);
  жди(р.когда?.length && р.где, `${р.id}: нет где/когда`);
  жди(!р.ремесло || р.ремесло === 'грузчик' || р.ремесло === 'грамота' || р.ремесло === 'наколки' || р.ремесло === 'кулак', `${р.id}: ремесло «${р.ремесло}» без обучения`);
  if (р.допуск) { const { почему, ...д } = р.допуск; усл(д, `${р.id}.допуск`); жди(почему || р.ученичество || !р.допуск.ремесло, `${р.id}: у допуска нет «почему»`); } усл(р.скрыто, `${р.id}.скрыто`);
  if (р.премияФлаг) проверяют.add(р.премияФлаг.флаг);
  const случаи = new Set();
  for (const с of р.колода) {
    const где = `${р.id}/${с.id}`;
    жди(!случаи.has(с.id), `${где}: id повторяется`); случаи.add(с.id);
    жди(!ids.has(с.id), `${где}: id совпал с другой колодой`); ids.add(с.id);
    текст(с.текст, где); усл(с.условие, где); эфф(с.эффект, где);
    жди(!с.нить || с.условие, `${где}: нить без условия`);
    for (const [i, о] of (с.выбор ?? []).entries()) {
      жди(о.итог !== undefined, `${где}#${i}: у выбора нет итога`);
      if (о.итог) текст(о.итог, `${где}#${i}`);
      усл(о.условие, `${где}#${i}`); эфф(о.эффект, `${где}#${i}`);
    }
    if (с.выбор) жди(с.выбор.length >= 2, `${где}: выбор из одного не выбор`);
  }
  if (р.ставка) for (const с of р.ставка.соперники) { усл(с.условие, `${р.id}/${с.id}`); эфф(с.победа.эффект, `${р.id}/${с.id}`); эфф(с.поражение.эффект, `${р.id}/${с.id}`); жди(с.победа.тексты.length && с.поражение.тексты.length, `${р.id}/${с.id}: нет текстов боя`); }
}
// флаг, что проверяют, но никто не ставит (кроме ставящихся кодом или диалогами мест)
// Четыре крючка сюжетных нитей оставлены в схеме, но сами нити не приняты и
// не внедрены. Пока они могут прийти только из будущих диалогов/дел.
const СНАРУЖИ = new Set(['совет_бойца', 'спросил_про_смерть',
  'весы_закрыты', 'весовщик_ножей', 'чтец_молчит', 'кухня_открыта']);
for (const ф of проверяют) жди(ставят.has(ф) || СНАРУЖИ.has(ф), `флаг «${ф}» проверяют, но никто не ставит`);
// денежная дисциплина: среднее по обычным случаям каждой колоды не больше +2 гр. за смену
for (const р of РАБОТЫ) {
  const обычные = р.колода.filter(с => !с.нить && !с.выбор);
  if (!обычные.length) continue;
  const в = обычные.reduce((а, с) => а + (с.вес ?? 1) * ((Array.isArray(с.эффект) ? с.эффект : [с.эффект]).reduce((г, э) => г + (э?.гроши ?? 0), 0)), 0);
  const w = обычные.reduce((а, с) => а + (с.вес ?? 1), 0);
  жди(в / w <= 2, `${р.id}: обычные случаи дают в среднем ${(в / w).toFixed(1)} гр. за смену — больше двух`);
}
if (ошибки.length) { console.log('ПРОВАЛ:\n- ' + ошибки.join('\n- ')); process.exit(1); }
console.log(`Данные работ в порядке: ${РАБОТЫ.length} работ, ${РАБОТЫ.reduce((а, р) => а + р.колода.length, 0)} случаев.`);
