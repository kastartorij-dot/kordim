import assert from 'node:assert/strict';
import { новоеСостояние, мигрировать, сохранить, загрузить, списокСохранений, ВЕРСИЯ } from '../движок/состояние.js';
import { добавитьОчки, бюджетВлияния } from '../движок/положение.js';
import { доступныеДействия } from '../движок/действия.js';
import { войти, действияСцены, вернутьсяВГород } from '../движок/разговор.js';
import { следующийОтрезок, потратитьОтрезок, снимокТела } from '../движок/время.js';
import { взятьОбязательство, закрытьОбязательство } from '../движок/сроки.js';
import { применитьЭффект } from '../движок/эффекты.js';
import { положить, получитьОтложенное, найтиВещь } from '../движок/вещи.js';
import { передатьВещь } from '../движок/хозяйство.js';
import { поставитьСобытие, начатьСобытие, завершитьСобытие } from '../движок/очередь.js';

const память = new Map();
globalThis.localStorage = {
  getItem: k => память.get(k) ?? null,
  setItem: (k, v) => память.set(k, String(v)),
  removeItem: k => память.delete(k),
};
const новый = () => новоеСостояние('семья', 42);

{
  const S = новый(); S.версия = 6;
  S.мир.очки = { ножи: 0, картель: 0, братство: 0, репутация: 0 };
  S.мир.фракции.ножи = -2; S.мир.репутация = -1;
  мигрировать(S);
  assert.equal(S.версия, ВЕРСИЯ);
  assert.equal(S.мир.очки.ножи, -5);
  assert.equal(S.мир.очки.репутация, -2);
  assert.equal(S.мир.фракции.ножи, -2);
}
{
  const S = новый(); S.версия = 9;
  S.мир.фракции.картель = -1; S.мир.очки.картель = 0;
  мигрировать(S);
  assert.equal(S.мир.очки.картель, -2, 'уже мигрировавший старый слот тоже восстановлен');
}
{
  const S = новый();
  assert.equal(бюджетВлияния(S), 14);
  добавитьОчки(S, 'ножи', 8, 'нить');
  добавитьОчки(S, 'картель', 8, 'нить');
  assert.notDeepEqual([S.мир.фракции.ножи, S.мир.фракции.картель], [2, 2]);
  применитьЭффект(S, { бюджетВлияния: 20 });
  assert.equal(бюджетВлияния(S), 20);
  добавитьОчки(S, 'ножи', 2, 'нить');
  assert.deepEqual([S.мир.фракции.ножи, S.мир.фракции.картель], [2, 2]);
  добавитьОчки(S, 'братство', 8, 'нить');
  assert.notDeepEqual(Object.values(S.мир.фракции), [2, 2, 2], 'три союза +2 одновременно недоступны');
  сохранить(S, 1);
  assert.equal(бюджетВлияния(загрузить(1)), 20);
}
{
  const S = новый();
  добавитьОчки(S, 'ножи', 15, 'смена');
  assert.equal(S.мир.фракции.ножи, 2, 'работа не даёт ступень +3');
  добавитьОчки(S, 'ножи', 7, 'нить');
  assert.equal(S.мир.фракции.ножи, 3, 'ступень +3 требует сюжетного источника');
}
{
  const S = новый(); S.мир.район = 'торговый'; S.герой.кошель = 100;
  const купить = доступныеДействия(S).find(x => x.id === 'купить:бинт');
  assert.ok(купить?.можно);
  купить.выполнить(S);
  const после = S.герой.кошель;
  купить.выполнить(S);
  assert.equal(S.герой.кошель, после, 'старая городская кнопка не платит дважды');
  сохранить(S, 'авто');
  const загружено = загрузить('авто');
  assert.equal(загружено.герой.кошель, после);
  assert.equal(загружено.герой.при_себе.length, 1);
}
{
  const S = новый(); S.мир.отрезок = 'вечер'; S.герой.кошель = 100;
  войти(S, 'таверна');
  const кружка = действияСцены(S).find(x => x.текст === 'Взять кружку');
  assert.ok(кружка?.можно);
  кружка.выполнить(S);
  const после = { кошель: S.герой.кошель, ходы: S.сцена.ходы };
  кружка.выполнить(S);
  assert.deepEqual({ кошель: S.герой.кошель, ходы: S.сцена.ходы }, после);
  действияСцены(S).find(x => x.id === 'заговорить:hozyain').выполнить(S);
  сохранить(S, 2);
  const загружено = загрузить(2);
  assert.equal(загружено.сцена.ходы, 1);
  assert.equal(загружено.герой.кошель, 97);
  assert.equal(загружено.сцена.собеседник, 'hozyain');
  assert.ok(действияСцены(загружено).some(x => x.id.startsWith('тема:')));
}
{
  const S = новый(); S.мир.день = 5; S.мир.отрезок = 'день';
  assert.equal(взятьОбязательство(S, { id: 'до-вечера', срок: { день: 5, отрезок: 'вечер' } }), true);
  следующийОтрезок(S);
  assert.equal(S.мир.обязательства['до-вечера'].статус, 'истекло');
  assert.equal(закрытьОбязательство(S, 'до-вечера'), false);
  assert.equal(взятьОбязательство(S, { id: 'конец-вечера', срок: { день: 5, отрезок: 'вечер', граница: 'конец' } }), true);
  войти(S, 'таверна');
  assert.equal(S.мир.отрезок, 'ночь');
  assert.equal(S.мир.обязательства['конец-вечера'].статус, 'активно', 'вечерняя сцена ещё идёт');
  assert.equal(взятьОбязательство(S, { id: 'визит', срок: { визит: 'текущий' } }), true);
  assert.equal(закрытьОбязательство(S, 'конец-вечера'), true);
  вернутьсяВГород(S);
  assert.equal(S.мир.обязательства.визит.статус, 'истекло');
  assert.equal(S.мир.обязательства['конец-вечера'].статус, 'выполнено');
}
{
  const S = новый(); S.мир.день = 5; S.мир.отрезок = 'ночь';
  взятьОбязательство(S, { id: 'до-конца-дня', срок: { день: 5, отрезок: 'ночь', граница: 'конец' } });
  assert.equal(S.мир.обязательства['до-конца-дня'].статус, 'активно');
  следующийОтрезок(S);
  assert.equal(S.мир.обязательства['до-конца-дня'].статус, 'истекло');
  assert.ok(S.мир.конецДня.журнал.some(x => x.includes('срок истёк')));
  S.мир.конецДня = null; // игрок закрыл утренний итог
  const передышка = доступныеДействия(S).find(x => x.id === 'передышка:после-ночи');
  assert.ok(передышка?.можно);
  const было = S.герой.тело.отдых;
  передышка.выполнить(S);
  assert.equal(S.герой.тело.отдых, Math.min(3, было + 1));
  assert.equal(S.мир.отрезок, 'день');
  передышка.выполнить(S);
  assert.equal(S.мир.отрезок, 'день');
}
{
  const S = новый();
  for (let i = 0; i < 8; i++) assert.equal(положить(S, 'пирог'), true);
  применитьЭффект(S, { один: 'награда', вещь: 'письмо', гроши: 5 });
  применитьЭффект(S, { один: 'награда', вещь: 'письмо', гроши: 5 });
  assert.equal(S.мир.отложенныеВещи.length, 1);
  assert.equal(S.герой.кошель, 65, 'одноразовая награда не повторяется');
  сохранить(S, 3);
  const загружено = загрузить(3);
  загружено.герой.при_себе.pop();
  assert.equal(получитьОтложенное(загружено, загружено.мир.отложенныеВещи[0].номер), true);
  assert.equal(загружено.мир.отложенныеВещи.length, 0);
  assert.ok(загружено.герой.при_себе.some(x => x.тип === 'письмо'));
}
{
  const S = новый(); S.мир.район = 'доки';
  const работа = доступныеДействия(S).find(x => x.id === 'работа:разгрузка');
  assert.ok(работа?.можно);
  работа.выполнить(S);
  сохранить(S, 1);
  const загружено = загрузить(1);
  assert.ok(загружено.мир.смена);
  const выбор = доступныеДействия(загружено).find(x => x.можно);
  выбор.выполнить(загружено);
  const итог = { кошель: загружено.герой.кошель, день: загружено.мир.день, отрезок: загружено.мир.отрезок };
  выбор.выполнить(загружено);
  assert.deepEqual({ кошель: загружено.герой.кошель, день: загружено.мир.день, отрезок: загружено.мир.отрезок }, итог);
}
{
  const S = новый(); S.мир.район = 'доки'; S.герой.тело.отдых = 1;
  доступныеДействия(S).find(x => x.id === 'работа:разгрузка').выполнить(S);
  доступныеДействия(S).find(x => x.можно).выполнить(S);
  assert.equal(S.мир.отрезок, 'день', 'усталость от смены не удваивает уже начатую смену');
}
{
  const S = новый(); S.герой.тело.отдых = 1;
  const старт = снимокТела(S);
  S.герой.тело.отдых = 0; // цена действия списана перед ходом времени
  потратитьОтрезок(S, старт);
  assert.equal(S.мир.отрезок, 'день', 'время считают по состоянию до цены действия');
}
{
  const S = новый(); S.мир.отрезок = 'вечер';
  положить(S, 'пирог');
  const uid = S.герой.при_себе[0].uid;
  войти(S, 'таверна');
  S.сцена.собеседник = 'hozyain';
  assert.equal(передатьВещь(S, uid, 'hozyain'), true);
  сохранить(S, 2);
  const загружено = загрузить(2);
  assert.equal(найтиВещь(загружено, uid), null);
  assert.equal(передатьВещь(загружено, uid, 'hozyain'), false);
}
{
  const S = новый();
  assert.equal(поставитьСобытие(S, { id: 'весть', день: 7 }), true);
  assert.equal(поставитьСобытие(S, { id: 'весть', день: 7 }), false);
  assert.equal(начатьСобытие(S, 'весть'), true);
  сохранить(S, 1);
  const загружено = загрузить(1);
  assert.equal(загружено.мир.очередьСобытий[0].статус, 'идёт');
  assert.equal(завершитьСобытие(загружено, 'весть'), true);
  assert.equal(поставитьСобытие(загружено, { id: 'весть' }), false);
}
{
  память.set('порт-теней-слот-3', '{bad json');
  assert.equal(списокСохранений().find(x => x.слот === 3).ошибка, 'повреждено');
  assert.equal(загрузить(3), null);
  сохранить(новый(), 3);
  assert.ok([...память.keys()].some(x => x.startsWith('порт-теней-слот-3-резерв-')));
  память.set('порт-теней-слот-3', JSON.stringify({ версия: ВЕРСИЯ + 1, мир: {}, герой: {} }));
  assert.match(списокСохранений().find(x => x.слот === 3).ошибка, /новая версия/);
  assert.equal(загрузить(3), null);
}

