const нов = (начало = 'наколки', сид = 5) => {
  const S = новоеСостояние(начало, сид);
  S.мир.отрезок = 'вечер'; S.мир.район = 'торговый'; S.герой.кошель = 300;
  return S;
};
const кн = (S, т) => действияСцены(S).find(x => (x.текст ?? '').includes(т) && x.можно !== false);
const жми = (S, т) => { const а = кн(S, т); if (!а) throw new Error(`нет кнопки «${т}»: ` + действияСцены(S).map(x => x.текст).join(' | ')); а.выполнить(S); return S; };
const расп = S => S.мир.люди.sib?.распол ?? 0;
const вДом = S => { войти(S, 'синий-час'); жми(S, 'Держи. Двадцать'); жми(S, 'Войти.'); };
const ленты = S => (S.сцена.диалог?.лента ?? []).map(з => з.т).join('\n');

// ── 1. Вероятности честные: 2d6, перебор 36 исходов ───────────────────────────
{
  assert.equal(шанс(8, 0), 42); assert.equal(шанс(6, 0), 72); assert.equal(шанс(10, 0), 17); assert.equal(шанс(12, 0), 3);
  assert.equal(шанс(8, 2), 72); assert.equal(шанс(8, 5), 97); assert.equal(шанс(12, -2), 0);
  assert.deepEqual(Object.keys(ПОРОГИ).sort(), ['лёгко', 'оченьТрудно', 'средне', 'трудно'].sort());
  // Бросок зависит только от (зерно, id, попытка): ни номер вызова, ни порядок не влияют.
  assert.deepEqual(кубики(77, 'колено', 1), кубики(77, 'колено', 1));
  assert.notDeepEqual([кубики(77, 'колено', 1), кубики(77, 'колено', 2)].map(String).filter((v, i, a) => a.indexOf(v) === i).length, 1, 'разные попытки обязаны давать разные броски хоть иногда');
  // Распределение суммы близко к треугольному: 7 — самая частая.
  const счёт = {};
  for (let i = 0; i < 6000; i++) { const [a, b] = кубики(1, 'x' + i, 1); счёт[a + b] = (счёт[a + b] ?? 0) + 1; }
  const мода = Object.entries(счёт).sort((a, b) => b[1] - a[1])[0][0];
  assert.equal(мода, '7');
}

// ── 2. Белая проверка: без «ещё раз», пока ничего не изменилось; красная — одна ───────
{
  const S = нов(); const п = { голос: 'МЕРА', порог: 'средне', тип: 'белая' };
  S.мир.проверки = {};
  const первая = бросить(S, 'т:белая', п, {});
  const повтор = карточка(S, 'т:белая', п, {});
  if (!первая.успех) { assert.equal(повтор.можно, false); assert.match(повтор.почему, /ничего не изменилось/); }
  // Бросок — функция попытки: «загрузка» и «назад» дают тот же результат.
  const Б = JSON.parse(JSON.stringify(S));
  assert.deepEqual(кубики(Б.мир.зерноКампании, 'т:белая', 1), первая.кубики);
  // Зерно кампании никогда не меняется от действий игрока.
  const зерно = S.мир.зерноКампании;
  for (let i = 0; i < 20; i++) бросить(S, 'другая:' + i, { голос: 'ЧУТЬЁ', порог: 'трудно' }, {});
  assert.equal(S.мир.зерноКампании, зерно);

  // Красная: провал закрывает навсегда.
  S.мир.проверки = {};
  const красная = { голос: 'ДЫМ', порог: 'оченьТрудно', тип: 'красная' };
  let id = 0, итог;
  do { итог = бросить(S, 'к:' + (++id), красная, {}); } while (итог.успех && id < 200);
  assert.ok(!итог.успех, 'за 200 id очень трудная проверка обязана хоть раз провалиться');
  assert.equal(карточка(S, 'к:' + id, красная, {}).можно, false);
  assert.match(карточка(S, 'к:' + id, красная, {}).почему, /красная/);
}

// ── 3. Голоса: ≤ 2 на узел, строка не повторяется, голос молчит два узла ──────────
{
  const S = нов(); S.герой.тело.сыт = 0; S.герой.тело.тепло = 1; S.герой.тело.отдых = 1; S.герой.тело.цел = 1;
  assert.equal(громкость(S, 'БРЮХО'), 3); assert.equal(громкость(S, 'КОСТИ'), 2);
  assert.equal(громкость(нов(), 'БРЮХО'), 0, 'сытый герой не слышит БРЮХО');
  const канд = ['БРЮХО', 'КОСТИ', 'БРЮХО'].map((голос, i) => ({ ид: 'г' + i, голос, т: '…', приоритет: 1 }));
  const раз = выбратьГолоса(S, канд);
  assert.ok(раз.length <= 2); assert.equal(new Set(раз.map(в => в.голос)).size, раз.length, 'один голос дважды на экране');
  assert.equal(выбратьГолоса(S, [{ ид: 'г0', голос: 'БРЮХО', т: '…', приоритет: 1 }]).length, 0, 'одна строка не повторяется');
  assert.equal(выбратьГолоса(S, [{ ид: 'новая', голос: 'БРЮХО', т: '…', приоритет: 1 }]).length, 0, 'голос молчит следующие узлы');
  // Голос ремесла один: у грузчика звучит МЕРА, у тату-мастера ИГЛА; выученное позже голоса не добавляет.
  const гр = нов('семья'), на = нов('наколки'), гм = нов('бумаги');
  assert.deepEqual([ступеньГолоса(гр, 'МЕРА') > 0, ступеньГолоса(гр, 'ИГЛА') > 0, ступеньГолоса(гр, 'СТРОКА') > 0], [true, false, false]);
  assert.deepEqual([ступеньГолоса(на, 'ИГЛА') > 0, ступеньГолоса(на, 'МЕРА') > 0], [true, false]);
  assert.equal(ступеньГолоса(гм, 'СТРОКА') > 0, true);
  гр.герой.ремёсла.наколки = { ступень: 'мастер', зарубки: 0 };
  assert.equal(ступеньГолоса(гр, 'ИГЛА'), 0, 'второе ремесло не открывает второй голос ремесла');
}

// ── 4. Хаб: пустых кнопок нет, первая встреча короче, хаб открывается со второй ────
{
  const мёртвых = [];
  for (const кто of Object.keys(ЛЮДИ)) for (const т of Object.keys(ТЕМЫ)) if (!ТЕМЫ[т].всегда && !(Р[кто] || {})[т]) мёртвых.push(`${кто}/${т}`);
  // «Пустая кнопка» — тема, которую человек не знает, но игрок видит в списке.
  const S = нов(); S.герой.кошель = 300; войти(S, 'синий-час'); жми(S, 'Держи. Двадцать'); жми(S, 'Войти.');
  S.сцена.комната = 'zal'; // общий зал: Ола, Старшая, Ния, Дорр ...
  for (const а of действияСцены(S).filter(x => x.вид === 'заговорить')) {
    const кто = а.id.split(':')[1];
    а.выполнить(S);
    for (const т of действияСцены(S).filter(x => x.вид === 'тема')) assert.ok((Р[кто] || {})[т.тема] || ТЕМЫ[т.тема]?.всегда, `${кто}: пустая кнопка «${т.тема}»`);
    if (S.сцена.собеседник) жми(S, 'Отойти');
  }
  assert.ok(мёртвых.length > 0, 'тест не проверяет ничего, если мёртвых пар нет');

  // Сиб: первая встреча — вступление и две вежливые ветки; полный хаб — со второй.
  const П = нов(); вДом(П); жми(П, 'Заговорить с: Сиб');
  const первый = действияСцены(П).filter(x => x.вид === 'ветка').map(x => x.id);
  assert.deepEqual(первый.sort(), ['ветка:давно', 'ветка:правила'], 'на первой встрече только вежливые ветки: ' + первый);
  assert.ok(П.мир.люди.sib.знаком, 'знакомство — отдельный факт');
  жми(П, 'Отойти'); жми(П, 'Выйти и пойти домой'); жми(П, 'Выйти.'); вернутьсяВГород(П);
  П.мир.отрезок = 'вечер'; П.мир.район = 'торговый'; вДом(П); жми(П, 'Заговорить с: Сиб');
  const второй = действияСцены(П).filter(x => x.вид === 'ветка').map(x => x.id);
  assert.ok(второй.includes('ветка:наколки') && второй.length > первый.length, 'со второй встречи хаб полный: ' + второй);
  assert.match(ленты(П), /Он стоит там же/, 'повторная встреча у двери звучит иначе, чем первая');
}

// ── 5. Дверь и нож: сдать, спрятать, вернуть на выходе ───────────────────────────
{
  // сдать
  const S = нов(); положить(S, 'нож'); войти(S, 'синий-час');
  assert.match(ленты(S), /Оружие на стол/);
  assert.ok(!кн(S, 'Держи. Двадцать'), 'с ножом «просто заплатить» нет');
  const до = S.герой.кошель; жми(S, 'Выложить нож');
  assert.equal(S.герой.кошель, до - 20); assert.ok(!естьВещь(S, 'нож'), 'нож должен лежать в ящике');
  assert.deepEqual(S.сцена.сданныеВещи.map(x => x.тип), ['нож']);
  assert.ok(S.сцена.флагиВечера.includes('сдал_нож'), 'сдача ножа помечена на вечер');
  жми(S, 'Войти.'); жми(S, 'Выйти и пойти домой');
  assert.match(ленты(S), /Ящик\. Твоё/); жми(S, 'Выйти.'); вернутьсяВГород(S);
  assert.ok(естьВещь(S, 'нож'), 'нож возвращается на любом выходе');
  assert.deepEqual(S.герой.возвратСиба ?? [], []);

  // вечер кончился сам: ножа всё равно возвращается
  const В = нов(); положить(В, 'нож'); войти(В, 'синий-час'); жми(В, 'Выложить нож'); жми(В, 'Войти.');
  В.сцена.ходы = 99; жми(В, 'Выйти и пойти домой'); жми(В, 'Выйти.'); вернутьсяВГород(В);
  assert.ok(естьВещь(В, 'нож'));

  // красная проверка «Оружия нет»: перебор по зёрнам — обе ветки достижимы и обе корректны
  let ок = 0, нет = 0;
  for (let сид = 1; сид <= 120 && (ок === 0 || нет === 0); сид++) {
    const Т = нов('наколки', сид); положить(Т, 'нож'); войти(Т, 'синий-час');
    const к = кн(Т, 'Оружия нет'); assert.ok(к, 'при ножах и 40 грошах «спрятать» доступно'); assert.match(к.метка, /ДЫМ/);
    const г0 = Т.герой.кошель; к.выполнить(Т);
    if (Т.сцена.флагиВечера.includes('спрятал')) { ок++; assert.equal(Т.герой.кошель, г0 - 20); assert.ok(естьВещь(Т, 'нож')); }
    else { нет++; assert.equal(Т.герой.кошель, г0 - 40, 'провал красной стоит ещё двадцать'); assert.ok(!естьВещь(Т, 'нож')); assert.ok(Т.мир.диалоги.sib.факты.includes('попался_с_ножом')); }
  }
  assert.ok(ок > 0 && нет > 0, `оба исхода красной проверки достижимы (удач ${ок}, провалов ${нет})`);
  // красная одна на игру: после провала «спрятать» второй раз не бывает
  const Ч = нов('наколки', 1); Ч.мир.проверки['sib:вход:спрятать'] = { попыток: 1, модПровала: 0, итог: 'провал' };
  положить(Ч, 'нож'); войти(Ч, 'синий-час');
  const закрыто = действияСцены(Ч).find(x => x.текст?.includes('Оружия нет'));
  assert.equal(закрыто.можно, false);
}

// ── 6. Ветки: ходы платит вход, возврат бесплатен, награды один раз ───────────────
{
  const S = нов(); вДом(S); жми(S, 'Заговорить с: Сиб');
  const х0 = S.сцена.ходы, р0 = расп(S);
  жми(S, 'сколько ты здесь');
  assert.equal(S.сцена.ходы, х0 + 1, 'вход в ветку стоит ход'); const после = расп(S);
  assert.ok(после >= р0, 'манера «прямо» Сиб любит'); жми(S, 'Баржа'); жми(S, 'С воды'); const р1 = расп(S);
  assert.equal(S.сцена.диалог.режим, 'хаб');
  const х1 = S.сцена.ходы;
  жми(S, 'сколько ты здесь');
  assert.equal(S.сцена.ходы, х1, 'возврат в пройденную ветку бесплатен');
  assert.equal(расп(S), р1, 'доверие повторно не растёт');
  assert.match(ленты(S), /Четвёртый год/);
  // Ветка, на которую не хватает ходов, закрыта и объясняет почему (иначе вечер оборвётся посреди разговора).
  const П = нов(); П.мир.люди.sib = { спрошено: [], исчерпано: [], распол: 3, знаком: true }; П.мир.места['синий-час'] = { визитов: 4, осмотрено: [], дом: 0 };
  вДом(П); жми(П, 'Заговорить с: Сиб');
  П.сцена.ходы = 3;
  const поздно = действияСцены(П).find(x => x.id === 'ветка:поздно');
  assert.ok(поздно && поздно.можно, 'двухходовая ветка доступна, пока ходов хватает');
  assert.equal(поздно.подпись, '2 хода');
  П.сцена.ходы = 6 - 1; // в доме шесть ходов на вечер
  const мало = действияСцены(П).find(x => x.id === 'ветка:поздно');
  assert.equal(мало.можно, false); assert.match(мало.почему, /не успеть/);
}

// ── 7. Десять веток Сиба достижимы и каждая даёт узел ─────────────────────────────
{
  const ветки = Object.keys(ДИАЛОГ_СИБ.ветки);
  assert.deepEqual(ветки.sort(), ['вход', 'выход', 'давно', 'деньги', 'долги', 'колено', 'наколки', 'поздно', 'правила', 'хозяйка'].sort(), 'десять веток');
  for (const [id, в] of Object.entries(ДИАЛОГ_СИБ.ветки)) {
    assert.ok(в.узлы.старт, `${id}: нет стартового узла`);
    for (const [уид, у] of Object.entries(в.узлы)) {
      assert.ok(у.варианты?.length, `${id}/${уид}: нет вариантов — игрок застрянет`);
      assert.ok(у.варианты.some(x => x.закреплён || x.дальше || x.эффект?.финал), `${id}/${уид}: нет безопасного выхода`);
      for (const x of у.варианты) {
        const цели = [x.дальше, x.успех?.дальше, x.провал?.дальше].filter(Boolean);
        for (const ц of цели) if (typeof ц === 'string' && !['хаб', 'закрыть', 'назад'].includes(ц)) assert.ok(в.узлы[ц], `${id}/${уид}/${x.ид}: ведёт в несуществующий узел «${ц}»`);
        for (const ц of цели) if (ц?.ветка) assert.ok(ДИАЛОГ_СИБ.ветки[ц.ветка], `${id}/${уид}/${x.ид}: несуществующая ветка «${ц.ветка}»`);
        if (x.проверка) assert.ok(x.успех && x.провал, `${id}/${уид}/${x.ид}: у проверки нет успеха или провала`);
      }
    }
  }
  // Каждую ветку хаба можно открыть при подходящем доверии: проходим все варианты каждой
  const S = нов(); S.мир.люди.sib = { спрошено: [], исчерпано: [], распол: 3, знаком: true }; S.мир.места['синий-час'] = { визитов: 5, осмотрено: [], дом: 0 };
  S.мир.темы.push('nakolki');
  вДом(S); жми(S, 'Заговорить с: Сиб');
  const были = [];
  for (let круг = 0; круг < 12; круг++) {
    const в = действияСцены(S).find(x => x.вид === 'ветка' && x.можно && !были.includes(x.id));
    if (!в) break;
    были.push(в.id); S.сцена.ходы = 0; в.выполнить(S);
    for (let k = 0; k < 8 && S.сцена.диалог?.режим === 'ветка'; k++) {
      const а = действияСцены(S).find(x => x.вид === 'вариант' && x.можно && !x.закреплён) ?? действияСцены(S).find(x => x.вид === 'вариант' && x.можно);
      а.выполнить(S);
    }
    assert.equal(S.сцена.диалог?.режим, 'хаб', `ветка ${в.id} не вернула в хаб`);
  }
  assert.ok(были.length >= 7, 'в хабе при доверии 3 доступно не меньше семи веток: ' + были.join(', '));
}

// ── 8. Колено: правда не зависит от кубика ────────────────────────────────────────
{
  const исходы = new Set();
  for (let сид = 1; сид <= 80; сид++) {
    const S = нов('наколки', сид); S.мир.люди.sib = { спрошено: [], исчерпано: [], распол: 3, знаком: true }; S.мир.места['синий-час'] = { визитов: 3, осмотрено: [], дом: 0 };
    вДом(S); жми(S, 'Заговорить с: Сиб'); жми(S, 'колено');
    жми(S, 'Правую бережёшь');
    const т = ленты(S);
    исходы.add(S.мир.диалоги.sib.факты.includes('колено') ? 'успех' : 'провал');
    // и успех, и провал одинаково правдивы: ни в одном нет выдуманного «в бою ранили»
    assert.ok(!/ранили|клинок|удар ножом/.test(т), 'колено: выдуманная причина');
    if (S.мир.диалоги.sib.факты.includes('колено')) assert.match(т, /мешок соли.*сходне|шесть лет/is);
    else assert.match(т, /Давнее|не твоё/);
  }
  assert.equal(исходы.size, 2, 'оба исхода проверки достижимы');
  // Поздний узел «поздно» сам рассказывает про колено тем, кто не сумел прочитать (правда одна)
  const П = ДИАЛОГ_СИБ.ветки.поздно.узлы.колено.текст.join(' ');
  assert.match(П, /мешок соли на сходне/i); assert.match(П, /шесть лет назад/i);
}

