function точка(id, имя, район, старт, ходов, люди, комнаты, ответы, отговорка) {
  const ЛЮДИ = Object.fromEntries(Object.entries(люди).map(([ключ, ч]) => [ключ, {
    имя: ч.имя, место: ч.место ?? 'Здесь', любит: ч.любит ?? 'прямо', она: ч.она ?? false,
    портрет: ч.портрет ?? '', вступление: ч.вступление, ...(ч.условие ? { условие: ч.условие } : {}),
  }]));
  const Р = Object.fromEntries(Object.entries(ответы).map(([ключ, речи]) => [ключ,
    Object.fromEntries(Object.entries(речи).map(([тема, ответ]) => [тема, { любой: typeof ответ === 'string' ? { т: ответ, э: {} } : answer(ответ) }]))
  ]));
  const ТЕМЫ = { ni_o_chem: { ярлык: 'Ни о чём', всегда: true } };
  for (const речи of Object.values(ответы)) for (const тема of Object.keys(речи))
    if (тема !== 'ni_o_chem') ТЕМЫ[тема] = { ярлык: РЕЕСТР[тема]?.ярлык ?? тема.replaceAll('_', ' ') };
  return { id, имя, район, когда: [], ходов, старт, откат: 40, безСчёта: true,
    флагиВечера: [], ТЕМЫ, ФРАЗЫ: {}, ЛЮДИ, КОМНАТЫ: комнаты, Р,
    ОТГОВОРКИ: Object.fromEntries(Object.keys(люди).map(к => [к, отговорка])),
    ЭКРАН, КАРТИНКИ: { папкиЛиц: ['лица/'], папкиФонов: ['места/'] } };
}
function answer(о) { return { т: о.т, э: о.э ?? {}, ...(о.тема ? { тема: о.тема } : {}) }; }

