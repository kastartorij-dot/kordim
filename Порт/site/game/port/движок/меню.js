// Меню (ГДД §18: три слота + автосейв, загрузка в любой момент) и «Как играть».
// Работает с DOM; решения о состоянии принимает index.html через колбэки.
import { списокСохранений, ошибкаЗагрузки } from './состояние.js';
import { НАЧАЛА } from '../данные/герой.js';
import { ВСТУПЛЕНИЕ } from '../данные/вступление.js';

const окно = html => {
  document.querySelectorAll('.ов.меню').forEach(o => o.remove());
  const ов = document.createElement('div');
  ов.className = 'ов меню';
  ов.innerHTML = `<div class="овбокс меню-бокс">${html}</div>`;
  document.body.appendChild(ов);
  return ов;
};
const закрыть = () => document.querySelectorAll('.ов.меню').forEach(o => o.remove());

// Вступление и «Как играть» ничего не должны показывать из уже готового города за кадром —
// ни шапку с деньгами и телом, ни нижнюю панель «Город · Герой · Вещи · Журнал» (в отличие от
// меню/сохранений, где город за окном оставлен виден нарочно). Прячем сами узлы DOM (не их HTML),
// чтобы вернуть как было одной строкой и не терять навешанные на кнопки обработчики.
function прячемГород(да) {
  const hud = document.getElementById('hud'), панель = document.getElementById('панель');
  const шторкаТаб = document.getElementById('шторка-таб'), шторка = document.getElementById('шторка');
  if (hud) hud.hidden = да;
  if (панель) панель.style.display = да ? 'none' : '';
  if (шторкаТаб) шторкаТаб.style.display = да ? 'none' : '';
  if (шторка) шторка.style.display = да ? 'none' : '';
}

function подпись(с) {
  if (с.пусто) return 'пусто';
  if (с.ошибка) return `Нельзя загрузить: ${с.ошибка}`;
  const н = НАЧАЛА.find(x => x.id === с.начало);
  return `день ${с.день}, ${с.отрезок}${н ? ' · ' + н.имя.toLowerCase() : ''}`;
}

// колбэки: { загрузить(слот), сохранитьВ(слот), заново(), помощь() }
export function рендерМеню(есть, к) {
  const список = списокСохранений();
  const строка = с => `
    <div class="слот">
      <div><b class="px">${с.слот === 'авто' ? 'Автосейв' : 'Слот ' + с.слот}</b><br><span class="mono">${подпись(с)}</span></div>
      <div class="слот-кнопки">
        ${с.слот !== 'авто' && есть ? `<button class="b" data-сохр="${с.слот}">${с.ошибка ? 'Сохранить с резервной копией' : 'Сохранить сюда'}</button>` : ''}
        <button class="b" data-загр="${с.слот}" ${с.пусто || с.ошибка ? 'disabled' : ''}>Загрузить</button>
      </div>
    </div>`;
  const ов = окно(`
    <h2 class="px">Меню</h2>
    <p class="меню-мелко">Игра сама сохраняется в конце каждого дня (и на каждом шаге внутри места) — это автосейв. Слоты — чтобы отложить момент и вернуться к нему.</p>
    ${список.map(строка).join('')}
    <div class="меню-низ">
      <button class="b" id="меню-помощь">Как играть</button>
      <button class="b" id="меню-обновить" title="Если после правки игры страница показывает старое — сохранённое не потеряется">Обновить игру</button>
      <button class="b" id="меню-заново">Начать заново</button>
      <button class="b sin" id="меню-закрыть">Закрыть</button>
    </div>`);
  ов.querySelectorAll('[data-сохр]').forEach(b => b.onclick = () => {
    const n = Number(b.dataset.сохр);
    const цель = список.find(с => с.слот === n);
    const вопрос = цель.ошибка
      ? `Слот ${n} нельзя загрузить (${цель.ошибка}). Исходные данные будут сохранены отдельно перед записью. Продолжить?`
      : `Перезаписать слот ${n}?`;
    if (!цель.пусто && !confirm(вопрос)) return;
    к.сохранитьВ(n);
    рендерМеню(есть, к);
  });
  ов.querySelectorAll('[data-загр]').forEach(b => b.onclick = () => {
    const n = b.dataset.загр === 'авто' ? 'авто' : Number(b.dataset.загр);
    if (есть && !confirm('Загрузить? Несохранённое с последнего автосейва пропадёт.')) return;
    закрыть();
    к.загрузить(n);
  });
  ов.querySelector('#меню-заново').onclick = () => {
    if (!confirm('Начать заново? Автосейв сотрётся, слоты 1–3 останутся.')) return;
    закрыть();
    к.заново();
  };
  ов.querySelector('#меню-помощь').onclick = () => { закрыть(); к.помощь(); };
  ов.querySelector('#меню-закрыть').onclick = () => {
    закрыть();
    if (к.закрыть) к.закрыть();
  };
  // Перезагрузка с параметром, которого раньше не было в адресе, — браузер не подставит
  // старые файлы из своего кэша. Автосейв и слоты живут в localStorage по адресу страницы
  // (не по строке запроса), так что не пропадают.
  ов.querySelector('#меню-обновить').onclick = () => { location.href = location.pathname + '?обновлено=' + Date.now(); };
}

// Главное меню показывается при каждом запуске. Автосейв не теряется, но игра
// не открывает последний экран без явного выбора игрока.
export function рендерГлавноеМеню(есть, к) {
  прячемГород(true);
  const ов = окно(`
    <h1 class="px">Порт Теней</h1>
    <p class="меню-мелко">Портовая история о возвращении домой.</p>
    ${ошибкаЗагрузки() ? `<p class="меню-мелко">Автосохранение нельзя загрузить: ${ошибкаЗагрузки()}. При новой игре его исходные данные будут сохранены в резервной копии.</p>` : ''}
    <div class="меню-низ главное-меню-кнопки">
      <button class="b sin" id="главное-продолжить" ${есть ? '' : 'disabled'}>${есть ? 'Продолжить' : 'Продолжить (нет сохранения)'}</button>
      <button class="b" id="главное-новая">Новая игра</button>
      <button class="b" id="главное-загрузить">Загрузить</button>
      <button class="b" id="главное-помощь">Как играть</button>
    </div>`);
  ов.querySelector('#главное-продолжить').onclick = () => {
    if (!есть) return;
    закрыть();
    прячемГород(false);
    к.продолжить();
  };
  ов.querySelector('#главное-новая').onclick = () => {
    закрыть();
    к.новая();
  };
  ов.querySelector('#главное-загрузить').onclick = () => {
    закрыть();
    рендерМеню(есть, {
      ...к,
      закрыть: () => рендерГлавноеМеню(есть, к),
    });
  };
  ов.querySelector('#главное-помощь').onclick = () => {
    закрыть();
    рендерПомощь(() => рендерГлавноеМеню(есть, к));
  };
}

