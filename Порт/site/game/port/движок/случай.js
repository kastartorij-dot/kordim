// Случайность только отсюда (ГДД §21): зерно лежит в S.мир.сид, значит прогон воспроизводим.
// mulberry32. Возвращает число из [0, 1) и двигает зерно.
export function бросок(S) {
  let t = (S.мир.сид = (S.мир.сид + 0x6D2B79F5) >>> 0);
  t = Math.imul(t ^ (t >>> 15), t | 1);
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}
