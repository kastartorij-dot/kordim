// ---------- дела (Шаг 6, ещё не реализован) ----------
// Дела могут лежать массивом (ГДД §21: дела:[]) или словарём {id: {статус}}
// (Порт-Слухи-о-герое.md). Поддержаны оба вида.

export const СТАТУСЫ_ГОТОВО = ['готово', 'выполнено'];
export function списокДел(S) {
  const д = S.мир?.дела;
  if (!д) return [];
  return Array.isArray(д) ? д : Object.entries(д).map(([id, з]) => ({ id, ...з }));
}
export const делоГотово = (S, id) =>
  списокДел(S).some(з => з.id === id && СТАТУСЫ_ГОТОВО.includes(з.статус));

// «Помог не за деньги»: настоящая награда и настоящее решение (ПЛАН П08.6).
// КОНТРАКТ, который должен выдать Шаг 6: у закрытого дела типа «помощь» есть
// итог.выплата (число, 0 если денег не брали) и итог.выбор ('взял плату' / другое).
// Пока поля нет — функция возвращает false и запись дневника не срабатывает.
export function делоБезОплаты(з) {
  if (!СТАТУСЫ_ГОТОВО.includes(з.статус) || з.тип !== 'помощь') return false;
  const выплата = з.итог?.выплата ?? з.выплата;
  const выбор = з.итог?.выбор ?? з.выбор;
  return выплата === 0 && typeof выбор === 'string' && выбор.length > 0 && выбор !== 'взял плату';
}

// ---------- тело ----------
// Первый кризис тела определяется по факту «кризис_тела» (его лучше ставить из
// модуля тела), а здесь — запасной опрос состояния на конец дня.
export function телоВКризисе(S) {
  const рана = S.герой?.рана ?? S.герой?.тело?.рана ?? S.герой?.травма;   // Совместимость с ранним пакетом
  if (рана) return true;
  const цел = S.герой?.тело?.цел;
  return Number.isFinite(цел) && цел <= НАСТРОЙКИ.кризисЦелости;
}
