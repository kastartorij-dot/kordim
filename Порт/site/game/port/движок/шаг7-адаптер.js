// ---------- время ----------

export const деньИгры = S => S.мир?.день ?? 1;

// ---------- вещи (экземпляры, Шаг 3) ----------
// Шаг 3: вещь — экземпляр с uid, типом, количеством, происхождением, состоянием
// и связью с делом; метаданные типа читаются из каталога.

export const типВещи = в => в.тип ?? в.id ?? '';
export const имяВещи = в => в.имя ?? в.название ?? каталогВещи(в)?.имя ?? String(типВещи(в) || 'вещь');
export const количество = в => Number.isFinite(в.количество) ? в.количество
  : Number.isFinite(в.кол) ? в.кол : 1;

// Только экземпляры с uid. Старые строки уходят в экземпляры миграцией v8 (Шаг_3),
// поэтому строки здесь игнорируются.
export function предметыПриСебе(S) {
  return (S.герой?.при_себе ?? []).filter(в => в && typeof в === 'object' && в.uid != null);
}

export function найтиВещь(S, uid) {
  return предметыПриСебе(S).find(в => в.uid === uid) ?? null;
}

// Убрать одну единицу. Стопка уменьшается, последняя единица уходит из слота,
// и если это «предмет в руке» (ссылка на экземпляр) — ссылка сбрасывается.
export function снятьОдну(S, в) {
  const n = количество(в);
  if (n > 1) {
    if ('количество' in в) в.количество = n - 1;
    else if ('кол' in в) в.кол = n - 1;
    return;
  }
  const слоты = S.герой.при_себе;
  const i = слоты.indexOf(в);
  if (i >= 0) слоты.splice(i, 1);
  for (const поле of ['в_руке', 'рука']) {       // рука — действующее поле; в_руке — совместимость с пакетом
    if (S.герой[поле] === в.uid || S.герой[поле] === в) S.герой[поле] = null;
  }
}

// Вещь связана с делом или помечена как важная (Шаг_3: «важные бумаги»).
export const делоВещи = в => в.дело ?? в.делоId ?? в.связь?.дело ?? в.связьСДелом ?? null;
export const вещьВажная = в => Boolean(в.важно || в.важная || в.важный || в.сюжетная || в.сюжетный
  || каталогВещи(в)?.важно || каталогВещи(в)?.дело || в.состояние?.прокат);

// Состояния, при которых вещь — плохой подарок. Шаг 3
// («еда черствеет», «бумага мокнет», «инструмент ломается»).
const ПЛОХОЕ_СОСТОЯНИЕ = ['испорчена', 'испорчено', 'протухла', 'сгнила', 'гнилая',
  'сломана', 'сломано', 'негодна', 'черствая', 'чёрствая', 'черствый', 'чёрствый'];
export function вещьИспорчена(в) {
  if (в.испорчена === true || в.испорчено === true) return true;
  if (типВещи(в) === 'сухарь' || в.состояние?.сломано || в.состояние?.испорчено) return true;
  const с = в.состояние;
  const строка = typeof с === 'string' ? с : (с?.вид ?? с?.статус ?? '');
  return ПЛОХОЕ_СОСТОЯНИЕ.includes(String(строка).toLowerCase());
}

