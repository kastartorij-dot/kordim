// Обмен сведениями (ГДД §11): игрок приносит тему — торговец отдаёт свою. Чистая логика, без DOM и без имён:
// кто торгует и что у него в запасе — поле «обмен» данных места. Правила — Порт-тексты-4.md, «Обмен сведениями».
import { РЕЕСТР } from '../данные/темы.js';
import { датьТему, отметитьУшло, верностьТемы, этоЛожь, СЛЫШАЛ, ПОДТВЕРЖДЕНО, ОПРОВЕРГНУТО } from './знание.js';

// Что тема стоит для торговца: ценность, минус один, если это только слух.
export function ценаТемы(S, тид) {
  const ц = РЕЕСТР[тид]?.ценность ?? 0;
  return ц - (верностьТемы(S, тид) === СЛЫШАЛ ? 1 : 0);
}

// Чем ответит торговец: самая дорогая тема запаса, которой у игрока нет и ценность которой не больше цены + 1
// (при равной ценности — первая по порядку). null — ничего подходящего.
export function чтоОтдаст(S, обмен, цена) {
  let лучшая = null;
  for (const тид of обмен.запас) {
    if (S.мир.темы.includes(тид)) continue;
    const ц = РЕЕСТР[тид].ценность;
    if (ц > цена + 1) continue;
    if (!лучшая || ц > РЕЕСТР[лучшая].ценность) лучшая = тид;
  }
  return лучшая;
}

// Предложить тему. Возвращает { реплика, получена, отдана, строка }; ход тратит вызывающий — он тратится всегда.
export function предложить(S, обмен, местоId, тид) {
  const ответы = обмен.ответы;
  const знание = S.мир.знания?.[тид];
  // 1. её собственная тема: то, что торговец сам тебе отдал или сказал
  if (знание?.от === местоId) return { реплика: ответы.своя };
  // 2. ложь или опровергнуто
  if (этоЛожь(тид) || знание?.верность === ОПРОВЕРГНУТО) {
    if (знание?.верность === СЛЫШАЛ) знание.верность = ОПРОВЕРГНУТО;
    return { реплика: ответы.ложь };
  }
  // 3. цена темы
  const цена = ценаТемы(S, тид);
  if (цена <= 0) return { реплика: ответы.ноль };
  // 4. что отдаст
  const получена = чтоОтдаст(S, обмен, цена);
  if (!получена) return { реплика: ответы.ничего };
  // 5. обмен состоялся
  датьТему(S, получена, ПОДТВЕРЖДЕНО, местоId);
  отметитьУшло(S, тид, обмен.уходитК);
  return {
    реплика: ответы.состоялся + '\n\n' + РЕЕСТР[получена].текст,
    получена,
    отдана: тид,
    строка: РЕЕСТР[тид].личная ? ответы.личная : null,
  };
}
