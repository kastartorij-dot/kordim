import { ДЕЛА } from '../данные/дела.js';
import { вещь, имяВещи, привестиВещи, найтиВещь, можноПоложить, положить, забрать, размер, занято, свободных, создатьВещь } from './вещи.js';
import { надеть, снятьВерх, постирать, высушить, починить, привестиОдежду, ценаУличнойПокупки } from './одежда.js';

const журнал = (S, с) => { S.мир.журналДня.push(с); return с; };
const хранилища = { вдова: 16, угол: 24 };
export const доступенСундук = (S, id) => id === 'угол' ? S.герой.жильё?.id === 'угол' : S.герой.жильё?.id === 'вдова' && S.герой.жильё.оплачено_по >= S.мир.день;

export function купитьВещь(S, id) {
  const в = вещь(id), ц = в && ценаУличнойПокупки(S, в.цена);
  if (!в || !Number.isFinite(ц) || !(ПРИЛАВОК[S.мир.район] ?? []).includes(id) || S.мир.отрезок === 'ночь' || S.герой.кошель < ц || !можноПоложить(S, id, 1, { происхождение: `прилавок: ${S.мир.район}` }) || S.сцена || S.мир.конецДня) return false;
  const дополнение = { происхождение: `прилавок: ${S.мир.район}` };
  if (id === 'кафтан' && S.мир.район === 'трущобы') дополнение.состояние = { метка: 'чужая нашивка' };
  if (!положить(S, id, 1, дополнение)) return false;
  S.герой.кошель -= ц;
  журнал(S, `${в.имя}: покупка −${ц} гр.`);
  return true;
}

export function продатьВещь(S, uid) {
  const x = найтиВещь(S, uid), в = вещь(x?.тип);
  if (!x || !в || в.важно || в.дело || x.состояние.прокат || !в.цена || S.мир.район !== 'торговый' || S.сцена || S.мир.конецДня) return false;
  const сумма = Math.max(1, Math.floor(в.цена / 2));
  забрать(S, uid, 1); S.герой.кошель += сумма;
  журнал(S, `${в.имя}: продажа +${сумма} гр.`);
  return true;
}

export function убратьВСундук(S, uid, id) {
  const список = привестиВещи(S), x = список.find(y => y.uid === uid), х = S.герой.хранилище[id];
  if (!x || !х || !доступенСундук(S, id) || занято(х) + размер(x) > хранилища[id] || S.сцена || S.мир.конецДня) return false;
  х.push(забрать(S, uid, x.количество));
  журнал(S, `${имяВещи(x)}: положено в сундук`);
  return true;
}

export function взятьИзСундука(S, uid, id) {
  привестиВещи(S);
  const х = S.герой.хранилище[id], x = х?.find(y => y.uid === uid);
  if (!x || !доступенСундук(S, id) || свободных(S) < размер(x) || S.сцена || S.мир.конецДня) return false;
  х.splice(х.indexOf(x), 1);
  S.герой.при_себе.push(x);
  журнал(S, `${имяВещи(x)}: взято из сундука`);
  return true;
}

export function заложитьВещь(S, uid) {
  const x = найтиВещь(S, uid), в = вещь(x?.тип);
  if (!x || !в?.цена || в.важно || в.дело || x.состояние.прокат || S.мир.район !== 'торговый' || S.сцена || S.мир.конецДня) return false;
  const сумма = Math.max(1, Math.floor(в.цена / 2));
  const вещьВЗалоге = забрать(S, uid, 1);
  S.герой.залог.push({ вещь: вещьВЗалоге, сумма, выкупДо: S.мир.день + 7 });
  S.герой.кошель += сумма;
  журнал(S, `${в.имя}: залог +${сумма} гр., выкуп до дня ${S.мир.день + 7}`);
  return true;
}

export function выкупитьВещь(S, uid) {
  привестиВещи(S);
  const запись = S.герой.залог.find(y => y.вещь.uid === uid);
  if (!запись || S.мир.день > запись.выкупДо || S.мир.район !== 'торговый' || S.сцена || S.мир.конецДня || S.герой.кошель < запись.сумма || свободных(S) < размер(запись.вещь)) return false;
  S.герой.залог.splice(S.герой.залог.indexOf(запись), 1);
  S.герой.при_себе.push(запись.вещь);
  S.герой.кошель -= запись.сумма;
  журнал(S, `${имяВещи(запись.вещь)}: выкуп −${запись.сумма} гр.`);
  return true;
}

export function просрочитьЗалоги(S, итог) {
  привестиВещи(S);
  for (const з of [...S.герой.залог]) if (S.мир.день > з.выкупДо) {
    S.герой.залог.splice(S.герой.залог.indexOf(з), 1);
    итог.причины.push(`${имяВещи(з.вещь)} продана после просрочки залога`);
  }
}

export function передатьВещь(S, uid, кому) {
  const x = найтиВещь(S, uid), в = вещь(x?.тип);
  if (!x || !кому || S.сцена?.собеседник !== кому || в?.важно || в?.дело || S.мир.конецДня) return false;
  забрать(S, uid, 1);
  (S.мир.передано ??= []).push({ кому, тип: x.тип, день: S.мир.день });
  (S.мир.люди[кому] ??= { спрошено: [], исчерпано: [] }).получено ??= [];
  S.мир.люди[кому].получено.push({ тип: x.тип, день: S.мир.день });
  S.сцена.реплика = `Собеседник принимает ${имяВещи(x).toLowerCase()}. О том, что это значит, вы ещё не договорились.`;
  журнал(S, `${имяВещи(x)} передано: ${кому}`);
  return true;
}

export function восстановитьБумагу(S, uid) {
  const x = найтиВещь(S, uid);
  if (!x?.состояние?.промокло || !вещь(x.тип)?.бумага || S.мир.район !== 'торговый' || S.герой.кошель < 2 || S.сцена || S.мир.конецДня) return false;
  x.состояние.промокло = false; S.герой.кошель -= 2;
  журнал(S, `${имяВещи(x)}: писец восстановил запись за 2 гр.`);
  return true;
}

export function восстановитьПотерянное(S, uid) {
  const записьПотери = (S.мир.утраченные ?? []).find(x => x.uid === uid);
  if (!записьПотери || !вещь(записьПотери.тип)?.бумага || S.мир.район !== 'торговый' || S.герой.кошель < 5 || !можноПоложить(S, записьПотери.тип) || S.сцена || S.мир.конецДня) return false;
  S.мир.утраченные.splice(S.мир.утраченные.indexOf(записьПотери), 1);
  S.герой.кошель -= 5;
  привестиВещи(S).push(создатьВещь(S, записьПотери.тип, { состояние: { копия: true }, происхождение: `копия записи от дня ${записьПотери.день}`, дело: записьПотери.дело }));
  журнал(S, `${имяВещи(записьПотери.тип)}: восстановлена копия за 5 гр.`);
  return true;
}

export function взятьНапрокат(S, id) {
  const в = ОДЕЖДА[id], залог = Math.ceil((в?.цена ?? 0) / 2);
  if (!в || !['плащ', 'накидка', 'приказчичья'].includes(id) || S.мир.район !== 'торговый' || S.мир.отрезок === 'ночь' || S.сцена || S.мир.конецДня || S.герой.кошель < залог || свободных(S) < 1) return false;
  const x = создатьВещь(S, id, { состояние: { прокат: { залог, до: S.мир.день + 3 } } });
  привестиВещи(S).push(x);
  S.герой.кошель -= залог;
  журнал(S, `${в.имя}: прокат, залог −${залог} гр., вернуть до дня ${S.мир.день + 3}`);
  return true;
}

export function вернутьПрокат(S, uid) {
  const x = найтиВещь(S, uid), р = x?.состояние?.прокат;
  if (!р || S.мир.район !== 'торговый' || S.сцена || S.мир.конецДня) return false;
  const удержано = S.мир.день <= р.до && !x.состояние.рвано ? 2 : р.залог;
  забрать(S, uid, 1);
  S.герой.кошель += Math.max(0, р.залог - удержано);
  журнал(S, `${имяВещи(x)}: прокат возвращён, залог +${Math.max(0, р.залог - удержано)} гр.`);
  return true;
}

export function сдатьНож(S) {
  if (!S.сцена || S.сцена.место !== 'синий-час') return false;
  const x = привестиВещи(S).find(y => y.тип === 'нож');
  if (!x) return false;
  (S.сцена.сданныеВещи ??= []).push(забрать(S, x.uid, 1));
  S.мир.журналДня.push('Нож оставлен у Сиба до выхода');
  return true;
}

export function вернутьСданное(S) {
  const сдано = S.сцена?.сданныеВещи ?? [];
  if (!сдано.length) return;
  привестиВещи(S);
  for (const x of сдано) {
    if (свободных(S) >= размер(x)) S.герой.при_себе.push(x);
    else (S.герой.возвратСиба ??= []).push(x);
  }
  S.мир.журналДня.push(S.герой.возвратСиба?.length ? 'Сиб оставил сданное у двери: забери, когда освободишь место' : 'Сиб вернул сданный нож');
  S.сцена.сданныеВещи = [];
}

export function забратьУСиба(S, uid) {
  const список = S.герой.возвратСиба ?? [], x = список.find(y => y.uid === uid);
  if (!x || S.мир.район !== 'торговый' || свободных(S) < размер(x)) return false;
  список.splice(список.indexOf(x), 1); привестиВещи(S).push(x);
  журнал(S, `${имяВещи(x)} возвращено у дверей «Синего часа»`);
  return true;
}

export function купитьУслугу(S, услуга) {
  if (S.сцена || S.мир.конецДня) return false;
  const о = привестиОдежду(S), цена = { стирка: 2, сушка: 1, починка: 4, снятьМетку: 3, карман: 8, подбой: 12, лекарь: 5, выпивка: 2, помыться: 2 }[услуга];
  const где = { стирка: 'трущобы', сушка: 'трущобы', починка: 'торговый', снятьМетку: 'торговый', карман: 'торговый', подбой: 'торговый', лекарь: 'торговый', выпивка: 'доки', помыться: 'трущобы' }[услуга];
  if (!цена || S.мир.район !== где || S.герой.кошель < цена) return false;
  let ок = false;
  if (услуга === 'стирка') ок = постирать(S);
  if (услуга === 'сушка') ок = высушить(S);
  if (услуга === 'починка') ок = починить(S);
  if (услуга === 'снятьМетку' && о.база.состояние.метка) { delete о.база.состояние.метка; ок = true; }
  if (услуга === 'карман' && !о.база.состояние.тайник) { о.база.состояние.тайник = true; ок = true; }
  if (услуга === 'подбой' && !о.база.состояние.подбой) { о.база.состояние.подбой = true; ок = true; }
  if (услуга === 'лекарь' && (S.герой.рана || S.герой.боль || S.герой.тело.цел < 3)) { S.герой.рана = 0; S.герой.боль = 0; S.герой.тело.цел = Math.min(3, S.герой.тело.цел + 1); ок = true; }
  if (услуга === 'выпивка' && S.герой.хмель < 3) {
    S.герой.хмель++; S.герой.напряжение = Math.max(0, S.герой.напряжение - 1);
    S.герой.жажда = Math.min(3, (S.герой.жажда ?? 0) + 1);
    S.герой.привычкаХмель = Math.min(3, (S.герой.привычкаХмель ?? 0) + 1);
    S.герой.хмельДень = S.мир.день; ок = true;
  }
  if (услуга === 'помыться' && (о.база.состояние.грязь || о.база.состояние.кровь)) ок = постирать(S);
  if (!ок) return false;
  S.герой.кошель -= цена;
  журнал(S, `${услуга}: −${цена} гр.`);
  return true;
}

export const ПРИЛАВОК = {
  торговый: ['пирог', 'рыба', 'бинт', 'настой', 'отмычка', 'нож', 'лохмотья', 'кафтан', 'ремесленная', 'приказчичья', 'купеческая', 'плащ', 'накидка', 'полушубок', 'суконная'],
  доки: ['хлеб', 'рыба', 'табак'],
  трущобы: ['бинт', 'лохмотья', 'кафтан'],
};

export function доступныеПокупки(S) {
  if (S.сцена || S.мир.конецДня || S.мир.отрезок === 'ночь') return [];
  return (ПРИЛАВОК[S.мир.район] ?? []).map(id => {
    const цена = ценаУличнойПокупки(S, вещь(id).цена);
    return { id: `купить:${id}`, вид: 'торговля', группа: 'товары', текст: `Купить: ${вещь(id).имя}`, подпись: `${цена} гр.`, цена, отрезков: 0, можно: S.герой.кошель >= цена && можноПоложить(S, id, 1, { происхождение: `прилавок: ${S.мир.район}` }), почему: S.герой.кошель < цена ? 'нет денег' : 'некуда положить', выполнить(S2) { return купитьВещь(S2, id); } };
  });
}

export function доступныеУслуги(S) {
  if (S.сцена || S.мир.конецДня || S.мир.отрезок === 'ночь') return [];
  const о = привестиОдежду(S), с = о.база.состояние;
  const грязнаяОдежда = [о.база, о.верх].filter(Boolean).some(x => x.состояние.грязь || x.состояние.кровь || x.состояние.запах);
  const рванаяОдежда = [о.база, о.верх].filter(Boolean).some(x => x.состояние.рвано);
  const набор = S.мир.район === 'трущобы' ? [['стирка', 2, грязнаяОдежда], ['сушка', 1, с.сырость || о.верх?.состояние?.сырость], ['помыться', 2, грязнаяОдежда]]
    : S.мир.район === 'торговый' ? [['починка', 4, рванаяОдежда], ['снятьМетку', 3, !!с.метка], ['карман', 8, !с.тайник], ['подбой', 12, !с.подбой], ['лекарь', 5, S.герой.рана || S.герой.боль || S.герой.тело.цел < 3]]
    : [['выпивка', 2, S.герой.хмель < 3]];
  const услуги = набор.filter(x => x[2]).map(([id, цена]) => ({ id: `услуга:${id}`, вид: 'услуга', группа: 'услуги', текст: id === 'снятьМетку' ? 'Снять чужую нашивку' : id === 'помыться' ? 'Вымыться и выстирать одежду' : id[0].toUpperCase() + id.slice(1), подпись: `${цена} гр.`, цена, отрезков: 0, можно: S.герой.кошель >= цена, почему: 'нет денег', выполнить(S2) { return купитьУслугу(S2, id); } }));
  if (S.мир.район === 'торговый') for (const id of ['плащ', 'накидка', 'приказчичья']) {
    const цена = Math.ceil(ОДЕЖДА[id].цена / 2);
    услуги.push({ id: `прокат:${id}`, вид: 'услуга', группа: 'услуги', текст: `Прокат: ${ОДЕЖДА[id].имя}`, подпись: `залог ${цена} гр., 3 дня`, цена, отрезков: 0, можно: S.герой.кошель >= цена && свободных(S) >= 1, почему: S.герой.кошель < цена ? 'нет денег' : 'некуда положить', выполнить(S2) { return взятьНапрокат(S2, id); } });
  }
  if (S.мир.район === 'торговый') for (const у of S.мир.утраченные ?? []) if (вещь(у.тип)?.бумага) {
    услуги.push({ id: `копия:${у.uid}`, вид: 'услуга', группа: 'услуги', текст: `Восстановить: ${имяВещи(у.тип)}`, подпись: '5 гр.', цена: 5, отрезков: 0, можно: S.герой.кошель >= 5 && можноПоложить(S, у.тип), почему: S.герой.кошель < 5 ? 'нет денег' : 'некуда положить', выполнить(S2) { return восстановитьПотерянное(S2, у.uid); } });
  }
  return услуги;
}

export function описатьВещь(x) {
  const в = вещь(x.тип);
  const с = x.состояние ?? {};
  return [в?.категория ?? 'вещь', `мест: ${размер(x)}`, x.количество > 1 ? `штук: ${x.количество}` : null,
    x.прочность !== undefined ? `износ: ${x.прочность}/${в?.прочность ?? x.прочность}` : null,
    с.промокло ? 'бумага промокла' : null, с.сломано ? 'сломана' : null,
    с.грязь ? 'грязная' : null, с.сырость ? 'сырая' : null, с.рвано ? 'рваная' : null,
    с.кровь ? 'в крови' : null, с.запах ? 'пахнет' : null, с.метка ? `метка: ${с.метка}` : null,
    с.прокат ? `прокат до дня ${с.прокат.до}` : null, с.вскрыто ? 'вскрыт' : null,
    x.происхождение ? `откуда: ${x.происхождение}` : null, x.дело ? `дело: ${ДЕЛА[x.дело]?.имя ?? x.дело}` : null].filter(Boolean).join(' · ');
}

export function действияХозяйства(S) {
  const а = [];
  привестиВещи(S); привестиОдежду(S);
  for (const x of S.герой.при_себе) {
    const в = вещь(x.тип), свободно = !S.сцена && !S.мир.конецДня;
    const доп = (id, текст, можно, выполнить) => а.push({ id: `${id}:${x.uid}`, uid: x.uid, текст, можно, выполнить });
    доп('рука', S.герой.рука === x.uid ? 'Убрать из руки' : 'Взять в руку', свободно,
      S2 => { if (!найтиВещь(S2, x.uid)) return false; S2.герой.рука = S2.герой.рука === x.uid ? null : x.uid; return true; });
    if (ОДЕЖДА[x.тип]) {
      const старое = S.герой.одежда[ОДЕЖДА[x.тип].слой];
      доп('надеть', 'Надеть', свободно && (!старое || свободных(S) + размер(x) >= размер(старое)), S2 => надеть(S2, x.uid));
    }
    for (const id of ['вдова', 'угол']) if (доступенСундук(S, id)) {
      доп(`сундук-${id}`, 'В сундук', свободно && занято(S.герой.хранилище[id]) + размер(x) <= хранилища[id], S2 => убратьВСундук(S2, x.uid, id));
    }
    if (S.мир.район === 'торговый' && в?.цена && !в.важно && !в.дело) {
      if (x.состояние.прокат) доп('прокат-вернуть', 'Вернуть прокат', свободно, S2 => вернутьПрокат(S2, x.uid));
      else {
        доп('продать', `Продать (+${Math.max(1, Math.floor(в.цена / 2))} гр.)`, свободно, S2 => продатьВещь(S2, x.uid));
        доп('залог', 'Заложить на 7 дней', свободно, S2 => заложитьВещь(S2, x.uid));
      }
    }
    if (S.мир.район === 'торговый' && в?.бумага && x.состояние.промокло) {
      доп('восстановить', 'Восстановить запись (2 гр.)', свободно && S.герой.кошель >= 2, S2 => восстановитьБумагу(S2, x.uid));
    }
    if (S.сцена?.собеседник && !в?.важно && !в?.дело) {
      const кому = S.сцена.собеседник;
      доп('передать', `Передать ${кому}`, true, S2 => передатьВещь(S2, x.uid, кому));
    }
  }
  for (const id of ['вдова', 'угол']) if (доступенСундук(S, id)) for (const x of S.герой.хранилище[id]) {
    а.push({ id: `достать:${x.uid}`, uid: x.uid, текст: 'Достать', можно: !S.сцена && свободных(S) >= размер(x), выполнить: S2 => взятьИзСундука(S2, x.uid, id) });
  }
  if (S.мир.район === 'торговый') {
    for (const з of S.герой.залог) а.push({ id: `выкуп:${з.вещь.uid}`, uid: з.вещь.uid, текст: `Выкупить (${з.сумма} гр.)`, можно: !S.сцена && S.герой.кошель >= з.сумма && свободных(S) >= размер(з.вещь), выполнить: S2 => выкупитьВещь(S2, з.вещь.uid) });
    for (const x of S.герой.возвратСиба ?? []) а.push({ id: `сиб:${x.uid}`, uid: x.uid, текст: 'Забрать у Сиба', можно: !S.сцена && свободных(S) >= размер(x), выполнить: S2 => забратьУСиба(S2, x.uid) });
  }
  if (S.герой.одежда.верх) а.push({ id: 'снять-верх', текст: 'Снять верхний слой', можно: !S.сцена && свободных(S) >= размер(S.герой.одежда.верх), выполнить: S2 => снятьВерх(S2) });
  return а;
}
