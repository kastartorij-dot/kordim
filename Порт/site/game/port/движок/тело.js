// Тело в конце дня. ГДД §5, задание этапа 2, шаг 5. Без DOM. Ничего о конкретных местах:
// всё, что зависит от ночлега, приходит в «сон» из данных/жильё.js.
import { ХОЛОДА_С } from '../данные/жильё.js';
import { утепление, запачкать, высушить } from './одежда.js';
import { отметитьКризисТела } from './голос.js';

export const МАКС = 3;
const НАЗВАНИЕ = { сыт: 'Сыт', отдых: 'Отдых', тепло: 'Тепло', цел: 'Цел' };
const зажать = v => Math.max(0, Math.min(МАКС, v));
const зн = n => (n > 0 ? '+' : '−') + Math.abs(n);

// Меняет S.герой.тело, дописывает в итог.причины по строке на причину.
export function применитьТело(S, сон, итог) {
  const г = S.герой, т = г.тело, п = итог.причины;
  отметитьКризисТела(S);
  const менять = (к, d, почему) => {
    const было = т[к];
    т[к] = зажать(т[к] + d);
    if (к === 'цел') отметитьКризисТела(S);
    if (т[к] !== было) п.push(`${НАЗВАНИЕ[к]} ${зн(т[к] - было)}: ${почему}`);
  };

  менять('сыт', -1, 'прошёл день');
  if (сон) {
    менять('отдых', сон.отдых, сон.имя);
    if (сон.тепло) менять('тепло', сон.тепло, сон.имя);
  } else {
    менять('отдых', -1, 'ночь без сна');
  }
  if (S.мир.день >= ХОЛОДА_С && !(сон && сон.укрыт) && утепление(S) < 2) менять('тепло', -1, 'осенние холода');
  if (сон && сон.укрыт) высушить(S);
  if (сон && ['небо', 'ночлежка'].includes(сон.id)) запачкать(S);
  if (г.рана > 0) менять('цел', -1, 'нелеченная рана');
  if (г.жажда >= 2) менять('сыт', -1, 'жажда');
  if (г.хмель >= 2) менять('отдых', -1, 'тяжёлая голова после выпивки');
  for (const [привычка, последний, слово] of [['привычкаТабак', 'табакДень', 'табака'], ['привычкаХмель', 'хмельДень', 'выпивки'], ['привычкаНастой', 'настойДень', 'настоя']]) {
    if ((г[привычка] ?? 0) >= 2 && г[последний] !== S.мир.день) {
      г.напряжение = Math.min(3, (г.напряжение ?? 0) + 1);
      п.push(`Напряжение +1: не было ${слово}`);
    }
    if (г[привычка] > 0 && S.мир.день - (г[последний] ?? 0) >= 3) {
      г[привычка]--; г[последний] = S.мир.день - 1;
      п.push(`Привычка к ${слово} ослабла`);
    }
  }
  if (сон) г.напряжение = Math.max(0, (г.напряжение ?? 0) - 1);
  if (сон?.отдых >= 2) г.боль = Math.max(0, (г.боль ?? 0) - 1);
  г.хмель = Math.max(0, (г.хмель ?? 0) - 1);

  if (т.тепло === 0) {
    менять('цел', -1, 'совсем нет тепла');
    г.холод1 = 0;
  } else if (т.тепло === 1) {
    г.холод1 += 1;
    if (г.холод1 >= 2) {
      // ВОПРОС: после штрафа за два дня подряд счётчик сбрасывается в 0 (следующий штраф — ещё через два дня)?
      менять('цел', -1, 'два дня подряд мало тепла');
      г.холод1 = 0;
    }
  } else {
    г.холод1 = 0;
  }

  if (сон && сон.поправка && т.сыт >= 2 && т.тепло >= 2) менять('цел', 1, 'ночь в покое, сыт и в тепле');

  // Тень спадает на 1 за три спокойных дня — без новых ушей (ГДД §8).
  const м = S.мир;
  if (м.тень > 0 && м.день - (м.теньДень ?? 0) >= 3) {
    м.тень -= 1;
    м.теньДень = м.день;
    п.push('Тень −1: три спокойных дня');
  }

  итог.предупреждение = т.цел === 0;
}
