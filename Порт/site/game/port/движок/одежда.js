import { ОДЕЖДА } from '../данные/одежда.js';
import { вещь, создатьВещь, привестиВещи, свободных, забрать, размер } from './вещи.js';

export function привестиОдежду(S) {
  const г = S.герой;
  if (!г.одежда) {
    const прежнийВид = г.вид;
    const состояние = прежнийВид === 0 ? { грязь: 2 } : прежнийВид >= 2 ? { опрятность: прежнийВид } : {};
    г.одежда = { база: создатьВещь(S, 'рабочая', { состояние }), верх: null };
  }
  if (typeof г.одежда.база === 'string') г.одежда.база = создатьВещь(S, г.одежда.база);
  if (typeof г.одежда.верх === 'string') г.одежда.верх = создатьВещь(S, г.одежда.верх);
  г.одежда.база ??= создатьВещь(S, 'рабочая');
  г.одежда.база.состояние ??= {};
  if (г.одежда.верх) г.одежда.верх.состояние ??= {};
  г.вид = видОдежды(S);
  return г.одежда;
}

export function видОдежды(S) {
  const о = S.герой.одежда;
  if (!о?.база) return 1;
  const с = о.база.состояние ?? {};
  const база = ОДЕЖДА[о.база.тип]?.вид ?? 1;
  const верх = ОДЕЖДА[о.верх?.тип]?.вид ?? 0;
  return Math.max(0, Math.min(3, база + верх - (с.грязь >= 2 ? 1 : 0) - (с.рвано || с.кровь ? 2 : 0)));
}

export const защищёнОтДождя = S => !!ОДЕЖДА[S.герой.одежда?.верх?.тип]?.дождь;
export const утепление = S => (ОДЕЖДА[S.герой.одежда?.верх?.тип]?.тепло ?? 0) + (S.герой.одежда?.база?.состояние?.подбой ? 1 : 0);
export const мокраяОдежда = S => !!(S.герой.одежда?.база?.состояние?.сырость || S.герой.одежда?.верх?.состояние?.сырость);

// Наряд меняет цену лишь у уличного торговца. В конторе и у лекаря свои тарифы.
export function ценаУличнойПокупки(S, цена) {
  if (!['доки', 'торговый'].includes(S.мир.район) || видОдежды(S) < 3) return цена;
  return Math.ceil(цена * 1.5);
}

export function надеть(S, uid) {
  if (S.сцена || S.мир.конецДня) return false;
  const о = привестиОдежду(S), список = привестиВещи(S);
  const x = список.find(y => y.uid === uid), тип = ОДЕЖДА[x?.тип];
  if (!тип) return false;
  const старое = о[тип.слой];
  if (старое && свободных(S) + размер(x) < размер(старое)) return false;
  const взято = забрать(S, uid, 1);
  о[тип.слой] = взято;
  if (старое) список.push(старое);
  S.герой.вид = видОдежды(S);
  S.мир.журналДня.push(`Надел: ${тип.имя}`);
  return true;
}

export function снятьВерх(S) {
  const о = привестиОдежду(S);
  if (!о.верх || S.сцена || свободных(S) < размер(о.верх)) return false;
  привестиВещи(S).push(о.верх); о.верх = null;
  S.герой.вид = видОдежды(S);
  S.мир.журналДня.push('Снял верхнюю одежду');
  return true;
}

export function запачкать(S, n = 1) {
  const о = привестиОдежду(S);
  о.база.состояние.грязь = Math.min(2, (о.база.состояние.грязь ?? 0) + n);
  delete о.база.состояние.опрятность;
  S.герой.вид = видОдежды(S);
}

export function повредитьОдежду(S, кровь = false) {
  const о = привестиОдежду(S);
  о.база.состояние.рвано = true;
  if (кровь) о.база.состояние.кровь = true;
  S.герой.вид = видОдежды(S);
}

export function постирать(S) {
  const о = привестиОдежду(S);
  const слои = [о.база, о.верх].filter(Boolean);
  if (!слои.some(x => x.состояние.грязь || x.состояние.кровь || x.состояние.запах)) return false;
  for (const x of слои) {
    x.состояние.грязь = 0; x.состояние.кровь = false; x.состояние.запах = false;
    delete x.состояние.опрятность;
  }
  S.герой.вид = видОдежды(S);
  S.мир.журналДня.push('Одежда выстирана');
  return true;
}

export function высушить(S) {
  const о = привестиОдежду(S);
  if (!о.база.состояние.сырость && !о.верх?.состояние?.сырость) return false;
  о.база.состояние.сырость = 0;
  if (о.верх) о.верх.состояние.сырость = 0;
  S.мир.журналДня.push('Одежда просохла');
  return true;
}

export function починить(S) {
  const о = привестиОдежду(S);
  const слои = [о.база, о.верх].filter(Boolean);
  if (!слои.some(x => x.состояние.рвано)) return false;
  for (const x of слои) x.состояние.рвано = false;
  S.герой.вид = видОдежды(S);
  S.мир.журналДня.push('Одежда зашита');
  return true;
}

export function намокнуть(S) {
  const о = привестиОдежду(S);
  if (защищёнОтДождя(S)) return false;
  о.база.состояние.сырость = Math.min(2, (о.база.состояние.сырость ?? 0) + 1);
  if (о.верх) о.верх.состояние.сырость = Math.min(2, (о.верх.состояние.сырость ?? 0) + 1);
  S.герой.тело.тепло = Math.max(0, S.герой.тело.тепло - 1);
  S.мир.журналДня.push('Промок под дождём: тепло −1');
  return true;
}

export function описаниеОдежды(S) {
  const о = привестиОдежду(S);
  const пометки = [о.база, о.верх].filter(Boolean).flatMap((x, i) => {
    const с = x.состояние;
    const признаки = [с.грязь ? 'грязная' : null, с.рвано ? 'рваная' : null, с.кровь ? 'в крови' : null, с.сырость ? 'сырая' : null, с.запах ? 'пахнет' : null, с.метка ? `метка: ${с.метка}` : null, с.опрятность >= 3 ? 'вычищена' : null].filter(Boolean);
    return признаки.map(признак => `${i ? 'верх' : 'основа'}: ${признак}`);
  });
  return { база: ОДЕЖДА[о.база.тип]?.имя ?? о.база.тип, верх: о.верх ? ОДЕЖДА[о.верх.тип]?.имя ?? о.верх.тип : 'нет', вид: видОдежды(S), состояние: пометки.join(', ') || 'в порядке' };
}
