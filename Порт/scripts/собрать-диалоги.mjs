  bras: 'Весовщик', yora: 'Торговка пирогами', pin: 'Торговец одеждой', veyt: 'Скупщик сведений', ulf: 'Ночной торговец',
  tobb: 'Служащий конторы', rest_dorr: 'Смотритель доков', svish: 'Посетитель конторы',
  ifo: 'Смотритель маяка', gvozd: 'Человек у маяка', vorn_healer: 'Лекарь', mila: 'Помощница лекаря',
