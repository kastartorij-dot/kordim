// Подарки: вещь из слотов — человеку, с которым идёт разговор.
// Замена функции подарить() из Порт-Подарки.md под экземпляры вещей Шага 3
// и четыре вида реакции из ПЛАН П08.1.
//
// Правила:
//  • один принятый подарок одному человеку за игровой день — проверяет само действие
//    подарить(), а не только кнопка в экране;
//  • сюжетные вещи (документ, груз, оружие, инструмент, вещь с привязкой к делу) подарком
//    не уходят и ничего не тратят;
//  • отвергнутый подарок остаётся у героя и лимит не тратит;
//  • подарками расположение растёт только до НАСТРОЙКИ.потолокОтПодарков;
//  • вещь идёт по uid, а не по номеру слота: номера смещаются, uid — нет.

import {
  НАСТРОЙКИ, деньИгры, найтиВещь, предметыПриСебе, снятьОдну, типВещи, имяВещи,
  делоВещи, вещьВажная, вещьИспорчена, записьЧеловека, журналДня, каталогВещи,
} from './шаг7-адаптер.js';
import {
  КЛАСС_ПО_ТИПУ, ЗАЩИЩЁННЫЕ_КЛАССЫ, ТЕКСТ_ЗАЩИТЫ, ЭФФЕКТ_ПОДАРКА,
  РЕАКЦИИ_ПО_УМОЛЧАНИЮ, ПОДАРКИ_ЛЮДЕЙ,
} from '../данные/подарки.js';

const норм = с => String(с ?? '').toLowerCase().replace(/ё/g, 'е');

export function классПодарка(в) {
  const категория = каталогВещи(в)?.категория;
  if (категория) return ({ улика: 'сюжет', память: 'сюжет', лечение: 'лекарство', расходник: типВещи(в) })[категория] ?? категория;
  const т = норм(типВещи(в));
  if (КЛАСС_ПО_ТИПУ[т]) return КЛАСС_ПО_ТИПУ[т];
  const ключ = Object.keys(КЛАСС_ПО_ТИПУ).find(к => т.startsWith(норм(к)));
  return ключ ? КЛАСС_ПО_ТИПУ[ключ] : 'прочее';
}

function совпадает(список, в) {
  if (!список?.length) return false;
  const т = норм(типВещи(в));
  const кл = норм(классПодарка(в));
  return список.some(е => { const x = норм(е); return т === x || т.startsWith(x) || кл === x; });
}

// { защищена, причина } — можно ли вообще отдать вещь подарком.
export function защитаВещи(в) {
  if (делоВещи(в)) return { защищена: true, причина: ТЕКСТ_ЗАЩИТЫ.дело };
  if (вещьВажная(в) || ЗАЩИЩЁННЫЕ_КЛАССЫ.includes(классПодарка(в))) {
    return { защищена: true, причина: ТЕКСТ_ЗАЩИТЫ.класс };
  }
  return { защищена: false };
}

// 'любимый' | 'обычный' | 'неуместный' | 'отвергнутый'
export function видПодарка(кто, в) {
  const п = ПОДАРКИ_ЛЮДЕЙ[кто] ?? {};
  if (совпадает(п.отвергает, в)) return 'отвергнутый';
  if (вещьИспорчена(в) || совпадает(п.неуместно, в)) return 'неуместный';
  if (совпадает(п.любит, в)) return 'любимый';
  return 'обычный';
}

export function можноДарить(S, кто) {
  if (S.мир?.люди?.[кто]?.дарилДень === деньИгры(S)) {
    return { можно: false, причина: 'Сегодня ты уже дарил этому человеку. Второй подарок за день — это уже не подарок.' };  // draft
  }
  return { можно: true };
}

// Список для экрана. Вид подарка игроку не раскрывается.
export function списокПодарков(S, кто) {
  const день = можноДарить(S, кто);
  return предметыПриСебе(S).map(в => {
    const з = защитаВещи(в);
    const можно = день.можно && !з.защищена;
    return { uid: в.uid, имя: имяВещи(в), можно, причина: можно ? null : (з.причина ?? день.причина) };
  });
}

function текстРеакции(кто, вид, в) {
  const с = ПОДАРКИ_ЛЮДЕЙ[кто]?.реакции?.[вид] ?? РЕАКЦИИ_ПО_УМОЛЧАНИЮ[вид];
  return с.replace('{вещь}', имяВещи(в));
}

// Подарить вещь uid человеку кто. Всё или ничего: при отказе состояние не меняется.
// → { ок, вид?, эффект?, текст, причина? }
export function подарить(S, кто, uid) {
  const в = найтиВещь(S, uid);
  if (!в) return { ок: false, причина: 'нет вещи', текст: 'Такой вещи при тебе нет.' };

  const з = защитаВещи(в);
  if (з.защищена) return { ок: false, причина: 'сюжетная', текст: з.причина };

  const лимит = можноДарить(S, кто);
  if (!лимит.можно) return { ок: false, причина: 'лимит', текст: лимит.причина };

  const вид = видПодарка(кто, в);
  const имя = имяВещи(в);

  if (вид === 'отвергнутый') {
    журналДня(S, `Не приняли: ${имя}.`);
    return { ок: false, причина: 'отвергнут', вид, эффект: 0, текст: текстРеакции(кто, вид, в) };
  }

  const л = записьЧеловека(S, кто);
  const было = л.распол ?? 0;
  const { мин, макс } = НАСТРОЙКИ.распол;
  const стало = Math.max(мин, Math.min(макс,
    Math.min(Math.max(было, НАСТРОЙКИ.потолокОтПодарков), было + ЭФФЕКТ_ПОДАРКА[вид])));

  снятьОдну(S, в);
  л.распол = стало;
  л.дарилДень = деньИгры(S);
  (л.подарено ??= []).push({ день: деньИгры(S), тип: типВещи(в), вид });
  if (л.подарено.length > 12) л.подарено.shift();
  журналДня(S, `Подарил: ${имя}.`);

  return { ок: true, вид, эффект: стало - было, текст: текстРеакции(кто, вид, в) };
}

// Точка подключения к действияСцены(): кнопка «Подарить» на каждую доступную вещь.
// id действия строится по uid; реакция сохраняется в сцене до отрисовки.
// `добавить(описание, выполнить)` — та же функция, что уже есть в действияСцены().
export function действияПодарков(S, кто, добавить) {
  if (!можноДарить(S, кто).можно) return;
  for (const п of списокПодарков(S, кто)) {
    if (!п.можно) continue;
    добавить({ id: `подарить:${п.uid}`, вид: 'подарить', текст: `Подарить: ${п.имя}` },
      S2 => {
        if (S2.сцена?.собеседник !== кто || S2.сцена.ветка || S2.сцена.нужнаСцена || S2.сцена.конец) return;
        const р = подарить(S2, кто, п.uid);
        S2.сцена.реплика = р.текст;
        S2.сцена.мояреплика = '';
      });
  }
}
