// Ремёсла (ГДД §6): умеешь → набил руку → мастер. Никаких очков опыта — зарубки за смены.
// Без DOM. Ремесло появляется у героя с первой зарубки, если работа даёт зарубки в ремесло, которого нет.
export const СТУПЕНИ = [
  { имя: 'умеешь', от: 0, множитель: 1 },
  { имя: 'набил руку', от: 10, множитель: 1.5 },
  { имя: 'мастер', от: 30, множитель: 2 },
];
const номер = имя => СТУПЕНИ.findIndex(с => с.имя === имя);

export function ремесло(S, имя) { return S.герой.ремёсла?.[имя] ?? null; }
export const ступеньНомер = (S, имя) => { const р = ремесло(S, имя); return р ? номер(р.ступень) : -1; };
export const множительСтупени = (S, имя) => { const р = ремесло(S, имя); return р ? СТУПЕНИ[номер(р.ступень)].множитель : 1; };
// хватает ли ступени: нет ремесла — нет; имя ступени «умеешь» и выше
export const хватает = (S, имя, минСтупень = 'умеешь') => ступеньНомер(S, имя) >= номер(минСтупень);

export function датьРемесло(S, имя) {
  S.герой.ремёсла ??= {};
  S.герой.ремёсла[имя] ??= { ступень: 'умеешь', зарубки: 0 };
}

// Возвращает строку для журнала, если ступень выросла, иначе null. Зарубка в ремесло, которого нет, его открывает.
export function зарубка(S, имя, n = 1) {
  if (!имя || !n) return null;
  датьРемесло(S, имя);
  const р = S.герой.ремёсла[имя], была = номер(р.ступень);
  // Не больше одной зарубки в день на ремесло: две работы одного ремесла в день не ускоряют мастерство.
  if (n === 1 && р.деньЗарубки === S.мир.день) return null;
  р.деньЗарубки = S.мир.день;
  р.зарубки += n;
  let новая = была;
  СТУПЕНИ.forEach((с, i) => { if (р.зарубки >= с.от) новая = Math.max(новая, i); });
  р.ступень = СТУПЕНИ[новая].имя;
  return новая > была ? `Ремесло «${имя}»: ${р.ступень}` : null;
}

// Сколько зарубок до следующей ступени (для экрана «Герой»); null у мастера.
export function доСледующей(S, имя) {
  const р = ремесло(S, имя);
  if (!р) return null;
  const с = СТУПЕНИ[номер(р.ступень) + 1];
  return с ? с.от - р.зарубки : null;
}


