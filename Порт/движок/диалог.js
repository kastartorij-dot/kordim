// Хост — функции движка места (разговор.js): диалог.js не импортирует его сам, чтобы не было круга.
let хост = null;
export const подключить = х => { хост = х; };

const ЛЕНТА_МАКС = 80;
const Д = S => хост.модуль(S);
export const графЧеловека = (S, кто) => (S.сцена ? Д(S).ДИАЛОГИ?.[кто] ?? null : null);
const граф = S => графЧеловека(S, S.сцена.диалог.кто);
const ветка = (S, id) => граф(S).ветки[id];
const память = (S, кто) => (S.мир.диалоги[кто] ??= { факты: [], ветки: {} });
const памятьВетки = (S, кто, id) => ((память(S, кто).ветки[id]) ??= { входов: 0, исход: null, награды: {} });

// ── условия ─────────────────────────────────────────────────────────────
const вДиап = (v, [от, до]) => v >= от && v <= до;
export function если(S, у, кто = S.сцена?.диалог?.кто) {
  if (!у) return true;
  const т = S.герой.тело;
  for (const к of ['сыт', 'отдых', 'тепло', 'цел']) if (у[к] && !вДиап(т[к], у[к])) return false;
  if (у.хмель && !вДиап(S.герой.хмель ?? 0, у.хмель)) return false;
  if (у.напряжение && !вДиап(S.герой.напряжение ?? 0, у.напряжение)) return false;
  if (у.тень && !вДиап(S.мир.тень ?? 0, у.тень)) return false;
  if (у.вид && !вДиап(S.герой.вид ?? 3, у.вид)) return false;
  if (у.флаг && !хост.есть(S, у.флаг)) return false;
  if (у.нетФлага && хост.есть(S, у.нетФлага)) return false;
  const п = кто ? память(S, кто) : null;
  if (у.факт && !п?.факты.includes(у.факт)) return false;
  if (у.нетФакта && п?.факты.includes(у.нетФакта)) return false;
  if (у.доверие !== undefined && хост.расп(S, кто) < у.доверие) return false;
  if (у.доверияДо !== undefined && хост.расп(S, кто) >= у.доверияДо) return false;
  if (у.деньгиОт !== undefined && S.герой.кошель < у.деньгиОт) return false;
  for (const x of [].concat(у.предмет ?? [])) if (!естьВещь(S, x)) return false;
  for (const x of [].concat(у.безПредмета ?? [])) if (естьВещь(S, x)) return false;
  if (у.вошёл !== undefined && !!S.сцена.вошёл !== у.вошёл) return false;
  if (у.тема && !S.мир.темы.includes(у.тема)) return false;
  if (у.нетТемы && S.мир.темы.includes(у.нетТемы)) return false;
  if (у.ходыОт !== undefined && S.сцена.ходы < у.ходыОт) return false;
  if (у.визитовОт !== undefined && хост.визитов(S) < у.визитовОт) return false;
  if (у.визитовДо !== undefined && хост.визитов(S) >= у.визитовДо) return false;
  if (у.начало && ![].concat(у.начало).includes(S.герой.начало)) return false;
  if (у.ремесло && !S.герой.ремёсла?.[у.ремесло]) return false;
  if (у.голос && !слышен(S, у.голос)) return false;
  if (у.обязательство) {
    const о = S.мир.обязательства?.[у.обязательство.ид];
    const статус = у.обязательство.статус === 'открыто' ? 'активно' : у.обязательство.статус;
    if ((о?.статус ?? 'нет') !== статус) return false;
  }
  if (у.веткаПройдена && !память(S, кто).ветки[у.веткаПройдена]?.исход) return false;
  if (у.не && если(S, у.не, кто)) return false;
  if (у.любое && !у.любое.some(x => если(S, x, кто))) return false;
  return true;
}

// ── лента ───────────────────────────────────────────────────────────────
function вЛенту(S, з) {
  const л = S.сцена.диалог.лента;
  л.push(з);
  if (л.length > ЛЕНТА_МАКС) л.splice(0, л.length - ЛЕНТА_МАКС);
}
// Строки узла: строка «— …» — речь человека, остальное — рассказчик. Элемент может быть { если, т } или { видят: true }.
function строкиУзла(S, список, имя) {
  for (const э of список ?? []) {
    if (typeof э === 'string') { вЛенту(S, э.startsWith('— ') ? { вид: 'нпс', кто: имя, т: э } : { вид: 'нарратив', т: э }); continue; }
    if (э.видят) { видятСтрока(S); continue; }
    if (!если(S, э.если)) continue;
    const т = typeof э.т === 'function' ? э.т(S) : э.т;
    if (т) вЛенту(S, т.startsWith('— ') || э.нпс ? { вид: 'нпс', кто: имя, т } : { вид: 'нарратив', т });
  }
}
// «Видят»: одна строка о том, что человек замечает по герою (голодное лицо, холод, шаг). Первая подошедшая.
function видятСтрока(S) {
  const в = граф(S).видят?.find(x => если(S, x.если));
  if (в) вЛенту(S, { вид: 'видят', т: в.т });
}

// ── вход в ветку и узел ─────────────────────────────────────────────────
const ходовВетки = (S, в, id) => ((память(S, S.сцена.диалог.кто).ветки[id]?.исход && память(S, S.сцена.диалог.кто).ветки[id].исход !== 'провал') ? 0 : (в.ходы ?? 1));

export function веткаДоступна(S, id) {
  const г = графЧеловека(S, S.сцена.диалог?.кто ?? хост.собеседник(S)), в = г?.ветки[id];
  if (!в || в.толькоУДвери) return false;
  return если(S, в.если, г.человек) && (хост.визитов(S) >= 2 || !!в.первая || !!в.внеХаба);
}

function войтиВУзел(S, id) {
  const д = S.сцена.диалог, в = ветка(S, д.ветка), у = в.узлы[id];
  if (!у) throw new Error(`диалог ${д.кто}: у ветки «${д.ветка}» нет узла «${id}»`);
  д.узел = id;
  тикУзла(S);
  строкиУзла(S, typeof у.текст === 'function' ? у.текст(S) : у.текст, граф(S).имя);
  // голоса: пассивные проверки (раз на строку за сейв) и нужды
  const канд = [];
  (у.голоса ?? []).forEach(г => {
    if (!если(S, г.если)) return;
    const ид = `${д.кто}:${д.ветка}:${id}:${г.ид}`;
    if (S.мир.голоса.показано[ид]) return;
    let пас = false;
    if (г.проверка) {
      if (!слышен(S, г.проверка.голос ?? г.голос)) return;
      пас = пассивная(S, `пас:${ид}`, { голос: г.голос, тип: 'пассивная', ...г.проверка });
      if (!пас) return; // провал ничего не показывает
    }
    канд.push({ ид, голос: г.голос, т: г.т, открывает: г.открывает, первый: г.открывает === г.голос, зарубка: пас && г.зарубка !== false, пассивныйУспех: пас, приоритет: приоритет(S, г, пас) });
  });
  for (const в_ of выбрать(S, канд)) {
    if (в_.открывает) открыть(S, в_.открывает);
    if (в_.зарубка) зарубка(S, в_.голос);
    вЛенту(S, { вид: 'врезка', голос: в_.голос, цвет: ГОЛОСА[в_.голос].цвет, т: в_.т });
  }
  [].concat(у.при ?? []).forEach((п, i) => {
    const э = п.э ?? п;
    if (п.э && !если(S, п.если)) return;
    применитьЭ(S, э, { ветка: д.ветка, ид: `при:${id}:${i}` });
  });
}

// Вход в ветку: цена ходов, память, стартовый узел. Возврат — false, если ходов не хватает.
export function войтиВВетку(S, кто, id, откуда = null, бездыхания = false) {
  const г = графЧеловека(S, кто), в = г.ветки[id];
  const м = памятьВетки(S, кто, id);
  const цена = ходовВетки(S, в, id);
  if (цена && (Д(S).ходов - S.сцена.ходы) <= цена) return false;
  S.сцена.диалог = S.сцена.диалог ?? { кто, лента: [] };
  const д = S.сцена.диалог;
  Object.assign(д, { кто, режим: 'ветка', ветка: id, узел: null, откуда });
  // Пройденная ветка (исход не «провал»): короткая «уже говорили», ничего не начисляется, ходы не тратятся.
  if (м.исход && м.исход !== 'провал' && в.уже) {
    if (!бездыхания) вЛенту(S, { вид: 'герой', т: в.реплика ?? в.ярлык });
    вЛенту(S, { вид: 'нпс', кто: г.имя, т: в.уже[(S.мир.день + м.входов) % в.уже.length] });
    м.входов += 1;
    вернутьсяКИсточнику(S);
    return true;
  }
  м.входов += 1;
  if (в.реплика && !бездыхания) вЛенту(S, { вид: 'герой', т: в.реплика });
  if (цена) хост.времяИдёт(S, цена);
  // Манера ветки: «любит» человека даёт доверие один раз за ветку, «обижает» отнимает
  const ч = Д(S).ЛЮДИ[кто];
  if (в.манера && ч) {
    if (ч.любит === в.манера) применитьЭ(S, { распол: { [кто]: 1 } }, { ветка: id, ид: 'манера-ветки' });
    else if (ч.обижает === в.манера) применитьЭ(S, { распол: { [кто]: -1 } }, { ветка: id, ид: 'манера-ветки' });
  }
  войтиВУзел(S, в.старт ?? 'старт');
  return true;
}

function вернутьсяКИсточнику(S) {
  const д = S.сцена.диалог, о = д.откуда;
  д.откуда = null;
  if (о?.режим === 'ветка') { д.режим = 'ветка'; д.ветка = о.ветка; д.узел = о.узел; } else { д.режим = 'хаб'; д.ветка = null; д.узел = null; }
}

export function закрыть(S) {
  const д = S.сцена.диалог;
  if (д) { д.режим = null; д.ветка = null; д.узел = null; }
}

// Начало разговора с человеком (кнопка «Заговорить»): первая встреча — вступление и вежливые ветки, дальше хаб.
export function начать(S, кто) {
  const г = графЧеловека(S, кто);
  const п = память(S, кто);
  const первая = !п.встреч;
  // знакомство — отдельный факт, а не наличие технической записи человека (S.мир.люди создаётся от любого вопроса)
  (S.мир.люди[кто] ??= { спрошено: [], исчерпано: [] }).знаком = true;
  const прежняяЛента = S.сцена.диалог?.кто === кто ? S.сцена.диалог.лента : [];
  S.сцена.диалог = { кто, режим: 'хаб', ветка: null, узел: null, откуда: null, лента: прежняяЛента, комната: S.сцена.комната };
  вЛенту(S, { вид: 'нарратив', т: Д(S).КОМНАТЫ[S.сцена.комната].текст });
  вЛенту(S, { вид: 'нарратив', т: первая ? (г.вступление ?? '') : (г.снова ?? г.вступление ?? '') });
  видятСтрока(S);
  п.встреч = (п.встреч ?? 0) + 1;
}

// Вход в диалог у двери: ветка «вход» начинается сама, когда герой пришёл в место.
export function начатьУДвери(S, кто) {
  const г = графЧеловека(S, кто);
  if (!г?.дверь) return false;
  S.сцена.диалог = { кто, режим: 'ветка', ветка: null, узел: null, откуда: null, лента: [], комната: S.сцена.комната };
  вЛенту(S, { вид: 'нарратив', т: Д(S).КОМНАТЫ[S.сцена.комната].текст });
  (S.мир.люди[кто] ??= { спрошено: [], исчерпано: [] }).знаком = true;
  войтиВВетку(S, кто, г.дверь);
  return true;
}

// Уход через дверь: ветка «выход» (прощание по тому, что ты сделал; возврат сданного делает финал).
export function выйти(S, кто) {
  S.сцена.диалог = { кто, режим: 'ветка', ветка: null, узел: null, откуда: null, лента: S.сцена.диалог?.лента ?? [], комната: S.сцена.комната };
  войтиВВетку(S, кто, 'выход');
}

// ── эффекты ─────────────────────────────────────────────────────────────
// Свои ключи диалога + весь старый мини-язык эффектов места. Доверие и дом за один и тот же вариант и исход даются раз.
export function применитьЭ(S, э, ctx = {}) {
  if (!э) return;
  if (э.один !== undefined) {
    const ключ = `д:${S.сцена.диалог?.кто}:${э.один}`;
    if (S.мир.выдано[ключ]) return;
    S.мир.выдано[ключ] = S.мир.день;
  }
  const д = S.сцена.диалог, кто = д?.кто;
  let рест = { ...э };
  const ключ = ctx.ветка && ctx.ид ? ctx.ид : null;
  if (ключ && кто) {
    const м = памятьВетки(S, кто, ctx.ветка);
    if (m_has(м.награды, ключ)) { delete рест.распол; delete рест.дом; delete рест.зарубка; delete рест.обещание; } else m_set(м.награды, ключ);
  }
  if (рест.слух) датьТему(S, рест.слух, СЛЫШАЛ, S.сцена.место);
  if (рест.факт && кто && !память(S, кто).факты.includes(рест.факт)) память(S, кто).факты.push(рест.факт);
  if (рест.открыть) открыть(S, рест.открыть);
  if (рест.зарубка) зарубка(S, рест.зарубка);
  if (рест.тень) S.мир.тень = Math.min(3, Math.max(0, (S.мир.тень ?? 0) + рест.тень));
  if (рест.сдатьОружие) сдатьНож(S);
  if (рест.обещание) {
    const о = рест.обещание;
    взятьОбязательство(S, { id: о.ид, название: о.что, срок: { день: S.мир.день + (о.дней ?? 3), отрезок: 'вечер', граница: 'конец' } });
  }
  if (рест.выполнено) закрытьОбязательство(S, рест.выполнено);
  for (const к of ['слух', 'факт', 'открыть', 'зарубка', 'тень', 'сдатьОружие', 'обещание', 'выполнено', 'один']) delete рест[к];
  хост.применить(S, рест);
}
const m_has = (о, к) => Object.prototype.hasOwnProperty.call(о, к);
const m_set = (о, к) => { о[к] = true; };

// ── варианты ────────────────────────────────────────────────────────────
export function варианты(S) {
  const д = S.сцена.диалог, в = ветка(S, д.ветка), у = в.узлы[д.узел];
  const вых = [];
  for (const в_ of у.варианты ?? []) {
    if (!если(S, в_.если)) continue;
    const тратит = (в_.стоит ?? 0) + (в_.стоитЕщё ?? 0); // стоит — плата сразу; стоитЕщё — добавка при провале (видна игроку заранее)
    const ид = `${д.кто}:${д.ветка}:${в_.ид}`;
    const к = в_.проверка ? карточка(S, ид, { голос: в_.проверка.голос, ...в_.проверка }, {}) : null;
    const мало = тратит > S.герой.кошель;
    const закрыта = к && !к.можно;
    вых.push({
      ид: в_.ид, текст: в_.текст, подпись: в_.стоит ? `${в_.стоит} гр.${в_.стоитЕщё ? ` (${тратит} при провале)` : ''}` : '',
      метка: к ? `${к.голос} · ${к.слово} · ${к.шанс}%` : '', карточка: к,
      красная: !!(к && к.тип === 'красная'), ещёРаз: !!(к && к.ещёРаз), закреплён: !!в_.закреплён,
      можно: !мало && !закрыта, почему: закрыта ? к.почему : мало ? 'не хватает грошей' : null,
    });
  }
  return вых.sort((a, b) => Number(a.закреплён) - Number(b.закреплён));
}

export function выбратьВариант(S, ид) {
  const д = S.сцена.диалог, в = ветка(S, д.ветка), у = в.узлы[д.узел];
  const в_ = (у.варианты ?? []).find(x => x.ид === ид);
  if (!в_ || !если(S, в_.если)) return false;
  const вид = варианты(S).find(x => x.ид === ид);
  if (!вид?.можно) return false;
  const г = граф(S), идП = `${д.кто}:${д.ветка}:${ид}`;
  вЛенту(S, { вид: 'герой', т: в_.эхо ?? в_.текст });

  // манера: «любит» человека даёт доверие один раз за вариант, «обижает» — отнимает
  const ч = Д(S).ЛЮДИ[д.кто];
  let рез = в_;
  let исход = 'всегда';
  if (в_.проверка) {
    const п = { голос: в_.проверка.голос, ...в_.проверка };
    const б = бросить(S, идП, п, {});
    исход = б.успех ? 'успех' : 'провал';
    вЛенту(S, { вид: 'бросок', тип: в_.проверка.тип ?? 'белая', голос: п.голос, цвет: ГОЛОСА[п.голос]?.цвет, успех: б.успех,
      т: `${п.голос} · порог ${б.порог} · мод ${б.мод.значение >= 0 ? '+' : ''}${б.мод.значение} · ${б.кубики[0]}+${б.кубики[1]} → ${б.сумма} · ${б.успех ? 'УСПЕХ' : 'ПРОВАЛ'}`,
      части: б.мод.части, шанс: б.шанс, попытка: б.попытка });
    if (в_.проверка.голос && ГОЛОСА[п.голос]?.группа !== 'нужды') открыть(S, п.голос);
    if (б.успех) зарубкаПоДелу(S, п.голос);
    рез = (б.успех ? в_.успех : в_.провал) ?? {};
  }
  if (в_.манера && ч) {
    if (ч.любит === в_.манера) применитьЭ(S, { распол: { [д.кто]: 1 } }, { ветка: д.ветка, ид: `манера:${ид}` });
    else if (ч.обижает === в_.манера) применитьЭ(S, { распол: { [д.кто]: -1 } }, { ветка: д.ветка, ид: `манера:${ид}` });
  }
  const эф = в_.проверка ? рез.эффект : (в_.эффект ?? null);
  const общий = в_.проверка ? в_.эффект : null; // эффект «в любом случае» рядом с проверкой
  if (общий) применитьЭ(S, общий, { ветка: д.ветка, ид: `${ид}:всегда` });
  if (эф) применитьЭ(S, эф, { ветка: д.ветка, ид: `${ид}:${исход}` });
  // заранее написанный итог: человек и голоса
  строкиУзла(S, рез.ответ, г.имя);
  for (const gl of рез.голоса ?? []) {
    if (!если(S, gl.если)) continue;
    const идСтроки = `${идП}:${gl.ид ?? gl.голос}`;
    if (S.мир.голоса.показано[идСтроки]) continue;
    записатьСтроку(S, идСтроки, gl.голос);
    if (gl.открывает) открыть(S, gl.открывает);
    вЛенту(S, { вид: 'врезка', голос: gl.голос, цвет: ГОЛОСА[gl.голос]?.цвет, т: gl.т });
  }
  const дальше = рез.дальше ?? в_.дальше;
  движениеДальше(S, дальше, рез.исход ?? в_.исход);
  return true;
}
function зарубкаПоДелу(S, голос) { if (ГОЛОСА[голос]?.группа !== 'нужды') зарубка(S, голос); }

function движениеДальше(S, дальше, исход) {
  const д = S.сцена.диалог;
  if (S.сцена.конец) return; // вечер кончился в эффекте: итог уже посчитан
  if (!дальше) return;
  if (typeof дальше === 'object' && дальше.ветка) {
    войтиВВетку(S, д.кто, дальше.ветка, { режим: 'ветка', ветка: д.ветка, узел: д.узел }, true);
    return;
  }
  if (дальше === 'хаб' || дальше === 'назад' || дальше === 'закрыть') {
    if (д.ветка && исход !== false) {
      const м = памятьВетки(S, д.кто, д.ветка);
      if ((!м.исход || м.исход === 'провал') && (исход || ветка(S, д.ветка).засчитывать !== false)) м.исход = исход || 'пройдена';
    }
    if (дальше === 'закрыть') { закрыть(S); return; }
    if (дальше === 'назад' && д.откуда) { вернутьсяКИсточнику(S); return; }
    вернутьсяКИсточнику(S); // из ветки, начатой у двери, — обратно к двери; из хаба — в хаб
    return;
  }
  войтиВУзел(S, дальше);
}

