export function диалогАктивен(S) {
  const д = S.сцена?.диалог;
  return !!(д && д.режим && д.комната === S.сцена.комната);
}

// Добавляет действия диалога через добавить() из разговор.js (снимок для отката делает он).
export function действия(S, добавить) {
  const д = S.сцена.диалог, г = граф(S);
  if (д.режим === 'ветка') {
    for (const в of варианты(S)) {
      добавить({ id: `вариант:${д.ветка}:${в.ид}`, вид: 'вариант', текст: в.текст, подпись: в.подпись, метка: в.метка, красная: в.красная, ещёРаз: в.ещёРаз,
        закреплён: в.закреплён, можно: в.можно, почему: в.почему, карточка: в.карточка },
      S2 => { выбратьВариант(S2, в.ид); });
    }
    return;
  }
  // хаб
  for (const id of г.хаб) {
    if (!веткаДоступна(S, id)) continue;
    const в = г.ветки[id], м = память(S, д.кто).ветки[id];
    const ц = ходовВетки(S, в, id);
    const мало = ц && (Д(S).ходов - S.сцена.ходы) <= ц;
    добавить({ id: `ветка:${id}`, вид: 'ветка', текст: в.ярлык, подпись: м?.исход ? 'уже говорили' : ц === 0 ? 'даром' : ц === 1 ? '1 ход' : `${ц} хода`,
      можно: !мало, почему: мало ? 'не успеть: вечер кончится' : null },
    S2 => { войтиВВетку(S2, д.кто, id, { режим: 'хаб' }); });
  }
  добавить({ id: 'отойти', вид: 'отойти', текст: 'Отойти', закреплён: true },
    S2 => { S2.сцена.собеседник = null; S2.сцена.диалог.режим = null; S2.сцена.реплика = ''; S2.сцена.мояреплика = ''; });
}

export function видДиалога(S) {
  const д = S.сцена.диалог;
  return { кто: д.кто, имя: граф(S).имя, режим: д.режим, лента: д.лента, ветка: д.ветка ? ветка(S, д.ветка).ярлык : null };
}
