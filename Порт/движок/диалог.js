// Диалоги как граф (ПЛАН_ДОРАБОТКИ П05, концепт диалогов): человек → хаб → ветка → узел → вариант.
// Чистая логика, без DOM. Имён не знает: всё про человека, ветки и реплики лежит в данные/места/*.js (ДИАЛОГИ) и данные/диалоги/*.js.
// Что здесь решается: что стоит ходов, что видно в ленте, какие голоса вмешались, как падают кубики и что начисляется один раз.
//
// Экономика ходов (концепт §5.3): платит ВХОД в новую ветку (1 ход, у «долгих» — 2), реплики внутри ветки, осмотр, голоса
// и проверки — 0. Возврат в пройденную ветку — 0, человек отвечает короткой «уже говорили», доверие не растёт.
