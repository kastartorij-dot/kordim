// Смена: работа как короткое событие (ГДД §14–§16, Порт-работы-задание.md). Без DOM, без имён.
// Кнопка работы не платит сразу, а открывает смену: S.мир.смена — карточка (случай из колоды работы) или
// выбор соперника (ставка). Деньги, цена, зарубки, очки фракций, время — всё применяется в одном месте,
// завершить(), ПОСЛЕ чего тратится отрезок: так конец дня видит всё, что случилось на смене.
