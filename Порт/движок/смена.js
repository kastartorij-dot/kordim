const зажать = (от, до, v) => Math.max(от, Math.min(до, v));
const зн = n => (n > 0 ? '+' : '−') + Math.abs(n);
const запись = (S, с) => { S.мир.журналДня.push(с); return с; };

export function счёт(S, id) { return (S.мир.работы[id] ??= { смен: 0, видели: [], дни: [], последний: null }); }

function длинаСерии(S, р) {
  const с = S.герой.серии[р.id], день = S.мир.день;
  return с && с.день === день ? с.длина : с && с.день === день - 1 ? с.длина + 1 : 1;
}

// Усталость от нескольких смен за день (против гринда, ГДД §14): вторая смена стоит лишний отдых −1, третья и дальше — −2.
// «Лёгкие» работы (баня, кухня) не считаются и не добавляют. Так три смены в день — это не доход, а долг перед телом.
export function допОтдых(S, р) {
  if (р.лёгкая) return 0;
  const с = S.мир.сменДень;
  return с && с.день === S.мир.день ? Math.min(2, с.n) : 0;
}

// Что заплатят и почему. Ступень ремесла, рыночный день, серия, ученичество, премия «чтец молчит».
export function условияПлаты(S, р) {
  const ученик = !!(р.ученичество && р.ремесло && !хватает(S, р.ремесло));
  const длина = длинаСерии(S, р);
  let к = 1;
  if (р.ремесло && !ученик) к *= р.ступени ? (р.ступени[ступеньНомер(S, р.ремесло)] ?? 1) : множительСтупени(S, р.ремесло);
  if (ученик) к *= р.ученичество.плата;
  if (р.серия && длина >= р.серия.с) к *= р.серия.множитель;
  if (р.рынок && рыночныйДень(S.мир.день)) к *= р.рынок;
  if (р.премияФлаг && S.мир.флаги.includes(р.премияФлаг.флаг)) к *= р.премияФлаг.множитель;
  const платит = р.плата ? Math.max(1, Math.round(р.плата * к)) : 0;
  return { платит, длина, ученик, садится: !!(р.серия && длина >= р.серия.с) };
}

// Можно ли взять работу прямо сейчас. видна:false — кнопки нет вовсе.
export function доступность(S, р) {
  const м = S.мир, т = S.герой.тело;
  if (р.скрыто && !условие(S, р.скрыто)) return { видна: false };
  const { ученик } = условияПлаты(S, р);
  const нет = почему => ({ видна: true, можно: false, почему });
  if (т.цел === 0) return нет('слишком разбит, чтобы работать');
  if (р.физическая && т.сыт === 0) return нет('нет сил');
  if (р.людная && (S.герой.вид ?? 3) <= 1) return нет('в таком виде к людям не подпустят');
  if (р.фракцияХозяин && (м.фракции[р.фракцияХозяин] ?? 0) <= -1) return нет('тебе здесь отказывают');
  if (р.допуск) {
    const { почему, ремесло: рем, ...остальное } = р.допуск;
    if (!условие(S, остальное)) return нет(почему ?? 'не берут');
    if (рем && !условие(S, { ремесло: рем }) && !р.ученичество) return нет(почему ?? `нужно ремесло «${рем.имя}»`);
  }
  const сч = м.работы?.[р.id];
  if (р.вДень && (сч?.дни ?? []).filter(д => д === м.день).length >= р.вДень) return нет('на сегодня хватит');
  if (р.лимит && (сч?.дни ?? []).filter(д => д > м.день - р.лимит.за).length >= р.лимит.раз) return нет('ждут в другие дни');
  if (р.цена?.расходники && S.герой.кошель < р.цена.расходники) return нет('нет денег на расходники');
  return { видна: true, можно: true, почему: null, ученик };
}

function подписьРаботы(S, р, ученик, платит) {
  const о = р.отрезков * (отрезковНа(S));
  const части = [];
  if (р.ставка) части.push('ставка на круге');
  else части.push(`+${платит} гр.`);
  части.push(о === 1 ? '1 отрезок' : `${о} отрезка`);
  const отд = (р.цена?.отдых ?? 0) + допОтдых(S, р);
  if (отд) части.push(`отдых −${отд}`);
  if (р.цена?.расходники) части.push(`расходники ${р.цена.расходники} гр.`);
  if (р.цена?.риск) части.push('риск: цел −1');
  if (ученик) части.push('учеником');
  return части.join(' · ');
}

// Кнопки работ этого района и отрезка — их подмешивает движок/действия.js.
export function действияРаботы(S) {
  const А = [];
  for (const р of РАБОТЫ) {
    if (!р.открыто || !(Array.isArray(р.где) ? р.где : [р.где]).includes(S.мир.район) || !р.когда.includes(S.мир.отрезок)) continue;
    const д = доступность(S, р);
    if (!д.видна) continue;
    const { платит, ученик } = условияПлаты(S, р);
    А.push({
      id: `работа:${р.id}`, вид: 'работа', группа: 'здесь', текст: ученик ? `Ученик: ${р.имя}` : р.имя,
      подпись: подписьРаботы(S, р, ученик, платит), отрезков: р.отрезков, можно: д.можно, почему: д.почему,
      выполнить(S2) {
        // условие могло устареть между построением списка и кликом (ГДД §21, правило плейтеста 19.09)
        if (S2.мир.смена || S2.сцена) return null;
        if (!(Array.isArray(р.где) ? р.где : [р.где]).includes(S2.мир.район) || !р.когда.includes(S2.мир.отрезок)) return null;
        if (!доступность(S2, р).можно) return null;
        return начатьСмену(S2, р);
      },
    });
  }
  return А;
}

// Текст может быть строкой или списком кусков: строка или { если: условие, т: текст }. Куски склеиваются через пустую строку.
export function собратьТекст(S, т) {
  if (typeof т === 'string' || т == null) return т ?? '';
  return т.filter(к => typeof к === 'string' || условие(S, к.если)).map(к => (typeof к === 'string' ? к : к.т)).join('\n\n');
}

// ── случай ──────────────────────────────────────────────────────────────
// Нить (сюжет) идёт первой, но не чаще раза в день; иначе — случайный по весам, не тот же, что в прошлый раз.
function выбратьСлучай(S, р) {
  const сч = счёт(S, р.id);
  const годные = р.колода.filter(с => условие(S, с.условие) && !(с.однажды && сч.видели.includes(с.id)));
  const нити = годные.filter(с => с.нить);
  if (нити.length && S.мир.нитьДень !== S.мир.день) return нити[0];
  const обычные = годные.filter(с => !с.нить && с.id !== сч.последний);
  const пул = обычные.length ? обычные : годные.filter(с => !с.нить);
  if (!пул.length) return null;
  const сумма = пул.reduce((а, с) => а + (с.вес ?? 1), 0);
  let х = бросок(S) * сумма;
  for (const с of пул) { х -= с.вес ?? 1; if (х < 0) return с; }
  return пул[пул.length - 1];
}

export function случайСмены(S) {
  const см = S.мир.смена;
  if (!см?.случай) return null;
  return работа(см.работа).колода.find(с => с.id === см.случай) ?? null;
}

export function начатьСмену(S, р) {
  const { платит, длина, ученик } = условияПлаты(S, р);
  S.мир.смена = { работа: р.id, район: S.мир.район, старт: S.мир.отрезок, плата: платит, длина, ученик, стадия: р.ставка ? 'соперник' : 'выбор', случай: null, итог: null };
  if (р.ставка) return `${р.имя}: круг`;
  const с = выбратьСлучай(S, р);
  S.мир.смена.случай = с?.id ?? null;
  if (с?.нить) S.мир.нитьДень = S.мир.день;
  if (!с || !с.выбор?.length) завершить(S, null);
  return `${р.имя}: смена`;
}

// ── завершение ──────────────────────────────────────────────────────────
function завершить(S, выбор, соперник = null) {
  const см = S.мир.смена, р = работа(см.работа), с = случайСмены(S);
  const ctx = { откуда: `работа:${р.id}`, источник: 'смена', бонусШанса: р.ремесло ? 0.1 * Math.max(0, ступеньНомер(S, р.ремесло)) : 0 };
  const строки = [];
  const журнал = [];
  const м = S.мир, г = S.герой;
  const сч = счёт(S, р.id);

  // деньги и цена
  let плата = см.плата;
  if (соперник) плата = 0; // на круге платит исход, не смена
  if (плата) { г.кошель += плата; строки.push(`${зн(плата)} гр.`); }
  журнал.push(`${р.имя}: ${плата ? `+${плата} гр.` : 'смена'}`);
  if (р.цена?.расходники) { г.кошель = Math.max(0, г.кошель - р.цена.расходники); строки.push(`−${р.цена.расходники} гр. на расходники`); }
  const отд = (р.цена?.отдых ?? 0) + допОтдых(S, р);
  if (отд) { г.тело.отдых = зажать(0, МАКС, г.тело.отдых - отд); строки.push(`отдых −${отд}`); }
  if (!р.лёгкая) { const с = м.сменДень; м.сменДень = с && с.день === м.день ? { день: м.день, n: с.n + 1 } : { день: м.день, n: 1 }; }
  if (р.цена?.риск) {
    const защита = (ступеньНомер(S, р.ремесло) >= 1 ? 0.1 : 0) + (ступеньНомер(S, р.ремесло) >= 2 ? 0.1 : 0);
    if (бросок(S) < р.цена.риск.шанс - защита) {
      г.тело.цел = зажать(0, МАКС, г.тело.цел + р.цена.риск.цел);
      строки.push(`цел ${зн(р.цена.риск.цел)}`);
    }
  }
  if (р.эффект) строки.push(...применитьЭффект(S, р.эффект, ctx));
  if (р.грязная) { м.грязь = м.день; }

  // ремесло: зарубка или учёба
  if (р.ремесло) {
    if (см.ученик) {
      const у = (г.ученичество ??= {});
      у[р.ремесло] = (у[р.ремесло] ?? 0) + 1;
      if (у[р.ремесло] >= ОБУЧЕНИЕ[р.ремесло].уроков) { датьРемесло(S, р.ремесло); строки.push(`Ремесло «${р.ремесло}»: умеешь`); }
    } else {
      const рос = зарубка(S, р.ремесло, 1);
      if (рос) строки.push(рос);
    }
  }
  // очки фракций за смену
  const оч = { ...(р.фракции ?? {}), ...(р.фракцииПоРайону?.[см.район] ?? {}) };
  for (const [к, n] of Object.entries(оч)) {
    const ст = добавитьОчки(S, к, n, 'смена');
    if (ст) строки.push(`${ФРАКЦИИ[к]}: ${СЛОВА[String(ст[2])]}`);
  }

  // случай и выбор
  let текстИтога = null;
  if (с) {
    if (с.эффект) строки.push(...применитьЭффект(S, с.эффект, { ...ctx, источник: с.нить ? 'нить' : 'смена' }));
    if (с.журнал) журнал.push(с.журнал);
    if (выбор !== null) {
      const о = с.выбор[выбор];
      if (о.стоит) { г.кошель = Math.max(0, г.кошель - о.стоит); строки.push(`−${о.стоит} гр.`); }
      if (о.эффект) строки.push(...применитьЭффект(S, о.эффект, { ...ctx, источник: с.нить ? 'нить' : 'смена' }));
      if (о.журнал) журнал.push(о.журнал);
      текстИтога = о.итог !== undefined ? собратьТекст(S, о.итог) : null;
    }
    if (с.однажды && !сч.видели.includes(с.id)) сч.видели.push(с.id);
    сч.последний = с.id;
  }
  if (соперник) {
    текстИтога = соперник.текст;
    // Нить после боя: первый подходящий случай колоды (однажды), его текст дописывается к итогу.
    const пост = р.колода.find(x => x.нить && условие(S, x.условие) && !(x.однажды && сч.видели.includes(x.id)));
    if (пост) {
      строки.push(...применитьЭффект(S, пост.эффект, { ...ctx, источник: 'нить' }));
      текстИтога += '\n\n' + собратьТекст(S, пост.текст);
      if (пост.однажды) сч.видели.push(пост.id);
    }
  }
  if (соперник?.строки) строки.push(...соперник.строки);

  // учёт
  сч.смен += 1; сч.дни.push(м.день);
  if (сч.дни.length > 40) сч.дни.splice(0, сч.дни.length - 40);
  if (р.серия) г.серии[р.id] = { день: м.день, длина: см.длина };
  for (const ж of журнал) запись(S, ж);

  см.стадия = 'итог';
  см.итог = { текст: текстИтога ?? (с && !с.выбор?.length ? собратьТекст(S, с.текст) : null), строки };
  const ещё = ctx.допОтрезков ?? 0;
  // время — последним: конец дня должен увидеть всё выше
  const деньСмены = м.день;
  for (let i = 0; i < р.отрезков + ещё; i++) { if (м.день !== деньСмены) break; потратитьОтрезок(S); }
  return см.итог;
}

// ── ставка (кулачный бой и любая другая: данные описывают, движок считает) ─────────
export function шансПобеды(S, ставка, соп) {
  const мод = ставка.мод, т = S.герой.тело;
  let ш = соп.шанс;
  ш += мод.ступень[ступеньНомер(S, 'кулак')] ?? 0;
  for (const [ф, д] of Object.entries(мод.флаги ?? {})) if (S.мир.флаги.includes(ф)) ш += д;
  if (т.сыт === 1) ш += мод.сыт1; if (т.отдых === 1) ш += мод.отдых1; if (т.цел === 2) ш += мод.цел2;
  return зажать(мод.минимум, мод.максимум, ш);
}
const слово = п => (п >= 0.6 ? 'хороший' : п >= 0.42 ? 'средний' : 'небольшой');

function выбратьТекст(S, список) { return список[Math.floor(бросок(S) * список.length)]; }

function драться(S, р, соп) {
  const п = шансПобеды(S, р.ставка, соп);
  const победа = бросок(S) < п;
  const строки = [];
  const ctx = { откуда: 'работа:бой', источник: 'смена' };
  let текст;
  if (победа) {
    S.герой.кошель += соп.кошелёк;
    строки.push(`+${соп.кошелёк} гр.`);
    строки.push(...применитьЭффект(S, соп.победа.эффект, ctx));
    текст = выбратьТекст(S, соп.победа.тексты);
  } else {
    строки.push(...применитьЭффект(S, соп.поражение.эффект, ctx));
    текст = выбратьТекст(S, соп.поражение.тексты);
  }
  for (const ф of Object.keys(р.ставка.мод.флаги ?? {})) if (S.мир.флаги.includes(ф) && р.ставка.мод.флаги[ф] > 0) применитьЭффект(S, { снятьФлаг: ф }, ctx);
  применитьЭффект(S, { счётчик: победа ? { бои: 1, победы: 1 } : { бои: 1 } }, ctx);
  return { текст, строки, победа };
}

// ── действия карточки: их возвращает доступныеДействия, пока смена не закрыта ────────
export function действияСмены(S) {
  const см = S.мир.смена;
  if (!см) return null;
  const р = работа(см.работа), с = случайСмены(S);
  const А = [];
  const кн = (id, текст, подпись, можно, почему, шаг) => А.push({ id, вид: 'смена', группа: 'смена', текст, подпись, отрезков: 0, можно, почему,
    выполнить(S2) { if (!S2.мир.смена) return null; шаг(S2); return null; } });

  if (см.стадия === 'итог') {
    кн('смена:дальше', 'Дальше', '', true, null, S2 => { S2.мир.смена = null; });
  } else if (см.стадия === 'соперник') {
    for (const [i, соп] of р.ставка.соперники.entries()) {
      if (!условие(S, соп.условие)) continue;
      const п = шансПобеды(S, р.ставка, соп);
      кн(`смена:соперник:${i}`, соп.имя, `${соп.кошелёк} гр. · шанс ${слово(п)} · при поражении ${соп.поражение.подпись}`, true, null, S2 => {
        if (S2.мир.смена?.стадия !== 'соперник') return;
        const исход = драться(S2, р, соп);
        S2.мир.смена.случай = null;
        завершить(S2, null, исход);
      });
    }
    кн('смена:отмена', 'Уйти с круга', 'ничего не потрачено', true, null, S2 => { S2.мир.смена = null; });
  } else {
    const варианты = с.выбор.map((о, i) => ({ о, i })).filter(({ о }) => условие(S, о.условие));
    for (const { о, i } of варианты) {
      const мало = о.стоит && S.герой.кошель < о.стоит;
      кн(`смена:выбор:${i}`, о.текст, о.стоит ? `${о.стоит} гр.` : '', !мало, мало ? 'нет денег' : null, S2 => {
        if (S2.мир.смена?.стадия !== 'выбор') return;
        if (о.стоит && S2.герой.кошель < о.стоит) return;
        завершить(S2, i);
      });
    }
  }
  return А;
}

// Что показывать на карточке (без вёрстки).
export function видСмены(S) {
  const см = S.мир.смена;
  if (!см) return null;
  const р = работа(см.работа), с = случайСмены(S);
  if (см.стадия === 'итог') return { заголовок: р.имя, текст: см.итог.текст, строки: см.итог.строки, стадия: 'итог' };
  if (см.стадия === 'соперник') return { заголовок: р.имя, текст: р.ставка.вступление, строки: [], стадия: 'соперник' };
  return { заголовок: р.имя, текст: собратьТекст(S, с.текст), строки: [], стадия: 'выбор' };
}

