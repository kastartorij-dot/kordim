// Граница срока задана явно. «До вечера» = до начала вечернего отрезка;
// «до конца вечера» = до начала ночи. Внутри сцены время остаётся временем
// входа, пока герой не выйдет: городской отрезок списан авансом за визит.
const ОТРЕЗКИ = ['утро', 'день', 'вечер', 'ночь'];
const номер = (день, отрезок) => день * 4 + ОТРЕЗКИ.indexOf(отрезок);

export function описаниеСрока(срок) {
  if (срок.визит !== undefined) return 'до выхода из места';
  const родительный = { утро: 'утра', день: 'дня', вечер: 'вечера', ночь: 'ночи' };
  return `до ${срок.граница === 'конец' ? 'конца' : 'начала'} ${родительный[срок.отрезок]} дня ${срок.день}`;
}

export function взятьОбязательство(S, данные) {
  const все = (S.мир.обязательства ??= {});
  if (!данные?.id || все[данные.id]) return false;
  const срок = { ...данные.срок };
  if (срок.визит !== undefined) {
    if (срок.визит === 'текущий') {
      if (!S.сцена) return false;
      срок.визит = S.сцена.номерВизита;
    } else if (!Number.isInteger(срок.визит)) return false;
  } else if (!Number.isInteger(срок.день) || !ОТРЕЗКИ.includes(срок.отрезок)) return false;
  const запись = { id: данные.id, название: данные.название ?? данные.id, срок, статус: 'активно' };
  все[данные.id] = запись;
  S.мир.журналДня.push(`${запись.название}: ${описаниеСрока(срок)}`);
  проверитьСроки(S);
  return запись.статус === 'активно';
}

export function закрытьОбязательство(S, id) {
  проверитьСроки(S);
  const запись = S.мир.обязательства?.[id];
  if (запись?.статус !== 'активно') return false;
  запись.статус = 'выполнено';
  запись.закрыто = { день: S.мир.день, отрезок: S.сцена?.отрезок ?? S.мир.отрезок };
  S.мир.журналДня.push(`${запись.название}: выполнено`);
  return true;
}

export function проверитьСроки(S, выходИзВизита = null) {
  const время = S.сцена?.вход ?? S.мир;
  const сейчас = номер(время.день, время.отрезок);
  for (const запись of Object.values(S.мир.обязательства ?? {})) {
    if (запись.статус !== 'активно') continue;
    const срок = запись.срок;
    const истёк = срок.визит !== undefined
      ? выходИзВизита !== null && срок.визит === выходИзВизита
      : сейчас >= номер(срок.день, срок.отрезок) + (срок.граница === 'конец' ? 1 : 0);
    if (!истёк) continue;
    запись.статус = 'истекло';
    запись.истекло = { день: S.мир.день, отрезок: S.мир.отрезок };
    S.мир.журналДня.push(`${запись.название}: срок истёк`);
  }
}
