// Сводки для экранов «Герой» и «Журнал» (этап 5): что показать, без единой строки вёрстки.
// Все слова состояний — из данные/состояния.js (слово в слово из задания). Без DOM.
import { НАЧАЛА } from '../данные/герой.js';
import { ЖИЛЬЁ } from '../данные/жильё.js';
import { МЕСТА } from '../данные/места.js';
import { РЕЕСТР } from '../данные/темы.js';
import { СВИДЕТЕЛЬСТВА } from '../данные/свидетельства.js';
import { ТЕЛО, В_ПОРЯДКЕ, ФРАКЦИИ, СТУПЕНИ, ТЕНЬ, РЕПУТАЦИЯ } from '../данные/состояния.js';
import { словоОтношения } from './разговор.js';

const зажать = (от, до, v) => Math.max(от, Math.min(до, v));
const число = v => (Number.isFinite(v) ? v : 0);

export function словоРепутации(р) {
  return РЕПУТАЦИЯ.find(x => р <= x.до).слово;
}

export function сводкаГероя(S) {
  const г = S.герой, м = S.мир;
  const начало = НАЧАЛА.find(н => н.id === г.начало);
  const тело = Object.keys(ТЕЛО).map(к => {
    const з = г.тело[к];
    return { ключ: к, название: ТЕЛО[к].название, значение: з, строка: з >= 2 ? В_ПОРЯДКЕ : ТЕЛО[к][з] ?? В_ПОРЯДКЕ };
  });
  const фракции = Object.keys(ФРАКЦИИ).map(к => {
    const з = зажать(-3, 3, число(м.фракции?.[к]));
    return { ключ: к, имя: ФРАКЦИИ[к], значение: з, слово: СТУПЕНИ[String(з)] };
  });
  const реп = зажать(-3, 3, число(м.репутация));
  const тень = зажать(0, 3, число(м.тень));
  const ж = г.жильё;
  const жилье = ж && ж.оплачено_по >= м.день
    ? `${ЖИЛЬЁ.find(x => x.id === ж.id)?.имя ?? ж.id}, оплачено до дня ${ж.оплачено_по}` : 'нет';
  return {
    имя: г.имя,
    начало: начало?.имя ?? г.начало,
    ремёсла: Object.entries(г.ремёсла ?? {}).map(([имя, р]) => ({ имя, ступень: р.ступень, зарубки: р.зарубки })),
    тело,
    положение: { фракции, репутация: { значение: реп, слово: словоРепутации(реп) }, тень: { значение: тень, строка: ТЕНЬ[тень] } },
    жильё: жилье,
  };
}

const ВЕРНОСТЬ = { слышал: 'слух', подтверждено: 'проверено', опровергнуто: 'враньё' };
const ТОЧЕК = 3;
const КОМУ = { ножи: 'знают Ножи', картель: 'знает картель' };

export function сводкаЖурнала(S) {
  const м = S.мир;
  // Темы: все, кроме «ни о чём»; сначала ценные
  const темы = (м.темы ?? []).map(тид => {
    const р = РЕЕСТР[тид];
    const ц = р?.ценность ?? 0;
    return {
      id: тид,
      ярлык: р?.ярлык ?? String(тид),
      верность: ВЕРНОСТЬ[м.знания?.[тид]?.верность] ?? ВЕРНОСТЬ.подтверждено,
      ценность: ц,
      точки: '●'.repeat(ц) + '○'.repeat(ТОЧЕК - ц),
      текст: р?.текст ?? null,
      ушла: (м.ушло?.[тид] ?? '').split(' ').filter(Boolean).map(к => КОМУ[к] ?? к),
      всегда: !!р?.всегда,
    };
  }).filter(т => !т.всегда).sort((a, b) => b.ценность - a.ценность);
  // Люди: с кем говорил
  const люди = Object.keys(м.люди ?? {}).map(id => {
    const пл = МЕСТА.find(x => x.модуль.ЛЮДИ[id]);
    return { id, имя: пл?.модуль.ЛЮДИ[id].имя ?? id, где: пл?.где ?? '', слово: пл ? словоОтношения(S, id, пл.модуль) : '' };
  });
  // Долги: места с долгом больше 0
  const долги = МЕСТА.filter(x => (м.места?.[x.id]?.долг ?? 0) > 0).map(x => ({ место: x.имя, сумма: м.места[x.id].долг }));
  const вклады = МЕСТА.filter(x => (м.места?.[x.id]?.вклад ?? 0) > 0).map(x => ({ место: x.имя, сумма: м.места[x.id].вклад }));
  const свидетельства = (м.свидетельства ?? []).map(id => ({ id, имя: СВИДЕТЕЛЬСТВА[id]?.[0] ?? id, текст: СВИДЕТЕЛЬСТВА[id]?.[1] ?? '' }));
  return { темы, люди, долги, вклады, свидетельства, дни: (м.хроника ?? []).slice(-3) };
}


