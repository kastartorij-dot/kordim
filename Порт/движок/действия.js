// Единый список действий (задание этапа 2, шаг 1). Экран рисует кнопки отсюда,
// бот ходит по нему же. Без DOM. Движок не знает имён: всё про места, еду,
// работы и ночлег приходит из данных/.
import { РАЙОНЫ } from '../данные/районы.js';
import { ЕДА } from '../данные/еда.js';
import { действияРаботы, действияСмены } from './смена.js';
import { ЖИЛЬЁ } from '../данные/жильё.js';
import { потратитьОтрезок, лечьСпать, отрезковНа } from './время.js';
import { бросок } from './случай.js';
import { МАКС } from './тело.js';
import { МЕСТА } from '../данные/места.js';
import { войти, можноВойти } from './разговор.js';
import { ВЕЩИ } from '../данные/вещи.js';
import { положить, можноПоложить, привестиВещи, потерятьВещь, вещь as типВещи } from './вещи.js';
import { доступныеПокупки, доступныеУслуги } from './хозяйство.js';

const зажать = v => Math.max(0, Math.min(МАКС, v));
const запись = (S, строка) => { S.мир.журналДня.push(строка); return строка; };

// Исход «слоняться»: 15% находка (+2 гр.), 15% невезение (тепло −1), иначе просто атмосфера.
// Доля мала и деньги малы нарочно — это должно быть хуже работы, а не бесплатной её заменой.
const НАХОДКА = 0.15, СЛУЧАЙ = 0.15;
function случайнаяСтрока(массив, S) {
  return массив[Math.floor(бросок(S) * массив.length)];
}
function игратьСлоняться(S, сл) {
  if (!сл) return null;
  const р = бросок(S);
  if (р < НАХОДКА && сл.находки?.length) {
    S.герой.кошель += 2;
    return запись(S, `${случайнаяСтрока(сл.находки, S)} (+2 гр.)`);
  }
  if (р < НАХОДКА + СЛУЧАЙ && сл.случаи?.length) {
    S.герой.тело.тепло = зажать(S.герой.тело.тепло - 1);
    return запись(S, `${случайнаяСтрока(сл.случаи, S)} (тепло −1)`);
  }
  return сл.варианты?.length ? запись(S, случайнаяСтрока(сл.варианты, S)) : null;
}

function подписьОтрезков(S, n = 1) {
  const всего = n === 1 ? отрезковНа(S) : n * отрезковНа(S);
  if (S.герой.тело.отдых === 0) return `${всего} отрезка — ты валишься с ног`;
  if (S.герой.тело.цел === 0) return `${всего} отрезка — еле тащишься`;
  return всего === 1 ? '1 отрезок' : `${всего} отрезка`;
}

export function доступныеДействия(S) {
  // Пока смена не закрыта, город стоит: есть только кнопки карточки (движок/смена.js).
  const карточка = действияСмены(S);
  if (карточка) return карточка;
  const А = [];
  const { район, отрезок } = S.мир;

  for (const р of РАЙОНЫ) {
    if (р.id === район) continue;
    А.push({
      id: `переход:${р.id}`, вид: 'переход', группа: 'пойти', текст: р.имя,
      подпись: подписьОтрезков(S), отрезков: 1, можно: true, почему: null,
      выполнить(S) {
        const с = запись(S, `Дорога: ${р.имя}`);
        S.мир.район = р.id;
        потратитьОтрезок(S);
        return с;
      },
    });
  }

  {
    const тек = РАЙОНЫ.find(р => р.id === район);
    const сл = тек?.слоняться;
    А.push({
      id: 'отрезок:здесь', вид: 'ждать', группа: 'здесь',
      текст: отрезок === 'ночь' ? 'Не спать: провести ночь здесь' : (сл?.кнопка ?? 'Провести здесь отрезок'),
      подпись: подписьОтрезков(S), отрезков: 1, можно: true, почему: null,
      выполнить(S) {
        // Мелкая механика, чтобы кнопка не была чистым пропуском времени: изредка либо
        // подворачивается пара грошей, либо не везёт с погодой (тепло −1). Специально мало и
        // ниже дохода от работы (+8/+12 гр.) — иначе это была бы бесплатная работа без риска.
        const с = игратьСлоняться(S, сл);
        потратитьОтрезок(S);
        return с;
      },
    });
  }

  // Места города: видны в своём районе; открыты только в свои отрезки.
  for (const м of МЕСТА) {
    if (м.район !== район) continue;
    const { можно, почему } = можноВойти(S, м.id);
    А.push({
      id: `место:${м.id}`, вид: 'место', группа: 'места', текст: м.имя,
      подпись: `${м.подпись} · ${м.когда.join(', ')}`, отрезков: 1, можно, почему,
      выполнить(S) {
        if (!можноВойти(S, м.id).можно) return null; // условие могло устареть между построением списка и кликом
        const с = запись(S, `${м.имя}: вошёл`);
        войти(S, м.id);
        return с;
      },
    });
  }

  А.push(...действияРаботы(S));

  for (const е of ЕДА) {
    if (!е.где.includes(район) || !е.когда.includes(отрезок)) continue;
    // Еда нужна, пока от неё есть толк: сытость или тепло (похлёбкой греются и сытые).
    const т = S.герой.тело;
    const сыт = т.сыт >= МАКС && !(е.тепло && т.тепло < МАКС);
    const бедно = S.герой.кошель < е.цена;
    А.push({
      id: `еда:${е.id}`, вид: 'еда', группа: 'на ходу', текст: е.имя, цена: е.цена,
      подпись: `${е.цена} гр. · сыт +${е.сыт}${е.тепло ? `, тепло +${е.тепло}` : ''}`,
      отрезков: 0, можно: !сыт && !бедно, почему: сыт ? 'сыт' : бедно ? 'нет денег' : null,
      выполнить(S) {
        const сытСейчас = S.герой.тело.сыт >= МАКС && !(е.тепло && S.герой.тело.тепло < МАКС);
        if (сытСейчас || S.герой.кошель < е.цена) return null;
        S.герой.кошель -= е.цена;
        S.герой.тело.сыт = зажать(S.герой.тело.сыт + е.сыт);
        S.герой.тело.тепло = зажать(S.герой.тело.тепло + (е.тепло || 0));
        return запись(S, `${е.имя}: −${е.цена} гр., сыт +${е.сыт}${е.тепло ? `, тепло +${е.тепло}` : ''}`);
      },
    });
  }

  // Еда «с собой»: та же цена, не ест, а кладёт вещь в свободный слот (данные/еда.js, поле «собой»).
  for (const е of ЕДА) {
    if (!е.собой || !е.где.includes(район) || !е.когда.includes(отрезок)) continue;
    const в = ВЕЩИ[е.собой];
    const некуда = !можноПоложить(S, в.id);
    const бедно = S.герой.кошель < е.цена;
    А.push({
      id: `еда-собой:${е.id}`, вид: 'еда-собой', группа: 'на ходу', текст: в.подписьСобой, цена: е.цена,
      подпись: `${е.цена} гр.`, отрезков: 0, можно: !некуда && !бедно,
      почему: некуда ? 'некуда положить' : бедно ? 'нет денег' : null,
      выполнить(S) {
        if (!можноПоложить(S, в.id) || S.герой.кошель < е.цена) return null;
        if (!положить(S, в.id, 1, { происхождение: 'рынок' })) return null; // не влезло — денег не берём
        S.герой.кошель -= е.цена;
        return запись(S, `${в.имя}: −${е.цена} гр., с собой`);
      },
    });
  }

  А.push(...доступныеПокупки(S), ...доступныеУслуги(S));

  if ((S.герой.жажда ?? 0) > 0) А.push({
    id: 'вода:пить', вид: 'еда', группа: 'на ходу', текст: 'Напиться воды', подпись: 'даром', отрезков: 0,
    можно: !S.сцена, почему: 'сейчас нельзя', выполнить(S2) {
      if (!S2.герой.жажда || S2.сцена) return null;
      S2.герой.жажда = 0; return запись(S2, 'Напился воды: жажда прошла');
    },
  });

  // Отдых 0 или цел 0: любое действие съедает два отрезка, и ночь выпадала бы из дня — из такого состояния не выбраться.
  // Поэтому в таком состоянии лечь можно уже вечером (Порт-работы-задание.md, шаг Р0).
  const т0 = S.герой.тело;
  if (отрезок === 'ночь' || (отрезок === 'вечер' && (т0.отдых === 0 || т0.цел === 0))) {
    for (const ж of ЖИЛЬЁ) {
      if (!ж.открыто || (ж.где && !ж.где.includes(район))) continue;
      const жильё = S.герой.жильё;
      const оплачено = ж.ночей && жильё && жильё.id === ж.id && жильё.оплачено_по >= S.мир.день;
      const платить = оплачено ? 0 : ж.цена;
      const бедно = S.герой.кошель < платить;
      const подпись = оплачено ? `оплачено до дня ${жильё.оплачено_по}`
        : ж.ночей ? `${ж.цена} гр. за ${ж.ночей} ночей` : ж.цена ? `${ж.цена} гр.` : 'даром';
      А.push({
        id: `сон:${ж.id}`, вид: 'сон', группа: 'ночлег', текст: ж.имя, цена: платить, отдых: ж.отдых,
        подпись: `${подпись} · отдых +${ж.отдых}${ж.тепло ? `, тепло ${ж.тепло > 0 ? '+' : '−'}${Math.abs(ж.тепло)}` : ''}`,
        отрезков: 0, можно: !бедно, почему: бедно ? 'нет денег' : null,
        выполнить(S) {
          if (S.герой.кошель < платить) return null;
          if (платить) {
            S.герой.кошель -= платить;
            запись(S, `${ж.имя}: −${платить} гр.`);
          }
          if (ж.ночей && !оплачено) S.герой.жильё = { id: ж.id, оплачено_по: S.мир.день + ж.ночей - 1 };
          let итог = null;
          if (ж.риск) {
            const [а, б] = ж.риск.шанс;
            if (бросок(S) < Math.min(1, а / б * (S.герой.кошель > 100 ? 1.5 : 1))) {
              const добыча = [...привестиВещи(S)].reverse().find(x => !типВещи(x.тип)?.важно);
              if (добыча) {
                потерятьВещь(S, добыча.uid, `украли во сне (${ж.имя})`);
                итог = S.мир.журналДня.at(-1);
              } else {
                const у = Math.floor(S.герой.кошель / 2);
                S.герой.кошель -= у;
                if (у > 0) итог = запись(S, `${ж.имя}: украли ${у} гр.`);
              }
            }
          }
          лечьСпать(S, ж);
          return итог;
        },
      });
    }
  }
  return А;
}


