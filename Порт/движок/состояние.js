export const ВЕРСИЯ = 11;
const КЛЮЧ = 'порт-теней';
let ошибка = null;
export const ошибкаЗагрузки = () => ошибка;

// Темы, известные с начала игры: то, что все знают, плюс своё у каждого начала.
function началоТемы(началоId) {
  const н = НАЧАЛА.find(x => x.id === началоId) ?? НАЧАЛА[0];
  return [...всегдаТемы(), ...(н.темы ?? [])];
}

// сид — зерно случайности (движок/случай.js); в браузере берём от часов, бот задаёт своё.
export function новоеСостояние(началоId, сид = Date.now() >>> 0) {
  const S = {
    версия: ВЕРСИЯ,
    герой: новыйГерой(началоId),
    мир: {
      день: 1,
      отрезок: ОТРЕЗКИ[0],
      район: СТАРТ_РАЙОН,
      погода: 'ясно',
      фракции: { ножи: 0, картель: 0, братство: 0 },
      репутация: 0,
      тень: 0,
      места: {}, // память мест: { 'синий-час': { дом, долг, флаги, осмотрено, визитов } }
      люди: {}, // { id: { распол, спрошено, исчерпано } }
      темы: началоТемы(началоId), // общие для города (ГДД §11)
      знания: {}, // { тид: { день, верность: слышал | подтверждено | опровергнуто, от? } } — рядом с темами
      хроника: [], // три последних итога дня для экрана «Журнал»
      ушло: {}, // { тид: 'картель' | 'ножи' | 'картель ножи' } — куда ушло то, что было сказано или продано
      дела: [],
      свидетельства: [], // увиденные записи и услышанные показания — отдельно от переносимых вещей
      флаги: [],
      долги: [],
      обещания: [],
      конецДня: null, // итог только что прошедшего дня, пока его экран не закрыт
      журналДня: [], // строки о сделанном за день, обнуляется с новым днём
      сид,
      отключкаДень: 0, // день, когда уже был «отключился на ходу» (цел −1 не чаще раза в день)
      очки: { ножи: 0, картель: 0, братство: 0, репутация: 0 }, // скрытые очки: на экране — ступени (движок/положение.js)
      бюджетВлияния: БЮДЖЕТ_ВЛИЯНИЯ,
      шаг: 0,
      обязательства: {},
      выдано: {},
      отложенныеВещи: [],
      ночьБезСна: null,
      очередьСобытий: [],
      завершённыеСобытия: [],
      работы: {}, // { id: { смен, видели[], дни[], последний } } — счёт смен по работам
      смена: null, // карточка идущей смены (движок/смена.js) — живёт, пока не нажато «Дальше»
      услуги: [], // { кому, откуда, день }: чем ты обязан фракциям (этап 6)
      грязь: 0, // день последней грязной работы (для вида)
      сменДень: null, // { день, n }: сколько смен уже сделано сегодня (усталость, движок/смена.js)
      нитьДень: 0, // день, когда уже сработал шаг сюжетной нити (не чаще раза в день)
    },
    сцена: null, // визит в место: комната, собеседник, подход, ветка, реплика, часы… — только внутри визита
    история: [], // откат только внутри сцены (ГДД §21)
  };
  // Стартовое знакомство с фракцией (ГДД §2).
  for (const [к, n] of Object.entries(НАЧАЛА.find(x => x.id === началоId)?.очки ?? {})) добавитьОчки(S, к, n, 'нить');
  // Всё, что игрок знает с начала, — подтверждено.
  for (const т of S.мир.темы) S.мир.знания[т] = { день: 1, верность: 'подтверждено' };
  привестиВещи(S);
  привестиОдежду(S);
  мигрироватьШаг7(S);
  return S;
}

function слот(n) {
  return `${КЛЮЧ}-слот-${n}`;
}

export function сохранить(S, слотN) {
  const ключ = слотN === 'авто' ? `${КЛЮЧ}-авто` : слот(слотN);
  const прежнее = localStorage.getItem(ключ);
  if (прежнее && !разобрать(прежнее).можно) {
    let резерв = `${ключ}-резерв-${Date.now()}`;
    for (let i = 1; localStorage.getItem(резерв); i++) резерв = `${ключ}-резерв-${Date.now()}-${i}`;
    localStorage.setItem(резерв, прежнее);
  }
  localStorage.setItem(ключ, JSON.stringify(S));
  ошибка = null;
}

function разобрать(сырое) {
  try {
    const S = JSON.parse(сырое);
    if (!S || typeof S !== 'object' || !S.мир || !S.герой || !Number.isInteger(S.версия) || S.версия < 1)
      return { можно: false, причина: 'повреждено' };
    if (S.версия > ВЕРСИЯ) return { можно: false, причина: `новая версия ${S.версия}` };
    return { можно: true, S };
  } catch { return { можно: false, причина: 'повреждено' }; }
}

export function загрузить(слотN) {
  const ключ = слотN === 'авто' ? `${КЛЮЧ}-авто` : слот(слотN);
  const сырое = localStorage.getItem(ключ);
  if (!сырое) { ошибка = null; return null; }
  const р = разобрать(сырое);
  if (!р.можно) { ошибка = р.причина; return null; }
  try { ошибка = null; return мигрировать(р.S); }
  catch { ошибка = 'повреждено'; return null; }
}

export function списокСохранений() {
  const слоты = [1, 2, 3, 'авто'];
  return слоты.map(n => {
    const ключ = n === 'авто' ? `${КЛЮЧ}-авто` : слот(n);
    const сырое = localStorage.getItem(ключ);
    if (!сырое) return { слот: n, пусто: true };
    const р = разобрать(сырое);
    if (!р.можно) return { слот: n, пусто: false, ошибка: р.причина };
    const S = р.S;
    return { слот: n, пусто: false, день: S.мир?.день, отрезок: S.мир?.отрезок, герой: S.герой?.имя, начало: S.герой?.начало };
  });
}

// Мягкая миграция при несовпадении версии (ГДД §21, правило 4).
export function мигрировать(S) {
  if (!S || !Number.isInteger(S.версия) || S.версия < 1 || S.версия > ВЕРСИЯ) return null;
  if (S.версия === ВЕРСИЯ) { привестиДела(S); return S; }
  if (S.версия === 1) {
    S.мир.журналДня ??= [];
    S.мир.сид ??= Date.now() >>> 0;
    S.мир.отключкаДень ??= 0;
    if (S.мир.конецДня) {
      S.мир.конецДня.журнал ??= [];
      S.мир.конецДня.причины ??= [];
      S.мир.конецДня.предупреждение ??= false;
    }
    S.герой.серии ??= {};
    S.герой.холод1 ??= 0;
    S.герой.жильё ??= null;
    S.версия = 2;
  }
  if (S.версия === 2) {
    S.мир.места ??= {};
    S.мир.люди ??= {};
    if (!S.мир.темы || !S.мир.темы.length) S.мир.темы = началоТемы(S.герой.начало);
    S.сцена = null;
    S.история ??= [];
    S.версия = 3;
  }
  if (S.версия === 3) {
    // Вечер в месте считается ходами, а не часами (решение автора 18.09): 12 часов → 6 ходов.
    if (S.сцена && S.сцена.часы !== undefined) {
      S.сцена.ходы = Math.ceil(S.сцена.часы / 2);
      delete S.сцена.часы;
    }
    S.история = []; // старые снимки — в часах, откатываться в них нельзя
    S.версия = 4;
  }
  if (S.версия === 4) {
    // Знание темы получило верность: всё, что игрок уже знает, — подтверждено, день 1.
    S.мир.знания ??= {};
    for (const т of S.мир.темы) S.мир.знания[т] ??= { день: 1, верность: 'подтверждено' };
    S.мир.ушло ??= {};
    S.история = []; // старые снимки без знаний
    S.версия = 5;
  }
  if (S.версия === 5) {
    S.мир.хроника ??= [];
    S.герой.при_себе ??= [];
    S.версия = 6;
  }
  if (S.версия === 6) {
    // Работы v2: очки фракций из нынешних ступеней, счёт смен, карточка смены, вид, услуги.
    const м = S.мир;
    м.очки ??= { ножи: 0, картель: 0, братство: 0, репутация: 0 };
    for (const к of ['ножи', 'картель', 'братство']) if (!м.очки[к] && м.фракции?.[к]) м.очки[к] = очкиДляСтупени(м.фракции[к]);
    if (!м.очки.репутация && м.репутация) м.очки.репутация = очкиДляСтупени(м.репутация);
    м.работы ??= {}; м.смена ??= null; м.услуги ??= []; м.грязь ??= 0; м.нитьДень ??= 0; м.флаги ??= [];
    S.герой.ученичество ??= {};
    S.герой.вид ??= 3;
    S.история = [];
    S.версия = 7;
  }
  if (S.версия === 7) {
    // П03: старые строки остаются отдельными экземплярами, без потери порядка и вещей.
    S.герой.счётчикВещей ??= 0;
    привестиВещи(S);
    привестиОдежду(S); // старый числовой «вид» не превращается в бесплатный купеческий костюм
    S.герой.рана ??= 0; S.герой.боль ??= 0; S.герой.жажда ??= 0;
    S.герой.хмель ??= 0; S.герой.напряжение ??= 0; S.герой.привычкаТабак ??= 0;
    S.герой.привычкаХмель ??= 0; S.герой.привычкаНастой ??= 0;
    S.герой.возвратСиба ??= [];
    S.мир.утраченные ??= []; S.мир.передано ??= []; S.мир.мокрыхОтрезков ??= 0;
    S.история = [];
    S.версия = 8;
  }
  if (S.версия === 8) {
    S.мир.хроника ??= [];
    привестиВещи(S);
    S.мир.свидетельства ??= [];
    for (const м of Object.values(S.мир.места ?? {})) м.дниДействий ??= {};
    S.история = [];
    S.версия = 9;
  }
  if (S.версия === 9) {
    const м = S.мир;
    м.очки ??= {};
    for (const к of ['ножи', 'картель', 'братство'])
      if (!м.очки[к] && (м.фракции?.[к] ?? 0) < 0) м.очки[к] = очкиДляСтупени(м.фракции[к]);
    if (!м.очки.репутация && (м.репутация ?? 0) < 0) м.очки.репутация = очкиДляСтупени(м.репутация);
    м.бюджетВлияния ??= БЮДЖЕТ_ВЛИЯНИЯ;
    м.шаг ??= 0;
    м.обязательства ??= {};
    м.выдано ??= {};
    м.отложенныеВещи ??= [];
    м.ночьБезСна ??= null;
    м.очередьСобытий ??= [];
    м.завершённыеСобытия ??= [];
    if (м.смена) м.смена.телоНаСтарте ??= { отдых: S.герой.тело.отдых, цел: S.герой.тело.цел };
    if (S.сцена && !S.сцена.вход) {
      const предыдущийДень = S.сцена.отрезок === 'ночь' && м.отрезок === 'утро';
      S.сцена.вход = { день: м.день - (предыдущийДень ? 1 : 0), отрезок: S.сцена.отрезок };
    }
    S.версия = 10;
  }
  if (S.версия === 10) {
    const былиМанеры = S.герой.манеры || S.герой.тон;
    мигрироватьШаг7(S);
    if (!былиМанеры) {
      for (const л of Object.values(S.мир.люди ?? {})) for (const вопрос of л.спрошено ?? []) {
        const манера = вопрос.split(':').at(-1);
        if (['прямо', 'мягко', 'деньгами'].includes(манера)) {
          const ключ = манера === 'деньгами' ? 'предлагал_деньги' : манера;
          S.герой.манеры[ключ] = (S.герой.манеры[ключ] ?? 0) + 1;
        }
      }
    }
    // Снимки старой сцены тоже мигрируют: откат не возвращает сохранение без памяти.
    S.история = (S.история ?? []).flatMap(сырое => {
      try { const с = мигрировать(JSON.parse(сырое)); return с ? [JSON.stringify(с)] : []; } catch { return []; }
    });
    S.версия = 11;
  }
  привестиДела(S);
  return S;
}


