// Версия 10 занята предыдущими исправлениями основы. Шаг 7 вводится миграцией 10 → 11.
// Сама инициализация полей идемпотентна и применяется также при новой игре.
export const ВЕРСИЯ_ШАГА_7 = 11;

// Поля, которые нужно положить в новоеСостояние() новой игры.
export function поляШага7() {
  return {
    герой: { манеры: {}, факты: {}, дневник: новыйДневник() },
    мир: { слухиОГерое: [] },
  };
}

// Перевод существующего состояния. Безопасно вызывать повторно.
// Подхватывает и поля из ранних черновиков (Порт-Голос-героя.md: тон, голос;
// Порт-Слухи-о-герое.md: слухиОГерое строками).
export function мигрироватьШаг7(S) {
  S.герой ??= {};
  S.мир ??= {};
  S.герой.манеры ??= {};
  S.герой.факты ??= {};
  const Д = (S.герой.дневник ??= новыйДневник());
  for (const [ключ, значение] of Object.entries(новыйДневник())) Д[ключ] ??= значение;

  if (S.герой.тон && typeof S.герой.тон === 'object') {
    for (const [ключ, n] of Object.entries(S.герой.тон)) {
      S.герой.манеры[ключ] = Math.max(S.герой.манеры[ключ] ?? 0, n);
    }
    delete S.герой.тон;
  }
  if (Array.isArray(S.герой.голос)) {
    for (const id of S.герой.голос) if (!Д.показано.includes(id)) Д.показано.push(id);
    delete S.герой.голос;
  }

  S.мир.слухиОГерое = (S.мир.слухиОГерое ?? []).map(з => typeof з === 'string'
    ? { id: з, день: деньИгры(S), статус: 'ходит', дошёл: null, комментировали: [] }
    : { статус: 'ходит', дошёл: null, комментировали: [], ...з });
  return S;
}

// Вызывать из закончитьДень после «последствия и факты» (ПЛАН П02.5), один раз.
export function обновитьСоциальнуюПамять(S, итог) {
  обновитьСлухи(S, итог);
  return обновитьДневник(S, итог);
}

// Для сводкаЖурнала(S): два новых раздела экрана «Журнал».
export function сводкаСоциальнойПамяти(S) {
  return { голос: сводкаДневника(S), слухи: сводкаСлухов(S) };
}

