// Эффекты смены: один язык данных на всё, что случай может сделать с миром. Без DOM, без имён.
// Возвращает строки для карточки «что изменилось» — только то, что игрок должен видеть (очки фракций скрыты,
// показывается смена ступени). Порядок применения не важен: каждое поле независимо.
import { МАКС } from './тело.js';
import { добавитьОчки, расширитьБюджет } from './положение.js';
import { датьТему, подтвердить, опровергнуть } from './знание.js';
import { зарубка } from './ремёсла.js';
import { выдатьВещь, убратьТип } from './вещи.js';
import { запачкать, постирать, видОдежды, повредитьОдежду } from './одежда.js';
import { ФРАКЦИИ, СТУПЕНИ as СЛОВА_СТУПЕНЕЙ } from '../данные/состояния.js';
import { РЕЕСТР } from '../данные/темы.js';
import { ВЕЩИ } from '../данные/вещи.js';
import { бросок } from './случай.js';
import { ОБУЧЕНИЕ } from '../данные/работы.js';
import { датьРемесло } from './ремёсла.js';
import { отметитьУшло, ушлоК } from './знание.js';
import { взятьОбязательство, закрытьОбязательство } from './сроки.js';
import { поставитьСобытие } from './очередь.js';

const зажать = (от, до, v) => Math.max(от, Math.min(до, v));
const зн = n => (n > 0 ? '+' : '−') + Math.abs(n);
const ТЕЛО = { сыт: 'сыт', отдых: 'отдых', тепло: 'тепло', цел: 'цел' };
const РЕП = ['дурная', 'сомнительная', 'никакая', 'добрая', 'громкая'];

export function применитьЭффект(S, э, ctx = {}) {
  const строки = [];
  if (!э) return строки;
  // Список эффектов: применяются по порядку, строки складываются.
  if (Array.isArray(э)) { for (const x of э) строки.push(...применитьЭффект(S, x, ctx)); return строки; }
  const г = S.герой, м = S.мир;
  if (э.один) {
    if ((м.выдано ??= {})[э.один]) return строки;
    м.выдано[э.один] = true;
  }
  if (э.бюджетВлияния === 20) расширитьБюджет(S);
  if (э.обязательство) взятьОбязательство(S, э.обязательство);
  if (э.закрытьОбязательство) закрытьОбязательство(S, э.закрытьОбязательство);
  if (э.событие) поставитьСобытие(S, э.событие);

  // Случайный исход: { шанс, тогда, иначе }. Шанс можно двигать телом (сыт/отдых на 1 — хуже).
  if (э.шанс !== undefined) {
    const т = г.тело;
    const штраф = (т.сыт === 1 ? 0.1 : 0) + (т.отдых === 1 ? 0.1 : 0);
    const ок = бросок(S) < зажать(0, 1, э.шанс + (ctx.бонусШанса ?? 0) - штраф);
    return применитьЭффект(S, ок ? э.тогда : э.иначе, ctx);
  }

  if (э.гроши) {
    г.кошель = Math.max(0, г.кошель + э.гроши);
    строки.push(`${зн(э.гроши)} гр.`);
  }
  if (э.тело) for (const [к, d] of Object.entries(э.тело)) {
    const было = г.тело[к];
    г.тело[к] = зажать(0, МАКС, было + d);
    if (к === 'цел' && d < 0) { г.боль = Math.max(1, г.боль ?? 0); if (ctx.откуда === 'работа:бой') повредитьОдежду(S, true); }
    if (г.тело[к] !== было) строки.push(`${ТЕЛО[к]} ${зн(г.тело[к] - было)}`);
  }
  if (э.вид) {
    const было = видОдежды(S);
    if (э.вид < 0) запачкать(S, Math.abs(э.вид));
    else постирать(S);
    г.вид = видОдежды(S);
    if (г.вид !== было) строки.push(`вид ${зн(г.вид - было)}`);
  }
  if (э.фракции) for (const [к, n] of Object.entries(э.фракции)) {
    const с = добавитьОчки(S, к, n, ctx.источник ?? 'смена');
    if (с) строки.push(`${ФРАКЦИИ[к]}: ${СЛОВА_СТУПЕНЕЙ[String(с[2])]}`);
  }
  if (э.репутация) {
    const с = добавитьОчки(S, 'репутация', э.репутация, ctx.источник ?? 'смена');
    if (с) строки.push(`Репутация: ${РЕП[зажать(0, 4, с[2] + 2)]}`);
  }
  if (э.тень) {
    const было = м.тень ?? 0;
    м.тень = зажать(0, 3, было + э.тень);
    if (э.тень > 0) m_теньДень(S);
    if (м.тень !== было) строки.push(`тень ${зн(м.тень - было)}`);
  }
  if (э.тема) {
    const { id, верность } = typeof э.тема === 'string' ? { id: э.тема } : э.тема;
    const была = м.темы.includes(id);
    датьТему(S, id, верность ?? 'подтверждено', ctx.от);
    if (!была) строки.push(`тема: ${РЕЕСТР[id]?.ярлык ?? id}`);
  }
  if (э.подтвердить) { подтвердить(S, э.подтвердить); строки.push(`проверено: ${РЕЕСТР[э.подтвердить]?.ярлык ?? э.подтвердить}`); }
  if (э.опровергнуть) { опровергнуть(S, э.опровергнуть); строки.push(`враньё: ${РЕЕСТР[э.опровергнуть]?.ярлык ?? э.опровергнуть}`); }
  if (э.распол) for (const [кто, n] of Object.entries(э.распол)) {
    const л = (м.люди[кто] ??= { спрошено: [], исчерпано: [] });
    л.распол = зажать(-2, 4, (л.распол || 0) + n);
  }
  if (э.дом) for (const [место, n] of Object.entries(э.дом)) {
    const п = (м.места[место] ??= { дом: 0, долг: 0, флаги: [], осмотрено: [], визитов: 0 });
    п.дом = зажать(-3, 3, п.дом + n);
  }
  if (э.флаг) for (const ф of [].concat(э.флаг)) if (!м.флаги.includes(ф)) м.флаги.push(ф);
  if (э.снятьФлаг) for (const ф of [].concat(э.снятьФлаг)) { const i = м.флаги.indexOf(ф); if (i >= 0) м.флаги.splice(i, 1); }
  if (э.вещь) {
    const итог = выдатьВещь(S, э.вещь, ctx.откуда ?? 'дело');
    строки.push(итог === 'получено' ? `вещь: ${ВЕЩИ[э.вещь]?.имя ?? э.вещь}` : `вещь ждёт свободного места: ${ВЕЩИ[э.вещь]?.имя ?? э.вещь}`);
  }
  if (э.убратьВещь) убратьТип(S, э.убратьВещь);
  if (э.услуга) (м.услуги ??= []).push({ кому: э.услуга, откуда: ctx.откуда ?? null, день: м.день });
  if (э.зарубки) {
    const с = зарубка(S, э.зарубки.ремесло, э.зарубки.n ?? 1);
    if (с) строки.push(с);
  }
  if (э.счётчик) for (const [имя, n] of Object.entries(э.счётчик)) { (м.счётчики ??= {})[имя] = (м.счётчики[имя] ?? 0) + n; }
  if (э.отметка) (м.отметки ??= {})[э.отметка] = м.день;
  if (э.урок) {
    const у = (г.ученичество ??= {});
    у[э.урок] = (у[э.урок] ?? 0) + 1;
    if (у[э.урок] >= ОБУЧЕНИЕ[э.урок].уроков) { датьРемесло(S, э.урок); строки.push(`Ремесло «${э.урок}»: умеешь`); }
    else строки.push(`урок ${у[э.урок]} из ${ОБУЧЕНИЕ[э.урок].уроков}`);
  }
  if (э.обещание) (м.обещания ??= []).push({ кому: э.обещание.кому, что: э.обещание.что, день: м.день });
  if (э.нарушитьОбещание) { const i = (м.обещания ?? []).findIndex(о => о.что === э.нарушитьОбещание); if (i >= 0) м.обещания.splice(i, 1); }
  // Продать чужие тайны: все личные темы, что у тебя есть, «ушли» к фракции. Возвращает число в ctx.проданоТайн.
  if (э.продатьЛичные) {
    let n = 0;
    for (const тид of м.темы) if (РЕЕСТР[тид]?.личная && !ушлоК(S, тид, э.продатьЛичные)) { отметитьУшло(S, тид, э.продатьЛичные); n++; }
    ctx.проданоТайн = n;
  }
  if (э.потерятьОтрезок) ctx.допОтрезков = (ctx.допОтрезков ?? 0) + э.потерятьОтрезок;
  if (э.строка) м.журналДня.push(э.строка);
  return строки;
}
function m_теньДень(S) { S.мир.теньДень = S.мир.день; }


