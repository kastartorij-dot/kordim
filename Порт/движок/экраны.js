// Экраны города: карта, экран района, конец дня, выбор начала. Пиксельная рамка; картинки (подложки, карта)
// необязательны — их подключение не требует правки этого файла (ГДД §21, правило 2). Что можно делать —
// решает движок/действия.js, экран только рисует кнопки.
import { район, РАЙОНЫ } from '../данные/районы.js';
import { НАЧАЛА } from '../данные/герой.js';
import { МЕСТА } from '../данные/места.js';
import { доступныеДействия } from './действия.js';
import { видСмены } from './смена.js';
import { можноВойти } from './разговор.js';

const $ = id => document.getElementById(id);

// Ресурсы лежат рядом с игрой. Путь от URL модуля работает и на сайте, и в приложении.
const БАЗА_ПОДЛОЖЕК = new URL('../assets/районы/', import.meta.url).href;
const БАЗА_КАРТЫ = new URL('../assets/', import.meta.url).href;
const КАРТА = 'карта.webp';

// «Пойти» здесь больше нет: переходы только с карты (этап 5).
const ГРУППЫ = [['здесь', 'Здесь'], ['места', 'Места'], ['на ходу', 'На ходу'], ['товары', 'Товары'], ['услуги', 'Услуги'], ['ночлег', 'Ночлег']];
const экр = т => String(т).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const список = строки => строки.length ? `<ul class="журнал mono">${строки.map(с => `<li>${экр(с)}</li>`).join('')}</ul>` : '';

// Состояние интерфейса города (в сохранение не входит): открыт ли экран района и какая карточка раскрыта.
export const ИНТ = { район: false, карточка: null };

// Есть ли картинка карты. Файла может не быть — тогда районы рисуются кнопками.
let картаЕсть; // undefined — ещё не проверяли
function проверитьКарту(готово) {
  if (картаЕсть !== undefined) return готово();
  const i = new Image();
  i.onload = () => { картаЕсть = true; готово(); };
  i.onerror = () => { картаЕсть = false; готово(); };
  i.src = БАЗА_КАРТЫ + КАРТА;
}

export function рендерHUD(S) {
  $('hud-день').textContent = `День ${S.мир.день}`;
  // Внутри места отрезок уже списан при входе (в S.мир.отрезок — следующий), но идёт ещё он:
  // шапка показывает отрезок места и само место, а не наступившую ночь.
  const м = S.сцена && МЕСТА.find(x => x.id === S.сцена.место);
  $('hud-отрезок').textContent = м ? `${S.сцена.отрезок ?? м.когда[0]} · ${м.имя}` : `${S.мир.отрезок} · ${S.мир.погода ?? 'ясно'}`;
  $('hud-кошель').textContent = `${S.герой.кошель} гр.`;
  // Сыт/отдых/тепло/цел в шапке не дублируем — с описанием и запасом на портрет и прочее
  // это уже вкладка «Герой» в нижней панели (движок/экраны-панель.js, экранГероя).
}

// Город: карта или экран района.
export function рендерКарту(S, onПереход) {
  if (ИНТ.район) рендерРайон(S, onПереход);
  else рендерГород(S, onПереход);
}

// Смена блокирует город, пока игрок не выберет исход и не закроет карточку.
// Раньше её действия возвращались движком, но экран района их не рисовал.
export function рендерСмены(S, onПереход) {
  const поле = $('экран');
  const вид = видСмены(S);
  const действия = доступныеДействия(S).filter(д => д.группа === 'смена');
  const строки = вид.строки?.length
    ? `<ul class="смена-итог mono">${вид.строки.map(с => `<li>${экр(с)}</li>`).join('')}</ul>`
    : '';
  поле.innerHTML = `
    <div class="смена-экран">
      <section class="смена-карточка">
        <h1 class="px">${экр(вид.заголовок)}</h1>
        ${вид.текст ? `<p class="смена-текст">${экр(вид.текст)}</p>` : ''}
        ${строки}
        <div class="смена-кнопки">${действия.map(д => `
          <button class="b" data-id="${экр(д.id)}" ${д.можно ? '' : 'disabled'}>
            ${экр(д.текст)}${д.подпись ? `<br><span class="mono">${экр(д.можно ? д.подпись : д.почему)}</span>` : ''}
          </button>`).join('')}
        </div>
      </section>
    </div>`;
  поле.querySelectorAll('button[data-id]').forEach(btn => {
    btn.onclick = () => {
      const д = действия.find(x => x.id === btn.dataset.id);
      if (!д?.можно) return;
      д.выполнить(S);
      onПереход(S, true);
    };
  });
}

// Значки мест района, открытых сейчас.
// Все места района: открытые сейчас — ярко, закрытые — серым (иначе днём «Синего часа» на карте будто нет).
const местаРайона = (S, районId) => МЕСТА.filter(м => м.район === районId).map(м => ({ м, открыто: можноВойти(S, м.id).можно }));

function рендерГород(S, onПереход) {
  const поле = $('экран');
  const действия = доступныеДействия(S);
  const ночь = S.мир.отрезок === 'ночь';
  const выбран = ИНТ.карточка && район(ИНТ.карточка);
  const ход = выбран && действия.find(д => д.id === `переход:${выбран.id}`);

  const метка = р => {
    const тут = р.id === S.мир.район;
    const значки = местаРайона(S, р.id).map(({ м, открыто }) => `<span class="значок${открыто ? '' : ' закрыто'}">${экр(м.имя)}</span>`).join('');
    return `<span class="табличка px${тут ? ' тут' : ''}">${экр(р.имя)}${тут ? '<small>ты здесь</small>' : ''}<span class="значки">${значки}</span></span>`;
  };
  const карточка = выбран ? `
    <div class="город-карточка">
      <div class="карта-подпись px">${экр(выбран.имя)}</div>
      <p class="карта-описание">${экр(выбран.описание)}</p>
      <p class="mono">${экр(ход ? ход.подпись : '')}</p>
      <div class="слот-кнопки"><button class="b sin" id="идти">Идти</button><button class="b" id="отмена">Отмена</button></div>
    </div>` : '';

  const собрать = естьКартинка => {
    const зоны = естьКартинка
      ? РАЙОНЫ.map(р => {
        const к = р.наКарте;
        return `<button class="зона" data-р="${р.id}" aria-label="${экр(р.имя)}" style="left:${к.x - к.rx}%;top:${к.y - к.ry}%;width:${2 * к.rx}%;height:${2 * к.ry}%"></button>
          <div class="табличка-место" style="left:${к.x}%;top:${к.y}%;transform:translate(${к.x < 20 ? -8 : к.x > 80 ? -92 : -50}%,-50%)">${метка(р)}</div>`;
      }).join('')
      : '';
    const полотно = естьКартинка
      ? `<div class="город-полотно"><img class="город-картинка" src="${БАЗА_КАРТЫ + КАРТА}" alt="">${зоны}${ночь ? '<div class="туман"></div>' : ''}</div>`
      : `<div class="город-кнопки">${РАЙОНЫ.map(р => `<button class="b район-кнопка" data-р="${р.id}">${метка(р)}</button>`).join('')}</div>`;
    поле.innerHTML = `<div class="город">${полотно}${карточка}${список(S.мир.журналДня)}</div>`;
    поле.querySelectorAll('[data-р]').forEach(el => {
      el.onclick = () => {
        if (el.dataset.р === S.мир.район) { ИНТ.район = true; ИНТ.карточка = null; } else ИНТ.карточка = el.dataset.р;
        onПереход(S);
      };
    });
    const идти = $('идти');
    if (идти) идти.onclick = () => {
      if (!ход || !ход.можно) return;
      ход.выполнить(S);
      ИНТ.карточка = null;
      ИНТ.район = true; // пришёл — экран района
      onПереход(S);
    };
    const отмена = $('отмена');
    if (отмена) отмена.onclick = () => { ИНТ.карточка = null; onПереход(S); };
  };
  if (картаЕсть === undefined) { поле.innerHTML = ''; проверитьКарту(() => собрать(картаЕсть)); } else собрать(картаЕсть);
}

function рендерРайон(S, onПереход) {
  const поле = $('экран');
  const текущий = район(S.мир.район);
  const действия = доступныеДействия(S);
  const блоки = ГРУППЫ.map(([г, имя]) => {
    const в = действия.filter(д => д.группа === г);
    if (!в.length) return '';
    return `<div class="группа"><div class="группа-имя mono">${имя}</div><div class="карта-районы">
      ${в.map(д => `
        <button class="b" data-id="${экр(д.id)}" ${д.можно ? '' : 'disabled'}>
          ${экр(д.текст)}<br><span class="mono">${экр(д.можно ? д.подпись : д.почему)}</span>
        </button>`).join('')}
    </div></div>`;
  }).join('');
  поле.innerHTML = `
    <div class="карта">
      <div class="карта-подложка" style="background-image:url('${подложка(текущий.id)}')"></div>
      <div class="район-шапка"><div class="карта-подпись px">${экр(текущий.имя)}</div><button class="b" id="на-карту">На карту</button></div>
      <p class="карта-описание">${экр(текущий.описание)}</p>
      ${блоки}
      ${список(S.мир.журналДня)}
    </div>
  `;
  $('на-карту').onclick = () => { ИНТ.район = false; onПереход(S); };
  поле.querySelectorAll('button[data-id]').forEach(btn => {
    btn.onclick = () => {
      const д = действия.find(x => x.id === btn.dataset.id);
      if (!д || !д.можно) return;
      д.выполнить(S);
      onПереход(S);
    };
  });
}

// Итог дня: день уже переключён (движок/время.js), здесь только показать и
// снять S.мир.конецДня. Автосейв делает index.html.
export function рендерКонецДня(S, onДальше) {
  const итог = S.мир.конецДня;
  const тело = S.герой.тело;
  $('экран').innerHTML = `
    <div class="ов">
      <div class="овбокс">
        <h2 class="px">День ${итог.день} позади</h2>
        ${список(итог.журнал)}
        <p>${итог.выспался ? (итог.сон ? `Ночь: ${экр(итог.сон)}.` : 'Ночь прошла во сне.') :'Ночь прошла без сна.'}</p>
        ${список(итог.причины)}
        <p>Сыт: ${тело.сыт} · Отдых: ${тело.отдых} · Тепло: ${тело.тепло} · Цел: ${тело.цел}</p>
        ${итог.предупреждение ? '<p class="предупр">Ещё один серьёзный удар может стать последним.</p>' : ''}
        <p class="mono">Кошель: ${S.герой.кошель} гр.</p>
        <button class="b sin" id="дальше">Начать день ${S.мир.день}</button>
      </div>
    </div>
  `;
  $('дальше').onclick = () => {
    S.мир.конецДня = null;
    onДальше(S);
  };
}

