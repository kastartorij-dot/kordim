// Экраны: карта, HUD, конец дня. Пиксельная рамка без картинок —
// подложки района необязательны (см. подложка(id) внизу), их подключение не
// требует правки этого файла (ГДД §21, правило 2). Что можно делать — решает
// движок/действия.js, экран только рисует кнопки.
import { район } from '../данные/районы.js';
import { НАЧАЛА } from '../данные/герой.js';
import { доступныеДействия } from './действия.js';
import { место } from '../данные/места.js';

const $ = id => document.getElementById(id);

// Путь разный у копии на сайте и у оригинала — тот же приём, что в «Синем часе».
const БАЗА_ПОДЛОЖЕК = location.pathname.includes('/game/')
  ? '../../img/port/районы/'
  : '../../wiki/img/port/районы/';

const НАЗВАНИЯ = { сыт: 'Сыт', отдых: 'Отдых', тепло: 'Тепло', цел: 'Цел' };
const ГРУППЫ = [['пойти', 'Пойти'], ['здесь', 'Здесь'], ['места', 'Места'], ['на ходу', 'На ходу'], ['ночлег', 'Ночлег']];
const экр = т => String(т).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const список = строки => строки.length ? `<ul class="журнал mono">${строки.map(с => `<li>${экр(с)}</li>`).join('')}</ul>` : '';

export function рендерHUD(S) {
  $('hud-день').textContent = `День ${S.мир.день}`;
  // Внутри места отрезок уже списан при входе (в S.мир.отрезок — следующий), но идёт ещё он:
  // шапка показывает отрезок места и само место, а не наступившую ночь.
  const м = S.сцена && место(S.сцена.место);
  $('hud-отрезок').textContent = м ? `${м.когда[0]} · ${м.имя}` : S.мир.отрезок;
  $('hud-кошель').textContent = `${S.герой.кошель} гр.`;
  const тело = S.герой.тело;
  $('hud-тело').innerHTML = ['сыт', 'отдых', 'тепло', 'цел']
    .map(к => `<span class="стат стат-${тело[к]}" title="${НАЗВАНИЯ[к]} ${тело[к]} из 3">${НАЗВАНИЯ[к][0]}${тело[к]}</span>`)
    .join('');
}

export function рендерКарту(S, onПереход) {
  const поле = $('экран');
  const текущий = район(S.мир.район);
  const действия = доступныеДействия(S);
  const блоки = ГРУППЫ.map(([г, имя]) => {
    const в = действия.filter(д => д.группа === г);
    if (!в.length) return '';
    return `<div class="группа"><div class="группа-имя mono">${имя}</div><div class="карта-районы">
      ${в.map(д => `
        <button class="b" data-id="${экр(д.id)}" ${д.можно ? '' : 'disabled'}>
          ${экр(д.текст)}<br><span class="mono">${экр(д.можно ? д.подпись : д.почему)}</span>
        </button>`).join('')}
    </div></div>`;
  }).join('');
  поле.innerHTML = `
    <div class="карта">
      <div class="карта-подложка" style="background-image:url('${подложка(текущий.id)}')"></div>
      <div class="карта-подпись px">${текущий.имя}</div>
      <p class="карта-описание">${текущий.описание}</p>
      ${блоки}
      ${список(S.мир.журналДня)}
    </div>
  `;
  поле.querySelectorAll('button[data-id]').forEach(btn => {
    btn.onclick = () => {
      const д = действия.find(x => x.id === btn.dataset.id);
      if (!д || !д.можно) return;
      д.выполнить(S);
      onПереход(S);
    };
  });
}

// Итог дня: день уже переключён (движок/время.js), здесь только показать и
// снять S.мир.конецДня. Автосейв делает index.html.
export function рендерКонецДня(S, onДальше) {
  const итог = S.мир.конецДня;
  const тело = S.герой.тело;
  $('экран').innerHTML = `
    <div class="ов">
      <div class="овбокс">
        <h2 class="px">День ${итог.день} позади</h2>
        ${список(итог.журнал)}
        <p>${итог.выспался ? (итог.сон ? `Ночь: ${экр(итог.сон)}.` : 'Ночь прошла во сне.') :'Ночь прошла без сна.'}</p>
        ${список(итог.причины)}
        <p>Сыт: ${тело.сыт} · Отдых: ${тело.отдых} · Тепло: ${тело.тепло} · Цел: ${тело.цел}</p>
        ${итог.предупреждение ? '<p class="предупр">Ещё один серьёзный удар может стать последним.</p>' : ''}
        <p class="mono">Кошель: ${S.герой.кошель} гр.</p>
        <button class="b sin" id="дальше">Начать день ${S.мир.день}</button>
      </div>
    </div>
  `;
  $('дальше').onclick = () => {
    S.мир.конецДня = null;
    onДальше(S);
  };
}

// Выбор начала (ГДД §2): три версии одного героя.
export function рендерСтарт(onВыбор) {
  $('экран').innerHTML = `
    <div class="карта">
      <div class="карта-подпись px">Одвин Скарре возвращается в Порт Теней</div>
      <p class="карта-описание">Семь лет его здесь не было. С чем он вернулся?</p>
      ${НАЧАЛА.map(н => `
        <button class="b начало" data-id="${н.id}" style="text-align:left">
          ${н.имя}<br><span class="mono">${н.ремесло} · ${н.деньги} гр.</span>
          <br><span style="font-family:var(--body);font-size:14px">${н.описание}</span>
        </button>
      `).join('')}
    </div>
  `;
  $('экран').querySelectorAll('.начало').forEach(btn => {
    btn.onclick = () => onВыбор(btn.dataset.id);
  });
}

function подложка(районId) {
  const р = район(районId);
  return р?.подложка ? БАЗА_ПОДЛОЖЕК + р.подложка : '';
}
