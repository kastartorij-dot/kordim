// Вещи при себе (ГДД §13): восемь слотов, S.герой.при_себе — список id. Чистая логика, без DOM.
// Незнакомая вещь (нож, жетон из условий «Синего часа») — просто id: показывается как есть, есть её нельзя.
import { ВЕЩИ, СЛОТОВ } from '../данные/вещи.js';
import { МАКС } from './тело.js';

export const вещь = id => ВЕЩИ[id] ?? null;
export const имяВещи = id => ВЕЩИ[id]?.имя ?? String(id);

// Восемь слотов: id вещи или null (пусто).
export function слоты(S) {
  S.герой.при_себе ??= [];
  return Array.from({ length: СЛОТОВ }, (_, i) => S.герой.при_себе[i] ?? null);
}
export const свободных = S => СЛОТОВ - (S.герой.при_себе ??= []).length;

export function положить(S, id) {
  if (свободных(S) <= 0) return false;
  S.герой.при_себе.push(id);
  return true;
}

// Съесть вещь из слота: 0 отрезков, тело растёт не выше МАКС, строка в журнал дня.
function съесть(S, i) {
  const id = S.герой.при_себе[i];
  const в = вещь(id);
  if (!в?.еда) return null;
  S.герой.при_себе.splice(i, 1);
  const строки = [];
  for (const [к, n] of Object.entries(в.еда)) {
    S.герой.тело[к] = Math.max(0, Math.min(МАКС, S.герой.тело[к] + n));
    строки.push(`${к} +${n}`);
  }
  const с = `${в.имя}: ${строки.join(', ')}`;
  S.мир.журналДня.push(с);
  return с;
}

// Действия экрана «Вещи» — по одному на занятый слот. Съесть нельзя внутри места (сцены).
export function действияВещей(S) {
  const А = [];
  S.герой.при_себе ??= [];
  S.герой.при_себе.forEach((id, i) => {
    const в = вещь(id);
    if (!в?.еда) return;
    А.push({
      id: `вещь:съесть:${i}`, вид: 'вещь', слот: i, вещь: id, текст: 'Съесть', подпись: '', отрезков: 0,
      можно: !S.сцена, почему: S.сцена ? 'сейчас нельзя' : null,
      выполнить(S2) { return съесть(S2, i); },
    });
  });
  return А;
}
