// Нижняя панель «Город · Герой · Вещи · Журнал» и три экрана поверх: Герой, Вещи, Журнал (этап 5).
// Они открываются поверх города и сцены места и закрываются, не трогая ни то, ни другое.
// Что показать — решают движок/сводка.js и движок/вещи.js; здесь только вёрстка.
import { сводкаГероя, сводкаЖурнала } from './сводка.js';
import { слоты, имяВещи, действияВещей } from './вещи.js';
import { действияХозяйства, описатьВещь } from './хозяйство.js';
import { описаниеОдежды } from './одежда.js';

const $ = id => document.getElementById(id);
const экр = т => String(т).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

// Открытая вкладка панели: 'город' (ничего поверх), 'герой', 'вещи', 'журнал'.
export const ПАН = { вкладка: 'город' };
const ВКЛАДКИ = [['город', 'Город'], ['герой', 'Герой'], ['вещи', 'Вещи'], ['журнал', 'Журнал']];

const блок = (заг, тело) => `<section class="пан-блок"><h3 class="px">${экр(заг)}</h3>${тело}</section>`;

function экранГероя(S) {
  const в = сводкаГероя(S);
  const ремесло = в.ремёсла.map(р => `${экр(р.имя)} — ${экр(р.ступень)}, зарубки: ${р.зарубки}`).join('; ') || 'нет';
  const тело = в.тело.map(т => `
    <div class="строка-тела тело-${т.значение}">
      <span class="полоска px">${экр(т.название)} ${т.значение}</span>
      <span class="описание">${экр(т.строка)}</span>
    </div>`).join('');
  const пол = в.положение;
  const одежда = описаниеОдежды(S);
  const фракции = пол.фракции.map(ф => `
    <div class="строка-тела"><span class="полоска px">${экр(ф.имя)} ${ф.значение > 0 ? '+' : ''}${ф.значение}</span><span class="описание">${экр(ф.слово)}</span></div>`).join('');
  return `
    <p class="пан-имя"><b>${экр(в.имя)}</b><br><span class="mono">${экр(в.начало)}</span><br><span class="mono">${ремесло}</span></p>
    ${блок('Тело', тело)}
    ${блок('Положение', `${фракции}
      <div class="строка-тела"><span class="полоска px">Репутация ${пол.репутация.значение > 0 ? '+' : ''}${пол.репутация.значение}</span><span class="описание">${экр(пол.репутация.слово)}</span></div>
      <div class="строка-тела"><span class="полоска px">Тень ${пол.тень.значение}</span><span class="описание">${экр(пол.тень.строка)}</span></div>`)}
    ${блок('Одежда', `<p>${экр(одежда.база)} · верх: ${экр(одежда.верх)} · вид ${одежда.вид}<br><span class="mono">${экр(одежда.состояние)}</span></p>`)}
    ${блок('Состояние', `<p>Рана: ${S.герой.рана ?? 0} · боль: ${S.герой.боль ?? 0} · жажда: ${S.герой.жажда ?? 0} · хмель: ${S.герой.хмель ?? 0} · напряжение: ${S.герой.напряжение ?? 0}<br>Привычки: табак ${S.герой.привычкаТабак ?? 0}, выпивка ${S.герой.привычкаХмель ?? 0}, настой ${S.герой.привычкаНастой ?? 0}</p>`)}
    ${блок('Жильё', `<p>${экр(в.жильё)}</p>`)}`;
}

function экранВещей(S, onШаг) {
  const дей = [...действияВещей(S), ...действияХозяйства(S)];
  const кнопки = uid => дей.filter(x => x.uid === uid).map(д => `<button class="b" data-действие="${экр(д.id)}" ${д.можно ? '' : `disabled title="${экр(д.почему ?? 'сейчас нельзя')}"`}>${экр(д.текст)}</button>`).join('');
  const строки = слоты(S).map((x, i) => {
    if (x === null) return `<div class="слот-вещи пусто"><span class="mono">${i + 1}</span> Пусто</div>`;
    if (x.блок) return `<div class="слот-вещи пусто"><span class="mono">${i + 1}</span> Недоступно из-за раны</div>`;
    if (x.продолжение) return `<div class="слот-вещи пусто"><span class="mono">${i + 1}</span> Занято крупной вещью</div>`;
    return `<div class="слот-вещи"><span class="mono">${i + 1}</span><div><b>${экр(имяВещи(x))}</b>${S.герой.рука === x.uid ? ' · в руке' : ''}<br><small>${экр(описатьВещь(x))}</small><div class="вещь-действия">${кнопки(x.uid)}</div></div></div>`;
  }).join('');
  const х = S.герой.хранилище ?? {};
  const сундуки = ['вдова', 'угол'].map(id => (х[id] ?? []).length ? блок(`Сундук: ${id}`, х[id].map(x => `<div class="слот-вещи"><span>${экр(имяВещи(x))}</span><small>${экр(описатьВещь(x))}</small><div class="вещь-действия">${кнопки(x.uid)}</div></div>`).join('')) : '').join('');
  const залог = (S.герой.залог ?? []).length ? блок('Залог', S.герой.залог.map(з => `<div class="слот-вещи"><span>${экр(имяВещи(з.вещь))} · до дня ${з.выкупДо}</span><div class="вещь-действия">${кнопки(з.вещь.uid)}</div></div>`).join('')) : '';
  const уСиба = (S.герой.возвратСиба ?? []).length ? блок('У Сиба', S.герой.возвратСиба.map(x => `<div class="слот-вещи"><span>${экр(имяВещи(x))}</span><div class="вещь-действия">${кнопки(x.uid)}</div></div>`).join('')) : '';
  const ожидают = (S.мир.отложенныеВещи ?? []).length ? блок('Ждут получения', S.мир.отложенныеВещи.map(x => `<p>${экр(имяВещи(x.тип))} — освободи место и забери в городе</p>`).join('')) : '';
  const снять = дей.find(x => x.id === 'снять-верх');
  const одежда = описаниеОдежды(S);
  return блок(`При себе · ${Math.max(0, 8 - слоты(S).filter(x => x && !x.блок).length)} свободно`, строки)
    + блок('Надето', `<p>${экр(одежда.база)} · ${экр(одежда.верх)}${снять ? `<button class="b" data-действие="снять-верх" ${снять.можно ? '' : 'disabled'}>Снять верх</button>` : ''}</p>`)
    + сундуки + залог + уСиба + ожидают;
}

function экранЖурнала(S) {
  const ж = сводкаЖурнала(S);
  const темы = ж.темы.length ? ж.темы.map(т => `
    <div class="тема-журнала ${т.верность === 'враньё' ? 'враньё' : ''}">
      <b>${экр(т.ярлык)}</b> <span class="mono">${экр(т.верность)} ${т.точки}</span>
      ${т.ушла.length ? `<span class="mono ушла">${экр(т.ушла.join(', '))}</span>` : ''}
      ${т.текст ? `<p>${экр(т.текст)}</p>` : ''}
    </div>`).join('') : '<p class="mono">Пусто</p>';
  const люди = ж.люди.length ? ж.люди.map(л => `<div class="строка-тела"><span class="полоска">${экр(л.имя)}</span><span class="описание">${экр(л.где)} · ${экр(л.слово)}</span></div>`).join('') : '<p class="mono">Пусто</p>';
  const долги = ж.долги.length ? ж.долги.map(д => `<p>${экр(д.место)} — ${д.сумма} гр.</p>`).join('') : '<p>Долгов нет</p>';
  const вклады = ж.вклады.length ? ж.вклады.map(д => `<p>${экр(д.место)} — ${д.сумма} гр.</p>`).join('') : '<p>Вкладов нет</p>';
  const свидетельства = ж.свидетельства.length ? ж.свидетельства.map(у => `<div class="тема-журнала"><b>${экр(у.имя)}</b><p>${экр(у.текст)}</p></div>`).join('') : '<p class="mono">Пока нет записей</p>';
  const обязательства = ж.обязательства.length ? ж.обязательства.map(о => `<p>${экр(о.название)} — ${экр(о.статус)}, ${экр(о.срок)}</p>`).join('') : '<p>Нет срочных обязательств</p>';
  const дни = ж.дни.length ? ж.дни.map(д => `
    <div class="день-журнала"><b class="px">День ${д.день}</b>
      ${д.журнал.length ? `<ul class="журнал mono">${д.журнал.map(с => `<li>${экр(с)}</li>`).join('')}</ul>` : ''}
      ${д.причины.length ? `<ul class="журнал mono">${д.причины.map(с => `<li>${экр(с)}</li>`).join('')}</ul>` : ''}
    </div>`).join('') : '<p class="mono">Пусто</p>';
  const голос = ж.голос.map(т => '<p>' + экр(т) + '</p>').join('') || '<p class="mono">Пока нет записей</p>';
  const слухи = ж.слухи.map(с => '<p>' + экр(с.текст) + ' <span class="mono">' + экр(с.статус) + '</span></p>').join('') || '<p class="mono">До тебя пока ничего не дошло</p>';
  return блок('Голос', голос) + блок('Слухи об Одвине', слухи) + блок('Темы', темы) + блок('Свидетельства', свидетельства) + блок('Люди', люди) + блок('Обязательства', обязательства) + блок('Долги', долги) + блок('Вклады', вклады) + блок('Дни', дни);
}

const ЭКРАНЫ = { герой: ['Герой', экранГероя], вещи: ['Вещи', экранВещей], журнал: ['Журнал', экранЖурнала] };

// Шторка слева от карты (по месту автора: «интерактивное меню со статами», всегда доступное,
// а на широком экране — открытое само, раз там всё равно пусто). Содержимое то же, что во
// вкладке «Герой» снизу — вкладку не убираем, шторка на узком экране всё ещё нужно открывать вручную.
export function рендерШторку(S) {
  const тело = $('шторка-тело');
  if (!тело) return;
  тело.innerHTML = S ? экранГероя(S) : '';
}

function убратьОверлей() {
  document.querySelectorAll('.ов.пан').forEach(o => o.remove());
}

// Перерисовывает панель и, если открыта вкладка «поверх», её содержимое. Вызывается после каждого шага игры.
// onШаг(S) — как в остальных экранах: сохранить и перерисовать всё.
export function рендерПанель(S, onШаг) {
  const панель = $('панель');
  if (!панель) return;
  const заперт = !!S.сцена || !!S.мир.конецДня; // в сцене и на итоге дня «Город» неактивен
  панель.innerHTML = ВКЛАДКИ.map(([id, имя]) =>
    `<button class="b ${ПАН.вкладка === id ? 'on' : ''}" data-вкладка="${id}" ${id === 'город' && заперт ? 'disabled' : ''}>${имя}</button>`).join('');
  панель.querySelectorAll('[data-вкладка]').forEach(b => {
    b.onclick = () => {
      const id = b.dataset.вкладка;
      ПАН.вкладка = id === 'город' || ПАН.вкладка === id ? 'город' : id;
      рендерПанель(S, onШаг);
    };
  });
  убратьОверлей();
  const э = ЭКРАНЫ[ПАН.вкладка];
  if (!э) return;
  const ов = document.createElement('div');
  ов.className = 'ов пан';
  ов.innerHTML = `<div class="овбокс пан-бокс"><div class="пан-шапка"><h2 class="px">${э[0]}</h2><button class="b" id="пан-закрыть">Закрыть</button></div>${э[1](S, onШаг)}</div>`;
  document.body.appendChild(ов);
  ов.style.bottom = `${панель.offsetHeight}px`; // панель остаётся видимой под окном
  ов.querySelector('#пан-закрыть').onclick = () => { ПАН.вкладка = 'город'; рендерПанель(S, onШаг); };
  ов.querySelectorAll('[data-действие]').forEach(b => {
    const номер = S.мир.шаг ?? 0;
    b.onclick = () => {
      if ((S.мир.шаг ?? 0) !== номер) return;
      const д = [...действияВещей(S), ...действияХозяйства(S)].find(x => x.id === b.dataset.действие);
      if (д && д.можно && д.выполнить(S)) { S.мир.шаг = номер + 1; onШаг(S); }
    };
  });
}


