// Продолжения рабочих решений, доступные прямо из города.
// У каждой кнопки есть потребитель конкретного факта из колоды работ.
import { можноПоложить, положить } from './вещи.js';
import { датьТему } from './знание.js';
import { потратитьОтрезок } from './время.js';

export function действияПоследствийРабот(S) {
  const А = [];
  const м = S.мир;
  if (м.район === 'доки' && м.флаги.includes('гиря_у_старшого')) А.push({
    id: 'работа:забрать-гирю', вид: 'действие', группа: 'здесь', текст: 'Забрать гирю у старшого',
    подпись: 'даром · 2 места в сумке', отрезков: 0,
    можно: можноПоложить(S, 'гиря'), почему: 'нужно два свободных места',
    выполнить(S2) {
      if (S2.мир.район !== 'доки' || !S2.мир.флаги.includes('гиря_у_старшого') || !положить(S2, 'гиря', 1, { происхождение: 'старшой' })) return null;
      S2.мир.флаги.splice(S2.мир.флаги.indexOf('гиря_у_старшого'), 1);
      if (!S2.мир.флаги.includes('гиря_бренна')) S2.мир.флаги.push('гиря_бренна');
      const строка = 'Старшой вернул гирю Бренна: три зарубки на боку.';
      S2.мир.журналДня.push(строка);
      return строка;
    },
  });
  if (м.район === 'торговый' && м.флаги.includes('соврал_мужчине') && !м.флаги.includes('сказал_правду_мужчине')) А.push({
    id: 'работа:сказать-правду', вид: 'действие', группа: 'здесь', текст: 'Найти адресата письма',
    подпись: '1 отрезок · признаться во лжи', отрезков: 1, можно: true, почему: null,
    выполнить(S2) {
      if (S2.мир.район !== 'торговый' || !S2.мир.флаги.includes('соврал_мужчине') || S2.мир.флаги.includes('сказал_правду_мужчине')) return null;
      S2.мир.флаги.push('сказал_правду_мужчине');
      const строка = 'У ворот ты нашёл адресата письма и признался: ответ был длиннее, чем «нет». Он выслушал письмо дословно и ушёл, не обещая ничего.';
      S2.мир.журналДня.push(строка);
      потратитьОтрезок(S2);
      return строка;
    },
  });
  if (м.район === 'маяк' && м.флаги.includes('знает_пещеры') && !м.темы.includes('peshchery_u_mayaka')) А.push({
    id: 'работа:осмотреть-тропу', вид: 'действие', группа: 'здесь', текст: 'Осмотреть тропу к пещерам',
    подпись: '1 отрезок · узнать путь', отрезков: 1, можно: true, почему: null,
    выполнить(S2) {
      if (S2.мир.район !== 'маяк' || !S2.мир.флаги.includes('знает_пещеры') || S2.мир.темы.includes('peshchery_u_mayaka')) return null;
      датьТему(S2, 'peshchery_u_mayaka', 'подтверждено', 'маяк');
      const строка = 'Со стороны маяка ты разглядел тропу к пещерам и запомнил её повороты. Теперь об этом можно расспрашивать других.';
      S2.мир.журналДня.push(строка);
      потратитьОтрезок(S2);
      return строка;
    },
  });
  return А;
}
