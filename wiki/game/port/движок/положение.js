// Очки фракций и репутации → ступени −3…+3. Без DOM. Ступени лежат в S.мир.фракции / S.мир.репутация,
// экраны читают их как раньше; очки — в S.мир.очки (ГДД §7, §8).
import { ПОРОГИ, ПОТОЛОК_СМЕН, КЛЮЧИ_ФРАКЦИЙ, УБЫВАНИЕ_ДНЕЙ, ПОТОЛОК_СУММЫ } from '../данные/положение.js';

export const ступеньПоОчкам = о => ПОРОГИ.find(([от]) => о >= от)[1];

function очки(S) {
  const м = S.мир;
  м.очки ??= {};
  for (const к of [...КЛЮЧИ_ФРАКЦИЙ, 'репутация']) м.очки[к] ??= 0;
  return м.очки;
}

export function пересчитать(S) {
  const о = очки(S);
  for (const к of КЛЮЧИ_ФРАКЦИЙ) S.мир.фракции[к] = ступеньПоОчкам(о[к]);
  S.мир.репутация = ступеньПоОчкам(о.репутация);
}

// источник: 'смена' — обычная работа (растёт до потолка), 'нить' — сюжет (потолка нет).
// Возвращает [ключ, было, стало], если ступень сменилась, иначе null.
export function добавитьОчки(S, ключ, n, источник = 'смена') {
  if (!n) return null;
  const о = очки(S), было = ступеньПоОчкам(о[ключ]);
  if (n > 0 && источник === 'смена') {
    if (о[ключ] < ПОТОЛОК_СМЕН) о[ключ] = Math.min(ПОТОЛОК_СМЕН, о[ключ] + n);
  } else {
    о[ключ] += n;
  }
  if (n > 0 && КЛЮЧИ_ФРАКЦИЙ.includes(ключ)) {
    (S.мир.делаСФракцией ??= {})[ключ] = S.мир.день;
    // внимание делится: сверх потолка суммы очки отбираются у самой слабой из остальных положительных фракций
    let сумма = КЛЮЧИ_ФРАКЦИЙ.reduce((а, к) => а + Math.max(0, о[к]), 0);
    while (сумма > ПОТОЛОК_СУММЫ) {
      const др = КЛЮЧИ_ФРАКЦИЙ.filter(к => к !== ключ && о[к] > 0).sort((а, б) => о[а] - о[б])[0];
      if (!др) break;
      о[др] -= 1; сумма -= 1;
    }
  }
  пересчитать(S);
  const стало = ступеньПоОчкам(о[ключ]);
  return стало !== было ? [ключ, было, стало] : null;
}

// Конец дня: фракция, с которой не было дел УБЫВАНИЕ_ДНЕЙ дней, забывает тебя на очко —
// и так каждые три дня, пока дел нет (не ниже нуля). «Своим у всех быть нельзя» (ГДД §7).
export function убывание(S) {
  const о = очки(S), д = S.мир.день, дела = (S.мир.делаСФракцией ??= {}), спис = (S.мир.списаноУФракции ??= {});
  for (const к of КЛЮЧИ_ФРАКЦИЙ) {
    if (о[к] <= 0) continue;
    if (д - (дела[к] ?? 0) >= УБЫВАНИЕ_ДНЕЙ && д - (спис[к] ?? 0) >= 3) { о[к] -= 1; спис[к] = д; }
  }
  пересчитать(S);
}

// Наименьшие очки для ступени — для миграции старых сохранений.
export const ПОРОГИ_МИН = { 1: 3, 2: 8, 3: 15 };


