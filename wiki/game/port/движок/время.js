// Верхний уровень времени: утро/день/вечер/ночь. ГДД §4.
// Ночь — полноценный отрезок: можно лечь спать, а можно потратить её на дела
// (ночная работа, слежка, ГДД §4 и §13) — тогда день кончается без сна.
import { применитьТело } from './тело.js';

export const ОТРЕЗКИ = ['утро', 'день', 'вечер', 'ночь'];

export function следующийОтрезок(S) {
  const i = ОТРЕЗКИ.indexOf(S.мир.отрезок);
  if (i < ОТРЕЗКИ.length - 1) {
    S.мир.отрезок = ОТРЕЗКИ[i + 1];
  } else {
    закончитьДень(S, null); // ночь ушла на дела, не на сон
  }
  return S;
}

// сон — вариант ночлега из данных/жильё.js (объект); у бессонной ночи его нет.
export function лечьСпать(S, сон) {
  закончитьДень(S, сон ?? null);
  return S;
}

// Итог дня пишется в S.мир.конецДня — экран конца дня показывается, пока он
// не снят (так он переживает и перезагрузку страницы после автосейва).
function закончитьДень(S, сон) {
  const итог = {
    день: S.мир.день,
    выспался: !!сон,
    сон: сон ? сон.имя : null,
    журнал: S.мир.журналДня.slice(),
    причины: [],
    предупреждение: false,
  };
  применитьТело(S, сон, итог);
  S.мир.конецДня = итог;
  // Хроника: три последних итога дня для экрана «Журнал» (старые выпадают).
  (S.мир.хроника ??= []).push({ день: итог.день, журнал: итог.журнал, причины: итог.причины, выспался: итог.выспался, сон: итог.сон });
  if (S.мир.хроника.length > 3) S.мир.хроника.splice(0, S.мир.хроника.length - 3);
  S.мир.день += 1;
  S.мир.отрезок = ОТРЕЗКИ[0];
  S.мир.журналДня = [];
  return S;
}

// Сколько отрезков съест действие «за отрезок»: с отдыхом 0 или цел 0 — два (§5).
export function отрезковНа(S) {
  return (S.герой.тело.отдых === 0 || S.герой.тело.цел === 0) ? 2 : 1;
}

// Тратит отрезок на действие (работа, дорога, ожидание — всё, что не сон).
export function потратитьОтрезок(S) {
  const день = S.мир.день;
  const т = S.герой.тело;
  if (т.отдых === 0 || т.цел === 0) {
    if (т.отдых === 0 && S.мир.отключкаДень !== день) {
      S.мир.отключкаДень = день;
      т.цел = Math.max(0, т.цел - 1);
      S.мир.журналДня.push('Отключился на ходу: цел −1');
    } else if (т.отдых === 0) {
      S.мир.журналДня.push('Отключился на ходу');
    } else {
      S.мир.журналДня.push('Еле тащишься на разбитом теле');
    }
    следующийОтрезок(S);
    if (S.мир.день === день) следующийОтрезок(S); // день уже кончился — второй отрезок не тратим
  } else {
    следующийОтрезок(S);
  }
  return S;
}

export function переход(S, районId) {
  if (S.мир.район === районId) return S; // внутри района — бесплатно (§4)
  S.мир.район = районId;
  потратитьОтрезок(S);
  return S;
}
