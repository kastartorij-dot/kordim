// Сюжетное событие ожидает своего экрана в сохранении. Повторный эффект с тем же
// id не создаёт вторую копию, а закрытое событие не воскресает после загрузки.
export function поставитьСобытие(S, событие) {
  if (!событие?.id) return false;
  const м = S.мир;
  const очередь = (м.очередьСобытий ??= []);
  if ((м.завершённыеСобытия ??= []).includes(событие.id) || очередь.some(x => x.id === событие.id)) return false;
  очередь.push({ ...событие, статус: 'ожидает' });
  return true;
}

export function начатьСобытие(S, id) {
  const событие = (S.мир.очередьСобытий ?? []).find(x => x.id === id);
  if (!событие || событие.статус !== 'ожидает') return false;
  событие.статус = 'идёт';
  return true;
}

export function завершитьСобытие(S, id) {
  const очередь = S.мир.очередьСобытий ?? [];
  const i = очередь.findIndex(x => x.id === id && x.статус === 'идёт');
  if (i < 0) return false;
  очередь.splice(i, 1);
  (S.мир.завершённыеСобытия ??= []).push(id);
  return true;
}
