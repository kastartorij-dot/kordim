const зажать = (от, до, v) => Math.max(от, Math.min(до, v));
const Д = S => место(S.сцена.место).модуль;
const М = S => S.мир.места[S.сцена.место];

диалог.подключить({
  модуль: S => Д(S), есть: (S, ф) => есть(S, ф), расп: (S, кто) => расп(S, кто), визитов: S => М(S).визитов,
  собеседник: S => S.сцена.собеседник, времяИдёт: (S, n) => времяИдёт(S, n), применить: (S, э) => применить(S, э), местоПамять: S => М(S),
});

function человек(S, id) {
  return (S.мир.люди[id] ??= { спрошено: [], исчерпано: [] });
}
const расп = (S, id) => S.мир.люди[id]?.распол ?? 0;
function добавитьРаспол(S, id, d) {
  const л = человек(S, id);
  л.распол = зажать(-2, 4, (л.распол || 0) + d);
}

// Выучить тему в этом месте: от него она и придёт (важно для обмена у Сибиллы — свои сведения ей ничего не стоят).
function датьТему(S, т, верность) {
  дать(S, т, верность, S.сцена?.место);
}

// Тема: сначала в данных текущего места, потом в реестре города.
function тема(S, тид) {
  return { ...(РЕЕСТР[тид] ?? {}), ...(Д(S).ТЕМЫ[тид] ?? {}) };
}
function есть(S, ф) {
  return S.сцена.флагиВечера.includes(ф) || М(S).флаги.includes(ф);
}
function флаг(S, ф) {
  const список = Д(S).флагиВечера.includes(ф) ? S.сцена.флагиВечера : М(S).флаги;
  if (!список.includes(ф)) список.push(ф);
}

