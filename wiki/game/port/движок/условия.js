// Условия для случаев смены и допусков работ. Один язык на всё: данные пишут `условие: { ... }`,
// движок не знает имён. Без DOM. Все поля необязательны и складываются через «и».
import { рыночныйДень, нечётныйДень } from '../данные/календарь.js';
import { ступеньНомер } from './ремёсла.js';
import { СТУПЕНИ } from './ремёсла.js';
import { верностьТемы, ушлоК } from './знание.js';
import { естьВещь } from './вещи.js';
import { видОдежды } from './одежда.js';

const вДиапазоне = (v, у) => v >= (у.от ?? -1e9) && v <= (у.до ?? 1e9);
const список = v => (Array.isArray(v) ? v : [v]);

export function условие(S, у) {
  if (!у) return true;
  const м = S.мир, г = S.герой;
  if (у.день && !вДиапазоне(м.день, у.день)) return false;
  if (у.рынок !== undefined && рыночныйДень(м.день) !== у.рынок) return false;
  if (у.нечётный !== undefined && нечётныйДень(м.день) !== у.нечётный) return false;
  if (у.район && !список(у.район).includes(м.район)) return false;
  if (у.отрезок && !список(у.отрезок).includes(м.отрезок)) return false;
  // сколько смен этой работы уже сделано (смена, что идёт сейчас, не считается)
  if (у.смен && !вДиапазоне(м.работы?.[у.смен.работа]?.смен ?? 0, у.смен)) return false;
  if (у.ремесло) {
    const н = СТУПЕНИ.findIndex(с => с.имя === (у.ремесло.ступень ?? 'умеешь'));
    if (ступеньНомер(S, у.ремесло.имя) < н) return false;
  }
  if (у.безРемесла && ступеньНомер(S, у.безРемесла) >= 0) return false;
  if (у.счётчик) for (const [имя, д] of Object.entries(у.счётчик)) if (!вДиапазоне(м.счётчики?.[имя] ?? 0, д)) return false;
  if (у.прошло && (м.отметки?.[у.прошло.отметка] === undefined || м.день - м.отметки[у.прошло.отметка] < у.прошло.от)) return false;
  if (у.тема && !м.темы.includes(у.тема)) return false;
  if (у.безТемы && м.темы.includes(у.безТемы)) return false;
  if (у.верность && верностьТемы(S, у.верность.тема) !== у.верность.значение) return false;
  if (у.ушло && !ушлоК(S, у.ушло.тема, у.ушло.кому)) return false;
  if (у.флаг && !список(у.флаг).every(ф => м.флаги.includes(ф))) return false;
  if (у.нетФлага && список(у.нетФлага).some(ф => м.флаги.includes(ф))) return false;
  if (у.фракция) for (const [к, д] of Object.entries(у.фракция)) if (!вДиапазоне(м.фракции?.[к] ?? 0, д)) return false;
  if (у.репутация && !вДиапазоне(м.репутация ?? 0, у.репутация)) return false;
  if (у.тень && !вДиапазоне(м.тень ?? 0, у.тень)) return false;
  if (у.тело) for (const [к, д] of Object.entries(у.тело)) if (!вДиапазоне(г.тело[к], д)) return false;
  if (у.вид && !вДиапазоне(видОдежды(S), у.вид)) return false;
  if (у.деньги && !вДиапазоне(г.кошель, у.деньги)) return false;
  if (у.распол) for (const [кто, д] of Object.entries(у.распол)) if (!вДиапазоне(м.люди?.[кто]?.распол ?? 0, д)) return false;
  if (у.предмет && !список(у.предмет).every(п => естьВещь(S, п))) return false;
  if (у.безПредмета && список(у.безПредмета).some(п => естьВещь(S, п))) return false;
  if (у.дом) for (const [место, д] of Object.entries(у.дом)) if (!вДиапазоне(м.места?.[место]?.дом ?? 0, д)) return false;
  return true;
}


