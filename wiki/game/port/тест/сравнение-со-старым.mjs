// ── поддельный DOM для старого скрипта ────────────────────────────
class Эл {
  constructor(тег) { this.тег = тег; this.children = []; this._html = ''; this.style = {}; this.dataset = {}; this.className = ''; this.textContent = ''; this.disabled = false; this.onclick = null; }
  set innerHTML(v) { this._html = String(v); this.children = []; }
  get innerHTML() { return this._html; }
  appendChild(с) { this.children.push(с); return с; }
  querySelector() { return new Эл('q'); }
  querySelectorAll() { return []; }
  remove() {}
}
function запустить() {
  const по_id = {};
  const тело = new Эл('body');
  const документ = {
    getElementById: id => (по_id[id] ??= new Эл(id)),
    createElement: т => new Эл(т),
    querySelector: () => null,
    querySelectorAll: () => [],
    body: тело,
  };
  const ctx = vm.createContext({
    document: документ,
    location: { pathname: '/Синий_час/index.html', reload() {} },
    localStorage: { getItem: () => null, setItem() {}, removeItem() {} },
    Image: class { set src(_) {} },
    confirm: () => true,
    console,
  });
  vm.runInContext(скрипт, ctx);
  return { ctx, документ, по_id, тело };
}

const снятьТеги = т => т.replace(/<[^>]*>/g, '');
const старыйЭкран = ({ ctx, по_id }) => {
  const S = vm.runInContext('S', ctx);
  const кнопки = по_id['acts'].children.map(б => {
    const м = б.innerHTML.match(/<span class="row"><span>([\s\S]*?)<\/span>(?:<span class="cost[^"]*">([\s\S]*?)<\/span>)?/);
    return [м[1], м[2] || '', !б.disabled];
  });
  const тон = по_id['tone'].children.map(с => с.textContent).join(' ');
  return {
    // В старой игре у Ярны нет «вступления»: на первом экране разговора она показывала слово «undefined».
    // В новой там пусто — это единственное осознанное расхождение (вопрос в журнале).
    say: по_id['say'].innerHTML === 'undefined' ? '' : по_id['say'].innerHTML, час: S.час, гроши: S.гроши, дом: S.дом, комната: S.комната,
    распол: Object.fromEntries(Object.entries(S.распол).filter(([, v]) => v !== 0 || true)),
    кнопки, тон, темы: [...S.темы],
  };
};

const НОВЫЕ_КНОПКИ = ['Отдать долг старшей', 'Поесть на кухне'];
const экранируй = т => String(т).replace(/&/g, '&amp;').replace(/</g, '&lt;');
function новыйЭкран(S) {
  const в = видСцены(S);
  const say = (в.моя ? '<span class="my">— ' + экранируй(в.моя) + '</span>\n\n' : '') + экранируй(в.реплика);
  // Кнопки, которых в старой игре не было намеренно (добавлены в городе), в сравнение не идут.
  const кнопки = действияСцены(S).filter(а => !НОВЫЕ_КНОПКИ.includes(а.текст)).map(а => [а.текст, а.подпись, а.можно]);
  const тон = в.подходы ? [...в.подходы.map(п => п.id), ...(в.любит ? [в.любит] : [])].join(' ') : '';
  const м = S.мир.места['синий-час'];
  return {
    say, час: S.сцена.часы, гроши: S.герой.кошель, дом: м.дом, комната: S.сцена.комната,
    распол: Object.fromEntries(Object.entries(S.мир.люди).filter(([, v]) => typeof v.распол === 'number').map(([k, v]) => [k, v.распол])),
    кнопки, тон, темы: [...S.мир.темы],
  };
}

