const ошибки = [];
let сверено = 0;
const различия = (имя, шаг, а, б) => {
  for (const к of Object.keys(а)) {
    const x = JSON.stringify(а[к]), y = JSON.stringify(б[к]);
    if (x !== y) ошибки.push(`[${имя}] после «${шаг}»: ${к}\n    старая: ${x.slice(0, 300)}\n    новая:  ${y.slice(0, 300)}`);
  }
  сверено++;
};

function итогСтарый({ тело }) {
  const ov = тело.children[тело.children.length - 1];
  const h = ov.innerHTML;
  return {
    заг: (h.match(/<h1>([\s\S]*?)<\/h1>/) || [])[1],
    текст: (h.match(/<p style="white-space:pre-wrap">([\s\S]*?)<\/p>/) || [])[1],
    строки: [...h.matchAll(/<div class="ln"><span>([\s\S]*?)<\/span><span>([\s\S]*?)<\/span><\/div>/g)].map(м => [м[1], м[2]]),
    утечки: [...h.matchAll(/<p style="color:#c6cddb;font-size:15px">— ([\s\S]*?)<\/p>/g)].map(м => м[1]),
  };
}

for (const путь of ПУТИ) {
  const О = запустить();
  vm.runInContext(`начать(${JSON.stringify(путь.старый)})`, О.ctx);
  const S = новоеСостояние(путь.начало, 1);
  S.герой.кошель = путь.деньги;
  S.мир.отрезок = 'вечер';
  S.мир.район = 'торговый';
  войти(S, 'синий-час');

  различия(путь.имя, '(вход)', старыйЭкран(О), новыйЭкран(S));
  for (const [тип, арг] of путь.шаги) {
    if (S.сцена.итог) { ошибки.push(`[${путь.имя}] новая версия закончила вечер раньше старой перед «${арг}»`); break; }
    if (тип === 'тон') {
      const б = О.по_id['tone'].children.find(с => с.textContent === арг);
      б.onclick();
      выбратьПодход(S, арг);
    } else {
      const б = О.по_id['acts'].children.find(б => !б.disabled && снятьТеги(б.innerHTML).includes(арг));
      const а = действияСцены(S).find(x => x.можно && x.текст.includes(арг));
      if (!б || !а) { ошибки.push(`[${путь.имя}] нет кнопки «${арг}» (старая: ${!!б}, новая: ${!!а})`); break; }
      б.onclick();
      а.выполнить(S);
      await догрузитьСцену(S, читатьСцену);
    }
    // финал в старой игре рисуется поверх, экран под ним не обновляется — сравниваем итог отдельно
    if (S.сцена.итог) break;
    различия(путь.имя, арг, старыйЭкран(О), новыйЭкран(S));
  }
  const старыйКонец = vm.runInContext('S.конец', О.ctx);
  if (!!старыйКонец !== !!S.сцена.итог) ошибки.push(`[${путь.имя}] конец вечера: старая ${старыйКонец}, новая ${S.сцена.итог?.причина}`);
  if (старыйКонец && S.сцена.итог) {
    const о = итогСтарый(О);
    const н = S.сцена.итог;
    различия(путь.имя, '(финал)', { заг: о.заг, текст: о.текст, строки: о.строки, утечки: о.утечки },
      { заг: н.заг, текст: н.текст.replace(/&/g, '&amp;').replace(/</g, '&lt;'), строки: н.строки, утечки: н.утечки });
    if (S.сцена.часы !== vm.runInContext('S.час', О.ctx)) ошибки.push(`[${путь.имя}] часы в конце различаются`);
  }
}

